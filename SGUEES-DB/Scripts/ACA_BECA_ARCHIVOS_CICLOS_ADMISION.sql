CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_ARCHIVO_EDICION
AS
SELECT PB.CORR_EMPRESA,PB.CORR_PROSPECTO_BECA,R.CORR_RESPUESTA_BECA,P.CORR_PREGUNTA_BECA,P.TIPO_RESPUESTA,
 CONVERT(varchar(4),COALESCE(PB.ANIO_ADMISION,PA.ANIO))+'-'+
 CONVERT(varchar(2),COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO))+'_'+
 COALESCE(NULLIF(LTRIM(RTRIM(PB.Cif)),''),CONVERT(varchar(12),PB.CORR_PROSPECTO_BECA)) AS CARPETA,
 R.ARCHIVO_RUTA,R.ARCHIVO_NOMBRE
FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R
JOIN dbo.ACA_PROSPECTO_BECA PB ON PB.CORR_PROSPECTO_BECA=R.CORR_PROSPECTO_BECA AND PB.CORR_EMPRESA=R.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=PB.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_FORMULARIO_VERSION=PB.CORR_FORMULARIO_VERSION AND S.CORR_EMPRESA=PB.CORR_EMPRESA
LEFT JOIN dbo.ACA_PERIODOS_ACADEMICOS PA ON PA.CORR_PERIODO_ACADEMICO=PB.CORR_PERIODO_ACADEMICO
WHERE ISNULL(PB.ACTIVO,1)=1 AND PB.ESTADO_BECA IN('BORRADOR','ENVIADA') AND P.TIPO_RESPUESTA='DOCUMENTO';
GO
CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_ARCHIVO
AS
SELECT E.CORR_EMPRESA,E.CORR_PROSPECTO_BECA,E.CORR_RESPUESTA_BECA,
 CAST(COALESCE(PB.ANIO_ADMISION,PA.ANIO) AS smallint) ANIO,
 CAST(COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO) AS tinyint) NUMERO_PERIODO,
 E.CARPETA,S.ORDEN ORDEN_SECCION,S.NOMBRE_SECCION,P.ORDEN ORDEN_PREGUNTA,
 E.CORR_PREGUNTA_BECA,P.TEXTO_PREGUNTA,E.ARCHIVO_NOMBRE,E.ARCHIVO_RUTA
FROM dbo.V_ACA_PROSPECTO_BECA_ARCHIVO_EDICION E
JOIN dbo.ACA_PROSPECTO_BECA PB ON PB.CORR_EMPRESA=E.CORR_EMPRESA AND PB.CORR_PROSPECTO_BECA=E.CORR_PROSPECTO_BECA
LEFT JOIN dbo.ACA_PERIODOS_ACADEMICOS PA ON PA.CORR_PERIODO_ACADEMICO=PB.CORR_PERIODO_ACADEMICO
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_EMPRESA=E.CORR_EMPRESA AND P.CORR_PREGUNTA_BECA=E.CORR_PREGUNTA_BECA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_EMPRESA=P.CORR_EMPRESA AND S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
WHERE NULLIF(LTRIM(RTRIM(ISNULL(E.ARCHIVO_NOMBRE,E.ARCHIVO_RUTA))),'') IS NOT NULL;
GO



CREATE OR ALTER VIEW [dbo].[V_ACA_PROSPECTO_BECA_CICLO]

AS

WITH CICLOS AS (

    SELECT

        ISNULL(PB.CORR_EMPRESA, 1) AS CORR_EMPRESA,

        CAST(COALESCE(PB.ANIO_ADMISION,PA.ANIO) AS smallint) AS ANIO,

        CAST(COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO) AS tinyint) AS NUMERO_PERIODO,

        CAST(COALESCE(PB.ANIO_ADMISION,PA.ANIO) AS int) * 100 + CAST(COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO) AS int) AS CLAVE_CICLO,

        COUNT(*) AS CANTIDAD_PROSPECTOS

    FROM dbo.ACA_PROSPECTO_BECA AS PB

    LEFT JOIN dbo.ACA_PERIODOS_ACADEMICOS AS PA

        ON PA.CORR_PERIODO_ACADEMICO = PB.CORR_PERIODO_ACADEMICO

    WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')

      AND ISNULL(PB.ACTIVO, 1) = 1

    GROUP BY ISNULL(PB.CORR_EMPRESA, 1), COALESCE(PB.ANIO_ADMISION,PA.ANIO), COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO)

)

SELECT

    C.CORR_EMPRESA,

    CAST(C.ANIO AS VARCHAR(4)) + '-' + RIGHT('0' + CAST(C.NUMERO_PERIODO AS VARCHAR(2)), 2) AS CICLO,

    C.ANIO,

    C.NUMERO_PERIODO,

    'Ciclo ' + RIGHT('0' + CAST(C.NUMERO_PERIODO AS VARCHAR(2)), 2) + ' - ' + CAST(C.ANIO AS VARCHAR(4)) AS NOMBRE_CICLO,

    C.CLAVE_CICLO,

    C.CANTIDAD_PROSPECTOS,

    CAST(CASE

            WHEN C.CLAVE_CICLO = (

                SELECT MAX(X.CLAVE_CICLO)

                FROM CICLOS AS X

                WHERE X.CORR_EMPRESA = C.CORR_EMPRESA)

            THEN 1

            ELSE 0

         END AS bit) AS ES_CICLO_DEFECTO

FROM CICLOS AS C;


GO
