--           a ACA_PROSPECTO_SOCIOECONOMICO. Beca se queda en ACA_PROSPECTO_BECA.
-- Cómo lo hace: crea la opción socioeconómica si falta (la FK lo exige)
--               y actualiza solo el tipo 105. El 104 vuelve a ACA_PROSPECTO
--               por si el script anterior ya lo había cambiado.
-- No asigna menú.
-- El usuario ejecuta este script. Después vuelve a ejecutar
-- Stored Procedures/dbo.PRAL_MTTO_ACA_PROSPECTO_NUEVO_INGRESO_AUTORIZA.sql
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRAN;

IF NOT EXISTS (
	SELECT 1 FROM dbo.SEG_OPCION_SISTEMA WHERE CODIGO_OPCION = N'ACA_PROSPECTO_SOCIOECONOMICO'
)
	INSERT INTO dbo.SEG_OPCION_SISTEMA (
		CODIGO_OPCION, NOMBRE_OPCION, URL_OPCION, IMAGEN_OPCION,
		USUARIO_CREA, FECHA_CREA, ESTACION_CREA
	)
	VALUES (
		N'ACA_PROSPECTO_SOCIOECONOMICO', N'Solicitud socioeconómica',
		N'/aca-prospecto-socioeconomico', N'mdi mdi-undefined',
		N'juanh', GETDATE(), N'SCRIPT_FLUJO_NI'
	);

UPDATE dbo.SEG_FLUJO_TIPO_DOCUMENTO
SET CODIGO_OPCION = N'ACA_PROSPECTO',
	USUARIO_ACTU = N'juanh',
	ESTACION_ACTU = N'SCRIPT_FLUJO_NI',
	FECHA_ACTU = GETDATE()
WHERE CORR_EMPRESA = 1
  AND CORR_TIPO_DOCUMENTO = 104
  AND CODIGO_OPCION <> N'ACA_PROSPECTO';

UPDATE dbo.SEG_FLUJO_TIPO_DOCUMENTO
SET CODIGO_OPCION = N'ACA_PROSPECTO_SOCIOECONOMICO',
	USUARIO_ACTU = N'juanh',
	ESTACION_ACTU = N'SCRIPT_FLUJO_NI',
	FECHA_ACTU = GETDATE()
WHERE CORR_EMPRESA = 1
  AND CORR_TIPO_DOCUMENTO = 105
  AND CODIGO_OPCION <> N'ACA_PROSPECTO_SOCIOECONOMICO';

COMMIT TRAN;

SELECT CORR_TIPO_DOCUMENTO, NOMBRE_TIPO, CODIGO_OPCION
FROM dbo.SEG_FLUJO_TIPO_DOCUMENTO
WHERE CORR_TIPO_DOCUMENTO IN (104, 105, 106)
ORDER BY CORR_TIPO_DOCUMENTO;
GO
