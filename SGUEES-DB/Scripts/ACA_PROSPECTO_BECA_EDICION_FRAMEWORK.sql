-- Fuente única de opciones: empresa, pregunta y puntaje vigente al día de consulta.
CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_OPCION_EDICION
AS
SELECT O.CORR_EMPRESA,O.CORR_PREGUNTA_BECA,O.CORR_OPCION_BECA,O.TEXTO_OPCION,O.ORDEN,
       CONVERT(decimal(10,2),ISNULL(PU.PUNTAJE,0)) AS PUNTAJE
FROM dbo.ACA_PROSPECTO_BECA_OPCION O
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=O.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=O.CORR_EMPRESA
OUTER APPLY (
    SELECT TOP(1) U.PUNTAJE
    FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U
    WHERE U.CORR_EMPRESA=O.CORR_EMPRESA AND U.CORR_PREGUNTA_BECA=O.CORR_PREGUNTA_BECA
      AND U.CORR_OPCION_BECA=O.CORR_OPCION_BECA AND U.ACTIVO=1
      AND U.FECHA_INICIO<=CONVERT(date,GETDATE()) AND (U.FECHA_FIN IS NULL OR U.FECHA_FIN>=CONVERT(date,GETDATE()))
    ORDER BY U.FECHA_INICIO DESC,U.CORR_PUNTAJE_BECA DESC
) PU
WHERE O.ACTIVO=1;
GO
CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_ARCHIVO_EDICION
AS
SELECT PB.CORR_EMPRESA,PB.CORR_PROSPECTO_BECA,R.CORR_RESPUESTA_BECA,P.CORR_PREGUNTA_BECA,P.TIPO_RESPUESTA,
       CONVERT(varchar(4),PA.ANIO)+'-'+CONVERT(varchar(2),PA.NUMERO_PERIODO)+'_'+CONVERT(varchar(12),PB.CORR_PROSPECTO_BECA) AS CARPETA,
       R.ARCHIVO_RUTA,R.ARCHIVO_NOMBRE
FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R
JOIN dbo.ACA_PROSPECTO_BECA PB ON PB.CORR_PROSPECTO_BECA=R.CORR_PROSPECTO_BECA AND PB.CORR_EMPRESA=R.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=PB.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_FORMULARIO_VERSION=PB.CORR_FORMULARIO_VERSION AND S.CORR_EMPRESA=PB.CORR_EMPRESA
JOIN dbo.ACA_PERIODOS_ACADEMICOS PA ON PA.CORR_PERIODO_ACADEMICO=PB.CORR_PERIODO_ACADEMICO
WHERE PB.ACTIVO=1 AND PB.ESTADO_BECA IN ('BORRADOR','ENVIADA') AND P.TIPO_RESPUESTA='DOCUMENTO';
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PROSPECTO_BECA_RESPUESTA
    @CORR_EMPRESA int,@SOLICITUD int,@PREGUNTA int,@FILAS xml,@USUARIO varchar(30),@ESTACION varchar(30)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'Sesión inválida.',1;
    IF @FILAS IS NULL OR @FILAS.exist('/Filas/Fila')=0 THROW 51000,N'Las respuestas no tienen un formato válido.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @VERSION int,@TIPO varchar(30),@REQUERIDO bit;
        SELECT @VERSION=CORR_FORMULARIO_VERSION FROM dbo.ACA_PROSPECTO_BECA WITH(UPDLOCK,HOLDLOCK)
        WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1 AND ESTADO_BECA IN ('BORRADOR','ENVIADA');
        IF @VERSION IS NULL THROW 51000,N'La solicitud no existe en su empresa o ya no permite modificaciones.',1;
        SELECT @TIPO=P.TIPO_RESPUESTA,@REQUERIDO=P.REQUERIDO
        FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
        WHERE P.CORR_PREGUNTA_BECA=@PREGUNTA AND P.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@VERSION;
        IF @TIPO IS NULL THROW 51000,N'La pregunta no pertenece al formulario de esta solicitud.',1;
        IF @TIPO NOT IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO','NUMERO','DECIMAL','TEXTO','TEXTO_LARGO','ACEPTACION')
            THROW 51000,N'Este tipo de respuesta no se edita desde esta operación.',1;
        DECLARE @D TABLE(ID int,OPCION int,TEXTO nvarchar(max),NUMERO decimal(18,4));
        INSERT @D SELECT N.value('(CORR_RESPUESTA_BECA/text())[1]','int'),N.value('(CORR_OPCION_BECA/text())[1]','int'),
            N.value('(RESPUESTA_TEXTO/text())[1]','nvarchar(max)'),
            CONVERT(decimal(18,4),NULLIF(N.value('(RESPUESTA_NUMERO/text())[1]','varchar(100)'),''))
        FROM @FILAS.nodes('/Filas/Fila') F(N);
        IF NOT EXISTS(SELECT 1 FROM @D) OR (SELECT COUNT(*) FROM @D)>1000 THROW 51000,N'La respuesta está vacía o excede el límite de filas.',1;
        IF EXISTS(SELECT ID FROM @D GROUP BY ID HAVING COUNT(*)>1) THROW 51000,N'Hay respuestas repetidas en la petición.',1;
        IF EXISTS(SELECT 1 FROM @D D WHERE NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R WITH(UPDLOCK,HOLDLOCK)
            WHERE R.CORR_RESPUESTA_BECA=D.ID AND R.CORR_PROSPECTO_BECA=@SOLICITUD AND R.CORR_PREGUNTA_BECA=@PREGUNTA AND R.CORR_EMPRESA=@CORR_EMPRESA))
            THROW 51000,N'Una respuesta no pertenece a esta solicitud y pregunta.',1;
        IF @TIPO IN ('OPCION_UNICA','SI_NO') AND (SELECT COUNT(*) FROM @D)<>1 THROW 51000,N'Esta pregunta admite una sola respuesta.',1;
        IF @TIPO IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO')
        BEGIN
            IF EXISTS(SELECT 1 FROM @D D WHERE NOT EXISTS(SELECT 1 FROM dbo.V_ACA_PROSPECTO_BECA_OPCION_EDICION O WHERE O.CORR_EMPRESA=@CORR_EMPRESA AND O.CORR_PREGUNTA_BECA=@PREGUNTA AND O.CORR_OPCION_BECA=D.OPCION))
                THROW 51000,N'La opción no está activa o no pertenece a esta pregunta y empresa.',1;
            IF EXISTS(SELECT OPCION FROM @D GROUP BY OPCION HAVING COUNT(*)>1) THROW 51000,N'No repita la misma opción.',1;
        END
        IF @TIPO IN ('NUMERO','DECIMAL') AND EXISTS(SELECT 1 FROM @D WHERE NUMERO IS NULL OR NUMERO<0 OR (@TIPO='DECIMAL' AND NUMERO>10) OR (@TIPO='NUMERO' AND NUMERO<>FLOOR(NUMERO)))
            THROW 51000,N'Ingrese un número válido: entero no negativo o calificación entre 0 y 10.',1;
        IF @REQUERIDO=1 AND @TIPO IN ('TEXTO','TEXTO_LARGO','ACEPTACION') AND EXISTS(SELECT 1 FROM @D WHERE NULLIF(LTRIM(RTRIM(TEXTO)),'') IS NULL)
            THROW 51000,N'La respuesta de texto es obligatoria.',1;
        UPDATE R SET
            CORR_OPCION_BECA=CASE WHEN @TIPO IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') THEN D.OPCION ELSE R.CORR_OPCION_BECA END,
            TEXTO_OPCION_HISTORICO=CASE WHEN @TIPO IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') THEN O.TEXTO_OPCION ELSE R.TEXTO_OPCION_HISTORICO END,
            RESPUESTA_TEXTO=CASE WHEN @TIPO IN ('TEXTO','TEXTO_LARGO','ACEPTACION') THEN D.TEXTO ELSE R.RESPUESTA_TEXTO END,
            RESPUESTA_NUMERO=CASE WHEN @TIPO IN ('NUMERO','DECIMAL') THEN D.NUMERO ELSE R.RESPUESTA_NUMERO END,
            PUNTAJE_OBTENIDO=CASE WHEN @TIPO IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') THEN O.PUNTAJE ELSE R.PUNTAJE_OBTENIDO END,
            PORCENTAJE_APLICADO=CASE WHEN @TIPO IN ('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') THEN O.PUNTAJE ELSE R.PORCENTAJE_APLICADO END,
            USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN @D D ON D.ID=R.CORR_RESPUESTA_BECA
        LEFT JOIN dbo.V_ACA_PROSPECTO_BECA_OPCION_EDICION O ON O.CORR_OPCION_BECA=D.OPCION AND O.CORR_PREGUNTA_BECA=@PREGUNTA AND O.CORR_EMPRESA=@CORR_EMPRESA
        WHERE R.CORR_EMPRESA=@CORR_EMPRESA AND R.CORR_PROSPECTO_BECA=@SOLICITUD AND R.CORR_PREGUNTA_BECA=@PREGUNTA;
        -- La misma vista usada en consulta resuelve las bandas configuradas. No hay rangos duplicados en C#.
        UPDATE R SET PUNTAJE_OBTENIDO=V.PUNTAJE_OBTENIDO,PORCENTAJE_APLICADO=V.PORCENTAJE_APLICADO
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN dbo.V_ACA_PROSPECTO_BECA_RESPUESTA V ON V.CORR_RESPUESTA_BECA=R.CORR_RESPUESTA_BECA AND V.CORR_EMPRESA=R.CORR_EMPRESA
        WHERE R.CORR_EMPRESA=@CORR_EMPRESA AND R.CORR_PROSPECTO_BECA=@SOLICITUD;
        DELETE dbo.ACA_PROSPECTO_BECA_SECCION_RESULTADO WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA;
        INSERT dbo.ACA_PROSPECTO_BECA_SECCION_RESULTADO(CORR_PROSPECTO_BECA,CORR_SECCION_BECA,PUNTAJE_OBTENIDO,PORCENTAJE_OBTENIDO,PORCENTAJE_SECCION_HISTORICO,FECHA_CALCULO,CORR_EMPRESA)
        SELECT @SOLICITUD,S.CORR_SECCION_BECA,SUM(R.PUNTAJE_OBTENIDO),SUM(R.PORCENTAJE_APLICADO),S.PORCENTAJE_SECCION,GETDATE(),@CORR_EMPRESA
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=@CORR_EMPRESA
        JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@VERSION
        WHERE R.CORR_PROSPECTO_BECA=@SOLICITUD AND R.CORR_EMPRESA=@CORR_EMPRESA GROUP BY S.CORR_SECCION_BECA,S.PORCENTAJE_SECCION;
        DECLARE @PUNTOS decimal(10,2),@PORCENTAJE decimal(5,2);
        SELECT @PUNTOS=ISNULL(SUM(PUNTAJE_OBTENIDO),0),@PORCENTAJE=ISNULL(SUM(PORCENTAJE_APLICADO),0) FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA;
        UPDATE dbo.ACA_PROSPECTO_BECA SET PUNTAJE_TOTAL=@PUNTOS,PORCENTAJE_TOTAL=@PORCENTAJE,
            RESULTADO_EVALUACION=CASE WHEN @PUNTOS>=70 THEN 'Potencialmente elegible' WHEN @PUNTOS>=55 THEN 'Elegibilidad condicionada' ELSE 'Baja viabilidad actual' END,
            PRIORIDAD_EVALUACION=CASE WHEN @PUNTOS>=85 THEN 'ALTA' WHEN @PUNTOS>=70 THEN 'MEDIA' WHEN @PUNTOS>=55 THEN 'CONDICIONADA' ELSE 'BAJA' END,
            USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
        WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA;
        COMMIT;
        SELECT PUNTAJE_TOTAL,PORCENTAJE_TOTAL,RESULTADO_EVALUACION,PRIORIDAD_EVALUACION FROM dbo.ACA_PROSPECTO_BECA WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        THROW;
    END CATCH
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PROSPECTO_BECA_ARCHIVO
    @CORR_EMPRESA int,@SOLICITUD int,@RESPUESTA int,@NOMBRE varchar(255),@RUTA varchar(500),@RUTA_ANTERIOR varchar(500)=NULL,@USUARIO varchar(30)=NULL,@ESTACION varchar(30)=NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(@USUARIO,'') IS NULL THROW 51000,N'Sesión inválida.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1 AND ESTADO_BECA IN ('BORRADOR','ENVIADA'))
            THROW 51000,N'La solicitud no permite modificaciones.',1;
        IF NOT EXISTS(SELECT 1 FROM dbo.V_ACA_PROSPECTO_BECA_ARCHIVO_EDICION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_RESPUESTA_BECA=@RESPUESTA)
            THROW 51000,N'El documento no pertenece a esta solicitud y empresa.',1;
        UPDATE dbo.ACA_PROSPECTO_BECA_RESPUESTA SET ARCHIVO_NOMBRE=@NOMBRE,ARCHIVO_RUTA=@RUTA,RESPUESTA_TEXTO=@NOMBRE,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
        WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PROSPECTO_BECA=@SOLICITUD AND CORR_RESPUESTA_BECA=@RESPUESTA AND ISNULL(ARCHIVO_RUTA,'')=ISNULL(@RUTA_ANTERIOR,'');
        IF @@ROWCOUNT<>1 THROW 51000,N'El documento cambió mientras lo editaba. Actualice e intente nuevamente.',1;
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        THROW;
    END CATCH
END;
