IF OBJECT_ID(N'dbo.PRAL_IMPR_BAN_CHEQUE_IMPRIME', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_IMPR_BAN_CHEQUE_IMPRIME];
