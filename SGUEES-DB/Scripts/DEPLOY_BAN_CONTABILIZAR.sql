IF OBJECT_ID(N'dbo.PRAL_MTTO_CON_PARTIDA_DETA', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_MTTO_CON_PARTIDA_DETA];
GO

CREATE PROCEDURE [dbo].[PRAL_MTTO_CON_PARTIDA_DETA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_CLASE_PARTIDA INT,
	@CORR_PARTIDA INT,
	@CORR_PARTIDA_DETA INT OUTPUT,
	@CUENTA_CONTABLE VARCHAR(30),
	@CORR_CENTRO_COSTO INT = NULL,
	@MONTO_CARGO DECIMAL(18, 4) = 0,
	@MONTO_ABONO DECIMAL(18, 4) = 0,
	@NOMBRE_TRAN VARCHAR(1255) = '',
	@MONTO_CARGO_FORANEA DECIMAL(12, 4) = NULL,
	@MONTO_ABONO_FORANEA DECIMAL(12, 4) = NULL,
	@FACTOR_CAMBIO DECIMAL(12, 6) = NULL,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT,
	@CORR_AUXILIAR INT = NULL
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_CATALOGO_CUENTA
				WHERE CORR_EMPRESA = @CORR_EMPRESA
					AND CUENTA_CONTABLE = @CUENTA_CONTABLE
					AND ES_DETALLE = 1
					AND NO_HABILITADA = 0
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000,
					@SYS_MENSAJE_ERROR = N'Cuenta: ' + @CUENTA_CONTABLE + N'. Seleccione una cuenta de detalle habilitada.',
					@SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_CENTRO_COSTO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CENTRO_COSTO = @CORR_CENTRO_COSTO
			)
				SET @CORR_CENTRO_COSTO = NULL;

			IF @MONTO_ABONO < 0 OR @MONTO_CARGO < 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No introduzca montos negativos', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF @MONTO_ABONO > 0 AND @MONTO_CARGO > 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Escriba al menos un monto igual que cero', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.CON_PARTIDA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA
				AND CORR_PARTIDA = @CORR_PARTIDA
				AND ESTADO_PARTIDA = 'DI'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El documento no puede ser modificado o eliminado.', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			IF ISNULL(@CORR_PARTIDA_DETA, 0) = 0
			BEGIN
				SELECT @CORR_PARTIDA_DETA = ISNULL(MAX(CORR_PARTIDA_DETA), 0) + 1
				FROM dbo.CON_PARTIDA_DETA
				WHERE CORR_EMPRESA = @CORR_EMPRESA
					AND ANIO_PERIODO = @ANIO_PERIODO
					AND MES_PERIODO = @MES_PERIODO
					AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA
					AND CORR_PARTIDA = @CORR_PARTIDA;
			END;

			INSERT INTO dbo.CON_PARTIDA_DETA
			(
				CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_CLASE_PARTIDA, CORR_PARTIDA, CORR_PARTIDA_DETA,
				CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO,
				MONTO_CARGO_FORANEA, MONTO_ABONO_FORANEA, CORR_AUXILIAR
			)
			VALUES
			(
				@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_CLASE_PARTIDA, @CORR_PARTIDA, @CORR_PARTIDA_DETA,
				@CUENTA_CONTABLE, @CORR_CENTRO_COSTO, @NOMBRE_TRAN, @MONTO_CARGO, @MONTO_ABONO,
				ISNULL(@MONTO_CARGO_FORANEA, 0), ISNULL(@MONTO_ABONO_FORANEA, 0), @CORR_AUXILIAR
			);
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

