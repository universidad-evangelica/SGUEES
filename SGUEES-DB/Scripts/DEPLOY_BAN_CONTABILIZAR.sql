	(
		[CORR_EMPRESA] [int] NOT NULL,
		[ANIO_PERIODO] [int] NOT NULL,
		[MES_PERIODO] [int] NOT NULL,
		[CORR_CLASE_PARTIDA] [int] NOT NULL,
		[CORR_PARTIDA] [int] NOT NULL,
		[CORR_PARTIDA_DETA] [int] NOT NULL,
		[CORR_TIPO_MOVIMIENTO] [int] NOT NULL,
		[CORR_DOCUMENTO] [int] NOT NULL,
		[ANIO_PERIODO_DOC] [int] NOT NULL,
		[MES_PERIODO_DOC] [int] NOT NULL,
		CONSTRAINT [PK_BAN_PARTIDA_DETA]
			PRIMARY KEY CLUSTERED (
				[CORR_EMPRESA], [ANIO_PERIODO], [MES_PERIODO], [CORR_CLASE_PARTIDA],
				[CORR_PARTIDA], [CORR_PARTIDA_DETA], [CORR_TIPO_MOVIMIENTO], [CORR_DOCUMENTO],
				[ANIO_PERIODO_DOC], [MES_PERIODO_DOC]
			)
	) ON [PRIMARY];

	ALTER TABLE [dbo].[BAN_PARTIDA_DETA]
		ADD CONSTRAINT [FK_BAN_PARTIDA_DETA_CON_PARTIDA_DETA]
		FOREIGN KEY ([CORR_EMPRESA], [ANIO_PERIODO], [MES_PERIODO], [CORR_CLASE_PARTIDA], [CORR_PARTIDA], [CORR_PARTIDA_DETA])
		REFERENCES [dbo].[CON_PARTIDA_DETA] ([CORR_EMPRESA], [ANIO_PERIODO], [MES_PERIODO], [CORR_CLASE_PARTIDA], [CORR_PARTIDA], [CORR_PARTIDA_DETA]);

	ALTER TABLE [dbo].[BAN_PARTIDA_DETA]
		ADD CONSTRAINT [FK_BAN_PARTIDA_DETA_BAN_DOCUMENTO]
		FOREIGN KEY ([CORR_EMPRESA], [ANIO_PERIODO_DOC], [MES_PERIODO_DOC], [CORR_TIPO_MOVIMIENTO], [CORR_DOCUMENTO])
		REFERENCES [dbo].[BAN_DOCUMENTO] ([CORR_EMPRESA], [ANIO_PERIODO], [MES_PERIODO], [CORR_TIPO_MOVIMIENTO], [CORR_DOCUMENTO]);

	PRINT N'Tabla BAN_PARTIDA_DETA creada.';
END
ELSE
	PRINT N'Tabla BAN_PARTIDA_DETA ya existe.';
GO

/* ── Contabilizar documento bancario ── */
IF OBJECT_ID(N'dbo.PRAL_MTTO_BAN_DOCUMENTO_CONTABILIZAR', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_CONTABILIZAR];
GO

CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_CONTABILIZAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE
		@TIPO_ACTUALIZA INT,
		@MONTO_CARGO DECIMAL(18, 2),
		@MONTO_ABONO DECIMAL(18, 2),
		@DETALLE_DOCUMENTO NVARCHAR(255),
		@NOMBRE_TIPO_MOVIMIENTO VARCHAR(100),
		@CORR_CLASE_PARTIDA INT,
		@CORR_PARTIDA INT,
		@CORR_PARTIDA_DETA INT,
		@ANIO_PERIODO_CON INT,
		@MES_PERIODO_CON INT,
		@FECHA_PARTIDA DATE,
		@NUMERO_DOCUMENTO BIGINT,
		@NOMBRE_PARTIDA VARCHAR(1000),
		@ESTADO_DOCUMENTO VARCHAR(2),
		@ESTA_CONTABILIZADO BIT,
		@CORR_MONEDA INT,
		@FACTOR_CAMBIO DECIMAL(16, 6),
		@OPERADOR VARCHAR(2),
		@CORR_DOCUMENTO_DETA INT,
		@CUENTA_CONTABLE_DETA VARCHAR(30),
		@CORR_CENTRO_COSTO_DETA INT,
		@NOMBRE_TRAN_DETA VARCHAR(1255),
		@MONTO_CARGO_DETA DECIMAL(18, 2),
		@MONTO_ABONO_DETA DECIMAL(18, 2),
		@NUMERO_DOCUMENTO_STR VARCHAR(25);

	DECLARE @TEMP TABLE
	(
		CORR_DOCUMENTO_DETA INT NOT NULL,
		CUENTA_CONTABLE VARCHAR(30) NOT NULL,
		CORR_CENTRO_COSTO INT NULL,
		NOMBRE_TRAN VARCHAR(1255) NOT NULL,
		MONTO_CARGO DECIMAL(18, 2) NOT NULL,
		MONTO_ABONO DECIMAL(18, 2) NOT NULL,
		ESTA_PROC BIT NOT NULL DEFAULT (0)
	);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE());

	BEGIN TRY
		SELECT @NOMBRE_TIPO_MOVIMIENTO = NOMBRE_TIPO_MOVIMIENTO, @CORR_CLASE_PARTIDA = CORR_CLASE_PARTIDA
		FROM dbo.BAN_TIPO_MOVI_BANCARIO
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

		SET @DETALLE_DOCUMENTO = @NOMBRE_TIPO_MOVIMIENTO + N' del Año ' + CONVERT(VARCHAR(10), @ANIO_PERIODO)
			+ N' Mes ' + CONVERT(VARCHAR(10), @MES_PERIODO)
			+ N' Correlativo No.' + CONVERT(VARCHAR(10), @CORR_DOCUMENTO);

		SELECT
			@ESTADO_DOCUMENTO = ESTADO_DOCUMENTO,
			@ESTA_CONTABILIZADO = ESTA_CONTABILIZADO,
			@FECHA_PARTIDA = FECHA_EMISION,
			@NUMERO_DOCUMENTO = NUMERO_DOCUMENTO,
			@NOMBRE_PARTIDA = NOMBRE_PARTIDA,
			@CORR_MONEDA = CORR_MONEDA,
			@FACTOR_CAMBIO = FACTOR_CAMBIO,
			@OPERADOR = OPERADOR,
			@ANIO_PERIODO_CON = ANIO_PERIODO,
			@MES_PERIODO_CON = MES_PERIODO
		FROM dbo.BAN_DOCUMENTO
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @ESTADO_DOCUMENTO NOT IN ('AP', 'IM') OR ISNULL(@ESTA_CONTABILIZADO, 0) <> 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'Este documento no está listo para contabilizar o ya fue contabilizado. ' + @DETALLE_DOCUMENTO,
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO_CON
				AND MES_PERIODO = @MES_PERIODO_CON
				AND ESTADO_PERIODO_CON = 'AB'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30001,
				@SYS_MENSAJE_ERROR = N'El período contable no está abierto. ' + @DETALLE_DOCUMENTO + N' no se puede contabilizar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.BAN_DOCUMENTO_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND CORR_DOCUMENTO = @CORR_DOCUMENTO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30004,
				@SYS_MENSAJE_ERROR = N'El documento no tiene detalle contable. ' + @DETALLE_DOCUMENTO + N' no se puede contabilizar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT @MONTO_CARGO = SUM(MONTO_CARGO), @MONTO_ABONO = SUM(MONTO_ABONO)
		FROM dbo.BAN_DOCUMENTO_DETA
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF ISNULL(@MONTO_CARGO, 0) <> ISNULL(@MONTO_ABONO, 0)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'El detalle contable no está cuadrado. ' + @DETALLE_DOCUMENTO + N' no se puede contabilizar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SET @TIPO_ACTUALIZA = 1;
		SET @CORR_PARTIDA = 0;
		SET @NUMERO_DOCUMENTO_STR = LTRIM(RTRIM(CONVERT(VARCHAR(25), @NUMERO_DOCUMENTO)));

		BEGIN TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;

		EXEC dbo.PRAL_MTTO_CON_PARTIDA
			@TIPO_ACTUALIZA,
			@CORR_EMPRESA,
			@ANIO_PERIODO_CON,
			@MES_PERIODO_CON,
			@CORR_CLASE_PARTIDA,
			@CORR_PARTIDA OUTPUT,
			@FECHA_PARTIDA,
			@NUMERO_DOCUMENTO_STR,
			@NOMBRE_PARTIDA,
			'DI',
			'NOR',
			@CORR_MONEDA,
			@FACTOR_CAMBIO,
			@OPERADOR,
			@USUARIO_ACTU,
			@FECHA_ACTU,
			@ESTACION_ACTU,
			@USUARIO_ACTU,
			@FECHA_ACTU,
			@ESTACION_ACTU,
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR OUTPUT,
			NULL;

		IF @SYS_NUMERO_ERROR <> 0
		BEGIN
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;
			SET @SYS_MENSAJE_ERROR = @DETALLE_DOCUMENTO + N' [' + @SYS_MENSAJE_ERROR + N']';
			GOTO FINA;
		END;

		INSERT INTO @TEMP (CORR_DOCUMENTO_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
		SELECT
			A.CORR_DOCUMENTO_DETA,
			A.CUENTA_CONTABLE,
			B.CORR_CENTRO_COSTO,
			A.NOMBRE_TRAN,
			ISNULL(A.MONTO_CARGO, 0),
			ISNULL(A.MONTO_ABONO, 0)
		FROM dbo.BAN_DOCUMENTO_DETA A
		LEFT JOIN dbo.CON_CENTRO_COSTO B
			ON A.CORR_EMPRESA = B.CORR_EMPRESA AND A.CORR_CENTRO_COSTO = B.CORR_CENTRO_COSTO
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA
			AND A.ANIO_PERIODO = @ANIO_PERIODO
			AND A.MES_PERIODO = @MES_PERIODO
			AND A.CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND A.CORR_DOCUMENTO = @CORR_DOCUMENTO;

		WHILE EXISTS (SELECT 1 FROM @TEMP WHERE ESTA_PROC = 0)
		BEGIN
			SELECT TOP 1
				@CORR_DOCUMENTO_DETA = CORR_DOCUMENTO_DETA,
				@CUENTA_CONTABLE_DETA = CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO_DETA = CORR_CENTRO_COSTO,
				@NOMBRE_TRAN_DETA = NOMBRE_TRAN,
				@MONTO_CARGO_DETA = MONTO_CARGO,
				@MONTO_ABONO_DETA = MONTO_ABONO
			FROM @TEMP
			WHERE ESTA_PROC = 0;

			SET @CORR_PARTIDA_DETA = @CORR_DOCUMENTO_DETA;

			EXEC dbo.PRAL_MTTO_CON_PARTIDA_DETA
				1,
				@CORR_EMPRESA,
				@ANIO_PERIODO_CON,
				@MES_PERIODO_CON,
				@CORR_CLASE_PARTIDA,
				@CORR_PARTIDA,
				@CORR_PARTIDA_DETA OUTPUT,
				@CUENTA_CONTABLE_DETA,
				@CORR_CENTRO_COSTO_DETA,
				@MONTO_CARGO_DETA,
				@MONTO_ABONO_DETA,
				@NOMBRE_TRAN_DETA,
				NULL,
				NULL,
				NULL,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR OUTPUT,
				NULL;

			IF @SYS_NUMERO_ERROR <> 0
			BEGIN
				IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;
				SET @SYS_MENSAJE_ERROR = @DETALLE_DOCUMENTO + N' [' + @SYS_MENSAJE_ERROR + N']';
				GOTO FINA;
			END;

			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_PARTIDA_DETA
				WHERE CORR_EMPRESA = @CORR_EMPRESA
					AND ANIO_PERIODO = @ANIO_PERIODO_CON
					AND MES_PERIODO = @MES_PERIODO_CON
					AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA
					AND CORR_PARTIDA = @CORR_PARTIDA
					AND CORR_PARTIDA_DETA = @CORR_PARTIDA_DETA
					AND ANIO_PERIODO_DOC = @ANIO_PERIODO
					AND MES_PERIODO_DOC = @MES_PERIODO
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
					AND CORR_DOCUMENTO = @CORR_DOCUMENTO
			)
			BEGIN
				INSERT INTO dbo.BAN_PARTIDA_DETA
				(
					CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_CLASE_PARTIDA, CORR_PARTIDA, CORR_PARTIDA_DETA,
					ANIO_PERIODO_DOC, MES_PERIODO_DOC, CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO
				)
				VALUES
				(
					@CORR_EMPRESA, @ANIO_PERIODO_CON, @MES_PERIODO_CON, @CORR_CLASE_PARTIDA, @CORR_PARTIDA, @CORR_PARTIDA_DETA,
					@ANIO_PERIODO, @MES_PERIODO, @CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO
				);
			END;

			UPDATE @TEMP SET ESTA_PROC = 1 WHERE CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA;
		END;

		EXEC dbo.PRAL_MTTO_CON_PARTIDA_APLICAR
			@CORR_EMPRESA,
			@ANIO_PERIODO_CON,
			@MES_PERIODO_CON,
			@CORR_CLASE_PARTIDA,
			@CORR_PARTIDA OUTPUT,
			@USUARIO_ACTU,
			@FECHA_ACTU,
			@ESTACION_ACTU,
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR OUTPUT;

		IF @SYS_NUMERO_ERROR <> 0
		BEGIN
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;
			SET @SYS_MENSAJE_ERROR = @DETALLE_DOCUMENTO + N' [' + @SYS_MENSAJE_ERROR + N']';
			GOTO FINA;
		END;

		UPDATE dbo.BAN_DOCUMENTO SET
			ESTA_CONTABILIZADO = 1,
			USUARIO_ACTU = @USUARIO_ACTU,
			FECHA_ACTU = @FECHA_ACTU,
			ESTACION_ACTU = @ESTACION_ACTU
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;

		IF @@TRANCOUNT > 0 COMMIT TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_CONTABILIZAR;
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

