CREATE PROCEDURE [dbo].[PRAL_IMPR_BAN_CHEQUE_IMPRIME]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@USUARIO_ACTU VARCHAR(30) = '',
	@FECHA_ACTU DATETIME = NULL,
	@ESTACION_ACTU VARCHAR(50) = '',
	@SYS_LOGIN_USUARIO VARCHAR(30) = '',
	@SYS_ESTACION VARCHAR(50) = '',
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE
		@ESTADO VARCHAR(2),
		@CLASE_MOV VARCHAR(3),
		@CORR_CUENTA INT,
		@CORR_CHEQUERA INT,
		@NUMERO_CHEQUE INT,
		@SERIE VARCHAR(10),
		@CORR_TIPO_CHEQUE INT,
		@CONTABILIZAR BIT;

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE());

	BEGIN TRY
		SELECT @ESTADO = A.ESTADO_DOCUMENTO, @CORR_CUENTA = A.CORR_CUENTA_BANCO,
			@CORR_TIPO_CHEQUE = A.CORR_TIPO_CHEQUE, @CLASE_MOV = B.CLASE_MOVIMIENTO
		FROM dbo.BAN_DOCUMENTO A
		INNER JOIN dbo.BAN_TIPO_MOVI_BANCARIO B
			ON A.CORR_EMPRESA = B.CORR_EMPRESA AND A.CORR_TIPO_MOVIMIENTO = B.CORR_TIPO_MOVIMIENTO
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA AND A.ANIO_PERIODO = @ANIO_PERIODO AND A.MES_PERIODO = @MES_PERIODO
			AND A.CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND A.CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @CLASE_MOV <> 'CHQ'
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Solo se pueden imprimir documentos tipo Cheque', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF @ESTADO NOT IN ('AP', 'IM')
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El cheque debe estar aplicado para imprimir', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT TOP 1 @CORR_CHEQUERA = CORR_CHEQUERA, @NUMERO_CHEQUE = NUMERO_CHEQUE_ACTUAL, @SERIE = SERIE_CHEQUE
		FROM dbo.BAN_CHEQUERA
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA AND ESTADO_CHEQUERA = 'AC'
		ORDER BY CORR_CHEQUERA;

		IF ISNULL(@CORR_CHEQUERA, 0) = 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No hay chequera activa para la cuenta bancaria', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		BEGIN TRANSACTION BAN_CHEQUE_IMPRIME;

		IF @ESTADO = 'AP'
		BEGIN
			IF EXISTS (
				SELECT 1 FROM dbo.BAN_DOCUMENTO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA
					AND CORR_CHEQUERA = @CORR_CHEQUERA AND SERIE_CHEQUE = @SERIE AND NUMERO_DOCUMENTO = @NUMERO_CHEQUE
					AND NOT (ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO)
			)
			BEGIN
				IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_CHEQUE_IMPRIME;
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El número de cheque ya fue utilizado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			UPDATE dbo.BAN_DOCUMENTO SET
				CORR_CHEQUERA = @CORR_CHEQUERA,
				NUMERO_DOCUMENTO = @NUMERO_CHEQUE,
				SERIE_CHEQUE = @SERIE,
				ESTADO_DOCUMENTO = 'IM',
				FECHA_IMPRESO = CAST(@FECHA_ACTU AS DATE),
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

			UPDATE M SET
				M.REFERENCIA = LTRIM(RTRIM(CONVERT(VARCHAR(25), D.SERIE_CHEQUE) + N' ' + CONVERT(VARCHAR(25), D.NUMERO_DOCUMENTO)))
			FROM dbo.BAN_MOVIMIENTO M
			INNER JOIN dbo.BAN_DOCUMENTO D
				ON M.CORR_EMPRESA = D.CORR_EMPRESA
				AND ISNULL(M.ANIO_PERIODO_DOC, M.ANIO_PERIODO) = D.ANIO_PERIODO
				AND ISNULL(M.MES_PERIODO_DOC, M.MES_PERIODO) = D.MES_PERIODO
				AND M.CORR_TIPO_MOVIMIENTO = D.CORR_TIPO_MOVIMIENTO
				AND M.CORR_DOCUMENTO = D.CORR_DOCUMENTO
			WHERE D.CORR_EMPRESA = @CORR_EMPRESA
				AND D.ANIO_PERIODO = @ANIO_PERIODO
				AND D.MES_PERIODO = @MES_PERIODO
				AND D.CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND D.CORR_DOCUMENTO = @CORR_DOCUMENTO;

			UPDATE dbo.BAN_CHEQUERA SET
				NUMERO_CHEQUE_ACTUAL = NUMERO_CHEQUE_ACTUAL + 1,
				ESTADO_CHEQUERA = CASE WHEN (NUMERO_CHEQUE_ACTUAL + 1) > NUMERO_CHEQUE_FINAL THEN 'IN' ELSE ESTADO_CHEQUERA END
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA AND CORR_CHEQUERA = @CORR_CHEQUERA
				AND NUMERO_CHEQUE_ACTUAL < NUMERO_CHEQUE_FINAL;
		END;

		SELECT @CONTABILIZAR = CONTABILIZAR_LUEGO_DE_IMPRIMIR
		FROM dbo.BAN_TIPO_CHEQUE
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE;

		IF @CONTABILIZAR IS NULL
			SELECT @CONTABILIZAR = CONTABILIZAR_LUEGO_DE_IMPRIMIR
			FROM dbo.BAN_PARAMETRO
			WHERE CORR_EMPRESA = @CORR_EMPRESA;

		IF ISNULL(@CONTABILIZAR, 0) = 1
		BEGIN
			EXEC dbo.PRAL_MTTO_BAN_DOCUMENTO_CONTABILIZAR
				@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO,
				@USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU, @SYS_LOGIN_USUARIO, @SYS_ESTACION,
				@SYS_FILAS_AFECTADAS OUTPUT, @SYS_NUMERO_ERROR OUTPUT, @SYS_MENSAJE_ERROR OUTPUT;

			IF @SYS_NUMERO_ERROR <> 0
			BEGIN
				IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_CHEQUE_IMPRIME;
				GOTO FINA;
			END;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
		IF @@TRANCOUNT > 0 COMMIT TRANSACTION BAN_CHEQUE_IMPRIME;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_CHEQUE_IMPRIME;
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

/* ── Des-contabilizar documento bancario ── */
IF OBJECT_ID(N'dbo.PRAL_MTTO_BAN_DOCUMENTO_DESCONTABILIZAR', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_DESCONTABILIZAR];
GO

CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_DESCONTABILIZAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE
		@ESTADO_DOCUMENTO VARCHAR(2),
		@ESTA_CONTABILIZADO BIT,
		@DETALLE_DOCUMENTO NVARCHAR(255),
		@NOMBRE_TIPO_MOVIMIENTO VARCHAR(100),
		@ANIO_PERIODO_CON INT,
		@MES_PERIODO_CON INT,
		@CORR_CLASE_PARTIDA INT,
		@CORR_PARTIDA INT,
		@ESTADO_PARTIDA VARCHAR(2);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE());

	BEGIN TRY
		SELECT @NOMBRE_TIPO_MOVIMIENTO = NOMBRE_TIPO_MOVIMIENTO
		FROM dbo.BAN_TIPO_MOVI_BANCARIO
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

		SET @DETALLE_DOCUMENTO = @NOMBRE_TIPO_MOVIMIENTO + N' del Año ' + CONVERT(VARCHAR(10), @ANIO_PERIODO)
			+ N' Mes ' + CONVERT(VARCHAR(10), @MES_PERIODO)
			+ N' Correlativo No.' + CONVERT(VARCHAR(10), @CORR_DOCUMENTO);

		SELECT
			@ESTADO_DOCUMENTO = ESTADO_DOCUMENTO,
			@ESTA_CONTABILIZADO = ESTA_CONTABILIZADO,
			@ANIO_PERIODO_CON = ANIO_PERIODO,
			@MES_PERIODO_CON = MES_PERIODO
		FROM dbo.BAN_DOCUMENTO
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @ESTADO_DOCUMENTO NOT IN ('AP', 'IM') OR ISNULL(@ESTA_CONTABILIZADO, 0) = 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'Este documento no está contabilizado o no se puede des-contabilizar. ' + @DETALLE_DOCUMENTO,
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO_CON
				AND MES_PERIODO = @MES_PERIODO_CON
				AND ESTADO_PERIODO_CON = 'AB'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30001,
				@SYS_MENSAJE_ERROR = N'El período contable no está abierto. ' + @DETALLE_DOCUMENTO + N' no se puede des-contabilizar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		BEGIN TRANSACTION BAN_DOCUMENTO_DESCONTABILIZAR;

		DECLARE curPartidas CURSOR LOCAL FAST_FORWARD FOR
			SELECT DISTINCT ANIO_PERIODO, MES_PERIODO, CORR_CLASE_PARTIDA, CORR_PARTIDA
			FROM dbo.BAN_PARTIDA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO_DOC = @ANIO_PERIODO
				AND MES_PERIODO_DOC = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		OPEN curPartidas;
		FETCH NEXT FROM curPartidas INTO @ANIO_PERIODO_CON, @MES_PERIODO_CON, @CORR_CLASE_PARTIDA, @CORR_PARTIDA;

		WHILE @@FETCH_STATUS = 0
		BEGIN
			SELECT @ESTADO_PARTIDA = ESTADO_PARTIDA
			FROM dbo.CON_PARTIDA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO_CON
				AND MES_PERIODO = @MES_PERIODO_CON
				AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA
				AND CORR_PARTIDA = @CORR_PARTIDA;

			IF @ESTADO_PARTIDA = 'AP'
			BEGIN
				EXEC dbo.PRAL_MTTO_CON_PARTIDA_DESAPLICAR
					@CORR_EMPRESA,
					@ANIO_PERIODO_CON,
					@MES_PERIODO_CON,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA OUTPUT,
					@USUARIO_ACTU,
					@FECHA_ACTU,
					@ESTACION_ACTU,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT;

				IF @SYS_NUMERO_ERROR <> 0
				BEGIN
					IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_DESCONTABILIZAR;
					CLOSE curPartidas;
					DEALLOCATE curPartidas;
					SET @SYS_MENSAJE_ERROR = @DETALLE_DOCUMENTO + N' [' + @SYS_MENSAJE_ERROR + N']';
					GOTO FINA;
				END;
			END;

			IF @ESTADO_PARTIDA IN ('DI', 'AP')
			BEGIN
				EXEC dbo.PRAL_MTTO_CON_PARTIDA_ANULAR
					@CORR_EMPRESA,
					@ANIO_PERIODO_CON,
					@MES_PERIODO_CON,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA OUTPUT,
					@USUARIO_ACTU,
					@FECHA_ACTU,
					@ESTACION_ACTU,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT;

				IF @SYS_NUMERO_ERROR <> 0
				BEGIN
					IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_DESCONTABILIZAR;
					CLOSE curPartidas;
					DEALLOCATE curPartidas;
					SET @SYS_MENSAJE_ERROR = @DETALLE_DOCUMENTO + N' [' + @SYS_MENSAJE_ERROR + N']';
					GOTO FINA;
				END;
			END;

			FETCH NEXT FROM curPartidas INTO @ANIO_PERIODO_CON, @MES_PERIODO_CON, @CORR_CLASE_PARTIDA, @CORR_PARTIDA;
		END;

		CLOSE curPartidas;
		DEALLOCATE curPartidas;

		DELETE FROM dbo.BAN_PARTIDA_DETA
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO_DOC = @ANIO_PERIODO
			AND MES_PERIODO_DOC = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		UPDATE dbo.BAN_DOCUMENTO SET
			ESTA_CONTABILIZADO = 0,
			USUARIO_ACTU = @USUARIO_ACTU,
			FECHA_ACTU = @FECHA_ACTU,
			ESTACION_ACTU = @ESTACION_ACTU
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;

		IF @@TRANCOUNT > 0 COMMIT TRANSACTION BAN_DOCUMENTO_DESCONTABILIZAR;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_DESCONTABILIZAR;
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

PRINT N'DEPLOY_BAN_CONTABILIZAR completado.';
