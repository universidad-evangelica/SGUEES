        WHERE T.CORR_EMPRESA = @CORR_EMPRESA
          AND T.CORR_TOKEN = @CORR_TOKEN;
    END;

    SELECT
        CORR_EMPRESA,
        CORR_TOKEN,
        CORR_SOLICITUD_EMPLEO,
        TOKEN_HASH,
        FECHA_GENERACION,
        FECHA_EXPIRACION,
        FECHA_UTILIZACION,
        ESTADO_TOKEN,
