            @APELLIDO1, NULLIF(LTRIM(RTRIM(@APELLIDO2)), ''), @FECHA_NACIMIENTO, ISNULL(@EDAD, 0),
            NULLIF(LTRIM(RTRIM(@ESTADO_CIVIL)), ''), NULLIF(LTRIM(RTRIM(@NACIONALIDAD)), ''),
            @CORREO, @CELULAR, NULLIF(LTRIM(RTRIM(@TELEFONO)), ''), @DIRECCION, @DUI,
            NULLIF(LTRIM(RTRIM(@PASAPORTE)), ''), NULLIF(LTRIM(RTRIM(@ISSS)), ''),
            NULLIF(LTRIM(RTRIM(@AFP)), ''), NULLIF(LTRIM(RTRIM(@NOMBRE_AFP)), ''),
            NULLIF(LTRIM(RTRIM(@LICENCIA)), ''), NULLIF(LTRIM(RTRIM(@PLAZA_SOLICITADA)), ''),
            ISNULL(@PRETENSION_SALARIAL, 0), NULLIF(LTRIM(RTRIM(@DISPONIBILIDAD)), ''),
            NULLIF(LTRIM(RTRIM(@RELIGION)), ''), NULLIF(LTRIM(RTRIM(@IGLESIA)), ''),
            NULLIF(LTRIM(RTRIM(@DIRECCION_IGLESIA)), ''), ISNULL(@ES_CONTRIBUYENTE_CCF, 0),
            ISNULL(@ES_JUBILADO, 0), ISNULL(@POSEE_DISCAPACIDAD, 0),
