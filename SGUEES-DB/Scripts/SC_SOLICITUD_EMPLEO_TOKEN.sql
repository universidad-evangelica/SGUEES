        SET @XML_EXPERIENCIAS = CAST(COALESCE(NULLIF(@EXPERIENCIAS_XML, N''), N'<rows/>') AS xml);
        SET @XML_FAMILIARES_UEES = CAST(COALESCE(NULLIF(@FAMILIARES_UEES_XML, N''), N'<rows/>') AS xml);

        SELECT
            @CORR_EMPRESA = T.CORR_EMPRESA,
            @CORR_TOKEN = T.CORR_TOKEN,
            @CORR_SOLICITUD_EMPLEO = T.CORR_SOLICITUD_EMPLEO
        FROM dbo.SC_SOLICITUD_EMPLEO_TOKEN T WITH (UPDLOCK, HOLDLOCK)
        INNER JOIN dbo.SC_SOLICITUD_EMPLEO S WITH (UPDLOCK, HOLDLOCK)
            ON S.CORR_EMPRESA = T.CORR_EMPRESA
           AND S.CORR_SOLICITUD_EMPLEO = T.CORR_SOLICITUD_EMPLEO
        WHERE T.TOKEN_HASH = @TOKEN_HASH
          AND T.ESTADO_TOKEN = 'ENVIADO'
          AND T.FECHA_EXPIRACION >= GETDATE()
          AND S.ACTIVO = 1
          AND S.CORR_PERSONA_DATOS IS NULL;

        IF @CORR_TOKEN IS NULL
            THROW 50002, N'El enlace es inválido, expiró o ya fue utilizado.', 1;

        SELECT @CORR_PERSONA_DATOS = ISNULL(MAX(CORR_PERSONA_DATOS), 0) + 1
        FROM dbo.SC_PERSONA_DATOS WITH (UPDLOCK, HOLDLOCK)
        WHERE CORR_EMPRESA = @CORR_EMPRESA;

        INSERT INTO dbo.SC_PERSONA_DATOS (
            CORR_EMPRESA, CORR_PERSONA_DATOS, NOMBRE1, NOMBRE2, APELLIDO1, APELLIDO2,
            FECHA_NACIMIENTO, EDAD, ESTADO_CIVIL, NACIONALIDAD, CORREO, CELULAR, TELEFONO,
            DIRECCION, DUI, PASAPORTE, ISSS, AFP, NOMBRE_AFP, LICENCIA, PLAZA_SOLICITADA,
            PRETENSION_SALARIAL, DISPONIBILIDAD, RELIGION, IGLESIA, DIRECCION_IGLESIA,
            ES_CONTRIBUYENTE_CCF, ES_JUBILADO, POSEE_DISCAPACIDAD, TIPO_DISCAPACIDAD,
