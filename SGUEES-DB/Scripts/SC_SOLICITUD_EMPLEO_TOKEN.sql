CREATE OR ALTER PROCEDURE dbo.PRAL_DATA_SC_SOLICITUD_EMPLEO_TOKEN
    @CORR_EMPRESA int,
    @CORR_SOLICITUD_EMPLEO int
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    UPDATE dbo.SC_SOLICITUD_EMPLEO_TOKEN
       SET ESTADO_TOKEN = 'EXPIRADO'
     WHERE CORR_EMPRESA = @CORR_EMPRESA
       AND CORR_SOLICITUD_EMPLEO = @CORR_SOLICITUD_EMPLEO
       AND ESTADO_TOKEN = 'ENVIADO'
       AND FECHA_EXPIRACION < GETDATE();

    SELECT
        CORR_EMPRESA,
        CORR_TOKEN,
        CORR_SOLICITUD_EMPLEO,
        CASE
            WHEN TOKEN_HASH IS NULL THEN NULL
            WHEN LEN(TOKEN_HASH) <= 12 THEN TOKEN_HASH
            ELSE LEFT(TOKEN_HASH, 8) + '...' + RIGHT(TOKEN_HASH, 4)
        END AS TOKEN_HASH,
        FECHA_GENERACION,
        FECHA_EXPIRACION,
        FECHA_UTILIZACION,
        ESTADO_TOKEN,
        CORREO_DESTINO
    FROM dbo.SC_SOLICITUD_EMPLEO_TOKEN
    WHERE CORR_EMPRESA = @CORR_EMPRESA
      AND CORR_SOLICITUD_EMPLEO = @CORR_SOLICITUD_EMPLEO
    ORDER BY CORR_TOKEN DESC;
END;
GO

CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_SC_SOLICITUD_EMPLEO_TOKEN_GENERAR
    @CORR_EMPRESA int,
    @CORR_SOLICITUD_EMPLEO int,
    @TOKEN_HASH varchar(64),
    @FECHA_GENERACION datetime,
    @FECHA_EXPIRACION datetime,
    @CORREO_DESTINO varchar(254)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRANSACTION;

    IF NOT EXISTS (
        SELECT 1
        FROM dbo.SC_SOLICITUD_EMPLEO WITH (UPDLOCK, HOLDLOCK)
        WHERE CORR_EMPRESA = @CORR_EMPRESA
          AND CORR_SOLICITUD_EMPLEO = @CORR_SOLICITUD_EMPLEO
          AND ACTIVO = 1
          AND CORR_PERSONA_DATOS IS NULL
    )
    BEGIN
        THROW 50001, N'La solicitud de empleo no existe, está inactiva o ya fue completada.', 1;
    END;

    UPDATE dbo.SC_SOLICITUD_EMPLEO_TOKEN
       SET ESTADO_TOKEN = CASE
            WHEN FECHA_EXPIRACION < @FECHA_GENERACION THEN 'EXPIRADO'
            ELSE 'REVOCADO'
       END
     WHERE CORR_EMPRESA = @CORR_EMPRESA
       AND CORR_SOLICITUD_EMPLEO = @CORR_SOLICITUD_EMPLEO
       AND ESTADO_TOKEN IN ('GENERADO', 'ENVIADO');

    DECLARE @CORR_TOKEN int;

    SELECT @CORR_TOKEN = ISNULL(MAX(CORR_TOKEN), 0) + 1
    FROM dbo.SC_SOLICITUD_EMPLEO_TOKEN WITH (UPDLOCK, HOLDLOCK)
    WHERE CORR_EMPRESA = @CORR_EMPRESA;

    INSERT INTO dbo.SC_SOLICITUD_EMPLEO_TOKEN (
        CORR_EMPRESA,
        CORR_TOKEN,
        CORR_SOLICITUD_EMPLEO,
        TOKEN_HASH,
        FECHA_GENERACION,
        FECHA_EXPIRACION,
        FECHA_UTILIZACION,
        ESTADO_TOKEN,
        CORREO_DESTINO
    )
    VALUES (
        @CORR_EMPRESA,
        @CORR_TOKEN,
        @CORR_SOLICITUD_EMPLEO,
        @TOKEN_HASH,
        @FECHA_GENERACION,
        @FECHA_EXPIRACION,
        NULL,
        'GENERADO',
        @CORREO_DESTINO
    );

    COMMIT TRANSACTION;

    SELECT
        CORR_EMPRESA,
        CORR_TOKEN,
        CORR_SOLICITUD_EMPLEO,
        TOKEN_HASH,
        FECHA_GENERACION,
        FECHA_EXPIRACION,
        FECHA_UTILIZACION,
        ESTADO_TOKEN,
        CORREO_DESTINO
    FROM dbo.V_SC_SOLICITUD_EMPLEO_TOKEN
    WHERE CORR_EMPRESA = @CORR_EMPRESA
      AND CORR_TOKEN = @CORR_TOKEN;
END;
GO

CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_SC_SOLICITUD_EMPLEO_TOKEN_ESTADO
    @CORR_EMPRESA int,
    @CORR_TOKEN int,
    @ESTADO_TOKEN varchar(50)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    UPDATE dbo.SC_SOLICITUD_EMPLEO_TOKEN
       SET ESTADO_TOKEN = @ESTADO_TOKEN
     WHERE CORR_EMPRESA = @CORR_EMPRESA
       AND CORR_TOKEN = @CORR_TOKEN;

