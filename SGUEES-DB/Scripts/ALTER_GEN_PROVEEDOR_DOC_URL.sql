-- Qué hace: adapta GEN_PROVEEDOR_DOC para guardar URL de archivo (uploads/gen-proveedor-doc).
-- Cómo: agrega columnas, recrea PK y FK a GEN_PROVEEDOR. Idempotente.
SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

IF OBJECT_ID(N'dbo.GEN_PROVEEDOR_DOC', N'U') IS NULL
BEGIN
	CREATE TABLE [dbo].[GEN_PROVEEDOR_DOC]
	(
		[CORR_EMPRESA] [int] NOT NULL,
		[CORR_PROVEEDOR] [int] NOT NULL,
		[CORR_DOCUMENTO] [int] NOT NULL,
		[URL_DOCUMENTO] [nvarchar](500) NOT NULL CONSTRAINT [DF_GEN_PROVEEDOR_DOC_URL] DEFAULT (N''),
		[NOMBRE_ARCHIVO] [nvarchar](260) NULL,
		[USUARIO_CREA] [varchar](50) NULL,
		[FECHA_CREA] [datetime] NULL,
		[ESTACION_CREA] [varchar](50) NULL,
		[USUARIO_ACTU] [varchar](50) NULL,
		[FECHA_ACTU] [datetime] NULL,
		[ESTACION_ACTU] [varchar](50) NULL,
		CONSTRAINT [PK_GEN_PROVEEDOR_DOC] PRIMARY KEY CLUSTERED
		(
			[CORR_EMPRESA] ASC,
			[CORR_PROVEEDOR] ASC,
			[CORR_DOCUMENTO] ASC
		)
	);
END
GO

IF COL_LENGTH(N'dbo.GEN_PROVEEDOR_DOC', N'URL_DOCUMENTO') IS NULL
BEGIN
	IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE name = N'PK_COM_PROVEEDOR_DOC' AND parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR_DOC'))
		ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] DROP CONSTRAINT [PK_COM_PROVEEDOR_DOC];

	IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE name = N'PK_GEN_PROVEEDOR_DOC' AND parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR_DOC'))
		ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] DROP CONSTRAINT [PK_GEN_PROVEEDOR_DOC];

	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [URL_DOCUMENTO] [nvarchar](500) NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [NOMBRE_ARCHIVO] [nvarchar](260) NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [USUARIO_CREA] [varchar](50) NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [FECHA_CREA] [datetime] NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [ESTACION_CREA] [varchar](50) NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [USUARIO_ACTU] [varchar](50) NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [FECHA_ACTU] [datetime] NULL;
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ADD [ESTACION_ACTU] [varchar](50) NULL;
END
GO

IF COL_LENGTH(N'dbo.GEN_PROVEEDOR_DOC', N'URL_DOCUMENTO') IS NOT NULL
BEGIN
	UPDATE [dbo].[GEN_PROVEEDOR_DOC]
	SET URL_DOCUMENTO = N''
	WHERE URL_DOCUMENTO IS NULL;

	IF EXISTS (
		SELECT 1
		FROM sys.columns
		WHERE object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR_DOC')
		  AND name = N'URL_DOCUMENTO'
		  AND is_nullable = 1
	)
		ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] ALTER COLUMN [URL_DOCUMENTO] [nvarchar](500) NOT NULL;
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.key_constraints
	WHERE name = N'PK_GEN_PROVEEDOR_DOC'
	  AND parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR_DOC')
)
BEGIN
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC]
		ADD CONSTRAINT [PK_GEN_PROVEEDOR_DOC] PRIMARY KEY CLUSTERED
		(
			[CORR_EMPRESA] ASC,
			[CORR_PROVEEDOR] ASC,
			[CORR_DOCUMENTO] ASC
		);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PROVEEDOR_DOC_GEN_PROVEEDOR'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PROVEEDOR_DOC] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PROVEEDOR_DOC_GEN_PROVEEDOR]
		FOREIGN KEY ([CORR_EMPRESA], [CORR_PROVEEDOR])
		REFERENCES [dbo].[GEN_PROVEEDOR] ([CORR_EMPRESA], [CORR_PROVEEDOR]);
END
GO

PRINT N'GEN_PROVEEDOR_DOC listo.';
GO
