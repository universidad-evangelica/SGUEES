/* ---------- TABLAS ---------- */
IF OBJECT_ID(N'dbo.SC_EXPEDIENTE_CANDIDATO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SC_EXPEDIENTE_CANDIDATO (
        CORR_EMPRESA int NOT NULL,
        CORR_EXPEDIENTE_CANDIDATO int NOT NULL,
        CORR_PERSONA_DATOS int NOT NULL,
        CORR_ESTADO_EXPEDIENTE int NOT NULL CONSTRAINT DF_SC_EXPEDIENTE_CANDIDATO_ESTADO DEFAULT (1),
        FECHA_GENERACION datetime NOT NULL,
        ACTIVO bit NOT NULL CONSTRAINT DF_SC_EXPEDIENTE_CANDIDATO_ACTIVO DEFAULT (1),
        USUARIO_CREA varchar(50) NULL,
        ESTACION_CREA varchar(50) NULL,
        FECHA_CREA datetime NULL,
        USUARIO_ACTU varchar(50) NULL,
        ESTACION_ACTU varchar(50) NULL,
        FECHA_ACTU datetime NULL,
        CONSTRAINT PK_SC_EXPEDIENTE_CANDIDATO PRIMARY KEY CLUSTERED (CORR_EMPRESA, CORR_EXPEDIENTE_CANDIDATO)
    );

    ALTER TABLE dbo.SC_EXPEDIENTE_CANDIDATO ADD CONSTRAINT FK_SC_EXPEDIENTE_CANDIDATO_GEN_EMPRESA
        FOREIGN KEY (CORR_EMPRESA) REFERENCES dbo.GEN_EMPRESA (CORR_EMPRESA);

    ALTER TABLE dbo.SC_EXPEDIENTE_CANDIDATO ADD CONSTRAINT FK_SC_EXPEDIENTE_CANDIDATO_SC_PERSONA_DATOS
        FOREIGN KEY (CORR_EMPRESA, CORR_PERSONA_DATOS)
        REFERENCES dbo.SC_PERSONA_DATOS (CORR_EMPRESA, CORR_PERSONA_DATOS);

    CREATE UNIQUE NONCLUSTERED INDEX UX_SC_EXPEDIENTE_CANDIDATO_PERSONA
        ON dbo.SC_EXPEDIENTE_CANDIDATO (CORR_EMPRESA, CORR_PERSONA_DATOS);

    PRINT N'Tabla SC_EXPEDIENTE_CANDIDATO creada.';
END
ELSE
    PRINT N'Tabla SC_EXPEDIENTE_CANDIDATO ya existe.';
GO

