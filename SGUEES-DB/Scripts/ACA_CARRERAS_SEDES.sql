CREATE OR ALTER VIEW dbo.V_ACA_CARRERAS_SEDES AS
SELECT CS.*, C.CORR_EMPRESA, S.CODIGO_SEDE, S.NOMBRE_SEDE, S.ESTADO_SEDE
FROM dbo.ACA_CARRERAS_SEDES CS
JOIN dbo.ACA_CARRERAS C ON C.CORR_CARRERA=CS.CORR_CARRERA
JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=CS.CORR_SEDE AND S.CORR_EMPRESA=C.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_SEDES_CARRERA_LOOKUP AS
SELECT C.CORR_CARRERA, C.CORR_EMPRESA, S.CORR_SEDE AS [Key], S.NOMBRE_SEDE AS Value,
       CAST(CASE WHEN C.ACTIVO=1 AND F.ACTIVO=1 AND S.ESTADO_SEDE='A' AND FS.ACTIVO=1 THEN 1 ELSE 0 END AS bit) AS HABILITADA,
       CASE WHEN C.ACTIVO=0 THEN 'La carrera está inactiva.'
            WHEN F.ACTIVO=0 THEN 'La facultad está inactiva.'
            WHEN ISNULL(S.ESTADO_SEDE,'')<>'A' THEN 'La sede está inactiva.'
            WHEN FS.CORR_FACULTAD IS NULL THEN 'La facultad no está autorizada en esta sede.'
            WHEN FS.ACTIVO=0 THEN 'La autorización de la facultad en esta sede está inactiva.'
            ELSE 'Disponible' END AS MOTIVO
FROM dbo.ACA_CARRERAS C
JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.GEN_SEDES S ON S.CORR_EMPRESA=C.CORR_EMPRESA
LEFT JOIN dbo.ACA_FACULTADES_SEDES FS ON FS.CORR_FACULTAD=C.CORR_FACULTAD AND FS.CORR_SEDE=S.CORR_SEDE;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_CARRERAS_SEDES
    @TIPO_ACTUALIZA int, -- 1 asociar, 2 activar/desactivar
    @CORR_EMPRESA int,
    @CORR_CARRERA int,
    @CORR_SEDE int,
    @SYS_LOGIN_USUARIO varchar(50),
    @SYS_ESTACION varchar(100),
    @SYS_NUMERO_ERROR int OUTPUT,
    @SYS_MENSAJE_ERROR nvarchar(4000) OUTPUT,
    @SYS_FILAS_AFECTADAS int OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @TRAN_INICIAL int=@@TRANCOUNT;
    SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR=N'',@SYS_FILAS_AFECTADAS=0;
    BEGIN TRY
        IF ISNULL(@CORR_EMPRESA,0)<=0 THROW 51000,N'No se encontró la empresa de la sesión.',1;
        IF @TIPO_ACTUALIZA IS NULL OR @TIPO_ACTUALIZA NOT IN (1,2) THROW 51000,N'Operación no válida.',1;
        IF NULLIF(LTRIM(RTRIM(@SYS_LOGIN_USUARIO)),'') IS NULL THROW 51000,N'No se encontró el usuario de la sesión.',1;
        IF @TRAN_INICIAL=0 BEGIN TRANSACTION;
        ELSE SAVE TRANSACTION ACA_CARRERAS_SEDES_MTTO;
        DECLARE @FACULTAD int,@CARRERA_ACTIVA bit,@ASOCIACION_ACTIVA bit;
        -- El bloqueo del padre coordina las operaciones con el mantenimiento de carreras.
        SELECT @FACULTAD=CORR_FACULTAD,@CARRERA_ACTIVA=ACTIVO
        FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
        WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_EMPRESA=@CORR_EMPRESA;
        IF @FACULTAD IS NULL THROW 51000,N'La carrera no existe en la empresa de la sesión. Guarde primero la carrera.',1;
        IF NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WITH (HOLDLOCK)
            WHERE CORR_SEDE=@CORR_SEDE AND CORR_EMPRESA=@CORR_EMPRESA)
            THROW 51000,N'La sede no existe en la empresa de la sesión.',1;
        SELECT @ASOCIACION_ACTIVA=ACTIVO
        FROM dbo.ACA_CARRERAS_SEDES WITH (UPDLOCK,HOLDLOCK)
        WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_SEDE=@CORR_SEDE;
        IF @TIPO_ACTUALIZA=1 AND @ASOCIACION_ACTIVA IS NOT NULL
        BEGIN
            IF @ASOCIACION_ACTIVA=0 THROW 51000,N'La sede ya está asociada e inactiva. Seleccione la fila y utilice Activar.',1;
            THROW 51000,N'La sede ya está asociada a esta carrera.',1;
        END;
        IF @TIPO_ACTUALIZA=2 AND @ASOCIACION_ACTIVA IS NULL THROW 51000,N'No existe la asociación carrera-sede seleccionada.',1;
        -- Desactivar se permite aun si un padre está inactivo; conserva períodos e historial.
        IF @TIPO_ACTUALIZA=1 OR @ASOCIACION_ACTIVA=0
        BEGIN
            IF @CARRERA_ACTIVA=0 THROW 51000,N'La carrera debe estar activa para habilitar una sede.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WITH (HOLDLOCK)
                WHERE CORR_SEDE=@CORR_SEDE AND CORR_EMPRESA=@CORR_EMPRESA AND ESTADO_SEDE='A')
                THROW 51000,N'La sede debe estar activa.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES WITH (HOLDLOCK)
                WHERE CORR_FACULTAD=@FACULTAD AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                THROW 51000,N'La facultad de la carrera debe estar activa.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES_SEDES WITH (HOLDLOCK)
                WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@CORR_SEDE AND ACTIVO=1)
                THROW 51000,N'La facultad no tiene una autorización activa en esta sede. Configure Facultades por sede antes de habilitar la carrera.',1;
        END;
        IF @TIPO_ACTUALIZA=1
            INSERT dbo.ACA_CARRERAS_SEDES(CORR_CARRERA,CORR_SEDE,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
            VALUES(@CORR_CARRERA,@CORR_SEDE,1,@SYS_LOGIN_USUARIO,@SYS_ESTACION,GETDATE());
        ELSE
            UPDATE dbo.ACA_CARRERAS_SEDES
            SET ACTIVO=CASE WHEN @ASOCIACION_ACTIVA=1 THEN 0 ELSE 1 END,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_SEDE=@CORR_SEDE;
        SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        IF @TRAN_INICIAL=0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @TRAN_INICIAL=0 AND XACT_STATE()<>0 ROLLBACK TRANSACTION;
        ELSE IF @TRAN_INICIAL>0 AND XACT_STATE()=1 ROLLBACK TRANSACTION ACA_CARRERAS_SEDES_MTTO;
        SELECT @SYS_NUMERO_ERROR=ERROR_NUMBER(),@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),@SYS_FILAS_AFECTADAS=0;
        IF @SYS_NUMERO_ERROR IN (2601,2627) SET @SYS_MENSAJE_ERROR=N'La sede ya está asociada a esta carrera.';
    END CATCH;
END;
GO
