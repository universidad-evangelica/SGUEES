CREATE OR ALTER VIEW dbo.V_ACA_BECA_TIPO_MTTO
AS
SELECT
    T.CORR_EMPRESA,
    T.CORR_BECA,
    T.CODIGO_BECA,
    T.NOMBRE_BECA,
    T.CORR_ORIGEN_BECA,
    O.CODIGO_ORIGEN,
    O.NOMBRE_ORIGEN,
    T.CORR_CONVENIO,
    C.CODIGO_CONVENIO,
    C.NOMBRE_CONVENIO,
    T.ARTICULO_REGLAMENTO,
    T.PORCENTAJE_COBERTURA_REFERENCIAL,
    T.CUM_MINIMO_RENOVACION,
    T.APLICA_NUEVO_INGRESO,
    T.APLICA_ANTIGUO_INGRESO,
    T.APLICA_EMPLEADO,
    T.APLICA_HIJO_EMPLEADO,
    T.NIVEL_ACADEMICO_APLICA,
    T.REQUIERE_CONVENIO,
    T.REQUIERE_ESTUDIO_SOCIOECONOMICO,
    T.REQUIERE_APROBACION_COMITE,
    T.REQUIERE_APROBACION_DIRECTORIO,
    T.UNIDAD_RESPONSABLE,
    T.DESCRIPCION,
    T.ESTADO_BECA,
    CAST(CASE WHEN T.ESTADO_BECA = 'ACTIVA' THEN 1 ELSE 0 END AS bit) AS ACTIVO,
    ISNULL(R.CANT_REQUISITOS, 0) AS CANT_REQUISITOS,
    ISNULL(D.CANT_DOCUMENTOS, 0) AS CANT_DOCUMENTOS,
    ISNULL(F.CANT_FINANCIADORES, 0) AS CANT_FINANCIADORES,
    (SELECT COUNT(*) FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO TF
     JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION FV ON FV.CORR_FORMULARIO_VERSION=TF.CORR_FORMULARIO_VERSION AND FV.CORR_EMPRESA=TF.CORR_EMPRESA
     WHERE TF.CORR_EMPRESA=T.CORR_EMPRESA AND TF.CORR_BECA=T.CORR_BECA AND TF.ACTIVO=1 AND FV.ACTIVO=1
      AND FV.FECHA_INICIO<=CONVERT(date,GETDATE()) AND (FV.FECHA_FIN IS NULL OR FV.FECHA_FIN>=CONVERT(date,GETDATE()))) CANT_FORMULARIOS,
    T.USUARIO_CREA,
    T.ESTACION_CREA,
    T.FECHA_CREA,
    T.USUARIO_ACTU,
    T.ESTACION_ACTU,
    T.FECHA_ACTU,
    T.VERSION_REGISTRO
FROM dbo.ACA_BECA_TIPO T
INNER JOIN dbo.ACA_BECA_ORIGEN_BECA O
    ON O.CORR_ORIGEN_BECA = T.CORR_ORIGEN_BECA
    AND O.CORR_EMPRESA = T.CORR_EMPRESA
LEFT JOIN dbo.ACA_BECA_CONVENIO C
    ON C.CORR_CONVENIO = T.CORR_CONVENIO
    AND C.CORR_EMPRESA = T.CORR_EMPRESA
LEFT JOIN (
    SELECT CORR_EMPRESA, CORR_BECA, COUNT(1) AS CANT_REQUISITOS
    FROM dbo.ACA_BECA_REQUISITO
    GROUP BY CORR_EMPRESA, CORR_BECA
) R ON R.CORR_EMPRESA = T.CORR_EMPRESA AND R.CORR_BECA = T.CORR_BECA
LEFT JOIN (
    SELECT CORR_EMPRESA, CORR_BECA, COUNT(1) AS CANT_DOCUMENTOS
    FROM dbo.ACA_BECA_DOCUMENTO_REQUERIDO
    GROUP BY CORR_EMPRESA, CORR_BECA
) D ON D.CORR_EMPRESA = T.CORR_EMPRESA AND D.CORR_BECA = T.CORR_BECA
LEFT JOIN (
    SELECT CORR_EMPRESA, CORR_BECA, COUNT(1) AS CANT_FINANCIADORES
    FROM dbo.ACA_BECA_FINANCIADOR
    GROUP BY CORR_EMPRESA, CORR_BECA
) F ON F.CORR_EMPRESA = T.CORR_EMPRESA AND F.CORR_BECA = T.CORR_BECA;
GO
