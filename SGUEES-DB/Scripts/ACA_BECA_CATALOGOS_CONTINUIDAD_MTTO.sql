CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_REQUISITO
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(30),
    @ESTACION varchar(30),
    @CORR_BECA int = NULL,
    @NOMBRE_REQUISITO varchar(200) = NULL,
    @DESCRIPCION varchar(1000) = NULL,
    @OBLIGATORIO bit = NULL,
    @ACTIVO bit = NULL,
    @VERSION_REGISTRO varbinary(8)=NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;

        IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
            THROW 51000,N'La empresa de sesion no existe.',1;
        IF @TIPO_ACTUALIZA<>1 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_REQUISITO WITH(UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
            THROW 51009,N'El registro cambio o ya no existe. Actualice el listado antes de continuar.',1;

        IF @TIPO_ACTUALIZA IN(1,2)
        BEGIN
            SET @NOMBRE_REQUISITO=LTRIM(RTRIM(@NOMBRE_REQUISITO));
            IF ISNULL(@CORR_BECA,0)<=0 OR NULLIF(@NOMBRE_REQUISITO,'') IS NULL OR @ACTIVO IS NULL OR @OBLIGATORIO IS NULL
                THROW 51000,N'Debe indicar la beca, el nombre, obligatoriedad y estado.',1;
            IF EXISTS(SELECT 1 FROM dbo.ACA_BECA_REQUISITO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA
                AND CORR_BECA=@CORR_BECA AND NOMBRE_REQUISITO=@NOMBRE_REQUISITO AND (@TIPO_ACTUALIZA=1 OR CORR_BECA_REQUISITO<>@ID))
                THROW 51000,N'Ya existe ese registro para la beca.',1;
        END;

        IF @TIPO_ACTUALIZA=2 AND EXISTS(SELECT 1 FROM dbo.ACA_BECA_REQUISITO R WHERE R.CORR_EMPRESA=@CORR_EMPRESA AND R.CORR_BECA_REQUISITO=@ID AND R.CORR_BECA<>@CORR_BECA)
            AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_REQUISITO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID)
            THROW 51000,N'No se puede cambiar la beca de un registro utilizado por solicitudes.',1;

        IF @TIPO_ACTUALIZA IN (1,2)
        BEGIN
            IF @CORR_BECA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA) THROW 51000,N'La referencia CORR_BECA no pertenece a su empresa.',1;
        END
        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_BECA_REQUISITO),0)+1 FROM dbo.ACA_BECA_REQUISITO WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_REQUISITO(CORR_BECA,NOMBRE_REQUISITO,DESCRIPCION,OBLIGATORIO,ACTIVO,CORR_EMPRESA,CORR_BECA_REQUISITO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CORR_BECA,@NOMBRE_REQUISITO,@DESCRIPCION,@OBLIGATORIO,@ACTIVO,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_REQUISITO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_REQUISITO SET CORR_BECA=@CORR_BECA,
                NOMBRE_REQUISITO=@NOMBRE_REQUISITO,
                DESCRIPCION=@DESCRIPCION,
                OBLIGATORIO=@OBLIGATORIO,
                ACTIVO=@ACTIVO, USUARIO_ACTU=@USUARIO, ESTACION_ACTU=@ESTACION, FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID;
            IF @TIPO_ACTUALIZA=3
                DELETE dbo.ACA_BECA_REQUISITO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID;
            IF @TIPO_ACTUALIZA=4
                UPDATE dbo.ACA_BECA_REQUISITO SET ACTIVO=CONVERT(bit,1-CONVERT(int,ACTIVO)),USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_REQUISITO=@ID;
        END
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        IF ERROR_NUMBER()=547 AND @TIPO_ACTUALIZA=3 THROW 51000,N'No se puede eliminar: el registro tiene dependencias.',1;
        THROW;
    END CATCH
END;
