CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_ORIGEN_BECA
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(30),
    @ESTACION varchar(30),
    @CODIGO_ORIGEN varchar(20) = NULL,
    @NOMBRE_ORIGEN varchar(100) = NULL,
    @DESCRIPCION varchar(300) = NULL,
    @ACTIVO bit = NULL,
    @VERSION_REGISTRO varbinary(8)=NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;

        IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
            THROW 51000,N'La empresa de sesion no existe.',1;
        IF @TIPO_ACTUALIZA<>1 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
            THROW 51009,N'El registro cambio o ya no existe. Actualice el listado antes de continuar.',1;

        IF @TIPO_ACTUALIZA IN(1,2)
        BEGIN
            SET @CODIGO_ORIGEN=UPPER(LTRIM(RTRIM(@CODIGO_ORIGEN)));
            SET @NOMBRE_ORIGEN=LTRIM(RTRIM(@NOMBRE_ORIGEN));
            IF NULLIF(@CODIGO_ORIGEN,'') IS NULL OR NULLIF(@NOMBRE_ORIGEN,'') IS NULL
                THROW 51000,N'El codigo y el nombre son obligatorios.',1;
            IF EXISTS(SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA
                AND CODIGO_ORIGEN=@CODIGO_ORIGEN AND (@TIPO_ACTUALIZA=1 OR CORR_ORIGEN_BECA<>@ID))
                THROW 51000,N'Ya existe un registro con ese codigo en la empresa.',1;
        END;

        IF ((@TIPO_ACTUALIZA=2 AND @ACTIVO=0) OR (@TIPO_ACTUALIZA=4 AND EXISTS(
            SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID AND ACTIVO=1)))
            AND EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID AND ESTADO_BECA='ACTIVA')
            THROW 51000,N'No se puede desactivar un origen con becas activas.',1;

        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_ORIGEN_BECA),0)+1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_ORIGEN_BECA(CODIGO_ORIGEN,NOMBRE_ORIGEN,DESCRIPCION,ACTIVO,CORR_EMPRESA,CORR_ORIGEN_BECA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CODIGO_ORIGEN,@NOMBRE_ORIGEN,@DESCRIPCION,@ACTIVO,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_ORIGEN_BECA SET CODIGO_ORIGEN=@CODIGO_ORIGEN,
                NOMBRE_ORIGEN=@NOMBRE_ORIGEN,
                DESCRIPCION=@DESCRIPCION,
                ACTIVO=@ACTIVO, USUARIO_ACTU=@USUARIO, ESTACION_ACTU=@ESTACION, FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID;
            IF @TIPO_ACTUALIZA=3
                DELETE dbo.ACA_BECA_ORIGEN_BECA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID;
            IF @TIPO_ACTUALIZA=4
                UPDATE dbo.ACA_BECA_ORIGEN_BECA SET ACTIVO=CONVERT(bit,1-CONVERT(int,ACTIVO)),USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@ID;
        END
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        IF ERROR_NUMBER()=547 AND @TIPO_ACTUALIZA=3 THROW 51000,N'No se puede eliminar: el registro tiene dependencias.',1;
        THROW;
    END CATCH
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_TIPO
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(30),
    @ESTACION varchar(30),
    @CODIGO_BECA varchar(30) = NULL,
    @NOMBRE_BECA varchar(200) = NULL,
    @CORR_ORIGEN_BECA int = NULL,
    @CORR_CONVENIO int = NULL,
    @ARTICULO_REGLAMENTO varchar(50) = NULL,
    @PORCENTAJE_COBERTURA_REFERENCIAL decimal(5,2) = NULL,
    @REQUIERE_CONVENIO bit = NULL,
    @REQUIERE_ESTUDIO_SOCIOECONOMICO bit = NULL,
    @REQUIERE_APROBACION_COMITE bit = NULL,
    @REQUIERE_APROBACION_DIRECTORIO bit = NULL,
    @UNIDAD_RESPONSABLE varchar(150) = NULL,
    @DESCRIPCION varchar(1000) = NULL,
    @ESTADO_BECA varchar(20) = NULL,
    @CUM_MINIMO_RENOVACION decimal(4,2) = NULL,
    @APLICA_NUEVO_INGRESO bit = NULL,
    @APLICA_ANTIGUO_INGRESO bit = NULL,
    @APLICA_EMPLEADO bit = NULL,
    @APLICA_HIJO_EMPLEADO bit = NULL,
    @NIVEL_ACADEMICO_APLICA varchar(20) = NULL,
    @VERSION_REGISTRO varbinary(8)=NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;

        IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
            THROW 51000,N'La empresa de sesion no existe.',1;
        IF @TIPO_ACTUALIZA<>1 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
            THROW 51009,N'El registro cambio o ya no existe. Actualice el listado antes de continuar.',1;

        IF @TIPO_ACTUALIZA IN(1,2)
        BEGIN
            SET @CODIGO_BECA=UPPER(LTRIM(RTRIM(@CODIGO_BECA)));
            SET @NOMBRE_BECA=LTRIM(RTRIM(@NOMBRE_BECA));
            IF NULLIF(@CODIGO_BECA,'') IS NULL OR NULLIF(@NOMBRE_BECA,'') IS NULL
                THROW 51000,N'El codigo y el nombre son obligatorios.',1;
            IF EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA
                AND CODIGO_BECA=@CODIGO_BECA AND (@TIPO_ACTUALIZA=1 OR CORR_BECA<>@ID))
                THROW 51000,N'Ya existe un registro con ese codigo en la empresa.',1;
        END;

        IF @TIPO_ACTUALIZA IN(1,2)
        BEGIN
            IF ISNULL(@CORR_ORIGEN_BECA,0)<=0 THROW 51000,N'Debe seleccionar el origen de beca.',1;
            IF @PORCENTAJE_COBERTURA_REFERENCIAL<0 OR @PORCENTAJE_COBERTURA_REFERENCIAL>100
                THROW 51000,N'La cobertura debe estar entre 0 y 100.',1;
            IF @CUM_MINIMO_RENOVACION<0 OR @CUM_MINIMO_RENOVACION>10
                THROW 51000,N'El CUM debe estar entre 0 y 10.',1;
            IF @ESTADO_BECA IS NULL OR @ESTADO_BECA NOT IN('ACTIVA','INACTIVA','CERRADA','CANCELADA')
                THROW 51000,N'El estado de beca no es valido.',1;
            IF @NIVEL_ACADEMICO_APLICA IS NULL OR @NIVEL_ACADEMICO_APLICA NOT IN('TODOS','PREGRADO','POSGRADO','DOCTORADO')
                THROW 51000,N'El nivel academico no es valido.',1;
            IF ISNULL(@APLICA_NUEVO_INGRESO,0)=0 AND ISNULL(@APLICA_ANTIGUO_INGRESO,0)=0
                AND ISNULL(@APLICA_EMPLEADO,0)=0 AND ISNULL(@APLICA_HIJO_EMPLEADO,0)=0
                THROW 51000,N'Seleccione al menos una poblacion a la que aplica la beca.',1;
            IF @REQUIERE_CONVENIO=0 SET @CORR_CONVENIO=NULL;
            IF @REQUIERE_CONVENIO=1 AND ISNULL(@CORR_CONVENIO,0)<=0
                THROW 51000,N'Debe seleccionar el convenio requerido.',1;
        END;
        DECLARE @ValidarActiva bit=0,@OrigenValidar int=@CORR_ORIGEN_BECA,
            @ConvenioValidar int=@CORR_CONVENIO,@RequiereValidar bit=@REQUIERE_CONVENIO;
        IF @TIPO_ACTUALIZA IN(1,2) AND @ESTADO_BECA='ACTIVA' SET @ValidarActiva=1;
        IF @TIPO_ACTUALIZA=4
            SELECT @ValidarActiva=CASE WHEN ESTADO_BECA='ACTIVA' THEN 0 ELSE 1 END,
                @OrigenValidar=CORR_ORIGEN_BECA,@ConvenioValidar=CORR_CONVENIO,@RequiereValidar=REQUIERE_CONVENIO
            FROM dbo.ACA_BECA_TIPO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@ID;
        IF @ValidarActiva=1
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(UPDLOCK,HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@OrigenValidar AND ACTIVO=1)
                THROW 51000,N'El origen debe estar activo para habilitar la beca.',1;
            IF @RequiereValidar=1 AND NOT EXISTS(
                SELECT 1 FROM dbo.ACA_BECA_CONVENIO C WITH(UPDLOCK,HOLDLOCK)
                JOIN dbo.ACA_BECA_ENTIDAD_FINANCIADORA E WITH(UPDLOCK,HOLDLOCK)
                  ON E.CORR_EMPRESA=C.CORR_EMPRESA AND E.CORR_ENTIDAD_FINANCIADORA=C.CORR_ENTIDAD_FINANCIADORA
                WHERE C.CORR_EMPRESA=@CORR_EMPRESA AND C.CORR_CONVENIO=@ConvenioValidar AND C.ESTADO_CONVENIO='VIGENTE'
                 AND E.ACTIVO=1 AND C.FECHA_INICIO<=CONVERT(date,GETDATE()) AND (C.FECHA_FIN IS NULL OR C.FECHA_FIN>=CONVERT(date,GETDATE())))
                THROW 51000,N'El convenio no esta vigente, su entidad esta inactiva o pertenece a otra empresa.',1;
        END;

        IF @TIPO_ACTUALIZA IN (1,2)
        BEGIN
            IF @CORR_ORIGEN_BECA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ORIGEN_BECA WITH(HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ORIGEN_BECA=@CORR_ORIGEN_BECA) THROW 51000,N'La referencia CORR_ORIGEN_BECA no pertenece a su empresa.',1;
            IF @CORR_CONVENIO IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_CONVENIO WITH(HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CONVENIO=@CORR_CONVENIO) THROW 51000,N'La referencia CORR_CONVENIO no pertenece a su empresa.',1;
        END
        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_BECA),0)+1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_TIPO(CODIGO_BECA,NOMBRE_BECA,CORR_ORIGEN_BECA,CORR_CONVENIO,ARTICULO_REGLAMENTO,PORCENTAJE_COBERTURA_REFERENCIAL,REQUIERE_CONVENIO,REQUIERE_ESTUDIO_SOCIOECONOMICO,REQUIERE_APROBACION_COMITE,REQUIERE_APROBACION_DIRECTORIO,UNIDAD_RESPONSABLE,DESCRIPCION,ESTADO_BECA,CUM_MINIMO_RENOVACION,APLICA_NUEVO_INGRESO,APLICA_ANTIGUO_INGRESO,APLICA_EMPLEADO,APLICA_HIJO_EMPLEADO,NIVEL_ACADEMICO_APLICA,CORR_EMPRESA,CORR_BECA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CODIGO_BECA,@NOMBRE_BECA,@CORR_ORIGEN_BECA,@CORR_CONVENIO,@ARTICULO_REGLAMENTO,@PORCENTAJE_COBERTURA_REFERENCIAL,@REQUIERE_CONVENIO,@REQUIERE_ESTUDIO_SOCIOECONOMICO,@REQUIERE_APROBACION_COMITE,@REQUIERE_APROBACION_DIRECTORIO,@UNIDAD_RESPONSABLE,@DESCRIPCION,@ESTADO_BECA,@CUM_MINIMO_RENOVACION,@APLICA_NUEVO_INGRESO,@APLICA_ANTIGUO_INGRESO,@APLICA_EMPLEADO,@APLICA_HIJO_EMPLEADO,@NIVEL_ACADEMICO_APLICA,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_TIPO SET CODIGO_BECA=@CODIGO_BECA,
                NOMBRE_BECA=@NOMBRE_BECA,
                CORR_ORIGEN_BECA=@CORR_ORIGEN_BECA,
                CORR_CONVENIO=@CORR_CONVENIO,
                ARTICULO_REGLAMENTO=@ARTICULO_REGLAMENTO,
                PORCENTAJE_COBERTURA_REFERENCIAL=@PORCENTAJE_COBERTURA_REFERENCIAL,
                REQUIERE_CONVENIO=@REQUIERE_CONVENIO,
                REQUIERE_ESTUDIO_SOCIOECONOMICO=@REQUIERE_ESTUDIO_SOCIOECONOMICO,
                REQUIERE_APROBACION_COMITE=@REQUIERE_APROBACION_COMITE,
                REQUIERE_APROBACION_DIRECTORIO=@REQUIERE_APROBACION_DIRECTORIO,
