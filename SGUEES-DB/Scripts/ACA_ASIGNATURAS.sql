 ('CUATRIMESTRAL',N'Cuatrimestral',4),('QUINTOMESTRAL',N'Quintomestral',5),('SEMESTRAL',N'Semestral',6),('ANUAL',N'Anual',12)) S(CODIGO,NOMBRE,MESES)
WHERE NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO P WHERE P.CORR_EMPRESA=E.CORR_EMPRESA AND P.CODIGO_PERIODO=S.CODIGO);
