GO
CREATE OR ALTER VIEW dbo.V_ACA_PERIODOS_CURSO AS
SELECT P.CORR_PERIODO_CURSO,P.CORR_EMPRESA,P.CODIGO_PERIODO,P.NOMBRE_PERIODO,P.DURACION_MESES,P.ACTIVO,
 P.USUARIO_CREA,P.FECHA_CREA,P.USUARIO_ACTU,P.FECHA_ACTU,P.VERSION,
 (SELECT COUNT(*) FROM dbo.ACA_ASIGNATURAS A WHERE A.CORR_PERIODO_CURSO=P.CORR_PERIODO_CURSO) CANTIDAD_ASIGNATURAS
FROM dbo.ACA_PERIODOS_CURSO P;
GO
CREATE OR ALTER VIEW dbo.V_ACA_ASIGNATURAS AS
SELECT A.CORR_ASIGNATURA,A.CORR_EMPRESA,A.CORR_CARRERA,C.CORR_FACULTAD,F.NOMBRE_FACULTAD,C.NOMBRE_CARRERA,
 A.CODIGO_ASIGNATURA,A.ALIAS,A.NOMBRE_ASIGNATURA,A.UNIDADES_VALORATIVAS,A.FECHA_APERTURA,A.CORR_PERIODO_CURSO,
 P.NOMBRE_PERIODO,P.DURACION_MESES,A.CORR_TIPO_PRACTICA,T.NOMBRE_TIPO AS NOMBRE_TIPO_PRACTICA,CONVERT(bit,ISNULL(T.HABILITA_COBROS_ADICIONALES,0)) HABILITA_COBROS_ADICIONALES,A.ACTIVO,A.USUARIO_CREA,A.FECHA_CREA,A.USUARIO_ACTU,A.FECHA_ACTU,A.VERSION,
 (SELECT COUNT(*) FROM dbo.ACA_PLANES_ASIGNATURAS R WHERE R.CORR_ASIGNATURA=A.CORR_ASIGNATURA AND R.ACTIVO=1) CANTIDAD_PLANES
FROM dbo.ACA_ASIGNATURAS A JOIN dbo.ACA_CARRERAS C ON C.CORR_CARRERA=A.CORR_CARRERA AND C.CORR_EMPRESA=A.CORR_EMPRESA
JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_PERIODOS_CURSO P ON P.CORR_PERIODO_CURSO=A.CORR_PERIODO_CURSO AND P.CORR_EMPRESA=A.CORR_EMPRESA
LEFT JOIN dbo.ACA_TIPOS_PRACTICA T ON T.CORR_TIPO_PRACTICA=A.CORR_TIPO_PRACTICA AND T.CORR_EMPRESA=A.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_ASIGNATURAS_CARRERAS AS
SELECT C.CORR_EMPRESA,C.CORR_CARRERA,C.CORR_FACULTAD,C.CODIGO_CARRERA,C.NOMBRE_CARRERA,F.NOMBRE_FACULTAD,
 CONVERT(bit,CASE WHEN C.ACTIVO=1 AND F.ACTIVO=1 AND A.ACTIVO=1 THEN 1 ELSE 0 END) ACTIVO
FROM dbo.ACA_CARRERAS C JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=C.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=C.CORR_EMPRESA;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_DATA_ACA_ASIGNATURAS_PLANES @CORR_EMPRESA int,@CORR_ASIGNATURA int AS
BEGIN
 SET NOCOUNT ON;
 SELECT P.CORR_PLAN_ACADEMICO,P.CODIGO_PLAN,P.ANIO_PLAN,M.NOMBRE_MODALIDAD,P.FECHA_VIGENCIA_INICIO,P.FECHA_VIGENCIA_FIN,P.PLAN_VIGENTE,
 CONVERT(bit,ISNULL(R.ACTIVO,0)) ASOCIADO,R.VERSION,
 CONVERT(bit,CASE WHEN EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO H WHERE H.CORR_PLAN_ACADEMICO=P.CORR_PLAN_ACADEMICO) THEN 1 ELSE 0 END) EN_USO
 FROM dbo.ACA_ASIGNATURAS A JOIN dbo.ACA_PLANES_ACADEMICOS P ON P.CORR_CARRERA=A.CORR_CARRERA
 JOIN dbo.ACA_MODALIDADES_ACADEMICAS M ON M.CORR_MODALIDAD=P.CORR_MODALIDAD AND M.CORR_EMPRESA=A.CORR_EMPRESA
 LEFT JOIN dbo.ACA_PLANES_ASIGNATURAS R ON R.CORR_PLAN_ACADEMICO=P.CORR_PLAN_ACADEMICO AND R.CORR_ASIGNATURA=A.CORR_ASIGNATURA
 WHERE A.CORR_EMPRESA=@CORR_EMPRESA AND A.CORR_ASIGNATURA=@CORR_ASIGNATURA
 ORDER BY P.ANIO_PLAN DESC,P.CODIGO_PLAN;
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PERIODOS_CURSO
 @CORR_EMPRESA int,@ID int OUTPUT,@CODIGO_PERIODO varchar(200),@NOMBRE_PERIODO nvarchar(500),@DURACION_MESES int,@ACTIVO bit,
 @VERSION varbinary(8)=NULL,@USUARIO varchar(50),@ESTACION varchar(100)
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRANSACTION;
  IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'Empresa y usuario de sesión requeridos.',1;
  SET @CODIGO_PERIODO=UPPER(LTRIM(RTRIM(@CODIGO_PERIODO)));SET @NOMBRE_PERIODO=LTRIM(RTRIM(@NOMBRE_PERIODO));
  IF @ID<0 OR @CODIGO_PERIODO IS NULL OR LEN(@CODIGO_PERIODO) NOT BETWEEN 1 AND 20 OR @CODIGO_PERIODO COLLATE Latin1_General_100_BIN2 LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2
   OR NULLIF(@NOMBRE_PERIODO,'') IS NULL OR LEN(@NOMBRE_PERIODO)>80 OR @DURACION_MESES IS NULL OR @DURACION_MESES NOT BETWEEN 1 AND 120 OR @ACTIVO IS NULL
   THROW 51000,N'Revise código, nombre y duración: de 1 a 120 meses.',1;
  DECLARE @ANTES nvarchar(max),@DESPUES nvarchar(max);
  IF @ID>0
  BEGIN
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PERIODO_CURSO=@ID) THROW 51000,N'El período no pertenece a la empresa de la sesión.',1;
   IF @VERSION IS NULL OR NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@ID AND VERSION=@VERSION) THROW 51000,N'Otro usuario modificó el período. Actualice la lista.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@ID AND CODIGO_PERIODO=@CODIGO_PERIODO) THROW 51000,N'El código del período no se puede cambiar.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_PERIODO_CURSO=@ID)
     AND EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@ID AND DURACION_MESES<>@DURACION_MESES) THROW 51000,N'No cambie la duración de un período utilizado; cree otro período.',1;
   IF @ACTIVO=0 AND EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_PERIODO_CURSO=@ID AND ACTIVO=1) THROW 51000,N'El período tiene asignaturas activas. Reasígnelas o desactívelas primero.',1;
   SET @ANTES=(SELECT * FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
   UPDATE dbo.ACA_PERIODOS_CURSO SET NOMBRE_PERIODO=@NOMBRE_PERIODO,DURACION_MESES=@DURACION_MESES,ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_PERIODO_CURSO=@ID;
  END ELSE
  BEGIN
   INSERT dbo.ACA_PERIODOS_CURSO(CORR_EMPRESA,CODIGO_PERIODO,NOMBRE_PERIODO,DURACION_MESES,ACTIVO,USUARIO_CREA,ESTACION_CREA) VALUES(@CORR_EMPRESA,@CODIGO_PERIODO,@NOMBRE_PERIODO,@DURACION_MESES,@ACTIVO,@USUARIO,@ESTACION);
   SET @ID=CONVERT(int,SCOPE_IDENTITY());
  END;
  SET @DESPUES=(SELECT * FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  INSERT dbo.ACA_ASIGNATURAS_BITACORA(CORR_EMPRESA,ENTIDAD,ID_REGISTRO,OPERACION,USUARIO,ESTACION,DATOS_ANTES,DATOS_DESPUES) VALUES(@CORR_EMPRESA,'PERIODO_CURSO',@ID,CASE WHEN @ANTES IS NULL THEN 'CREAR' ELSE 'ACTUALIZAR' END,@USUARIO,@ESTACION,@ANTES,@DESPUES);
  COMMIT;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  IF ERROR_NUMBER() IN(2601,2627) THROW 51000,N'Ya existe un período con ese código.',1;
  THROW;
 END CATCH;
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_ASIGNATURAS
 @CORR_EMPRESA int,@ID int OUTPUT,@CORR_CARRERA int,@CODIGO_ASIGNATURA varchar(200),@ALIAS nvarchar(500)=NULL,
 @NOMBRE_ASIGNATURA nvarchar(1000),@UNIDADES_VALORATIVAS decimal(10,4),@FECHA_APERTURA date,@CORR_PERIODO_CURSO int,
 @ACTIVO bit,@VERSION varbinary(8)=NULL,@USUARIO varchar(50),@ESTACION varchar(100),@CORR_TIPO_PRACTICA int=NULL
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRANSACTION;
  IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'Empresa y usuario de sesión requeridos.',1;
  SET @CODIGO_ASIGNATURA=UPPER(LTRIM(RTRIM(@CODIGO_ASIGNATURA)));SET @NOMBRE_ASIGNATURA=LTRIM(RTRIM(@NOMBRE_ASIGNATURA));SET @ALIAS=NULLIF(LTRIM(RTRIM(@ALIAS)),'');
  IF @ID<0 OR @CODIGO_ASIGNATURA IS NULL OR LEN(@CODIGO_ASIGNATURA) NOT BETWEEN 1 AND 30 OR @CODIGO_ASIGNATURA COLLATE Latin1_General_100_BIN2 LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2
   OR NULLIF(@NOMBRE_ASIGNATURA,'') IS NULL OR LEN(@NOMBRE_ASIGNATURA)>250 OR LEN(@ALIAS)>60 OR @FECHA_APERTURA IS NULL OR @UNIDADES_VALORATIVAS IS NULL
   OR @UNIDADES_VALORATIVAS<0 OR @UNIDADES_VALORATIVAS>9999.99 OR @UNIDADES_VALORATIVAS<>ROUND(@UNIDADES_VALORATIVAS,2) OR @ACTIVO IS NULL
    THROW 51000,N'Revise código, nombre, alias, fecha y UV (de 0 a 9999.99, máximo dos decimales; no se permite vacío).',1;
  DECLARE @ANTES nvarchar(max),@DESPUES nvarchar(max),@CARRERA_ANTERIOR int,@PERIODO_ANTERIOR int,@PRACTICA_ANTERIOR int;
  IF @ID>0
  BEGIN
   SELECT @CARRERA_ANTERIOR=CORR_CARRERA,@PERIODO_ANTERIOR=CORR_PERIODO_CURSO,@PRACTICA_ANTERIOR=CORR_TIPO_PRACTICA FROM dbo.ACA_ASIGNATURAS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_ASIGNATURA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
   IF @CARRERA_ANTERIOR IS NULL THROW 51000,N'La asignatura no pertenece a la empresa de la sesión.',1;
   IF @VERSION IS NULL OR NOT EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID AND VERSION=@VERSION) THROW 51000,N'Otro usuario modificó la asignatura. Actualice la lista.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID AND CODIGO_ASIGNATURA=@CODIGO_ASIGNATURA) THROW 51000,N'El código de la asignatura queda reservado y no se puede cambiar.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID) AND @CARRERA_ANTERIOR<>@CORR_CARRERA THROW 51000,N'No cambie la carrera de una asignatura con asociaciones de planes.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ASIGNATURAS R JOIN dbo.ACA_PROSPECTO H ON H.CORR_PLAN_ACADEMICO=R.CORR_PLAN_ACADEMICO WHERE R.CORR_ASIGNATURA=@ID)
     AND EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID AND (UNIDADES_VALORATIVAS<>@UNIDADES_VALORATIVAS OR CORR_PERIODO_CURSO<>@CORR_PERIODO_CURSO OR FECHA_APERTURA<>@FECHA_APERTURA OR ISNULL(CORR_TIPO_PRACTICA,0)<>ISNULL(@CORR_TIPO_PRACTICA,0)))
     THROW 51000,N'El plan está en uso. No cambie UV, duración, apertura o clasificación de práctica de su asignatura.',1;
   SET @ANTES=(SELECT * FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  END;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS WITH(HOLDLOCK) WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_EMPRESA=@CORR_EMPRESA) THROW 51000,N'La carrera no pertenece a la empresa de la sesión.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WITH(HOLDLOCK) WHERE CORR_PERIODO_CURSO=@CORR_PERIODO_CURSO AND CORR_EMPRESA=@CORR_EMPRESA) THROW 51000,N'El período de curso no pertenece a la empresa de la sesión.',1;
  IF (@ACTIVO=1 OR @ID=0 OR @CARRERA_ANTERIOR<>@CORR_CARRERA) AND NOT EXISTS(SELECT 1 FROM dbo.V_ACA_ASIGNATURAS_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA AND ACTIVO=1) THROW 51000,N'La carrera, su facultad y su área deben estar activas.',1;
  IF (@ACTIVO=1 OR @ID=0 OR @PERIODO_ANTERIOR<>@CORR_PERIODO_CURSO) AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_CURSO WHERE CORR_PERIODO_CURSO=@CORR_PERIODO_CURSO AND ACTIVO=1) THROW 51000,N'Seleccione un período de curso activo.',1;
  IF @CORR_TIPO_PRACTICA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WITH(HOLDLOCK) WHERE CORR_TIPO_PRACTICA=@CORR_TIPO_PRACTICA AND CORR_EMPRESA=@CORR_EMPRESA AND (ACTIVO=1 OR (@ACTIVO=0 AND @PRACTICA_ANTERIOR=@CORR_TIPO_PRACTICA))) THROW 51000,N'Seleccione un tipo de práctica activo de la empresa o deje No aplica.',1;
  IF @ID=0
  BEGIN
   INSERT dbo.ACA_ASIGNATURAS(CORR_EMPRESA,CORR_CARRERA,CODIGO_ASIGNATURA,ALIAS,NOMBRE_ASIGNATURA,UNIDADES_VALORATIVAS,FECHA_APERTURA,CORR_PERIODO_CURSO,CORR_TIPO_PRACTICA,ACTIVO,USUARIO_CREA,ESTACION_CREA)
   VALUES(@CORR_EMPRESA,@CORR_CARRERA,@CODIGO_ASIGNATURA,@ALIAS,@NOMBRE_ASIGNATURA,@UNIDADES_VALORATIVAS,@FECHA_APERTURA,@CORR_PERIODO_CURSO,@CORR_TIPO_PRACTICA,@ACTIVO,@USUARIO,@ESTACION);
   SET @ID=CONVERT(int,SCOPE_IDENTITY());
  END ELSE
   UPDATE dbo.ACA_ASIGNATURAS SET CORR_CARRERA=@CORR_CARRERA,ALIAS=@ALIAS,NOMBRE_ASIGNATURA=@NOMBRE_ASIGNATURA,UNIDADES_VALORATIVAS=@UNIDADES_VALORATIVAS,FECHA_APERTURA=@FECHA_APERTURA,CORR_PERIODO_CURSO=@CORR_PERIODO_CURSO,CORR_TIPO_PRACTICA=@CORR_TIPO_PRACTICA,ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_ASIGNATURA=@ID;
  SET @DESPUES=(SELECT * FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  INSERT dbo.ACA_ASIGNATURAS_BITACORA(CORR_EMPRESA,ENTIDAD,ID_REGISTRO,OPERACION,USUARIO,ESTACION,DATOS_ANTES,DATOS_DESPUES) VALUES(@CORR_EMPRESA,'ASIGNATURA',@ID,CASE WHEN @ANTES IS NULL THEN 'CREAR' ELSE 'ACTUALIZAR' END,@USUARIO,@ESTACION,@ANTES,@DESPUES);
  COMMIT;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  IF ERROR_NUMBER() IN(2601,2627) THROW 51000,N'El código de asignatura ya está reservado. No se permite duplicarlo, aunque esté inactivo.',1;
  THROW;
 END CATCH;
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PLANES_ASIGNATURAS
 @CORR_EMPRESA int,@CORR_ASIGNATURA int,@CORR_PLAN_ACADEMICO int,@ACTIVO bit,@VERSION varbinary(8)=NULL,@USUARIO varchar(50),@ESTACION varchar(100)
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRANSACTION;
  IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL OR @ACTIVO IS NULL THROW 51000,N'Empresa, usuario y estado requeridos.',1;
  DECLARE @CARRERA int,@ID int,@ANTES nvarchar(max),@DESPUES nvarchar(max);
  SELECT @CARRERA=CORR_CARRERA FROM dbo.ACA_ASIGNATURAS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_ASIGNATURA=@CORR_ASIGNATURA AND CORR_EMPRESA=@CORR_EMPRESA;
  IF @CARRERA IS NULL THROW 51000,N'La asignatura no pertenece a la empresa de la sesión.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO AND CORR_CARRERA=@CARRERA) THROW 51000,N'El plan debe pertenecer a la misma carrera de la asignatura.',1;
  SELECT @ID=CORR_PLAN_ASIGNATURA FROM dbo.ACA_PLANES_ASIGNATURAS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_ASIGNATURA=@CORR_ASIGNATURA AND CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO;
  IF (@ID IS NULL AND @VERSION IS NOT NULL) OR (@ID IS NOT NULL AND (@VERSION IS NULL OR NOT EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ASIGNATURAS WHERE CORR_PLAN_ASIGNATURA=@ID AND VERSION=@VERSION))) THROW 51000,N'Otro usuario modificó la asociación. Actualice los planes.',1;
  IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO WITH(HOLDLOCK) WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO) THROW 51000,N'El plan está en uso. Conserve su estructura histórica; utilice una nueva versión del plan.',1;
  IF @ACTIVO=1 AND (NOT EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WHERE CORR_ASIGNATURA=@CORR_ASIGNATURA AND ACTIVO=1)
     OR NOT EXISTS(SELECT 1 FROM dbo.V_ACA_ASIGNATURAS_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CARRERA AND ACTIVO=1)
     OR NOT EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS P JOIN dbo.ACA_MODALIDADES_ACADEMICAS M ON M.CORR_MODALIDAD=P.CORR_MODALIDAD AND M.CORR_EMPRESA=@CORR_EMPRESA WHERE P.CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO AND P.PLAN_VIGENTE=1 AND M.ACTIVO=1))
   THROW 51000,N'Para asociar, la asignatura y la carrera deben estar activas, el plan vigente y su modalidad activa.',1;
  IF @ID IS NULL
  BEGIN
   IF @ACTIVO=0 THROW 51000,N'La asignatura no está asociada a este plan.',1;
   INSERT dbo.ACA_PLANES_ASIGNATURAS(CORR_ASIGNATURA,CORR_PLAN_ACADEMICO,ACTIVO,USUARIO_CREA,ESTACION_CREA) VALUES(@CORR_ASIGNATURA,@CORR_PLAN_ACADEMICO,1,@USUARIO,@ESTACION);
   SET @ID=CONVERT(int,SCOPE_IDENTITY());
  END ELSE
  BEGIN
   SET @ANTES=(SELECT * FROM dbo.ACA_PLANES_ASIGNATURAS WHERE CORR_PLAN_ASIGNATURA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
   UPDATE dbo.ACA_PLANES_ASIGNATURAS SET ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_PLAN_ASIGNATURA=@ID;
  END;
  -- También invalida el editor de la asignatura si cambian sus asociaciones.
  UPDATE dbo.ACA_ASIGNATURAS SET USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_ASIGNATURA=@CORR_ASIGNATURA;
  SET @DESPUES=(SELECT * FROM dbo.ACA_PLANES_ASIGNATURAS WHERE CORR_PLAN_ASIGNATURA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  INSERT dbo.ACA_ASIGNATURAS_BITACORA(CORR_EMPRESA,ENTIDAD,ID_REGISTRO,OPERACION,USUARIO,ESTACION,DATOS_ANTES,DATOS_DESPUES) VALUES(@CORR_EMPRESA,'PLAN_ASIGNATURA',@ID,CASE WHEN @ACTIVO=1 THEN 'ASOCIAR' ELSE 'RETIRAR' END,@USUARIO,@ESTACION,@ANTES,@DESPUES);
  COMMIT;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  THROW;
 END CATCH;
END;
GO
