CREATE TABLE dbo.ACA_PERIODOS_CURSO(
 CORR_PERIODO_CURSO int IDENTITY PRIMARY KEY, CORR_EMPRESA int NOT NULL REFERENCES dbo.GEN_EMPRESA(CORR_EMPRESA),
 CODIGO_PERIODO varchar(20) NOT NULL, NOMBRE_PERIODO nvarchar(80) NOT NULL, DURACION_MESES int NOT NULL,
 ACTIVO bit NOT NULL DEFAULT 1, USUARIO_CREA varchar(50) NOT NULL, ESTACION_CREA varchar(100) NOT NULL, FECHA_CREA datetime2 NOT NULL DEFAULT SYSDATETIME(),
 USUARIO_ACTU varchar(50) NULL, ESTACION_ACTU varchar(100) NULL, FECHA_ACTU datetime2 NULL, VERSION rowversion,
 CONSTRAINT UQ_ACA_PERIODO_CURSO UNIQUE(CORR_EMPRESA,CODIGO_PERIODO),
 CONSTRAINT CK_ACA_PERIODO_MESES CHECK(DURACION_MESES BETWEEN 1 AND 120),
 CONSTRAINT CK_ACA_PERIODO_CODIGO CHECK(LEN(CODIGO_PERIODO)>0 AND CODIGO_PERIODO COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2),
 CONSTRAINT CK_ACA_PERIODO_NOMBRE CHECK(LEN(LTRIM(RTRIM(NOMBRE_PERIODO)))>0));
IF OBJECT_ID('dbo.ACA_TIPOS_PRACTICA','U') IS NULL
CREATE TABLE dbo.ACA_TIPOS_PRACTICA(
 CORR_TIPO_PRACTICA int IDENTITY PRIMARY KEY,CORR_EMPRESA int NOT NULL REFERENCES dbo.GEN_EMPRESA(CORR_EMPRESA),
 CODIGO_TIPO varchar(30) NOT NULL,NOMBRE_TIPO nvarchar(80) NOT NULL,HABILITA_COBROS_ADICIONALES bit NOT NULL DEFAULT 1,ACTIVO bit NOT NULL DEFAULT 1,
 USUARIO_CREA varchar(50) NOT NULL,ESTACION_CREA varchar(100) NOT NULL,FECHA_CREA datetime2 NOT NULL DEFAULT SYSDATETIME(),
 USUARIO_ACTU varchar(50) NULL,ESTACION_ACTU varchar(100) NULL,FECHA_ACTU datetime2 NULL,VERSION rowversion,
 CONSTRAINT UQ_ACA_TIPO_PRACTICA UNIQUE(CORR_EMPRESA,CODIGO_TIPO),
 CONSTRAINT CK_ACA_TIPO_PRACTICA_CODIGO CHECK(LEN(CODIGO_TIPO)>0 AND CODIGO_TIPO COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2),
 CONSTRAINT CK_ACA_TIPO_PRACTICA_NOMBRE CHECK(LEN(LTRIM(RTRIM(NOMBRE_TIPO)))>0));
IF OBJECT_ID('dbo.ACA_ASIGNATURAS','U') IS NULL
CREATE TABLE dbo.ACA_ASIGNATURAS(
 CORR_ASIGNATURA int IDENTITY PRIMARY KEY, CORR_EMPRESA int NOT NULL REFERENCES dbo.GEN_EMPRESA(CORR_EMPRESA),
 CORR_CARRERA int NOT NULL REFERENCES dbo.ACA_CARRERAS(CORR_CARRERA),
 CODIGO_ASIGNATURA varchar(30) NOT NULL, ALIAS nvarchar(60) NULL, NOMBRE_ASIGNATURA nvarchar(250) NOT NULL,
 UNIDADES_VALORATIVAS decimal(6,2) NOT NULL, FECHA_APERTURA date NOT NULL,
 CORR_PERIODO_CURSO int NOT NULL REFERENCES dbo.ACA_PERIODOS_CURSO(CORR_PERIODO_CURSO), ACTIVO bit NOT NULL DEFAULT 1,
 USUARIO_CREA varchar(50) NOT NULL, ESTACION_CREA varchar(100) NOT NULL, FECHA_CREA datetime2 NOT NULL DEFAULT SYSDATETIME(),
 USUARIO_ACTU varchar(50) NULL, ESTACION_ACTU varchar(100) NULL, FECHA_ACTU datetime2 NULL, VERSION rowversion,
 CONSTRAINT UQ_ACA_ASIGNATURA_CODIGO UNIQUE(CODIGO_ASIGNATURA),
 CONSTRAINT CK_ACA_ASIGNATURA_CODIGO CHECK(LEN(CODIGO_ASIGNATURA)>0 AND CODIGO_ASIGNATURA COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2),
 CONSTRAINT CK_ACA_ASIGNATURA_NOMBRE CHECK(LEN(LTRIM(RTRIM(NOMBRE_ASIGNATURA)))>0),
 CONSTRAINT CK_ACA_ASIGNATURA_UV CHECK(UNIDADES_VALORATIVAS>=0));
-- Actualiza también las bases que conservan la restricción anterior UV > 0.
IF EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.ACA_ASIGNATURAS') AND name='CK_ACA_ASIGNATURA_UV')
 ALTER TABLE dbo.ACA_ASIGNATURAS DROP CONSTRAINT CK_ACA_ASIGNATURA_UV;
