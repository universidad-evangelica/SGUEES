 OPERACION varchar(20) NOT NULL,USUARIO varchar(50) NOT NULL,ESTACION varchar(100) NOT NULL,FECHA datetime2 NOT NULL DEFAULT SYSDATETIME(),
 DATOS_ANTES nvarchar(max) NULL,DATOS_DESPUES nvarchar(max) NOT NULL);
