SET XACT_ABORT ON;
BEGIN TRANSACTION;
DECLARE @ORDEN_PERIODOS int=(SELECT ORDEN_OPCION FROM dbo.SEG_CONFIG_OPCION WHERE CODIGO_SISTEMA='ACADEMICS' AND CODIGO_MENU='GENERAL' AND CODIGO_OPCION='ACA_PERIODOS_CURSO');
