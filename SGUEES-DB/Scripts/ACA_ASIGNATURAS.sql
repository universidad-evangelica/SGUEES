IF COL_LENGTH('dbo.ACA_ASIGNATURAS','CORR_TIPO_PRACTICA') IS NULL
 ALTER TABLE dbo.ACA_ASIGNATURAS ADD CORR_TIPO_PRACTICA int NULL CONSTRAINT FK_ACA_ASIGNATURAS_PRACTICA REFERENCES dbo.ACA_TIPOS_PRACTICA(CORR_TIPO_PRACTICA);
IF OBJECT_ID('dbo.ACA_PLANES_ASIGNATURAS','U') IS NULL
CREATE TABLE dbo.ACA_PLANES_ASIGNATURAS(
 CORR_PLAN_ASIGNATURA int IDENTITY PRIMARY KEY, CORR_ASIGNATURA int NOT NULL REFERENCES dbo.ACA_ASIGNATURAS(CORR_ASIGNATURA),
 CORR_PLAN_ACADEMICO int NOT NULL REFERENCES dbo.ACA_PLANES_ACADEMICOS(CORR_PLAN_ACADEMICO), ACTIVO bit NOT NULL DEFAULT 1,
 USUARIO_CREA varchar(50) NOT NULL, ESTACION_CREA varchar(100) NOT NULL, FECHA_CREA datetime2 NOT NULL DEFAULT SYSDATETIME(),
 USUARIO_ACTU varchar(50) NULL, ESTACION_ACTU varchar(100) NULL, FECHA_ACTU datetime2 NULL, VERSION rowversion,
 CONSTRAINT UQ_ACA_PLAN_ASIGNATURA UNIQUE(CORR_ASIGNATURA,CORR_PLAN_ACADEMICO));
IF OBJECT_ID('dbo.ACA_ASIGNATURAS_BITACORA','U') IS NULL
CREATE TABLE dbo.ACA_ASIGNATURAS_BITACORA(
