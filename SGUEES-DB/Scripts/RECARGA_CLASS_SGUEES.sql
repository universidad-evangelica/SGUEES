/*
  Recarga datos CLASS -> SGUEES (uso repetible).

  Que hace:
    1. Despliega SP/funciones de reportes y migracion (idempotente)
    2. LIMPIAR + MIGRAR CON_CATALOGO_SALDO_HIS desde CLASS
    3. Opcional: LIMPIAR + MIGRAR + APLICAR partidas del mes

  Requisitos:
    - Linked server CLASS_UEES activo
    - Ejecutar desde esta carpeta (Scripts) para que funcionen los :r

  Uso habitual (solo saldos historicos, ~4 min):
    cd "c:\Desarrollo GIT\SGUEES\SGUEES-DB\Scripts"
    sqlcmd -S 192.168.0.250 -U erp -d SGUEES -v ANIO=2026 -v MES_CORTE=4 -v RECARGAR_PARTIDAS=0 -i RECARGA_CLASS_SGUEES.sql

  Uso completo (HIS + partidas mayo, mas lento):
    sqlcmd -S 192.168.0.250 -U erp -d SGUEES -v ANIO=2026 -v MES_CORTE=4 -v MES_PARTIDAS=5 -v RECARGAR_PARTIDAS=1 -i RECARGA_CLASS_SGUEES.sql

  Reportes: FECHA_FINAL = ultimo dia del mes migrado (ej. 2026-05-31).
*/
SET NOCOUNT ON;

DECLARE @ANIO INT = TRY_CONVERT(INT, '$(ANIO)');
DECLARE @MES_CORTE INT = TRY_CONVERT(INT, '$(MES_CORTE)');
DECLARE @MES_PARTIDAS INT = TRY_CONVERT(INT, '$(MES_PARTIDAS)');
DECLARE @RECARGAR_PARTIDAS INT = TRY_CONVERT(INT, '$(RECARGAR_PARTIDAS)');
DECLARE @E NUMERIC(38, 0);
DECLARE @M NVARCHAR(4000);
DECLARE @F INT;

IF @ANIO IS NULL SET @ANIO = 2026;
IF @MES_CORTE IS NULL SET @MES_CORTE = 4;
IF @MES_PARTIDAS IS NULL SET @MES_PARTIDAS = 5;
IF @RECARGAR_PARTIDAS IS NULL SET @RECARGAR_PARTIDAS = 0;

PRINT '=== RECARGA CLASS -> SGUEES ===';
PRINT 'Anio: ' + CAST(@ANIO AS VARCHAR(4))
    + ' | HIS hasta mes: ' + CAST(@MES_CORTE AS VARCHAR(2))
    + ' | Partidas mes: ' + CASE WHEN @RECARGAR_PARTIDAS = 1 THEN CAST(@MES_PARTIDAS AS VARCHAR(2)) ELSE 'NO' END;
GO

PRINT '=== 1. Objetos SQL (parametros, SP balance, SP HIS) ===';
GO
