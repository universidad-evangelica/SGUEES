GO
:r IMPORT_CLASS_CENTRO_COSTO_REL.sql
GO
:r MIGRATE_CLASS_PARTIDAS_MES.sql
GO

DECLARE @ANIO INT = TRY_CONVERT(INT, '$(ANIO)');
DECLARE @MES_CORTE INT = TRY_CONVERT(INT, '$(MES_CORTE)');
DECLARE @MES_PARTIDAS INT = TRY_CONVERT(INT, '$(MES_PARTIDAS)');
DECLARE @RECARGAR_PARTIDAS INT = TRY_CONVERT(INT, '$(RECARGAR_PARTIDAS)');
DECLARE @E NUMERIC(38, 0);
DECLARE @M NVARCHAR(4000);
DECLARE @F INT;

IF @ANIO IS NULL SET @ANIO = 2026;
IF @MES_CORTE IS NULL SET @MES_CORTE = 4;
IF @MES_PARTIDAS IS NULL SET @MES_PARTIDAS = 5;
IF @RECARGAR_PARTIDAS IS NULL SET @RECARGAR_PARTIDAS = 0;

PRINT '=== 2. Limpiar resultado periodo en HIS (3106/3108) ===';
DELETE FROM CON_CATALOGO_SALDO_HIS
WHERE CORR_EMPRESA = 1
  AND ANIO_PERIODO = @ANIO
  AND (
        LEFT(CUENTA_CONTABLE, 4) IN ('3106', '3108')
     OR CUENTA_CONTABLE IN ('3106', '3108', '310601', '310801')
  );
PRINT CAST(@@ROWCOUNT AS VARCHAR(10)) + ' filas eliminadas (patrimonio periodo en HIS).';

PRINT '=== 3. CON_CATALOGO_SALDO_HIS: LIMPIAR + MIGRAR ===';
EXEC dbo.PRAL_MIGR_CLASS_SALDO_HISTORICO
    @ANIO = @ANIO, @MES_CORTE = @MES_CORTE, @CIERRE = 0, @MODO = 'LIMPIAR',
    @SYS_NUMERO_ERROR = @E OUTPUT, @SYS_MENSAJE_ERROR = @M OUTPUT;

EXEC dbo.PRAL_MIGR_CLASS_SALDO_HISTORICO
    @ANIO = @ANIO, @MES_CORTE = @MES_CORTE, @CIERRE = 0, @MODO = 'MIGRAR',
    @SYS_NUMERO_ERROR = @E OUTPUT, @SYS_MENSAJE_ERROR = @M OUTPUT, @SYS_FILAS_AFECTADAS = @F OUTPUT;

IF ISNULL(@E, 0) <> 0
BEGIN
    RAISERROR(N'Error HIS: %s', 16, 1, @M);
    RETURN;
END;
PRINT ISNULL(@M, N'HIS OK') + N' (' + CAST(@F AS VARCHAR(10)) + N' cuentas)';

IF @RECARGAR_PARTIDAS = 1
BEGIN
    PRINT '=== 4. Partidas mes ' + CAST(@MES_PARTIDAS AS VARCHAR(2)) + ': LIMPIAR + MIGRAR + APLICAR ===';

    IF OBJECT_ID(N'dbo.PRAL_MIGR_CLASS_PARTIDAS_MES', N'P') IS NULL
    BEGIN
        RAISERROR(N'Falta PRAL_MIGR_CLASS_PARTIDAS_MES. Ejecute MIGRATE_CLASS_PARTIDAS_MES.sql una vez.', 16, 1);
        RETURN;
    END;

    EXEC dbo.PRAL_MIGR_CLASS_PARTIDAS_MES
        @ANIO = @ANIO, @MES = @MES_PARTIDAS, @MODO = 'LIMPIAR',
        @SYS_NUMERO_ERROR = @E OUTPUT, @SYS_MENSAJE_ERROR = @M OUTPUT;

    EXEC dbo.PRAL_MIGR_CLASS_PARTIDAS_MES
        @ANIO = @ANIO, @MES = @MES_PARTIDAS, @MODO = 'MIGRAR',
        @SYS_NUMERO_ERROR = @E OUTPUT, @SYS_MENSAJE_ERROR = @M OUTPUT, @SYS_FILAS_AFECTADAS = @F OUTPUT;

    IF ISNULL(@E, 0) <> 0
    BEGIN
        RAISERROR(N'Error MIGRAR partidas: %s', 16, 1, @M);
        RETURN;
    END;

    EXEC dbo.PRAL_MIGR_CLASS_PARTIDAS_MES
        @ANIO = @ANIO, @MES = @MES_PARTIDAS, @MODO = 'APLICAR',
        @SYS_NUMERO_ERROR = @E OUTPUT, @SYS_MENSAJE_ERROR = @M OUTPUT;

    IF ISNULL(@E, 0) <> 0
    BEGIN
        RAISERROR(N'Error APLICAR partidas: %s', 16, 1, @M);
        RETURN;
    END;
    PRINT ISNULL(@M, N'Partidas aplicadas.');
END
ELSE
    PRINT '=== 4. Partidas: omitido (RECARGAR_PARTIDAS=0) ===';

PRINT '=== 5. Resumen patrimonio HIS (apertura mes ' + CAST(@MES_CORTE + 1 AS VARCHAR(2)) + ') ===';
SELECT CUENTA_CONTABLE, SALDO_INICIAL5
FROM CON_CATALOGO_SALDO_HIS
WHERE CORR_EMPRESA = 1 AND ANIO_PERIODO = @ANIO AND CUENTA_CONTABLE LIKE '310%'
ORDER BY 1;

DECLARE @FECHA DATE = EOMONTH(DATEFROMPARTS(@ANIO, @MES_CORTE + 1, 1));
PRINT 'Listo. Use FECHA_FINAL = ' + CONVERT(VARCHAR(10), @FECHA, 23) + ' en Balance y Estado de Resultados.';
GO
