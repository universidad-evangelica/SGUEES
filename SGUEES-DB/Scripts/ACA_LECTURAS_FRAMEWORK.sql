CREATE OR ALTER PROCEDURE dbo.PRAL_DATA_ACA_CONFIG_CICLOS
    @empresa int,
    @id int = 0
AS
BEGIN
    SET NOCOUNT ON;
SELECT H.CORR_CICLO_ACADEMICO,A.NOMBRE_AREA,H.ANIO,H.NUMERO_PERIODO,H.ESTADO,G.NOMBRE_SEDE,F.ACTIVO AS PARTICIPA_FACULTAD,S.ACTIVO AS PARTICIPA_SEDE,
                  (SELECT COUNT(*) FROM dbo.V_ACA_CICLOS_RESUMEN R WHERE R.CORR_CICLO_ACADEMICO=F.CORR_CICLO_ACADEMICO AND R.CORR_SEDE=F.CORR_SEDE AND R.CORR_FACULTAD=F.CORR_FACULTAD AND R.SELECCIONADA=1) AS CARRERAS_INCLUIDAS,
                  (SELECT COUNT(*) FROM dbo.V_ACA_CICLOS_RESUMEN R WHERE R.CORR_CICLO_ACADEMICO=F.CORR_CICLO_ACADEMICO AND R.CORR_SEDE=F.CORR_SEDE AND R.CORR_FACULTAD=F.CORR_FACULTAD AND R.SELECCIONADA=1 AND R.DIAGNOSTICO<>N'Lista para apertura') AS PENDIENTES
                  FROM dbo.ACA_CICLOS_FACULTADES_SEDES F JOIN dbo.ACA_CICLOS_ACADEMICOS H ON H.CORR_CICLO_ACADEMICO=F.CORR_CICLO_ACADEMICO JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=H.CORR_AREA_ACADEMICA
                  JOIN dbo.GEN_SEDES G ON G.CORR_SEDE=F.CORR_SEDE JOIN dbo.ACA_CICLOS_SEDES S ON S.CORR_CICLO_ACADEMICO=F.CORR_CICLO_ACADEMICO AND S.CORR_SEDE=F.CORR_SEDE
                  WHERE H.CORR_EMPRESA=@empresa AND F.CORR_FACULTAD=@id ORDER BY H.ANIO DESC,H.NUMERO_PERIODO DESC,G.NOMBRE_SEDE;
END;
GO
