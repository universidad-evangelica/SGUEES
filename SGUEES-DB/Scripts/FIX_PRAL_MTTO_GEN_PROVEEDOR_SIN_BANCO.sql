/*
  Fix: PRAL_MTTO_GEN_PROVEEDOR en BD aún exige @CUENTA_BANCARIA / @CORR_BANCO,
  pero el mtto de proveedor ya no maneja bancos (van en GEN_PERSONA_BANCO).

  También dropea columnas legacy de GEN_PROVEEDOR si siguen existiendo.

  Uso:
    sqlcmd -S <srv> -d SGUEES -U <user> -P <pwd> -f 65001 -i FIX_PRAL_MTTO_GEN_PROVEEDOR_SIN_BANCO.sql
*/
SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

PRINT N'=== 1) PRAL_MTTO_GEN_PROVEEDOR sin banco/cuenta ===';
GO

CREATE OR ALTER PROCEDURE [dbo].[PRAL_MTTO_GEN_PROVEEDOR]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@CORR_PROVEEDOR INT OUTPUT,
	@CORR_PERSONA BIGINT,
	@CODIGO_PROVEEDOR VARCHAR(20),
	@NOMBRE_COMERCIAL VARCHAR(150),
	@CORR_FORMA_PAGO INT,
	@ESTADO_PROVEEDOR VARCHAR(1),
	@ESTADO_PROVEEDOR_WEB VARCHAR(1),
	@CORR_CONDICION_PAGO INT,
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		DECLARE
			@TIPO_PERSONERIA VARCHAR(1) = N'',
			@NOMBRE_PROVEEDOR VARCHAR(150) = N'',
			@PRIMER_NOMBRE VARCHAR(50) = N'',
			@SEGUNDO_NOMBRE VARCHAR(50) = N'',
			@PRIMER_APELLIDO VARCHAR(50) = N'',
			@SEGUNDO_APELLIDO VARCHAR(50) = N'',
			@CORR_ACTIVIDAD VARCHAR(10) = N'';

		IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.GEN_PERSONA_PROVEEDOR
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PROVEEDOR = @CORR_PROVEEDOR;

			DELETE FROM dbo.GEN_PROVEEDOR
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PROVEEDOR = @CORR_PROVEEDOR;

			SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
			GOTO FINA;
		END;

		IF @CORR_PERSONA IS NULL OR @CORR_PERSONA <= 0
		BEGIN
			SET @SYS_NUMERO_ERROR = 4101;
			SET @SYS_MENSAJE_ERROR = N'Debe seleccionar una persona para el proveedor.';
			GOTO FINA;
		END;

		IF NOT EXISTS (SELECT 1 FROM dbo.GEN_PERSONA WHERE CORR_PERSONA = @CORR_PERSONA)
		BEGIN
			SET @SYS_NUMERO_ERROR = 4102;
			SET @SYS_MENSAJE_ERROR = N'La persona indicada no existe.';
			GOTO FINA;
		END;

		IF EXISTS (SELECT 1 FROM dbo.GEN_PERSONA_NATURAL WHERE CORR_PERSONA = @CORR_PERSONA)
		BEGIN
			SET @TIPO_PERSONERIA = N'N';
			SELECT
				@NOMBRE_PROVEEDOR = LEFT(ISNULL(NULLIF(LTRIM(RTRIM(NOMBRE_COMPLETO)), N''), N''), 150),
				@PRIMER_NOMBRE = ISNULL(PRIMER_NOMBRE, N''),
				@SEGUNDO_NOMBRE = ISNULL(SEGUNDO_NOMBRE, N''),
				@PRIMER_APELLIDO = ISNULL(PRIMER_APELLIDO, N''),
				@SEGUNDO_APELLIDO = ISNULL(SEGUNDO_APELLIDO, N''),
				@CORR_ACTIVIDAD = ISNULL(CONVERT(VARCHAR(10), CORR_ACTIVIDAD_ECONOMICA), N'')
			FROM dbo.GEN_PERSONA_NATURAL
			WHERE CORR_PERSONA = @CORR_PERSONA;
		END
		ELSE IF EXISTS (SELECT 1 FROM dbo.GEN_PERSONA_JURIDICA WHERE CORR_PERSONA = @CORR_PERSONA)
		BEGIN
			SET @TIPO_PERSONERIA = N'J';
			SELECT
				@NOMBRE_PROVEEDOR = LEFT(ISNULL(NULLIF(LTRIM(RTRIM(RAZON_SOCIAL)), N''), ISNULL(NOMBRE_EMPRESA, N'')), 150),
				@CORR_ACTIVIDAD = ISNULL(CONVERT(VARCHAR(10), CORR_ACTIVIDAD_ECONOMICA), N'')
			FROM dbo.GEN_PERSONA_JURIDICA
			WHERE CORR_PERSONA = @CORR_PERSONA;
		END
		ELSE
		BEGIN
			SET @SYS_NUMERO_ERROR = 4103;
			SET @SYS_MENSAJE_ERROR = N'La persona debe ser natural o jurídica.';
			GOTO FINA;
		END;

		IF NULLIF(LTRIM(RTRIM(ISNULL(@NOMBRE_COMERCIAL, N''))), N'') IS NULL
			SET @NOMBRE_COMERCIAL = @NOMBRE_PROVEEDOR;
		ELSE
			SET @NOMBRE_COMERCIAL = LEFT(LTRIM(RTRIM(@NOMBRE_COMERCIAL)), 150);

		IF ISNULL(@ESTADO_PROVEEDOR, N'') = N'' SET @ESTADO_PROVEEDOR = N'A';
		IF ISNULL(@ESTADO_PROVEEDOR_WEB, N'') = N'' SET @ESTADO_PROVEEDOR_WEB = N'D';
		IF @CODIGO_PROVEEDOR IS NULL SET @CODIGO_PROVEEDOR = N'';

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			IF EXISTS (
				SELECT 1 FROM dbo.GEN_PERSONA_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA
			)
			BEGIN
				SET @SYS_NUMERO_ERROR = 4104;
				SET @SYS_MENSAJE_ERROR = N'La persona ya está registrada como proveedor en esta empresa.';
				GOTO FINA;
			END;

			SELECT @CORR_PROVEEDOR = ISNULL(MAX(CORR_PROVEEDOR), 0) + 1
			FROM dbo.GEN_PROVEEDOR WITH (UPDLOCK, HOLDLOCK)
			WHERE CORR_EMPRESA = @CORR_EMPRESA;

			INSERT INTO dbo.GEN_PROVEEDOR
			(
				CORR_EMPRESA, CORR_PROVEEDOR, CODIGO_PROVEEDOR, TIPO_PERSONERIA, NOMBRE_PROVEEDOR,
				PRIMER_NOMBRE, SEGUNDO_NOMBRE, PRIMER_APELLIDO, SEGUNDO_APELLIDO, NOMBRE_COMERCIAL,
				CORR_TIPO_DIP, NUMERO_DIP, NUMERO_NRC, NUMERO_NIT, CORR_ACTIVIDAD_ECONOMICA,
				DIRECCION_PROVEEDOR, CORR_PAIS, CORR_DEPTO, CORR_MUNICIPIO, NOMBRE_CONTACTO,
				TELEFONO_FIJO, TELEFONO_MOVIL, CORREO_ELECTRONICO_1, CORREO_ELECTRONICO_2,
				CORR_FORMA_PAGO, ESTADO_PROVEEDOR, ESTADO_PROVEEDOR_WEB,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA, USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU, CORR_CONDICION_PAGO
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_PROVEEDOR, @CODIGO_PROVEEDOR, @TIPO_PERSONERIA, @NOMBRE_PROVEEDOR,
				@PRIMER_NOMBRE, @SEGUNDO_NOMBRE, @PRIMER_APELLIDO, @SEGUNDO_APELLIDO, @NOMBRE_COMERCIAL,
				0, N'', N'', N'', @CORR_ACTIVIDAD,
				N'', 0, 0, 0, N'',
				N'', N'', N'', N'',
				ISNULL(@CORR_FORMA_PAGO, 0), @ESTADO_PROVEEDOR, @ESTADO_PROVEEDOR_WEB,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA, @USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU, @CORR_CONDICION_PAGO
			);

			INSERT INTO dbo.GEN_PERSONA_PROVEEDOR
			(
				CORR_EMPRESA, CORR_PERSONA, CORR_PROVEEDOR,
				USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_PERSONA, @CORR_PROVEEDOR,
				@USUARIO_CREA, @ESTACION_CREA, @FECHA_CREA, @USUARIO_ACTU, @ESTACION_ACTU, @FECHA_ACTU
			);
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.GEN_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			)
			BEGIN
				SET @SYS_NUMERO_ERROR = 4105;
				SET @SYS_MENSAJE_ERROR = N'El proveedor no existe.';
				GOTO FINA;
			END;

			IF EXISTS (
				SELECT 1 FROM dbo.GEN_PERSONA_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PERSONA = @CORR_PERSONA
				  AND CORR_PROVEEDOR <> @CORR_PROVEEDOR
			)
			BEGIN
				SET @SYS_NUMERO_ERROR = 4104;
				SET @SYS_MENSAJE_ERROR = N'La persona ya está vinculada a otro proveedor.';
				GOTO FINA;
			END;

			UPDATE dbo.GEN_PROVEEDOR SET
				CODIGO_PROVEEDOR = @CODIGO_PROVEEDOR,
				TIPO_PERSONERIA = @TIPO_PERSONERIA,
				NOMBRE_PROVEEDOR = @NOMBRE_PROVEEDOR,
				PRIMER_NOMBRE = @PRIMER_NOMBRE,
				SEGUNDO_NOMBRE = @SEGUNDO_NOMBRE,
				PRIMER_APELLIDO = @PRIMER_APELLIDO,
				SEGUNDO_APELLIDO = @SEGUNDO_APELLIDO,
				NOMBRE_COMERCIAL = @NOMBRE_COMERCIAL,
				CORR_ACTIVIDAD_ECONOMICA = @CORR_ACTIVIDAD,
				CORR_FORMA_PAGO = ISNULL(@CORR_FORMA_PAGO, 0),
				ESTADO_PROVEEDOR = @ESTADO_PROVEEDOR,
				ESTADO_PROVEEDOR_WEB = @ESTADO_PROVEEDOR_WEB,
				CORR_CONDICION_PAGO = @CORR_CONDICION_PAGO,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR;

			IF EXISTS (
				SELECT 1 FROM dbo.GEN_PERSONA_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			)
			BEGIN
				UPDATE dbo.GEN_PERSONA_PROVEEDOR SET
					CORR_PERSONA = @CORR_PERSONA,
					USUARIO_ACTU = @USUARIO_ACTU,
					ESTACION_ACTU = @ESTACION_ACTU,
					FECHA_ACTU = @FECHA_ACTU
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR;
			END
			ELSE
			BEGIN
				INSERT INTO dbo.GEN_PERSONA_PROVEEDOR
				(
					CORR_EMPRESA, CORR_PERSONA, CORR_PROVEEDOR,
					USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
				)
				VALUES
				(
					@CORR_EMPRESA, @CORR_PERSONA, @CORR_PROVEEDOR,
					@USUARIO_ACTU, @ESTACION_ACTU, @FECHA_ACTU, @USUARIO_ACTU, @ESTACION_ACTU, @FECHA_ACTU
				);
			END;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		DECLARE
			@CORR_BITACORA INT,
			@SEVERITY_ERROR INT,
			@ESTADO_ERROR INT,
			@ORIGEN_ERROR NVARCHAR(126),
			@LINEA_ERROR INT,
			@SYS_FECHA DATETIME;

		SELECT
			@CORR_BITACORA = 0,
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SEVERITY_ERROR = ERROR_SEVERITY(),
			@ESTADO_ERROR = ERROR_STATE(),
			@ORIGEN_ERROR = ERROR_PROCEDURE(),
			@LINEA_ERROR = ERROR_LINE(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(),
			@SYS_FECHA = GETDATE();

		EXEC dbo.PRAL_MTTO_ADMIN_BITACORA_SISTEMA
			1, @CORR_BITACORA OUTPUT, 'PM',
			@SYS_NUMERO_ERROR, @SEVERITY_ERROR, @ESTADO_ERROR,
			@ORIGEN_ERROR, @LINEA_ERROR, @SYS_MENSAJE_ERROR,
			@SYS_LOGIN_USUARIO, @SYS_FECHA, @SYS_ESTACION;
	END CATCH;
FINA:
END
GO

PRINT N'=== 2) Drop columnas legacy banco en GEN_PROVEEDOR ===';
GO

IF COL_LENGTH(N'dbo.GEN_PROVEEDOR', N'CUENTA_BANCARIA') IS NOT NULL
BEGIN
	DECLARE @dfCuenta SYSNAME;
	SELECT @dfCuenta = dc.name
	FROM sys.default_constraints dc
	INNER JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id
	WHERE dc.parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR')
	  AND c.name = N'CUENTA_BANCARIA';
	IF @dfCuenta IS NOT NULL
		EXEC(N'ALTER TABLE dbo.GEN_PROVEEDOR DROP CONSTRAINT [' + @dfCuenta + N']');
	ALTER TABLE dbo.GEN_PROVEEDOR DROP COLUMN [CUENTA_BANCARIA];
	PRINT N'Columna CUENTA_BANCARIA eliminada.';
END
ELSE
	PRINT N'CUENTA_BANCARIA ya no existe.';
GO

IF COL_LENGTH(N'dbo.GEN_PROVEEDOR', N'CORR_BANCO') IS NOT NULL
BEGIN
	DECLARE @fkBanco SYSNAME;
	SELECT @fkBanco = fk.name
	FROM sys.foreign_keys fk
	INNER JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
	INNER JOIN sys.columns c ON c.object_id = fkc.parent_object_id AND c.column_id = fkc.parent_column_id
	WHERE fk.parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR')
	  AND c.name = N'CORR_BANCO';
	IF @fkBanco IS NOT NULL
		EXEC(N'ALTER TABLE dbo.GEN_PROVEEDOR DROP CONSTRAINT [' + @fkBanco + N']');

	DECLARE @dfBanco SYSNAME;
	SELECT @dfBanco = dc.name
	FROM sys.default_constraints dc
	INNER JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id
	WHERE dc.parent_object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR')
	  AND c.name = N'CORR_BANCO';
	IF @dfBanco IS NOT NULL
		EXEC(N'ALTER TABLE dbo.GEN_PROVEEDOR DROP CONSTRAINT [' + @dfBanco + N']');

	ALTER TABLE dbo.GEN_PROVEEDOR DROP COLUMN [CORR_BANCO];
	PRINT N'Columna CORR_BANCO eliminada.';
END
ELSE
	PRINT N'CORR_BANCO ya no existe.';
GO

PRINT N'=== 3) Verificación parámetros SP ===';
GO

SELECT p.name AS parametro
FROM sys.parameters p
WHERE p.object_id = OBJECT_ID(N'dbo.PRAL_MTTO_GEN_PROVEEDOR')
  AND p.name IN (N'@CUENTA_BANCARIA', N'@CORR_BANCO', N'@CORR_PERSONA', N'@NOMBRE_COMERCIAL');

SELECT
	COL_LENGTH(N'dbo.GEN_PROVEEDOR', N'CORR_BANCO') AS col_corr_banco,
	COL_LENGTH(N'dbo.GEN_PROVEEDOR', N'CUENTA_BANCARIA') AS col_cuenta,
	OBJECT_ID(N'dbo.GEN_PERSONA_BANCO', N'U') AS tbl_persona_banco;

PRINT N'=== FIX_PRAL_MTTO_GEN_PROVEEDOR_SIN_BANCO completado ===';
GO
