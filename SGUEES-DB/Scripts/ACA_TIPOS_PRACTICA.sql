SET XACT_ABORT ON;
BEGIN TRANSACTION;
INSERT dbo.ACA_TIPOS_PRACTICA(CORR_EMPRESA,CODIGO_TIPO,NOMBRE_TIPO,HABILITA_COBROS_ADICIONALES,USUARIO_CREA,ESTACION_CREA)
SELECT E.CORR_EMPRESA,S.CODIGO,S.NOMBRE,1,'MIGRACION','ACA_TIPOS_PRACTICA'
FROM dbo.GEN_EMPRESA E CROSS JOIN(VALUES('PRACTICA_PROFESIONAL',N'Práctica profesional'),('TALLER_SEMINARIO',N'Taller de seminario'),
 ('TALLER_ESPECIALIZACION',N'Taller de especialización'),('TALLER_ENFERMERIA',N'Taller de enfermería'),('PRACTICA_CLINICA',N'Práctica clínica')) S(CODIGO,NOMBRE)
WHERE NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA T WHERE T.CORR_EMPRESA=E.CORR_EMPRESA AND T.CODIGO_TIPO=S.CODIGO);
DECLARE @ORDEN int=(SELECT ORDEN_OPCION FROM dbo.SEG_CONFIG_OPCION WHERE CODIGO_SISTEMA='ACADEMICS' AND CODIGO_MENU='GENERAL' AND CODIGO_OPCION='ACA_TIPOS_PRACTICA');
EXEC dbo.PR_SEG_ASIGNAR_OPCION_MENU @CODIGO_SISTEMA='ACADEMICS',@CODIGO_MENU='GENERAL',@CODIGO_OPCION='ACA_TIPOS_PRACTICA',@NOMBRE_OPCION=N'Tipos de práctica',@URL_OPCION=N'/aca-tipos-practica',@LOGIN_ASIGNA='MIGRACION',@ORDEN_OPCION=@ORDEN;
COMMIT;
GO
CREATE OR ALTER VIEW dbo.V_ACA_TIPOS_PRACTICA AS
SELECT T.CORR_TIPO_PRACTICA,T.CORR_EMPRESA,T.CODIGO_TIPO,T.NOMBRE_TIPO,T.HABILITA_COBROS_ADICIONALES,T.ACTIVO,T.USUARIO_CREA,T.FECHA_CREA,T.USUARIO_ACTU,T.FECHA_ACTU,T.VERSION,
 (SELECT COUNT(*) FROM dbo.ACA_ASIGNATURAS A WHERE A.CORR_TIPO_PRACTICA=T.CORR_TIPO_PRACTICA) CANTIDAD_ASIGNATURAS
FROM dbo.ACA_TIPOS_PRACTICA T;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_TIPOS_PRACTICA
 @CORR_EMPRESA int,@ID int OUTPUT,@CODIGO_TIPO varchar(200),@NOMBRE_TIPO nvarchar(500),@HABILITA_COBROS_ADICIONALES bit,@ACTIVO bit,
 @VERSION varbinary(8)=NULL,@USUARIO varchar(50),@ESTACION varchar(100)
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRANSACTION;
  IF @CORR_EMPRESA IS NULL OR @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'Empresa y usuario de sesión requeridos.',1;
  SET @CODIGO_TIPO=UPPER(LTRIM(RTRIM(@CODIGO_TIPO)));SET @NOMBRE_TIPO=LTRIM(RTRIM(@NOMBRE_TIPO));
  IF @ID IS NULL OR @ID<0 OR @CODIGO_TIPO IS NULL OR LEN(@CODIGO_TIPO) NOT BETWEEN 1 AND 30 OR @CODIGO_TIPO COLLATE Latin1_General_100_BIN2 LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2
   OR NULLIF(@NOMBRE_TIPO,'') IS NULL OR LEN(@NOMBRE_TIPO)>80 OR @HABILITA_COBROS_ADICIONALES IS NULL OR @ACTIVO IS NULL
   THROW 51000,N'Revise código (hasta 30 caracteres), nombre y opciones de cobro y estado.',1;
  DECLARE @ANTES nvarchar(max),@DESPUES nvarchar(max);
  IF @ID>0
  BEGIN
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_TIPO_PRACTICA=@ID) THROW 51000,N'El tipo de práctica no pertenece a la empresa de la sesión.',1;
   IF @VERSION IS NULL OR NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WHERE CORR_TIPO_PRACTICA=@ID AND VERSION=@VERSION) THROW 51000,N'Otro usuario modificó el tipo de práctica. Actualice la lista.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WHERE CORR_TIPO_PRACTICA=@ID AND CODIGO_TIPO=@CODIGO_TIPO) THROW 51000,N'El código del tipo de práctica no se puede cambiar.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WITH(HOLDLOCK) WHERE CORR_TIPO_PRACTICA=@ID)
     AND EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WHERE CORR_TIPO_PRACTICA=@ID AND HABILITA_COBROS_ADICIONALES<>@HABILITA_COBROS_ADICIONALES) THROW 51000,N'El tipo está utilizado. Cree otro tipo para cambiar su regla de cobro sin alterar registros existentes.',1;
   IF @ACTIVO=0 AND EXISTS(SELECT 1 FROM dbo.ACA_ASIGNATURAS WITH(HOLDLOCK) WHERE CORR_TIPO_PRACTICA=@ID AND ACTIVO=1) THROW 51000,N'El tipo de práctica tiene asignaturas activas. Reasígnelas o desactívelas primero.',1;
   SET @ANTES=(SELECT * FROM dbo.ACA_TIPOS_PRACTICA WHERE CORR_TIPO_PRACTICA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
   UPDATE dbo.ACA_TIPOS_PRACTICA SET NOMBRE_TIPO=@NOMBRE_TIPO,HABILITA_COBROS_ADICIONALES=@HABILITA_COBROS_ADICIONALES,ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_TIPO_PRACTICA=@ID;
  END ELSE
  BEGIN
   INSERT dbo.ACA_TIPOS_PRACTICA(CORR_EMPRESA,CODIGO_TIPO,NOMBRE_TIPO,HABILITA_COBROS_ADICIONALES,ACTIVO,USUARIO_CREA,ESTACION_CREA) VALUES(@CORR_EMPRESA,@CODIGO_TIPO,@NOMBRE_TIPO,@HABILITA_COBROS_ADICIONALES,@ACTIVO,@USUARIO,@ESTACION);
   SET @ID=CONVERT(int,SCOPE_IDENTITY());
  END;
  SET @DESPUES=(SELECT * FROM dbo.ACA_TIPOS_PRACTICA WHERE CORR_TIPO_PRACTICA=@ID FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  INSERT dbo.ACA_ASIGNATURAS_BITACORA(CORR_EMPRESA,ENTIDAD,ID_REGISTRO,OPERACION,USUARIO,ESTACION,DATOS_ANTES,DATOS_DESPUES) VALUES(@CORR_EMPRESA,'TIPO_PRACTICA',@ID,CASE WHEN @ANTES IS NULL THEN 'CREAR' ELSE 'ACTUALIZAR' END,@USUARIO,@ESTACION,@ANTES,@DESPUES);
  COMMIT;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  IF ERROR_NUMBER() IN(2601,2627) THROW 51000,N'Ya existe un tipo de práctica con ese código.',1;
  THROW;
 END CATCH;
END;
GO
