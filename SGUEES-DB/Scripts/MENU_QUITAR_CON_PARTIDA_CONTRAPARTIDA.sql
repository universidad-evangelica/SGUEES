/* Quitar opción de menú independiente — la contrapartida vive en Partidas Contables (modal) */
SET NOCOUNT ON;
DECLARE @SISTEMA varchar(30) = 'CONTABILIDAD';
DECLARE @OPCION varchar(30) = 'CON_PARTIDA_CONTRAPARTIDA';

DELETE FROM SEG_USUARIO_OPCION WHERE CODIGO_SISTEMA = @SISTEMA AND CODIGO_OPCION = @OPCION;
DELETE FROM SEG_CONFIG_OPCION WHERE CODIGO_SISTEMA = @SISTEMA AND CODIGO_OPCION = @OPCION;
DELETE FROM SEG_OPCION_SISTEMA_SUITE WHERE CODIGO_OPCION = @OPCION;
DELETE FROM SEG_OPCION_SISTEMA WHERE CODIGO_OPCION = @OPCION;

PRINT N'Opción CON_PARTIDA_CONTRAPARTIDA eliminada del menú.';
