CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT = NULL,
	@CORR_DOCUMENTO INT OUTPUT,
	@CORR_CUENTA_BANCO INT = NULL,
	@NUMERO_DOCUMENTO BIGINT = 0,
	@FECHA_EMISION DATE = NULL,
	@NOMBRE_PARTIDA VARCHAR(1000) = '',
	@CORR_PROVEEDOR INT = NULL,
	@CORR_EMPLEADO INT = NULL,
	@CORR_CLIENTE INT = NULL,
	@NOMBRE_BENEFICIARIO VARCHAR(255) = NULL,
	@MONTO_DOCUMENTO DECIMAL(18, 2) = 0,
	@ESTADO_DOCUMENTO VARCHAR(2) = 'DI',
	@ESTA_CONTABILIZADO BIT = 0,
	@CANTIDAD_LETRAS VARCHAR(255) = '',
	@USUARIO_CREA VARCHAR(30) = '',
	@FECHA_CREA DATETIME = NULL,
	@ESTACION_CREA VARCHAR(50) = '',
	@USUARIO_ACTU VARCHAR(30) = NULL,
	@FECHA_ACTU DATETIME = NULL,
	@ESTACION_ACTU VARCHAR(50) = NULL,
	@CORR_TIPO_CHEQUE INT = NULL,
	@CORR_CHEQUERA INT = NULL,
	@SERIE_CHEQUE VARCHAR(10) = NULL,
	@CORR_CUENTA_BANCO_DESTINO INT = NULL,
	@NUMERO_CUENTA_DESTINO_TERCERO VARCHAR(50) = NULL,
	@MONTO_DESTINO DECIMAL(18, 2) = 0,
	@CORR_MONEDA INT = NULL,
	@FACTOR_CAMBIO DECIMAL(16, 6) = 1,
	@OPERADOR VARCHAR(2) = '*',
	@GENERA_DETALLE BIT = 1,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe el periodo contable seleccionado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
					AND ISNULL(ESTADO_PERIODO_BAN, 'AB') = 'AB'
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El periodo bancario no está abierto', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF @CORR_TIPO_MOVIMIENTO IS NULL OR NOT EXISTS (
				SELECT 1 FROM dbo.BAN_TIPO_MOVI_BANCARIO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe el tipo de movimiento seleccionado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF @CORR_CUENTA_BANCO IS NULL OR NOT EXISTS (
				SELECT 1 FROM dbo.BAN_CUENTA_BANCARIA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe la cuenta bancaria seleccionada', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF LTRIM(RTRIM(ISNULL(@NOMBRE_PARTIDA, ''))) = ''
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe especificar el concepto del documento', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF ISNULL(@MONTO_DOCUMENTO, 0) < 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El monto del documento no puede ser negativo', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			DECLARE @CLASE_MOVIMIENTO VARCHAR(10);
			SELECT @CLASE_MOVIMIENTO = CLASE_MOVIMIENTO
			FROM dbo.BAN_TIPO_MOVI_BANCARIO
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

			IF @CLASE_MOVIMIENTO = 'TPR'
			BEGIN
				IF ISNULL(@CORR_CUENTA_BANCO_DESTINO, 0) <= 0
				BEGIN
					SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe seleccionar la cuenta bancaria destino', @SYS_FILAS_AFECTADAS = 0;
					GOTO FINA;
				END;

				IF @CORR_CUENTA_BANCO_DESTINO = @CORR_CUENTA_BANCO
				BEGIN
					SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'La cuenta destino debe ser diferente a la cuenta origen', @SYS_FILAS_AFECTADAS = 0;
					GOTO FINA;
				END;

				IF NOT EXISTS (
					SELECT 1 FROM dbo.BAN_CUENTA_BANCARIA
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO_DESTINO
				)
				BEGIN
					SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe la cuenta bancaria destino seleccionada', @SYS_FILAS_AFECTADAS = 0;
					GOTO FINA;
				END;

				IF ISNULL(@NUMERO_CUENTA_DESTINO_TERCERO, '') = ''
				BEGIN
					SELECT @NUMERO_CUENTA_DESTINO_TERCERO = ISNULL(NUMERO_CUENTA_BANCO, '')
					FROM dbo.BAN_CUENTA_BANCARIA
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO_DESTINO;
				END;

				SET @MONTO_DESTINO = ISNULL(NULLIF(@MONTO_DESTINO, 0), @MONTO_DOCUMENTO);
			END
			ELSE IF @CLASE_MOVIMIENTO = 'TTE'
			BEGIN
				SET @CORR_CUENTA_BANCO_DESTINO = NULL;

				IF LTRIM(RTRIM(ISNULL(@NUMERO_CUENTA_DESTINO_TERCERO, ''))) = ''
				BEGIN
					SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe indicar la cuenta bancaria destino del tercero', @SYS_FILAS_AFECTADAS = 0;
					GOTO FINA;
				END;

				SET @MONTO_DESTINO = ISNULL(NULLIF(@MONTO_DESTINO, 0), @MONTO_DOCUMENTO);
			END
			ELSE
			BEGIN
				SET @CORR_CUENTA_BANCO_DESTINO = NULL;
				SET @NUMERO_CUENTA_DESTINO_TERCERO = NULL;
				SET @MONTO_DESTINO = 0;
			END;

			IF @CLASE_MOVIMIENTO IN ('TPR', 'TTE') AND ISNULL(@MONTO_DESTINO, 0) <= 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe indicar el monto destino', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			DECLARE @NOMBRE_MONEDA VARCHAR(100) = N'DÓLARES';
			IF OBJECT_ID(N'dbo.GEN_TIPO_MONEDA', N'U') IS NOT NULL
			BEGIN
				SELECT @NOMBRE_MONEDA = ISNULL(M.NOMBRE_MONEDA, @NOMBRE_MONEDA)
				FROM dbo.GEN_TIPO_MONEDA M
				WHERE M.CORR_MONEDA = ISNULL(@CORR_MONEDA, 0);
			END

			DECLARE @sFraccion VARCHAR(15) = '00' + LTRIM(CAST(CAST(((@MONTO_DOCUMENTO - CAST(@MONTO_DOCUMENTO AS INT)) * 100) AS INT) AS VARCHAR(15)));
			SELECT @CANTIDAD_LETRAS = dbo.FN_NUMEROS_A_LETRAS(@MONTO_DOCUMENTO, 1) + N' ' + @NOMBRE_MONEDA
				+ N' CON ' + SUBSTRING(@sFraccion, LEN(@sFraccion) - 1, 2) + N'/100';
		END;

		IF @TIPO_ACTUALIZA IN (2, 3)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_DOCUMENTO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
					AND ESTADO_DOCUMENTO = 'DI'
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El documento no puede modificarse o eliminarse (estado distinto de Digitado)', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_DOCUMENTO = ISNULL(MAX(CORR_DOCUMENTO), 0) + 1
			FROM dbo.BAN_DOCUMENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

			SET @ESTADO_DOCUMENTO = 'DI';
			SET @ESTA_CONTABILIZADO = 0;
			SET @FECHA_CREA = ISNULL(@FECHA_CREA, GETDATE());
			SET @USUARIO_ACTU = @USUARIO_CREA;
			SET @FECHA_ACTU = @FECHA_CREA;
			SET @ESTACION_ACTU = @ESTACION_CREA;

			INSERT INTO dbo.BAN_DOCUMENTO
			(
				CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO,
				CORR_CUENTA_BANCO, NUMERO_DOCUMENTO, FECHA_EMISION, NOMBRE_PARTIDA,
				CORR_PROVEEDOR, CORR_EMPLEADO, CORR_CLIENTE, NOMBRE_BENEFICIARIO,
				MONTO_DOCUMENTO, ESTADO_DOCUMENTO, ESTA_CONTABILIZADO, CANTIDAD_LETRAS,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA, USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU,
				CORR_TIPO_CHEQUE, CORR_CHEQUERA, SERIE_CHEQUE, CORR_CUENTA_BANCO_DESTINO,
				NUMERO_CUENTA_DESTINO_TERCERO, MONTO_DESTINO, CORR_MONEDA, FACTOR_CAMBIO, OPERADOR
			)
			VALUES
			(
				@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO,
				@CORR_CUENTA_BANCO, ISNULL(@NUMERO_DOCUMENTO, 0), @FECHA_EMISION, @NOMBRE_PARTIDA,
				@CORR_PROVEEDOR, @CORR_EMPLEADO, @CORR_CLIENTE, @NOMBRE_BENEFICIARIO,
				@MONTO_DOCUMENTO, @ESTADO_DOCUMENTO, @ESTA_CONTABILIZADO, @CANTIDAD_LETRAS,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA, @USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU,
				@CORR_TIPO_CHEQUE, @CORR_CHEQUERA, @SERIE_CHEQUE, @CORR_CUENTA_BANCO_DESTINO,
				@NUMERO_CUENTA_DESTINO_TERCERO, @MONTO_DESTINO, @CORR_MONEDA, @FACTOR_CAMBIO, @OPERADOR
			);

			IF ISNULL(@GENERA_DETALLE, 1) = 1
			BEGIN
				EXEC dbo.PRAL_GENE_BAN_DOCUMENTO_DETA
					@CORR_EMPRESA = @CORR_EMPRESA,
					@ANIO_PERIODO = @ANIO_PERIODO,
					@MES_PERIODO = @MES_PERIODO,
					@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO,
					@CORR_DOCUMENTO = @CORR_DOCUMENTO,
					@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
					@SYS_ESTACION = @SYS_ESTACION,
					@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

				IF @SYS_NUMERO_ERROR <> 0
				BEGIN
					DELETE FROM dbo.BAN_DOCUMENTO_DETA
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

					DELETE FROM dbo.BAN_DOCUMENTO
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

					GOTO FINA;
				END;
			END;
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.BAN_DOCUMENTO SET
				CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO,
				NUMERO_DOCUMENTO = @NUMERO_DOCUMENTO,
				FECHA_EMISION = @FECHA_EMISION,
				NOMBRE_PARTIDA = @NOMBRE_PARTIDA,
				CORR_PROVEEDOR = @CORR_PROVEEDOR,
				CORR_EMPLEADO = @CORR_EMPLEADO,
				CORR_CLIENTE = @CORR_CLIENTE,
				NOMBRE_BENEFICIARIO = @NOMBRE_BENEFICIARIO,
				MONTO_DOCUMENTO = @MONTO_DOCUMENTO,
				CANTIDAD_LETRAS = @CANTIDAD_LETRAS,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE()),
				ESTACION_ACTU = @ESTACION_ACTU,
				CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE,
				CORR_CHEQUERA = @CORR_CHEQUERA,
				SERIE_CHEQUE = @SERIE_CHEQUE,
				CORR_CUENTA_BANCO_DESTINO = @CORR_CUENTA_BANCO_DESTINO,
				NUMERO_CUENTA_DESTINO_TERCERO = @NUMERO_CUENTA_DESTINO_TERCERO,
				MONTO_DESTINO = @MONTO_DESTINO,
				CORR_MONEDA = @CORR_MONEDA,
				FACTOR_CAMBIO = @FACTOR_CAMBIO,
				OPERADOR = @OPERADOR
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.BAN_DOCUMENTO_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

			DELETE FROM dbo.BAN_DOCUMENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
