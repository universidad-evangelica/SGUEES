IF OBJECT_ID(N'dbo.PRAL_MTTO_BAN_DOCUMENTO_APLICAR', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_APLICAR];
