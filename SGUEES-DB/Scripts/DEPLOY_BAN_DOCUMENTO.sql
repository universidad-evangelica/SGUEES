CREATE VIEW [dbo].[V_BAN_DOCUMENTO]
AS
SELECT
	A.CORR_EMPRESA,
	A.ANIO_PERIODO,
	A.MES_PERIODO,
	A.CORR_TIPO_MOVIMIENTO,
	B.NOMBRE_TIPO_MOVIMIENTO,
	B.CLASE_MOVIMIENTO,
	A.CORR_DOCUMENTO,
	A.CORR_CUENTA_BANCO,
	C.NOMBRE_CUENTA_BANCO,
	C.NUMERO_CUENTA_BANCO,
	A.NUMERO_DOCUMENTO,
	A.FECHA_EMISION,
	A.NOMBRE_PARTIDA,
	ISNULL(A.CORR_PROVEEDOR, 0) CORR_PROVEEDOR,
	ISNULL(A.NOMBRE_BENEFICIARIO, '') NOMBRE_BENEFICIARIO,
	ISNULL(A.CORR_EMPLEADO, 0) CORR_EMPLEADO,
	ISNULL(A.CORR_CLIENTE, 0) CORR_CLIENTE,
	A.MONTO_DOCUMENTO,
	A.ESTADO_DOCUMENTO,
	CASE A.ESTADO_DOCUMENTO
		WHEN 'DI' THEN N'Digitado'
		WHEN 'AP' THEN N'Aplicado'
		WHEN 'IM' THEN N'Impreso'
		WHEN 'VA' THEN N'Validación'
		WHEN 'AN' THEN N'Anulado'
		WHEN 'SO' THEN N'Solicitando Autorización'
		ELSE N''
	END AS NOMBRE_ESTADO_DOCUMENTO,
	A.ESTA_CONTABILIZADO,
	A.CANTIDAD_LETRAS,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU,
	ISNULL(A.CORR_TIPO_CHEQUE, 0) CORR_TIPO_CHEQUE,
	ISNULL(E.CLASE_TIPO_CHEQUE, '') CLASE_TIPO_CHEQUE,
	ISNULL(E.NOMBRE_TIPO_CHEQUE, '') NOMBRE_TIPO_CHEQUE,
	ISNULL(A.CORR_CHEQUERA, 0) CORR_CHEQUERA,
	ISNULL(A.SERIE_CHEQUE, '') SERIE_CHEQUE,
	ISNULL(A.CORR_CUENTA_BANCO_DESTINO, 0) CORR_CUENTA_BANCO_DESTINO,
	ISNULL(F.NOMBRE_CUENTA_BANCO, '') NOMBRE_CUENTA_BANCO_DESTINO,
	ISNULL(A.NUMERO_CUENTA_DESTINO_TERCERO, '') NUMERO_CUENTA_DESTINO_TERCERO,
	ISNULL(A.MONTO_DESTINO, 0) MONTO_DESTINO,
	ISNULL(A.CORR_MONEDA, 0) CORR_MONEDA,
	ISNULL(A.FACTOR_CAMBIO, 1) FACTOR_CAMBIO,
	ISNULL(A.OPERADOR, '*') OPERADOR,
	A.FECHA_IMPRESO,
	A.FECHA_ANULACION
FROM dbo.BAN_DOCUMENTO A
INNER JOIN dbo.BAN_TIPO_MOVI_BANCARIO B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA AND A.CORR_TIPO_MOVIMIENTO = B.CORR_TIPO_MOVIMIENTO
INNER JOIN dbo.V_BAN_CUENTA_BANCARIA C
	ON A.CORR_EMPRESA = C.CORR_EMPRESA AND A.CORR_CUENTA_BANCO = C.CORR_CUENTA_BANCO
LEFT JOIN dbo.V_BAN_TIPO_CHEQUE E
	ON A.CORR_EMPRESA = E.CORR_EMPRESA AND A.CORR_TIPO_CHEQUE = E.CORR_TIPO_CHEQUE
LEFT JOIN dbo.V_BAN_CUENTA_BANCARIA F
	ON A.CORR_EMPRESA = F.CORR_EMPRESA AND A.CORR_CUENTA_BANCO_DESTINO = F.CORR_CUENTA_BANCO;
GO

