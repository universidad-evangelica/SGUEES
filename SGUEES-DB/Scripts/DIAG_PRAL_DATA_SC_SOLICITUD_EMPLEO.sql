/*
  Diagnóstico: por qué un login ve 0 solicitudes en sc-solicitud-empleo.
  Ajusta @LOGIN y ejecuta en SSMS. No modifica datos.

  sqlcmd ... -f 65001 -i DIAG_PRAL_DATA_SC_SOLICITUD_EMPLEO.sql
*/

DECLARE @CORR_EMPRESA INT = 1;
DECLARE @LOGIN VARCHAR(30) = N'kaguilera'; /* probar también jonathan.avalos */

DECLARE @LOGIN_U VARCHAR(30) = UPPER(LTRIM(RTRIM(@LOGIN)));

PRINT N'=== 1) Empleado del login ===';
SELECT E.CORR_EMPRESA, E.CORR_EMPLEADO, PU.LOGIN_SISTEMA
FROM dbo.GEN_EMPLEADO AS E
INNER JOIN dbo.GEN_PERSONA_USUARIO AS PU ON PU.CORR_PERSONA = E.CORR_PERSONA
WHERE E.CORR_EMPRESA = @CORR_EMPRESA
  AND UPPER(LTRIM(RTRIM(PU.LOGIN_SISTEMA))) = @LOGIN_U;

PRINT N'=== 2) Unidad TH padre (1010101 / nombre) ===';
SELECT CORR_UNIDAD, CODIGO_UNIDAD, NOMBRE_UNIDAD, CORR_UNIDAD_PADRE
FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES
WHERE CORR_EMPRESA = @CORR_EMPRESA
  AND ACTIVO = 1
  AND (
		LTRIM(RTRIM(ISNULL(CODIGO_UNIDAD, N''))) = N'1010101'
		OR NOMBRE_UNIDAD LIKE N'%Departamento de Talento Humano%'
	  );

PRINT N'=== 3) Unidad 1010102 (¿está bajo TH?) ===';
SELECT
	U.CORR_UNIDAD,
	U.CODIGO_UNIDAD,
	U.NOMBRE_UNIDAD,
	U.CORR_UNIDAD_PADRE,
	P.CODIGO_UNIDAD AS CODIGO_PADRE,
	P.NOMBRE_UNIDAD AS NOMBRE_PADRE
FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS U
LEFT JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS P
	ON P.CORR_EMPRESA = U.CORR_EMPRESA AND P.CORR_UNIDAD = U.CORR_UNIDAD_PADRE
WHERE U.CORR_EMPRESA = @CORR_EMPRESA
  AND LTRIM(RTRIM(ISNULL(U.CODIGO_UNIDAD, N''))) = N'1010102';

PRINT N'=== 4) Jefaturas activas del login ===';
SELECT JU.CORR_UNIDAD, U.CODIGO_UNIDAD, U.NOMBRE_UNIDAD, JU.ACTIVO
FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_JEFES_UNIDADES AS JU
INNER JOIN dbo.GEN_EMPLEADO AS E
	ON E.CORR_EMPRESA = JU.CORR_EMPRESA AND E.CORR_EMPLEADO = JU.CORR_EMPLEADO
INNER JOIN dbo.GEN_PERSONA_USUARIO AS PU ON PU.CORR_PERSONA = E.CORR_PERSONA
INNER JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS U
	ON U.CORR_EMPRESA = JU.CORR_EMPRESA AND U.CORR_UNIDAD = JU.CORR_UNIDAD
WHERE JU.CORR_EMPRESA = @CORR_EMPRESA
  AND JU.ACTIVO = 1
  AND UPPER(LTRIM(RTRIM(PU.LOGIN_SISTEMA))) = @LOGIN_U;

PRINT N'=== 5) Puestos del login ===';
SELECT EP.CORR_UNIDAD, U.CODIGO_UNIDAD, U.NOMBRE_UNIDAD
FROM dbo.GEN_EMPLEADO_PUESTO AS EP
INNER JOIN dbo.GEN_EMPLEADO AS E
	ON E.CORR_EMPRESA = EP.CORR_EMPRESA AND E.CORR_EMPLEADO = EP.CORR_EMPLEADO
INNER JOIN dbo.GEN_PERSONA_USUARIO AS PU ON PU.CORR_PERSONA = E.CORR_PERSONA
LEFT JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS U
	ON U.CORR_EMPRESA = EP.CORR_EMPRESA AND U.CORR_UNIDAD = EP.CORR_UNIDAD
WHERE EP.CORR_EMPRESA = @CORR_EMPRESA
  AND UPPER(LTRIM(RTRIM(PU.LOGIN_SISTEMA))) = @LOGIN_U;

PRINT N'=== 6) Solicitudes totales vs con vínculo requisición ===';
SELECT
	(SELECT COUNT(*) FROM dbo.V_SC_SOLICITUD_EMPLEO WHERE CORR_EMPRESA = @CORR_EMPRESA) AS TOTAL_SOLICITUDES,
	(SELECT COUNT(DISTINCT CORR_SOLICITUD_EMPLEO) FROM dbo.SC_SOLICITUD_REQUISICION WHERE CORR_EMPRESA = @CORR_EMPRESA) AS CON_REQUISICION,
	(SELECT COUNT(*) FROM dbo.V_SC_SOLICITUD_EMPLEO WHERE CORR_EMPRESA = @CORR_EMPRESA AND UPPER(LTRIM(RTRIM(ISNULL(USUARIO_CREA, '')))) = @LOGIN_U) AS CREADAS_POR_LOGIN;

PRINT N'=== 7) Vínculos solicitud-requisición de unidad 1010102 (y hijas/padre del código) ===';
SELECT
	SR.CORR_SOLICITUD_EMPLEO,
	SR.CORR_REQUISICION_PERSONAL,
	R.CORR_UNIDAD,
	U.CODIGO_UNIDAD,
	U.NOMBRE_UNIDAD
FROM dbo.SC_SOLICITUD_REQUISICION AS SR
INNER JOIN dbo.SC_REQUISICION_PERSONAL AS R
	ON R.CORR_EMPRESA = SR.CORR_EMPRESA AND R.CORR_REQUISICION_PERSONAL = SR.CORR_REQUISICION_PERSONAL
LEFT JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS U
	ON U.CORR_EMPRESA = R.CORR_EMPRESA AND U.CORR_UNIDAD = R.CORR_UNIDAD
WHERE SR.CORR_EMPRESA = @CORR_EMPRESA
  AND (
		LTRIM(RTRIM(ISNULL(U.CODIGO_UNIDAD, N''))) = N'1010102'
		OR U.CORR_UNIDAD_PADRE IN (
			SELECT CORR_UNIDAD FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND LTRIM(RTRIM(ISNULL(CODIGO_UNIDAD, N''))) = N'1010102'
		)
	  );

PRINT N'=== 8) Resultado del SP ===';
EXEC dbo.PRAL_DATA_SC_SOLICITUD_EMPLEO
	@CORR_EMPRESA = @CORR_EMPRESA,
	@LOGIN_SISTEMA = @LOGIN;
GO
