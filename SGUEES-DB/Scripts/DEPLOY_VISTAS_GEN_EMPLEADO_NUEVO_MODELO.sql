-- QuÃ© hace: catÃ¡logo de empleados para lookups (misma forma que antes para API/SPA).
-- CÃ³mo lo hace: lee GEN_EMPLEADO nuevo + GEN_PERSONA_NATURAL (nombre) + GEN_PERSONA_USUARIO (login)
--               + puesto vigente desde GEN_EMPLEADO_PUESTO. Expone alias legacy
--               (NOMBRE_EMPLEADO, ESTADO_EMPLEADO, LOGIN_SISTEMA_WEB, etc.).
CREATE OR ALTER VIEW [dbo].[V_GEN_EMPLEADO]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_EMPLEADO,
	A.CORR_PERSONA,
	A.CODIGO_EMPLEADO,
	ISNULL(PN.NOMBRE_COMPLETO, N'') AS NOMBRE_EMPLEADO,
	ISNULL(PN.PRIMER_NOMBRE, N'') AS NOMBRE_1,
	ISNULL(PN.SEGUNDO_NOMBRE, N'') AS NOMBRE_2,
	ISNULL(PN.PRIMER_APELLIDO, N'') AS APELLIDO_1,
