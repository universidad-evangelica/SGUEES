CREATE OR ALTER FUNCTION dbo.SEG_FN_ObtenerLoginPorCodigoEmpleado
(
	@CORR_EMPLEADO INT
)
RETURNS VARCHAR(30)
AS
BEGIN
	DECLARE @Login VARCHAR(30);

	SELECT TOP (1) @Login = PU.LOGIN_SISTEMA
	FROM dbo.GEN_EMPLEADO E
	INNER JOIN dbo.GEN_PERSONA_USUARIO PU
