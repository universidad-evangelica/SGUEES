(
	@CORR_UNIDAD INT
)
RETURNS VARCHAR(30)
AS
BEGIN
	DECLARE @Login VARCHAR(30);

	SELECT TOP (1) @Login = PU.LOGIN_SISTEMA
	FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_JEFES_UNIDADES J
	INNER JOIN dbo.GEN_EMPLEADO GE
