	WHERE J.CORR_UNIDAD = @CORR_UNIDAD
	  AND J.ACTIVO = 1
	  AND (J.FECHA_FIN IS NULL OR J.FECHA_FIN >= CAST(GETDATE() AS DATE))
	  AND ISNULL(GE.ACTIVO_EMPLEADO, 0) = 1
	ORDER BY J.FECHA_INICIO DESC, PU.LOGIN_SISTEMA;

