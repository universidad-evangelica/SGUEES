-- Icono del sistema Académico. school no existe en DevExtreme; bookmark sí.
UPDATE dbo.SEG_SISTEMA
SET IMAGEN_SISTEMA = 'bookmark'
WHERE CODIGO_SISTEMA = 'ACADEMICS'
  AND IMAGEN_SISTEMA = 'school';
GO

-- La opción ya quedó registrada con el nombre corto. Este bloque la deja igual a la tabla.
-- El usuario lo ejecuta. No está aplicado en la base.

UPDATE dbo.SEG_USUARIO_OPCION
SET CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO'
WHERE CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO';

UPDATE dbo.SEG_OPCION_SISTEMA_SUITE
SET CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO'
WHERE CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO';

UPDATE dbo.SEG_CONFIG_OPCION
SET CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO'
WHERE CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO';

UPDATE dbo.SEG_OPCION_SISTEMA
SET CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO',
    URL_OPCION = '/aca-documento-admision-flujo-tipo-documento'
WHERE CODIGO_OPCION = 'ACA_DOCUMENTO_ADMISION_FLUJO';
GO

