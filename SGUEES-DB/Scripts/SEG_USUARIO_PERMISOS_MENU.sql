CREATE OR ALTER VIEW dbo.V_SEG_USUARIO_PERMISOS AS
SELECT A.LOGIN_SISTEMA,A.CODIGO_SISTEMA,A.NOMBRE_SISTEMA,A.IMAGEN_SISTEMA,
 A.CODIGO_MENU,A.NOMBRE_MENU,A.IMAGEN_MENU,A.CODIGO_OPCION,A.NOMBRE_OPCION,A.IMAGEN_OPCION,A.URL_OPCION,
 A.NUEVO,A.MODIFICAR,A.ELIMINAR,A.IMPRIMIR,A.ORDEN_SISTEMA,A.ORDEN_MENU,A.ORDEN_OPCION,
 CASE WHEN A.NUEVO=1 THEN 'C' ELSE '' END+'R'+CASE WHEN A.MODIFICAR=1 THEN 'U' ELSE '' END+
 CASE WHEN A.ELIMINAR=1 THEN 'D' ELSE '' END+CASE WHEN A.IMPRIMIR=1 THEN 'P' ELSE '' END PERMISO,
 CONVERT(bit,CASE WHEN A.CODIGO_OPCION IN('ACA_PERIODOS_CURSO','ACA_TIPOS_PRACTICA') THEN 0 ELSE 1 END) MOSTRAR_EN_MENU
FROM dbo.V_SEG_USUARIO_OPCION A;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_DATA_SEG_USUARIO_PERMISOS
 @LOGIN_SISTEMA varchar(30),@CODIGO_SUITE varchar(30)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT A.CODIGO_SISTEMA,A.NOMBRE_SISTEMA,A.IMAGEN_SISTEMA,A.CODIGO_MENU,A.NOMBRE_MENU,A.IMAGEN_MENU,
 A.CODIGO_OPCION,A.NOMBRE_OPCION,A.IMAGEN_OPCION,A.URL_OPCION,A.NUEVO,A.MODIFICAR,A.ELIMINAR,A.IMPRIMIR,
 A.ORDEN_SISTEMA,A.ORDEN_MENU,A.ORDEN_OPCION,A.PERMISO,A.MOSTRAR_EN_MENU
 FROM dbo.V_SEG_USUARIO_PERMISOS A
 WHERE LTRIM(RTRIM(A.LOGIN_SISTEMA))=LTRIM(RTRIM(@LOGIN_SISTEMA))
 AND EXISTS(SELECT 1 FROM dbo.SEG_USUARIO U WHERE LTRIM(RTRIM(U.LOGIN_SISTEMA))=LTRIM(RTRIM(@LOGIN_SISTEMA)))
 AND EXISTS(SELECT 1 FROM dbo.SEG_OPCION_SISTEMA_SUITE S WHERE S.CODIGO_OPCION=A.CODIGO_OPCION
 AND LTRIM(RTRIM(UPPER(S.CODIGO_SUITE)))=LTRIM(RTRIM(UPPER(@CODIGO_SUITE))))
 ORDER BY A.ORDEN_SISTEMA DESC,A.ORDEN_MENU,A.ORDEN_OPCION;
END;
