CREATE OR ALTER PROCEDURE dbo.PR_ACA_FACULTAD_CONFIGURAR
 @OPERACION varchar(15),@EMPRESA int,@FACULTAD int OUTPUT,@CODIGO varchar(20)=NULL,@NOMBRE varchar(200)=NULL,@DECANO int=NULL,@ACTIVO bit=1,
 @SEDE int=NULL,@USUARIO varchar(50),@ESTACION varchar(100)
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
 BEGIN TRANSACTION;
 IF @EMPRESA<=0 OR NULLIF(@USUARIO,'') IS NULL THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
 IF @OPERACION NOT IN('CREAR','GUARDAR','ESTADO','ELIMINAR','SEDE_CREAR','SEDE_GUARDAR','SEDE_ELIMINAR') THROW 51000,N'Operación de facultad inválida.',1;
 DECLARE @anterior bit,@decanoAnterior int;
 IF @OPERACION<>'CREAR'
 BEGIN
 SELECT @anterior=ACTIVO,@decanoAnterior=CORR_DECANO FROM dbo.ACA_FACULTADES WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@EMPRESA AND CORR_FACULTAD=@FACULTAD;
 IF @anterior IS NULL THROW 51000,N'La facultad no existe en la empresa de sesión.',1;
 END;
 IF @OPERACION IN('CREAR','GUARDAR')
 BEGIN
 IF NULLIF(LTRIM(RTRIM(@CODIGO)),'') IS NULL OR NULLIF(LTRIM(RTRIM(@NOMBRE)),'') IS NULL THROW 51000,N'Complete código y nombre de la facultad.',1;
 IF @DECANO IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.V_GEN_EMPLEADO WHERE CORR_EMPRESA=@EMPRESA AND CORR_EMPLEADO=@DECANO AND (ACTIVO_EMPLEADO=1 OR @decanoAnterior=@DECANO)) THROW 51000,N'Seleccione un empleado activo de la empresa como decano.',1;
 IF @OPERACION='CREAR'
 BEGIN
 IF EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@EMPRESA AND CODIGO_FACULTAD=@CODIGO) THROW 51000,N'Ya existe una facultad con ese código.',1;
 INSERT dbo.ACA_FACULTADES(CORR_EMPRESA,CODIGO_FACULTAD,NOMBRE_FACULTAD,CORR_DECANO,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@EMPRESA,@CODIGO,@NOMBRE,@DECANO,@ACTIVO,@USUARIO,@ESTACION,GETDATE());
 SET @FACULTAD=SCOPE_IDENTITY();
 END
 ELSE UPDATE dbo.ACA_FACULTADES SET NOMBRE_FACULTAD=@NOMBRE,CORR_DECANO=@DECANO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_FACULTAD=@FACULTAD AND CORR_EMPRESA=@EMPRESA;
 END;
 IF @OPERACION IN('ELIMINAR','ESTADO') AND (@OPERACION='ELIMINAR' OR @anterior=1)
 BEGIN
 IF EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_FACULTAD=@FACULTAD AND (@OPERACION='ELIMINAR' OR ACTIVO=1)) THROW 51000,N'La facultad tiene carreras relacionadas. Revise Carreras antes de retirarla.',1;
 IF EXISTS(SELECT 1 FROM dbo.ACA_CICLOS_FACULTADES_SEDES F WITH(UPDLOCK,HOLDLOCK) JOIN dbo.ACA_CICLOS_ACADEMICOS H WITH(UPDLOCK,HOLDLOCK) ON H.CORR_CICLO_ACADEMICO=F.CORR_CICLO_ACADEMICO WHERE F.CORR_FACULTAD=@FACULTAD AND (@OPERACION='ELIMINAR' OR (H.ESTADO='HABILITADO' AND F.ACTIVO=1))) THROW 51000,N'La facultad está vinculada a ciclos. Revise Participación en ciclos; conserve el historial mediante desactivación.',1;
 IF @OPERACION='ELIMINAR' AND (EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_FACULTAD=@FACULTAD) OR EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS_BITACORA WHERE CORR_FACULTAD=@FACULTAD)) THROW 51000,N'La facultad tiene períodos o historial. Utilice desactivación.',1;
 END;
 IF @OPERACION='ESTADO' UPDATE dbo.ACA_FACULTADES SET ACTIVO=1-CONVERT(int,@anterior),USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_FACULTAD=@FACULTAD AND CORR_EMPRESA=@EMPRESA;
 IF @OPERACION='ELIMINAR'
 BEGIN
 DELETE dbo.ACA_FACULTADES_SEDES WHERE CORR_FACULTAD=@FACULTAD;
 DELETE dbo.ACA_FACULTADES WHERE CORR_FACULTAD=@FACULTAD AND CORR_EMPRESA=@EMPRESA;
 END;
 IF @OPERACION LIKE 'SEDE%'
 BEGIN
 IF NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WITH(UPDLOCK,HOLDLOCK) WHERE CORR_SEDE=@SEDE AND CORR_EMPRESA=@EMPRESA) THROW 51000,N'La sede no pertenece a la empresa.',1;
 IF @OPERACION<>'SEDE_CREAR' AND NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES_SEDES WITH(UPDLOCK,HOLDLOCK) WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE) THROW 51000,N'La autorización por sede no existe.',1;
 IF @ACTIVO=1 AND @OPERACION<>'SEDE_ELIMINAR' AND (@anterior=0 OR NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WHERE CORR_SEDE=@SEDE AND ESTADO_SEDE='A')) THROW 51000,N'Para autorizar la sede, la facultad y la sede deben estar activas.',1;
 IF @OPERACION='SEDE_ELIMINAR' AND (EXISTS(SELECT 1 FROM dbo.ACA_CICLOS_FACULTADES_SEDES WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE) OR EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE) OR EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS_BITACORA WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE) OR EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS C JOIN dbo.ACA_CARRERAS_SEDES S ON S.CORR_CARRERA=C.CORR_CARRERA WHERE C.CORR_FACULTAD=@FACULTAD AND S.CORR_SEDE=@SEDE)) THROW 51000,N'La autorización tiene carreras, ciclos o historial. Utilice desactivación.',1;
 IF @ACTIVO=0 AND @OPERACION='SEDE_GUARDAR' AND EXISTS(SELECT 1 FROM dbo.ACA_CICLOS_CARRERAS_SEDES R WITH(UPDLOCK,HOLDLOCK) JOIN dbo.ACA_CICLOS_ACADEMICOS H WITH(UPDLOCK,HOLDLOCK) ON H.CORR_CICLO_ACADEMICO=R.CORR_CICLO_ACADEMICO JOIN dbo.ACA_CICLOS_SEDES S ON S.CORR_CICLO_ACADEMICO=R.CORR_CICLO_ACADEMICO AND S.CORR_SEDE=R.CORR_SEDE JOIN dbo.ACA_CICLOS_FACULTADES_SEDES F ON F.CORR_CICLO_ACADEMICO=R.CORR_CICLO_ACADEMICO AND F.CORR_SEDE=R.CORR_SEDE AND F.CORR_FACULTAD=R.CORR_FACULTAD WHERE R.CORR_FACULTAD=@FACULTAD AND R.CORR_SEDE=@SEDE AND R.ACTIVO=1 AND F.ACTIVO=1 AND S.ACTIVO=1 AND H.ESTADO='HABILITADO') THROW 51000,N'Esta sede tiene carreras en ciclos habilitados. Pase el ciclo a borrador y retire su oferta antes de desautorizarla.',1;
 IF @OPERACION='SEDE_CREAR'
 BEGIN
 IF EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES_SEDES WITH(UPDLOCK,HOLDLOCK) WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE) THROW 51000,N'La sede ya está asignada a esta facultad.',1;
 INSERT dbo.ACA_FACULTADES_SEDES(CORR_FACULTAD,CORR_SEDE,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@FACULTAD,@SEDE,@ACTIVO,@USUARIO,@ESTACION,GETDATE());
 END;
 IF @OPERACION='SEDE_GUARDAR' UPDATE dbo.ACA_FACULTADES_SEDES SET ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE;
 IF @OPERACION='SEDE_ELIMINAR' DELETE dbo.ACA_FACULTADES_SEDES WHERE CORR_FACULTAD=@FACULTAD AND CORR_SEDE=@SEDE;
 END;
 DECLARE @datos nvarchar(max)=(SELECT @FACULTAD FACULTAD,@SEDE SEDE,@DECANO DECANO,@NOMBRE NOMBRE,@ACTIVO ACTIVO FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
 INSERT dbo.ACA_CONFIGURACION_BITACORA(ENTIDAD,ID_REGISTRO,CORR_EMPRESA,OPERACION,USUARIO,ESTACION,DATOS) VALUES('FACULTAD',@FACULTAD,@EMPRESA,@OPERACION,@USUARIO,@ESTACION,@datos);
 COMMIT;
 END TRY
 BEGIN CATCH IF XACT_STATE()<>0 ROLLBACK;THROW;END CATCH;
END;
GO


