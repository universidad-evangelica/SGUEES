CREATE OR ALTER VIEW dbo.V_ACA_FACULTADES
AS
SELECT F.CORR_FACULTAD,
       F.CORR_EMPRESA, F.CORR_DECANO, E.NOMBRE_EMPLEADO AS NOMBRE_DECANO,
       F.CODIGO_FACULTAD,
       F.NOMBRE_FACULTAD,
       F.ACTIVO,
       F.USUARIO_CREA,
       F.ESTACION_CREA,
       F.FECHA_CREA,
       F.USUARIO_ACTU,
       F.ESTACION_ACTU,
       F.FECHA_ACTU,
       (SELECT COUNT(*) FROM dbo.ACA_CARRERAS C
         WHERE C.CORR_FACULTAD = F.CORR_FACULTAD AND C.CORR_EMPRESA = F.CORR_EMPRESA AND C.ACTIVO = 1) AS CARRERAS_ACTIVAS,
       (SELECT COUNT(*) FROM dbo.ACA_CARRERAS C
         WHERE C.CORR_FACULTAD = F.CORR_FACULTAD AND C.CORR_EMPRESA = F.CORR_EMPRESA)                  AS CARRERAS,
       (SELECT COUNT(*) FROM dbo.ACA_PERIODOS_ACADEMICOS P
         WHERE P.CORR_FACULTAD = F.CORR_FACULTAD)                                                      AS PERIODOS,
       CAST(ISNULL(STUFF((SELECT ', ' + G.NOMBRE_SEDE
                          FROM dbo.ACA_FACULTADES_SEDES S
                          INNER JOIN dbo.GEN_SEDES G ON G.CORR_SEDE = S.CORR_SEDE
                          WHERE S.CORR_FACULTAD = F.CORR_FACULTAD AND S.ACTIVO = 1
                          ORDER BY G.NOMBRE_SEDE
                          FOR XML PATH(''), TYPE).value('.', 'varchar(500)'), 1, 2, ''), '') AS varchar(500)) AS SEDES
FROM dbo.ACA_FACULTADES F LEFT JOIN dbo.V_GEN_EMPLEADO E ON E.CORR_EMPRESA=F.CORR_EMPRESA AND E.CORR_EMPLEADO=F.CORR_DECANO;

GO
CREATE OR ALTER VIEW dbo.V_ACA_CARRERAS
AS
SELECT C.*, A.NOMBRE_AREA, F.NOMBRE_FACULTAD, G.NOMBRE_GRADO, F.CORR_DECANO,
    D.NOMBRE_EMPLEADO AS NOMBRE_DECANO,
    COALESCE(STUFF((
        SELECT N', ' + S.NOMBRE_SEDE
        FROM dbo.ACA_CARRERAS_SEDES CS
        JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=CS.CORR_SEDE AND S.CORR_EMPRESA=C.CORR_EMPRESA
        WHERE CS.CORR_CARRERA=C.CORR_CARRERA AND CS.ACTIVO=1 AND S.ESTADO_SEDE='A'
        ORDER BY S.NOMBRE_SEDE, S.CORR_SEDE
        FOR XML PATH(''), TYPE
    ).value('.', 'nvarchar(max)'), 1, 2, N''), N'Sin sedes activas') AS SEDES_ACTIVAS
FROM dbo.ACA_CARRERAS C
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=C.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
LEFT JOIN dbo.ACA_GRADOS_ACADEMICOS G ON G.CORR_GRADO_ACADEMICO=C.CORR_GRADO_ACADEMICO AND G.CORR_EMPRESA=C.CORR_EMPRESA
LEFT JOIN dbo.V_GEN_EMPLEADO D ON D.CORR_EMPRESA=C.CORR_EMPRESA AND D.CORR_EMPLEADO=F.CORR_DECANO;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_CARRERAS
    @TIPO_ACTUALIZA int, -- 1 alta, 2 edición, 3 eliminación, 4 estado
    @CORR_EMPRESA int,
    @CORR_CARRERA int OUTPUT,
    @CORR_AREA_ACADEMICA int = NULL,
    @CORR_FACULTAD int = NULL,
    @CORR_GRADO_ACADEMICO int = NULL,
    @CODIGO_CARRERA varchar(30) = NULL,
    @NOMBRE_CARRERA varchar(250) = NULL,
    @MAX_REPETICIONES smallint=3,
    @CREDITOS_REQUERIDOS decimal(7,2)=NULL,
    @NOTA_MINIMA decimal(4,2)=NULL,
    @SYS_LOGIN_USUARIO varchar(50),
    @SYS_ESTACION varchar(100),
    @SYS_NUMERO_ERROR int OUTPUT,
    @SYS_MENSAJE_ERROR nvarchar(4000) OUTPUT,
    @SYS_FILAS_AFECTADAS int OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SELECT @SYS_NUMERO_ERROR=0, @SYS_MENSAJE_ERROR=N'', @SYS_FILAS_AFECTADAS=0;
    DECLARE @TRAN_INICIAL int=@@TRANCOUNT;
    BEGIN TRY
        IF ISNULL(@CORR_EMPRESA,0)<=0 THROW 51000, N'No se encontró la empresa de la sesión.', 1;
        IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) OR @TIPO_ACTUALIZA IS NULL
            THROW 51000, N'Operación no válida.', 1;
        IF NULLIF(LTRIM(RTRIM(@SYS_LOGIN_USUARIO)),'') IS NULL
            THROW 51000, N'No se encontró el usuario de la sesión.', 1;
        IF @TRAN_INICIAL=0 BEGIN TRANSACTION;
        ELSE SAVE TRANSACTION ACA_CARRERAS_MTTO;
        DECLARE @AREA_ANTERIOR int, @FACULTAD_ANTERIOR int, @GRADO_ANTERIOR int, @ACTIVO_ANTERIOR bit;
        IF @TIPO_ACTUALIZA<>1
        BEGIN
            SELECT @AREA_ANTERIOR=CORR_AREA_ACADEMICA, @FACULTAD_ANTERIOR=CORR_FACULTAD,
                   @GRADO_ANTERIOR=CORR_GRADO_ACADEMICO, @ACTIVO_ANTERIOR=ACTIVO
            FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            IF @AREA_ANTERIOR IS NULL THROW 51000, N'La carrera no existe en la empresa de la sesión.', 1;
        END;
        IF @TIPO_ACTUALIZA IN (1,2)
        BEGIN
            IF @MAX_REPETICIONES IS NULL OR @MAX_REPETICIONES NOT BETWEEN 0 AND 99 THROW 51000,N'Las repeticiones adicionales deben estar entre 0 y 99.',1;
            IF (@CREDITOS_REQUERIDOS IS NOT NULL AND @CREDITOS_REQUERIDOS<=0) OR (@TIPO_ACTUALIZA=1 AND @CREDITOS_REQUERIDOS IS NULL) THROW 51000,N'Indique los créditos requeridos para completar la carrera.',1;
            IF (@NOTA_MINIMA IS NOT NULL AND @NOTA_MINIMA NOT BETWEEN 0 AND 10) OR (@TIPO_ACTUALIZA=1 AND @NOTA_MINIMA IS NULL) THROW 51000,N'La nota mínima de materia debe estar entre 0 y 10.',1;
            SELECT @CODIGO_CARRERA=LTRIM(RTRIM(@CODIGO_CARRERA)), @NOMBRE_CARRERA=LTRIM(RTRIM(@NOMBRE_CARRERA));
            IF NULLIF(@CODIGO_CARRERA,'') IS NULL OR NULLIF(@NOMBRE_CARRERA,'') IS NULL
                THROW 51000, N'El código y el nombre de la carrera son obligatorios.', 1;
            -- Una referencia inactiva ya asignada puede conservarse al corregir texto.
            IF NOT EXISTS (SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WITH (HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA
                AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @AREA_ANTERIOR=@CORR_AREA_ACADEMICA)))
                THROW 51000, N'Seleccione un área académica activa de la empresa.', 1;
            IF NOT EXISTS (SELECT 1 FROM dbo.ACA_FACULTADES WITH (HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FACULTAD=@CORR_FACULTAD
                AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @FACULTAD_ANTERIOR=@CORR_FACULTAD)))
                THROW 51000, N'Seleccione una facultad activa de la empresa.', 1;
            IF @CORR_GRADO_ACADEMICO IS NOT NULL AND NOT EXISTS
                (SELECT 1 FROM dbo.ACA_GRADOS_ACADEMICOS WITH (HOLDLOCK)
                 WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_GRADO_ACADEMICO=@CORR_GRADO_ACADEMICO
                 AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @GRADO_ANTERIOR=@CORR_GRADO_ACADEMICO)))
                THROW 51000, N'Seleccione un grado académico activo de la empresa.', 1;
            IF EXISTS (SELECT 1 FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CODIGO_CARRERA=@CODIGO_CARRERA
                AND (@TIPO_ACTUALIZA=1 OR CORR_CARRERA<>@CORR_CARRERA))
                THROW 51000, N'Ya existe una carrera con ese código en la empresa.', 1;
            IF @TIPO_ACTUALIZA=2 AND (@AREA_ANTERIOR<>@CORR_AREA_ACADEMICA OR @FACULTAD_ANTERIOR<>@CORR_FACULTAD)
               AND (EXISTS (SELECT 1 FROM dbo.ACA_CARRERAS_SEDES WHERE CORR_CARRERA=@CORR_CARRERA)
                 OR EXISTS (SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS WHERE CORR_CARRERA=@CORR_CARRERA)
                 OR EXISTS (SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_CARRERA=@CORR_CARRERA))
                THROW 51000, N'No se puede cambiar área o facultad: revise primero las sedes, planes y períodos relacionados.', 1;
        END;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            INSERT dbo.ACA_CARRERAS
                (CORR_EMPRESA,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_GRADO_ACADEMICO,CODIGO_CARRERA,NOMBRE_CARRERA,ACTIVO,
                 MAX_REPETICIONES,CREDITOS_REQUERIDOS,NOTA_MINIMA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
            VALUES (@CORR_EMPRESA,@CORR_AREA_ACADEMICA,@CORR_FACULTAD,@CORR_GRADO_ACADEMICO,@CODIGO_CARRERA,@NOMBRE_CARRERA,1,
                    @MAX_REPETICIONES,@CREDITOS_REQUERIDOS,@NOTA_MINIMA,@SYS_LOGIN_USUARIO,@SYS_ESTACION,GETDATE());
            SET @CORR_CARRERA=CONVERT(int,SCOPE_IDENTITY());
            SET @SYS_FILAS_AFECTADAS=1;
        END;
        IF @TIPO_ACTUALIZA=2
        BEGIN
            UPDATE dbo.ACA_CARRERAS SET CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA, CORR_FACULTAD=@CORR_FACULTAD,
                CORR_GRADO_ACADEMICO=@CORR_GRADO_ACADEMICO,CODIGO_CARRERA=@CODIGO_CARRERA,NOMBRE_CARRERA=@NOMBRE_CARRERA,
                MAX_REPETICIONES=@MAX_REPETICIONES,CREDITOS_REQUERIDOS=@CREDITOS_REQUERIDOS,NOTA_MINIMA=@NOTA_MINIMA,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END;
        IF @TIPO_ACTUALIZA=3
        BEGIN
            DELETE dbo.ACA_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END;
        IF @TIPO_ACTUALIZA=4
        BEGIN
            IF @ACTIVO_ANTERIOR=1 AND EXISTS(SELECT 1 FROM dbo.ACA_CICLOS_CARRERAS_SEDES R JOIN dbo.ACA_CICLOS_ACADEMICOS H ON H.CORR_CICLO_ACADEMICO=R.CORR_CICLO_ACADEMICO WHERE R.CORR_CARRERA=@CORR_CARRERA AND R.ACTIVO=1 AND H.ESTADO='HABILITADO') THROW 51000,N'La carrera está seleccionada en ciclos habilitados. Retire su oferta antes de desactivarla.',1;
            IF @ACTIVO_ANTERIOR=0 AND
                (NOT EXISTS (SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WITH (HOLDLOCK) WHERE CORR_AREA_ACADEMICA=@AREA_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                 OR NOT EXISTS (SELECT 1 FROM dbo.ACA_FACULTADES WITH (HOLDLOCK) WHERE CORR_FACULTAD=@FACULTAD_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                 OR (@GRADO_ANTERIOR IS NOT NULL AND NOT EXISTS (SELECT 1 FROM dbo.ACA_GRADOS_ACADEMICOS WITH (HOLDLOCK) WHERE CORR_GRADO_ACADEMICO=@GRADO_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)))
                THROW 51000, N'Para activar la carrera, su área, facultad y grado asignado deben estar activos.', 1;
            EXEC dbo.PRAL_MTTO_CATALOGO_ESTADO_BIT
                @NOMBRE_TABLA='ACA_CARRERAS',@CAMPO_PK='CORR_CARRERA',@CAMPO_ESTADO='ACTIVO',@USA_EMPRESA=1,
                @CORR_EMPRESA=@CORR_EMPRESA,@CORR_RELATIVO=@CORR_CARRERA,
                @SYS_LOGIN_USUARIO=@SYS_LOGIN_USUARIO,@SYS_ESTACION=@SYS_ESTACION,
                @SYS_NUMERO_ERROR=@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR=@SYS_MENSAJE_ERROR OUTPUT,
                @SYS_FILAS_AFECTADAS=@SYS_FILAS_AFECTADAS OUTPUT;
            IF @SYS_NUMERO_ERROR<>0 THROW 51000, @SYS_MENSAJE_ERROR, 1;
        END;
        IF @TIPO_ACTUALIZA IN(1,2) AND OBJECT_ID('dbo.ACA_CONFIGURACION_BITACORA') IS NOT NULL
        BEGIN
            DECLARE @datosConfig nvarchar(max)=(SELECT * FROM dbo.ACA_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
            INSERT dbo.ACA_CONFIGURACION_BITACORA(ENTIDAD,ID_REGISTRO,CORR_EMPRESA,OPERACION,USUARIO,ESTACION,DATOS) VALUES('CARRERA',@CORR_CARRERA,@CORR_EMPRESA,CASE WHEN @TIPO_ACTUALIZA=1 THEN 'CREAR' ELSE 'GUARDAR' END,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@datosConfig);
        END;
        IF @TRAN_INICIAL=0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @TRAN_INICIAL=0 AND XACT_STATE()<>0 ROLLBACK TRANSACTION;
        ELSE IF @TRAN_INICIAL>0 AND XACT_STATE()=1 ROLLBACK TRANSACTION ACA_CARRERAS_MTTO;
        SELECT @SYS_NUMERO_ERROR=ERROR_NUMBER(),@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),@SYS_FILAS_AFECTADAS=0;
        IF @SYS_NUMERO_ERROR IN (2601,2627) SET @SYS_MENSAJE_ERROR=N'Ya existe una carrera con ese código en la empresa.';
        IF @SYS_NUMERO_ERROR=547 SET @SYS_MENSAJE_ERROR=N'No se puede eliminar la carrera porque tiene registros relacionados. Utilice Desactivar.';
    END CATCH;
END;
GO
CREATE OR ALTER PROCEDURE dbo.PR_ACA_CARRERA_COSTO_GUARDAR
 @EMPRESA int,@ID int OUTPUT,@DATOS nvarchar(max),@VERSION varbinary(8)=NULL,@USUARIO varchar(50),@ESTACION varchar(100)
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 DECLARE @CORR_CARRERA int=CONVERT(int,JSON_VALUE(@DATOS,'$.CORR_CARRERA'));
DECLARE @CORR_SEDE int=CONVERT(int,JSON_VALUE(@DATOS,'$.CORR_SEDE'));
DECLARE @CORR_MONEDA int=CONVERT(int,JSON_VALUE(@DATOS,'$.CORR_MONEDA'));
DECLARE @FECHA_INICIO date=CONVERT(date,JSON_VALUE(@DATOS,'$.FECHA_INICIO'));
DECLARE @FECHA_FIN date=CONVERT(date,JSON_VALUE(@DATOS,'$.FECHA_FIN'));
DECLARE @MATRICULA_NACIONAL decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.MATRICULA_NACIONAL'));
DECLARE @MATRICULA_EXTRANJERA decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.MATRICULA_EXTRANJERA'));
DECLARE @INSCRIPCION decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.INSCRIPCION'));
DECLARE @INSCRIPCION_TUTORIA decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.INSCRIPCION_TUTORIA'));
DECLARE @COSTO_CARNE decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.COSTO_CARNE'));
DECLARE @COBRA_DIFERENCIA_INSCRIPCION bit=CONVERT(bit,JSON_VALUE(@DATOS,'$.COBRA_DIFERENCIA_INSCRIPCION'));
DECLARE @TIPO_IMPUESTO varchar(10)=CONVERT(varchar(10),JSON_VALUE(@DATOS,'$.TIPO_IMPUESTO'));
DECLARE @REFERENCIA_FINANCIAMIENTO varchar(20)=CONVERT(varchar(20),JSON_VALUE(@DATOS,'$.REFERENCIA_FINANCIAMIENTO'));
DECLARE @MONTO_FINANCIAMIENTO decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.MONTO_FINANCIAMIENTO'));
DECLARE @PORCENTAJE_RECUPERACION decimal(5,2)=CONVERT(decimal(5,2),JSON_VALUE(@DATOS,'$.PORCENTAJE_RECUPERACION'));
DECLARE @CARGO_CAMBIO_ASIGNATURA decimal(12,2)=CONVERT(decimal(12,2),JSON_VALUE(@DATOS,'$.CARGO_CAMBIO_ASIGNATURA'));
DECLARE @POLITICA_CARGO varchar(10)=CONVERT(varchar(10),JSON_VALUE(@DATOS,'$.POLITICA_CARGO'));
DECLARE @MODALIDAD_PAGO varchar(10)=CONVERT(varchar(10),JSON_VALUE(@DATOS,'$.MODALIDAD_PAGO'));
DECLARE @TIPO_COBRO_ASIGNATURA varchar(10)=CONVERT(varchar(10),JSON_VALUE(@DATOS,'$.TIPO_COBRO_ASIGNATURA'));
DECLARE @ACTIVO bit=CONVERT(bit,JSON_VALUE(@DATOS,'$.ACTIVO'));
 BEGIN TRY
 BEGIN TRANSACTION;
 IF @EMPRESA<=0 OR NULLIF(@USUARIO,'') IS NULL OR @CORR_CARRERA IS NULL OR @CORR_SEDE IS NULL THROW 51000,N'Sesión o carrera/sede inválida.',1;
 IF @FECHA_INICIO IS NULL OR @FECHA_FIN<@FECHA_INICIO THROW 51000,N'Revise las fechas de vigencia.',1;
 DECLARE @anterior varbinary(8),@oldCarrera int,@oldSede int;
 IF @ID>0
 BEGIN
 SELECT @anterior=VERSION,@oldCarrera=CORR_CARRERA,@oldSede=CORR_SEDE FROM dbo.ACA_CARRERAS_COSTOS WITH(UPDLOCK,HOLDLOCK) WHERE CORR_COSTO=@ID AND CORR_EMPRESA=@EMPRESA;
 IF @anterior IS NULL OR @VERSION IS NULL OR @anterior<>@VERSION THROW 51000,N'El costo cambió o no existe. Actualice la lista y vuelva a abrirlo.',1;
 IF @oldCarrera<>@CORR_CARRERA OR @oldSede<>@CORR_SEDE THROW 51000,N'La carrera y la sede del costo no se pueden cambiar; cree otra vigencia.',1;
 END;
 IF NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS C WITH(UPDLOCK,HOLDLOCK) JOIN dbo.ACA_CARRERAS_SEDES CS WITH(UPDLOCK,HOLDLOCK) ON CS.CORR_CARRERA=C.CORR_CARRERA AND CS.CORR_SEDE=@CORR_SEDE
 JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
 JOIN dbo.ACA_FACULTADES_SEDES FS WITH(UPDLOCK,HOLDLOCK) ON FS.CORR_FACULTAD=C.CORR_FACULTAD AND FS.CORR_SEDE=CS.CORR_SEDE
 JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=CS.CORR_SEDE AND S.CORR_EMPRESA=C.CORR_EMPRESA
 WHERE C.CORR_EMPRESA=@EMPRESA AND C.CORR_CARRERA=@CORR_CARRERA AND (@ACTIVO=0 OR (C.ACTIVO=1 AND CS.ACTIVO=1 AND F.ACTIVO=1 AND FS.ACTIVO=1 AND S.ESTADO_SEDE='A')))
 THROW 51000,N'La carrera no tiene autorización activa en la sede seleccionada. Revise Carreras y Facultades.',1;
 IF NOT EXISTS(SELECT 1 FROM dbo.GEN_TIPO_MONEDA WHERE CORR_MONEDA=@CORR_MONEDA AND (@ACTIVO=0 OR ESTADO_MONEDA=1)) THROW 51000,N'Seleccione una moneda activa.',1;
 IF @ACTIVO=1 AND EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS_COSTOS WITH(UPDLOCK,HOLDLOCK,INDEX(IX_COSTOS_VIGENCIA)) WHERE CORR_EMPRESA=@EMPRESA AND CORR_CARRERA=@CORR_CARRERA AND CORR_SEDE=@CORR_SEDE AND ACTIVO=1 AND CORR_COSTO<>@ID
 AND FECHA_INICIO<=ISNULL(@FECHA_FIN,CONVERT(date,'99991231')) AND ISNULL(FECHA_FIN,CONVERT(date,'99991231'))>=@FECHA_INICIO) THROW 51000,N'Ya existe un costo activo que se cruza con estas fechas para la carrera y sede. Finalice la vigencia anterior o ajuste las fechas.',1;
 IF @ID=0
 BEGIN
 INSERT dbo.ACA_CARRERAS_COSTOS(CORR_EMPRESA,CORR_CARRERA,CORR_SEDE,CORR_MONEDA,FECHA_INICIO,FECHA_FIN,MATRICULA_NACIONAL,MATRICULA_EXTRANJERA,INSCRIPCION,INSCRIPCION_TUTORIA,COSTO_CARNE,COBRA_DIFERENCIA_INSCRIPCION,TIPO_IMPUESTO,REFERENCIA_FINANCIAMIENTO,MONTO_FINANCIAMIENTO,PORCENTAJE_RECUPERACION,CARGO_CAMBIO_ASIGNATURA,POLITICA_CARGO,MODALIDAD_PAGO,TIPO_COBRO_ASIGNATURA,ACTIVO,USUARIO_CREA,ESTACION_CREA) VALUES(@EMPRESA,@CORR_CARRERA,@CORR_SEDE,@CORR_MONEDA,@FECHA_INICIO,@FECHA_FIN,@MATRICULA_NACIONAL,@MATRICULA_EXTRANJERA,@INSCRIPCION,@INSCRIPCION_TUTORIA,@COSTO_CARNE,@COBRA_DIFERENCIA_INSCRIPCION,@TIPO_IMPUESTO,@REFERENCIA_FINANCIAMIENTO,@MONTO_FINANCIAMIENTO,@PORCENTAJE_RECUPERACION,@CARGO_CAMBIO_ASIGNATURA,@POLITICA_CARGO,@MODALIDAD_PAGO,@TIPO_COBRO_ASIGNATURA,@ACTIVO,@USUARIO,@ESTACION);
 SET @ID=SCOPE_IDENTITY();
 END
 ELSE UPDATE dbo.ACA_CARRERAS_COSTOS SET CORR_MONEDA=@CORR_MONEDA,FECHA_INICIO=@FECHA_INICIO,FECHA_FIN=@FECHA_FIN,MATRICULA_NACIONAL=@MATRICULA_NACIONAL,MATRICULA_EXTRANJERA=@MATRICULA_EXTRANJERA,INSCRIPCION=@INSCRIPCION,INSCRIPCION_TUTORIA=@INSCRIPCION_TUTORIA,COSTO_CARNE=@COSTO_CARNE,COBRA_DIFERENCIA_INSCRIPCION=@COBRA_DIFERENCIA_INSCRIPCION,TIPO_IMPUESTO=@TIPO_IMPUESTO,REFERENCIA_FINANCIAMIENTO=@REFERENCIA_FINANCIAMIENTO,MONTO_FINANCIAMIENTO=@MONTO_FINANCIAMIENTO,PORCENTAJE_RECUPERACION=@PORCENTAJE_RECUPERACION,CARGO_CAMBIO_ASIGNATURA=@CARGO_CAMBIO_ASIGNATURA,POLITICA_CARGO=@POLITICA_CARGO,MODALIDAD_PAGO=@MODALIDAD_PAGO,TIPO_COBRO_ASIGNATURA=@TIPO_COBRO_ASIGNATURA,ACTIVO=@ACTIVO,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME() WHERE CORR_COSTO=@ID AND CORR_EMPRESA=@EMPRESA;
 DECLARE @snapshot nvarchar(max)=(SELECT * FROM dbo.ACA_CARRERAS_COSTOS WHERE CORR_COSTO=@ID AND CORR_EMPRESA=@EMPRESA FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
 INSERT dbo.ACA_CONFIGURACION_BITACORA(ENTIDAD,ID_REGISTRO,CORR_EMPRESA,OPERACION,USUARIO,ESTACION,DATOS) VALUES('COSTO_CARRERA',@ID,@EMPRESA,'GUARDAR',@USUARIO,@ESTACION,@snapshot);
 COMMIT;
 END TRY BEGIN CATCH IF XACT_STATE()<>0 ROLLBACK;THROW;END CATCH;
END;
GO
