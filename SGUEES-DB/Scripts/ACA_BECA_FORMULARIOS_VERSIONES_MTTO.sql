CREATE OR ALTER VIEW dbo.V_ACA_BECA_VERSION_MTTO
AS
SELECT V.CORR_EMPRESA,V.CORR_FORMULARIO_VERSION,V.CORR_FORMULARIO_BECA,F.NOMBRE_FORMULARIO,
 V.VERSION_FORMULARIO,V.FECHA_INICIO,V.FECHA_FIN,V.ACTIVO,V.ESTADO_VERSION,V.VERSION_REGISTRO,
 (SELECT COUNT(*) FROM dbo.ACA_PROSPECTO_BECA_SECCION S WHERE S.CORR_FORMULARIO_VERSION=V.CORR_FORMULARIO_VERSION AND S.CORR_EMPRESA=V.CORR_EMPRESA AND S.ACTIVO=1) CANT_SECCIONES,
 (SELECT COUNT(*) FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
  WHERE S.CORR_FORMULARIO_VERSION=V.CORR_FORMULARIO_VERSION AND S.CORR_EMPRESA=V.CORR_EMPRESA AND P.CORR_EMPRESA=V.CORR_EMPRESA AND S.ACTIVO=1 AND P.ACTIVO=1) CANT_PREGUNTAS,
 (SELECT COUNT(*) FROM dbo.ACA_PROSPECTO_BECA B WHERE B.CORR_FORMULARIO_VERSION=V.CORR_FORMULARIO_VERSION AND B.CORR_EMPRESA=V.CORR_EMPRESA) CANT_SOLICITUDES
FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION V JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO F
 ON F.CORR_EMPRESA=V.CORR_EMPRESA AND F.CORR_FORMULARIO_BECA=V.CORR_FORMULARIO_BECA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_ASIGNACION_MTTO
AS SELECT A.CORR_EMPRESA,A.CORR_TIPO_FORMULARIO,A.CORR_BECA,A.CORR_FORMULARIO_VERSION,V.CORR_FORMULARIO_BECA,F.NOMBRE_FORMULARIO,
 V.VERSION_FORMULARIO,V.ESTADO_VERSION,V.FECHA_INICIO,V.FECHA_FIN,A.ANIO_ADMISION,A.NUMERO_PERIODO_ADMISION,A.ACTIVO,A.VERSION_REGISTRO
FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO A
JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION V ON V.CORR_EMPRESA=A.CORR_EMPRESA AND V.CORR_FORMULARIO_VERSION=A.CORR_FORMULARIO_VERSION
JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO F ON F.CORR_EMPRESA=V.CORR_EMPRESA AND F.CORR_FORMULARIO_BECA=V.CORR_FORMULARIO_BECA;
GO
CREATE OR ALTER FUNCTION dbo.ACA_FN_BECA_VERSION_DISPONIBLE(@Beca int,@Empresa int,@Anio int,@Numero int,@Fecha date)
RETURNS TABLE AS RETURN
 SELECT TOP(1) A.CORR_FORMULARIO_VERSION
 FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO A
 JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION V ON V.CORR_FORMULARIO_VERSION=A.CORR_FORMULARIO_VERSION AND V.CORR_EMPRESA=A.CORR_EMPRESA
 JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO F ON F.CORR_FORMULARIO_BECA=V.CORR_FORMULARIO_BECA AND F.CORR_EMPRESA=V.CORR_EMPRESA
 WHERE A.CORR_EMPRESA=@Empresa AND A.CORR_BECA=@Beca AND A.ACTIVO=1 AND V.ACTIVO=1 AND V.ESTADO_VERSION='PUBLICADA' AND F.ACTIVO=1
  AND V.FECHA_INICIO<=@Fecha AND (V.FECHA_FIN IS NULL OR V.FECHA_FIN>=@Fecha)
  AND ((A.ANIO_ADMISION=@Anio AND A.NUMERO_PERIODO_ADMISION=@Numero) OR A.ANIO_ADMISION IS NULL)
 ORDER BY CASE WHEN A.ANIO_ADMISION IS NOT NULL THEN 0 ELSE 1 END,V.FECHA_INICIO DESC,A.CORR_TIPO_FORMULARIO DESC;
GO
CREATE OR ALTER PROCEDURE dbo.ACA_SP_BECA_VERSION_CLONAR
 @Empresa int,@Origen int,@Destino int,@BecaPlantilla int,@Beca int,@Usuario varchar(100),@Estacion varchar(50)
AS
BEGIN
 SET NOCOUNT ON;
 IF @@TRANCOUNT=0 THROW 51000,N'La clonacion requiere la transaccion del mantenimiento.',1;
 DECLARE @Secciones TABLE(Anterior int PRIMARY KEY,Nuevo int NOT NULL);
 DECLARE @Preguntas TABLE(Anterior int PRIMARY KEY,Nuevo int NOT NULL);
 DECLARE @Opciones TABLE(Anterior int PRIMARY KEY,Nuevo int NOT NULL);
 DECLARE @Anterior int,@Nuevo int;

 SET @Anterior=0;
 WHILE 1=1
 BEGIN
  SELECT @Anterior=MIN(X.CORR_SECCION_BECA) FROM dbo.ACA_PROSPECTO_BECA_SECCION X WHERE X.CORR_EMPRESA=@Empresa AND X.CORR_SECCION_BECA>@Anterior AND X.CORR_FORMULARIO_VERSION=@Origen AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT ON PT.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA WHERE P.CORR_SECCION_BECA=X.CORR_SECCION_BECA AND PT.CORR_BECA=@BecaPlantilla AND PT.CORR_EMPRESA=@Empresa AND PT.ACTIVO=1);
  IF @Anterior IS NULL BREAK;
  INSERT dbo.ACA_PROSPECTO_BECA_SECCION(CORR_FORMULARIO_VERSION,NOMBRE_SECCION,DESCRIPCION,ORDEN,PUNTAJE_MAXIMO,PORCENTAJE_SECCION,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) SELECT @Destino,X.NOMBRE_SECCION,X.DESCRIPCION,X.ORDEN,X.PUNTAJE_MAXIMO,X.PORCENTAJE_SECCION,X.ACTIVO,X.CORR_EMPRESA,@Usuario,@Estacion,GETDATE() FROM dbo.ACA_PROSPECTO_BECA_SECCION X WHERE X.CORR_SECCION_BECA=@Anterior AND X.CORR_EMPRESA=@Empresa;
  SET @Nuevo=CONVERT(int,SCOPE_IDENTITY()); INSERT @Secciones(Anterior,Nuevo) VALUES(@Anterior,@Nuevo);
 END;

 SET @Anterior=0;
 WHILE 1=1
 BEGIN
  SELECT @Anterior=MIN(X.CORR_PREGUNTA_BECA) FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA X WHERE X.CORR_EMPRESA=@Empresa AND X.CORR_PREGUNTA_BECA>@Anterior AND EXISTS(SELECT 1 FROM @Secciones M WHERE M.Anterior=X.CORR_SECCION_BECA) AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT WHERE PT.CORR_PREGUNTA_BECA=X.CORR_PREGUNTA_BECA AND PT.CORR_BECA=@BecaPlantilla AND PT.CORR_EMPRESA=@Empresa AND PT.ACTIVO=1);
  IF @Anterior IS NULL BREAK;
  INSERT dbo.ACA_PROSPECTO_BECA_PREGUNTA(CORR_SECCION_BECA,CODIGO_PREGUNTA,TEXTO_PREGUNTA,AYUDA,TIPO_RESPUESTA,REQUERIDO,ORDEN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) SELECT (SELECT Nuevo FROM @Secciones WHERE Anterior=X.CORR_SECCION_BECA),X.CODIGO_PREGUNTA,X.TEXTO_PREGUNTA,X.AYUDA,X.TIPO_RESPUESTA,X.REQUERIDO,X.ORDEN,X.ACTIVO,X.CORR_EMPRESA,@Usuario,@Estacion,GETDATE() FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA X WHERE X.CORR_PREGUNTA_BECA=@Anterior AND X.CORR_EMPRESA=@Empresa;
  SET @Nuevo=CONVERT(int,SCOPE_IDENTITY()); INSERT @Preguntas(Anterior,Nuevo) VALUES(@Anterior,@Nuevo);
 END;

 SET @Anterior=0;
 WHILE 1=1
 BEGIN
  SELECT @Anterior=MIN(X.CORR_OPCION_BECA) FROM dbo.ACA_PROSPECTO_BECA_OPCION X WHERE X.CORR_EMPRESA=@Empresa AND X.CORR_OPCION_BECA>@Anterior AND EXISTS(SELECT 1 FROM @Preguntas M WHERE M.Anterior=X.CORR_PREGUNTA_BECA);
  IF @Anterior IS NULL BREAK;
  INSERT dbo.ACA_PROSPECTO_BECA_OPCION(CORR_PREGUNTA_BECA,TEXTO_OPCION,ORDEN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) SELECT (SELECT Nuevo FROM @Preguntas WHERE Anterior=X.CORR_PREGUNTA_BECA),X.TEXTO_OPCION,X.ORDEN,X.ACTIVO,X.CORR_EMPRESA,@Usuario,@Estacion,GETDATE() FROM dbo.ACA_PROSPECTO_BECA_OPCION X WHERE X.CORR_OPCION_BECA=@Anterior AND X.CORR_EMPRESA=@Empresa;
  SET @Nuevo=CONVERT(int,SCOPE_IDENTITY()); INSERT @Opciones(Anterior,Nuevo) VALUES(@Anterior,@Nuevo);
 END;

 IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D JOIN @Preguntas H ON H.Anterior=D.CORR_PREGUNTA_HIJA
  WHERE D.CORR_EMPRESA=@Empresa AND D.ACTIVO=1 AND (NOT EXISTS(SELECT 1 FROM @Preguntas P WHERE P.Anterior=D.CORR_PREGUNTA_PADRE)
   OR NOT EXISTS(SELECT 1 FROM @Opciones O WHERE O.Anterior=D.CORR_OPCION_PADRE)))
  THROW 51000,N'La plantilla tiene dependencias fuera de las preguntas de esa beca.',1;
 INSERT dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO(CORR_PREGUNTA_BECA,CORR_BECA,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
 SELECT M.Nuevo,@Beca,PT.ACTIVO,@Empresa,@Usuario,@Estacion,GETDATE() FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT
 JOIN @Preguntas M ON M.Anterior=PT.CORR_PREGUNTA_BECA WHERE PT.CORR_EMPRESA=@Empresa AND PT.CORR_BECA=@BecaPlantilla;
 INSERT dbo.ACA_PROSPECTO_BECA_PUNTAJE(CORR_PREGUNTA_BECA,CORR_OPCION_BECA,PUNTAJE,PORCENTAJE,FECHA_INICIO,FECHA_FIN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
 SELECT M.Nuevo,O.Nuevo,U.PUNTAJE,U.PORCENTAJE,U.FECHA_INICIO,U.FECHA_FIN,U.ACTIVO,@Empresa,@Usuario,@Estacion,GETDATE()
 FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U JOIN @Preguntas M ON M.Anterior=U.CORR_PREGUNTA_BECA LEFT JOIN @Opciones O ON O.Anterior=U.CORR_OPCION_BECA
 WHERE U.CORR_EMPRESA=@Empresa AND (U.CORR_OPCION_BECA IS NULL OR O.Nuevo IS NOT NULL);
 INSERT dbo.ACA_PROSPECTO_BECA_DEPENDENCIA(CORR_PREGUNTA_PADRE,CORR_OPCION_PADRE,CORR_PREGUNTA_HIJA,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
 SELECT P.Nuevo,O.Nuevo,H.Nuevo,D.ACTIVO,@Empresa,@Usuario,@Estacion,GETDATE() FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D
 JOIN @Preguntas P ON P.Anterior=D.CORR_PREGUNTA_PADRE JOIN @Preguntas H ON H.Anterior=D.CORR_PREGUNTA_HIJA JOIN @Opciones O ON O.Anterior=D.CORR_OPCION_PADRE
 WHERE D.CORR_EMPRESA=@Empresa;
END;
GO

CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_FORMULARIOS
 @OPERACION varchar(20),@CORR_EMPRESA int,@CORR_BECA int,@ID int OUTPUT,@USUARIO varchar(100),@ESTACION varchar(50),
 @CORR_FORMULARIO_BECA int=NULL OUTPUT,@CORR_VERSION_ORIGEN int=NULL,@CORR_BECA_PLANTILLA int=NULL,
 @CODIGO_FORMULARIO varchar(30)=NULL,@NOMBRE_FORMULARIO varchar(200)=NULL,@DESCRIPCION varchar(1000)=NULL,
 @VERSION_FORMULARIO varchar(20)=NULL,@FECHA_INICIO date=NULL,@FECHA_FIN date=NULL,
 @ANIO_ADMISION smallint=NULL,@NUMERO_PERIODO_ADMISION tinyint=NULL,@VERSION_REGISTRO varbinary(8)=NULL
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'La sesion no es valida.',1;
 IF @OPERACION NOT IN('CREAR_DESDE_CERO','CREAR_FORMULARIO','EDITAR_FORMULARIO','CREAR_VERSION','EDITAR_VERSION','PUBLICAR','ASIGNAR','RETIRAR')
  THROW 51000,N'Operacion de formulario no valida.',1;
 -- La comprobacion del ciclo se hace fuera de la transaccion para no promover MSDTC.
 IF @OPERACION='ASIGNAR' AND (@ANIO_ADMISION IS NOT NULL OR @NUMERO_PERIODO_ADMISION IS NOT NULL)
 BEGIN
  IF @ANIO_ADMISION IS NULL OR @NUMERO_PERIODO_ADMISION IS NULL OR NOT EXISTS(
   SELECT 1 FROM dbo.V_ACA_BECA_ADMISION_PERIODO WHERE ANIO=@ANIO_ADMISION AND NUMERO_PERIODO=@NUMERO_PERIODO_ADMISION)
   THROW 51000,N'El ciclo no existe en SIS_ADMISION.',1;
 END;
 BEGIN TRY
  BEGIN TRANSACTION;
  DECLARE @Lock int;
  EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
  IF @Lock<0 THROW 51000,N'Otro usuario esta guardando. Intente nuevamente.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA)
   THROW 51000,N'La beca no pertenece a la empresa de sesion.',1;
  IF @OPERACION IN('CREAR_FORMULARIO','EDITAR_FORMULARIO','CREAR_DESDE_CERO')
  BEGIN
   SET @CODIGO_FORMULARIO=UPPER(LTRIM(RTRIM(@CODIGO_FORMULARIO))); SET @NOMBRE_FORMULARIO=LTRIM(RTRIM(@NOMBRE_FORMULARIO));
   IF NULLIF(@CODIGO_FORMULARIO,'') IS NULL OR NULLIF(@NOMBRE_FORMULARIO,'') IS NULL THROW 51000,N'El codigo y nombre del formulario son obligatorios.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CODIGO_FORMULARIO=@CODIGO_FORMULARIO AND (@OPERACION IN('CREAR_FORMULARIO','CREAR_DESDE_CERO') OR CORR_FORMULARIO_BECA<>@ID))
    THROW 51000,N'Ya existe un formulario con ese codigo.',1;
   IF @OPERACION IN('CREAR_FORMULARIO','CREAR_DESDE_CERO')
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_FORMULARIO(CODIGO_FORMULARIO,NOMBRE_FORMULARIO,DESCRIPCION,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CODIGO_FORMULARIO,@NOMBRE_FORMULARIO,@DESCRIPCION,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
    IF @OPERACION='CREAR_DESDE_CERO'
    BEGIN
     IF NULLIF(LTRIM(RTRIM(@VERSION_FORMULARIO)),'') IS NULL OR @FECHA_INICIO IS NULL OR @FECHA_FIN<@FECHA_INICIO
      THROW 51000,N'Indique la version inicial y una vigencia valida.',1;
     SET @CORR_FORMULARIO_BECA=@ID;
     INSERT dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION(CORR_FORMULARIO_BECA,VERSION_FORMULARIO,FECHA_INICIO,FECHA_FIN,ACTIVO,ESTADO_VERSION,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
     VALUES(@CORR_FORMULARIO_BECA,LTRIM(RTRIM(@VERSION_FORMULARIO)),@FECHA_INICIO,@FECHA_FIN,0,'BORRADOR',@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE());
     SET @ID=CONVERT(int,SCOPE_IDENTITY());
    END;
   END
   ELSE
   BEGIN
    IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_BECA=@ID AND ESTADO_VERSION='PUBLICADA')
     THROW 51000,N'El formulario tiene versiones publicadas; cree otro formulario para conservar su historial.',1;
    UPDATE dbo.ACA_PROSPECTO_BECA_FORMULARIO SET CODIGO_FORMULARIO=@CODIGO_FORMULARIO,NOMBRE_FORMULARIO=@NOMBRE_FORMULARIO,DESCRIPCION=@DESCRIPCION,
     USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_BECA=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO;
    IF @@ROWCOUNT=0 THROW 51009,N'El formulario cambio. Actualice el listado.',1;
   END;
  END
  ELSE IF @OPERACION IN('CREAR_VERSION','EDITAR_VERSION')
  BEGIN
   SET @VERSION_FORMULARIO=LTRIM(RTRIM(@VERSION_FORMULARIO));
   IF NULLIF(@VERSION_FORMULARIO,'') IS NULL OR @FECHA_INICIO IS NULL OR @FECHA_FIN<@FECHA_INICIO
    THROW 51000,N'Indique la version y una vigencia valida.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_BECA=@CORR_FORMULARIO_BECA AND ACTIVO=1)
    THROW 51000,N'El formulario no pertenece a su empresa o esta inactivo.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_BECA=@CORR_FORMULARIO_BECA
    AND VERSION_FORMULARIO=@VERSION_FORMULARIO AND (@OPERACION='CREAR_VERSION' OR CORR_FORMULARIO_VERSION<>@ID)) THROW 51000,N'La version ya existe en ese formulario.',1;
   IF @OPERACION='CREAR_VERSION'
   BEGIN
    IF ISNULL(@CORR_VERSION_ORIGEN,0)>0 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_VERSION_ORIGEN AND ESTADO_VERSION='PUBLICADA')
     THROW 51000,N'La version plantilla no pertenece a su empresa o no esta publicada.',1;
    IF ISNULL(@CORR_VERSION_ORIGEN,0)>0 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=PT.CORR_PREGUNTA_BECA
     JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
     WHERE PT.CORR_EMPRESA=@CORR_EMPRESA AND PT.CORR_BECA=@CORR_BECA_PLANTILLA AND PT.ACTIVO=1 AND P.ACTIVO=1 AND S.ACTIVO=1 AND S.CORR_FORMULARIO_VERSION=@CORR_VERSION_ORIGEN)
     THROW 51000,N'La beca plantilla no tiene preguntas activas en esa version.',1;
    INSERT dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION(CORR_FORMULARIO_BECA,VERSION_FORMULARIO,FECHA_INICIO,FECHA_FIN,ACTIVO,ESTADO_VERSION,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_FORMULARIO_BECA,@VERSION_FORMULARIO,@FECHA_INICIO,@FECHA_FIN,0,'BORRADOR',@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
    IF ISNULL(@CORR_VERSION_ORIGEN,0)>0 EXEC dbo.ACA_SP_BECA_VERSION_CLONAR @CORR_EMPRESA,@CORR_VERSION_ORIGEN,@ID,@CORR_BECA_PLANTILLA,@CORR_BECA,@USUARIO,@ESTACION;
   END
   ELSE
   BEGIN
    IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@ID) THROW 51000,N'No se puede editar una version utilizada por solicitudes.',1;
    UPDATE dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION SET VERSION_FORMULARIO=@VERSION_FORMULARIO,FECHA_INICIO=@FECHA_INICIO,FECHA_FIN=@FECHA_FIN,
     USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
     WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@ID AND CORR_FORMULARIO_BECA=@CORR_FORMULARIO_BECA AND ESTADO_VERSION='BORRADOR' AND VERSION_REGISTRO=@VERSION_REGISTRO;
    IF @@ROWCOUNT=0 THROW 51009,N'La version cambio o ya esta publicada. Actualice el listado.',1;
   END;
  END
  ELSE IF @OPERACION='PUBLICAR'
  BEGIN
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@ID AND ESTADO_VERSION='BORRADOR' AND VERSION_REGISTRO=@VERSION_REGISTRO)
    THROW 51009,N'La version cambio o ya esta publicada. Actualice el listado.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_SECCION S JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_SECCION_BECA=S.CORR_SECCION_BECA
    JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT ON PT.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND PT.CORR_EMPRESA=S.CORR_EMPRESA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND S.ACTIVO=1 AND P.ACTIVO=1 AND PT.ACTIVO=1 AND PT.CORR_BECA=@CORR_BECA)
    THROW 51000,N'La version no tiene preguntas activas para esta beca.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND S.ACTIVO=1 AND P.ACTIVO=1 AND P.TIPO_RESPUESTA IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO')
     AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION O WHERE O.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND O.CORR_EMPRESA=@CORR_EMPRESA AND O.ACTIVO=1))
    THROW 51000,N'Hay preguntas de seleccion sin opciones activas.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_SECCION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@ID
     AND (PUNTAJE_MAXIMO<0 OR PORCENTAJE_SECCION<0 OR PORCENTAJE_SECCION>100))
    THROW 51000,N'Revise los puntajes y porcentajes de las secciones.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=U.CORR_PREGUNTA_BECA
    JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND (U.PUNTAJE<0 OR U.PORCENTAJE<0 OR U.PORCENTAJE>100 OR U.FECHA_FIN<U.FECHA_INICIO))
    THROW 51000,N'Revise la vigencia, los puntajes y porcentajes de las preguntas.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA H ON H.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_HIJA
    JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=H.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND H.ACTIVO=1 AND D.ACTIVO=1
     AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION PS ON PS.CORR_SECCION_BECA=P.CORR_SECCION_BECA
      JOIN dbo.ACA_PROSPECTO_BECA_OPCION O ON O.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND O.CORR_OPCION_BECA=D.CORR_OPCION_PADRE AND O.ACTIVO=1
      WHERE P.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_PADRE AND P.ACTIVO=1 AND PS.ACTIVO=1 AND PS.CORR_EMPRESA=@CORR_EMPRESA AND PS.CORR_FORMULARIO_VERSION=@ID))
    THROW 51000,N'Hay dependencias con preguntas u opciones inexistentes o inactivas.',1;
   DECLARE @Ordenadas TABLE(Id int PRIMARY KEY);
   WHILE 1=1
   BEGIN
    INSERT @Ordenadas SELECT P.CORR_PREGUNTA_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P
    JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND S.ACTIVO=1 AND P.ACTIVO=1
     AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=P.CORR_PREGUNTA_BECA)
     AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D WHERE D.CORR_PREGUNTA_HIJA=P.CORR_PREGUNTA_BECA AND D.ACTIVO=1 AND D.CORR_EMPRESA=@CORR_EMPRESA
      AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=D.CORR_PREGUNTA_PADRE));
    IF @@ROWCOUNT=0 BREAK;
   END;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@ID AND S.ACTIVO=1 AND P.ACTIVO=1 AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=P.CORR_PREGUNTA_BECA))
    THROW 51000,N'Las dependencias del cuestionario contienen un ciclo.',1;
   UPDATE dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION SET ESTADO_VERSION='PUBLICADA',ACTIVO=1,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
    WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@ID;
  END
  ELSE IF @OPERACION='ASIGNAR'
  BEGIN
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA AND ESTADO_BECA='ACTIVA')
    THROW 51000,N'Active la beca antes de habilitar su formulario.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION V JOIN dbo.ACA_PROSPECTO_BECA_FORMULARIO F ON F.CORR_FORMULARIO_BECA=V.CORR_FORMULARIO_BECA AND F.CORR_EMPRESA=V.CORR_EMPRESA
    WHERE V.CORR_EMPRESA=@CORR_EMPRESA AND V.CORR_FORMULARIO_VERSION=@CORR_VERSION_ORIGEN AND V.ESTADO_VERSION='PUBLICADA' AND V.ACTIVO=1 AND F.ACTIVO=1)
    THROW 51000,N'Seleccione una version publicada y activa.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=PT.CORR_PREGUNTA_BECA
    JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA WHERE PT.CORR_EMPRESA=@CORR_EMPRESA AND PT.CORR_BECA=@CORR_BECA AND PT.ACTIVO=1 AND P.ACTIVO=1 AND S.ACTIVO=1 AND S.CORR_FORMULARIO_VERSION=@CORR_VERSION_ORIGEN)
    THROW 51000,N'La version no tiene preguntas configuradas para esta beca. Clone una plantilla para esta beca.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA AND ACTIVO=1
    AND ISNULL(ANIO_ADMISION,0)=ISNULL(@ANIO_ADMISION,0) AND ISNULL(NUMERO_PERIODO_ADMISION,0)=ISNULL(@NUMERO_PERIODO_ADMISION,0) AND CORR_TIPO_FORMULARIO<>@ID)
    THROW 51000,N'Ya existe una asignacion activa para ese ciclo. Seleccionela para cambiarla o retirarla.',1;
   IF ISNULL(@ID,0)=0
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO(CORR_BECA,CORR_FORMULARIO_VERSION,ACTIVO,CORR_EMPRESA,ANIO_ADMISION,NUMERO_PERIODO_ADMISION,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_BECA,@CORR_VERSION_ORIGEN,1,@CORR_EMPRESA,@ANIO_ADMISION,@NUMERO_PERIODO_ADMISION,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
   END
   ELSE
   BEGIN
    UPDATE dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO SET CORR_FORMULARIO_VERSION=@CORR_VERSION_ORIGEN,ANIO_ADMISION=@ANIO_ADMISION,NUMERO_PERIODO_ADMISION=@NUMERO_PERIODO_ADMISION,ACTIVO=1,
     USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA AND CORR_TIPO_FORMULARIO=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO;
    IF @@ROWCOUNT=0 THROW 51009,N'La asignacion cambio. Actualice el listado.',1;
   END;
  END
  ELSE IF @OPERACION='RETIRAR'
  BEGIN
   UPDATE dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
    WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA AND CORR_TIPO_FORMULARIO=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO;
   IF @@ROWCOUNT=0 THROW 51009,N'La asignacion cambio. Actualice el listado.',1;
  END;
  COMMIT;
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK; THROW;
 END CATCH;
END;
GO

CREATE OR ALTER VIEW dbo.V_ACA_BECA_VERSION_PLANTILLA_MTTO
AS SELECT DISTINCT V.CORR_EMPRESA,V.CORR_FORMULARIO_VERSION,PT.CORR_BECA,T.NOMBRE_BECA
FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION V JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_FORMULARIO_VERSION=V.CORR_FORMULARIO_VERSION AND S.CORR_EMPRESA=V.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_SECCION_BECA=S.CORR_SECCION_BECA AND P.CORR_EMPRESA=S.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT ON PT.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND PT.CORR_EMPRESA=P.CORR_EMPRESA
JOIN dbo.ACA_BECA_TIPO T ON T.CORR_BECA=PT.CORR_BECA AND T.CORR_EMPRESA=PT.CORR_EMPRESA
WHERE V.ESTADO_VERSION='PUBLICADA' AND S.ACTIVO=1 AND P.ACTIVO=1 AND PT.ACTIVO=1;
GO
