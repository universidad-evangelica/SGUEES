IF NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_ACA_BECA_FORMULARIO_CICLO')
 ALTER TABLE dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO WITH CHECK ADD CONSTRAINT CK_ACA_BECA_FORMULARIO_CICLO
