/*
  Menú Compras — Provisiones y Pagos (SGUEES)
  Rutas SPA: /com-provision, /com-provision-desaplicar, /com-pago, /com-pago-desaplicar
  Ejecutar: sqlcmd ... -f 65001 -i MENU_COM_PROVISION_PAGO.sql
  Tras aplicar: cerrar sesión y volver a entrar (menú viene al login).
*/
SET NOCOUNT ON;

DECLARE @SISTEMA     varchar(30) = 'COMPRAS';
DECLARE @SUITE       varchar(30) = 'SGUEES';
DECLARE @MENU        varchar(10) = 'PROCESO';
DECLARE @ORD_SISTEMA int;
DECLARE @ORD_MENU    int         = 1;
DECLARE @LOGIN       varchar(30) = 'admin';
DECLARE @USR         varchar(30) = 'admin';
DECLARE @EST         varchar(30) = 'SISTEMA';
DECLARE @HOY         datetime    = GETDATE();

SELECT TOP 1 @ORD_SISTEMA = ORDEN_SISTEMA
FROM dbo.SEG_CONFIG_OPCION
WHERE CODIGO_SISTEMA = @SISTEMA
ORDER BY ORDEN_SISTEMA;

IF @ORD_SISTEMA IS NULL SET @ORD_SISTEMA = 3;

DECLARE @Opciones TABLE (
    CODIGO_OPCION varchar(40) NOT NULL PRIMARY KEY,
    NOMBRE_OPCION nvarchar(120) NOT NULL,
    URL_OPCION    nvarchar(120) NOT NULL,
    ORDEN_OPCION  int NOT NULL
);

INSERT INTO @Opciones (CODIGO_OPCION, NOMBRE_OPCION, URL_OPCION, ORDEN_OPCION)
VALUES
    (N'COM_PROVISION', N'Provisiones', N'/com-provision', 11),
    (N'COM_PROVISION_DESAPLICAR', N'Desaplicar Provisiones', N'/com-provision-desaplicar', 12),
    (N'COM_PAGO', N'Pagos', N'/com-pago', 13),
    (N'COM_PAGO_DESAPLICAR', N'Desaplicar Pagos', N'/com-pago-desaplicar', 14);

/* SEG_OPCION_SISTEMA */
MERGE dbo.SEG_OPCION_SISTEMA AS T
USING @Opciones AS S
ON T.CODIGO_OPCION = S.CODIGO_OPCION
WHEN MATCHED THEN
    UPDATE SET
        T.NOMBRE_OPCION = S.NOMBRE_OPCION,
        T.URL_OPCION = S.URL_OPCION,
        T.IMAGEN_OPCION = N'',
        T.USUARIO_ACTU = @USR,
        T.FECHA_ACTU = @HOY,
        T.ESTACION_ACTU = @EST
WHEN NOT MATCHED THEN
    INSERT (CODIGO_OPCION, NOMBRE_OPCION, URL_OPCION, IMAGEN_OPCION, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
    VALUES (S.CODIGO_OPCION, S.NOMBRE_OPCION, S.URL_OPCION, N'', @USR, @HOY, @EST);

/* Suite SGUEES */
INSERT INTO dbo.SEG_OPCION_SISTEMA_SUITE (CODIGO_OPCION, CODIGO_SUITE)
SELECT o.CODIGO_OPCION, @SUITE
FROM @Opciones o
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.SEG_OPCION_SISTEMA_SUITE s
    WHERE s.CODIGO_OPCION = o.CODIGO_OPCION AND s.CODIGO_SUITE = @SUITE
);

/* Config menú: una entrada por opción en PROCESO */
DELETE c
FROM dbo.SEG_CONFIG_OPCION c
INNER JOIN @Opciones o ON o.CODIGO_OPCION = c.CODIGO_OPCION
WHERE c.CODIGO_SISTEMA = @SISTEMA;

INSERT INTO dbo.SEG_CONFIG_OPCION
    (CODIGO_SISTEMA, CODIGO_MENU, CODIGO_OPCION, ORDEN_SISTEMA, ORDEN_MENU, ORDEN_OPCION, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
SELECT @SISTEMA, @MENU, o.CODIGO_OPCION, @ORD_SISTEMA, @ORD_MENU, o.ORDEN_OPCION, @USR, @HOY, @EST
FROM @Opciones o;

/* Permisos: admin + usuarios que ya tienen COM_DOCUMENTO */
DECLARE @Logins TABLE (LOGIN_SISTEMA varchar(30) PRIMARY KEY);
INSERT INTO @Logins (LOGIN_SISTEMA) VALUES (@LOGIN);
INSERT INTO @Logins (LOGIN_SISTEMA)
SELECT DISTINCT u.LOGIN_SISTEMA
FROM dbo.SEG_USUARIO_OPCION u
WHERE u.CODIGO_OPCION = N'COM_DOCUMENTO'
  AND NOT EXISTS (SELECT 1 FROM @Logins l WHERE l.LOGIN_SISTEMA = u.LOGIN_SISTEMA);

DELETE u
FROM dbo.SEG_USUARIO_OPCION u
INNER JOIN @Opciones o ON o.CODIGO_OPCION = u.CODIGO_OPCION
INNER JOIN @Logins l ON l.LOGIN_SISTEMA = u.LOGIN_SISTEMA
WHERE u.CODIGO_SISTEMA = @SISTEMA;

INSERT INTO dbo.SEG_USUARIO_OPCION
    (LOGIN_SISTEMA, CODIGO_SISTEMA, CODIGO_MENU, CODIGO_OPCION, NUEVO, MODIFICAR, ELIMINAR, IMPRIMIR, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
SELECT l.LOGIN_SISTEMA, @SISTEMA, @MENU, o.CODIGO_OPCION, 1, 1, 1, 1, @USR, @HOY, @EST
FROM @Logins l
CROSS JOIN @Opciones o;

PRINT N'Menú COM_PROVISION / COM_PAGO aplicado en COMPRAS/PROCESO.';
PRINT N'Cerrar sesión y reingresar para ver las opciones.';
GO

SELECT c.CODIGO_MENU, c.ORDEN_OPCION, c.CODIGO_OPCION, o.NOMBRE_OPCION, o.URL_OPCION
FROM dbo.SEG_CONFIG_OPCION c
INNER JOIN dbo.SEG_OPCION_SISTEMA o ON o.CODIGO_OPCION = c.CODIGO_OPCION
WHERE c.CODIGO_SISTEMA = N'COMPRAS'
  AND c.CODIGO_MENU = N'PROCESO'
  AND c.CODIGO_OPCION IN (N'COM_PROVISION', N'COM_PROVISION_DESAPLICAR', N'COM_PAGO', N'COM_PAGO_DESAPLICAR')
ORDER BY c.ORDEN_OPCION;
GO
