-- Paso 1: mantenimiento de entidades (incluidas iglesias) y convenios de becas.
-- Ejecutar en SGUEES antes de publicar esta API. No modifica SIS_ADMISION.
-- Conserva los catalogos ACA_BEC_* y las solicitudes existentes.
SET XACT_ABORT ON;
IF DB_NAME()<>'SGUEES' THROW 51000,N'Este script requiere la base SGUEES.',1;
IF OBJECT_ID('dbo.ACA_BECA_CONVENIO','U') IS NULL OR OBJECT_ID('dbo.ACA_BECA_ENTIDAD_FINANCIADORA','U') IS NULL
 THROW 51000,N'Faltan los catalogos actuales de becas.',1;
IF COL_LENGTH('dbo.ACA_BECA_CONVENIO','VERSION_REGISTRO') IS NULL
 ALTER TABLE dbo.ACA_BECA_CONVENIO ADD VERSION_REGISTRO rowversion;
IF COL_LENGTH('dbo.ACA_BECA_ENTIDAD_FINANCIADORA','VERSION_REGISTRO') IS NULL
 ALTER TABLE dbo.ACA_BECA_ENTIDAD_FINANCIADORA ADD VERSION_REGISTRO rowversion;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_ENTIDAD_FINANCIADORA_MTTO
AS
SELECT CORR_EMPRESA,CORR_ENTIDAD_FINANCIADORA,CODIGO_ENTIDAD,NOMBRE_ENTIDAD,TIPO_ENTIDAD,
 CONTACTO,TELEFONO,CORREO,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA,
 USUARIO_ACTU,ESTACION_ACTU,FECHA_ACTU,VERSION_REGISTRO
FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_CONVENIO_MTTO
AS
SELECT C.CORR_EMPRESA,C.CORR_CONVENIO,C.CODIGO_CONVENIO,C.NOMBRE_CONVENIO,
 C.CORR_ENTIDAD_FINANCIADORA,E.CODIGO_ENTIDAD,E.NOMBRE_ENTIDAD,E.TIPO_ENTIDAD,
 C.FECHA_INICIO,C.FECHA_FIN,C.DESCRIPCION,C.ESTADO_CONVENIO,
 C.USUARIO_CREA,C.ESTACION_CREA,C.FECHA_CREA,C.USUARIO_ACTU,C.ESTACION_ACTU,C.FECHA_ACTU,C.VERSION_REGISTRO
FROM dbo.ACA_BECA_CONVENIO C
JOIN dbo.ACA_BECA_ENTIDAD_FINANCIADORA E ON E.CORR_EMPRESA=C.CORR_EMPRESA
 AND E.CORR_ENTIDAD_FINANCIADORA=C.CORR_ENTIDAD_FINANCIADORA;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_ENTIDAD_FINANCIADORA
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(100),
    @ESTACION varchar(50),
    @CODIGO_ENTIDAD varchar(30) = NULL,
    @NOMBRE_ENTIDAD varchar(200) = NULL,
    @TIPO_ENTIDAD varchar(30) = NULL,
    @CONTACTO varchar(150) = NULL,
    @TELEFONO varchar(30) = NULL,
    @CORREO varchar(150) = NULL,
    @ACTIVO bit = NULL ,@VERSION_REGISTRO varbinary(8) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    SET @CODIGO_ENTIDAD=UPPER(LTRIM(RTRIM(@CODIGO_ENTIDAD)));
    SET @NOMBRE_ENTIDAD=LTRIM(RTRIM(@NOMBRE_ENTIDAD));
    IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
        THROW 51000,N'La empresa de sesion no existe.',1;
    IF @TIPO_ACTUALIZA IN (1,2)
    BEGIN
        IF NULLIF(@CODIGO_ENTIDAD,'') IS NULL OR NULLIF(@NOMBRE_ENTIDAD,'') IS NULL
            THROW 51000,N'El codigo y el nombre son obligatorios.',1;
        SET @TIPO_ENTIDAD=UPPER(LTRIM(RTRIM(@TIPO_ENTIDAD)));
        IF @TIPO_ENTIDAD IS NULL OR @TIPO_ENTIDAD NOT IN ('UEES','FUNDACION','IGLESIA','EMPRESA','GOBIERNO','PERSONA','OTRO')
            THROW 51000,N'El tipo de entidad no es valido.',1;
        IF @ACTIVO IS NULL THROW 51000,N'Debe indicar el estado de la entidad.',1;
    END;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;
        IF @TIPO_ACTUALIZA IN (1,2) AND EXISTS(
            SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA WITH(UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CODIGO_ENTIDAD=@CODIGO_ENTIDAD AND (@TIPO_ACTUALIZA=1 OR CORR_ENTIDAD_FINANCIADORA<>@ID))
            THROW 51000,N'Ya existe un registro con ese codigo en la empresa.',1;
        IF ((@TIPO_ACTUALIZA IN (1,2) AND @ACTIVO=0) OR
            (@TIPO_ACTUALIZA=4 AND EXISTS(SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA
             WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID AND ACTIVO=1)))
            AND EXISTS(SELECT 1 FROM dbo.ACA_BECA_CONVENIO WITH(UPDLOCK,HOLDLOCK)
             WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID AND ESTADO_CONVENIO='VIGENTE')
            THROW 51000,N'Cierre o suspenda los convenios vigentes antes de desactivar la entidad.',1;

        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_ENTIDAD_FINANCIADORA),0)+1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_ENTIDAD_FINANCIADORA(CODIGO_ENTIDAD,NOMBRE_ENTIDAD,TIPO_ENTIDAD,CONTACTO,TELEFONO,CORREO,ACTIVO,CORR_EMPRESA,CORR_ENTIDAD_FINANCIADORA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CODIGO_ENTIDAD,@NOMBRE_ENTIDAD,@TIPO_ENTIDAD,@CONTACTO,@TELEFONO,@CORREO,@ACTIVO,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @VERSION_REGISTRO IS NULL OR NOT EXISTS(
                SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA WHERE CORR_EMPRESA=@CORR_EMPRESA
                 AND CORR_ENTIDAD_FINANCIADORA=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
                THROW 51009,N'Otro usuario modifico el registro. Actualice el listado antes de guardar.',1;

            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_ENTIDAD_FINANCIADORA SET CODIGO_ENTIDAD=@CODIGO_ENTIDAD,
                NOMBRE_ENTIDAD=@NOMBRE_ENTIDAD,
                TIPO_ENTIDAD=@TIPO_ENTIDAD,
                CONTACTO=@CONTACTO,
                TELEFONO=@TELEFONO,
                CORREO=@CORREO,
                ACTIVO=@ACTIVO, USUARIO_ACTU=@USUARIO, ESTACION_ACTU=@ESTACION, FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID;
            IF @TIPO_ACTUALIZA=3
                DELETE dbo.ACA_BECA_ENTIDAD_FINANCIADORA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID;
            IF @TIPO_ACTUALIZA=4
                UPDATE dbo.ACA_BECA_ENTIDAD_FINANCIADORA SET ACTIVO=CONVERT(bit,1-CONVERT(int,ACTIVO)),USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_ENTIDAD_FINANCIADORA=@ID;
        END
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        IF ERROR_NUMBER()=547 AND @TIPO_ACTUALIZA=3 THROW 51000,N'No se puede eliminar: el registro tiene dependencias.',1;
        THROW;
    END CATCH
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_CONVENIO
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(100),
    @ESTACION varchar(50),
    @CODIGO_CONVENIO varchar(50) = NULL,
    @NOMBRE_CONVENIO varchar(200) = NULL,
    @CORR_ENTIDAD_FINANCIADORA int = NULL,
    @FECHA_INICIO date = NULL,
    @FECHA_FIN date = NULL,
    @DESCRIPCION varchar(1000) = NULL,
    @ESTADO_CONVENIO varchar(20) = NULL ,@VERSION_REGISTRO varbinary(8) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    SET @CODIGO_CONVENIO=UPPER(LTRIM(RTRIM(@CODIGO_CONVENIO)));
    SET @NOMBRE_CONVENIO=LTRIM(RTRIM(@NOMBRE_CONVENIO));
    IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
        THROW 51000,N'La empresa de sesion no existe.',1;
    IF @TIPO_ACTUALIZA IN (1,2)
    BEGIN
        IF NULLIF(@CODIGO_CONVENIO,'') IS NULL OR NULLIF(@NOMBRE_CONVENIO,'') IS NULL
            THROW 51000,N'El codigo y el nombre son obligatorios.',1;
        SET @ESTADO_CONVENIO=UPPER(LTRIM(RTRIM(@ESTADO_CONVENIO)));
        IF @FECHA_INICIO IS NULL OR @FECHA_FIN<@FECHA_INICIO
            THROW 51000,N'La vigencia del convenio no es valida.',1;
        IF @ESTADO_CONVENIO IS NULL OR @ESTADO_CONVENIO NOT IN ('VIGENTE','VENCIDO','SUSPENDIDO','CERRADO')
            THROW 51000,N'El estado del convenio no es valido.',1;
        IF @CORR_ENTIDAD_FINANCIADORA IS NULL OR @CORR_ENTIDAD_FINANCIADORA<=0
            THROW 51000,N'Debe seleccionar la iglesia o institucion.',1;
    END;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;
        IF @TIPO_ACTUALIZA IN (1,2) AND EXISTS(
            SELECT 1 FROM dbo.ACA_BECA_CONVENIO WITH(UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CODIGO_CONVENIO=@CODIGO_CONVENIO AND (@TIPO_ACTUALIZA=1 OR CORR_CONVENIO<>@ID))
            THROW 51000,N'Ya existe un registro con ese codigo en la empresa.',1;
        IF @TIPO_ACTUALIZA IN (1,2) AND NOT EXISTS(
            SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA E WITH(UPDLOCK,HOLDLOCK)
            WHERE E.CORR_EMPRESA=@CORR_EMPRESA AND E.CORR_ENTIDAD_FINANCIADORA=@CORR_ENTIDAD_FINANCIADORA
              AND (E.ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND EXISTS(
                SELECT 1 FROM dbo.ACA_BECA_CONVENIO C WHERE C.CORR_EMPRESA=@CORR_EMPRESA
                 AND C.CORR_CONVENIO=@ID AND C.CORR_ENTIDAD_FINANCIADORA=E.CORR_ENTIDAD_FINANCIADORA))))
            THROW 51000,N'La iglesia o institucion no pertenece a su empresa o esta inactiva.',1;

        IF @TIPO_ACTUALIZA=4 AND EXISTS(
            SELECT 1 FROM dbo.ACA_BECA_CONVENIO C
            JOIN dbo.ACA_BECA_ENTIDAD_FINANCIADORA E ON E.CORR_EMPRESA=C.CORR_EMPRESA
             AND E.CORR_ENTIDAD_FINANCIADORA=C.CORR_ENTIDAD_FINANCIADORA
            WHERE C.CORR_EMPRESA=@CORR_EMPRESA AND C.CORR_CONVENIO=@ID
             AND C.ESTADO_CONVENIO<>'VIGENTE' AND E.ACTIVO=0)
            THROW 51000,N'Active la iglesia o institucion antes de reabrir su convenio.',1;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_CONVENIO),0)+1 FROM dbo.ACA_BECA_CONVENIO WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_CONVENIO(CODIGO_CONVENIO,NOMBRE_CONVENIO,CORR_ENTIDAD_FINANCIADORA,FECHA_INICIO,FECHA_FIN,DESCRIPCION,ESTADO_CONVENIO,CORR_EMPRESA,CORR_CONVENIO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CODIGO_CONVENIO,@NOMBRE_CONVENIO,@CORR_ENTIDAD_FINANCIADORA,@FECHA_INICIO,@FECHA_FIN,@DESCRIPCION,@ESTADO_CONVENIO,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_CONVENIO WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CONVENIO=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @VERSION_REGISTRO IS NULL OR NOT EXISTS(
                SELECT 1 FROM dbo.ACA_BECA_CONVENIO WHERE CORR_EMPRESA=@CORR_EMPRESA
                 AND CORR_CONVENIO=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
                THROW 51009,N'Otro usuario modifico el registro. Actualice el listado antes de guardar.',1;

            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_CONVENIO SET CODIGO_CONVENIO=@CODIGO_CONVENIO,
                NOMBRE_CONVENIO=@NOMBRE_CONVENIO,
                CORR_ENTIDAD_FINANCIADORA=@CORR_ENTIDAD_FINANCIADORA,
                FECHA_INICIO=@FECHA_INICIO,
                FECHA_FIN=@FECHA_FIN,
                DESCRIPCION=@DESCRIPCION,
                ESTADO_CONVENIO=@ESTADO_CONVENIO, USUARIO_ACTU=@USUARIO, ESTACION_ACTU=@ESTACION, FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CONVENIO=@ID;
            IF @TIPO_ACTUALIZA=3
                DELETE dbo.ACA_BECA_CONVENIO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CONVENIO=@ID;
            IF @TIPO_ACTUALIZA=4
                UPDATE dbo.ACA_BECA_CONVENIO SET ESTADO_CONVENIO=CASE WHEN ESTADO_CONVENIO='VIGENTE' THEN 'CERRADO' ELSE 'VIGENTE' END,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CONVENIO=@ID;
        END
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        IF ERROR_NUMBER()=547 AND @TIPO_ACTUALIZA=3 THROW 51000,N'No se puede eliminar: el registro tiene dependencias.',1;
        THROW;
    END CATCH
END;
GO
