CREATE OR ALTER VIEW dbo.V_ACA_PERIODOS_MTTO AS
SELECT P.*,S.CORR_EMPRESA,S.NOMBRE_SEDE,A.NOMBRE_AREA,F.NOMBRE_FACULTAD,C.NOMBRE_CARRERA,
    CAST(CASE WHEN P.CORR_CARRERA IS NOT NULL THEN 'Carrera' WHEN P.CORR_FACULTAD IS NOT NULL THEN 'Facultad' ELSE 'Área' END AS varchar(12)) AS ALCANCE,
    CAST(CASE WHEN EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO R WHERE R.CORR_PERIODO_ACADEMICO=P.CORR_PERIODO_ACADEMICO)
        OR EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA R WHERE R.CORR_PERIODO_ACADEMICO=P.CORR_PERIODO_ACADEMICO)
        OR EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_DOCUMENTO R WHERE R.CORR_PERIODO_ACADEMICO=P.CORR_PERIODO_ACADEMICO)
        THEN 1 ELSE 0 END AS bit) AS EN_USO
FROM dbo.ACA_PERIODOS_ACADEMICOS P
JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=P.CORR_SEDE
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=P.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=S.CORR_EMPRESA
LEFT JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=P.CORR_FACULTAD AND F.CORR_EMPRESA=S.CORR_EMPRESA
LEFT JOIN dbo.ACA_CARRERAS C ON C.CORR_CARRERA=P.CORR_CARRERA AND C.CORR_EMPRESA=S.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_PERIODOS_HISTORIAL AS
SELECT B.*,S.CORR_EMPRESA,S.NOMBRE_SEDE,A.NOMBRE_AREA,F.NOMBRE_FACULTAD,C.NOMBRE_CARRERA,
    CAST(CASE WHEN B.CORR_CARRERA IS NOT NULL THEN 'Carrera' WHEN B.CORR_FACULTAD IS NOT NULL THEN 'Facultad' ELSE 'Área' END AS varchar(12)) AS ALCANCE
FROM dbo.ACA_PERIODOS_ACADEMICOS_BITACORA B
JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=B.CORR_SEDE
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=B.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=S.CORR_EMPRESA
LEFT JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=B.CORR_FACULTAD AND F.CORR_EMPRESA=S.CORR_EMPRESA
LEFT JOIN dbo.ACA_CARRERAS C ON C.CORR_CARRERA=B.CORR_CARRERA AND C.CORR_EMPRESA=S.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_PERIODOS_CATALOGOS AS
SELECT 'SEDE' AS TIPO,S.CORR_EMPRESA,S.CORR_SEDE AS [Key],CAST(S.NOMBRE_SEDE AS varchar(250)) AS Value,
    CAST(CASE WHEN S.ESTADO_SEDE='A' THEN 1 ELSE 0 END AS bit) AS ACTIVO,
    S.CORR_SEDE,CAST(NULL AS int) AS CORR_AREA_ACADEMICA,CAST(NULL AS int) AS CORR_FACULTAD FROM dbo.GEN_SEDES S
UNION ALL
SELECT 'AREA',CORR_EMPRESA,CORR_AREA_ACADEMICA,NOMBRE_AREA,ACTIVO,NULL,CORR_AREA_ACADEMICA,NULL FROM dbo.ACA_AREAS_ACADEMICAS
UNION ALL
SELECT 'FACULTAD',F.CORR_EMPRESA,F.CORR_FACULTAD,F.NOMBRE_FACULTAD,
    CAST(CASE WHEN F.ACTIVO=1 AND FS.ACTIVO=1 AND S.ESTADO_SEDE='A' THEN 1 ELSE 0 END AS bit),FS.CORR_SEDE,NULL,F.CORR_FACULTAD
FROM dbo.ACA_FACULTADES F JOIN dbo.ACA_FACULTADES_SEDES FS ON FS.CORR_FACULTAD=F.CORR_FACULTAD
JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=FS.CORR_SEDE AND S.CORR_EMPRESA=F.CORR_EMPRESA
UNION ALL
SELECT 'CARRERA',C.CORR_EMPRESA,C.CORR_CARRERA,C.NOMBRE_CARRERA,
    CAST(CASE WHEN C.ACTIVO=1 AND CS.ACTIVO=1 AND F.ACTIVO=1 AND FS.ACTIVO=1 AND S.ESTADO_SEDE='A' AND A.ACTIVO=1 THEN 1 ELSE 0 END AS bit),
    CS.CORR_SEDE,C.CORR_AREA_ACADEMICA,C.CORR_FACULTAD
FROM dbo.ACA_CARRERAS C JOIN dbo.ACA_CARRERAS_SEDES CS ON CS.CORR_CARRERA=C.CORR_CARRERA
JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=CS.CORR_SEDE AND S.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=C.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_FACULTADES_SEDES FS ON FS.CORR_FACULTAD=C.CORR_FACULTAD AND FS.CORR_SEDE=CS.CORR_SEDE;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PERIODOS
    @TIPO_ACTUALIZA int, -- 1 crear inactivo, 2 editar calendario, 3 activar/desactivar
    @CORR_EMPRESA int,
    @CORR_PERIODO_ACADEMICO int OUTPUT,
    @CORR_SEDE int=NULL,@CORR_AREA_ACADEMICA int=NULL,@CORR_FACULTAD int=NULL,@CORR_CARRERA int=NULL,
    @ANIO int=NULL,@NUMERO_PERIODO int=NULL,
    @FECHA_INICIO date=NULL,@FECHA_FIN date=NULL,@FECHA_INICIO_INSCRIPCION date=NULL,@FECHA_FIN_INSCRIPCION date=NULL,
    @SYS_LOGIN_USUARIO varchar(50),@SYS_ESTACION varchar(100),
    @SYS_NUMERO_ERROR int OUTPUT,@SYS_MENSAJE_ERROR nvarchar(4000) OUTPUT,@SYS_FILAS_AFECTADAS int OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @TRAN_INICIAL int=@@TRANCOUNT;
    SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR=N'',@SYS_FILAS_AFECTADAS=0;
    BEGIN TRY
        IF ISNULL(@CORR_EMPRESA,0)<=0 THROW 51000,N'No se encontró la empresa de la sesión.',1;
        IF @TIPO_ACTUALIZA IS NULL OR @TIPO_ACTUALIZA NOT IN (1,2,3) THROW 51000,N'Operación no válida.',1;
        IF NULLIF(LTRIM(RTRIM(@SYS_LOGIN_USUARIO)),'') IS NULL THROW 51000,N'No se encontró el usuario de la sesión.',1;
        IF @TRAN_INICIAL=0 BEGIN TRANSACTION;
        ELSE SAVE TRANSACTION ACA_PERIODOS_MTTO;
        -- Serializa escrituras por empresa, incluyendo altas concurrentes del mismo alcance.
        DECLARE @EMPRESA int,@ACTIVO bit=0,@CAMBIO_ALCANCE bit=0,@SEDE_ANT int,@AREA_ANT int,@FAC_ANT int,@CAR_ANT int,@ANIO_ANT smallint,@NUM_ANT tinyint;
        SELECT @EMPRESA=CORR_EMPRESA FROM dbo.GEN_EMPRESA WITH (UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA;
        IF @EMPRESA IS NULL THROW 51000,N'La empresa de la sesión no existe.',1;
        IF @TIPO_ACTUALIZA<>1
        BEGIN
            SELECT @ACTIVO=P.ACTIVO,@SEDE_ANT=P.CORR_SEDE,@AREA_ANT=P.CORR_AREA_ACADEMICA,@FAC_ANT=P.CORR_FACULTAD,
                @CAR_ANT=P.CORR_CARRERA,@ANIO_ANT=P.ANIO,@NUM_ANT=P.NUMERO_PERIODO
            FROM dbo.ACA_PERIODOS_ACADEMICOS P WITH (UPDLOCK,HOLDLOCK)
            JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=P.CORR_SEDE AND S.CORR_EMPRESA=@CORR_EMPRESA
            WHERE P.CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
            IF @SEDE_ANT IS NULL THROW 51000,N'El período no existe en la empresa de la sesión.',1;
        END;
        IF @TIPO_ACTUALIZA=3
        BEGIN
            SELECT @CORR_SEDE=CORR_SEDE,@CORR_AREA_ACADEMICA=CORR_AREA_ACADEMICA,@CORR_FACULTAD=CORR_FACULTAD,@CORR_CARRERA=CORR_CARRERA,
                @ANIO=ANIO,@NUMERO_PERIODO=NUMERO_PERIODO,@FECHA_INICIO=FECHA_INICIO,@FECHA_FIN=FECHA_FIN,
                @FECHA_INICIO_INSCRIPCION=FECHA_INICIO_INSCRIPCION,@FECHA_FIN_INSCRIPCION=FECHA_FIN_INSCRIPCION
            FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
            SET @ACTIVO=CASE WHEN @ACTIVO=1 THEN 0 ELSE 1 END;
        END;
        -- Siempre permitir desactivar para conservar y retirar configuraciones heredadas.
        IF NOT (@TIPO_ACTUALIZA=3 AND @ACTIVO=0)
        BEGIN
            IF @ANIO IS NULL OR @ANIO NOT BETWEEN 1 AND 9999 THROW 51000,N'Ingrese un año entre 1 y 9999.',1;
            IF @NUMERO_PERIODO IS NULL OR @NUMERO_PERIODO NOT BETWEEN 1 AND 255 THROW 51000,N'Esta etapa requiere un número de período entre 1 y 255.',1;
            IF @FECHA_INICIO IS NULL OR @FECHA_FIN IS NULL OR @FECHA_INICIO_INSCRIPCION IS NULL OR @FECHA_FIN_INSCRIPCION IS NULL
                THROW 51000,N'Las cuatro fechas son obligatorias.',1;
            IF @FECHA_FIN<@FECHA_INICIO THROW 51000,N'El fin académico no puede ser anterior al inicio.',1;
            IF @FECHA_FIN_INSCRIPCION<@FECHA_INICIO_INSCRIPCION THROW 51000,N'El cierre de inscripción no puede ser anterior a su apertura.',1;
            IF @FECHA_FIN_INSCRIPCION>@FECHA_FIN THROW 51000,N'El cierre de inscripción no puede ser posterior al fin académico.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WITH (HOLDLOCK) WHERE CORR_SEDE=@CORR_SEDE AND CORR_EMPRESA=@CORR_EMPRESA)
                OR NOT EXISTS(SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WITH (HOLDLOCK) WHERE CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA AND CORR_EMPRESA=@CORR_EMPRESA)
                THROW 51000,N'La sede y el área deben pertenecer a la empresa de la sesión.',1;
            IF @CORR_CARRERA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS WITH (HOLDLOCK)
                WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_EMPRESA=@CORR_EMPRESA AND CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA
                  AND CORR_FACULTAD=@CORR_FACULTAD)
                THROW 51000,N'La carrera debe coincidir con el área y la facultad seleccionadas.',1;
            IF @CORR_FACULTAD IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES F WITH (HOLDLOCK)
                JOIN dbo.ACA_FACULTADES_SEDES FS WITH (HOLDLOCK) ON FS.CORR_FACULTAD=F.CORR_FACULTAD AND FS.CORR_SEDE=@CORR_SEDE
                WHERE F.CORR_FACULTAD=@CORR_FACULTAD AND F.CORR_EMPRESA=@CORR_EMPRESA)
                THROW 51000,N'La facultad no está asociada a la sede de esta empresa.',1;
            IF @CORR_CARRERA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS_SEDES WITH (HOLDLOCK) WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_SEDE=@CORR_SEDE)
                THROW 51000,N'La carrera no está asociada a la sede.',1;
            IF @TIPO_ACTUALIZA=2 AND (@SEDE_ANT<>@CORR_SEDE OR @AREA_ANT<>@CORR_AREA_ACADEMICA OR ISNULL(@FAC_ANT,0)<>ISNULL(@CORR_FACULTAD,0)
                OR ISNULL(@CAR_ANT,0)<>ISNULL(@CORR_CARRERA,0) OR @ANIO_ANT<>@ANIO OR ISNULL(@NUM_ANT,0)<>@NUMERO_PERIODO)
                SET @CAMBIO_ALCANCE=1;
            IF @CAMBIO_ALCANCE=1 AND (EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO WITH (HOLDLOCK) WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO)
                OR EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA WITH (HOLDLOCK) WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO)
                OR EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_DOCUMENTO WITH (HOLDLOCK) WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO))
                THROW 51000,N'El período tiene registros relacionados. Conserve sede, área, alcance, año y número; cree otro período.',1;
            IF @TIPO_ACTUALIZA=1 OR (@TIPO_ACTUALIZA=3 AND @ACTIVO=1) OR @CAMBIO_ALCANCE=1
            BEGIN
                IF NOT EXISTS(SELECT 1 FROM dbo.GEN_SEDES WHERE CORR_SEDE=@CORR_SEDE AND ESTADO_SEDE='A')
                    OR NOT EXISTS(SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WHERE CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA AND ACTIVO=1)
                    THROW 51000,N'La sede y el área deben estar activas para crear o activar el período.',1;
                IF @CORR_FACULTAD IS NOT NULL AND (NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES WHERE CORR_FACULTAD=@CORR_FACULTAD AND ACTIVO=1)
                    OR NOT EXISTS(SELECT 1 FROM dbo.ACA_FACULTADES_SEDES WHERE CORR_FACULTAD=@CORR_FACULTAD AND CORR_SEDE=@CORR_SEDE AND ACTIVO=1))
                    THROW 51000,N'La facultad y su asociación por sede deben estar activas.',1;
                IF @CORR_CARRERA IS NOT NULL AND (NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS WHERE CORR_CARRERA=@CORR_CARRERA AND ACTIVO=1)
                    OR NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS_SEDES WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_SEDE=@CORR_SEDE AND ACTIVO=1))
                    THROW 51000,N'La carrera y su asociación por sede deben estar activas.',1;
            END;
            IF EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS WITH (UPDLOCK,HOLDLOCK) WHERE CORR_SEDE=@CORR_SEDE AND CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA
                AND ANIO=@ANIO AND NUMERO_PERIODO=@NUMERO_PERIODO AND ISNULL(CORR_FACULTAD,0)=ISNULL(@CORR_FACULTAD,0)
                AND ISNULL(CORR_CARRERA,0)=ISNULL(@CORR_CARRERA,0) AND (@TIPO_ACTUALIZA=1 OR CORR_PERIODO_ACADEMICO<>@CORR_PERIODO_ACADEMICO))
                THROW 51000,N'Ya existe un período para esa sede, área, ciclo y alcance.',1;
        END;
        -- Conservar también el estado previo al primer cambio de un período heredado.
        IF @TIPO_ACTUALIZA<>1 AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS_BITACORA WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO)
            INSERT dbo.ACA_PERIODOS_ACADEMICOS_BITACORA(CORR_PERIODO_ACADEMICO,CORR_SEDE,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_CARRERA,ANIO,NUMERO_PERIODO,
                FECHA_INICIO,FECHA_FIN,FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA,USUARIO_ACTU,ESTACION_ACTU,FECHA_ACTU,
                TIPO_CAMBIO,USUARIO_CAMBIO,FECHA_CAMBIO)
            SELECT CORR_PERIODO_ACADEMICO,CORR_SEDE,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_CARRERA,ANIO,NUMERO_PERIODO,
                FECHA_INICIO,FECHA_FIN,FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA,USUARIO_ACTU,ESTACION_ACTU,FECHA_ACTU,
                'BASE',@SYS_LOGIN_USUARIO,SYSDATETIME()
            FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            INSERT dbo.ACA_PERIODOS_ACADEMICOS(CORR_SEDE,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_CARRERA,ANIO,NUMERO_PERIODO,
                FECHA_INICIO,FECHA_FIN,FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
            VALUES(@CORR_SEDE,@CORR_AREA_ACADEMICA,@CORR_FACULTAD,@CORR_CARRERA,@ANIO,@NUMERO_PERIODO,
                @FECHA_INICIO,@FECHA_FIN,@FECHA_INICIO_INSCRIPCION,@FECHA_FIN_INSCRIPCION,0,@SYS_LOGIN_USUARIO,@SYS_ESTACION,GETDATE());
            SET @CORR_PERIODO_ACADEMICO=CONVERT(int,SCOPE_IDENTITY());
        END
        ELSE IF @TIPO_ACTUALIZA=2
            UPDATE dbo.ACA_PERIODOS_ACADEMICOS SET CORR_SEDE=@CORR_SEDE,CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA,CORR_FACULTAD=@CORR_FACULTAD,CORR_CARRERA=@CORR_CARRERA,
                ANIO=@ANIO,NUMERO_PERIODO=@NUMERO_PERIODO,FECHA_INICIO=@FECHA_INICIO,FECHA_FIN=@FECHA_FIN,
                FECHA_INICIO_INSCRIPCION=@FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION=@FECHA_FIN_INSCRIPCION,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
        ELSE
            UPDATE dbo.ACA_PERIODOS_ACADEMICOS SET ACTIVO=@ACTIVO,USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
        INSERT dbo.ACA_PERIODOS_ACADEMICOS_BITACORA(CORR_PERIODO_ACADEMICO,CORR_SEDE,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_CARRERA,ANIO,NUMERO_PERIODO,
            FECHA_INICIO,FECHA_FIN,FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA,USUARIO_ACTU,ESTACION_ACTU,FECHA_ACTU,
            TIPO_CAMBIO,USUARIO_CAMBIO,FECHA_CAMBIO)
        SELECT CORR_PERIODO_ACADEMICO,CORR_SEDE,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_CARRERA,ANIO,NUMERO_PERIODO,
            FECHA_INICIO,FECHA_FIN,FECHA_INICIO_INSCRIPCION,FECHA_FIN_INSCRIPCION,ACTIVO,USUARIO_CREA,ESTACION_CREA,FECHA_CREA,USUARIO_ACTU,ESTACION_ACTU,FECHA_ACTU,
            CASE @TIPO_ACTUALIZA WHEN 1 THEN 'ALTA' WHEN 2 THEN 'EDICION' ELSE 'ESTADO' END,@SYS_LOGIN_USUARIO,SYSDATETIME()
        FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_PERIODO_ACADEMICO=@CORR_PERIODO_ACADEMICO;
        SET @SYS_FILAS_AFECTADAS=1;
        IF @TRAN_INICIAL=0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @TRAN_INICIAL=0 AND XACT_STATE()<>0 ROLLBACK TRANSACTION;
        ELSE IF @TRAN_INICIAL>0 AND XACT_STATE()=1 ROLLBACK TRANSACTION ACA_PERIODOS_MTTO;
        SELECT @SYS_NUMERO_ERROR=ERROR_NUMBER(),@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),@SYS_FILAS_AFECTADAS=0;
        IF @SYS_NUMERO_ERROR IN (2601,2627) SET @SYS_MENSAJE_ERROR=N'Ya existe un período para esa sede, área, ciclo y alcance.';
    END CATCH;
END;
