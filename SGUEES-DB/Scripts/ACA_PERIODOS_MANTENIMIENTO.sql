    WHERE K.parent_object_id=OBJECT_ID('dbo.ACA_PERIODOS_ACADEMICOS_BITACORA') AND K.type='PK'
      AND COL_NAME(IC.object_id,IC.column_id)='CORR_PERIODO_ACADEMICO')
BEGIN
    IF EXISTS(SELECT 1 FROM sys.foreign_keys WHERE referenced_object_id=OBJECT_ID('dbo.ACA_PERIODOS_ACADEMICOS_BITACORA'))
