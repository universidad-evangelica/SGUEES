CREATE OR ALTER VIEW dbo.V_ACA_PLANES_CARRERA AS
SELECT P.*, C.CORR_EMPRESA, M.NOMBRE_MODALIDAD,
    CAST(CASE WHEN EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO R WHERE R.CORR_PLAN_ACADEMICO=P.CORR_PLAN_ACADEMICO)
         THEN 1 ELSE 0 END AS bit) AS EN_USO
FROM dbo.ACA_PLANES_ACADEMICOS P
JOIN dbo.ACA_CARRERAS C ON C.CORR_CARRERA=P.CORR_CARRERA
JOIN dbo.ACA_MODALIDADES_ACADEMICAS M ON M.CORR_MODALIDAD=P.CORR_MODALIDAD AND M.CORR_EMPRESA=C.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_MODALIDADES_CARRERA_LOOKUP AS
SELECT C.CORR_CARRERA,C.CORR_EMPRESA,M.CORR_MODALIDAD AS [Key],M.NOMBRE_MODALIDAD AS Value,M.ACTIVO
FROM dbo.ACA_CARRERAS C
JOIN dbo.ACA_MODALIDADES_ACADEMICAS M ON M.CORR_EMPRESA=C.CORR_EMPRESA;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_PLANES_ACADEMICOS
    @TIPO_ACTUALIZA int, -- 1 crear borrador, 2 editar, 3 cambiar PLAN_VIGENTE
    @CORR_EMPRESA int,
    @CORR_CARRERA int,
    @CORR_PLAN_ACADEMICO int OUTPUT,
    @CODIGO_PLAN varchar(max)=NULL,
    @CORR_MODALIDAD int=NULL,
    @ANIO_PLAN int=NULL,
    @FECHA_VIGENCIA_INICIO date=NULL,
    @FECHA_VIGENCIA_FIN date=NULL,
    @SYS_LOGIN_USUARIO varchar(50),
    @SYS_ESTACION varchar(100),
    @SYS_NUMERO_ERROR int OUTPUT,
    @SYS_MENSAJE_ERROR nvarchar(4000) OUTPUT,
    @SYS_FILAS_AFECTADAS int OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @TRAN_INICIAL int=@@TRANCOUNT;
    SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR=N'',@SYS_FILAS_AFECTADAS=0;
    BEGIN TRY
        IF ISNULL(@CORR_EMPRESA,0)<=0 THROW 51000,N'No se encontró la empresa de la sesión.',1;
        IF @TIPO_ACTUALIZA IS NULL OR @TIPO_ACTUALIZA NOT IN (1,2,3) THROW 51000,N'Operación no válida.',1;
        IF NULLIF(LTRIM(RTRIM(@SYS_LOGIN_USUARIO)),'') IS NULL THROW 51000,N'No se encontró el usuario de la sesión.',1;
        IF @TRAN_INICIAL=0 BEGIN TRANSACTION;
        ELSE SAVE TRANSACTION ACA_PLANES_MTTO;
        DECLARE @CARRERA_ACTIVA bit,@VIGENTE bit=0,@MODALIDAD_ANT int,@CODIGO_ANT varchar(20),@ANIO_ANT smallint,@INICIO_ANT date;
        -- Serializa también altas/reactivaciones concurrentes de planes de la misma carrera.
        SELECT @CARRERA_ACTIVA=ACTIVO FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
        WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_EMPRESA=@CORR_EMPRESA;
        IF @CARRERA_ACTIVA IS NULL THROW 51000,N'La carrera no existe en la empresa de la sesión. Guarde primero la carrera.',1;
        IF @TIPO_ACTUALIZA<>1
        BEGIN
            SELECT @VIGENTE=PLAN_VIGENTE,@MODALIDAD_ANT=CORR_MODALIDAD,@CODIGO_ANT=CODIGO_PLAN,
                   @ANIO_ANT=ANIO_PLAN,@INICIO_ANT=FECHA_VIGENCIA_INICIO
            FROM dbo.ACA_PLANES_ACADEMICOS WITH (UPDLOCK,HOLDLOCK)
            WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO AND CORR_CARRERA=@CORR_CARRERA;
            IF @MODALIDAD_ANT IS NULL THROW 51000,N'El plan no pertenece a la carrera seleccionada.',1;
        END;
        IF @TIPO_ACTUALIZA=3
        BEGIN
            -- El cliente no decide el estado ni envía datos de cabecera para esta acción.
            SELECT @CODIGO_PLAN=CODIGO_PLAN,@CORR_MODALIDAD=CORR_MODALIDAD,@ANIO_PLAN=ANIO_PLAN,
                   @FECHA_VIGENCIA_INICIO=FECHA_VIGENCIA_INICIO,@FECHA_VIGENCIA_FIN=FECHA_VIGENCIA_FIN
            FROM dbo.ACA_PLANES_ACADEMICOS WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO;
            SET @VIGENTE=CASE WHEN @VIGENTE=1 THEN 0 ELSE 1 END;
        END;
        -- Se permite retirar la vigencia incluso con padres inactivos o datos heredados inválidos.
        IF NOT (@TIPO_ACTUALIZA=3 AND @VIGENTE=0)
        BEGIN
            SET @CODIGO_PLAN=LTRIM(RTRIM(@CODIGO_PLAN));
            IF NULLIF(@CODIGO_PLAN,'') IS NULL OR LEN(@CODIGO_PLAN)>20 THROW 51000,N'Ingrese el código del plan (máximo 20 caracteres).',1;
            IF @ANIO_PLAN IS NULL OR @ANIO_PLAN NOT BETWEEN 1 AND 9999 THROW 51000,N'Ingrese un año del plan entre 1 y 9999.',1;
            IF @FECHA_VIGENCIA_INICIO IS NULL THROW 51000,N'La fecha inicial de vigencia es obligatoria.',1;
            IF @FECHA_VIGENCIA_FIN<@FECHA_VIGENCIA_INICIO THROW 51000,N'La fecha final no puede ser anterior a la inicial.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_MODALIDADES_ACADEMICAS WITH (HOLDLOCK)
                WHERE CORR_MODALIDAD=@CORR_MODALIDAD AND CORR_EMPRESA=@CORR_EMPRESA)
                THROW 51000,N'La modalidad no pertenece a la empresa de la sesión.',1;
            IF @TIPO_ACTUALIZA=1 OR @VIGENTE=1 OR @CORR_MODALIDAD<>@MODALIDAD_ANT
            BEGIN
                IF @CARRERA_ACTIVA=0 THROW 51000,N'La carrera debe estar activa para crear o habilitar un plan.',1;
                IF NOT EXISTS(SELECT 1 FROM dbo.ACA_MODALIDADES_ACADEMICAS WITH (HOLDLOCK)
                    WHERE CORR_MODALIDAD=@CORR_MODALIDAD AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                    THROW 51000,N'La modalidad debe estar activa para crear o habilitar un plan.',1;
            END;
            IF @TIPO_ACTUALIZA=2 AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO WITH (HOLDLOCK)
                WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO)
                AND (@CODIGO_PLAN<>@CODIGO_ANT OR @CORR_MODALIDAD<>@MODALIDAD_ANT OR @ANIO_PLAN<>@ANIO_ANT
                     OR @FECHA_VIGENCIA_INICIO<>@INICIO_ANT)
                THROW 51000,N'El plan tiene registros relacionados. Conserve código, año, modalidad e inicio; cree una nueva versión.',1;
            IF EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS WITH (UPDLOCK,HOLDLOCK)
                WHERE CORR_CARRERA=@CORR_CARRERA AND ANIO_PLAN=@ANIO_PLAN AND CORR_MODALIDAD=@CORR_MODALIDAD
                  AND (@TIPO_ACTUALIZA=1 OR CORR_PLAN_ACADEMICO<>@CORR_PLAN_ACADEMICO))
                THROW 51000,N'Ya existe un plan de esta carrera, año y modalidad.',1;
            IF @VIGENTE=1 AND EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS WITH (UPDLOCK,HOLDLOCK)
                WHERE CORR_CARRERA=@CORR_CARRERA AND CORR_MODALIDAD=@CORR_MODALIDAD AND PLAN_VIGENTE=1
                  AND CORR_PLAN_ACADEMICO<>@CORR_PLAN_ACADEMICO
                  AND FECHA_VIGENCIA_INICIO<=ISNULL(@FECHA_VIGENCIA_FIN,CONVERT(date,'99991231'))
                  AND ISNULL(FECHA_VIGENCIA_FIN,CONVERT(date,'99991231'))>=@FECHA_VIGENCIA_INICIO)
                THROW 51000,N'Existe otro plan vigente de la misma carrera y modalidad con fechas superpuestas. Revise sus fechas de cierre.',1;
        END;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            INSERT dbo.ACA_PLANES_ACADEMICOS(CODIGO_PLAN,CORR_CARRERA,CORR_MODALIDAD,ANIO_PLAN,FECHA_VIGENCIA_INICIO,
                FECHA_VIGENCIA_FIN,PLAN_VIGENTE,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
            VALUES(@CODIGO_PLAN,@CORR_CARRERA,@CORR_MODALIDAD,@ANIO_PLAN,@FECHA_VIGENCIA_INICIO,
                @FECHA_VIGENCIA_FIN,0,@SYS_LOGIN_USUARIO,@SYS_ESTACION,GETDATE());
            SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT,@CORR_PLAN_ACADEMICO=CONVERT(int,SCOPE_IDENTITY());
        END
        ELSE IF @TIPO_ACTUALIZA=2
        BEGIN
            UPDATE dbo.ACA_PLANES_ACADEMICOS SET CODIGO_PLAN=@CODIGO_PLAN,CORR_MODALIDAD=@CORR_MODALIDAD,ANIO_PLAN=@ANIO_PLAN,
                FECHA_VIGENCIA_INICIO=@FECHA_VIGENCIA_INICIO,FECHA_VIGENCIA_FIN=@FECHA_VIGENCIA_FIN,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END
        ELSE
        BEGIN
            UPDATE dbo.ACA_PLANES_ACADEMICOS SET PLAN_VIGENTE=@VIGENTE,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_PLAN_ACADEMICO=@CORR_PLAN_ACADEMICO AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END;
        IF @TRAN_INICIAL=0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @TRAN_INICIAL=0 AND XACT_STATE()<>0 ROLLBACK TRANSACTION;
        ELSE IF @TRAN_INICIAL>0 AND XACT_STATE()=1 ROLLBACK TRANSACTION ACA_PLANES_MTTO;
        SELECT @SYS_NUMERO_ERROR=ERROR_NUMBER(),@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),@SYS_FILAS_AFECTADAS=0;
        IF @SYS_NUMERO_ERROR IN (2601,2627) SET @SYS_MENSAJE_ERROR=N'Ya existe un plan de esta carrera, año y modalidad.';
    END CATCH;
END;
GO
