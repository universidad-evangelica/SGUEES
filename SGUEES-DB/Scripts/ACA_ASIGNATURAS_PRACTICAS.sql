CREATE OR ALTER VIEW dbo.V_ACA_ASIGNATURAS_PRACTICAS AS
SELECT A.CORR_EMPRESA,A.CORR_ASIGNATURA,A.CORR_CARRERA,A.CORR_FACULTAD,A.CODIGO_ASIGNATURA,A.NOMBRE_ASIGNATURA,
 A.CORR_TIPO_PRACTICA,A.NOMBRE_TIPO_PRACTICA,A.ACTIVO,A.VERSION,
 CONVERT(bit,CASE WHEN EXISTS(SELECT 1 FROM dbo.ACA_PLANES_ASIGNATURAS R
 JOIN dbo.ACA_PROSPECTO P ON P.CORR_PLAN_ACADEMICO=R.CORR_PLAN_ACADEMICO WHERE R.CORR_ASIGNATURA=A.CORR_ASIGNATURA) THEN 1 ELSE 0 END) EN_USO
FROM dbo.V_ACA_ASIGNATURAS A;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_DATA_ACA_ASIGNATURAS_PRACTICAS
 @CORR_EMPRESA int,@CORR_FACULTAD int,@CORR_CARRERA int
AS
BEGIN
 SET NOCOUNT ON;
 IF NOT EXISTS(SELECT 1 FROM dbo.V_ACA_ASIGNATURAS_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FACULTAD=@CORR_FACULTAD AND CORR_CARRERA=@CORR_CARRERA AND ACTIVO=1)
  THROW 51000,N'Seleccione una carrera activa de la facultad y empresa indicadas.',1;
 SELECT CORR_ASIGNATURA,CORR_CARRERA,CODIGO_ASIGNATURA,NOMBRE_ASIGNATURA,CORR_TIPO_PRACTICA,NOMBRE_TIPO_PRACTICA,ACTIVO,VERSION,EN_USO
 FROM dbo.V_ACA_ASIGNATURAS_PRACTICAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA AND CORR_FACULTAD=@CORR_FACULTAD
 ORDER BY CODIGO_ASIGNATURA;
END;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_ASIGNATURAS_PRACTICAS
 @CORR_EMPRESA int,@CORR_FACULTAD int,@CORR_CARRERA int,@CORR_TIPO_PRACTICA int,@VERSION_TIPO varbinary(8),
 @ASIGNATURAS xml,@CONFIRMAR_REEMPLAZOS bit,@USUARIO varchar(50),@ESTACION varchar(100),@FILAS int OUTPUT
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;SET @FILAS=0;
 BEGIN TRY
  BEGIN TRANSACTION;
  IF ISNULL(@CORR_EMPRESA,0)<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL OR @CONFIRMAR_REEMPLAZOS IS NULL
   THROW 51000,N'Empresa, usuario y revisión del cambio requeridos.',1;
  DECLARE @R TABLE(Id int NOT NULL,Version varbinary(8) NOT NULL);
  INSERT @R SELECT X.value('@id','int'),X.value('xs:hexBinary((@version)[1])','varbinary(8)') FROM @ASIGNATURAS.nodes('/asignaturas/a') T(X);
  IF (SELECT COUNT(*) FROM @R) NOT BETWEEN 1 AND 500 OR EXISTS(SELECT Id FROM @R GROUP BY Id HAVING COUNT(*)>1)
   OR EXISTS(SELECT 1 FROM @R WHERE Id<=0 OR DATALENGTH(Version)<>8) THROW 51000,N'Seleccione entre 1 y 500 materias diferentes, con su versión vigente.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_TIPOS_PRACTICA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_TIPO_PRACTICA=@CORR_TIPO_PRACTICA AND ACTIVO=1 AND VERSION=@VERSION_TIPO)
   THROW 51000,N'El tipo de práctica está inactivo o cambió. Actualice los catálogos y vuelva a revisar.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_CARRERAS C WITH(HOLDLOCK) JOIN dbo.ACA_FACULTADES F WITH(HOLDLOCK) ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
   JOIN dbo.ACA_AREAS_ACADEMICAS E WITH(HOLDLOCK) ON E.CORR_AREA_ACADEMICA=C.CORR_AREA_ACADEMICA AND E.CORR_EMPRESA=C.CORR_EMPRESA
   WHERE C.CORR_EMPRESA=@CORR_EMPRESA AND C.CORR_CARRERA=@CORR_CARRERA AND C.CORR_FACULTAD=@CORR_FACULTAD AND C.ACTIVO=1 AND F.ACTIVO=1 AND E.ACTIVO=1)
   THROW 51000,N'La carrera, facultad y área deben pertenecer a la empresa y estar activas.',1;
  IF EXISTS(SELECT 1 FROM @R R LEFT JOIN dbo.ACA_ASIGNATURAS A WITH(UPDLOCK,HOLDLOCK) ON A.CORR_ASIGNATURA=R.Id
   WHERE A.CORR_ASIGNATURA IS NULL OR A.CORR_EMPRESA<>@CORR_EMPRESA OR A.CORR_CARRERA<>@CORR_CARRERA OR A.ACTIVO<>1 OR A.VERSION<>R.Version)
   THROW 51000,N'Alguna materia no pertenece a la carrera, está inactiva o fue modificada. Recargue y revise nuevamente.',1;
  IF EXISTS(SELECT 1 FROM @R R JOIN dbo.ACA_PLANES_ASIGNATURAS P WITH(HOLDLOCK) ON P.CORR_ASIGNATURA=R.Id JOIN dbo.ACA_PROSPECTO H WITH(HOLDLOCK) ON H.CORR_PLAN_ACADEMICO=P.CORR_PLAN_ACADEMICO)
   THROW 51000,N'Hay materias de planes en uso. Conserve su estructura histórica y utilice una nueva versión del plan.',1;
  IF @CONFIRMAR_REEMPLAZOS=0 AND EXISTS(SELECT 1 FROM @R R JOIN dbo.ACA_ASIGNATURAS A ON A.CORR_ASIGNATURA=R.Id WHERE A.CORR_TIPO_PRACTICA IS NOT NULL AND A.CORR_TIPO_PRACTICA<>@CORR_TIPO_PRACTICA)
   THROW 51000,N'Revise y confirme expresamente el reemplazo de las clasificaciones existentes.',1;
  DECLARE @Antes TABLE(Id int PRIMARY KEY,Datos nvarchar(max));
  INSERT @Antes SELECT A.CORR_ASIGNATURA,(SELECT S.* FROM dbo.ACA_ASIGNATURAS S WHERE S.CORR_ASIGNATURA=A.CORR_ASIGNATURA FOR JSON PATH,WITHOUT_ARRAY_WRAPPER)
   FROM dbo.ACA_ASIGNATURAS A JOIN @R R ON R.Id=A.CORR_ASIGNATURA WHERE ISNULL(A.CORR_TIPO_PRACTICA,0)<>@CORR_TIPO_PRACTICA;
  IF NOT EXISTS(SELECT 1 FROM @Antes) THROW 51000,N'Las materias seleccionadas ya tienen ese tipo de práctica.',1;
  UPDATE A SET CORR_TIPO_PRACTICA=@CORR_TIPO_PRACTICA,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=SYSDATETIME()
   FROM dbo.ACA_ASIGNATURAS A JOIN @Antes R ON R.Id=A.CORR_ASIGNATURA;
  SET @FILAS=@@ROWCOUNT;
  INSERT dbo.ACA_ASIGNATURAS_BITACORA(CORR_EMPRESA,ENTIDAD,ID_REGISTRO,OPERACION,USUARIO,ESTACION,DATOS_ANTES,DATOS_DESPUES)
   SELECT @CORR_EMPRESA,'ASIGNATURA',R.Id,'ASIGNAR_PRACTICA',@USUARIO,@ESTACION,R.Datos,
    (SELECT A.* FROM dbo.ACA_ASIGNATURAS A WHERE A.CORR_ASIGNATURA=R.Id FOR JSON PATH,WITHOUT_ARRAY_WRAPPER) FROM @Antes R;
  COMMIT TRANSACTION;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
  SET @FILAS=0;THROW;
 END CATCH;
END;
