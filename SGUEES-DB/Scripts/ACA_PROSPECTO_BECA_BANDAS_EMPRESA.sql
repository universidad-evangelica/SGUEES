/* ==========================================================================
   V_ACA_PROSPECTO_BECA_CONSULTA
   Qué hace: una fila por solicitud de beca en borrador o enviada, con los
             datos del prospecto y el resultado de la evaluación.
   Cómo lo hace: parte de ACA_PROSPECTO_BECA, trae persona, beca, ciclo y
             carrera del plan del prospecto. La API filtra por CORR_EMPRESA,
             ANIO y NUMERO_PERIODO.
   ========================================================================== */
CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_CONSULTA
AS
SELECT
    PB.CORR_EMPRESA,
    PB.CORR_PROSPECTO_BECA,
    PB.CORR_PROSPECTO,
    P.CODIGO_PROSPECTO,
    LTRIM(RTRIM(PP.NOMBRES))
        + ' ' + LTRIM(RTRIM(PP.APELLIDO1))
        + ISNULL(' ' + NULLIF(LTRIM(RTRIM(PP.APELLIDO2)), ''), '') AS NOMBRE_COMPLETO,
    PP.DUI,
    CA.NOMBRE_CARRERA,
    PB.CORR_BECA,
    BT.CODIGO_BECA,
    BT.NOMBRE_BECA,
    PB.CORR_PERIODO_ACADEMICO,
    PA.ANIO,
    PA.NUMERO_PERIODO,
    CAST(PA.ANIO AS VARCHAR(4)) + '-' + RIGHT('0' + CAST(PA.NUMERO_PERIODO AS VARCHAR(2)), 2) AS CICLO,
    PB.ESTADO_BECA,
    CASE PB.ESTADO_BECA
        WHEN 'BORRADOR' THEN 'Borrador'
        WHEN 'ENVIADA' THEN 'Enviada'
        ELSE PB.ESTADO_BECA
    END AS ESTADO_BECA_TEXTO,
    CAST(ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) AS decimal(10, 2)) AS PUNTAJE_TOTAL,
    CAST(ISNULL(PB.PORCENTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) AS decimal(5, 2)) AS PORCENTAJE_TOTAL,
    CASE
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) = ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0)
            THEN PB.RESULTADO_EVALUACION
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 85 THEN 'Potencialmente elegible'
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 70 THEN 'Potencialmente elegible'
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 55 THEN 'Elegibilidad condicionada'
        ELSE 'Baja viabilidad actual'
    END AS RESULTADO_EVALUACION,
    CASE
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) = ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0)
            THEN PB.PRIORIDAD_EVALUACION
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 85 THEN 'ALTA'
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 70 THEN 'MEDIA'
        WHEN ISNULL(PB.PUNTAJE_TOTAL, 0) - ISNULL(G.GUARDADO, 0) + ISNULL(C.CALCULADO, 0) >= 55 THEN 'CONDICIONADA'
        ELSE 'BAJA'
    END AS PRIORIDAD_EVALUACION,
    PB.FECHA_SOLICITUD
FROM dbo.ACA_PROSPECTO_BECA AS PB
INNER JOIN dbo.ACA_PROSPECTO AS P
    ON P.CORR_PROSPECTO = PB.CORR_PROSPECTO
INNER JOIN dbo.ACA_BECA_TIPO AS BT
    ON BT.CORR_BECA = PB.CORR_BECA
INNER JOIN dbo.ACA_PERIODOS_ACADEMICOS AS PA
    ON PA.CORR_PERIODO_ACADEMICO = PB.CORR_PERIODO_ACADEMICO
LEFT JOIN dbo.ACA_PROSPECTO_PERSONA AS PP
    ON PP.CORR_PROSPECTO = PB.CORR_PROSPECTO
LEFT JOIN dbo.ACA_PLANES_ACADEMICOS AS PL
    ON PL.CORR_PLAN_ACADEMICO = P.CORR_PLAN_ACADEMICO
LEFT JOIN dbo.ACA_CARRERAS AS CA
    ON CA.CORR_CARRERA = PL.CORR_CARRERA
OUTER APPLY (
    SELECT ISNULL(SUM(R.PUNTAJE_OBTENIDO), 0) AS GUARDADO
    FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R
    INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P
        ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA
    WHERE R.CORR_PROSPECTO_BECA = PB.CORR_PROSPECTO_BECA
      AND P.CODIGO_PREGUNTA IN (
            N'SOC_DEPENDIENTES_ECONOMICOS',
            N'ACA_PROMEDIO_PRIMERO',
            N'ACA_PROMEDIO_SEGUNDO',
            N'ACA_PROMEDIO_TERCERO')
) AS G
OUTER APPLY (
    SELECT AVG(R.RESPUESTA_NUMERO) AS PROMEDIO
    FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R
    INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P
        ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA
    WHERE R.CORR_PROSPECTO_BECA = PB.CORR_PROSPECTO_BECA
      AND P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
      AND R.RESPUESTA_NUMERO IS NOT NULL
) AS PR
OUTER APPLY (
    SELECT
        ISNULL((
            SELECT TOP (1) B.PUNTAJE
            FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R
            INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P
                ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA
            INNER JOIN dbo.ACA_PROSPECTO_BECA_BANDA AS B
                ON B.ACTIVO = 1 AND B.CORR_EMPRESA = PB.CORR_EMPRESA
               AND B.CODIGO_REGLA = N'DEPENDIENTES'
               AND R.RESPUESTA_NUMERO >= B.VALOR_DESDE
               AND R.RESPUESTA_NUMERO < B.VALOR_HASTA
            WHERE R.CORR_PROSPECTO_BECA = PB.CORR_PROSPECTO_BECA
              AND P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS'
        ), 0)
        + ISNULL((
            SELECT TOP (1) B.PUNTAJE
            FROM dbo.ACA_PROSPECTO_BECA_BANDA AS B
            WHERE B.ACTIVO = 1 AND B.CORR_EMPRESA = PB.CORR_EMPRESA
              AND B.CODIGO_REGLA = N'PROMEDIO_BACHILLERATO'
              AND PR.PROMEDIO >= B.VALOR_DESDE
              AND PR.PROMEDIO < B.VALOR_HASTA
        ), 0) AS CALCULADO
) AS C
WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')
  AND PA.CORR_AREA_ACADEMICA = 5;
GO
/* ==========================================================================
   V_ACA_PROSPECTO_BECA_RESPUESTA
   Qué hace: cada respuesta guardada del cuestionario, con su puntaje.
   Cómo lo hace: una fila por ACA_PROSPECTO_BECA_RESPUESTA (en opción
             múltiple hay una fila por opción marcada). La API filtra por
             CORR_EMPRESA y CORR_PROSPECTO_BECA.
   ========================================================================== */
CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_RESPUESTA
AS
SELECT
    R.CORR_EMPRESA,
    R.CORR_PROSPECTO_BECA,
    R.CORR_RESPUESTA_BECA,
    S.ORDEN AS ORDEN_SECCION,
    S.NOMBRE_SECCION,
    P.ORDEN AS ORDEN_PREGUNTA,
    P.CORR_PREGUNTA_BECA,
    P.CODIGO_PREGUNTA,
    P.TEXTO_PREGUNTA,
    P.TIPO_RESPUESTA,
    ISNULL(R.CORR_OPCION_BECA, 0) AS CORR_OPCION_BECA,
    CASE
        WHEN P.TIPO_RESPUESTA = 'ACEPTACION'
            THEN COALESCE(NULLIF(LTRIM(RTRIM(R.RESPUESTA_TEXTO)), ''), R.TEXTO_OPCION_HISTORICO)
        WHEN P.TIPO_RESPUESTA IN ('OPCION_UNICA', 'OPCION_MULTIPLE', 'SI_NO')
            THEN R.TEXTO_OPCION_HISTORICO
        WHEN P.TIPO_RESPUESTA = 'DOCUMENTO'
            THEN R.ARCHIVO_NOMBRE
        WHEN P.TIPO_RESPUESTA IN ('NUMERO', 'DECIMAL') AND R.RESPUESTA_NUMERO IS NOT NULL
            THEN CASE
                    WHEN R.RESPUESTA_NUMERO = FLOOR(R.RESPUESTA_NUMERO)
                        THEN CONVERT(VARCHAR(40), CONVERT(BIGINT, R.RESPUESTA_NUMERO))
                    ELSE CONVERT(VARCHAR(40), CONVERT(DECIMAL(18, 2), R.RESPUESTA_NUMERO))
                 END
        WHEN P.TIPO_RESPUESTA IN ('TEXTO', 'TEXTO_LARGO')
            THEN R.RESPUESTA_TEXTO
        WHEN R.RESPUESTA_FECHA IS NOT NULL
            THEN CONVERT(VARCHAR(10), R.RESPUESTA_FECHA, 103)
        ELSE COALESCE(R.TEXTO_OPCION_HISTORICO, R.RESPUESTA_TEXTO)
    END AS RESPUESTA,
    CAST(CASE
        WHEN P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS' THEN ISNULL(DEP.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
             AND P.CORR_PREGUNTA_BECA = PR.CORR_PREGUNTA_DESTINO THEN ISNULL(ACA.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO') THEN 0
        ELSE R.PUNTAJE_OBTENIDO
    END AS decimal(10, 2)) AS PUNTAJE_OBTENIDO,
    CAST(CASE
        WHEN P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS' THEN ISNULL(DEP.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
             AND P.CORR_PREGUNTA_BECA = PR.CORR_PREGUNTA_DESTINO THEN ISNULL(ACA.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO') THEN 0
        ELSE R.PORCENTAJE_APLICADO
    END AS decimal(10, 2)) AS PORCENTAJE_APLICADO
FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R
INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P
    ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA
INNER JOIN dbo.ACA_PROSPECTO_BECA_SECCION AS S
    ON S.CORR_SECCION_BECA = P.CORR_SECCION_BECA
INNER JOIN dbo.ACA_PROSPECTO_BECA AS PB
    ON PB.CORR_PROSPECTO_BECA = R.CORR_PROSPECTO_BECA
LEFT JOIN (
    SELECT
        G.CORR_PROSPECTO_BECA,
        G.PROMEDIO,
        D.CORR_PREGUNTA_BECA AS CORR_PREGUNTA_DESTINO
    FROM (
        SELECT
            R2.CORR_PROSPECTO_BECA,
            AVG(R2.RESPUESTA_NUMERO) AS PROMEDIO
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R2
        INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P2
            ON P2.CORR_PREGUNTA_BECA = R2.CORR_PREGUNTA_BECA
        WHERE P2.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
          AND R2.RESPUESTA_NUMERO IS NOT NULL
        GROUP BY R2.CORR_PROSPECTO_BECA
    ) AS G
    CROSS APPLY (
        SELECT TOP (1) R3.CORR_PREGUNTA_BECA
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R3
        INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P3
            ON P3.CORR_PREGUNTA_BECA = R3.CORR_PREGUNTA_BECA
        WHERE R3.CORR_PROSPECTO_BECA = G.CORR_PROSPECTO_BECA
          AND P3.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
          AND R3.RESPUESTA_NUMERO IS NOT NULL
        ORDER BY P3.ORDEN DESC, R3.CORR_RESPUESTA_BECA DESC
    ) AS D
) AS PR
    ON PR.CORR_PROSPECTO_BECA = R.CORR_PROSPECTO_BECA
OUTER APPLY (
    SELECT TOP (1) B.PUNTAJE
    FROM dbo.ACA_PROSPECTO_BECA_BANDA AS B
    WHERE B.ACTIVO = 1 AND B.CORR_EMPRESA = PB.CORR_EMPRESA
      AND B.CODIGO_REGLA = N'DEPENDIENTES'
      AND P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS'
      AND R.RESPUESTA_NUMERO >= B.VALOR_DESDE
      AND R.RESPUESTA_NUMERO < B.VALOR_HASTA
) AS DEP
OUTER APPLY (
    SELECT TOP (1) B.PUNTAJE
    FROM dbo.ACA_PROSPECTO_BECA_BANDA AS B
    WHERE B.ACTIVO = 1 AND B.CORR_EMPRESA = PB.CORR_EMPRESA
      AND B.CODIGO_REGLA = N'PROMEDIO_BACHILLERATO'
      AND PR.PROMEDIO >= B.VALOR_DESDE
      AND PR.PROMEDIO < B.VALOR_HASTA
) AS ACA
WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')
  AND P.TIPO_RESPUESTA <> 'DOCUMENTO';
GO
