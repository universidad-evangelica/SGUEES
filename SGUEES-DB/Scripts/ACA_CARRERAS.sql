CREATE OR ALTER VIEW dbo.V_ACA_CARRERAS
AS
SELECT C.*, A.NOMBRE_AREA, F.NOMBRE_FACULTAD, G.NOMBRE_GRADO,
    COALESCE(STUFF((
        SELECT N', ' + S.NOMBRE_SEDE
        FROM dbo.ACA_CARRERAS_SEDES CS
        JOIN dbo.GEN_SEDES S ON S.CORR_SEDE=CS.CORR_SEDE AND S.CORR_EMPRESA=C.CORR_EMPRESA
        WHERE CS.CORR_CARRERA=C.CORR_CARRERA AND CS.ACTIVO=1 AND S.ESTADO_SEDE='A'
        ORDER BY S.NOMBRE_SEDE, S.CORR_SEDE
        FOR XML PATH(''), TYPE
    ).value('.', 'nvarchar(max)'), 1, 2, N''), N'Sin sedes activas') AS SEDES_ACTIVAS
FROM dbo.ACA_CARRERAS C
JOIN dbo.ACA_AREAS_ACADEMICAS A ON A.CORR_AREA_ACADEMICA=C.CORR_AREA_ACADEMICA AND A.CORR_EMPRESA=C.CORR_EMPRESA
JOIN dbo.ACA_FACULTADES F ON F.CORR_FACULTAD=C.CORR_FACULTAD AND F.CORR_EMPRESA=C.CORR_EMPRESA
LEFT JOIN dbo.ACA_GRADOS_ACADEMICOS G ON G.CORR_GRADO_ACADEMICO=C.CORR_GRADO_ACADEMICO AND G.CORR_EMPRESA=C.CORR_EMPRESA;
GO
CREATE OR ALTER VIEW dbo.V_ACA_AREAS_CARRERA_LOOKUP AS
SELECT CORR_AREA_ACADEMICA AS [Key], NOMBRE_AREA AS Value, CORR_EMPRESA, ACTIVO FROM dbo.ACA_AREAS_ACADEMICAS;
GO
CREATE OR ALTER VIEW dbo.V_ACA_FACULTADES_CARRERA_LOOKUP AS
SELECT CORR_FACULTAD AS [Key], NOMBRE_FACULTAD AS Value, CORR_EMPRESA, ACTIVO FROM dbo.ACA_FACULTADES;
GO
CREATE OR ALTER VIEW dbo.V_ACA_GRADOS_CARRERA_LOOKUP AS
SELECT CORR_GRADO_ACADEMICO AS [Key], NOMBRE_GRADO AS Value, CORR_EMPRESA, ACTIVO FROM dbo.ACA_GRADOS_ACADEMICOS;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_CARRERAS
    @TIPO_ACTUALIZA int, -- 1 alta, 2 edición, 3 eliminación, 4 estado
    @CORR_EMPRESA int,
    @CORR_CARRERA int OUTPUT,
    @CORR_AREA_ACADEMICA int = NULL,
    @CORR_FACULTAD int = NULL,
    @CORR_GRADO_ACADEMICO int = NULL,
    @CODIGO_CARRERA varchar(30) = NULL,
    @NOMBRE_CARRERA varchar(250) = NULL,
    @SYS_LOGIN_USUARIO varchar(50),
    @SYS_ESTACION varchar(100),
    @SYS_NUMERO_ERROR int OUTPUT,
    @SYS_MENSAJE_ERROR nvarchar(4000) OUTPUT,
    @SYS_FILAS_AFECTADAS int OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SELECT @SYS_NUMERO_ERROR=0, @SYS_MENSAJE_ERROR=N'', @SYS_FILAS_AFECTADAS=0;
    DECLARE @TRAN_INICIAL int=@@TRANCOUNT;
    BEGIN TRY
        IF ISNULL(@CORR_EMPRESA,0)<=0 THROW 51000, N'No se encontró la empresa de la sesión.', 1;
        IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) OR @TIPO_ACTUALIZA IS NULL
            THROW 51000, N'Operación no válida.', 1;
        IF NULLIF(LTRIM(RTRIM(@SYS_LOGIN_USUARIO)),'') IS NULL
            THROW 51000, N'No se encontró el usuario de la sesión.', 1;
        IF @TRAN_INICIAL=0 BEGIN TRANSACTION;
        ELSE SAVE TRANSACTION ACA_CARRERAS_MTTO;
        DECLARE @AREA_ANTERIOR int, @FACULTAD_ANTERIOR int, @GRADO_ANTERIOR int, @ACTIVO_ANTERIOR bit;
        IF @TIPO_ACTUALIZA<>1
        BEGIN
            SELECT @AREA_ANTERIOR=CORR_AREA_ACADEMICA, @FACULTAD_ANTERIOR=CORR_FACULTAD,
                   @GRADO_ANTERIOR=CORR_GRADO_ACADEMICO, @ACTIVO_ANTERIOR=ACTIVO
            FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            IF @AREA_ANTERIOR IS NULL THROW 51000, N'La carrera no existe en la empresa de la sesión.', 1;
        END;
        IF @TIPO_ACTUALIZA IN (1,2)
        BEGIN
            SELECT @CODIGO_CARRERA=LTRIM(RTRIM(@CODIGO_CARRERA)), @NOMBRE_CARRERA=LTRIM(RTRIM(@NOMBRE_CARRERA));
            IF NULLIF(@CODIGO_CARRERA,'') IS NULL OR NULLIF(@NOMBRE_CARRERA,'') IS NULL
                THROW 51000, N'El código y el nombre de la carrera son obligatorios.', 1;
            -- Una referencia inactiva ya asignada puede conservarse al corregir texto.
            IF NOT EXISTS (SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WITH (HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA
                AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @AREA_ANTERIOR=@CORR_AREA_ACADEMICA)))
                THROW 51000, N'Seleccione un área académica activa de la empresa.', 1;
            IF NOT EXISTS (SELECT 1 FROM dbo.ACA_FACULTADES WITH (HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FACULTAD=@CORR_FACULTAD
                AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @FACULTAD_ANTERIOR=@CORR_FACULTAD)))
                THROW 51000, N'Seleccione una facultad activa de la empresa.', 1;
            IF @CORR_GRADO_ACADEMICO IS NOT NULL AND NOT EXISTS
                (SELECT 1 FROM dbo.ACA_GRADOS_ACADEMICOS WITH (HOLDLOCK)
                 WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_GRADO_ACADEMICO=@CORR_GRADO_ACADEMICO
                 AND (ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @GRADO_ANTERIOR=@CORR_GRADO_ACADEMICO)))
                THROW 51000, N'Seleccione un grado académico activo de la empresa.', 1;
            IF EXISTS (SELECT 1 FROM dbo.ACA_CARRERAS WITH (UPDLOCK,HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CODIGO_CARRERA=@CODIGO_CARRERA
                AND (@TIPO_ACTUALIZA=1 OR CORR_CARRERA<>@CORR_CARRERA))
                THROW 51000, N'Ya existe una carrera con ese código en la empresa.', 1;
            IF @TIPO_ACTUALIZA=2 AND (@AREA_ANTERIOR<>@CORR_AREA_ACADEMICA OR @FACULTAD_ANTERIOR<>@CORR_FACULTAD)
               AND (EXISTS (SELECT 1 FROM dbo.ACA_CARRERAS_SEDES WHERE CORR_CARRERA=@CORR_CARRERA)
                 OR EXISTS (SELECT 1 FROM dbo.ACA_PLANES_ACADEMICOS WHERE CORR_CARRERA=@CORR_CARRERA)
                 OR EXISTS (SELECT 1 FROM dbo.ACA_PERIODOS_ACADEMICOS WHERE CORR_CARRERA=@CORR_CARRERA))
                THROW 51000, N'No se puede cambiar área o facultad: revise primero las sedes, planes y períodos relacionados.', 1;
        END;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            INSERT dbo.ACA_CARRERAS
                (CORR_EMPRESA,CORR_AREA_ACADEMICA,CORR_FACULTAD,CORR_GRADO_ACADEMICO,CODIGO_CARRERA,NOMBRE_CARRERA,ACTIVO,
                 USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
            VALUES (@CORR_EMPRESA,@CORR_AREA_ACADEMICA,@CORR_FACULTAD,@CORR_GRADO_ACADEMICO,@CODIGO_CARRERA,@NOMBRE_CARRERA,1,
                    @SYS_LOGIN_USUARIO,@SYS_ESTACION,GETDATE());
            SET @CORR_CARRERA=CONVERT(int,SCOPE_IDENTITY());
            SET @SYS_FILAS_AFECTADAS=1;
        END;
        IF @TIPO_ACTUALIZA=2
        BEGIN
            UPDATE dbo.ACA_CARRERAS SET CORR_AREA_ACADEMICA=@CORR_AREA_ACADEMICA, CORR_FACULTAD=@CORR_FACULTAD,
                CORR_GRADO_ACADEMICO=@CORR_GRADO_ACADEMICO,CODIGO_CARRERA=@CODIGO_CARRERA,NOMBRE_CARRERA=@NOMBRE_CARRERA,
                USUARIO_ACTU=@SYS_LOGIN_USUARIO,ESTACION_ACTU=@SYS_ESTACION,FECHA_ACTU=GETDATE()
            WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END;
        IF @TIPO_ACTUALIZA=3
        BEGIN
            DELETE dbo.ACA_CARRERAS WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_CARRERA=@CORR_CARRERA;
            SET @SYS_FILAS_AFECTADAS=@@ROWCOUNT;
        END;
        IF @TIPO_ACTUALIZA=4
        BEGIN
            IF @ACTIVO_ANTERIOR=0 AND
                (NOT EXISTS (SELECT 1 FROM dbo.ACA_AREAS_ACADEMICAS WITH (HOLDLOCK) WHERE CORR_AREA_ACADEMICA=@AREA_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                 OR NOT EXISTS (SELECT 1 FROM dbo.ACA_FACULTADES WITH (HOLDLOCK) WHERE CORR_FACULTAD=@FACULTAD_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)
                 OR (@GRADO_ANTERIOR IS NOT NULL AND NOT EXISTS (SELECT 1 FROM dbo.ACA_GRADOS_ACADEMICOS WITH (HOLDLOCK) WHERE CORR_GRADO_ACADEMICO=@GRADO_ANTERIOR AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1)))
                THROW 51000, N'Para activar la carrera, su área, facultad y grado asignado deben estar activos.', 1;
            EXEC dbo.PRAL_MTTO_CATALOGO_ESTADO_BIT
                @NOMBRE_TABLA='ACA_CARRERAS',@CAMPO_PK='CORR_CARRERA',@CAMPO_ESTADO='ACTIVO',@USA_EMPRESA=1,
                @CORR_EMPRESA=@CORR_EMPRESA,@CORR_RELATIVO=@CORR_CARRERA,
                @SYS_LOGIN_USUARIO=@SYS_LOGIN_USUARIO,@SYS_ESTACION=@SYS_ESTACION,
                @SYS_NUMERO_ERROR=@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR=@SYS_MENSAJE_ERROR OUTPUT,
                @SYS_FILAS_AFECTADAS=@SYS_FILAS_AFECTADAS OUTPUT;
            IF @SYS_NUMERO_ERROR<>0 THROW 51000, @SYS_MENSAJE_ERROR, 1;
        END;
        IF @TRAN_INICIAL=0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @TRAN_INICIAL=0 AND XACT_STATE()<>0 ROLLBACK TRANSACTION;
        ELSE IF @TRAN_INICIAL>0 AND XACT_STATE()=1 ROLLBACK TRANSACTION ACA_CARRERAS_MTTO;
        SELECT @SYS_NUMERO_ERROR=ERROR_NUMBER(),@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),@SYS_FILAS_AFECTADAS=0;
        IF @SYS_NUMERO_ERROR IN (2601,2627) SET @SYS_MENSAJE_ERROR=N'Ya existe una carrera con ese código en la empresa.';
        IF @SYS_NUMERO_ERROR=547 SET @SYS_MENSAJE_ERROR=N'No se puede eliminar la carrera porque tiene registros relacionados. Utilice Desactivar.';
    END CATCH;
END;
GO
-- Registro de menú. No concede permisos a todos los usuarios ni modifica otras opciones.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
DECLARE @AUDITOR varchar(30)='juanh';
DECLARE @ORDEN int=(SELECT ORDEN_OPCION FROM dbo.SEG_CONFIG_OPCION
                   WHERE CODIGO_SISTEMA='ACADEMICS' AND CODIGO_MENU='GENERAL' AND CODIGO_OPCION='ACA_CARRERAS');
IF NOT EXISTS (SELECT 1 FROM dbo.SEG_USUARIO WHERE LOGIN_SISTEMA=@AUDITOR)
    THROW 51000, N'No existe el usuario juanh para registrar la opción.', 1;
IF EXISTS (SELECT 1 FROM dbo.SEG_CONFIG_OPCION WHERE CODIGO_OPCION='ACA_CARRERAS'
           AND (CODIGO_SISTEMA<>'ACADEMICS' OR CODIGO_MENU<>'GENERAL'))
    THROW 51000, N'Carreras ya está configurada en otro menú; revise antes de moverla.', 1;
EXEC dbo.PR_SEG_ASIGNAR_OPCION_MENU
    @CODIGO_SISTEMA='ACADEMICS',@CODIGO_MENU='GENERAL',
    @CODIGO_OPCION='ACA_CARRERAS',@NOMBRE_OPCION=N'Carreras',@URL_OPCION=N'/aca-carreras',
    @LOGIN_ASIGNA=@AUDITOR,@LOGIN_SISTEMA='juanh',
    @ORDEN_OPCION=@ORDEN,
    @NUEVO=1,@MODIFICAR=1,@ELIMINAR=1,@IMPRIMIR=1;
UPDATE dbo.SEG_OPCION_SISTEMA SET IMAGEN_OPCION='mdi mdi-school' WHERE CODIGO_OPCION='ACA_CARRERAS';
COMMIT TRANSACTION;
GO

