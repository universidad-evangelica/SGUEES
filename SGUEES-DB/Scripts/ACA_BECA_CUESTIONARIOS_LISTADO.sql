-- Listado general de cuestionarios por beca. Requiere los scripts de formularios y editor.
-- Solo define una vista; conserva asignaciones, versiones y respuestas existentes.
IF DB_NAME()<>'SGUEES' THROW 51000,N'Este script requiere SGUEES.',1;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_CUESTIONARIOS_MTTO
AS
WITH Preguntas AS (
 SELECT P.CORR_EMPRESA,P.CORR_BECA,P.CORR_FORMULARIO_VERSION,
  COUNT(DISTINCT P.CORR_PREGUNTA_BECA) CANT_PREGUNTAS
 FROM dbo.V_ACA_BECA_EDITOR_PREGUNTA P
 GROUP BY P.CORR_EMPRESA,P.CORR_BECA,P.CORR_FORMULARIO_VERSION
), Relaciones AS (
 SELECT CORR_EMPRESA,CORR_BECA,CORR_FORMULARIO_VERSION FROM Preguntas
 UNION
 SELECT CORR_EMPRESA,CORR_BECA,CORR_FORMULARIO_VERSION
 FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO WHERE ACTIVO=1
)
SELECT B.CORR_EMPRESA,B.CORR_BECA,B.CODIGO_BECA,B.NOMBRE_BECA,
 V.CORR_FORMULARIO_BECA,V.CORR_FORMULARIO_VERSION,V.NOMBRE_FORMULARIO,V.VERSION_FORMULARIO,V.ESTADO_VERSION,
 ISNULL(P.CANT_PREGUNTAS,0) CANT_PREGUNTAS,ISNULL(V.CANT_SOLICITUDES,0) CANT_SOLICITUDES,
 (SELECT COUNT(*) FROM dbo.ACA_PROSPECTO_BECA_TIPO_FORMULARIO A
  WHERE A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_BECA=B.CORR_BECA
   AND A.CORR_FORMULARIO_VERSION=V.CORR_FORMULARIO_VERSION AND A.ACTIVO=1) CANT_ASIGNACIONES
FROM dbo.ACA_BECA_TIPO B
LEFT JOIN Relaciones R ON R.CORR_EMPRESA=B.CORR_EMPRESA AND R.CORR_BECA=B.CORR_BECA
LEFT JOIN dbo.V_ACA_BECA_VERSION_MTTO V ON V.CORR_EMPRESA=R.CORR_EMPRESA AND V.CORR_FORMULARIO_VERSION=R.CORR_FORMULARIO_VERSION
LEFT JOIN Preguntas P ON P.CORR_EMPRESA=R.CORR_EMPRESA AND P.CORR_BECA=R.CORR_BECA AND P.CORR_FORMULARIO_VERSION=R.CORR_FORMULARIO_VERSION;
GO
