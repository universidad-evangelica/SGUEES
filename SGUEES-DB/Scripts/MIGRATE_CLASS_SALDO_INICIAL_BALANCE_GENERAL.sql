    -- 3) Aplicar
    EXEC dbo.PRAL_MIGR_CLASS_SALDO_INICIAL_BALANCE
         @ANIO=2026, @MES=6, @CORR_PARTIDA=@P, @MODO='APLICAR';
================================================================================
*/
