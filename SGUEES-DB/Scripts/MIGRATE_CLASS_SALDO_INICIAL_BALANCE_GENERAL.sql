    -- 2) Crear partida (capturar @CORR_PARTIDA salida)
    DECLARE @P INT, @E NUMERIC(38,0), @M NVARCHAR(4000), @F INT;
    EXEC dbo.PRAL_MIGR_CLASS_SALDO_INICIAL_BALANCE
