SET NOCOUNT ON;
SELECT TOP 30 c.CODIGO_SISTEMA, c.CODIGO_MENU, c.ORDEN_MENU, c.ORDEN_OPCION, c.CODIGO_OPCION, o.NOMBRE_OPCION, o.URL_OPCION
FROM SEG_CONFIG_OPCION c
INNER JOIN SEG_OPCION_SISTEMA o ON o.CODIGO_OPCION = c.CODIGO_OPCION
WHERE c.CODIGO_OPCION LIKE 'COM_%' OR o.URL_OPCION LIKE '/com-%'
ORDER BY c.CODIGO_SISTEMA, c.ORDEN_MENU, c.ORDEN_OPCION;
GO
