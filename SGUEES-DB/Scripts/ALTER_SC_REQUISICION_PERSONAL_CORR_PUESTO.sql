/* -------------------------------------------------------------------------- */
/* 1) Tabla SC_REQUISICION_PERSONAL                                           */
/* -------------------------------------------------------------------------- */
IF COL_LENGTH(N'dbo.SC_REQUISICION_PERSONAL', N'CORR_PUESTO') IS NULL
BEGIN
    ALTER TABLE dbo.SC_REQUISICION_PERSONAL
        ADD CORR_PUESTO INT NULL;
END;
GO

/* Best-effort: rellena CORR_PUESTO desde el descriptor vinculado. */
IF COL_LENGTH(N'dbo.SC_REQUISICION_PERSONAL', N'CORR_PUESTO') IS NOT NULL
   AND COL_LENGTH(N'dbo.SC_REQUISICION_PERSONAL', N'CORR_DESCRIPTOR_PUESTO') IS NOT NULL
   AND OBJECT_ID(N'dbo.SC_DESCRIPTOR_PUESTO', N'U') IS NOT NULL
BEGIN
    UPDATE R
    SET R.CORR_PUESTO = D.CORR_PUESTO
    FROM dbo.SC_REQUISICION_PERSONAL AS R
    INNER JOIN dbo.SC_DESCRIPTOR_PUESTO AS D
        ON D.CORR_EMPRESA = R.CORR_EMPRESA
       AND D.CORR_DESCRIPTOR_PUESTO = R.CORR_DESCRIPTOR_PUESTO
    WHERE R.CORR_PUESTO IS NULL
      AND D.CORR_PUESTO IS NOT NULL
      AND D.CORR_PUESTO > 0;
END;
GO

IF COL_LENGTH(N'dbo.SC_REQUISICION_PERSONAL', N'CORR_PUESTO') IS NOT NULL
   AND OBJECT_ID(N'dbo.PLA_PUESTO', N'U') IS NOT NULL
   AND NOT EXISTS (
        SELECT 1
        FROM sys.foreign_keys
        WHERE name = N'FK_SC_REQUISICION_PERSONAL_PLA_PUESTO'
          AND parent_object_id = OBJECT_ID(N'dbo.SC_REQUISICION_PERSONAL')
    )
BEGIN
    ALTER TABLE dbo.SC_REQUISICION_PERSONAL WITH NOCHECK
        ADD CONSTRAINT FK_SC_REQUISICION_PERSONAL_PLA_PUESTO
        FOREIGN KEY (CORR_EMPRESA, CORR_PUESTO)
        REFERENCES dbo.PLA_PUESTO (CORR_EMPRESA, CORR_PUESTO);
END;
GO

IF COL_LENGTH(N'dbo.SC_REQUISICION_PERSONAL', N'NOMBRE_PUESTO_SOLICITADO') IS NOT NULL
BEGIN
    ALTER TABLE dbo.SC_REQUISICION_PERSONAL
        DROP COLUMN NOMBRE_PUESTO_SOLICITADO;
END;
GO

