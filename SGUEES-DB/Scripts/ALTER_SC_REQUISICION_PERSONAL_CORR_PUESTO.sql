  por CORR_PUESTO (FK a PLA_PUESTO). Actualiza vistas dependientes.

  Ejecutar (UTF-8):
  sqlcmd -S <srv> -d SGUEES -U <user> -P <pwd> -f 65001 -i ALTER_SC_REQUISICION_PERSONAL_CORR_PUESTO.sql
