CREATE OR ALTER PROCEDURE dbo.ACA_SP_BECA_EVALUACION_RECALCULAR @Solicitud int,@Empresa int
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRANSACTION;
  DECLARE @Version int,@Beca int,@Fecha date;
  SELECT @Version=CORR_FORMULARIO_VERSION,@Beca=CORR_BECA,@Fecha=CONVERT(date,ISNULL(FECHA_SOLICITUD,GETDATE()))
  FROM dbo.ACA_PROSPECTO_BECA WITH(UPDLOCK,HOLDLOCK) WHERE CORR_PROSPECTO_BECA=@Solicitud AND CORR_EMPRESA=@Empresa;
  IF @Version IS NULL THROW 51000,N'La solicitud no pertenece a la empresa de sesion.',1;
  IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_SECCION WHERE CORR_EMPRESA=@Empresa AND CORR_FORMULARIO_VERSION=@Version AND ACTIVO=1 AND (PUNTAJE_MAXIMO IS NULL OR PUNTAJE_MAXIMO<0))
   THROW 51000,N'El formulario contiene una seccion sin puntaje maximo valido.',1;
  -- Una sola fuente para bandas numericas; reglas de opciones y generales resueltas a fecha de solicitud.
  UPDATE R SET PUNTAJE_OBTENIDO=CONVERT(decimal(10,2),CASE WHEN V.CORR_PREGUNTA_BECA IS NULL THEN 0
   WHEN P.CODIGO_PREGUNTA IN('SOC_DEPENDIENTES_ECONOMICOS','ACA_PROMEDIO_PRIMERO','ACA_PROMEDIO_SEGUNDO','ACA_PROMEDIO_TERCERO') THEN ISNULL(B.PUNTAJE_OBTENIDO,0)
   ELSE ISNULL(U.PUNTAJE,0) END)
  FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R
  JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=@Empresa
  LEFT JOIN dbo.ACA_FN_BECA_PREGUNTAS_VISIBLES(@Solicitud,@Empresa) V ON V.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA
  LEFT JOIN dbo.V_ACA_BECA_RESPUESTA_CALCULO B ON B.CORR_RESPUESTA_BECA=R.CORR_RESPUESTA_BECA AND B.CORR_EMPRESA=@Empresa
  OUTER APPLY(SELECT TOP(1) U.PUNTAJE FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U
   WHERE U.CORR_EMPRESA=@Empresa AND U.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND ISNULL(U.CORR_OPCION_BECA,0)=ISNULL(R.CORR_OPCION_BECA,0)
    AND U.ACTIVO=1 AND U.FECHA_INICIO<=@Fecha AND (U.FECHA_FIN IS NULL OR U.FECHA_FIN>=@Fecha)
   ORDER BY U.FECHA_INICIO DESC,U.CORR_PUNTAJE_BECA DESC) U
  WHERE R.CORR_PROSPECTO_BECA=@Solicitud AND R.CORR_EMPRESA=@Empresa;
  DECLARE @Secciones TABLE(Id int PRIMARY KEY,Maximo decimal(18,4),Bruto decimal(18,4),Obtenido decimal(18,4),Historico decimal(5,2));
  INSERT @Secciones
  SELECT S.CORR_SECCION_BECA,S.PUNTAJE_MAXIMO,ISNULL(R.Puntos,0),
   CASE WHEN ISNULL(R.Puntos,0)>S.PUNTAJE_MAXIMO THEN S.PUNTAJE_MAXIMO ELSE ISNULL(R.Puntos,0) END,ISNULL(S.PORCENTAJE_SECCION,0)
  FROM dbo.ACA_PROSPECTO_BECA_SECCION S
  OUTER APPLY(SELECT SUM(R.PUNTAJE_OBTENIDO) Puntos FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R
   JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=@Empresa
   WHERE R.CORR_EMPRESA=@Empresa AND R.CORR_PROSPECTO_BECA=@Solicitud AND P.CORR_SECCION_BECA=S.CORR_SECCION_BECA) R
  WHERE S.CORR_EMPRESA=@Empresa AND S.CORR_FORMULARIO_VERSION=@Version AND S.ACTIVO=1
   AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO T ON T.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND T.CORR_EMPRESA=@Empresa AND T.CORR_BECA=@Beca AND T.ACTIVO=1
    WHERE P.CORR_EMPRESA=@Empresa AND P.CORR_SECCION_BECA=S.CORR_SECCION_BECA AND P.ACTIVO=1);
  DECLARE @Maximo decimal(18,4),@Puntos decimal(18,4),@Porcentaje decimal(5,2);
  SELECT @Maximo=ISNULL(SUM(Maximo),0),@Puntos=ISNULL(SUM(Obtenido),0) FROM @Secciones;
  SET @Porcentaje=CASE WHEN @Maximo<=0 THEN 0 WHEN @Puntos>=@Maximo THEN 100 ELSE @Puntos*100.0/@Maximo END;
  UPDATE R SET PUNTAJE_OBTENIDO=CONVERT(decimal(10,2),CASE WHEN S.Bruto<=0 THEN 0 ELSE R.PUNTAJE_OBTENIDO*S.Obtenido/S.Bruto END)
  FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=@Empresa
  JOIN @Secciones S ON S.Id=P.CORR_SECCION_BECA WHERE R.CORR_EMPRESA=@Empresa AND R.CORR_PROSPECTO_BECA=@Solicitud;
  -- Ajustar el residuo de redondeo: incluso las sumas de respuestas respetan el tope.
  ;WITH Distribucion AS(
   SELECT R.CORR_RESPUESTA_BECA,S.Obtenido,
    SUM(R.PUNTAJE_OBTENIDO) OVER(PARTITION BY S.Id) Suma,
    ROW_NUMBER() OVER(PARTITION BY S.Id ORDER BY R.PUNTAJE_OBTENIDO DESC,R.CORR_RESPUESTA_BECA DESC) Fila
   FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=R.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=@Empresa
   JOIN @Secciones S ON S.Id=P.CORR_SECCION_BECA WHERE R.CORR_EMPRESA=@Empresa AND R.CORR_PROSPECTO_BECA=@Solicitud)
  UPDATE R SET PUNTAJE_OBTENIDO=R.PUNTAJE_OBTENIDO+D.Obtenido-D.Suma
  FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R JOIN Distribucion D ON D.CORR_RESPUESTA_BECA=R.CORR_RESPUESTA_BECA
  WHERE D.Fila=1 AND D.Obtenido<>D.Suma;
  UPDATE R SET PORCENTAJE_APLICADO=CONVERT(decimal(5,2),CASE WHEN @Maximo<=0 THEN 0 ELSE R.PUNTAJE_OBTENIDO*100.0/@Maximo END)
  FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA R WHERE R.CORR_EMPRESA=@Empresa AND R.CORR_PROSPECTO_BECA=@Solicitud;
  DELETE dbo.ACA_PROSPECTO_BECA_SECCION_RESULTADO WHERE CORR_PROSPECTO_BECA=@Solicitud AND CORR_EMPRESA=@Empresa;
  INSERT dbo.ACA_PROSPECTO_BECA_SECCION_RESULTADO(CORR_PROSPECTO_BECA,CORR_SECCION_BECA,PUNTAJE_OBTENIDO,PORCENTAJE_OBTENIDO,PORCENTAJE_SECCION_HISTORICO,FECHA_CALCULO,CORR_EMPRESA)
  SELECT @Solicitud,Id,Obtenido,CASE WHEN @Maximo<=0 THEN 0 ELSE Obtenido*100.0/@Maximo END,Historico,GETDATE(),@Empresa FROM @Secciones;
  UPDATE dbo.ACA_PROSPECTO_BECA SET PUNTAJE_TOTAL=@Puntos,PORCENTAJE_TOTAL=@Porcentaje,
   RESULTADO_EVALUACION=CASE WHEN @Porcentaje>=70 THEN 'Potencialmente elegible' WHEN @Porcentaje>=55 THEN 'Elegibilidad condicionada' ELSE 'Baja viabilidad actual' END,
   PRIORIDAD_EVALUACION=CASE WHEN @Porcentaje>=85 THEN 'ALTA' WHEN @Porcentaje>=70 THEN 'MEDIA' WHEN @Porcentaje>=55 THEN 'CONDICIONADA' ELSE 'BAJA' END,
   FECHA_ACTU=GETDATE() WHERE CORR_PROSPECTO_BECA=@Solicitud AND CORR_EMPRESA=@Empresa;
  COMMIT;
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;THROW;
 END CATCH;
END;
GO


