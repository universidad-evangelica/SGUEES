CREATE OR ALTER FUNCTION dbo.ACA_FN_BECA_MAXIMOS(@Empresa int,@Version int,@Beca int,@Fecha date)
RETURNS TABLE
AS RETURN
 SELECT S.CORR_SECCION_BECA,
  CONVERT(decimal(18,4),SUM(CASE
   WHEN P.CODIGO_PREGUNTA='SOC_DEPENDIENTES_ECONOMICOS' THEN ISNULL(BD.Maximo,0)
   WHEN P.CODIGO_PREGUNTA IN('ACA_PROMEDIO_PRIMERO','ACA_PROMEDIO_SEGUNDO','ACA_PROMEDIO_TERCERO') THEN
    CASE WHEN P.CORR_PREGUNTA_BECA=Destino.Id THEN ISNULL(BA.Maximo,0) ELSE 0 END
   WHEN P.TIPO_RESPUESTA='OPCION_MULTIPLE' THEN ISNULL(U.Suma,0) ELSE ISNULL(U.Maximo,0) END)) MAXIMO_POSIBLE
 FROM dbo.ACA_PROSPECTO_BECA_SECCION S
 JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_SECCION_BECA=S.CORR_SECCION_BECA AND P.CORR_EMPRESA=S.CORR_EMPRESA AND P.ACTIVO=1
 OUTER APPLY(SELECT SUM(X.Puntos) Suma,MAX(X.Puntos) Maximo FROM(
  SELECT U.CORR_OPCION_BECA,MAX(U.PUNTAJE) Puntos FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U
  WHERE U.CORR_EMPRESA=@Empresa AND U.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND U.ACTIVO=1
   AND U.FECHA_INICIO<=@Fecha AND (U.FECHA_FIN IS NULL OR U.FECHA_FIN>=@Fecha)
   AND (U.CORR_OPCION_BECA IS NULL OR EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION O WHERE O.CORR_OPCION_BECA=U.CORR_OPCION_BECA AND O.CORR_EMPRESA=@Empresa AND O.ACTIVO=1))
  GROUP BY U.CORR_OPCION_BECA) X) U
 OUTER APPLY(SELECT MAX(PUNTAJE) Maximo FROM dbo.ACA_PROSPECTO_BECA_BANDA WHERE CORR_EMPRESA=@Empresa AND ACTIVO=1 AND CODIGO_REGLA='DEPENDIENTES') BD
 OUTER APPLY(SELECT MAX(PUNTAJE) Maximo FROM dbo.ACA_PROSPECTO_BECA_BANDA WHERE CORR_EMPRESA=@Empresa AND ACTIVO=1 AND CODIGO_REGLA='PROMEDIO_BACHILLERATO') BA
 OUTER APPLY(SELECT TOP(1) A.CORR_PREGUNTA_BECA Id FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA A
  JOIN dbo.ACA_PROSPECTO_BECA_SECCION Z ON Z.CORR_SECCION_BECA=A.CORR_SECCION_BECA AND Z.CORR_EMPRESA=A.CORR_EMPRESA
  WHERE Z.CORR_EMPRESA=@Empresa AND Z.CORR_FORMULARIO_VERSION=@Version AND Z.ACTIVO=1 AND A.ACTIVO=1
   AND A.CODIGO_PREGUNTA IN('ACA_PROMEDIO_PRIMERO','ACA_PROMEDIO_SEGUNDO','ACA_PROMEDIO_TERCERO')
   AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO T WHERE T.CORR_EMPRESA=@Empresa AND T.CORR_BECA=@Beca AND T.CORR_PREGUNTA_BECA=A.CORR_PREGUNTA_BECA AND T.ACTIVO=1)
  ORDER BY A.ORDEN DESC,A.CORR_PREGUNTA_BECA DESC) Destino
 WHERE S.CORR_EMPRESA=@Empresa AND S.CORR_FORMULARIO_VERSION=@Version AND S.ACTIVO=1
  AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO T WHERE T.CORR_EMPRESA=@Empresa AND T.CORR_BECA=@Beca AND T.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND T.ACTIVO=1)
 GROUP BY S.CORR_SECCION_BECA;
GO
CREATE OR ALTER PROCEDURE dbo.ACA_SP_BECA_VALIDAR_PUNTAJES @Empresa int,@Version int,@Seccion int=NULL
AS
BEGIN
 SET NOCOUNT ON;
 IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_EMPRESA=@Empresa AND CORR_FORMULARIO_VERSION=@Version)
  THROW 51000,N'La version no pertenece a la empresa de sesion.',1;
 IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_SECCION WHERE CORR_EMPRESA=@Empresa AND CORR_FORMULARIO_VERSION=@Version AND ACTIVO=1
  AND (@Seccion IS NULL OR CORR_SECCION_BECA=@Seccion) AND (PUNTAJE_MAXIMO IS NULL OR PUNTAJE_MAXIMO<0 OR PORCENTAJE_SECCION IS NULL))
  THROW 51000,N'Cada seccion requiere un puntaje maximo no negativo y un valor historico no nulo.',1;
 DECLARE @Inicio date,@Fin date;
 SELECT @Inicio=FECHA_INICIO,@Fin=ISNULL(FECHA_FIN,'99991231') FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_EMPRESA=@Empresa AND CORR_FORMULARIO_VERSION=@Version;
 DECLARE @Fechas TABLE(Fecha date PRIMARY KEY);
 INSERT @Fechas SELECT @Inicio UNION
  SELECT U.FECHA_INICIO FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=U.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=U.CORR_EMPRESA
  JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
  WHERE S.CORR_EMPRESA=@Empresa AND S.CORR_FORMULARIO_VERSION=@Version AND U.ACTIVO=1 AND U.FECHA_INICIO BETWEEN @Inicio AND @Fin;
 -- Los maximos solo pueden aumentar al comenzar una regla: se comprueba cada inicio de vigencia.
 DECLARE @Error nvarchar(2048);
 SELECT TOP(1) @Error=CONCAT(N'La seccion "',S.NOMBRE_SECCION,N'" permite ',M.MAXIMO_POSIBLE,N' puntos, pero su maximo es ',S.PUNTAJE_MAXIMO,N'. Ajuste los puntajes de sus respuestas o el maximo de la seccion.')
 FROM(SELECT DISTINCT T.CORR_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO T
  JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=T.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=T.CORR_EMPRESA
  JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
  WHERE S.CORR_EMPRESA=@Empresa AND S.CORR_FORMULARIO_VERSION=@Version AND S.ACTIVO=1 AND P.ACTIVO=1 AND T.ACTIVO=1) B
 CROSS JOIN @Fechas F CROSS APPLY dbo.ACA_FN_BECA_MAXIMOS(@Empresa,@Version,B.CORR_BECA,F.Fecha) M
 JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=M.CORR_SECCION_BECA AND S.CORR_EMPRESA=@Empresa
 WHERE (@Seccion IS NULL OR S.CORR_SECCION_BECA=@Seccion) AND M.MAXIMO_POSIBLE>S.PUNTAJE_MAXIMO;
 IF @Error IS NOT NULL THROW 51000,@Error,1;
END;
GO
