    P.TEXTO_PREGUNTA,

    P.TIPO_RESPUESTA,

    ISNULL(R.CORR_OPCION_BECA, 0) AS CORR_OPCION_BECA,

    CASE

        WHEN P.TIPO_RESPUESTA = 'ACEPTACION'

            THEN COALESCE(NULLIF(LTRIM(RTRIM(R.RESPUESTA_TEXTO)), ''), R.TEXTO_OPCION_HISTORICO)

        WHEN P.TIPO_RESPUESTA IN ('OPCION_UNICA', 'OPCION_MULTIPLE', 'SI_NO')

            THEN R.TEXTO_OPCION_HISTORICO

        WHEN P.TIPO_RESPUESTA = 'DOCUMENTO'

            THEN R.ARCHIVO_NOMBRE

        WHEN P.TIPO_RESPUESTA IN ('NUMERO', 'DECIMAL') AND R.RESPUESTA_NUMERO IS NOT NULL

            THEN CASE

                    WHEN R.RESPUESTA_NUMERO = FLOOR(R.RESPUESTA_NUMERO)

                        THEN CONVERT(VARCHAR(40), CONVERT(BIGINT, R.RESPUESTA_NUMERO))

                    ELSE CONVERT(VARCHAR(40), CONVERT(DECIMAL(18, 2), R.RESPUESTA_NUMERO))

                 END

        WHEN P.TIPO_RESPUESTA IN ('TEXTO', 'TEXTO_LARGO')

            THEN R.RESPUESTA_TEXTO

        WHEN R.RESPUESTA_FECHA IS NOT NULL

            THEN CONVERT(VARCHAR(10), R.RESPUESTA_FECHA, 103)

        ELSE COALESCE(R.TEXTO_OPCION_HISTORICO, R.RESPUESTA_TEXTO)

    END AS RESPUESTA,

    CONVERT(decimal(10,2),R.PUNTAJE_OBTENIDO) AS PUNTAJE_OBTENIDO,

    CONVERT(decimal(10,2),R.PORCENTAJE_APLICADO) AS PORCENTAJE_APLICADO

FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R

INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P

    ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA

INNER JOIN dbo.ACA_PROSPECTO_BECA_SECCION AS S

    ON S.CORR_SECCION_BECA = P.CORR_SECCION_BECA

INNER JOIN dbo.ACA_PROSPECTO_BECA AS PB

    ON PB.CORR_PROSPECTO_BECA = R.CORR_PROSPECTO_BECA

WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')

  AND P.TIPO_RESPUESTA <> 'DOCUMENTO';


GO


CREATE OR ALTER VIEW dbo.V_ACA_PROSPECTO_BECA_CONSULTA

AS

SELECT

    PB.CORR_EMPRESA,

    PB.CORR_PROSPECTO_BECA,

    PB.CORR_PROSPECTO,

    --COALESCE(P.CODIGO_PROSPECTO, PB.Cif) AS CODIGO_PROSPECTO,

    COALESCE(P.CODIGO_PROSPECTO, PB.Cif COLLATE DATABASE_DEFAULT) AS CODIGO_PROSPECTO,

    CASE

        WHEN PB.CORR_PROSPECTO IS NOT NULL THEN

            LTRIM(RTRIM(PP.NOMBRES))

                + ' ' + LTRIM(RTRIM(PP.APELLIDO1))

                + ISNULL(' ' + NULLIF(LTRIM(RTRIM(PP.APELLIDO2)), ''), '')

        ELSE

            LTRIM(RTRIM(XA.NOMBRES))

                + ' ' + LTRIM(RTRIM(XA.APELLIDO1))

                + ISNULL(' ' + NULLIF(LTRIM(RTRIM(XA.APELLIDO2)), ''), '')

    END AS NOMBRE_COMPLETO,

    CASE WHEN PB.CORR_PROSPECTO IS NOT NULL THEN PP.DUI ELSE XA.DUI END AS DUI,

    CASE WHEN PB.CORR_PROSPECTO IS NOT NULL THEN CA.NOMBRE_CARRERA ELSE XA.NOMBRE_CARRERA END AS NOMBRE_CARRERA,

    PB.CORR_BECA,

    BT.CODIGO_BECA,

    BT.NOMBRE_BECA,

    PB.CORR_PERIODO_ACADEMICO,

    COALESCE(PB.ANIO_ADMISION,PA.ANIO) AS ANIO,

    COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO) AS NUMERO_PERIODO,

    CAST(COALESCE(PB.ANIO_ADMISION,PA.ANIO) AS VARCHAR(4)) + '-' + RIGHT('0' + CAST(COALESCE(PB.NUMERO_PERIODO_ADMISION,PA.NUMERO_PERIODO) AS VARCHAR(2)), 2) AS CICLO,

    PB.ESTADO_BECA,

    CASE PB.ESTADO_BECA

        WHEN 'BORRADOR' THEN 'Borrador'

        WHEN 'ENVIADA' THEN 'Enviada'

        ELSE PB.ESTADO_BECA

    END AS ESTADO_BECA_TEXTO,

    ISNULL(PB.PUNTAJE_TOTAL,0) AS PUNTAJE_TOTAL,
    ISNULL(PB.PORCENTAJE_TOTAL,0) AS PORCENTAJE_TOTAL,
    PB.RESULTADO_EVALUACION,PB.PRIORIDAD_EVALUACION,
    PB.FECHA_SOLICITUD

FROM dbo.ACA_PROSPECTO_BECA AS PB

INNER JOIN dbo.ACA_BECA_TIPO AS BT

    ON BT.CORR_BECA = PB.CORR_BECA

LEFT JOIN dbo.ACA_PERIODOS_ACADEMICOS AS PA

    ON PA.CORR_PERIODO_ACADEMICO = PB.CORR_PERIODO_ACADEMICO

LEFT JOIN dbo.ACA_PROSPECTO AS P

    ON P.CORR_PROSPECTO = PB.CORR_PROSPECTO

LEFT JOIN dbo.ACA_PROSPECTO_PERSONA AS PP

    ON PP.CORR_PROSPECTO = PB.CORR_PROSPECTO

LEFT JOIN dbo.ACA_PLANES_ACADEMICOS AS PL

    ON PL.CORR_PLAN_ACADEMICO = P.CORR_PLAN_ACADEMICO

LEFT JOIN dbo.ACA_CARRERAS AS CA

    ON CA.CORR_CARRERA = PL.CORR_CARRERA

OUTER APPLY (

    -- Datos del prospecto de SIS_ADMISION guardados al momento de la solicitud.

    SELECT

        PB.DATOS_ADMISION.value('(/Prospecto/Names/text())[1]',          'nvarchar(200)') COLLATE Modern_Spanish_CI_AS AS NOMBRES,

        PB.DATOS_ADMISION.value('(/Prospecto/FirstLastName/text())[1]',  'nvarchar(100)') COLLATE Modern_Spanish_CI_AS AS APELLIDO1,

        PB.DATOS_ADMISION.value('(/Prospecto/SecondLastName/text())[1]', 'nvarchar(100)') COLLATE Modern_Spanish_CI_AS AS APELLIDO2,

        PB.DATOS_ADMISION.value('(/Prospecto/DUI/text())[1]',            'nvarchar(20)')  COLLATE Modern_Spanish_CI_AS AS DUI,

        (SELECT NOMBRE_CARRERA FROM ACA_CARRERAS WHERE CODIGO_CARRERA = PB.DATOS_ADMISION.value('(/Prospecto/CareerCode/text())[1]',     'nvarchar(300)') COLLATE Modern_Spanish_CI_AS) AS NOMBRE_CARRERA

) AS XA

WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')

  AND (PA.CORR_AREA_ACADEMICA = 5 OR PB.INFORMATION_ID_SIS_ADMISION IS NOT NULL);


GO
