/*
  Solo crea GEN_PERSONA_BANCO (+ FKs) y V_GEN_PERSONA_BANCO.
  Uso:
    sqlcmd -S <srv> -d SGUEES -U <user> -P <pwd> -f 65001 -i DEPLOY_GEN_PERSONA_BANCO_TABLA.sql

  Si al Guardar proveedor aparece error de @CUENTA_BANCARIA, ejecute también:
    FIX_PRAL_MTTO_GEN_PROVEEDOR_SIN_BANCO.sql
*/
SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

IF OBJECT_ID(N'dbo.GEN_PERSONA_BANCO', N'U') IS NULL
BEGIN
	CREATE TABLE [dbo].[GEN_PERSONA_BANCO]
	(
		[CORR_EMPRESA] [int] NOT NULL,
		[CORR_PERSONA] [bigint] NOT NULL,
		[CORR_PERSONA_BANCO] [int] NOT NULL,
		[CORR_BANCO] [int] NOT NULL,
		[CUENTA_BANCARIA] [varchar](30) NOT NULL,
		[USUARIO_CREA] [varchar](50) NULL,
		[FECHA_CREA] [datetime] NULL,
		[ESTACION_CREA] [varchar](50) NULL,
		[USUARIO_ACTU] [varchar](50) NULL,
		[FECHA_ACTU] [datetime] NULL,
		[ESTACION_ACTU] [varchar](50) NULL,
		CONSTRAINT [PK_GEN_PERSONA_BANCO] PRIMARY KEY CLUSTERED
		(
			[CORR_EMPRESA] ASC,
			[CORR_PERSONA] ASC,
			[CORR_PERSONA_BANCO] ASC
		)
	);
	PRINT N'Tabla GEN_PERSONA_BANCO creada.';
END
ELSE
	PRINT N'Tabla GEN_PERSONA_BANCO ya existe.';
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_EMPRESA')
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_EMPRESA]
		FOREIGN KEY ([CORR_EMPRESA]) REFERENCES [dbo].[GEN_EMPRESA] ([CORR_EMPRESA]);
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_PERSONA')
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_PERSONA]
		FOREIGN KEY ([CORR_PERSONA]) REFERENCES [dbo].[GEN_PERSONA] ([CORR_PERSONA]);
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_BANCO')
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_BANCO]
		FOREIGN KEY ([CORR_EMPRESA], [CORR_BANCO])
		REFERENCES [dbo].[GEN_BANCO] ([CORR_EMPRESA], [CORR_BANCO]);
END
GO

CREATE OR ALTER VIEW [dbo].[V_GEN_PERSONA_BANCO]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PERSONA,
	A.CORR_PERSONA_BANCO,
	A.CORR_BANCO,
	ISNULL(B.NOMBRE_BANCO, N'') AS NOMBRE_BANCO,
	A.CUENTA_BANCARIA,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU
FROM dbo.GEN_PERSONA_BANCO A
LEFT JOIN dbo.GEN_BANCO B
	ON B.CORR_EMPRESA = A.CORR_EMPRESA
	AND B.CORR_BANCO = A.CORR_BANCO
GO

PRINT N'DEPLOY_GEN_PERSONA_BANCO_TABLA completado.';
GO
