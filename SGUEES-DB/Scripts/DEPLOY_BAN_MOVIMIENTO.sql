CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_APLICAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE
		@ESTADO VARCHAR(2),
		@ESTA_CONTABILIZADO BIT,
		@MONTO_CARGO DECIMAL(18, 2),
		@MONTO_ABONO DECIMAL(18, 2),
		@NOMBRE_TIPO_MOVIMIENTO VARCHAR(100),
		@DETALLE_DOCUMENTO NVARCHAR(255),
		@CUENTA_CONTABLE_BANCO VARCHAR(30),
		@CORR_MOVIMIENTO INT,
		@CORR_CUENTA_BANCO INT,
		@FECHA_MOVIMIENTO DATE,
		@NOMBRE_BENEFICIARIO VARCHAR(255),
		@DESCRIPCION_MOVIMIENTO VARCHAR(1000),
		@REFERENCIA VARCHAR(255),
		@CORR_DOCUMENTO_DETA INT,
		@MONTO_CARGO_DETA DECIMAL(12, 2),
		@MONTO_ABONO_DETA DECIMAL(12, 2),
		@DESCRIPCION_MOVIMIENTO_DETA VARCHAR(1255);

	DECLARE @MOVIMIENTOS TABLE
	(
		CORR_DOCUMENTO_DETA INT NOT NULL,
		MONTO_CARGO_DETA DECIMAL(12, 2) NOT NULL,
		MONTO_ABONO_DETA DECIMAL(12, 2) NOT NULL,
		DESCRIPCION_MOVIMIENTO_DETA VARCHAR(1255) NOT NULL
	);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE());

	BEGIN TRY
		SELECT @NOMBRE_TIPO_MOVIMIENTO = NOMBRE_TIPO_MOVIMIENTO
		FROM dbo.BAN_TIPO_MOVI_BANCARIO
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

		SET @DETALLE_DOCUMENTO = @NOMBRE_TIPO_MOVIMIENTO + N' del Año ' + CONVERT(VARCHAR(10), @ANIO_PERIODO)
			+ N' Mes ' + CONVERT(VARCHAR(10), @MES_PERIODO)
			+ N' Correlativo No.' + CONVERT(VARCHAR(10), @CORR_DOCUMENTO);

		SELECT
			@ESTADO = ESTADO_DOCUMENTO,
			@ESTA_CONTABILIZADO = ESTA_CONTABILIZADO,
			@CORR_CUENTA_BANCO = CORR_CUENTA_BANCO,
			@FECHA_MOVIMIENTO = FECHA_EMISION,
			@NOMBRE_BENEFICIARIO = ISNULL(NOMBRE_BENEFICIARIO, N''),
			@DESCRIPCION_MOVIMIENTO = NOMBRE_PARTIDA,
			@REFERENCIA = LTRIM(RTRIM(CONVERT(VARCHAR(25), NUMERO_DOCUMENTO)))
		FROM dbo.BAN_DOCUMENTO
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @ESTADO IN ('AP', 'IM', 'AN') OR ISNULL(@ESTA_CONTABILIZADO, 0) <> 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'Este documento ya está aplicado o anulado. ' + @DETALLE_DOCUMENTO + N' no se puede aplicar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND ISNULL(ESTADO_PERIODO_BAN, 'AB') = 'AB'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30001,
				@SYS_MENSAJE_ERROR = N'El período bancario no está abierto. ' + @DETALLE_DOCUMENTO + N' no se puede aplicar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.BAN_DOCUMENTO_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND CORR_DOCUMENTO = @CORR_DOCUMENTO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30004,
				@SYS_MENSAJE_ERROR = N'El documento no tiene detalle contable. ' + @DETALLE_DOCUMENTO + N' no se puede aplicar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT @MONTO_CARGO = SUM(MONTO_CARGO), @MONTO_ABONO = SUM(MONTO_ABONO)
		FROM dbo.BAN_DOCUMENTO_DETA
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF ISNULL(@MONTO_CARGO, 0) <> ISNULL(@MONTO_ABONO, 0)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'El detalle contable no está cuadrado (cargo ≠ abono). ' + @DETALLE_DOCUMENTO + N' no se puede aplicar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT @CUENTA_CONTABLE_BANCO = CUENTA_CONTABLE
		FROM dbo.BAN_CUENTA_BANCARIA
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.BAN_DOCUMENTO_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND CORR_DOCUMENTO = @CORR_DOCUMENTO
				AND CUENTA_CONTABLE = @CUENTA_CONTABLE_BANCO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30005,
				@SYS_MENSAJE_ERROR = N'El documento no contiene la cuenta contable del banco. ' + @DETALLE_DOCUMENTO + N' no se puede aplicar.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		INSERT INTO @MOVIMIENTOS (CORR_DOCUMENTO_DETA, MONTO_CARGO_DETA, MONTO_ABONO_DETA, DESCRIPCION_MOVIMIENTO_DETA)
		SELECT B.CORR_DOCUMENTO_DETA, ISNULL(B.MONTO_CARGO, 0), ISNULL(B.MONTO_ABONO, 0), B.NOMBRE_TRAN
		FROM dbo.BAN_DOCUMENTO_DETA B
		WHERE B.CORR_EMPRESA = @CORR_EMPRESA
			AND B.ANIO_PERIODO = @ANIO_PERIODO
			AND B.MES_PERIODO = @MES_PERIODO
			AND B.CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND B.CORR_DOCUMENTO = @CORR_DOCUMENTO
			AND B.CUENTA_CONTABLE = @CUENTA_CONTABLE_BANCO;

		SET @CORR_MOVIMIENTO = 0;
		BEGIN TRANSACTION BAN_DOCUMENTO_APLICAR;

		WHILE EXISTS (SELECT 1 FROM @MOVIMIENTOS)
		BEGIN
			SELECT TOP 1
				@CORR_DOCUMENTO_DETA = CORR_DOCUMENTO_DETA,
				@MONTO_CARGO_DETA = MONTO_CARGO_DETA,
				@MONTO_ABONO_DETA = MONTO_ABONO_DETA,
				@DESCRIPCION_MOVIMIENTO_DETA = DESCRIPCION_MOVIMIENTO_DETA
			FROM @MOVIMIENTOS;

			EXEC dbo.PRAL_MTTO_BAN_MOVIMIENTO
				1,
				@CORR_EMPRESA,
				@ANIO_PERIODO,
				@MES_PERIODO,
				@CORR_CUENTA_BANCO,
				@CORR_MOVIMIENTO OUTPUT,
				@FECHA_MOVIMIENTO,
				@CORR_TIPO_MOVIMIENTO,
				@REFERENCIA,
				@NOMBRE_BENEFICIARIO,
				@DESCRIPCION_MOVIMIENTO_DETA,
				@MONTO_CARGO_DETA,
				@MONTO_ABONO_DETA,
				@USUARIO_ACTU,
				@FECHA_ACTU,
				@ESTACION_ACTU,
				@USUARIO_ACTU,
				@FECHA_ACTU,
				@ESTACION_ACTU,
				@CORR_DOCUMENTO,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR OUTPUT,
				@CORR_DOCUMENTO_DETA,
				@ANIO_PERIODO,
				@MES_PERIODO;

			IF @SYS_NUMERO_ERROR <> 0
			BEGIN
				IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_APLICAR;
				SET @SYS_MENSAJE_ERROR = N'No se pudo generar el movimiento bancario. ' + @SYS_MENSAJE_ERROR;
				GOTO FINA;
			END;

			DELETE FROM @MOVIMIENTOS WHERE CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA;
		END;

		UPDATE dbo.BAN_DOCUMENTO SET
			ESTADO_DOCUMENTO = 'AP',
			CORR_MOVIMIENTO = @CORR_MOVIMIENTO,
			USUARIO_ACTU = @USUARIO_ACTU,
			FECHA_ACTU = @FECHA_ACTU,
			ESTACION_ACTU = @ESTACION_ACTU
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;

		IF @@TRANCOUNT > 0 COMMIT TRANSACTION BAN_DOCUMENTO_APLICAR;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_APLICAR;
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

/* ── Anular documento (elimina movimientos si aplicado/impreso) ── */
IF OBJECT_ID(N'dbo.PRAL_MTTO_BAN_DOCUMENTO_ANULAR', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_ANULAR];
GO

CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_DOCUMENTO_ANULAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE @ESTADO VARCHAR(2), @FECHA_ANULACION DATE;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE());
	SET @FECHA_ANULACION = CAST(@FECHA_ACTU AS DATE);

	BEGIN TRY
		SELECT @ESTADO = ESTADO_DOCUMENTO
		FROM dbo.BAN_DOCUMENTO
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @ESTADO = 'AN'
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El documento ya está anulado', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		BEGIN TRANSACTION BAN_DOCUMENTO_ANULAR;

		IF @ESTADO IN ('AP', 'IM')
		BEGIN
			DELETE FROM dbo.BAN_MOVIMIENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ISNULL(ANIO_PERIODO_DOC, ANIO_PERIODO) = @ANIO_PERIODO
				AND ISNULL(MES_PERIODO_DOC, MES_PERIODO) = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
				AND CORR_DOCUMENTO = @CORR_DOCUMENTO;
		END;

		UPDATE dbo.BAN_DOCUMENTO SET
			ESTADO_DOCUMENTO = 'AN',
			FECHA_ANULACION = @FECHA_ANULACION,
			CORR_MOVIMIENTO = NULL,
			CORR_MOVIMIENTO_DESTINO = NULL,
			USUARIO_ACTU = @USUARIO_ACTU,
			FECHA_ACTU = @FECHA_ACTU,
			ESTACION_ACTU = @ESTACION_ACTU
		WHERE CORR_EMPRESA = @CORR_EMPRESA
			AND ANIO_PERIODO = @ANIO_PERIODO
			AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;

		IF @@TRANCOUNT > 0 COMMIT TRANSACTION BAN_DOCUMENTO_ANULAR;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION BAN_DOCUMENTO_ANULAR;
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

