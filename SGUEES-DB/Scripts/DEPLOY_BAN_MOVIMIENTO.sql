CREATE VIEW [dbo].[V_BAN_CHEQUE_IMPRIME]
AS
SELECT
	A.CORR_EMPRESA,
	D.NOMBRE_EMPRESA,
	A.ANIO_PERIODO,
	A.MES_PERIODO,
	A.CORR_TIPO_MOVIMIENTO,
	A.NOMBRE_TIPO_MOVIMIENTO,
	A.CLASE_MOVIMIENTO,
	A.CORR_DOCUMENTO,
	A.CORR_CUENTA_BANCO,
	A.NOMBRE_CUENTA_BANCO,
	A.NUMERO_CUENTA_BANCO,
	A.NUMERO_DOCUMENTO,
	A.SERIE_CHEQUE,
	N'SAN SALVADOR, ' + LTRIM(RTRIM(CONVERT(VARCHAR(2), DAY(A.FECHA_EMISION)))) + N' DE '
		+ CASE MONTH(A.FECHA_EMISION)
			WHEN 1 THEN N'ENERO' WHEN 2 THEN N'FEBRERO' WHEN 3 THEN N'MARZO' WHEN 4 THEN N'ABRIL'
			WHEN 5 THEN N'MAYO' WHEN 6 THEN N'JUNIO' WHEN 7 THEN N'JULIO' WHEN 8 THEN N'AGOSTO'
			WHEN 9 THEN N'SEPTIEMBRE' WHEN 10 THEN N'OCTUBRE' WHEN 11 THEN N'NOVIEMBRE' WHEN 12 THEN N'DICIEMBRE'
			ELSE N'' END + N' DE ' + LTRIM(RTRIM(CONVERT(VARCHAR(4), YEAR(A.FECHA_EMISION)))) AS LUGAR_FECHA,
	A.FECHA_EMISION,
	A.NOMBRE_PARTIDA,
	A.CORR_PROVEEDOR,
	A.NOMBRE_BENEFICIARIO,
	A.MONTO_DOCUMENTO,
	A.ESTADO_DOCUMENTO,
	A.NOMBRE_ESTADO_DOCUMENTO,
	A.CANTIDAD_LETRAS,
	A.FECHA_IMPRESO,
	A.CORR_MOVIMIENTO,
	A.CORR_TIPO_CHEQUE,
	A.NOMBRE_TIPO_CHEQUE,
	A.CORR_CHEQUERA,
	B.CORR_DOCUMENTO_DETA,
	B.CUENTA_CONTABLE,
	ISNULL(C.NOMBRE_CUENTA, N'') NOMBRE_CUENTA,
	B.CORR_CENTRO_COSTO,
	N'CHQ #' + LTRIM(RTRIM(CONVERT(VARCHAR(20), A.NUMERO_DOCUMENTO))) + N' ' + B.NOMBRE_TRAN AS NOMBRE_TRAN,
	B.MONTO_CARGO,
	B.MONTO_ABONO,
	ISNULL(G.NOMBRE_MONEDA, N'') NOMBRE_MONEDA,
	ISNULL(G.SIMBOLO, N'') SIMBOLO_MONEDA
FROM dbo.V_BAN_DOCUMENTO A
INNER JOIN dbo.V_BAN_DOCUMENTO_DETA B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.ANIO_PERIODO = B.ANIO_PERIODO
	AND A.MES_PERIODO = B.MES_PERIODO
	AND A.CORR_TIPO_MOVIMIENTO = B.CORR_TIPO_MOVIMIENTO
	AND A.CORR_DOCUMENTO = B.CORR_DOCUMENTO
INNER JOIN dbo.CON_CATALOGO_CUENTA C
	ON B.CORR_EMPRESA = C.CORR_EMPRESA AND B.CUENTA_CONTABLE = C.CUENTA_CONTABLE
INNER JOIN dbo.V_GEN_EMPRESA D
	ON A.CORR_EMPRESA = D.CORR_EMPRESA
LEFT JOIN dbo.GEN_TIPO_MONEDA G
	ON A.CORR_MONEDA = G.CORR_MONEDA
WHERE A.CLASE_MOVIMIENTO = 'CHQ';
