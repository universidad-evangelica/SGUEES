CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_MOVIMIENTO]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_CUENTA_BANCO INT,
	@CORR_MOVIMIENTO INT OUTPUT,
	@FECHA_MOVIMIENTO DATE,
	@CORR_TIPO_MOVIMIENTO INT,
	@REFERENCIA VARCHAR(255),
	@NOMBRE_BENEFICIARIO VARCHAR(255),
	@DESCRIPCION_MOVIMIENTO VARCHAR(1000),
	@MONTO_CARGO DECIMAL(12, 2),
	@MONTO_ABONO DECIMAL(12, 2),
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@CORR_DOCUMENTO INT = NULL,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT,
	@CORR_DOCUMENTO_DETA INT = NULL,
	@ANIO_PERIODO_DOC INT = 0,
	@MES_PERIODO_DOC INT = 0
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF ISNULL(@ANIO_PERIODO_DOC, 0) = 0
			SET @ANIO_PERIODO_DOC = @ANIO_PERIODO;
		IF ISNULL(@MES_PERIODO_DOC, 0) = 0
			SET @MES_PERIODO_DOC = @MES_PERIODO;

		IF NOT EXISTS (
			SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND ISNULL(ESTADO_PERIODO_BAN, 'AB') = 'AB'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'El período bancario no está abierto.',
				@SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_MOVIMIENTO = ISNULL(MAX(CORR_MOVIMIENTO), 0) + 1
			FROM dbo.BAN_MOVIMIENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO;

			INSERT INTO dbo.BAN_MOVIMIENTO
			(
				CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_CUENTA_BANCO, CORR_MOVIMIENTO,
				FECHA_MOVIMIENTO, CORR_TIPO_MOVIMIENTO, REFERENCIA, NOMBRE_BENEFICIARIO,
				DESCRIPCION_MOVIMIENTO, MONTO_CARGO, MONTO_ABONO,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA, USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU,
				CORR_DOCUMENTO, CORR_DOCUMENTO_DETA, ANIO_PERIODO_DOC, MES_PERIODO_DOC
			)
			VALUES
			(
				@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_CUENTA_BANCO, @CORR_MOVIMIENTO,
				@FECHA_MOVIMIENTO, @CORR_TIPO_MOVIMIENTO, @REFERENCIA, @NOMBRE_BENEFICIARIO,
				@DESCRIPCION_MOVIMIENTO, @MONTO_CARGO, @MONTO_ABONO,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA, @USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU,
				@CORR_DOCUMENTO, @CORR_DOCUMENTO_DETA, @ANIO_PERIODO_DOC, @MES_PERIODO_DOC
			);
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.BAN_MOVIMIENTO SET
				FECHA_MOVIMIENTO = @FECHA_MOVIMIENTO,
				CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO,
				REFERENCIA = @REFERENCIA,
				NOMBRE_BENEFICIARIO = @NOMBRE_BENEFICIARIO,
				DESCRIPCION_MOVIMIENTO = @DESCRIPCION_MOVIMIENTO,
				MONTO_CARGO = @MONTO_CARGO,
				MONTO_ABONO = @MONTO_ABONO,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU,
				CORR_DOCUMENTO = @CORR_DOCUMENTO,
				CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA,
				ANIO_PERIODO_DOC = @ANIO_PERIODO_DOC,
				MES_PERIODO_DOC = @MES_PERIODO_DOC
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
				AND CORR_MOVIMIENTO = @CORR_MOVIMIENTO;
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.BAN_MOVIMIENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND MES_PERIODO = @MES_PERIODO
				AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
				AND CORR_MOVIMIENTO = @CORR_MOVIMIENTO;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

