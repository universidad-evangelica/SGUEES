CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_SOLI_CHEQUE_APLICAR_SOLICITUD]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT OUTPUT,
	@CORR_CUENTA_BANCO INT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE
		@ESTADO_DOCUMENTO VARCHAR(2),
		@ANIO_PERIODO_CHEQUE INT,
		@MES_PERIODO_CHEQUE INT,
		@CORR_TIPO_MOVIMIENTO_CHEQUE INT,
		@CORR_DOCUMENTO_CHEQUE INT,
		@FECHA_EMISION DATE,
		@NUMERO_DOCUMENTO BIGINT,
		@NOMBRE_PARTIDA VARCHAR(1000),
		@CORR_PROVEEDOR INT,
		@CORR_EMPLEADO INT,
		@CORR_CLIENTE INT,
		@NOMBRE_BENEFICIARIO VARCHAR(255),
		@MONTO_DOCUMENTO DECIMAL(18, 2),
		@FECHA_APLICADO DATE,
		@CANTIDAD_LETRAS VARCHAR(255),
		@CORR_TIPO_CHEQUE INT,
		@USUARIO_ACTU VARCHAR(30),
		@FECHA_ACTU DATETIME,
		@ESTACION_ACTU VARCHAR(50),
		@CORR_MONEDA INT,
		@CORR_DOCUMENTO_DETA INT,
		@SRC_DOCUMENTO_DETA INT,
		@CUENTA_CONTABLE VARCHAR(30),
		@CORR_CENTRO_COSTO INT,
		@NOMBRE_TRAN VARCHAR(1255),
		@MONTO_CARGO DECIMAL(12, 2),
		@MONTO_ABONO DECIMAL(12, 2);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @USUARIO_ACTU = @SYS_LOGIN_USUARIO;
	SET @FECHA_ACTU = GETDATE();
	SET @ESTACION_ACTU = @SYS_ESTACION;
	SET @FECHA_APLICADO = CAST(GETDATE() AS DATE);

	BEGIN TRY
		SELECT @ESTADO_DOCUMENTO = ESTADO_DOCUMENTO
		FROM dbo.BAN_SOLI_CHEQUE
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		IF @ESTADO_DOCUMENTO <> 'SO'
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30001, @SYS_MENSAJE_ERROR = N'No se puede autorizar esta solicitud', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF @CORR_CUENTA_BANCO IS NULL OR NOT EXISTS (
			SELECT 1 FROM dbo.BAN_CUENTA_BANCARIA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe la cuenta bancaria seleccionada', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT @CORR_TIPO_MOVIMIENTO_CHEQUE = CORR_TIPO_MOVIMIENTO
		FROM dbo.V_BAN_TIPO_MOVI_BANCARIO
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CLASE_MOVIMIENTO = 'CHQ';

		IF ISNULL(@CORR_TIPO_MOVIMIENTO_CHEQUE, 0) = 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30002, @SYS_MENSAJE_ERROR = N'No está configurado el tipo de movimiento de cheque', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT
			@ANIO_PERIODO_CHEQUE = YEAR(FECHA_EMISION),
			@MES_PERIODO_CHEQUE = MONTH(FECHA_EMISION),
			@FECHA_EMISION = FECHA_EMISION,
			@CORR_DOCUMENTO_CHEQUE = 0,
			@NUMERO_DOCUMENTO = NUMERO_DOCUMENTO,
			@NOMBRE_PARTIDA = NOMBRE_PARTIDA,
			@CORR_PROVEEDOR = CORR_PROVEEDOR,
			@CORR_EMPLEADO = CORR_EMPLEADO,
			@CORR_CLIENTE = CORR_CLIENTE,
			@NOMBRE_BENEFICIARIO = NOMBRE_BENEFICIARIO,
			@MONTO_DOCUMENTO = MONTO_DOCUMENTO,
			@CANTIDAD_LETRAS = CANTIDAD_LETRAS,
			@CORR_TIPO_CHEQUE = CORR_TIPO_CHEQUE
		FROM dbo.BAN_SOLI_CHEQUE
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SELECT @CORR_MONEDA = CORR_MONEDA
		FROM dbo.CON_PARAMETRO
		WHERE CORR_EMPRESA = @CORR_EMPRESA;

		EXEC dbo.PRAL_MTTO_BAN_DOCUMENTO
			@TIPO_ACTUALIZA = 1,
			@CORR_EMPRESA = @CORR_EMPRESA,
			@ANIO_PERIODO = @ANIO_PERIODO_CHEQUE,
			@MES_PERIODO = @MES_PERIODO_CHEQUE,
			@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE,
			@CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE OUTPUT,
			@CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO,
			@NUMERO_DOCUMENTO = @NUMERO_DOCUMENTO,
			@FECHA_EMISION = @FECHA_EMISION,
			@NOMBRE_PARTIDA = @NOMBRE_PARTIDA,
			@CORR_PROVEEDOR = @CORR_PROVEEDOR,
			@CORR_EMPLEADO = @CORR_EMPLEADO,
			@CORR_CLIENTE = @CORR_CLIENTE,
			@NOMBRE_BENEFICIARIO = @NOMBRE_BENEFICIARIO,
			@MONTO_DOCUMENTO = @MONTO_DOCUMENTO,
			@ESTADO_DOCUMENTO = 'DI',
			@ESTA_CONTABILIZADO = 0,
			@CANTIDAD_LETRAS = @CANTIDAD_LETRAS,
			@USUARIO_CREA = @SYS_LOGIN_USUARIO,
			@FECHA_CREA = @FECHA_ACTU,
			@ESTACION_CREA = @SYS_ESTACION,
			@USUARIO_ACTU = @USUARIO_ACTU,
			@FECHA_ACTU = @FECHA_ACTU,
			@ESTACION_ACTU = @ESTACION_ACTU,
			@CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE,
			@CORR_MONEDA = @CORR_MONEDA,
			@FACTOR_CAMBIO = 1,
			@OPERADOR = '*',
			@GENERA_DETALLE = 0,
			@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
			@SYS_ESTACION = @SYS_ESTACION,
			@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

		IF @SYS_NUMERO_ERROR <> 0
			GOTO FINA;

		DECLARE @TEMP1 TABLE
		(
			CORR_DOCUMENTO_DETA INT,
			CUENTA_CONTABLE VARCHAR(30),
			CORR_CENTRO_COSTO INT,
			NOMBRE_TRAN VARCHAR(1255),
			MONTO_CARGO DECIMAL(12, 2),
			MONTO_ABONO DECIMAL(12, 2),
			ESTA_PROC BIT NOT NULL DEFAULT 0
		);

		INSERT INTO @TEMP1 (CORR_DOCUMENTO_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
		SELECT CORR_DOCUMENTO_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO
		FROM dbo.BAN_SOLI_CHEQUE_DETA
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		WHILE EXISTS (SELECT 1 FROM @TEMP1 WHERE ESTA_PROC = 0)
		BEGIN
			SELECT TOP 1
				@SRC_DOCUMENTO_DETA = CORR_DOCUMENTO_DETA,
				@CUENTA_CONTABLE = CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO = CORR_CENTRO_COSTO,
				@NOMBRE_TRAN = NOMBRE_TRAN,
				@MONTO_CARGO = MONTO_CARGO,
				@MONTO_ABONO = MONTO_ABONO
			FROM @TEMP1
			WHERE ESTA_PROC = 0
			ORDER BY CORR_DOCUMENTO_DETA;

			SET @CORR_DOCUMENTO_DETA = 0;

			EXEC dbo.PRAL_MTTO_BAN_DOCUMENTO_DETA
				@TIPO_ACTUALIZA = 1,
				@CORR_EMPRESA = @CORR_EMPRESA,
				@ANIO_PERIODO = @ANIO_PERIODO_CHEQUE,
				@MES_PERIODO = @MES_PERIODO_CHEQUE,
				@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE,
				@CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE,
				@CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA OUTPUT,
				@CUENTA_CONTABLE = @CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO = @CORR_CENTRO_COSTO,
				@NOMBRE_TRAN = @NOMBRE_TRAN,
				@MONTO_CARGO = @MONTO_CARGO,
				@MONTO_ABONO = @MONTO_ABONO,
				@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
				@SYS_ESTACION = @SYS_ESTACION,
				@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

			IF @SYS_NUMERO_ERROR <> 0
			BEGIN
				DELETE FROM dbo.BAN_DOCUMENTO_DETA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO_CHEQUE AND MES_PERIODO = @MES_PERIODO_CHEQUE
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE AND CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE;

				DELETE FROM dbo.BAN_DOCUMENTO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO_CHEQUE AND MES_PERIODO = @MES_PERIODO_CHEQUE
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE AND CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE;

				GOTO FINA;
			END;

			UPDATE @TEMP1 SET ESTA_PROC = 1
			WHERE CORR_DOCUMENTO_DETA = @SRC_DOCUMENTO_DETA;
		END;

		EXEC dbo.PRAL_MTTO_BAN_DOCUMENTO_APLICAR
			@CORR_EMPRESA = @CORR_EMPRESA,
			@ANIO_PERIODO = @ANIO_PERIODO_CHEQUE,
			@MES_PERIODO = @MES_PERIODO_CHEQUE,
			@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE,
			@CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE,
			@USUARIO_ACTU = @USUARIO_ACTU,
			@FECHA_ACTU = @FECHA_ACTU,
			@ESTACION_ACTU = @ESTACION_ACTU,
			@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
			@SYS_ESTACION = @SYS_ESTACION,
			@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

		IF @SYS_NUMERO_ERROR <> 0
		BEGIN
			DELETE FROM dbo.BAN_DOCUMENTO_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO_CHEQUE AND MES_PERIODO = @MES_PERIODO_CHEQUE
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE AND CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE;

			DELETE FROM dbo.BAN_DOCUMENTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO_CHEQUE AND MES_PERIODO = @MES_PERIODO_CHEQUE
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO_CHEQUE AND CORR_DOCUMENTO = @CORR_DOCUMENTO_CHEQUE;

			GOTO FINA;
		END;

		UPDATE dbo.BAN_SOLI_CHEQUE SET
			ESTADO_DOCUMENTO = 'AP',
			FECHA_APLICADO = @FECHA_APLICADO,
			APLICADO_POR = @SYS_LOGIN_USUARIO,
			ANIO_PERIODO_CHEQUE = @ANIO_PERIODO_CHEQUE,
			MES_PERIODO_CHEQUE = @MES_PERIODO_CHEQUE,
			CORR_TIPO_MOVIMIENTO_CHEQUE = @CORR_TIPO_MOVIMIENTO_CHEQUE,
			CORR_DOCUMENTO_CHEQUE = @CORR_DOCUMENTO_CHEQUE,
			CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO,
			USUARIO_ACTU = @USUARIO_ACTU,
			FECHA_ACTU = @FECHA_ACTU,
			ESTACION_ACTU = @ESTACION_ACTU
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
