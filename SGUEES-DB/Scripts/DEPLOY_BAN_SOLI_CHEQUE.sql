CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_SOLI_CHEQUE_DETA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@CORR_DOCUMENTO_DETA INT OUTPUT,
	@CUENTA_CONTABLE VARCHAR(30),
	@CORR_CENTRO_COSTO INT = NULL,
	@NOMBRE_TRAN VARCHAR(1255),
	@MONTO_CARGO DECIMAL(12, 2) = 0,
	@MONTO_ABONO DECIMAL(12, 2) = 0,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2, 3)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_SOLI_CHEQUE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
					AND ESTADO_DOCUMENTO = 'DI'
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'La solicitud no está en estado Digitado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF @TIPO_ACTUALIZA IN (1, 2)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_CATALOGO_CUENTA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CUENTA_CONTABLE = @CUENTA_CONTABLE
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe la cuenta contable', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_DOCUMENTO_DETA = ISNULL(MAX(CORR_DOCUMENTO_DETA), 0) + 1
			FROM dbo.BAN_SOLI_CHEQUE_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

			INSERT INTO dbo.BAN_SOLI_CHEQUE_DETA
			(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO, CORR_DOCUMENTO_DETA,
			 CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
			VALUES
			(@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO, @CORR_DOCUMENTO_DETA,
			 @CUENTA_CONTABLE, @CORR_CENTRO_COSTO, @NOMBRE_TRAN, @MONTO_CARGO, @MONTO_ABONO);
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.BAN_SOLI_CHEQUE_DETA SET
				CUENTA_CONTABLE = @CUENTA_CONTABLE,
				CORR_CENTRO_COSTO = @CORR_CENTRO_COSTO,
				NOMBRE_TRAN = @NOMBRE_TRAN,
				MONTO_CARGO = @MONTO_CARGO,
				MONTO_ABONO = @MONTO_ABONO
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
				AND CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA;
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.BAN_SOLI_CHEQUE_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
				AND CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

/* ── Generador automático detalle contable ── */
IF OBJECT_ID(N'dbo.PRAL_GENE_BAN_SOLI_CHEQUE_DETA', N'P') IS NOT NULL
	DROP PROCEDURE [dbo].[PRAL_GENE_BAN_SOLI_CHEQUE_DETA];
GO

CREATE PROCEDURE [dbo].[PRAL_GENE_BAN_SOLI_CHEQUE_DETA]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE
		@CLASE_MOVIMIENTO VARCHAR(3),
		@SUMA_RESTA INT,
		@CORR_CUENTA_BANCO INT,
		@MONTO_DOCUMENTO DECIMAL(18, 2),
		@NOMBRE_BENEFICIARIO VARCHAR(255),
		@NOMBRE_PARTIDA VARCHAR(1000),
		@NOMBRE_TRAN VARCHAR(1255),
		@CLASE_TIPO_CHEQUE VARCHAR(2),
		@CORR_TIPO_CHEQUE INT,
		@CUENTA_CONTABLE_TIPO_CHEQUE VARCHAR(30),
		@CORR_DOCUMENTO_DETA INT,
		@CUENTA_CONTABLE VARCHAR(30),
		@CORR_CENTRO_COSTO INT,
		@MONTO_CARGO DECIMAL(12, 2),
		@MONTO_ABONO DECIMAL(12, 2);

	DECLARE @BAN_SOLI_CHEQUE_DETA TABLE
	(
		CUENTA_CONTABLE VARCHAR(30) NOT NULL,
		CORR_CENTRO_COSTO INT NULL,
		NOMBRE_TRAN VARCHAR(1255) NOT NULL,
		MONTO_CARGO DECIMAL(12, 2) NOT NULL,
		MONTO_ABONO DECIMAL(12, 2) NOT NULL
	);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF NOT EXISTS (
			SELECT 1 FROM dbo.BAN_SOLI_CHEQUE
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
				AND ESTADO_DOCUMENTO = 'DI'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'La solicitud no está en estado Digitado', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF EXISTS (
			SELECT 1 FROM dbo.BAN_SOLI_CHEQUE_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'La solicitud ya tiene detalle contable', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		SELECT
			@CORR_CUENTA_BANCO = CORR_CUENTA_BANCO,
			@MONTO_DOCUMENTO = MONTO_DOCUMENTO,
			@NOMBRE_BENEFICIARIO = ISNULL(NOMBRE_BENEFICIARIO, ''),
			@NOMBRE_PARTIDA = ISNULL(NOMBRE_PARTIDA, ''),
			@CLASE_TIPO_CHEQUE = ISNULL(CLASE_TIPO_CHEQUE, ''),
			@CORR_TIPO_CHEQUE = ISNULL(CORR_TIPO_CHEQUE, 0)
		FROM dbo.V_BAN_SOLI_CHEQUE
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

		SELECT @CLASE_MOVIMIENTO = CLASE_MOVIMIENTO, @SUMA_RESTA = SUMA_RESTA
		FROM dbo.BAN_TIPO_MOVI_BANCARIO
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

		SET @NOMBRE_TRAN = LTRIM(RTRIM(@NOMBRE_BENEFICIARIO + N' ' + @NOMBRE_PARTIDA));

		IF ISNULL(@MONTO_DOCUMENTO, 0) <= 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El monto del documento debe ser mayor a cero para generar detalle', @SYS_FILAS_AFECTADAS = 0;
			GOTO FINA;
		END;

		IF @CLASE_MOVIMIENTO = 'CHQ'
		BEGIN
			IF ISNULL(@CORR_TIPO_CHEQUE, 0) = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe seleccionar el tipo de cheque', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			SELECT @CUENTA_CONTABLE_TIPO_CHEQUE = ISNULL(CUENTA_CONTABLE, '')
			FROM dbo.BAN_TIPO_CHEQUE
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE;

			INSERT INTO @BAN_SOLI_CHEQUE_DETA (CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
			SELECT A.CUENTA_CONTABLE, A.CORR_CENTRO_COSTO, @NOMBRE_TRAN, 0, @MONTO_DOCUMENTO
			FROM dbo.BAN_CUENTA_BANCARIA A
			WHERE A.CORR_EMPRESA = @CORR_EMPRESA AND A.CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO;

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No se encontró la cuenta bancaria de la solicitud', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF LTRIM(RTRIM(ISNULL(@CUENTA_CONTABLE_TIPO_CHEQUE, ''))) <> ''
			BEGIN
				INSERT INTO @BAN_SOLI_CHEQUE_DETA (CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
				VALUES (@CUENTA_CONTABLE_TIPO_CHEQUE, NULL, @NOMBRE_TRAN, @MONTO_DOCUMENTO, 0);
			END;
		END
		ELSE
		BEGIN
			INSERT INTO @BAN_SOLI_CHEQUE_DETA (CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
			SELECT
				A.CUENTA_CONTABLE,
				A.CORR_CENTRO_COSTO,
				@NOMBRE_TRAN,
				CASE WHEN @SUMA_RESTA = 1 THEN @MONTO_DOCUMENTO ELSE 0 END,
				CASE WHEN @SUMA_RESTA = 1 THEN 0 ELSE @MONTO_DOCUMENTO END
			FROM dbo.BAN_CUENTA_BANCARIA A
			WHERE A.CORR_EMPRESA = @CORR_EMPRESA AND A.CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO;

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No se encontró la cuenta bancaria de la solicitud', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		WHILE EXISTS (SELECT 1 FROM @BAN_SOLI_CHEQUE_DETA)
		BEGIN
			SELECT TOP 1
				@CORR_DOCUMENTO_DETA = 0,
				@CUENTA_CONTABLE = CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO = CORR_CENTRO_COSTO,
				@NOMBRE_TRAN = NOMBRE_TRAN,
				@MONTO_CARGO = MONTO_CARGO,
				@MONTO_ABONO = MONTO_ABONO
			FROM @BAN_SOLI_CHEQUE_DETA
			ORDER BY CUENTA_CONTABLE, MONTO_CARGO DESC, MONTO_ABONO DESC;

			EXEC dbo.PRAL_MTTO_BAN_SOLI_CHEQUE_DETA
				@TIPO_ACTUALIZA = 1,
				@CORR_EMPRESA = @CORR_EMPRESA,
				@ANIO_PERIODO = @ANIO_PERIODO,
				@MES_PERIODO = @MES_PERIODO,
				@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO,
				@CORR_DOCUMENTO = @CORR_DOCUMENTO,
				@CORR_DOCUMENTO_DETA = @CORR_DOCUMENTO_DETA OUTPUT,
				@CUENTA_CONTABLE = @CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO = @CORR_CENTRO_COSTO,
				@NOMBRE_TRAN = @NOMBRE_TRAN,
				@MONTO_CARGO = @MONTO_CARGO,
				@MONTO_ABONO = @MONTO_ABONO,
				@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
				@SYS_ESTACION = @SYS_ESTACION,
				@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

			IF @SYS_NUMERO_ERROR <> 0
				GOTO FINA;

			;WITH CTE AS
			(
				SELECT TOP 1 *
				FROM @BAN_SOLI_CHEQUE_DETA
				ORDER BY CUENTA_CONTABLE, MONTO_CARGO DESC, MONTO_ABONO DESC
			)
			DELETE FROM CTE;
		END;

		SET @SYS_FILAS_AFECTADAS = (
			SELECT COUNT(1) FROM dbo.BAN_SOLI_CHEQUE_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
