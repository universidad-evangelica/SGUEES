CREATE PROCEDURE [dbo].[PRAL_MTTO_BAN_SOLI_CHEQUE]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,
	@CORR_TIPO_MOVIMIENTO INT,
	@CORR_DOCUMENTO INT OUTPUT,
	@CORR_CUENTA_BANCO INT = NULL,
	@NUMERO_DOCUMENTO BIGINT = NULL,
	@FECHA_EMISION DATE = NULL,
	@NOMBRE_PARTIDA VARCHAR(1000) = '',
	@CORR_PROVEEDOR INT = NULL,
	@CORR_CLIENTE INT = NULL,
	@CORR_EMPLEADO INT = NULL,
	@NOMBRE_BENEFICIARIO VARCHAR(255) = '',
	@MONTO_DOCUMENTO DECIMAL(18, 2) = 0,
	@ESTADO_DOCUMENTO VARCHAR(2) = 'DI',
	@SOLICITADO_POR VARCHAR(30) = '',
	@FECHA_SOLICITADO DATE = NULL,
	@FECHA_APLICADO DATE = NULL,
	@CANTIDAD_LETRAS VARCHAR(255) = NULL,
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@CORR_TIPO_CHEQUE INT = NULL,
	@ANIO_PERIODO_CHEQUE INT = NULL,
	@MES_PERIODO_CHEQUE INT = NULL,
	@CORR_TIPO_MOVIMIENTO_CHEQUE INT = NULL,
	@CORR_DOCUMENTO_CHEQUE INT = NULL,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT,
	@GENERA_DETALLE BIT = 1,
	@CORR_MONEDA INT = NULL,
	@FACTOR_CAMBIO DECIMAL(16, 6) = 1,
	@OPERADOR VARCHAR(2) = '*'
)
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE @CLASE_TIPO_CHEQUE VARCHAR(3);

	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No existe el periodo contable seleccionado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF NOT EXISTS (
				SELECT 1 FROM dbo.CON_PERIODO_CONTABLE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
					AND ISNULL(ESTADO_PERIODO_BAN, 'AB') = 'AB'
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El periodo bancario no está abierto', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_TIPO_MOVI_BANCARIO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No ha seleccionado correctamente el tipo de movimiento bancario', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF @CORR_CUENTA_BANCO IS NULL OR NOT EXISTS (
				SELECT 1 FROM dbo.BAN_CUENTA_BANCARIA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
			)
			BEGIN
				SELECT @CORR_CUENTA_BANCO = NULL, @GENERA_DETALLE = 0;
			END;

			IF LTRIM(RTRIM(ISNULL(@NOMBRE_PARTIDA, ''))) = ''
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'Debe especificar un concepto para el documento a emitir', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF ISNULL(@MONTO_DOCUMENTO, 0) < 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'El monto del documento no puede ser menor que cero', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			SELECT @ANIO_PERIODO_CHEQUE = NULL, @MES_PERIODO_CHEQUE = NULL, @CORR_TIPO_MOVIMIENTO_CHEQUE = NULL, @CORR_DOCUMENTO_CHEQUE = NULL;

			DECLARE @NOMBRE_MONEDA VARCHAR(100) = N'DÓLARES';
			IF OBJECT_ID(N'dbo.GEN_TIPO_MONEDA', N'U') IS NOT NULL
			BEGIN
				SELECT @NOMBRE_MONEDA = ISNULL(M.NOMBRE_MONEDA, @NOMBRE_MONEDA)
				FROM dbo.GEN_TIPO_MONEDA M
				WHERE M.CORR_MONEDA = ISNULL(@CORR_MONEDA, 0);
			END;

			DECLARE @sFraccion VARCHAR(15) = '00' + LTRIM(CAST(CAST(((@MONTO_DOCUMENTO - CAST(@MONTO_DOCUMENTO AS INT)) * 100) AS INT) AS VARCHAR(15)));
			SELECT @CANTIDAD_LETRAS = dbo.FN_NUMEROS_A_LETRAS(@MONTO_DOCUMENTO, 1) + N' ' + @NOMBRE_MONEDA
				+ N' CON ' + SUBSTRING(@sFraccion, LEN(@sFraccion) - 1, 2) + N'/100';

			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_TIPO_CHEQUE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No ha seleccionado correctamente el tipo de cheque', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			SELECT @CLASE_TIPO_CHEQUE = ISNULL(CLASE_TIPO_CHEQUE, 'OT')
			FROM dbo.BAN_TIPO_CHEQUE
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE;

			IF OBJECT_ID(N'dbo.GEN_PROVEEDOR', N'U') IS NOT NULL
				AND NOT EXISTS (
					SELECT 1 FROM dbo.GEN_PROVEEDOR
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PROVEEDOR = @CORR_PROVEEDOR
				) AND @CLASE_TIPO_CHEQUE IN ('PR', 'OT')
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No ha seleccionado correctamente el proveedor', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF OBJECT_ID(N'dbo.GEN_EMPLEADO', N'U') IS NOT NULL
				AND NOT EXISTS (
					SELECT 1 FROM dbo.GEN_EMPLEADO
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_EMPLEADO = @CORR_EMPLEADO
				) AND @CLASE_TIPO_CHEQUE IN ('EM')
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No ha seleccionado correctamente el empleado', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF OBJECT_ID(N'dbo.GEN_CLIENTE', N'U') IS NOT NULL
				AND NOT EXISTS (
					SELECT 1 FROM dbo.GEN_CLIENTE
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CLIENTE = @CORR_CLIENTE
				) AND @CLASE_TIPO_CHEQUE IN ('CL')
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'No ha seleccionado correctamente el cliente', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF @TIPO_ACTUALIZA IN (2, 3)
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.BAN_SOLI_CHEQUE
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
					AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO
					AND ESTADO_DOCUMENTO = 'DI'
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30000, @SYS_MENSAJE_ERROR = N'La solicitud no puede modificarse o eliminarse (estado distinto de Digitado)', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;
		END;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_DOCUMENTO = ISNULL(MAX(CORR_DOCUMENTO), 0) + 1, @ESTADO_DOCUMENTO = 'DI'
			FROM dbo.BAN_SOLI_CHEQUE
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO;

			SET @FECHA_CREA = ISNULL(@FECHA_CREA, GETDATE());
			SET @USUARIO_ACTU = @USUARIO_CREA;
			SET @FECHA_ACTU = @FECHA_CREA;
			SET @ESTACION_ACTU = @ESTACION_CREA;

			INSERT INTO dbo.BAN_SOLI_CHEQUE
			(
				CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO,
				CORR_CUENTA_BANCO, NUMERO_DOCUMENTO, FECHA_EMISION, NOMBRE_PARTIDA,
				CORR_PROVEEDOR, CORR_EMPLEADO, CORR_CLIENTE, NOMBRE_BENEFICIARIO,
				MONTO_DOCUMENTO, ESTADO_DOCUMENTO, SOLICITADO_POR, FECHA_SOLICITADO, FECHA_APLICADO,
				CANTIDAD_LETRAS, USUARIO_CREA, FECHA_CREA, ESTACION_CREA, USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU,
				CORR_TIPO_CHEQUE, ANIO_PERIODO_CHEQUE, MES_PERIODO_CHEQUE, CORR_TIPO_MOVIMIENTO_CHEQUE, CORR_DOCUMENTO_CHEQUE,
				CORR_MONEDA, FACTOR_CAMBIO, OPERADOR
			)
			VALUES
			(
				@CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO,
				@CORR_CUENTA_BANCO, ISNULL(@NUMERO_DOCUMENTO, 0), @FECHA_EMISION, @NOMBRE_PARTIDA,
				@CORR_PROVEEDOR, @CORR_EMPLEADO, @CORR_CLIENTE, @NOMBRE_BENEFICIARIO,
				@MONTO_DOCUMENTO, @ESTADO_DOCUMENTO, @SOLICITADO_POR, @FECHA_SOLICITADO, @FECHA_APLICADO,
				@CANTIDAD_LETRAS, @USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA, @USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU,
				@CORR_TIPO_CHEQUE, @ANIO_PERIODO_CHEQUE, @MES_PERIODO_CHEQUE, @CORR_TIPO_MOVIMIENTO_CHEQUE, @CORR_DOCUMENTO_CHEQUE,
				@CORR_MONEDA, @FACTOR_CAMBIO, @OPERADOR
			);

			IF ISNULL(@GENERA_DETALLE, 1) = 1 AND @CORR_CUENTA_BANCO IS NOT NULL
			BEGIN
				EXEC dbo.PRAL_GENE_BAN_SOLI_CHEQUE_DETA
					@CORR_EMPRESA = @CORR_EMPRESA,
					@ANIO_PERIODO = @ANIO_PERIODO,
					@MES_PERIODO = @MES_PERIODO,
					@CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO,
					@CORR_DOCUMENTO = @CORR_DOCUMENTO,
					@SYS_LOGIN_USUARIO = @SYS_LOGIN_USUARIO,
					@SYS_ESTACION = @SYS_ESTACION,
					@SYS_FILAS_AFECTADAS = @SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR = @SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR = @SYS_MENSAJE_ERROR OUTPUT;

				IF @SYS_NUMERO_ERROR <> 0
				BEGIN
					DELETE FROM dbo.BAN_SOLI_CHEQUE_DETA
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

					DELETE FROM dbo.BAN_SOLI_CHEQUE
					WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

					GOTO FINA;
				END;
			END;
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.BAN_SOLI_CHEQUE SET
				CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO,
				NUMERO_DOCUMENTO = @NUMERO_DOCUMENTO,
				FECHA_EMISION = @FECHA_EMISION,
				NOMBRE_PARTIDA = @NOMBRE_PARTIDA,
				CORR_PROVEEDOR = @CORR_PROVEEDOR,
				CORR_EMPLEADO = @CORR_EMPLEADO,
				CORR_CLIENTE = @CORR_CLIENTE,
				NOMBRE_BENEFICIARIO = @NOMBRE_BENEFICIARIO,
				MONTO_DOCUMENTO = @MONTO_DOCUMENTO,
				CANTIDAD_LETRAS = @CANTIDAD_LETRAS,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = ISNULL(@FECHA_ACTU, GETDATE()),
				ESTACION_ACTU = @ESTACION_ACTU,
				CORR_TIPO_CHEQUE = @CORR_TIPO_CHEQUE,
				CORR_MONEDA = @CORR_MONEDA,
				FACTOR_CAMBIO = @FACTOR_CAMBIO,
				OPERADOR = @OPERADOR
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			IF EXISTS (
				SELECT 1 FROM dbo.BAN_DOCUMENTO A
				INNER JOIN dbo.BAN_SOLI_CHEQUE B
					ON A.CORR_EMPRESA = B.CORR_EMPRESA
					AND A.ANIO_PERIODO = B.ANIO_PERIODO_CHEQUE
					AND A.MES_PERIODO = B.MES_PERIODO_CHEQUE
					AND A.CORR_TIPO_MOVIMIENTO = B.CORR_TIPO_MOVIMIENTO_CHEQUE
					AND A.CORR_DOCUMENTO = B.CORR_DOCUMENTO_CHEQUE
				WHERE B.CORR_EMPRESA = @CORR_EMPRESA AND B.ANIO_PERIODO = @ANIO_PERIODO AND B.MES_PERIODO = @MES_PERIODO
					AND B.CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND B.CORR_DOCUMENTO = @CORR_DOCUMENTO
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30001, @SYS_MENSAJE_ERROR = N'No se puede eliminar porque existe un documento bancario asociado a esta solicitud', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF OBJECT_ID(N'dbo.BAN_LIQUI_CAJA_CHICA', N'U') IS NOT NULL
				AND EXISTS (
					SELECT 1 FROM dbo.BAN_LIQUI_CAJA_CHICA
					WHERE CORR_EMPRESA = @CORR_EMPRESA
						AND ANIO_PERIODO_SOLI_CHEQUE = @ANIO_PERIODO
						AND MES_PERIODO_SOLI_CHEQUE = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE = @CORR_TIPO_MOVIMIENTO
						AND CORR_DOCUMENTO_SOLI_CHEQUE = @CORR_DOCUMENTO
				)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30001, @SYS_MENSAJE_ERROR = N'No se puede eliminar porque existe una liquidación de caja asociada a esta solicitud', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			IF OBJECT_ID(N'dbo.COM_PAGO', N'U') IS NOT NULL
				AND EXISTS (
					SELECT 1 FROM dbo.COM_PAGO
					WHERE CORR_EMPRESA = @CORR_EMPRESA
						AND ANIO_PERIODO_SOLI_CHEQUE = @ANIO_PERIODO
						AND MES_PERIODO_SOLI_CHEQUE = @MES_PERIODO
						AND CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE = @CORR_TIPO_MOVIMIENTO
						AND CORR_DOCUMENTO_SOLI_CHEQUE = @CORR_DOCUMENTO
				)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30001, @SYS_MENSAJE_ERROR = N'No se puede eliminar porque existe un pago por compras asociado a esta solicitud', @SYS_FILAS_AFECTADAS = 0;
				GOTO FINA;
			END;

			DELETE FROM dbo.BAN_SOLI_CHEQUE_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;

			DELETE FROM dbo.BAN_SOLI_CHEQUE
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND MES_PERIODO = @MES_PERIODO
				AND CORR_TIPO_MOVIMIENTO = @CORR_TIPO_MOVIMIENTO AND CORR_DOCUMENTO = @CORR_DOCUMENTO;
		END;

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FILAS_AFECTADAS = 0;
	END CATCH;

FINA:
END
GO

