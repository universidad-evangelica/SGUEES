/* Contrapartida + Partidas especiales (cierre / apertura / liquidación) — menú Contabilidad */
SET NOCOUNT ON;
DECLARE @SISTEMA varchar(30) = 'CONTABILIDAD';
DECLARE @SUITE   varchar(30) = 'SGUEES';
DECLARE @USR     varchar(30) = 'admin';
DECLARE @EST     varchar(30) = 'SISTEMA';
DECLARE @HOY     datetime    = GETDATE();

DECLARE @Opciones TABLE (CODIGO varchar(30), NOMBRE nvarchar(120), URL nvarchar(4000), IMG varchar(25));
INSERT INTO @Opciones (CODIGO, NOMBRE, URL, IMG) VALUES
  (N'CON_PARTIDA_ESPECIAL', N'Partidas de Cierre y Apertura', N'/con-partida-especial', N'');

MERGE SEG_OPCION_SISTEMA AS T
USING @Opciones AS S ON T.CODIGO_OPCION = S.CODIGO
WHEN MATCHED THEN
  UPDATE SET T.NOMBRE_OPCION = S.NOMBRE, T.URL_OPCION = S.URL, T.IMAGEN_OPCION = S.IMG,
             T.USUARIO_ACTU = @USR, T.FECHA_ACTU = @HOY, T.ESTACION_ACTU = @EST
WHEN NOT MATCHED THEN
  INSERT (CODIGO_OPCION, NOMBRE_OPCION, URL_OPCION, IMAGEN_OPCION, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
  VALUES (S.CODIGO, S.NOMBRE, S.URL, S.IMG, @USR, @HOY, @EST);

INSERT INTO SEG_OPCION_SISTEMA_SUITE (CODIGO_OPCION, CODIGO_SUITE)
SELECT o.CODIGO, @SUITE FROM @Opciones o
WHERE NOT EXISTS (
  SELECT 1 FROM SEG_OPCION_SISTEMA_SUITE s WHERE s.CODIGO_OPCION = o.CODIGO AND s.CODIGO_SUITE = @SUITE
);

/* PROCESO: orden después de anular partidas */
MERGE SEG_CONFIG_OPCION AS T
USING (
  SELECT @SISTEMA AS CODIGO_SISTEMA, 'PROCESO' AS CODIGO_MENU, 'CON_PARTIDA_ESPECIAL' AS CODIGO_OPCION, 1 AS ORDEN_MENU, 43 AS ORDEN_OPCION
) AS S
ON T.CODIGO_SISTEMA = S.CODIGO_SISTEMA AND T.CODIGO_MENU = S.CODIGO_MENU AND T.CODIGO_OPCION = S.CODIGO_OPCION
WHEN MATCHED THEN
  UPDATE SET ORDEN_SISTEMA = 2, ORDEN_MENU = S.ORDEN_MENU, ORDEN_OPCION = S.ORDEN_OPCION,
             USUARIO_ACTU = @USR, FECHA_ACTU = @HOY, ESTACION_ACTU = @EST
WHEN NOT MATCHED THEN
  INSERT (CODIGO_SISTEMA, CODIGO_MENU, CODIGO_OPCION, ORDEN_SISTEMA, ORDEN_MENU, ORDEN_OPCION, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
  VALUES (S.CODIGO_SISTEMA, S.CODIGO_MENU, S.CODIGO_OPCION, 2, S.ORDEN_MENU, S.ORDEN_OPCION, @USR, @HOY, @EST);

DECLARE @Logins TABLE (LOGIN_SISTEMA varchar(30));
INSERT INTO @Logins (LOGIN_SISTEMA)
SELECT DISTINCT LOGIN_SISTEMA FROM SEG_USUARIO_OPCION
WHERE CODIGO_OPCION = 'CON_PARTIDA';

INSERT INTO SEG_USUARIO_OPCION
  (LOGIN_SISTEMA, CODIGO_SISTEMA, CODIGO_MENU, CODIGO_OPCION, NUEVO, MODIFICAR, ELIMINAR, IMPRIMIR, USUARIO_CREA, FECHA_CREA, ESTACION_CREA)
SELECT l.LOGIN_SISTEMA, @SISTEMA, 'PROCESO', o.CODIGO, 1, 1, 0, 1, @USR, @HOY, @EST
FROM @Logins l
CROSS JOIN @Opciones o
WHERE NOT EXISTS (
  SELECT 1 FROM SEG_USUARIO_OPCION u
  WHERE u.LOGIN_SISTEMA = l.LOGIN_SISTEMA AND u.CODIGO_SISTEMA = @SISTEMA AND u.CODIGO_OPCION = o.CODIGO
);

SELECT c.CODIGO_MENU, c.ORDEN_OPCION, o.CODIGO_OPCION, o.NOMBRE_OPCION, o.URL_OPCION
FROM SEG_CONFIG_OPCION c
INNER JOIN SEG_OPCION_SISTEMA o ON o.CODIGO_OPCION = c.CODIGO_OPCION
WHERE c.CODIGO_SISTEMA = @SISTEMA AND c.CODIGO_OPCION = 'CON_PARTIDA_ESPECIAL'
ORDER BY c.ORDEN_OPCION;
