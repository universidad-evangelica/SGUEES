/* =============================================================================
   Flujo 103 — movimiento de personal, tres niveles por la unidad del puesto.

   Oficial = SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES.ACTIVO = 1.
   Nivel 3 = ancestro con CORR_NIVEL = 3 (no una unidad fija).

   COORD    Puesto en una unidad activa de nivel mayor a 4 (coordinación).
            N1 jefe de esa unidad → N2 jefe del departamento (nivel 4) → N3.
   DIRECTO  Puesto en el departamento (nivel 4) y ese departamento tiene
            al menos un hijo ACTIVO. Al enviar se firman N1 y N2 y pasa a N3.
   SIN_COORD Departamento sin hijo activo. Una sola tarea al jefe del
            departamento: al aprobar quedan las firmas de N1 y de N2, y pasa a N3.

   Confirmar en pantalla solo cuando N3 deja el movimiento en AP (Aprobado GG).
   ============================================================================= */
