/* Borradores ya abiertos: la unidad del circuito es el puesto del solicitante, no la jefatura. */
UPDATE I
SET I.CORR_UNIDAD_DOCUMENTO = P.CORR_UNIDAD,
	I.USUARIO_ACTU = N'SISTEMA',
	I.FECHA_ACTU = GETDATE()
FROM dbo.SEG_FLUJO_INSTANCIA AS I
INNER JOIN dbo.SEG_FLUJO_PASO AS PA
	ON PA.CORR_EMPRESA = I.CORR_EMPRESA AND PA.CORR_PASO = I.CORR_PASO_ACTUAL AND PA.ORDEN = 1
INNER JOIN dbo.SEG_FLUJO_ESTADO AS ES
	ON ES.CORR_EMPRESA = I.CORR_EMPRESA AND ES.CORR_ESTADO = I.CORR_ESTADO_ACTUAL AND ES.ES_INICIAL = 1
CROSS APPLY (
	SELECT TOP 1 EP.CORR_UNIDAD
	FROM dbo.GEN_PERSONA_USUARIO AS PU
	INNER JOIN dbo.GEN_EMPLEADO AS E
		ON E.CORR_PERSONA = PU.CORR_PERSONA AND E.CORR_EMPRESA = I.CORR_EMPRESA
	INNER JOIN dbo.GEN_EMPLEADO_PUESTO AS EP
		ON EP.CORR_EMPRESA = E.CORR_EMPRESA AND EP.CORR_EMPLEADO = E.CORR_EMPLEADO
	INNER JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS UN
		ON UN.CORR_EMPRESA = EP.CORR_EMPRESA AND UN.CORR_UNIDAD = EP.CORR_UNIDAD
	WHERE LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(I.USUARIO_CREA))
	ORDER BY CASE WHEN UN.ACTIVO = 1 THEN 0 ELSE 1 END, UN.CORR_NIVEL DESC, EP.CORR_UNIDAD DESC
) AS P
WHERE I.CORR_EMPRESA = @EMP
  AND I.CORR_TIPO_DOCUMENTO = @TIPO
  AND I.ACTIVO = 1
  AND ISNULL(P.CORR_UNIDAD, 0) > 0
  AND ISNULL(I.CORR_UNIDAD_DOCUMENTO, 0) <> P.CORR_UNIDAD;

COMMIT TRAN;

SELECT P.ORDEN, P.CORR_PASO, P.NOMBRE_PASO, P.CORR_ACTOR_ORIGEN, P.CORR_ACTOR_DESTINO, P.PERMITE_AUTO_APROBACION,
	A.CORR_ACCION, E.NOMBRE_ESTADO, A.CORR_TIPO_MOVIMIENTO, A.CORR_TIPO_NOTIFICACION, A.CORR_PASO_DESTINO
FROM dbo.SEG_FLUJO_PASO AS P
LEFT JOIN dbo.SEG_FLUJO_PASO_ACCION_ESTADO AS A
	ON A.CORR_EMPRESA = P.CORR_EMPRESA AND A.CORR_FLUJO_PROCESO = P.CORR_FLUJO_PROCESO AND A.CORR_PASO = P.CORR_PASO AND A.ACTIVO = 1
LEFT JOIN dbo.SEG_FLUJO_ESTADO AS E
	ON E.CORR_EMPRESA = A.CORR_EMPRESA AND E.CORR_ESTADO = A.CORR_ESTADO_DESTINO
WHERE P.CORR_EMPRESA = @EMP AND P.CORR_FLUJO_PROCESO = @FLUJO
ORDER BY P.ORDEN, A.CORR_ACCION;
GO
