-- Financiadores usa el mismo catalogo que Iglesias y Convenios.
-- Aplicar en SGUEES antes de arrancar la API actualizada. Conserva las tablas ACA_BEC_*.
SET XACT_ABORT ON;
IF DB_NAME()<>'SGUEES' THROW 51000,N'Este script requiere la base SGUEES.',1;
IF OBJECT_ID('dbo.ACA_BECA_FINANCIADOR','U') IS NULL
 THROW 51000,N'No existe el catalogo actual de financiadores.',1;
IF COL_LENGTH('dbo.ACA_BECA_FINANCIADOR','VERSION_REGISTRO') IS NULL
 ALTER TABLE dbo.ACA_BECA_FINANCIADOR ADD VERSION_REGISTRO rowversion;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_FINANCIADOR_TIPO
AS
SELECT CORR_EMPRESA,CORR_BECA,CODIGO_BECA,NOMBRE_BECA,ESTADO_BECA,
 CAST(CASE WHEN ESTADO_BECA='ACTIVA' THEN 1 ELSE 0 END AS bit) AS ACTIVO
FROM dbo.ACA_BECA_TIPO;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_FINANCIADOR_ENTIDAD
AS
SELECT CORR_EMPRESA,CORR_ENTIDAD_FINANCIADORA,CODIGO_ENTIDAD,NOMBRE_ENTIDAD,TIPO_ENTIDAD,ACTIVO
FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA;
GO

CREATE OR ALTER VIEW dbo.V_ACA_BECA_FINANCIADOR_MTTO
AS
SELECT
    F.CORR_EMPRESA,
    F.CORR_BECA_FINANCIADOR,
    F.CORR_BECA,
    T.CODIGO_BECA,
    T.NOMBRE_BECA,
    F.CORR_ENTIDAD_FINANCIADORA,
    E.CODIGO_ENTIDAD,
    E.NOMBRE_ENTIDAD,
    E.TIPO_ENTIDAD,
    F.CONCEPTO_COBERTURA,
    F.PORCENTAJE_COBERTURA,
    F.MONTO_MAXIMO,
    F.ACTIVO,
    F.USUARIO_CREA,
    F.ESTACION_CREA,
    F.FECHA_CREA,
    F.USUARIO_ACTU,
    F.ESTACION_ACTU,
    F.FECHA_ACTU,
    F.VERSION_REGISTRO
FROM dbo.ACA_BECA_FINANCIADOR F
INNER JOIN dbo.ACA_BECA_TIPO T
    ON T.CORR_BECA = F.CORR_BECA
    AND T.CORR_EMPRESA = F.CORR_EMPRESA
INNER JOIN dbo.ACA_BECA_ENTIDAD_FINANCIADORA E
    ON E.CORR_ENTIDAD_FINANCIADORA = F.CORR_ENTIDAD_FINANCIADORA
    AND E.CORR_EMPRESA = F.CORR_EMPRESA;

GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_FINANCIADOR
    @TIPO_ACTUALIZA int,
    @CORR_EMPRESA int,
    @ID int OUTPUT,
    @USUARIO varchar(100),
    @ESTACION varchar(50),
    @CORR_BECA int = NULL,
    @CORR_ENTIDAD_FINANCIADORA int = NULL,
    @CONCEPTO_COBERTURA varchar(50) = NULL,
    @PORCENTAJE_COBERTURA decimal(5,2) = NULL,
    @MONTO_MAXIMO decimal(12,2) = NULL,
    @ACTIVO bit = NULL,
    @VERSION_REGISTRO varbinary(8) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL
        THROW 51000,N'No se encontró la empresa o el usuario de sesión.',1;
    IF @TIPO_ACTUALIZA NOT IN (1,2,3,4) THROW 51000,N'Operación de catálogo inválida.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.GEN_EMPRESA WHERE CORR_EMPRESA=@CORR_EMPRESA)
        THROW 51000,N'La empresa de sesion no existe.',1;
    IF @TIPO_ACTUALIZA IN (1,2)
    BEGIN
        SET @CONCEPTO_COBERTURA=UPPER(LTRIM(RTRIM(@CONCEPTO_COBERTURA)));
        IF ISNULL(@CORR_BECA,0)<=0 OR ISNULL(@CORR_ENTIDAD_FINANCIADORA,0)<=0
            THROW 51000,N'Debe seleccionar la beca y la entidad financiadora.',1;
        IF NULLIF(@CONCEPTO_COBERTURA,'') IS NULL OR @ACTIVO IS NULL
            THROW 51000,N'Debe indicar el concepto de cobertura y el estado.',1;
        IF @PORCENTAJE_COBERTURA IS NULL OR @PORCENTAJE_COBERTURA<0 OR @PORCENTAJE_COBERTURA>100
            THROW 51000,N'El porcentaje de cobertura debe estar entre 0 y 100.',1;
        IF @MONTO_MAXIMO<0 THROW 51000,N'El monto maximo no puede ser negativo.',1;
    END;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Lock int;
        EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
        IF @Lock<0 THROW 51000,N'Otro usuario está guardando. Intente nuevamente.',1;
        IF @TIPO_ACTUALIZA IN (1,2)
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO T WITH(UPDLOCK,HOLDLOCK)
                WHERE T.CORR_EMPRESA=@CORR_EMPRESA AND T.CORR_BECA=@CORR_BECA
                 AND (T.ESTADO_BECA='ACTIVA' OR (@TIPO_ACTUALIZA=2 AND @ACTIVO=0 AND EXISTS(
                    SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR F WHERE F.CORR_EMPRESA=@CORR_EMPRESA
                     AND F.CORR_BECA_FINANCIADOR=@ID AND F.CORR_BECA=T.CORR_BECA))))
                THROW 51000,N'La beca no pertenece a su empresa o esta inactiva.',1;
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_ENTIDAD_FINANCIADORA E WITH(UPDLOCK,HOLDLOCK)
                WHERE E.CORR_EMPRESA=@CORR_EMPRESA AND E.CORR_ENTIDAD_FINANCIADORA=@CORR_ENTIDAD_FINANCIADORA
                 AND (E.ACTIVO=1 OR (@TIPO_ACTUALIZA=2 AND @ACTIVO=0 AND EXISTS(
                    SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR F WHERE F.CORR_EMPRESA=@CORR_EMPRESA
                     AND F.CORR_BECA_FINANCIADOR=@ID AND F.CORR_ENTIDAD_FINANCIADORA=E.CORR_ENTIDAD_FINANCIADORA))))
                THROW 51000,N'La entidad no pertenece a su empresa o esta inactiva.',1;
            IF EXISTS(SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR WITH(UPDLOCK,HOLDLOCK)
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA
                 AND CORR_ENTIDAD_FINANCIADORA=@CORR_ENTIDAD_FINANCIADORA AND CONCEPTO_COBERTURA=@CONCEPTO_COBERTURA
                 AND (@TIPO_ACTUALIZA=1 OR CORR_BECA_FINANCIADOR<>@ID))
                THROW 51000,N'Ya existe financiamiento para esa beca, entidad y concepto.',1;
        END;
        IF @TIPO_ACTUALIZA=1
        BEGIN
            SELECT @ID=ISNULL(MAX(CORR_BECA_FINANCIADOR),0)+1 FROM dbo.ACA_BECA_FINANCIADOR WITH(UPDLOCK,HOLDLOCK);
            INSERT dbo.ACA_BECA_FINANCIADOR(CORR_BECA,CORR_ENTIDAD_FINANCIADORA,CONCEPTO_COBERTURA,PORCENTAJE_COBERTURA,MONTO_MAXIMO,ACTIVO,CORR_EMPRESA,CORR_BECA_FINANCIADOR,USUARIO_CREA,ESTACION_CREA,FECHA_CREA) VALUES(@CORR_BECA,@CORR_ENTIDAD_FINANCIADORA,@CONCEPTO_COBERTURA,@PORCENTAJE_COBERTURA,@MONTO_MAXIMO,@ACTIVO,@CORR_EMPRESA,@ID,@USUARIO,@ESTACION,GETDATE());
        END
        ELSE
        BEGIN
            IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_FINANCIADOR=@ID)
                THROW 51000,N'El registro no existe en la empresa de sesión.',1;
            IF @VERSION_REGISTRO IS NULL OR NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_FINANCIADOR=@ID AND VERSION_REGISTRO=@VERSION_REGISTRO)
                THROW 51009,N'Otro usuario modifico el registro. Actualice el listado antes de guardar.',1;
            IF @TIPO_ACTUALIZA=4 AND EXISTS(
                SELECT 1 FROM dbo.ACA_BECA_FINANCIADOR F
                JOIN dbo.ACA_BECA_TIPO T ON T.CORR_EMPRESA=F.CORR_EMPRESA AND T.CORR_BECA=F.CORR_BECA
                JOIN dbo.ACA_BECA_ENTIDAD_FINANCIADORA E ON E.CORR_EMPRESA=F.CORR_EMPRESA AND E.CORR_ENTIDAD_FINANCIADORA=F.CORR_ENTIDAD_FINANCIADORA
                WHERE F.CORR_EMPRESA=@CORR_EMPRESA AND F.CORR_BECA_FINANCIADOR=@ID AND F.ACTIVO=0
                  AND (T.ESTADO_BECA<>'ACTIVA' OR E.ACTIVO=0))
                THROW 51000,N'Active la beca y la entidad antes de habilitar el financiamiento.',1;

            IF @TIPO_ACTUALIZA=2
                UPDATE dbo.ACA_BECA_FINANCIADOR SET CORR_BECA=@CORR_BECA,
                CORR_ENTIDAD_FINANCIADORA=@CORR_ENTIDAD_FINANCIADORA,
                CONCEPTO_COBERTURA=@CONCEPTO_COBERTURA,
                PORCENTAJE_COBERTURA=@PORCENTAJE_COBERTURA,
                MONTO_MAXIMO=@MONTO_MAXIMO,
                ACTIVO=@ACTIVO, USUARIO_ACTU=@USUARIO, ESTACION_ACTU=@ESTACION, FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_FINANCIADOR=@ID;
            IF @TIPO_ACTUALIZA=3
                DELETE dbo.ACA_BECA_FINANCIADOR WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_FINANCIADOR=@ID;
            IF @TIPO_ACTUALIZA=4
                UPDATE dbo.ACA_BECA_FINANCIADOR SET ACTIVO=CONVERT(bit,1-CONVERT(int,ACTIVO)),USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
                WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA_FINANCIADOR=@ID;
        END
        COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE()<>0 ROLLBACK;
        IF ERROR_NUMBER()=547 AND @TIPO_ACTUALIZA=3 THROW 51000,N'No se puede eliminar: el registro tiene dependencias.',1;
        THROW;
    END CATCH
END;
GO
