CREATE FUNCTION dbo.FN_CLASS_GASTOINGRESO(@ANIO INT, @MES INT)
RETURNS DECIMAL(18, 2)
AS
BEGIN
    DECLARE @GASTOINGRESO DECIMAL(18, 2);
    DECLARE @T TABLE
    (
        TRABNK VARCHAR(5) NOT NULL,
        TRABRN VARCHAR(5) NOT NULL,
        TRADCC CHAR(1) NULL,
        CARGO DECIMAL(18, 2) NOT NULL DEFAULT 0,
        ABONO DECIMAL(18, 2) NOT NULL DEFAULT 0,
        TRAGLN VARCHAR(12) NOT NULL
    );

    INSERT INTO @T (TRABNK, TRABRN, TRADCC, CARGO, ABONO, TRAGLN)
    SELECT ISNULL(TR.TRABNK, '01'), ISNULL(TR.TRABRN, '001'), TR.TRADCC,
           CASE WHEN TR.TRADCC = 'D' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CASE WHEN TR.TRADCC = 'C' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12)) + REPLICATE('0', 12 - LEN(CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12))))
    FROM CLASS_UEES.CLASS_UEES.dbo.TRANSAC TR
    WHERE TR.TRATYP = 'R'
      AND LEFT(CAST(TR.TRAGLN AS VARCHAR(25)), 1) IN ('4', '5')
      AND TR.TRAMOD <> 'P/G'
      AND TR.TRALOT NOT IN ('2077')
      AND YEAR(TR.TRAFVL) < @ANIO
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '9999' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '2078' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) + TR.TRADSC <> '2080' + CAST(@ANIO AS VARCHAR(5)) + 'Liquidación Cuenta';

    INSERT INTO @T (TRABNK, TRABRN, TRADCC, CARGO, ABONO, TRAGLN)
    SELECT ISNULL(TR.TRABNK, '01'), ISNULL(TR.TRABRN, '001'), TR.TRADCC,
           CASE WHEN TR.TRADCC = 'D' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CASE WHEN TR.TRADCC = 'C' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12)) + REPLICATE('0', 12 - LEN(CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12))))
    FROM CLASS_UEES.CLASS_UEES.dbo.TRANSAC TR
    WHERE TR.TRATYP = 'R'
      AND LEFT(CAST(TR.TRAGLN AS VARCHAR(25)), 1) IN ('4', '5')
      AND TR.TRAMOD <> 'P/G'
      AND TR.TRALOT NOT IN ('2077')
      AND YEAR(TR.TRAFVL) = @ANIO
      AND MONTH(TR.TRAFVL) <= @MES
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '9999' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '2078' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) + TR.TRADSC <> '2080' + CAST(@ANIO AS VARCHAR(5)) + 'Liquidación Cuenta';

    INSERT INTO @T (TRABNK, TRABRN, TRADCC, CARGO, ABONO, TRAGLN)
    SELECT ISNULL(TR.TRABNK, '01'), ISNULL(TR.TRABRN, '001'), TR.TRADCC,
           CASE WHEN TR.TRADCC = 'D' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CASE WHEN TR.TRADCC = 'C' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12)) + REPLICATE('0', 12 - LEN(CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12))))
    FROM CLASS_UEES.CLASS_UEES.dbo.TRANSAC_HST TR
    WHERE TR.TRATYP = 'R'
      AND LEFT(CAST(TR.TRAGLN AS VARCHAR(25)), 1) IN ('4', '5')
      AND TR.TRAMOD <> 'P/G'
      AND TR.TRALOT NOT IN ('2077')
      AND YEAR(TR.TRAFVL) < @ANIO
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '9999' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '2078' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) + TR.TRADSC <> '2080' + CAST(@ANIO AS VARCHAR(5)) + 'Liquidación Cuenta';

    INSERT INTO @T (TRABNK, TRABRN, TRADCC, CARGO, ABONO, TRAGLN)
    SELECT ISNULL(TR.TRABNK, '01'), ISNULL(TR.TRABRN, '001'), TR.TRADCC,
           CASE WHEN TR.TRADCC = 'D' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CASE WHEN TR.TRADCC = 'C' THEN ISNULL(TR.TRAAMT, 0.00) ELSE 0.00 END,
           CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12)) + REPLICATE('0', 12 - LEN(CAST(LEFT(TR.TRAGLN, 4) AS VARCHAR(12))))
    FROM CLASS_UEES.CLASS_UEES.dbo.TRANSAC_HST TR
    WHERE TR.TRATYP = 'R'
      AND LEFT(CAST(TR.TRAGLN AS VARCHAR(25)), 1) IN ('4', '5')
      AND TR.TRAMOD <> 'P/G'
      AND TR.TRALOT NOT IN ('2077')
      AND YEAR(TR.TRAFVL) = @ANIO
      AND MONTH(TR.TRAFVL) <= @MES
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '9999' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) <> '2078' + CAST(@ANIO AS VARCHAR(5))
      AND CAST(TR.TRALOT AS VARCHAR(5)) + CAST(YEAR(TR.TRAFVL) AS VARCHAR(5)) + TR.TRADSC <> '2080' + CAST(@ANIO AS VARCHAR(5)) + 'Liquidación Cuenta';

    SET @GASTOINGRESO =
        ISNULL((SELECT SUM(M.ABONO) - SUM(M.CARGO) FROM @T M WHERE LEFT(M.TRAGLN, 1) IN ('5')), 0.00)
      - ISNULL((SELECT SUM(M.CARGO) - SUM(M.ABONO) FROM @T M WHERE LEFT(M.TRAGLN, 1) IN ('4')), 0.00);

    RETURN @GASTOINGRESO;
END;
GO

