/*
   Corrige FECHA_ACCION de firmas auto DIRECTO (ESTACION_CREA = SP_REQUISICION)
   JI / JU para historial ORDER BY FECHA_ACCION DESC, CORR_BITACORA DESC.

   Regla:
     - Si ya existe Aprobado GG (estado final): JU = GG-1s, JI = GG-2s
       (así DESC queda GG → JU → JI → …).
     - Si aún no hay GG: anclar al MAX del motor (Borrador/Enviar/JI no-SP)
       con JI = base+1s, JU = base+2s.

   Bug del script anterior: usaba MAX(todos los no-SP) e incluía el GG,
   dejando JU DESPUÉS del GG.

   Ejecutar:
     sqlcmd -S <srv> -d SGUEES -U <user> -P <pass> -f 65001 -i FIX_SEG_FLUJO_BITACORA_FECHA_DIRECTO.sql
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRAN;

;WITH AutoSp AS (
	SELECT
		B.CORR_EMPRESA,
		B.CORR_BITACORA,
		B.CORR_INSTANCIA,
		E.NOMBRE_ESTADO,
		B.FECHA_ACCION,
		CASE
			WHEN E.NOMBRE_ESTADO LIKE N'%JU%' OR E.NOMBRE_ESTADO LIKE N'%Unidad%' THEN N'JU'
			WHEN E.NOMBRE_ESTADO LIKE N'%JI%' OR E.NOMBRE_ESTADO LIKE N'%Inmediato%' THEN N'JI'
			ELSE N'OTRO'
		END AS TIPO_AUTO
	FROM dbo.SEG_FLUJO_BITACORA AS B
	INNER JOIN dbo.SEG_FLUJO_INSTANCIA AS I
		ON I.CORR_EMPRESA = B.CORR_EMPRESA
	   AND I.CORR_INSTANCIA = B.CORR_INSTANCIA
	INNER JOIN dbo.SEG_FLUJO_TIPO_DOCUMENTO AS TD
		ON TD.CORR_EMPRESA = I.CORR_EMPRESA
	   AND TD.CORR_TIPO_DOCUMENTO = I.CORR_TIPO_DOCUMENTO
	   AND TD.CODIGO_OPCION = N'SC_REQUISICION'
	INNER JOIN dbo.SEG_FLUJO_ESTADO AS E
		ON E.CORR_EMPRESA = B.CORR_EMPRESA
	   AND E.CORR_ESTADO = B.CORR_ESTADO_NUEVO
	WHERE B.ESTACION_CREA = N'SP_REQUISICION'
	  AND (
			E.NOMBRE_ESTADO LIKE N'%JU%'
			OR E.NOMBRE_ESTADO LIKE N'%Unidad%'
			OR E.NOMBRE_ESTADO LIKE N'%JI%'
			OR E.NOMBRE_ESTADO LIKE N'%Inmediato%'
	  )
),
Anclas AS (
	SELECT
		I.CORR_EMPRESA,
		I.CORR_INSTANCIA,
		/* Motor / pasos previos: excluye firmas SP auto y el cierre GG (final). */
		MAX(CASE
			WHEN B.ESTACION_CREA = N'SP_REQUISICION' THEN NULL
			WHEN ISNULL(E.ES_FINAL, 0) = 1 THEN NULL
			WHEN E.NOMBRE_ESTADO LIKE N'% GG%' OR E.NOMBRE_ESTADO LIKE N'Aprobado GG%' THEN NULL
			ELSE B.FECHA_ACCION
		END) AS FECHA_MOTOR,
		MAX(CASE
			WHEN ISNULL(E.ES_FINAL, 0) = 1
			  OR E.NOMBRE_ESTADO LIKE N'% GG%'
			  OR E.NOMBRE_ESTADO LIKE N'Aprobado GG%'
			THEN B.FECHA_ACCION
			ELSE NULL
		END) AS FECHA_GG
	FROM dbo.SEG_FLUJO_INSTANCIA AS I
	INNER JOIN dbo.SEG_FLUJO_TIPO_DOCUMENTO AS TD
		ON TD.CORR_EMPRESA = I.CORR_EMPRESA
	   AND TD.CORR_TIPO_DOCUMENTO = I.CORR_TIPO_DOCUMENTO
	   AND TD.CODIGO_OPCION = N'SC_REQUISICION'
	INNER JOIN dbo.SEG_FLUJO_BITACORA AS B
		ON B.CORR_EMPRESA = I.CORR_EMPRESA
	   AND B.CORR_INSTANCIA = I.CORR_INSTANCIA
	INNER JOIN dbo.SEG_FLUJO_ESTADO AS E
		ON E.CORR_EMPRESA = B.CORR_EMPRESA
	   AND E.CORR_ESTADO = B.CORR_ESTADO_NUEVO
	GROUP BY I.CORR_EMPRESA, I.CORR_INSTANCIA
),
Calc AS (
	SELECT
		A.CORR_EMPRESA,
		A.CORR_BITACORA,
		A.TIPO_AUTO,
		A.FECHA_ACCION AS FECHA_ACTUAL,
		CASE
			WHEN N.FECHA_GG IS NOT NULL THEN
				DATEADD(
					SECOND,
					CASE WHEN A.TIPO_AUTO = N'JU' THEN -1 ELSE -2 END,
					N.FECHA_GG
				)
			WHEN N.FECHA_MOTOR IS NOT NULL THEN
				DATEADD(
					SECOND,
					CASE WHEN A.TIPO_AUTO = N'JU' THEN 2 ELSE 1 END,
					N.FECHA_MOTOR
				)
			ELSE A.FECHA_ACCION
		END AS FECHA_NUEVA
	FROM AutoSp AS A
	INNER JOIN Anclas AS N
		ON N.CORR_EMPRESA = A.CORR_EMPRESA
	   AND N.CORR_INSTANCIA = A.CORR_INSTANCIA
	WHERE A.TIPO_AUTO IN (N'JI', N'JU')
)
UPDATE B
SET B.FECHA_ACCION = C.FECHA_NUEVA
FROM dbo.SEG_FLUJO_BITACORA AS B
INNER JOIN Calc AS C
	ON C.CORR_EMPRESA = B.CORR_EMPRESA
   AND C.CORR_BITACORA = B.CORR_BITACORA
WHERE B.FECHA_ACCION <> C.FECHA_NUEVA
   OR C.FECHA_NUEVA IS NOT NULL;

DECLARE @Filas INT = @@ROWCOUNT;

SELECT
	FB.CORR_DOCUMENTO AS CORR_REQUISICION,
	FB.ESTADO_DESTINO,
	CONVERT(varchar(23), FB.FECHA_ACCION, 121) AS FECHA_ACCION,
	FB.CORR_BITACORA,
	FB.LOGIN_SISTEMA,
	LEFT(ISNULL(FB.COMENTARIO, N''), 90) AS COMENTARIO
FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS FB
INNER JOIN dbo.SEG_FLUJO_TIPO_DOCUMENTO AS TD
	ON TD.CORR_EMPRESA = FB.CORR_EMPRESA
   AND TD.CORR_TIPO_DOCUMENTO = FB.CORR_TIPO_DOCUMENTO
   AND TD.CODIGO_OPCION = N'SC_REQUISICION'
WHERE FB.CORR_DOCUMENTO = 19
ORDER BY FB.FECHA_ACCION DESC, FB.CORR_BITACORA DESC;

PRINT N'Filas FECHA_ACCION actualizadas: ' + CAST(@Filas AS NVARCHAR(20));

COMMIT TRAN;
GO
