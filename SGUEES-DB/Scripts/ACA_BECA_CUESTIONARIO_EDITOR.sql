CREATE OR ALTER VIEW dbo.V_ACA_BECA_EDITOR_SECCION
AS SELECT S.CORR_EMPRESA,S.CORR_FORMULARIO_VERSION,S.CORR_SECCION_BECA,S.NOMBRE_SECCION,S.DESCRIPCION,S.ORDEN,S.PUNTAJE_MAXIMO,S.PORCENTAJE_SECCION
FROM dbo.ACA_PROSPECTO_BECA_SECCION S WHERE S.ACTIVO=1;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_EDITOR_PREGUNTA
AS SELECT P.CORR_EMPRESA,S.CORR_FORMULARIO_VERSION,PT.CORR_BECA,P.CORR_SECCION_BECA,P.CORR_PREGUNTA_BECA,P.CODIGO_PREGUNTA,P.TEXTO_PREGUNTA,P.AYUDA,P.TIPO_RESPUESTA,P.REQUERIDO,P.ORDEN
FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT ON PT.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND PT.CORR_EMPRESA=P.CORR_EMPRESA
WHERE P.ACTIVO=1 AND S.ACTIVO=1 AND PT.ACTIVO=1;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_EDITOR_OPCION
AS SELECT O.CORR_EMPRESA,S.CORR_FORMULARIO_VERSION,O.CORR_PREGUNTA_BECA,O.CORR_OPCION_BECA,O.TEXTO_OPCION,O.ORDEN
FROM dbo.ACA_PROSPECTO_BECA_OPCION O JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=O.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=O.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
WHERE O.ACTIVO=1 AND P.ACTIVO=1 AND S.ACTIVO=1;
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_EDITOR_PUNTAJE
AS SELECT U.CORR_EMPRESA,S.CORR_FORMULARIO_VERSION,U.CORR_PREGUNTA_BECA,U.CORR_PUNTAJE_BECA,U.CORR_OPCION_BECA,O.TEXTO_OPCION,
U.PUNTAJE,U.PORCENTAJE,U.FECHA_INICIO,U.FECHA_FIN
FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE U JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=U.CORR_PREGUNTA_BECA AND P.CORR_EMPRESA=U.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA AND S.CORR_EMPRESA=P.CORR_EMPRESA
LEFT JOIN dbo.ACA_PROSPECTO_BECA_OPCION O ON O.CORR_OPCION_BECA=U.CORR_OPCION_BECA AND O.CORR_EMPRESA=U.CORR_EMPRESA
WHERE U.ACTIVO=1 AND P.ACTIVO=1 AND S.ACTIVO=1 AND (U.CORR_OPCION_BECA IS NULL OR O.ACTIVO=1);
GO
CREATE OR ALTER VIEW dbo.V_ACA_BECA_EDITOR_DEPENDENCIA
AS SELECT D.CORR_EMPRESA,S.CORR_FORMULARIO_VERSION,D.CORR_DEPENDENCIA_BECA,D.CORR_PREGUNTA_PADRE,D.CORR_OPCION_PADRE,D.CORR_PREGUNTA_HIJA,
P.TEXTO_PREGUNTA PREGUNTA_PADRE,O.TEXTO_OPCION OPCION_PADRE,H.TEXTO_PREGUNTA PREGUNTA_HIJA
FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA H ON H.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_HIJA AND H.CORR_EMPRESA=D.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_PADRE AND P.CORR_EMPRESA=D.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_OPCION O ON O.CORR_OPCION_BECA=D.CORR_OPCION_PADRE AND O.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND O.CORR_EMPRESA=D.CORR_EMPRESA
JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=H.CORR_SECCION_BECA AND S.CORR_EMPRESA=H.CORR_EMPRESA
WHERE D.ACTIVO=1 AND H.ACTIVO=1 AND P.ACTIVO=1 AND O.ACTIVO=1 AND S.ACTIVO=1;
GO
CREATE OR ALTER PROCEDURE dbo.PRAL_MTTO_ACA_BECA_CUESTIONARIO
 @OPERACION varchar(10),@ELEMENTO tinyint,@CORR_EMPRESA int,@CORR_BECA int,@CORR_FORMULARIO_VERSION int,@ID int OUTPUT,
 @VERSION_REGISTRO varbinary(8),@USUARIO varchar(100),@ESTACION varchar(50),
 @CORR_SECCION_BECA int=NULL,@CORR_PREGUNTA_BECA int=NULL,@CORR_OPCION_BECA int=NULL,
 @NOMBRE_SECCION varchar(200)=NULL,@DESCRIPCION varchar(1000)=NULL,@ORDEN int=NULL,
 @PUNTAJE_MAXIMO decimal(12,4)=NULL,@PORCENTAJE_SECCION decimal(5,2)=NULL,
 @CODIGO_PREGUNTA varchar(50)=NULL,@TEXTO_PREGUNTA varchar(max)=NULL,@AYUDA varchar(1000)=NULL,@TIPO_RESPUESTA varchar(30)=NULL,@REQUERIDO bit=NULL,
 @TEXTO_OPCION varchar(500)=NULL,@PUNTAJE decimal(12,4)=NULL,@PORCENTAJE decimal(5,2)=NULL,@FECHA_INICIO date=NULL,@FECHA_FIN date=NULL,
 @CORR_PREGUNTA_PADRE int=NULL,@CORR_OPCION_PADRE int=NULL,@CORR_PREGUNTA_HIJA int=NULL
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 IF ISNULL(@OPERACION,'') NOT IN('AGREGAR','EDITAR','QUITAR') OR @ELEMENTO IS NULL OR @ELEMENTO NOT BETWEEN 1 AND 5
  THROW 51000,N'La operacion de cuestionario no es valida.',1;
 IF @CORR_EMPRESA<=0 OR NULLIF(LTRIM(RTRIM(@USUARIO)),'') IS NULL THROW 51000,N'La sesion no es valida.',1;
 IF @OPERACION='AGREGAR' SET @ID=0;
 IF @OPERACION<>'AGREGAR' AND ISNULL(@ID,0)<=0 THROW 51000,N'Seleccione el elemento que desea modificar.',1;
 BEGIN TRY
  BEGIN TRANSACTION;
  DECLARE @Lock int,@TipoActual varchar(30),@FechaVersion date;
  EXEC @Lock=sys.sp_getapplock @Resource=N'ACA_BECA_CONVENIOS_ENTIDADES:ESCRITURA',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
  IF @Lock<0 THROW 51000,N'Otro usuario esta guardando. Intente nuevamente.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_BECA_TIPO WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_BECA=@CORR_BECA)
   THROW 51000,N'La beca no pertenece a la empresa de sesion.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WITH(UPDLOCK,HOLDLOCK) WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION
   AND ESTADO_VERSION='BORRADOR' AND ACTIVO=0 AND VERSION_REGISTRO=@VERSION_REGISTRO)
   THROW 51009,N'El borrador cambio o la version esta publicada. Actualice el cuestionario.',1;
  IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION)
   THROW 51000,N'No se puede modificar una version utilizada por solicitudes.',1;
  IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=PT.CORR_PREGUNTA_BECA
   JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
   WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND PT.ACTIVO=1)
   AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO PT JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=PT.CORR_PREGUNTA_BECA
    JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND PT.CORR_BECA=@CORR_BECA AND PT.ACTIVO=1)
   THROW 51000,N'Este borrador corresponde a otra beca. Clone una version para la beca seleccionada.',1;
  SELECT @FechaVersion=FECHA_INICIO FROM dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION WHERE CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND CORR_EMPRESA=@CORR_EMPRESA;

  -- Resolver los padres desde el registro original al editar o quitar; el cliente no puede trasladar elementos a otra version.
  IF @OPERACION<>'AGREGAR'
  BEGIN
   SET @CORR_SECCION_BECA=NULL; SET @CORR_PREGUNTA_BECA=NULL;
   IF @ELEMENTO=3 SET @CORR_OPCION_BECA=NULL;
   IF @ELEMENTO=1 SELECT @CORR_SECCION_BECA=CORR_SECCION_BECA FROM dbo.ACA_PROSPECTO_BECA_SECCION WHERE CORR_SECCION_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND ACTIVO=1;
   IF @ELEMENTO=2 SELECT @CORR_PREGUNTA_BECA=CORR_PREGUNTA_BECA,@CORR_SECCION_BECA=CORR_SECCION_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_PREGUNTA_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
   IF @ELEMENTO=3 SELECT @CORR_OPCION_BECA=CORR_OPCION_BECA,@CORR_PREGUNTA_BECA=CORR_PREGUNTA_BECA FROM dbo.ACA_PROSPECTO_BECA_OPCION WHERE CORR_OPCION_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
   IF @ELEMENTO=4 SELECT @CORR_PREGUNTA_BECA=CORR_PREGUNTA_BECA FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE WHERE CORR_PUNTAJE_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
   IF @ELEMENTO=5 SELECT @CORR_PREGUNTA_BECA=CORR_PREGUNTA_HIJA FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA WHERE CORR_DEPENDENCIA_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
  END;
  IF @ELEMENTO IN(3,4,5) AND @OPERACION<>'AGREGAR'
   SELECT @CORR_SECCION_BECA=CORR_SECCION_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
  IF @ELEMENTO IN(3,4) AND @OPERACION='AGREGAR'
  BEGIN
   SET @CORR_SECCION_BECA=NULL;
   SELECT @CORR_SECCION_BECA=CORR_SECCION_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
  END;
  IF @ELEMENTO=5 AND @OPERACION='AGREGAR'
  BEGIN
   SET @CORR_SECCION_BECA=NULL;
   SELECT @CORR_SECCION_BECA=CORR_SECCION_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_PREGUNTA_BECA=@CORR_PREGUNTA_HIJA AND CORR_EMPRESA=@CORR_EMPRESA AND ACTIVO=1;
  END;
  IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_SECCION WHERE CORR_SECCION_BECA=@CORR_SECCION_BECA AND CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND ACTIVO=1)
   AND NOT(@ELEMENTO=1 AND @OPERACION='AGREGAR') THROW 51000,N'El elemento no pertenece a esta version del cuestionario.',1;

  IF @OPERACION='QUITAR'
  BEGIN
   IF @ELEMENTO=1
   BEGIN
    IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_PADRE
     JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA H ON H.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_HIJA WHERE D.CORR_EMPRESA=@CORR_EMPRESA AND D.ACTIVO=1
      AND P.CORR_SECCION_BECA=@ID AND H.CORR_SECCION_BECA<>@ID) THROW 51000,N'Quite primero las condiciones que utilizan esta seccion desde otras secciones.',1;
    UPDATE D SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D
     JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=D.CORR_PREGUNTA_HIJA WHERE P.CORR_SECCION_BECA=@ID AND D.CORR_EMPRESA=@CORR_EMPRESA;
    UPDATE dbo.ACA_PROSPECTO_BECA_SECCION SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_SECCION_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
   END;
   IF @ELEMENTO=2
   BEGIN
    IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_PADRE=@ID AND ACTIVO=1)
     THROW 51000,N'Quite primero las condiciones de otras preguntas que utilizan esta pregunta.',1;
    UPDATE dbo.ACA_PROSPECTO_BECA_DEPENDENCIA SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_HIJA=@ID;
    UPDATE dbo.ACA_PROSPECTO_BECA_PREGUNTA SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@ID;
   END;
   IF @ELEMENTO=3
   BEGIN
    IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_OPCION_PADRE=@ID AND ACTIVO=1)
     THROW 51000,N'Quite primero las condiciones que utilizan esta opcion.',1;
    UPDATE dbo.ACA_PROSPECTO_BECA_OPCION SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_OPCION_BECA=@ID;
    UPDATE dbo.ACA_PROSPECTO_BECA_PUNTAJE SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_OPCION_BECA=@ID;
   END;
   IF @ELEMENTO=4 UPDATE dbo.ACA_PROSPECTO_BECA_PUNTAJE SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PUNTAJE_BECA=@ID;
   IF @ELEMENTO=5 UPDATE dbo.ACA_PROSPECTO_BECA_DEPENDENCIA SET ACTIVO=0,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_DEPENDENCIA_BECA=@ID;
  END
  ELSE IF @ELEMENTO=1
  BEGIN
   SET @NOMBRE_SECCION=LTRIM(RTRIM(@NOMBRE_SECCION));
   IF NULLIF(@NOMBRE_SECCION,'') IS NULL OR ISNULL(@ORDEN,0)<1 OR @PUNTAJE_MAXIMO<0 OR @PORCENTAJE_SECCION<0 OR @PORCENTAJE_SECCION>100
    THROW 51000,N'Indique nombre, orden y valores validos para la seccion.',1;
   IF @OPERACION='AGREGAR'
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_SECCION(CORR_FORMULARIO_VERSION,NOMBRE_SECCION,DESCRIPCION,ORDEN,PUNTAJE_MAXIMO,PORCENTAJE_SECCION,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_FORMULARIO_VERSION,@NOMBRE_SECCION,@DESCRIPCION,@ORDEN,@PUNTAJE_MAXIMO,@PORCENTAJE_SECCION,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
   END
   ELSE UPDATE dbo.ACA_PROSPECTO_BECA_SECCION SET NOMBRE_SECCION=@NOMBRE_SECCION,DESCRIPCION=@DESCRIPCION,ORDEN=@ORDEN,PUNTAJE_MAXIMO=@PUNTAJE_MAXIMO,PORCENTAJE_SECCION=@PORCENTAJE_SECCION,
    USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_SECCION_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
  END
  ELSE IF @ELEMENTO=2
  BEGIN
   SET @TEXTO_PREGUNTA=LTRIM(RTRIM(@TEXTO_PREGUNTA));
   IF NULLIF(@TEXTO_PREGUNTA,'') IS NULL OR ISNULL(@ORDEN,0)<1 OR @REQUERIDO IS NULL OR @TIPO_RESPUESTA IS NULL OR @TIPO_RESPUESTA NOT IN('TEXTO','TEXTO_LARGO','NUMERO','DECIMAL','FECHA','OPCION_UNICA','OPCION_MULTIPLE','SI_NO','DOCUMENTO','ACEPTACION')
    THROW 51000,N'Indique la pregunta, el tipo de respuesta, su orden y si es obligatoria.',1;
   IF @OPERACION='EDITAR' AND @TIPO_RESPUESTA NOT IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO')
    AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@ID AND ACTIVO=1)
    THROW 51000,N'Quite primero las opciones antes de cambiar a un tipo de respuesta sin opciones.',1;
   IF @OPERACION='EDITAR' AND @TIPO_RESPUESTA IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') AND EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@ID AND CORR_OPCION_BECA IS NULL AND ACTIVO=1)
    THROW 51000,N'Quite el puntaje general de esta pregunta antes de cambiar a respuestas por opcion.',1;
   SELECT @CODIGO_PREGUNTA=COALESCE(NULLIF(LTRIM(RTRIM(@CODIGO_PREGUNTA)),''),CASE WHEN @OPERACION='EDITAR' THEN CODIGO_PREGUNTA END)
    FROM (SELECT 1 X) X LEFT JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA P ON P.CORR_PREGUNTA_BECA=@ID AND P.CORR_EMPRESA=@CORR_EMPRESA;
   SET @CODIGO_PREGUNTA=COALESCE(@CODIGO_PREGUNTA,'P_'+REPLACE(CONVERT(varchar(36),NEWID()),'-',''));
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND P.CODIGO_PREGUNTA=@CODIGO_PREGUNTA AND P.ACTIVO=1 AND P.CORR_PREGUNTA_BECA<>@ID)
    THROW 51000,N'Ya existe una pregunta con esa referencia en la version.',1;
   IF @OPERACION='AGREGAR'
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_PREGUNTA(CORR_SECCION_BECA,CODIGO_PREGUNTA,TEXTO_PREGUNTA,AYUDA,TIPO_RESPUESTA,REQUERIDO,ORDEN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_SECCION_BECA,@CODIGO_PREGUNTA,@TEXTO_PREGUNTA,@AYUDA,@TIPO_RESPUESTA,@REQUERIDO,@ORDEN,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
    INSERT dbo.ACA_PROSPECTO_BECA_PREGUNTA_TIPO(CORR_PREGUNTA_BECA,CORR_BECA,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@ID,@CORR_BECA,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE());
   END
   ELSE UPDATE dbo.ACA_PROSPECTO_BECA_PREGUNTA SET TEXTO_PREGUNTA=@TEXTO_PREGUNTA,AYUDA=@AYUDA,TIPO_RESPUESTA=@TIPO_RESPUESTA,REQUERIDO=@REQUERIDO,ORDEN=@ORDEN,CODIGO_PREGUNTA=@CODIGO_PREGUNTA,
    USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_PREGUNTA_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
   IF @TIPO_RESPUESTA='SI_NO' AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@ID AND ACTIVO=1)
    INSERT dbo.ACA_PROSPECTO_BECA_OPCION(CORR_PREGUNTA_BECA,TEXTO_OPCION,ORDEN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@ID,'Si',1,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()),(@ID,'No',2,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE());
  END
  ELSE IF @ELEMENTO=3
  BEGIN
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND ACTIVO=1 AND TIPO_RESPUESTA IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO'))
    THROW 51000,N'El tipo de pregunta no utiliza opciones de respuesta.',1;
   SET @TEXTO_OPCION=LTRIM(RTRIM(@TEXTO_OPCION));
   IF NULLIF(@TEXTO_OPCION,'') IS NULL OR ISNULL(@ORDEN,0)<1 THROW 51000,N'Indique el texto y orden de la opcion.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND ACTIVO=1 AND UPPER(TEXTO_OPCION)=UPPER(@TEXTO_OPCION) AND CORR_OPCION_BECA<>@ID)
    THROW 51000,N'Ya existe esa opcion en la pregunta.',1;
   IF @OPERACION='AGREGAR'
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_OPCION(CORR_PREGUNTA_BECA,TEXTO_OPCION,ORDEN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_PREGUNTA_BECA,@TEXTO_OPCION,@ORDEN,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
   END
   ELSE UPDATE dbo.ACA_PROSPECTO_BECA_OPCION SET TEXTO_OPCION=@TEXTO_OPCION,ORDEN=@ORDEN,USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_OPCION_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
  END
  ELSE IF @ELEMENTO=4
  BEGIN
   SELECT @TipoActual=TIPO_RESPUESTA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA WHERE CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND CORR_EMPRESA=@CORR_EMPRESA;
   IF @PUNTAJE IS NULL OR @PUNTAJE<0 OR @PORCENTAJE IS NULL OR @PORCENTAJE<0 OR @PORCENTAJE>100 OR @FECHA_INICIO IS NULL OR @FECHA_FIN<@FECHA_INICIO
    THROW 51000,N'Indique puntaje, porcentaje y fechas validas.',1;
   IF @TipoActual IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_OPCION WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND CORR_OPCION_BECA=@CORR_OPCION_BECA AND ACTIVO=1)
    THROW 51000,N'Seleccione la opcion a la que corresponde el puntaje.',1;
   IF @TipoActual NOT IN('OPCION_UNICA','OPCION_MULTIPLE','SI_NO') AND @CORR_OPCION_BECA IS NOT NULL
    THROW 51000,N'Esta pregunta recibe un puntaje general sin opcion.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PUNTAJE WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_BECA=@CORR_PREGUNTA_BECA AND ISNULL(CORR_OPCION_BECA,0)=ISNULL(@CORR_OPCION_BECA,0)
    AND ACTIVO=1 AND CORR_PUNTAJE_BECA<>@ID AND FECHA_INICIO<=ISNULL(@FECHA_FIN,'99991231') AND ISNULL(FECHA_FIN,'99991231')>=@FECHA_INICIO)
    THROW 51000,N'La regla de puntaje se cruza con otra regla activa de la misma respuesta.',1;
   IF @OPERACION='AGREGAR'
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_PUNTAJE(CORR_PREGUNTA_BECA,CORR_OPCION_BECA,PUNTAJE,PORCENTAJE,FECHA_INICIO,FECHA_FIN,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_PREGUNTA_BECA,@CORR_OPCION_BECA,@PUNTAJE,@PORCENTAJE,@FECHA_INICIO,@FECHA_FIN,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
   END
   ELSE UPDATE dbo.ACA_PROSPECTO_BECA_PUNTAJE SET CORR_OPCION_BECA=@CORR_OPCION_BECA,PUNTAJE=@PUNTAJE,PORCENTAJE=@PORCENTAJE,FECHA_INICIO=@FECHA_INICIO,FECHA_FIN=@FECHA_FIN,
    USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_PUNTAJE_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
  END
  ELSE IF @ELEMENTO=5
  BEGIN
   IF @CORR_PREGUNTA_PADRE=@CORR_PREGUNTA_HIJA OR NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA H JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=H.CORR_SECCION_BECA
    WHERE H.CORR_EMPRESA=@CORR_EMPRESA AND H.CORR_PREGUNTA_BECA=@CORR_PREGUNTA_HIJA AND H.ACTIVO=1 AND S.ACTIVO=1 AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION)
    THROW 51000,N'La pregunta hija no pertenece a esta version o coincide con la pregunta padre.',1;
   IF NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    JOIN dbo.ACA_PROSPECTO_BECA_OPCION O ON O.CORR_PREGUNTA_BECA=P.CORR_PREGUNTA_BECA AND O.CORR_EMPRESA=P.CORR_EMPRESA
    WHERE P.CORR_EMPRESA=@CORR_EMPRESA AND P.CORR_PREGUNTA_BECA=@CORR_PREGUNTA_PADRE AND P.ACTIVO=1 AND S.ACTIVO=1 AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND O.ACTIVO=1 AND O.CORR_OPCION_BECA=@CORR_OPCION_PADRE)
    THROW 51000,N'Seleccione una pregunta padre y una opcion activa de esta version.',1;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_PREGUNTA_PADRE=@CORR_PREGUNTA_PADRE AND CORR_PREGUNTA_HIJA=@CORR_PREGUNTA_HIJA AND CORR_OPCION_PADRE=@CORR_OPCION_PADRE AND ACTIVO=1 AND CORR_DEPENDENCIA_BECA<>@ID)
    THROW 51000,N'La condicion ya existe.',1;
   IF @OPERACION='AGREGAR'
   BEGIN
    INSERT dbo.ACA_PROSPECTO_BECA_DEPENDENCIA(CORR_PREGUNTA_PADRE,CORR_OPCION_PADRE,CORR_PREGUNTA_HIJA,ACTIVO,CORR_EMPRESA,USUARIO_CREA,ESTACION_CREA,FECHA_CREA)
    VALUES(@CORR_PREGUNTA_PADRE,@CORR_OPCION_PADRE,@CORR_PREGUNTA_HIJA,1,@CORR_EMPRESA,@USUARIO,@ESTACION,GETDATE()); SET @ID=CONVERT(int,SCOPE_IDENTITY());
   END
   ELSE UPDATE dbo.ACA_PROSPECTO_BECA_DEPENDENCIA SET CORR_PREGUNTA_PADRE=@CORR_PREGUNTA_PADRE,CORR_OPCION_PADRE=@CORR_OPCION_PADRE,CORR_PREGUNTA_HIJA=@CORR_PREGUNTA_HIJA,
    USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE() WHERE CORR_DEPENDENCIA_BECA=@ID AND CORR_EMPRESA=@CORR_EMPRESA;
   DECLARE @Ordenadas TABLE(Id int PRIMARY KEY);
   WHILE 1=1
   BEGIN
    INSERT @Ordenadas SELECT P.CORR_PREGUNTA_BECA FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND S.ACTIVO=1 AND P.ACTIVO=1
     AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=P.CORR_PREGUNTA_BECA)
     AND NOT EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_DEPENDENCIA D WHERE D.CORR_EMPRESA=@CORR_EMPRESA AND D.CORR_PREGUNTA_HIJA=P.CORR_PREGUNTA_BECA AND D.ACTIVO=1
      AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=D.CORR_PREGUNTA_PADRE));
    IF @@ROWCOUNT=0 BREAK;
   END;
   IF EXISTS(SELECT 1 FROM dbo.ACA_PROSPECTO_BECA_PREGUNTA P JOIN dbo.ACA_PROSPECTO_BECA_SECCION S ON S.CORR_SECCION_BECA=P.CORR_SECCION_BECA
    WHERE S.CORR_EMPRESA=@CORR_EMPRESA AND S.CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION AND S.ACTIVO=1 AND P.ACTIVO=1 AND NOT EXISTS(SELECT 1 FROM @Ordenadas X WHERE X.Id=P.CORR_PREGUNTA_BECA))
    THROW 51000,N'La condicion crea un ciclo entre preguntas.',1;
  END;
  UPDATE dbo.ACA_PROSPECTO_BECA_FORMULARIO_VERSION SET USUARIO_ACTU=@USUARIO,ESTACION_ACTU=@ESTACION,FECHA_ACTU=GETDATE()
   WHERE CORR_EMPRESA=@CORR_EMPRESA AND CORR_FORMULARIO_VERSION=@CORR_FORMULARIO_VERSION;
  COMMIT;
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK; THROW;
 END CATCH;
END;
