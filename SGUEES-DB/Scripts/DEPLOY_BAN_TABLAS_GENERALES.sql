SET NOCOUNT ON;
GO

IF OBJECT_ID('dbo.GEN_BANCO', 'U') IS NULL
BEGIN
    RAISERROR('GEN_BANCO no existe. Despliegue GEN_BANCO antes de continuar.', 16, 1);
    RETURN;
END
ELSE
    PRINT 'GEN_BANCO OK.';
GO

IF OBJECT_ID('dbo.BAN_LINEA_TRABAJO_CONCILIACION', 'U') IS NULL
BEGIN
    PRINT 'Creando BAN_LINEA_TRABAJO_CONCILIACION...';
    :r ..\Tables\dbo.BAN_LINEA_TRABAJO_CONCILIACION.sql
END
