GO

IF OBJECT_ID('dbo.BAN_CUENTA_BANCARIA', 'U') IS NULL
BEGIN
    PRINT 'Creando BAN_CUENTA_BANCARIA...';
    :r ..\Tables\dbo.BAN_CUENTA_BANCARIA.sql
END
ELSE IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_BAN_CUENTA_BANCARIA_GEN_BANCO')
BEGIN
    PRINT 'Agregando FK_BAN_CUENTA_BANCARIA_GEN_BANCO...';
    ALTER TABLE dbo.BAN_CUENTA_BANCARIA
        ADD CONSTRAINT FK_BAN_CUENTA_BANCARIA_GEN_BANCO
        FOREIGN KEY (CORR_EMPRESA, CORR_BANCO) REFERENCES dbo.GEN_BANCO (CORR_EMPRESA, CORR_BANCO);
END
ELSE
    PRINT 'BAN_CUENTA_BANCARIA OK.';
GO

SELECT TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME IN (
    'GEN_BANCO',
    'BAN_LINEA_TRABAJO_CONCILIACION',
    'BAN_TIPO_CHEQUE',
    'BAN_TIPO_MOVI_BANCARIO',
    'BAN_CUENTA_BANCARIA'
)
ORDER BY 1;
GO
