CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PROVISION_APLICAR]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int OUTPUT,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)

AS

BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
	
		DECLARE	 @ESTADO_PROVISION VARCHAR(2), @MONTO_CARGO DECIMAL(12,2), @MONTO_ABONO DECIMAL(12,2), @CUENTA_CONTABLE_PROVEEDOR VARCHAR(30),
		@TIPO_ACTUALIZA INT, @CORR_CLASE_PARTIDA INT, @CORR_PARTIDA INT, @CORR_PARTIDA_DETA INT, @CLASE_PARTIDA VARCHAR(3), @FECHA_PARTIDA DATE, 
		@NUMERO_DOCUMENTO INT, @NOMBRE_PARTIDA VARCHAR(1000),@CORR_DETA INT,@CUENTA_CONTABLE_DETA VARCHAR(30),@CORR_CENTRO_COSTO_DETA INT,
		@NOMBRE_TRAN_DETA VARCHAR(255),@MONTO_CARGO_DETA DECIMAL(18,2), @MONTO_ABONO_DETA DECIMAL(18,2)
		, @HOY DATETIME, @ANIO_PERIODO_PARTIDA INT,@CORR_AUXILIAR INT,
		@MES_PERIODO_PARTIDA INT
		
		SELECT @ESTADO_PROVISION=ESTADO_PROVISION, @CUENTA_CONTABLE_PROVEEDOR=B.CUENTA_CONTABLE
		,@CORR_PARTIDA=CORR_PARTIDA
		,@CORR_CLASE_PARTIDA=CORR_CLASE_PARTIDA
		,@ANIO_PERIODO_PARTIDA=ANIO_PERIODO_PARTIDA
		,@MES_PERIODO_PARTIDA=MES_PERIODO_PARTIDA
		FROM COM_PROVISION  A
		INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION
		
		IF ISNULL(@ANIO_PERIODO_PARTIDA,0)=0
			SELECT @ANIO_PERIODO_PARTIDA=@ANIO_PERIODO
			
		IF ISNULL(@MES_PERIODO_PARTIDA,0)=0
			SELECT @MES_PERIODO_PARTIDA=@MES_PERIODO
		
		SELECT @CORR_PARTIDA=ISNULL(@CORR_PARTIDA,0)		
		
		IF ISNULL(@ESTADO_PROVISION,'') = ''
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Esta provisión no existe.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF @ESTADO_PROVISION <> 'DI'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='Esta provisión ya está aplicada o anulada',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF NOT EXISTS(SELECT 1 FROM CON_PERIODO_CONTABLE
					  WHERE CORR_EMPRESA=@CORR_EMPRESA
					  AND ANIO_PERIODO=@ANIO_PERIODO
					  AND MES_PERIODO=@MES_PERIODO
					  AND ESTADO_PERIODO_COM='AB')
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='El periodo contable para compras NO esta Abierto. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF NOT EXISTS(SELECT 1 FROM COM_PROVISION_CONTA 
						  WHERE CORR_EMPRESA=@CORR_EMPRESA
						  AND ANIO_PERIODO=@ANIO_PERIODO
						  AND MES_PERIODO=@MES_PERIODO
						  AND CORR_PROVISION=@CORR_PROVISION )
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30004,@SYS_MENSAJE_ERROR='El Documento NO tiene detalle contable. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		SELECT @MONTO_CARGO=SUM(A.MONTO_CARGO),
		@MONTO_ABONO=SUM(A.MONTO_ABONO)
		FROM COM_PROVISION_CONTA A
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
		
		IF @MONTO_CARGO<>@MONTO_ABONO
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Documento NO cuadrada. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF @MONTO_CARGO=0 AND @MONTO_ABONO=0
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30003,@SYS_MENSAJE_ERROR='El Documento suma cero. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END	
		
		IF NOT EXISTS(SELECT 1 FROM COM_PROVISION_CONTA
					  WHERE CORR_EMPRESA=@CORR_EMPRESA
					  AND ANIO_PERIODO=@ANIO_PERIODO
					  AND MES_PERIODO=@MES_PERIODO
					  AND CORR_PROVISION=@CORR_PROVISION
					  AND CUENTA_CONTABLE=@CUENTA_CONTABLE_PROVEEDOR)
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30005,@SYS_MENSAJE_ERROR='El Documento NO contiene la cuenta del proveedor. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		--Se valida que el periodo CONTABLE este abierto
		IF NOT EXISTS(SELECT 1 FROM CON_PERIODO_CONTABLE
				  WHERE CORR_EMPRESA=@CORR_EMPRESA
				  AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
				  AND MES_PERIODO=@MES_PERIODO_PARTIDA
				  AND ESTADO_PERIODO_CON='AB')
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='El periodo contable NO esta Abierto. Esta provision no se puede contabilizar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF ISNULL(@CORR_CLASE_PARTIDA,0)=0
		BEGIN
			SELECT @CORR_CLASE_PARTIDA=ISNULL(CORR_CLASE_PARTIDA_DEFAULT,1)
			FROM CON_PARAMETRO A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		END
		
		IF NOT EXISTS(SELECT 1 FROM CON_PARTIDA
					  WHERE CORR_EMPRESA=@CORR_EMPRESA
					  AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
					  AND MES_PERIODO=@MES_PERIODO_PARTIDA
					  AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
					  AND CORR_PARTIDA=@CORR_PARTIDA)
		BEGIN	
			SELECT @TIPO_ACTUALIZA=1
		END ELSE
		BEGIN
			SELECT @TIPO_ACTUALIZA=2
		END
			
		SELECT @FECHA_PARTIDA=FECHA_PROVISION, @NUMERO_DOCUMENTO=CORR_PROVISION, @NOMBRE_PARTIDA=NOMBRE_PARTIDA  
		FROM COM_PROVISION 
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION 	
		
BEGIN TRANSACTION
		SELECT @HOY=GETDATE()
		
		EXECUTE PRAL_MTTO_CON_PARTIDA
		   @TIPO_ACTUALIZA
		, @CORR_EMPRESA
		  ,@ANIO_PERIODO_PARTIDA
		  ,@MES_PERIODO_PARTIDA
		  ,@CORR_CLASE_PARTIDA
		  ,@CORR_PARTIDA OUTPUT
		  ,@FECHA_PARTIDA
		  ,@NUMERO_DOCUMENTO
		  ,@NOMBRE_PARTIDA
		  ,'DI'
		  ,NULL, NULL, NULL, NULL
		  ,@SYS_LOGIN_USUARIO
		  ,@HOY
		  ,@SYS_ESTACION
		  ,@SYS_LOGIN_USUARIO
		  ,@HOY
		  ,@SYS_ESTACION
		  ,@SYS_LOGIN_USUARIO
		  ,@SYS_ESTACION
		  ,@SYS_FILAS_AFECTADAS OUTPUT
		  ,@SYS_NUMERO_ERROR OUTPUT
		  ,@SYS_MENSAJE_ERROR OUTPUT
		  ,0 --@APLICAR_DOC_CONTA = NO
		
		IF @SYS_NUMERO_ERROR<>0
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION
			
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='No se puede aplicar esta provisión, ya que la partida contable no se pudo generar. '+@SYS_MENSAJE_ERROR,@SYS_FILAS_AFECTADAS=0		
			GOTO FINA
		END ELSE
		BEGIN
		    
		    DELETE FROM CON_PARTIDA_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
			AND MES_PERIODO=@MES_PERIODO_PARTIDA
			AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
			AND CORR_PARTIDA=@CORR_PARTIDA
			
			SELECT @TIPO_ACTUALIZA=1
		
			DECLARE @TEMP TABLE (
				CORR_DETA INT
				,CUENTA_CONTABLE VARCHAR(30)
				,CORR_CENTRO_COSTO INT
				,CORR_AUXILIAR INT
				,NOMBRE_TRAN VARCHAR(255)
				,MONTO_CARGO DECIMAL(18,2)
				,MONTO_ABONO DECIMAL(18,2)
				,ESTA_PROC BIT
			)
			
			DECLARE @CONTADOR INT, @CANTIDAD_REGISTROS INT
			
			INSERT INTO @TEMP 
			SELECT CORR_DETA
			,CUENTA_CONTABLE
			,CORR_CENTRO_COSTO
			,CORR_AUXILIAR
			,NOMBRE_TRAN
			,MONTO_CARGO
			,MONTO_ABONO
			
			,ESTA_PROC=0
			FROM COM_PROVISION_CONTA  
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			
			SELECT @CONTADOR=0, @CANTIDAD_REGISTROS=COUNT(*)
			FROM @TEMP 
			
			WHILE (@CONTADOR<@CANTIDAD_REGISTROS)
			BEGIN
				SELECT TOP 1 @CORR_DETA=CORR_DETA, @CUENTA_CONTABLE_DETA=CUENTA_CONTABLE,@CORR_CENTRO_COSTO_DETA=CORR_CENTRO_COSTO,@CORR_AUXILIAR=CORR_AUXILIAR,
				@NOMBRE_TRAN_DETA=NOMBRE_TRAN, @MONTO_CARGO_DETA=MONTO_CARGO, @MONTO_ABONO_DETA=MONTO_ABONO
				FROM @TEMP 
				WHERE ESTA_PROC=0
				
				SELECT @CORR_PARTIDA_DETA=0

				EXECUTE PRAL_MTTO_CON_PARTIDA_DETA
				   @TIPO_ACTUALIZA
		, @CORR_EMPRESA
				  ,@ANIO_PERIODO_PARTIDA
				  ,@MES_PERIODO_PARTIDA
				  ,@CORR_CLASE_PARTIDA
				  ,@CORR_PARTIDA
				  ,@CORR_PARTIDA_DETA OUTPUT
				  ,@CUENTA_CONTABLE_DETA
				  ,@CORR_CENTRO_COSTO_DETA 
				  ,@MONTO_CARGO_DETA 
				  ,@MONTO_ABONO_DETA 
				  ,@NOMBRE_TRAN_DETA 
				  ,NULL, NULL, NULL
				  ,@SYS_LOGIN_USUARIO
				  ,@SYS_ESTACION
				  ,@SYS_FILAS_AFECTADAS OUTPUT
				  ,@SYS_NUMERO_ERROR OUTPUT
				  ,@SYS_MENSAJE_ERROR OUTPUT
				  ,@CORR_AUXILIAR
				  
				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					IF @@TRANCOUNT>0
						ROLLBACK TRANSACTION
					
					SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='No se puede aplicar esta provisión, ya que el detalle de la partida contable no se pudo generar. '+@SYS_MENSAJE_ERROR,@SYS_FILAS_AFECTADAS=0		
					GOTO FINA
				END 
				
				UPDATE @TEMP SET ESTA_PROC=1
				WHERE CORR_DETA=@CORR_DETA 					
				SELECT @CONTADOR+=1
			END
		END		
		
		EXECUTE PRAL_MTTO_CON_PARTIDA_APLICAR
@CORR_EMPRESA
		  ,@ANIO_PERIODO_PARTIDA
		  ,@MES_PERIODO_PARTIDA
		  ,@CORR_CLASE_PARTIDA
		  ,@CORR_PARTIDA OUTPUT
		  ,@SYS_LOGIN_USUARIO
		  ,@HOY
		  ,@SYS_ESTACION 
		  ,@SYS_LOGIN_USUARIO
		  ,@SYS_ESTACION
		  ,@SYS_FILAS_AFECTADAS OUTPUT
		  ,@SYS_NUMERO_ERROR OUTPUT
		  ,@SYS_MENSAJE_ERROR OUTPUT
		  
		IF @SYS_NUMERO_ERROR<>0
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION
				
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='No se puede aplicar esta provisión, ya que la partida contable no se pudo aplicar. '+@SYS_MENSAJE_ERROR,@SYS_FILAS_AFECTADAS=0		
			GOTO FINA
		END 
			
		UPDATE COM_PROVISION SET
		ESTADO_PROVISION='AP',
		ANIO_PERIODO_PARTIDA=@ANIO_PERIODO,MES_PERIODO_PARTIDA=@MES_PERIODO,
		CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA,CORR_PARTIDA=@CORR_PARTIDA 
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION 
		
		UPDATE COM_DOCUMENTO SET
		ESTA_PROVISIONADO=1
		FROM COM_PROVISION A
		INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
		INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION 
		
		
		SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
		
		IF @@TRANCOUNT>0
			COMMIT TRANSACTION		
		
		GOTO FINA
		
		
		
	END TRY
	BEGIN CATCH
	IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO


