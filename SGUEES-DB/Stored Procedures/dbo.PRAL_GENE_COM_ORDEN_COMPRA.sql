CREATE PROCEDURE [dbo].[PRAL_GENE_COM_ORDEN_COMPRA]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@CORR_CUADRO_COMPARATIVO INT OUTPUT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38,0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
	DECLARE @ANIO_PERIODO_BITACORA INT = YEAR(GETDATE()),
		@CORR_BITACORA_TRANS INT = 0,
		@FECHA_BITACORA DATE = GETDATE(),
		@LLAVE_TRANSACCION VARCHAR(250),
		@REFERENCIA_TRANSACCION VARCHAR(500),
		@USUARIO_CREA_TRANS VARCHAR(50),
		@ESTACION_CREA_TRANS VARCHAR(50),
		@FECHA_CREA_TRANS DATETIME,
		@USUARIO_ACTU_TRANS VARCHAR(50),
		@ESTACION_ACTU_TRANS VARCHAR(50),
		@FECHA_ACTU_TRANS DATETIME,
		@FECHA_CREA_BITACORA DATETIME = GETDATE(),
		@CODIGO_OPCION VARCHAR(150) = 'COM_CUADRO_COMPARATIVO',
		@CLASE_BITACORA VARCHAR(3) = 'AU',
		@REFERENCIA_TRANSACCION_ORDEN VARCHAR(500)

	DECLARE @CORR_PROVEEDOR INT,
		@OBSERVACION VARCHAR(2000),
		@CORR_CONDICION_PAGO INT,
		@CORR_FORMA_PAGO INT,
		@DETALLE_FORMA_PAGO VARCHAR(250),
		@CORR_ORDEN_COMPRA INT,
		@NUMERO_ORDEN_COMPRA INT,
		@MONTO_TOTAL_ORDEN_COMPRA DECIMAL(18, 6),
		@CORR_ORDEN_COMPRA_DETA INT,
		@FECHA_HOY DATETIME = GETDATE()

	DECLARE @PROVEEDORES TABLE (
		CORR_PROVEEDOR INT,
		OBSERVACION VARCHAR(2000),
		CORR_CONDICION_PAGO INT,
		CORR_FORMA_PAGO INT,
		DETALLE_FORMA_PAGO VARCHAR(250)
	)

	DECLARE @LINEAS TABLE (
		CODIGO_ITEM VARCHAR(30),
		CORR_UNIDAD_MEDIDA INT,
		CANTIDAD DECIMAL(18, 2),
		PRECIO_UNITARIO DECIMAL(18, 6),
		MONTO_SUBTOTAL DECIMAL(18, 6),
		ANIO_PERIODO_COTIZACION INT,
		CORR_COTIZACION INT,
		CORR_COTIZACION_DETA INT
	)
BEGIN
	SET NOCOUNT ON
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0

	BEGIN TRY
		SELECT
			@LLAVE_TRANSACCION = N'Año: ' + CONVERT(VARCHAR, A.ANIO_PERIODO) + N' Correlativo No.: ' + CONVERT(VARCHAR, A.CORR_CUADRO_COMPARATIVO),
			@REFERENCIA_TRANSACCION = N' Fecha: ' + CONVERT(VARCHAR, A.FECHA_CUADRO_COMPARATIVO)
				+ N', Proveedor: ' + ISNULL(A.NOMBRE_PROVEEDOR, N'')
				+ N', Observaciones: ' + ISNULL(A.OBSERVACIONES, N''),
			@USUARIO_CREA_TRANS = A.USUARIO_CREA,
			@ESTACION_CREA_TRANS = A.ESTACION_CREA,
			@FECHA_CREA_TRANS = A.FECHA_CREA,
			@USUARIO_ACTU_TRANS = A.USUARIO_ACTU,
			@ESTACION_ACTU_TRANS = A.ESTACION_ACTU,
			@FECHA_ACTU_TRANS = A.FECHA_ACTU
		FROM dbo.V_COM_CUADRO_COMPARATIVO A
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA
			AND A.ANIO_PERIODO = @ANIO_PERIODO
			AND A.CORR_CUADRO_COMPARATIVO = @CORR_CUADRO_COMPARATIVO

		INSERT INTO @PROVEEDORES (CORR_PROVEEDOR, OBSERVACION, CORR_CONDICION_PAGO, CORR_FORMA_PAGO, DETALLE_FORMA_PAGO)
		SELECT DISTINCT
			D.CORR_PROVEEDOR,
			ISNULL(A.OBSERVACIONES, N''),
			D.CORR_CONDICION_PAGO,
			D.CORR_FORMA_PAGO,
			D.DETALLE_FORMA_PAGO
		FROM dbo.COM_CUADRO_COMPARATIVO A
		INNER JOIN dbo.COM_CUADRO_COMPARATIVO_DETA B
			ON A.CORR_EMPRESA = B.CORR_EMPRESA
			AND A.ANIO_PERIODO = B.ANIO_PERIODO
			AND A.CORR_CUADRO_COMPARATIVO = B.CORR_CUADRO_COMPARATIVO
		INNER JOIN dbo.COM_COTIZACION_DETA C
			ON B.CORR_EMPRESA = C.CORR_EMPRESA
			AND B.ANIO_PERIODO_COTIZACION = C.ANIO_PERIODO
			AND B.CORR_COTIZACION = C.CORR_COTIZACION
			AND B.CORR_COTIZACION_DETA = C.CORR_COTIZACION_DETA
		INNER JOIN dbo.COM_COTIZACION D
			ON D.CORR_EMPRESA = C.CORR_EMPRESA
			AND D.ANIO_PERIODO = C.ANIO_PERIODO
			AND D.CORR_COTIZACION = C.CORR_COTIZACION
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA
			AND A.ANIO_PERIODO = @ANIO_PERIODO
			AND A.CORR_CUADRO_COMPARATIVO = @CORR_CUADRO_COMPARATIVO
			AND B.SELECCION = 1
			AND ISNULL(C.MONTO_SUBTOTAL, 0) > 0

		WHILE EXISTS (SELECT 1 FROM @PROVEEDORES)
		BEGIN
			SELECT TOP 1
				@CORR_PROVEEDOR = CORR_PROVEEDOR,
				@OBSERVACION = OBSERVACION,
				@CORR_CONDICION_PAGO = CORR_CONDICION_PAGO,
				@CORR_FORMA_PAGO = CORR_FORMA_PAGO,
				@DETALLE_FORMA_PAGO = DETALLE_FORMA_PAGO
			FROM @PROVEEDORES

			DELETE FROM @LINEAS

			INSERT INTO @LINEAS (
				CODIGO_ITEM, CORR_UNIDAD_MEDIDA, CANTIDAD, PRECIO_UNITARIO, MONTO_SUBTOTAL,
				ANIO_PERIODO_COTIZACION, CORR_COTIZACION, CORR_COTIZACION_DETA
			)
			SELECT
				C.CODIGO_ITEM,
				C.CORR_UNIDAD_MEDIDA,
				C.CANTIDAD,
				C.PRECIO_UNITARIO,
				C.MONTO_SUBTOTAL,
				C.ANIO_PERIODO,
				C.CORR_COTIZACION,
				C.CORR_COTIZACION_DETA
			FROM dbo.COM_CUADRO_COMPARATIVO A
			INNER JOIN dbo.COM_CUADRO_COMPARATIVO_DETA B
				ON A.CORR_EMPRESA = B.CORR_EMPRESA
				AND A.ANIO_PERIODO = B.ANIO_PERIODO
				AND A.CORR_CUADRO_COMPARATIVO = B.CORR_CUADRO_COMPARATIVO
			INNER JOIN dbo.COM_COTIZACION_DETA C
				ON B.CORR_EMPRESA = C.CORR_EMPRESA
				AND B.ANIO_PERIODO_COTIZACION = C.ANIO_PERIODO
				AND B.CORR_COTIZACION = C.CORR_COTIZACION
				AND B.CORR_COTIZACION_DETA = C.CORR_COTIZACION_DETA
			INNER JOIN dbo.COM_COTIZACION D
				ON D.CORR_EMPRESA = C.CORR_EMPRESA
				AND D.ANIO_PERIODO = C.ANIO_PERIODO
				AND D.CORR_COTIZACION = C.CORR_COTIZACION
			WHERE A.CORR_EMPRESA = @CORR_EMPRESA
				AND A.ANIO_PERIODO = @ANIO_PERIODO
				AND A.CORR_CUADRO_COMPARATIVO = @CORR_CUADRO_COMPARATIVO
				AND B.SELECCION = 1
				AND D.CORR_PROVEEDOR = @CORR_PROVEEDOR
				AND ISNULL(C.MONTO_SUBTOTAL, 0) > 0

			SELECT @MONTO_TOTAL_ORDEN_COMPRA = ISNULL(SUM(MONTO_SUBTOTAL), 0) FROM @LINEAS

			SELECT @CORR_ORDEN_COMPRA = ISNULL(MAX(CORR_ORDEN_COMPRA), 0) + 1
			FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO

			SELECT @NUMERO_ORDEN_COMPRA = ISNULL(MAX(NUMERO_ORDEN_COMPRA), (@ANIO_PERIODO % 100) * 100000) + 1
			FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO

			INSERT INTO dbo.COM_ORDEN_COMPRA (
				CORR_EMPRESA, ANIO_PERIODO, CORR_ORDEN_COMPRA, CORR_TIPO_DOC, CORR_PROVEEDOR,
				ATENCION_A, FECHA_ORDEN, ESTADO_ORDEN, USUARIO_AUTORIZA, FECHA_AUTORIZA,
				OBSERVACIONES, COMPRA_TOTAL, MONTO_EN_LETRAS, NUMERO_ORDEN_COMPRA,
				CORR_CONDICION_PAGO, CORR_FORMA_PAGO, DETALLE_FORMA_PAGO,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA
			)
			VALUES (
				@CORR_EMPRESA, @ANIO_PERIODO, @CORR_ORDEN_COMPRA, NULL, @CORR_PROVEEDOR,
				NULL, CONVERT(DATE, @FECHA_HOY), N'AP', @SYS_LOGIN_USUARIO, @FECHA_HOY,
				@OBSERVACION, @MONTO_TOTAL_ORDEN_COMPRA, NULL, @NUMERO_ORDEN_COMPRA,
				@CORR_CONDICION_PAGO, @CORR_FORMA_PAGO, @DETALLE_FORMA_PAGO,
				@SYS_LOGIN_USUARIO, @FECHA_HOY, @SYS_ESTACION
			)

			SET @CORR_ORDEN_COMPRA_DETA = 0
			WHILE EXISTS (SELECT 1 FROM @LINEAS)
			BEGIN
				DECLARE @CODIGO_ITEM VARCHAR(30),
					@CORR_UNIDAD_MEDIDA INT,
					@CANTIDAD DECIMAL(18, 2),
					@PRECIO_UNITARIO DECIMAL(18, 6),
					@MONTO_SUBTOTAL DECIMAL(18, 6),
					@ANIO_PERIODO_COTIZACION INT,
					@CORR_COTIZACION INT,
					@CORR_COTIZACION_DETA INT

				SELECT TOP 1
					@CODIGO_ITEM = CODIGO_ITEM,
					@CORR_UNIDAD_MEDIDA = CORR_UNIDAD_MEDIDA,
					@CANTIDAD = CANTIDAD,
					@PRECIO_UNITARIO = PRECIO_UNITARIO,
					@MONTO_SUBTOTAL = MONTO_SUBTOTAL,
					@ANIO_PERIODO_COTIZACION = ANIO_PERIODO_COTIZACION,
					@CORR_COTIZACION = CORR_COTIZACION,
					@CORR_COTIZACION_DETA = CORR_COTIZACION_DETA
				FROM @LINEAS

				SET @CORR_ORDEN_COMPRA_DETA = @CORR_ORDEN_COMPRA_DETA + 1

				INSERT INTO dbo.COM_ORDEN_COMPRA_DETA (
					CORR_EMPRESA, ANIO_PERIODO, CORR_ORDEN_COMPRA, CORR_ORDEN_COMPRA_DETA,
					CODIGO_ITEM, CORR_UNIDAD_MEDIDA, CANTIDAD_COMPRA, PRECIO_UNITARIO, MONTO_SUBTOTAL,
					ANIO_PERIODO_COTIZACION, CORR_COTIZACION, CORR_COTIZACION_DETA, CANTIDAD_RECIBIDA,
					USUARIO_CREA, FECHA_CREA, ESTACION_CREA
				)
				VALUES (
					@CORR_EMPRESA, @ANIO_PERIODO, @CORR_ORDEN_COMPRA, @CORR_ORDEN_COMPRA_DETA,
					@CODIGO_ITEM, @CORR_UNIDAD_MEDIDA, @CANTIDAD, @PRECIO_UNITARIO, @MONTO_SUBTOTAL,
					@ANIO_PERIODO_COTIZACION, @CORR_COTIZACION, @CORR_COTIZACION_DETA, 0,
					@SYS_LOGIN_USUARIO, @FECHA_HOY, @SYS_ESTACION
				)

				DELETE FROM @LINEAS
				WHERE CODIGO_ITEM = @CODIGO_ITEM
					AND CORR_COTIZACION = @CORR_COTIZACION
					AND CORR_COTIZACION_DETA = @CORR_COTIZACION_DETA
					AND ANIO_PERIODO_COTIZACION = @ANIO_PERIODO_COTIZACION
			END

			INSERT INTO dbo.COM_CUADRO_COMPARATIVO_ORDEN_COMPRA (
				CORR_EMPRESA, ANIO_PERIODO, CORR_CUADRO_COMPARATIVO, NUMERO_ORDEN, CORR_ORDEN_COMPRA,
				CORR_PROVEEDOR, MONTO_TOTAL_ORDEN, CORR_CONDICION_PAGO, CORR_FORMA_PAGO, DETALLE_FORMA_PAGO
			)
			VALUES (
				@CORR_EMPRESA, @ANIO_PERIODO, @CORR_CUADRO_COMPARATIVO, @NUMERO_ORDEN_COMPRA, @CORR_ORDEN_COMPRA,
				@CORR_PROVEEDOR, @MONTO_TOTAL_ORDEN_COMPRA, @CORR_CONDICION_PAGO, @CORR_FORMA_PAGO, @DETALLE_FORMA_PAGO
			)

			DELETE FROM @PROVEEDORES WHERE CORR_PROVEEDOR = @CORR_PROVEEDOR

			SET @REFERENCIA_TRANSACCION_ORDEN = N'Orden No.' + CONVERT(VARCHAR(25), @NUMERO_ORDEN_COMPRA) + N' ' + @REFERENCIA_TRANSACCION

			EXECUTE dbo.PRAL_MTTO_COM_BITACORA
				1,
				@CORR_EMPRESA,
				@ANIO_PERIODO_BITACORA,
				@CORR_BITACORA_TRANS OUTPUT,
				@FECHA_BITACORA,
				@CODIGO_OPCION,
				@CLASE_BITACORA,
				@LLAVE_TRANSACCION,
				@REFERENCIA_TRANSACCION_ORDEN,
				@USUARIO_CREA_TRANS,
				@ESTACION_CREA_TRANS,
				@FECHA_CREA_TRANS,
				@USUARIO_ACTU_TRANS,
				@ESTACION_ACTU_TRANS,
				@FECHA_ACTU_TRANS,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@FECHA_CREA_BITACORA,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR OUTPUT
		END

		SELECT @SYS_FILAS_AFECTADAS = @@ROWCOUNT
	END TRY
	BEGIN CATCH
		SELECT
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE()
	END CATCH
END
