CREATE PROCEDURE [dbo].[PRAL_GENE_COM_PAGO_CONTA]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PAGO int,
	@CORR_DETA int OUTPUT,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
	DECLARE @USA_DESCRIPCION_PARTIDA BIT,@PROVISIONAR_POR_DOC BIT

BEGIN

	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY			
		
		--Eliminando el detalle contable anterior
		DELETE FROM COM_PAGO_CONTA
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO
--Si No se pago con caja chica
		IF EXISTS(SELECT 1 FROM COM_PAGO
				  WHERE CORR_EMPRESA=@CORR_EMPRESA 
				  AND ANIO_PERIODO=@ANIO_PERIODO 
				  AND MES_PERIODO=@MES_PERIODO
				  AND CORR_PAGO=@CORR_PAGO
				  AND ISNULL(PAGADO_CAJA_CHICA,0)=0)
		BEGIN
			SELECT @CORR_DETA=1
			
			SELECT @USA_DESCRIPCION_PARTIDA=ISNULL(A.USA_DESCRIPCION_PARTIDA,0),@PROVISIONAR_POR_DOC=ISNULL(A.PROVISIONAR_POR_DOC,0)
			FROM COM_PARAMETRO A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
							
			--Abono el total de la provisión a la cuenta del banco
			INSERT INTO dbo.COM_PAGO_CONTA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_DETA,CUENTA_CONTABLE,CORR_CENTRO_COSTO,NOMBRE_TRAN,MONTO_CARGO,MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,@CORR_DETA CORR_DETA 
			,C.CUENTA_CONTABLE
			,NULL CORR_CENTRO_COSTO
			,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN B.NOMBRE_PROVEEDOR+' '+ISNULL(E.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END END NOMBRE_TRAN
			,CASE WHEN A.MONTO_PAGO<0 THEN ABS(A.MONTO_PAGO) ELSE 0 END
			,CASE WHEN A.MONTO_PAGO>0 THEN ABS(A.MONTO_PAGO) ELSE 0 END
			,D.CORR_AUXILIAR
			FROM COM_PAGO A
			INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR
			LEFT OUTER JOIN BAN_CUENTA_BANCARIA C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_CUENTA_BANCO=C.CORR_CUENTA_BANCO 
			LEFT OUTER JOIN CON_CATALOGO_CUENTA_AUXI D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_CUENTA_BANCO = D.CORR_CUENTA_BANCO AND C.CUENTA_CONTABLE = D.CUENTA_CONTABLE
			INNER JOIN V_COM_PAGO_DESCRIPCION E ON A.CORR_EMPRESA=E.CORR_EMPRESA AND A.ANIO_PERIODO=E.ANIO_PERIODO AND A.MES_PERIODO=E.MES_PERIODO AND A.CORR_PAGO=E.CORR_PAGO
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
			GROUP BY  A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,C.CUENTA_CONTABLE
			,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN B.NOMBRE_PROVEEDOR+' '+ISNULL(E.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END END
			,A.MONTO_PAGO
		    ,D.CORR_AUXILIAR
			
			--Insertar la cuenta por cobrar para liquidar todas las compras provisionadas
			INSERT INTO dbo.COM_PAGO_CONTA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_DETA,CUENTA_CONTABLE,CORR_CENTRO_COSTO,NOMBRE_TRAN,MONTO_CARGO,MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PAGO) CORR_DETA
			,F.CUENTA_CONTABLE
			,F.CORR_CENTRO_COSTO
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END NOMBRE_TRAN
			,CASE WHEN SUM(B.MONTO_PAGO*D.SUMA_RESTA)>0 THEN SUM(B.MONTO_PAGO*D.SUMA_RESTA) ELSE 0 END
			,CASE WHEN SUM(B.MONTO_PAGO*D.SUMA_RESTA)<0 THEN ABS(SUM(B.MONTO_PAGO*D.SUMA_RESTA)) ELSE 0 END
			,NULL
			FROM COM_PAGO A
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO		
			INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR		
			INNER JOIN COM_PROVISION_DETA I ON C.CORR_EMPRESA=I.CORR_EMPRESA AND C.ANIO_PERIODO=I.ANIO_PERIODO_COM AND C.MES_PERIODO=I.MES_PERIODO_COM AND C.CORR_DOCUMENTO=I.CORR_DOCUMENTO_COM		
			INNER JOIN GEN_TIPO_DOCUMENTO D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_TIPO_DOC=D.CORR_TIPO_DOC			
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO		
			GROUP BY A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,F.CUENTA_CONTABLE
			,F.CORR_CENTRO_COSTO
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END

			SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
			FROM COM_PAGO_CONTA A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
					
			--Insertar los impuestos de manera individual por cada documento para las compras NO provisionadas
			INSERT INTO dbo.COM_PAGO_CONTA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_DETA,CUENTA_CONTABLE,CORR_CENTRO_COSTO,NOMBRE_TRAN,MONTO_CARGO,MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PAGO) CORR_DETA
			,G.CUENTA_CONTABLE
			,NULL CORR_CENTRO_COSTO
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE H.NOMBRE_CORTO_TIPO_DOC+' '+LTRIM(RTRIM(CONVERT(VARCHAR,C.NUMERO_DOCUMENTO)))+' '+F.NOMBRE_PROVEEDOR+' '+G.NOMBRE_RUBRO END NOMBRE_TRAN
			,SUM(CASE WHEN D.MONTO_RUBRO>0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END)
			,SUM(CASE WHEN D.MONTO_RUBRO<0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END)
			,NULL
			FROM COM_PAGO A
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
			INNER JOIN COM_DOCUMENTO_TOTAL D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
			INNER JOIN GEN_TIPO_GASTO E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_TIPO_GASTO=E.CORR_TIPO_GASTO
			INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR
			INNER JOIN GEN_RUBRO G ON D.CORR_EMPRESA=G.CORR_EMPRESA AND D.CORR_RUBRO=G.CORR_RUBRO
			INNER JOIN GEN_TIPO_DOCUMENTO H ON C.CORR_EMPRESA=H.CORR_EMPRESA AND C.CORR_TIPO_DOC=H.CORR_TIPO_DOC
			LEFT OUTER JOIN COM_PROVISION_DETA I ON C.CORR_EMPRESA=I.CORR_EMPRESA AND C.ANIO_PERIODO=I.ANIO_PERIODO_COM AND C.MES_PERIODO=I.MES_PERIODO_COM AND C.CORR_DOCUMENTO=I.CORR_DOCUMENTO_COM
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND A.ANIO_PERIODO=@ANIO_PERIODO
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
			AND G.ES_IMPUESTO=1
			AND D.MONTO_RUBRO<>0
			AND I.CORR_DOCUMENTO_COM IS NULL
			GROUP BY A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,G.CUENTA_CONTABLE
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE H.NOMBRE_CORTO_TIPO_DOC+' '+LTRIM(RTRIM(CONVERT(VARCHAR,C.NUMERO_DOCUMENTO)))+' '+F.NOMBRE_PROVEEDOR+' '+G.NOMBRE_RUBRO END
				
			SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
			FROM COM_PAGO_CONTA A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
			
			--Cargo los diferentes gastos de manera acumulada para las compras NO provisionadas
			INSERT INTO dbo.COM_PAGO_CONTA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_DETA,CUENTA_CONTABLE,CORR_CENTRO_COSTO,NOMBRE_TRAN,MONTO_CARGO,MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PAGO) CORR_DETA
			,E.CUENTA_CONTABLE
			,F.CORR_CENTRO_COSTO
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END NOMBRE_TRAN
			,CASE WHEN SUM(D.MONTO_RUBRO*H.SUMA_RESTA)>0 THEN SUM(D.MONTO_RUBRO*H.SUMA_RESTA) ELSE 0 END
			,CASE WHEN SUM(D.MONTO_RUBRO*H.SUMA_RESTA)<0 THEN ABS(SUM(D.MONTO_RUBRO*H.SUMA_RESTA)) ELSE 0 END
			,NULL
			FROM COM_PAGO A
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
			INNER JOIN COM_DOCUMENTO_TOTAL D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
			INNER JOIN GEN_TIPO_GASTO E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_TIPO_GASTO=E.CORR_TIPO_GASTO
			INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR
			INNER JOIN GEN_RUBRO G ON D.CORR_EMPRESA=G.CORR_EMPRESA AND D.CORR_RUBRO=G.CORR_RUBRO
			LEFT OUTER JOIN COM_PROVISION_DETA I ON C.CORR_EMPRESA=I.CORR_EMPRESA AND C.ANIO_PERIODO=I.ANIO_PERIODO_COM AND C.MES_PERIODO=I.MES_PERIODO_COM AND C.CORR_DOCUMENTO=I.CORR_DOCUMENTO_COM
			INNER JOIN GEN_TIPO_DOCUMENTO H ON C.CORR_EMPRESA=H.CORR_EMPRESA AND C.CORR_TIPO_DOC=H.CORR_TIPO_DOC			
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
			AND G.ES_IMPUESTO=0
			AND D.MONTO_RUBRO<>0
			AND G.CLASE_RUBRO IN('GRA','NSU','EXE')
			AND I.CORR_DOCUMENTO_COM IS NULL
			GROUP BY A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PAGO
			,E.CUENTA_CONTABLE
			,F.CORR_CENTRO_COSTO
			,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE A.NOMBRE_PARTIDA END
		END	
		
		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT
		
	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE() 

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO




