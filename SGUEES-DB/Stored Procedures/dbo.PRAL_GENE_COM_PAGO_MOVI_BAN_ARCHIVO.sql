CREATE PROCEDURE [dbo].[PRAL_GENE_COM_PAGO_MOVI_BAN_ARCHIVO]
(
	@CORR_EMPRESA int,	
	@CORR_ARCHIVO int OUTPUT,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output	
)
AS
BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
			
		DECLARE @PAGO_CUENTA TABLE (
			CORR_DETA INT,
			CUENTA_CONTABLE VARCHAR(30),
			CORR_AUXILIAR INT,
			CORR_CENTRO_COSTO INT,
			MONTO_CARGO DECIMAL(18,2),
			MONTO_ABONO DECIMAL(18,2),
			NOMBRE_TRAN VARCHAR(255),
			ESTA_PROC INT
		)
		
		--DECLARE	   @ESTADO_DOCUMENTO VARCHAR(2)		
		--		,  @SUMA_RESTA INT
		--		,  @CORR_TIPO_DOC INT
		--		
		--		,  @TIPO_ACTUALIZA int
		--		,  @CORR_PROVEEDOR int
		--		,  @FECHA_MOVIMIENTO date
		--		,  @REFERENCIA varchar(4000)
		--		,  @TOTAL DECIMAL(14,2)
		--		,  @MONTO_CARGO DECIMAL(14,2)
		--		,  @MONTO_ABONO DECIMAL(14,2)
		--		,  @USUARIO_CREA varchar(30)
		--		,  @FECHA_CREA datetime
		--		,  @ESTACION_CREA varchar(50)
		--		,  @USUARIO_ACTU varchar(30)
		--		,  @FECHA_ACTU datetime
		--		,  @ESTACION_ACTU varchar(50)
		--		,  @ESTADO_MOVIMIENTO varchar(2)		
				
		--DECLARE @CLASE_MOVIMIENTO VARCHAR(3),		
		--@FECHA_SOLICITADO DATE, @NOMBRE_BENEFICIARIO VARCHAR(255),  @CORR_TIPO_CHEQUE INT, @CORR_MOVIMIENTO_CHEQUE INT, @CORR_MOVIMIENTO_DESTINO_CHEQUE INT
		
		DECLARE @CORR_TIPO_MOVIMIENTO INT,  @ANIO_PERIODO_MOVI INT, @MES_PERIODO_MOVI INT, @CORR_DOCUMENTO_MOVI INT, @CORR_CUENTA_BANCO INT,@NOMBRE_PARTIDA VARCHAR(1000),		
		@NUMERO_DOCUMENTO INT,@MONTO_DOCUMENTO DECIMAL(18,2), @FECHA_EMISION DATE, @HOY DATETIME,
		@CORR_DETA INT, @CUENTA_CONTABLE VARCHAR(30), @CORR_CENTRO_COSTO INT, @MONTO_CARGO_DETA DECIMAL(18,2), @MONTO_ABONO_DETA DECIMAL(18,2), @NOMBRE_TRAN VARCHAR(255)
		,@USA_DESCRIPCION_PARTIDA BIT,@PROVISIONAR_POR_DOC BIT,@DESCRIPCION_PARTIDA VARCHAR(500),@CORR_AUXILIAR INT
		
BEGIN TRANSACTION GENE_COM_PAGO_BANCO
        
		SELECT @CORR_TIPO_MOVIMIENTO=A.CORR_TIPO_MOVIMIENTO,@ANIO_PERIODO_MOVI=YEAR(A.FECHA_PAGO),@MES_PERIODO_MOVI=MONTH(A.FECHA_PAGO), @CORR_DOCUMENTO_MOVI=0,
		@CORR_CUENTA_BANCO=A.CORR_CUENTA_BANCO,@NUMERO_DOCUMENTO=C.CORRELATIVO
		,@MONTO_DOCUMENTO=SUM(A.MONTO_PAGO), @FECHA_EMISION=C.FECHA_PAGO,@HOY=GETDATE(),
		@DESCRIPCION_PARTIDA=dbo.StrConcat(DISTINCT A.NOMBRE_PARTIDA)
		FROM COM_PAGO A
		INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR
		INNER JOIN COM_PAGO_ARCHIVO C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_ARCHIVO=C.CORR_ARCHIVO
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 		
		AND A.CORR_ARCHIVO=@CORR_ARCHIVO
		GROUP BY A.CORR_TIPO_MOVIMIENTO,YEAR(A.FECHA_PAGO),MONTH(A.FECHA_PAGO),A.CORR_CUENTA_BANCO, C.CORRELATIVO,		
		C.FECHA_PAGO
		
		SELECT @USA_DESCRIPCION_PARTIDA=ISNULL(A.USA_DESCRIPCION_PARTIDA,0),@PROVISIONAR_POR_DOC=ISNULL(A.PROVISIONAR_POR_DOC,0)
		FROM COM_PARAMETRO A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		
		IF NOT EXISTS ( SELECT 1 FROM BAN_TIPO_MOVI_BANCARIO 
						WHERE CORR_EMPRESA=@CORR_EMPRESA 
						AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO )
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION GENE_COM_PAGO_BANCO
			SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Este pago no puede generar un movimiento bancario porque no existe el tipo de movimiento seleccionado.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END		
		
		
		EXEC PRAL_MTTO_BAN_DOCUMENTO 
		1,
		@CORR_EMPRESA,
		@ANIO_PERIODO_MOVI,
		@MES_PERIODO_MOVI,
		@CORR_TIPO_MOVIMIENTO,
		@CORR_DOCUMENTO_MOVI OUTPUT,
		@CORR_CUENTA_BANCO,
		@NUMERO_DOCUMENTO,
		@FECHA_EMISION,
		@DESCRIPCION_PARTIDA,
		NULL,NULL,NULL,'',
		@MONTO_DOCUMENTO,
		'DI', 0,@SYS_LOGIN_USUARIO, '', '', '', '',@HOY, NULL, NULL,'',@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,NULL, NULL,NULL,NULL, '', NULL, NULL, NULL,NULL, NULL, NULL, NULL,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT,0
		
		
		IF @SYS_NUMERO_ERROR<>0
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION GENE_COM_PAGO_BANCO
			GOTO FINA
		END
		
		--Insertando la cuenta del banco acumulada
		INSERT INTO @PAGO_CUENTA
		(CORR_DETA,CUENTA_CONTABLE,CORR_AUXILIAR,CORR_CENTRO_COSTO,MONTO_CARGO,MONTO_ABONO,NOMBRE_TRAN,ESTA_PROC)
		SELECT 1 CORR_DETA
		,B.CUENTA_CONTABLE
		,B.CORR_AUXILIAR
		,ISNULL(B.CORR_CENTRO_COSTO,0)
		,SUM(B.MONTO_CARGO)
		,SUM(B.MONTO_ABONO)
		,@DESCRIPCION_PARTIDA
		,0
		FROM COM_PAGO A
		INNER JOIN COM_PAGO_CONTA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO		
		INNER JOIN BAN_CUENTA_BANCARIA C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_CUENTA_BANCO=C.CORR_CUENTA_BANCO AND B.CUENTA_CONTABLE=C.CUENTA_CONTABLE
		--LEFT OUTER JOIN CON_CATALOGO_CUENTA_AUXI D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_CUENTA_BANCO = D.CORR_CUENTA_BANCO AND C.CUENTA_CONTABLE = D.CUENTA_CONTABLE
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 		
		AND A.CORR_ARCHIVO=@CORR_ARCHIVO
		GROUP BY B.CUENTA_CONTABLE,B.CORR_AUXILIAR,ISNULL(B.CORR_CENTRO_COSTO,0)
		
		--Insertando el detalle			
		INSERT INTO @PAGO_CUENTA
		(CORR_DETA,CUENTA_CONTABLE,CORR_AUXILIAR,CORR_CENTRO_COSTO,MONTO_CARGO,MONTO_ABONO,NOMBRE_TRAN,ESTA_PROC)
		SELECT 1+ROW_NUMBER() OVER(ORDER BY B.CORR_DETA) CORR_DETA,
		B.CUENTA_CONTABLE,
		0,
		ISNULL(B.CORR_CENTRO_COSTO,0),
		B.MONTO_CARGO,
		B.MONTO_ABONO,
		B.NOMBRE_TRAN,
		0
		FROM COM_PAGO A
		INNER JOIN COM_PAGO_CONTA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO
		LEFT OUTER JOIN BAN_CUENTA_BANCARIA C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_CUENTA_BANCO=C.CORR_CUENTA_BANCO
			AND B.CUENTA_CONTABLE=C.CUENTA_CONTABLE
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 		
		AND A.CORR_ARCHIVO=@CORR_ARCHIVO
		AND C.CUENTA_CONTABLE IS NULL
		
		WHILE EXISTS(SELECT 1 FROM @PAGO_CUENTA)
		BEGIN
			SELECT TOP 1 @CORR_DETA=CORR_DETA,
			@CUENTA_CONTABLE=CUENTA_CONTABLE,
			@CORR_CENTRO_COSTO=CORR_CENTRO_COSTO,
			@MONTO_ABONO_DETA=MONTO_ABONO,
			@MONTO_CARGO_DETA=MONTO_CARGO,
			@NOMBRE_TRAN=NOMBRE_TRAN,
			@CORR_AUXILIAR=CORR_AUXILIAR
			FROM @PAGO_CUENTA
			
			EXEC PRAL_MTTO_BAN_DOCUMENTO_DETA 
			1,
		@CORR_EMPRESA,
			@ANIO_PERIODO_MOVI,
			@MES_PERIODO_MOVI,
			@CORR_TIPO_MOVIMIENTO,
			@CORR_DOCUMENTO_MOVI,
			0,
			@CUENTA_CONTABLE,
			@CORR_CENTRO_COSTO,
			@NOMBRE_TRAN,
			@MONTO_CARGO_DETA,
			@MONTO_ABONO_DETA,
			@CORR_AUXILIAR,
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR OUTPUT

		
			IF @SYS_NUMERO_ERROR<>0
			BEGIN
				IF @@TRANCOUNT>0
					ROLLBACK TRANSACTION GENE_COM_PAGO_BANCO
				GOTO FINA
			END
		
			DELETE FROM @PAGO_CUENTA
			WHERE CORR_DETA=@CORR_DETA			
		END 
		
		EXEC PRAL_MTTO_BAN_DOCUMENTO_APLICAR 
		@CORR_EMPRESA,
		@ANIO_PERIODO_MOVI,
		@MES_PERIODO_MOVI,
		@CORR_TIPO_MOVIMIENTO,
		@CORR_DOCUMENTO_MOVI OUTPUT,
		@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT
		
		IF @SYS_NUMERO_ERROR<>0
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION GENE_COM_PAGO_BANCO
			GOTO FINA
		END
		
		UPDATE COM_PAGO SET		
		ANIO_PERIODO_CHEQUE=@ANIO_PERIODO_MOVI,
		MES_PERIODO_CHEQUE=@MES_PERIODO_MOVI,
		CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO,
		CORR_DOCUMENTO_CHEQUE=@CORR_DOCUMENTO_MOVI
		WHERE CORR_EMPRESA=@CORR_EMPRESA 		
		AND CORR_ARCHIVO=@CORR_ARCHIVO
				
		IF @@TRANCOUNT>0
			COMMIT TRANSACTION GENE_COM_PAGO_BANCO
		
	END TRY
	BEGIN CATCH
	  IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION GENE_COM_PAGO_BANCO
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO



