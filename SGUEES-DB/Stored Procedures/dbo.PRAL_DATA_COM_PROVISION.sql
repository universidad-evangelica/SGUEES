CREATE PROCEDURE [dbo].[PRAL_DATA_COM_PROVISION]
(
	@TIPO_CONSULTA int,
	@CORR_EMPRESA int=NULL,
	@ANIO_PERIODO int=NULL,
	@MES_PERIODO int=NULL,
	@CORR_PROVISION int=NULL,
	@FECHA_INICIAL DATE=NULL,
	@FECHA_FINAL DATE=NULL,
	@OPCION_CONSULTA int=0
)
AS
BEGIN
	SET NOCOUNT ON

	IF @TIPO_CONSULTA=1 --Todos los campos, todos los registrosl (Mtto)
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT * FROM V_COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND (FECHA_PROVISION>=@FECHA_INICIAL OR @FECHA_INICIAL IS NULL)
			AND (FECHA_PROVISION<=@FECHA_FINAL OR @FECHA_FINAL IS NULL)
			ORDER BY ANIO_PERIODO DESC, MES_PERIODO DESC, FECHA_PROVISION DESC
		END ELSE
		IF @OPCION_CONSULTA=1 --Des-Aplicar Provisiones
		BEGIN
			SELECT * FROM V_COM_PROVISION_SELECCION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND FECHA_PROVISION>=@FECHA_INICIAL
			AND FECHA_PROVISION<=@FECHA_FINAL
			AND ESTADO_PROVISION='AP'
			ORDER BY ANIO_PERIODO DESC, MES_PERIODO DESC, FECHA_PROVISION DESC
		END
		
	END ELSE
	IF @TIPO_CONSULTA=2 --Algunos campos, todos los registrosl (Combos)
	BEGIN
		SELECT * FROM V_COM_PROVISION
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
	END ELSE
	IF @TIPO_CONSULTA=3 --Todos los campos, un solo registro
	BEGIN
		SELECT * FROM V_COM_PROVISION
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
	END ELSE
	IF @TIPO_CONSULTA=4 --Un campo, un solo registro
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT CORR_EMPRESA FROM V_COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
		END
		IF @OPCION_CONSULTA=1
		BEGIN
			SELECT MONTO_PAGO FROM V_COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
		END
	END

END
GO



