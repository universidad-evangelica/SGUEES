-- Procedimiento: dbo.PRAL_IMPR_SC_MOVIMIENTO_PERSONAL
-- Qué hace: devuelve TODAS las columnas de la fila de SC_MOVIMIENTO_PERSONAL.
--           El XtraReport enlaza las que use; el resto se asigna en el diseñador.
-- Parámetros: @CORR_EMPRESA, @CORR_MOVIMIENTO_PERSONAL
-- Consumo: SGUEES-RPT Layouts/SelectionHiring/SelectionHiring.aspx
--   ?fuente=sc-movimiento-personal&report=rptMovimientoPersonal&...
-- =============================================================================
CREATE OR ALTER PROCEDURE [dbo].[PRAL_IMPR_SC_MOVIMIENTO_PERSONAL]
(
	@CORR_EMPRESA INT,
	@CORR_MOVIMIENTO_PERSONAL INT
)
AS
BEGIN
	SET NOCOUNT ON;

	SELECT
		M.*,
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(JI.NOMBRE_FIRMANTE)), N''), ISNULL(JI.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_JEFE_INMEDIATO,
		JI.FECHA_ACCION AS FECHA_JEFE_INMEDIATO,
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(JU.NOMBRE_FIRMANTE)), N''), ISNULL(JU.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_DECANO_GERENTE,
		JU.FECHA_ACCION AS FECHA_DECANO_GERENTE,
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(GG.NOMBRE_FIRMANTE)), N''), ISNULL(GG.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_VRA,
		GG.FECHA_ACCION AS FECHA_VRA
	FROM dbo.SC_MOVIMIENTO_PERSONAL AS M
	LEFT JOIN dbo.SC_MOVIMIENTO_REQUISICION AS MR
		ON MR.CORR_EMPRESA = M.CORR_EMPRESA
	   AND MR.CORR_MOVIMIENTO_PERSONAL = M.CORR_MOVIMIENTO_PERSONAL
	OUTER APPLY (
		SELECT TOP (1) B.LOGIN_SISTEMA, B.FECHA_ACCION, PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = M.CORR_EMPRESA AND B.CORR_TIPO_DOCUMENTO = 101
		  AND B.CORR_DOCUMENTO = MR.CORR_REQUISICION_PERSONAL AND B.ESTADO_DESTINO = N'Aprobado JI'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS JI
	OUTER APPLY (
		SELECT TOP (1) B.LOGIN_SISTEMA, B.FECHA_ACCION, PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = M.CORR_EMPRESA AND B.CORR_TIPO_DOCUMENTO = 101
		  AND B.CORR_DOCUMENTO = MR.CORR_REQUISICION_PERSONAL AND B.ESTADO_DESTINO = N'Aprobado JU'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS JU
	OUTER APPLY (
		SELECT TOP (1) B.LOGIN_SISTEMA, B.FECHA_ACCION, PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = M.CORR_EMPRESA AND B.CORR_TIPO_DOCUMENTO = 101
		  AND B.CORR_DOCUMENTO = MR.CORR_REQUISICION_PERSONAL AND B.ESTADO_DESTINO = N'Aprobado GG'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS GG
	WHERE M.CORR_EMPRESA = @CORR_EMPRESA
	  AND M.CORR_MOVIMIENTO_PERSONAL = @CORR_MOVIMIENTO_PERSONAL;
END
GO
