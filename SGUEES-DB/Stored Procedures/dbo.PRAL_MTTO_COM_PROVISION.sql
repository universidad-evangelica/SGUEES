CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PROVISION]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int OUTPUT,
	@FECHA_PROVISION date = NULL,
	@CORR_PROVEEDOR int = 0,
	@NOMBRE_PARTIDA varchar(255) = '',
	@MONTO_PAGO decimal(18,2) = 0,
	@ANIO_PERIODO_PARTIDA int = NULL,
	@MES_PERIODO_PARTIDA int = NULL,
	@CORR_CLASE_PARTIDA int = NULL,
	@CORR_PARTIDA int = NULL,
	@ESTADO_PROVISION VARCHAR(2) = '',
	@NOMBRE_BENEFICIARIO VARCHAR(255)='',
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
BEGIN
	
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2) --VALIDACION PREVIA SI SE VA A ADICIONAR O ACTIALIZAR
		BEGIN
			IF NOT (@MES_PERIODO BETWEEN 1 AND 12)
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No ha seleccionado correctamente el mes.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
			IF NOT EXISTS ( SELECT 1 FROM GEN_PROVEEDOR
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND CORR_PROVEEDOR=@CORR_PROVEEDOR ) --SE VERIFICA QUE EXISTA EL PROVEEDOR SELECCIONADO
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No existe el Proveedor seleccionado.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
		END
		IF @TIPO_ACTUALIZA=1 --Adicionar
		BEGIN
			SELECT @CORR_PROVISION=ISNULL(MAX(CORR_PROVISION),0)+1, @ESTADO_PROVISION='DI'
			FROM COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO

			SELECT  @ANIO_PERIODO_PARTIDA=NULL, @MES_PERIODO_PARTIDA=NULL, @CORR_PARTIDA=NULL, @CORR_CLASE_PARTIDA=NULL
			
			INSERT INTO COM_PROVISION
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PROVISION,FECHA_PROVISION,CORR_PROVEEDOR,NOMBRE_PARTIDA,MONTO_PAGO,ANIO_PERIODO_PARTIDA,MES_PERIODO_PARTIDA,CORR_CLASE_PARTIDA,CORR_PARTIDA,ESTADO_PROVISION,NOMBRE_BENEFICIARIO)
			VALUES
			(@CORR_EMPRESA,@ANIO_PERIODO,@MES_PERIODO,@CORR_PROVISION,@FECHA_PROVISION,@CORR_PROVEEDOR,@NOMBRE_PARTIDA,@MONTO_PAGO,@ANIO_PERIODO_PARTIDA,@MES_PERIODO_PARTIDA,@CORR_CLASE_PARTIDA,@CORR_PARTIDA,@ESTADO_PROVISION,@NOMBRE_BENEFICIARIO)
		END ELSE
		IF @TIPO_ACTUALIZA=2 --Actualizar
		BEGIN
			UPDATE COM_PROVISION SET
			FECHA_PROVISION=@FECHA_PROVISION,
			CORR_PROVEEDOR=@CORR_PROVEEDOR,
			NOMBRE_PARTIDA=@NOMBRE_PARTIDA,
			MONTO_PAGO=@MONTO_PAGO,
			ESTADO_PROVISION=@ESTADO_PROVISION,
			NOMBRE_BENEFICIARIO=@NOMBRE_BENEFICIARIO
			--ANIO_PERIODO_PARTIDA=@ANIO_PERIODO_PARTIDA,
			--MES_PERIODO_PARTIDA=@MES_PERIODO_PARTIDA,
			--CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA,
			--CORR_PARTIDA=@CORR_PARTIDA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
		END ELSE
		IF @TIPO_ACTUALIZA=3 --Eliminar
		BEGIN
			UPDATE B SET B.ANIO_PERIODO_PRO=NULL
			,B.MES_PERIODO_PRO=NULL
			,B.CORR_PROVISION=NULL
			FROM COM_PROVISION A
			INNER JOIN COM_QUEDAN_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO_PRO AND A.MES_PERIODO=B.MES_PERIODO_PRO AND A.CORR_PROVISION=B.CORR_PROVISION
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND A.ANIO_PERIODO=@ANIO_PERIODO
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PROVISION=@CORR_PROVISION
			
			DELETE FROM COM_PROVISION_CONTA 
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			
			DELETE FROM COM_PROVISION_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			
			DELETE FROM COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION

		END
		
		IF @TIPO_ACTUALIZA=4 --Eliminar TODO su detalle
		BEGIN
			DELETE FROM COM_PROVISION_CONTA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION 
			
			DELETE FROM COM_PROVISION_DETA 
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION 
		END
		
		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT
	
	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO



