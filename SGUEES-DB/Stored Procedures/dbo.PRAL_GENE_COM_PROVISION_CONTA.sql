CREATE PROCEDURE [dbo].[PRAL_GENE_COM_PROVISION_CONTA]
(	
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int OUTPUT,	
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
	DECLARE @USA_DESCRIPCION_PARTIDA BIT,@PROVISIONAR_POR_DOC BIT

	--Para insertar la contabilidad documento por documento, similar a Liq. Cheque o Caja Chica
	DECLARE @CAJA_DETA TABLE
	(CORR_DETA INT) 
BEGIN
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
		
		INSERT INTO @CAJA_DETA (CORR_DETA)
		SELECT CORR_DETA 
		FROM COM_PROVISION_DETA
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION

		DECLARE @CORR_DETA INT, @CORR_DETA_COM INT
					
		--Eliminando el detalle contable anterior
		DELETE FROM COM_PROVISION_CONTA
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
		
		SELECT @USA_DESCRIPCION_PARTIDA=ISNULL(A.USA_DESCRIPCION_PARTIDA,0)
		,@PROVISIONAR_POR_DOC=ISNULL(A.PROVISIONAR_POR_DOC,0)
		FROM COM_PARAMETRO A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		
		SELECT @CORR_DETA=1
		
		--Abono el total de la provisión a la cuenta del Proveedor
		INSERT INTO COM_PROVISION_CONTA
		(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_PROVISION, CORR_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO,CORR_AUXILIAR)	
SELECT A.CORR_EMPRESA
		,A.ANIO_PERIODO
		,A.MES_PERIODO
		,A.CORR_PROVISION
		,@CORR_DETA CORR_DETA
		,B.CUENTA_CONTABLE
		,NULL CORR_CENTRO_COSTO
		,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN B.NOMBRE_PROVEEDOR+' '+ISNULL(E.DESCRIPCION_PARTIDA,'') ELSE B.NOMBRE_PROVEEDOR END END NOMBRE_TRAN
		,CASE WHEN A.MONTO_PAGO<0 THEN ABS(A.MONTO_PAGO) ELSE 0 END
		,CASE WHEN A.MONTO_PAGO>0 THEN ABS(A.MONTO_PAGO) ELSE 0 END
		,NULL
		FROM COM_PROVISION A
		INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR		
		INNER JOIN V_COM_PROVISION_DESCRIPCION E ON A.CORR_EMPRESA=E.CORR_EMPRESA AND A.ANIO_PERIODO=E.ANIO_PERIODO AND A.MES_PERIODO=E.MES_PERIODO AND A.CORR_PROVISION=E.CORR_PROVISION
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PROVISION=@CORR_PROVISION
		GROUP BY A.CORR_EMPRESA
		,A.ANIO_PERIODO
		,A.MES_PERIODO
		,A.CORR_PROVISION
		,B.CUENTA_CONTABLE
		,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN B.NOMBRE_PROVEEDOR+' '+ISNULL(E.DESCRIPCION_PARTIDA,'') ELSE B.NOMBRE_PROVEEDOR END END
		,A.MONTO_PAGO

		WHILE EXISTS(SELECT 1 FROM @CAJA_DETA)
		BEGIN
			SELECT TOP 1 @CORR_DETA_COM=CORR_DETA
			FROM @CAJA_DETA
			ORDER BY CORR_DETA

			SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
			FROM COM_PROVISION_CONTA A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PROVISION=@CORR_PROVISION
			
			--Insertar los impuestos de manera individual por cada documento
			INSERT INTO COM_PROVISION_CONTA
			(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_PROVISION, CORR_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PROVISION
			,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PROVISION) CORR_DETA
			,G.CUENTA_CONTABLE
			,NULL CORR_CENTRO_COSTO
			,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE H.NOMBRE_CORTO_TIPO_DOC+' '+LTRIM(RTRIM(CONVERT(VARCHAR,C.NUMERO_DOCUMENTO)))+' '+F.NOMBRE_PROVEEDOR+' '+G.NOMBRE_RUBRO END END NOMBRE_TRAN
			,SUM(CASE WHEN D.MONTO_RUBRO*H.SUMA_RESTA>0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END)
			,SUM(CASE WHEN D.MONTO_RUBRO*H.SUMA_RESTA<0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END)
			,NULL
			FROM COM_PROVISION A
			INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
			INNER JOIN COM_DOCUMENTO_TOTAL D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
			INNER JOIN GEN_TIPO_GASTO E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_TIPO_GASTO=E.CORR_TIPO_GASTO
			INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR
			INNER JOIN GEN_RUBRO G ON D.CORR_EMPRESA=G.CORR_EMPRESA AND D.CORR_RUBRO=G.CORR_RUBRO
			INNER JOIN GEN_TIPO_DOCUMENTO H ON C.CORR_EMPRESA=H.CORR_EMPRESA AND C.CORR_TIPO_DOC=H.CORR_TIPO_DOC
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PROVISION=@CORR_PROVISION
			AND G.ES_IMPUESTO=1
			AND G.CLASE_RUBRO NOT IN('RET')
			AND D.MONTO_RUBRO<>0
			AND B.CORR_DETA=@CORR_DETA_COM
			GROUP BY A.CORR_EMPRESA
			,A.ANIO_PERIODO
			,A.MES_PERIODO
			,A.CORR_PROVISION
			,G.CUENTA_CONTABLE
			,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE H.NOMBRE_CORTO_TIPO_DOC+' '+LTRIM(RTRIM(CONVERT(VARCHAR,C.NUMERO_DOCUMENTO)))+' '+F.NOMBRE_PROVEEDOR+' '+G.NOMBRE_RUBRO END END

			SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
			FROM COM_PROVISION_CONTA A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PROVISION=@CORR_PROVISION
		
			----------------------------------------------------------------------------------------------------------------------
			-- Este codigo sera movido fuera del bloque WHILE para que no sea individual por documento, sino que consolidado
			----------------------------------------------------------------------------------------------------------------------
			----Insertar los impuestos de manera individual por cada documento
			--INSERT INTO COM_PROVISION_CONTA
			--(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_PROVISION, CORR_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO)
			--SELECT A.CORR_SUSCRIPCION
			--,A.CORR_CONFI_PAIS
			--,A.CORR_EMPRESA
			--,A.ANIO_PERIODO
			--,A.MES_PERIODO
			--,A.CORR_PROVISION
			--,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PROVISION) CORR_DETA
			--,G.CUENTA_CONTABLE
			--,NULL CORR_CENTRO_COSTO
			--,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE 'C.R. '+LTRIM(RTRIM(CONVERT(VARCHAR,ISNULL(J.NUMERO_COMPRO_RETE,''))))+' '+F.NOMBRE_PROVEEDOR END NOMBRE_TRAN
			--,SUM(CASE WHEN D.MONTO_RUBRO*H.SUMA_RESTA>0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END) MONTO_CARGO
			--,SUM(CASE WHEN D.MONTO_RUBRO*H.SUMA_RESTA<0 THEN ABS(D.MONTO_RUBRO) ELSE 0 END) MONTO_ABONO
			--FROM COM_PROVISION A
			--INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
			--INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
			--INNER JOIN COM_DOCUMENTO_TOTAL D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
			--INNER JOIN GEN_TIPO_GASTO E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_TIPO_GASTO=E.CORR_TIPO_GASTO
			--INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR
			--INNER JOIN GEN_RUBRO G ON D.CORR_EMPRESA=G.CORR_EMPRESA AND D.CORR_RUBRO=G.CORR_RUBRO
			--INNER JOIN GEN_TIPO_DOCUMENTO H ON C.CORR_EMPRESA=H.CORR_EMPRESA AND C.CORR_TIPO_DOC=H.CORR_TIPO_DOC
			--LEFT OUTER JOIN COM_QUEDAN_DETA I ON C.CORR_EMPRESA=I.CORR_EMPRESA AND C.ANIO_PERIODO=I.ANIO_PERIODO_COM AND C.MES_PERIODO=I.MES_PERIODO_COM AND C.CORR_DOCUMENTO=I.CORR_DOCUMENTO
			--LEFT OUTER JOIN COM_QUEDAN J ON I.CORR_EMPRESA=J.CORR_EMPRESA AND I.ANIO_PERIODO=J.ANIO_PERIODO AND I.MES_PERIODO=J.MES_PERIODO AND I.CORR_QUEDAN=J.CORR_QUEDAN
			--WHERE A.CORR_SUSCRIPCION=@CORR_SUSCRIPCION
			--AND A.CORR_CONFI_PAIS=@CORR_CONFI_PAIS 
			--AND A.CORR_EMPRESA=@CORR_EMPRESA 
			--AND A.ANIO_PERIODO=@ANIO_PERIODO 
			--AND A.MES_PERIODO=@MES_PERIODO
			--AND A.CORR_PROVISION=@CORR_PROVISION
			--AND G.ES_IMPUESTO=1
			--AND G.CLASE_RUBRO IN('RET')
			--AND D.MONTO_RUBRO<>0
			--AND B.CORR_DETA=@CORR_DETA_COM
			--GROUP BY A.CORR_SUSCRIPCION
			--,A.CORR_CONFI_PAIS
			--,A.CORR_EMPRESA
			--,A.ANIO_PERIODO
			--,A.MES_PERIODO
			--,A.CORR_PROVISION
			--,G.CUENTA_CONTABLE
			--,CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE 'C.R. '+LTRIM(RTRIM(CONVERT(VARCHAR,ISNULL(J.NUMERO_COMPRO_RETE,''))))+' '+F.NOMBRE_PROVEEDOR END
			------------------------------------------------------------------------------------------------------------------------------------------------------
			-- Fin de codigo movido
			------------------------------------------------------------------------------------------------------------------------------------------------------


			IF NOT EXISTS (  --Si no existe distribucion por centro de costo
				SELECT 1 FROM COM_PROVISION A
				INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
				INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
				INNER JOIN COM_DOCUMENTO_CENTRO_COSTO D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
				INNER JOIN CON_CENTRO_COSTO E ON D.CORR_EMPRESA=E.CORR_EMPRESA AND D.CORR_CENTRO_COSTO=E.CORR_CENTRO_COSTO
				WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
				AND A.ANIO_PERIODO=@ANIO_PERIODO 
				AND A.MES_PERIODO=@MES_PERIODO
				AND A.CORR_PROVISION=@CORR_PROVISION
				AND B.CORR_DETA=@CORR_DETA_COM
			) AND NOT EXISTS ( --Y tampoco tiene un detalle de itemes de inventario
				SELECT 1 FROM COM_PROVISION A
				INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
				INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
				INNER JOIN COM_DOCUMENTO_DETALLE_ITEM D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
				INNER JOIN INV_ITEM E ON D.CORR_EMPRESA=E.CORR_EMPRESA AND D.CORR_TIPO_ITEM=E.CORR_TIPO_ITEM AND D.CORR_ITEM=E.CORR_ITEM
				WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
				AND A.ANIO_PERIODO=@ANIO_PERIODO 
				AND A.MES_PERIODO=@MES_PERIODO
				AND A.CORR_PROVISION=@CORR_PROVISION
				AND CORR_DETA=@CORR_DETA_COM
			)
			BEGIN
				SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
				FROM COM_PROVISION_CONTA A
				WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
				AND A.ANIO_PERIODO=@ANIO_PERIODO 
				AND A.MES_PERIODO=@MES_PERIODO
				AND A.CORR_PROVISION=@CORR_PROVISION

				--Cargo los diferentes gastos de manera acumulada, como tradicionalmente se ha hecho siempre
				INSERT INTO COM_PROVISION_CONTA
				(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_PROVISION, CORR_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
				,A.ANIO_PERIODO
				,A.MES_PERIODO
				,A.CORR_PROVISION
				,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PROVISION) CORR_DETA
				,E.CUENTA_CONTABLE
				,F.CORR_CENTRO_COSTO
				,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE F.NOMBRE_PROVEEDOR+' '+E.NOMBRE_TIPO_GASTO END END NOMBRE_TRAN
				,CASE WHEN SUM(D.MONTO_RUBRO*H.SUMA_RESTA)>0 THEN SUM((D.MONTO_RUBRO-ISNULL(J.MONTO_RUBRO_INCLUIDO,0))*H.SUMA_RESTA) ELSE 0 END
				,CASE WHEN SUM(D.MONTO_RUBRO*H.SUMA_RESTA)<0 THEN ABS(SUM((D.MONTO_RUBRO-ISNULL(J.MONTO_RUBRO_INCLUIDO,0))*H.SUMA_RESTA)) ELSE 0 END
				,NULL
				FROM COM_PROVISION A
				INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
				INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
				INNER JOIN COM_DOCUMENTO_TOTAL D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO AND C.MES_PERIODO=D.MES_PERIODO AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO
				INNER JOIN GEN_TIPO_GASTO E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_TIPO_GASTO=E.CORR_TIPO_GASTO
				INNER JOIN GEN_PROVEEDOR F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_PROVEEDOR=F.CORR_PROVEEDOR
				INNER JOIN GEN_RUBRO G ON D.CORR_EMPRESA=G.CORR_EMPRESA AND D.CORR_RUBRO=G.CORR_RUBRO
				INNER JOIN GEN_TIPO_DOCUMENTO H ON C.CORR_EMPRESA=H.CORR_EMPRESA AND C.CORR_TIPO_DOC=H.CORR_TIPO_DOC
				INNER JOIN COM_PARAMETRO I ON A.CORR_EMPRESA=I.CORR_EMPRESA
				LEFT OUTER JOIN V_COM_DOCUMENTO_IMPUESTO_SUM J ON C.CORR_EMPRESA=J.CORR_EMPRESA AND C.ANIO_PERIODO = J.ANIO_PERIODO AND C.MES_PERIODO = J.MES_PERIODO AND C.CORR_DOCUMENTO = J.CORR_DOCUMENTO
				WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
				AND A.ANIO_PERIODO=@ANIO_PERIODO 
				AND A.MES_PERIODO=@MES_PERIODO
				AND A.CORR_PROVISION=@CORR_PROVISION
				AND G.ES_IMPUESTO=0
				AND D.MONTO_RUBRO<>0
				AND G.CLASE_RUBRO IN('GRA','NSU','EXE')
				AND B.CORR_DETA=@CORR_DETA_COM
				GROUP BY A.CORR_EMPRESA
				,A.ANIO_PERIODO
				,A.MES_PERIODO
				,A.CORR_PROVISION
				,E.CUENTA_CONTABLE
				,F.CORR_CENTRO_COSTO
				,CASE WHEN @PROVISIONAR_POR_DOC = 1 THEN A.NOMBRE_PARTIDA ELSE CASE WHEN ISNULL(@USA_DESCRIPCION_PARTIDA,0)=1 THEN F.NOMBRE_PROVEEDOR+' '+ISNULL(C.DESCRIPCION_PARTIDA,'') ELSE F.NOMBRE_PROVEEDOR+' '+E.NOMBRE_TIPO_GASTO END END 
				,D.MONTO_RUBRO
				,H.SUMA_RESTA

			END ELSE
			BEGIN
				SELECT @CORR_DETA=ISNULL(MAX(A.CORR_DETA),0)
				FROM COM_PROVISION_CONTA A
				WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
				AND A.ANIO_PERIODO=@ANIO_PERIODO 
				AND A.MES_PERIODO=@MES_PERIODO
				AND A.CORR_PROVISION=@CORR_PROVISION

				--Cargo los diferentes gastos de manera distribuida segun los centros de costo
				INSERT INTO COM_PROVISION_CONTA
				(CORR_EMPRESA, ANIO_PERIODO, MES_PERIODO, CORR_PROVISION, CORR_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO,CORR_AUXILIAR)
SELECT A.CORR_EMPRESA
				,A.ANIO_PERIODO
				,A.MES_PERIODO
				,A.CORR_PROVISION
				,@CORR_DETA+ROW_NUMBER() OVER(ORDER BY A.CORR_EMPRESA,A.ANIO_PERIODO,A.MES_PERIODO,A.CORR_PROVISION) CORR_DETA
				,ISNULL(G.CUENTA_CONTABLE, E.CUENTA_CONTABLE)
