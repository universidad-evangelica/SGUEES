		IF @DUI_FORMATEADO IS NOT NULL
		BEGIN
			IF EXISTS (
				SELECT 1 FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 7
			)
			BEGIN
				UPDATE dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
				SET VALOR_DOCUMENTO = @DUI_FORMATEADO,
				    USUARIO_ACTU = @SYS_LOGIN_USUARIO,
				    ESTACION_ACTU = @SYS_ESTACION,
				    FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 7;
			END
			ELSE
			BEGIN
				INSERT INTO dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
				(CORR_EMPRESA, CORR_PERSONA, CORR_TIPO_DOCUMENTO_IDENTIDAD, VALOR_DOCUMENTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
				VALUES (@CORR_EMPRESA, @CORR_PERSONA, 7, @DUI_FORMATEADO, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
			END;
		END;

		IF @PASAPORTE_CANDIDATO IS NOT NULL AND NOT EXISTS (
			SELECT 1 FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 9
		)
		BEGIN
			INSERT INTO dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
			(CORR_EMPRESA, CORR_PERSONA, CORR_TIPO_DOCUMENTO_IDENTIDAD, VALOR_DOCUMENTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, 9, @PASAPORTE_CANDIDATO, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		IF @LICENCIA_CANDIDATO IS NOT NULL AND NOT EXISTS (
			SELECT 1 FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 10
		)
		BEGIN
			INSERT INTO dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
			(CORR_EMPRESA, CORR_PERSONA, CORR_TIPO_DOCUMENTO_IDENTIDAD, VALOR_DOCUMENTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, 10, @LICENCIA_CANDIDATO, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		-- =====================================================================
		-- 6. MIGRAR CONTACTOS (CORREO, CELULAR, TELÉFONO)
		-- =====================================================================
		DECLARE @MAX_CONTACTO INT = ISNULL((SELECT MAX(CORR_CONTACTO) FROM dbo.GEN_PERSONA_CONTACTO WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		IF @CELULAR_CANDIDATO IS NOT NULL
		BEGIN
			SET @MAX_CONTACTO = @MAX_CONTACTO + 1;
			INSERT INTO dbo.GEN_PERSONA_CONTACTO
			(CORR_EMPRESA, CORR_PERSONA, CORR_CONTACTO, VALOR_CONTACTO, ACTIVO_CONTACTO, CORR_TIPO_CONTACTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, @MAX_CONTACTO, @CELULAR_CANDIDATO, 1, 1, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		IF @TELEFONO_CANDIDATO IS NOT NULL AND @TELEFONO_CANDIDATO <> ISNULL(@CELULAR_CANDIDATO, '')
		BEGIN
			SET @MAX_CONTACTO = @MAX_CONTACTO + 1;
			INSERT INTO dbo.GEN_PERSONA_CONTACTO
			(CORR_EMPRESA, CORR_PERSONA, CORR_CONTACTO, VALOR_CONTACTO, ACTIVO_CONTACTO, CORR_TIPO_CONTACTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, @MAX_CONTACTO, @TELEFONO_CANDIDATO, 1, 1, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		IF @CORREO_CANDIDATO IS NOT NULL
		BEGIN
			SET @MAX_CONTACTO = @MAX_CONTACTO + 1;
			INSERT INTO dbo.GEN_PERSONA_CONTACTO
			(CORR_EMPRESA, CORR_PERSONA, CORR_CONTACTO, VALOR_CONTACTO, ACTIVO_CONTACTO, CORR_TIPO_CONTACTO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, @MAX_CONTACTO, @CORREO_CANDIDATO, 1, 3, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		-- =====================================================================
		-- 7. MIGRAR DOMICILIO
		-- =====================================================================
		IF @DIRECCION_CANDIDATO IS NOT NULL
		BEGIN
			DECLARE @MAX_DOMICILIO INT = ISNULL((SELECT MAX(CORR_DOMICILIO) FROM dbo.GEN_PERSONA_DOMICILIO WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0) + 1;

			INSERT INTO dbo.GEN_PERSONA_DOMICILIO
			(CORR_EMPRESA, CORR_PERSONA, CORR_DOMICILIO, DIRECCION, ACTIVO_DOMICILIO, USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (@CORR_EMPRESA, @CORR_PERSONA, @MAX_DOMICILIO, LEFT(@DIRECCION_CANDIDATO, 255), 1, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);
		END;

		-- =====================================================================
		-- 8. MIGRAR CONTACTO DE EMERGENCIA
		-- =====================================================================
		IF @EMERGENCIA_NOMBRE IS NOT NULL
		BEGIN
			DECLARE @MAX_PARENTESCO_CONT INT = ISNULL((SELECT MAX(CORR_PARENTESCO_CONTACTO) FROM dbo.GEN_PERSONA_PARENTESCO_CONTACTO WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0) + 1;

			INSERT INTO dbo.GEN_PERSONA_PARENTESCO_CONTACTO
			(
				CORR_EMPRESA, CORR_PERSONA, CORR_PARENTESCO_CONTACTO,
				NOMBRE_COMPLETO, VALOR_CONTACTO, PARENTESCO_CONTACTO_EMERGENCIA, ACTIVO_PARENTESCO_CONTACTO,
				USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_PERSONA, @MAX_PARENTESCO_CONT,
				LEFT(@EMERGENCIA_NOMBRE, 100), @EMERGENCIA_TELEFONO, 1, 1,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
			);
		END;

		-- =====================================================================
		-- 9. MIGRAR FORMACIÓN ACADÉMICA (Omitiendo PERIODO_* calculadas)
		-- =====================================================================
		DECLARE @MAX_FORMACION INT = ISNULL((SELECT MAX(CORR_FORMACION_ACADEMICA) FROM dbo.GEN_PERSONA_FORMACION_ACADEMICA WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_FORMACION_ACADEMICA
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_FORMACION_ACADEMICA,
			TITULO, CENTRO_EDUCATIVO, NIVEL, DESDE, HASTA,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_FORMACION + ROW_NUMBER() OVER (ORDER BY E.CORR_ESTUDIO),
			LEFT(ISNULL(E.TITULO, 'SIN TITULO'), 100),
			LEFT(E.INSTITUCION, 150),
			LEFT(E.NIVEL, 100),
			E.DESDE,
			E.HASTA,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_ESTUDIO AS E
		WHERE E.CORR_EMPRESA = @CORR_EMPRESA
		  AND E.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		-- =====================================================================
		-- 10. MIGRAR EXPERIENCIA LABORAL (Omitiendo PERIODO_* calculadas)
		-- =====================================================================
		DECLARE @MAX_EXP INT = ISNULL((SELECT MAX(CORR_EXPERIENCIA_LABORAL) FROM dbo.GEN_PERSONA_EXPERIENCIA_LABORAL WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_EXPERIENCIA_LABORAL
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_EXPERIENCIA_LABORAL,
			LUGAR_TRABAJO, CARGO_DESEMPENADO, TELEFONO, JEFE_INMEDIATO,
			SALARIO_INICIAL, SALARIO_FINAL, FECHA_INICIO, FECHA_FIN, MOTIVO_SALIDA,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_EXP + ROW_NUMBER() OVER (ORDER BY X.CORR_EXPERIENCIA_LABORAL),
			LEFT(X.EMPRESA, 150),
			LEFT(X.CARGO, 150),
			LEFT(X.TELEFONO, 25),
			LEFT(X.JEFE_INMEDIATO, 100),
			X.SALARIO_INICIAL,
			X.SALARIO_FINAL,
			X.FECHA_INICIO,
			X.FECHA_FIN,
			LEFT(X.MOTIVO_SALIDA, 500),
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_EXPERIENCIA_LABORAL AS X
		WHERE X.CORR_EMPRESA = @CORR_EMPRESA
		  AND X.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		-- =====================================================================
		-- 11. MIGRAR COMPETENCIAS / HABILIDADES (Homologando CHECK NIVEL_DOMINIO)
		-- =====================================================================
		DECLARE @MAX_COMP INT = ISNULL((SELECT MAX(CORR_COMPETENCIA) FROM dbo.GEN_PERSONA_COMPETENCIA WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_COMPETENCIA
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_COMPETENCIA,
			NOMBRE_COMPETENCIA, NIVEL_DOMINIO,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_COMP + ROW_NUMBER() OVER (ORDER BY C.CORR_COMPETENCIA_TECNICA),
			LEFT(C.HERRAMIENTA, 100),
			CASE
				WHEN UPPER(LTRIM(RTRIM(C.NIVEL))) LIKE '%AVANZ%' THEN 'AVANZADO'
				WHEN UPPER(LTRIM(RTRIM(C.NIVEL))) LIKE '%INTERM%' THEN 'INTERMEDIO'
				ELSE 'BASICO'
			END,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_COMPETENCIAS_TECNICAS AS C
		WHERE C.CORR_EMPRESA = @CORR_EMPRESA
		  AND C.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		-- =====================================================================
		-- 12. MIGRAR IDIOMAS (Homologando CHECK NIVEL_DOMINIO)
		-- =====================================================================
		DECLARE @MAX_IDIOMA INT = ISNULL((SELECT MAX(CORR_IDIOMA) FROM dbo.GEN_PERSONA_IDIOMAS WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_IDIOMAS
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_IDIOMA,
			NOMBRE_IDIOMA, NIVEL_DOMINIO,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_IDIOMA + ROW_NUMBER() OVER (ORDER BY I.CORR_IDIOMA),
			LEFT(I.IDIOMA, 100),
			CASE
				WHEN UPPER(LTRIM(RTRIM(I.NIVEL))) LIKE '%AVANZ%' THEN 'AVANZADO'
				WHEN UPPER(LTRIM(RTRIM(I.NIVEL))) LIKE '%INTERM%' THEN 'INTERMEDIO'
				ELSE 'BASICO'
			END,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_IDIOMAS AS I
		WHERE I.CORR_EMPRESA = @CORR_EMPRESA
		  AND I.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		-- =====================================================================
		-- 13. MIGRAR FAMILIARES, FAMILIARES EN UEES E HIJOS
		-- =====================================================================
		DECLARE @MAX_FAM INT = ISNULL((SELECT MAX(CORR_FAMILIAR) FROM dbo.GEN_PERSONA_FAMILIAR WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_FAMILIAR
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_FAMILIAR,
			NOMBRE_COMPLETO, DOMICILIO, FECHA_NACIMIENTO, OCUPACION,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_FAM + ROW_NUMBER() OVER (ORDER BY F.CORR_FAMILIAR),
			LEFT(F.NOMBRE, 100),
			LEFT(F.DOMICILIO, 255),
			F.FECHA_NACIMIENTO,
			LEFT(F.OCUPACION, 150),
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_FAMILIAR AS F
		WHERE F.CORR_EMPRESA = @CORR_EMPRESA
		  AND F.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		DECLARE @MAX_FAM_UEES INT = ISNULL((SELECT MAX(CORR_FAMILIAR_UEES) FROM dbo.GEN_PERSONA_FAMILIAR_UEES WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_FAMILIAR_UEES
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_FAMILIAR_UEES,
			NOMBRE_COMPLETO, TELEFONO, LUGAR_TRABAJO,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_FAM_UEES + ROW_NUMBER() OVER (ORDER BY FU.CORR_FAMILIAR_UEES),
			LEFT(FU.NOMBRE, 100),
			LEFT(FU.TELEFONO, 25),
			LEFT(FU.UNIDAD, 150),
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_FAMILIAR_UEES AS FU
		WHERE FU.CORR_EMPRESA = @CORR_EMPRESA
		  AND FU.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

		DECLARE @MAX_HIJO INT = ISNULL((SELECT MAX(CORR_HIJO) FROM dbo.GEN_PERSONA_HIJOS WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA), 0);

		INSERT INTO dbo.GEN_PERSONA_HIJOS
		(
			CORR_EMPRESA, CORR_PERSONA, CORR_HIJO,
			NOMBRE_COMPLETO, EDAD, SEXO, FECHA_NACIMIENTO,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		SELECT
			@CORR_EMPRESA,
			@CORR_PERSONA,
			@MAX_HIJO + ROW_NUMBER() OVER (ORDER BY H.CORR_HIJO),
			LEFT(H.NOMBRE, 100),
			H.EDAD,
			CASE
				WHEN UPPER(LTRIM(RTRIM(H.SEXO))) IN ('FEMENINO', 'F') THEN 'FEMENINO'
				WHEN UPPER(LTRIM(RTRIM(H.SEXO))) IN ('MASCULINO', 'M') THEN 'MASCULINO'
				ELSE NULL
			END,
			H.FECHA_NACIMIENTO,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		FROM dbo.SC_PERSONA_HIJOS AS H
		WHERE H.CORR_EMPRESA = @CORR_EMPRESA
		  AND H.CORR_PERSONA_DATOS = @CORR_PERSONA_DATOS;

