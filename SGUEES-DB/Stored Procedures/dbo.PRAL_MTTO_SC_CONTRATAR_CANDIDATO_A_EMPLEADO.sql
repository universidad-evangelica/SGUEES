		-- 14. CREAR EMPLEADO (GEN_EMPLEADO)
		-- =====================================================================
		SELECT @CORR_EMPLEADO = ISNULL(MAX(CORR_EMPLEADO), 0) + 1
		FROM dbo.GEN_EMPLEADO WITH (UPDLOCK, HOLDLOCK)
		WHERE CORR_EMPRESA = @CORR_EMPRESA;

		SET @CODIGO_EMPLEADO_NUEVO = CONVERT(VARCHAR(50), @CORR_EMPLEADO);

		DECLARE @CORR_AFP_EMPLEADO INT = NULL;
		IF @NOMBRE_AFP_CANDIDATO IS NOT NULL
		BEGIN
			SELECT TOP 1 @CORR_AFP_EMPLEADO = CORR_AFP
			FROM dbo.PLA_AFP
			WHERE ACTIVO_AFP = 1
			  AND (
				@NOMBRE_AFP_CANDIDATO LIKE '%' + NOMBRE_CORTO_AFP + '%'
				OR @NOMBRE_AFP_CANDIDATO LIKE '%' + NOMBRE_AFP + '%'
			  );
		END;

		INSERT INTO dbo.GEN_EMPLEADO
		(
			CORR_EMPRESA, CORR_EMPLEADO, CORR_PERSONA, CODIGO_EMPLEADO,
			CORR_AFP,
			FECHA_INGRESO, ACTIVO_EMPLEADO,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
		)
		VALUES
		(
			@CORR_EMPRESA, @CORR_EMPLEADO, @CORR_PERSONA, @CODIGO_EMPLEADO_NUEVO,
			@CORR_AFP_EMPLEADO,
			@FECHA_INGRESO, 1,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		);

		-- =====================================================================
		-- 15. ASIGNAR PUESTO Y CONDICIONES (GEN_EMPLEADO_PUESTO)
		-- =====================================================================
		IF @CORR_UNIDAD_PROPUESTA IS NOT NULL AND @CORR_PUESTO_PROPUESTO IS NOT NULL
		BEGIN
			INSERT INTO dbo.GEN_EMPLEADO_PUESTO
			(
				CORR_EMPRESA, CORR_EMPLEADO, CORR_UNIDAD, CORR_PUESTO,
				FECHA_INGRESO, SUELDO, HORARIO_LABORAL, CORR_TIPO_CONTRATACION, CORR_TIPO_MODALIDAD,
				USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_EMPLEADO, @CORR_UNIDAD_PROPUESTA, @CORR_PUESTO_PROPUESTO,
				@FECHA_INGRESO, @SALARIO_PROPUESTO, LEFT(@HORARIO_PROPUESTO, 300),
				ISNULL(@CORR_TIPO_CONTRATACION, CASE WHEN @TIPO_MOVIMIENTO = 'EVENTUAL' THEN 2 ELSE 1 END),
				@CORR_TIPO_MODALIDAD_PROPUESTA,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
			);
		END;

		-- =====================================================================
		-- 16. ENLAZAR EMPLEADO A SC_MOVIMIENTO_PERSONAL Y REGISTRAR BITÁCORA
		-- =====================================================================
		UPDATE dbo.SC_MOVIMIENTO_PERSONAL
		SET
			CORR_EMPLEADO = @CORR_EMPLEADO,
			USUARIO_ACTU = @SYS_LOGIN_USUARIO,
			ESTACION_ACTU = @SYS_ESTACION,
			FECHA_ACTU = @FECHA_AUD
		WHERE CORR_EMPRESA = @CORR_EMPRESA
		  AND CORR_MOVIMIENTO_PERSONAL = @CORR_MOVIMIENTO_PERSONAL;

		INSERT INTO dbo.SC_MOVIMIENTO_PERSONAL_BITACORA
		(
			CORR_EMPRESA, CORR_MOVIMIENTO_PERSONAL, LOGIN_SISTEMA,
			ESTADO_DESTINO, COMENTARIO, FECHA_ACCION,
			USUARIO_CREA, ESTACION_CREA, FECHA_CREA
		)
		VALUES
		(
			@CORR_EMPRESA, @CORR_MOVIMIENTO_PERSONAL, @SYS_LOGIN_USUARIO,
			N'Contratado',
			CONCAT(N'Se contrató al candidato. Se generó el Empleado #', @CORR_EMPLEADO, N' y Persona #', @CORR_PERSONA),
			@FECHA_AUD,
			@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
		);

		-- =====================================================================
		-- CIERRE EXITOSO DE TRANSACCIÓN
		-- =====================================================================
		COMMIT TRANSACTION;
		SET @SYS_FILAS_AFECTADAS = 1;
		SET @SYS_NUMERO_ERROR = 0;
		SET @SYS_MENSAJE_ERROR = N'';

	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION;

		SELECT
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(),
			@SYS_FILAS_AFECTADAS = 0,
			@CORR_EMPLEADO = NULL,
			@CORR_PERSONA = NULL;
	END CATCH;

SALIDA:
	RETURN;
END;
