CREATE PROCEDURE [dbo].[PRAL_GENE_COM_ANULACION_PAGO]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PAGO int,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)

AS

BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
		DECLARE	@TEMP1 TABLE (
			  ANIO_PERIODO_COM INT
			, MES_PERIODO_COM INT
			, CORR_DOCUMENTO_COM INT
			, MONTO_PAGO DECIMAL(14,2)
			, ESTA_PROC INT
		)
		
		DECLARE @CONTADOR INT, @CANTIDAD_REGISTROS INT, @ESTADO_PAGO VARCHAR(2),
		@ANIO_PERIODO_COM INT, @MES_PERIODO_COM INT, @CORR_DOCUMENTO_COM INT, @MONTO_PAGO DECIMAL(18,2)
		
		SELECT @ESTADO_PAGO=ESTADO_PAGO
		FROM COM_PAGO  A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PAGO=@CORR_PAGO
		
		IF ISNULL(@ESTADO_PAGO,'') = ''
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='Este pago no existe.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF @ESTADO_PAGO = 'AN'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Este pago ya está anulado',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		INSERT INTO @TEMP1 
		SELECT A.ANIO_PERIODO_COM, A.MES_PERIODO_COM, A.CORR_DOCUMENTO_COM, A.MONTO_PAGO, 0 ESTA_PROC
		FROM COM_PAGO_DETA A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PAGO=@CORR_PAGO 
		
		SELECT @CANTIDAD_REGISTROS=COUNT(*), @CONTADOR=0
		FROM @TEMP1 
		
		WHILE (@CONTADOR<@CANTIDAD_REGISTROS)
		BEGIN
			SELECT TOP 1 @CORR_DOCUMENTO_COM=CORR_DOCUMENTO_COM, @ANIO_PERIODO_COM=ANIO_PERIODO_COM, @MES_PERIODO_COM=MES_PERIODO_COM, @MONTO_PAGO=MONTO_PAGO 
			FROM @TEMP1 WHERE ESTA_PROC=0
			
			UPDATE COM_DOCUMENTO SET
			SALDO_DOCUMENTO=SALDO_DOCUMENTO+@MONTO_PAGO 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO_COM 
			AND MES_PERIODO=@MES_PERIODO_COM 
			AND CORR_DOCUMENTO=@CORR_DOCUMENTO_COM 
			
			UPDATE @TEMP1 SET
			ESTA_PROC=1
			WHERE ANIO_PERIODO_COM=@ANIO_PERIODO_COM 
			AND MES_PERIODO_COM=@MES_PERIODO_COM 
			AND CORR_DOCUMENTO_COM=@CORR_DOCUMENTO_COM 
						
			SELECT @CONTADOR+=1
		END
		
		
		UPDATE COM_PAGO SET
		ESTADO_PAGO='AN'
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PAGO=@CORR_PAGO 
		SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
		GOTO FINA
		
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO


