CREATE PROCEDURE [dbo].[PRAL_IMPR_COM_PROVISION_TRASLADO]
( 
  @CORR_EMPRESA INT,
  @FECHA_INICIAL DATE,
  @CORR_PROVISION_INICIAL INT,
  @CORR_PROVISION_FINAL INT
)
AS	        
BEGIN
    
    SET NOCOUNT ON
    
    SELECT *
    FROM V_COM_PROVISION_TRASLADO
    WHERE CORR_EMPRESA=@CORR_EMPRESA
    AND ANIO_PERIODO=YEAR(@FECHA_INICIAL)
    AND MES_PERIODO=MONTH(@FECHA_INICIAL)
    AND FECHA_PROVISION=@FECHA_INICIAL
    AND CORR_PROVISION>=@CORR_PROVISION_INICIAL
    AND CORR_PROVISION<=@CORR_PROVISION_FINAL
    
	SELECT A.CORR_EMPRESA
	,A.NOMBRE_EMPRESA
	,'' PERIODO
	,A.LOGO_1 LOGO1
	,A.LOGO_2 LOGO2
	,'' TITULO_REPORTE
	,'' NOMBRE_SISTEMA
	,GETDATE() FECHA_IMPRESION
	FROM GEN_EMPRESA A
	WHERE A.CORR_EMPRESA=@CORR_EMPRESA
	
END
GO


