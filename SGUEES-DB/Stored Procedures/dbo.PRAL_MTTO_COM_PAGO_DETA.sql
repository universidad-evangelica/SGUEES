CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PAGO_DETA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PAGO int,
	@CORR_DETA int OUTPUT,
	@ANIO_PERIODO_COM int,
	@MES_PERIODO_COM int,
	@CORR_DOCUMENTO_COM int,
	@MONTO_DOCUMENTO decimal(14,2),
	@MONTO_INICIAL decimal(14,2),
	@MONTO_PAGO decimal(14,2),
	@MONTO_FINAL decimal(14,2),	
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output,
	@GENERA_DETALLE_CONTABLE BIT=1,--SI ENVIA 0 NO GENERA EL DETALLE DE LA TABLA COM_PAGO_CONTA
	@GENERA_CONCEPTO BIT=1 --Si genera o no el concepto del pago
)
AS
	DECLARE @PROVISIONES VARCHAR(1000), @PAGOS VARCHAR(1000)
BEGIN

	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY
		IF @TIPO_ACTUALIZA=1 --Adicionar
		BEGIN
			SELECT @CORR_DETA=ISNULL(MAX(CORR_DETA),0)+1
			FROM COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO

			INSERT INTO COM_PAGO_DETA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_DETA,ANIO_PERIODO_COM,MES_PERIODO_COM,CORR_DOCUMENTO_COM,MONTO_DOCUMENTO,MONTO_INICIAL,MONTO_PAGO,MONTO_FINAL)
			VALUES
			(@CORR_EMPRESA,@ANIO_PERIODO,@MES_PERIODO,@CORR_PAGO,@CORR_DETA,@ANIO_PERIODO_COM,@MES_PERIODO_COM,@CORR_DOCUMENTO_COM,ABS(@MONTO_DOCUMENTO),ABS(@MONTO_INICIAL),ABS(@MONTO_PAGO),ABS(@MONTO_FINAL))
		END ELSE
		IF @TIPO_ACTUALIZA=2 --Actualizar
		BEGIN
			UPDATE COM_PAGO_DETA SET
			ANIO_PERIODO_COM=@ANIO_PERIODO_COM,
			MES_PERIODO_COM=@MES_PERIODO_COM,
			CORR_DOCUMENTO_COM=@CORR_DOCUMENTO_COM,
			MONTO_DOCUMENTO=ABS(@MONTO_DOCUMENTO),
			MONTO_INICIAL=ABS(@MONTO_INICIAL),
			MONTO_PAGO=ABS(@MONTO_PAGO),
			MONTO_FINAL=ABS(@MONTO_FINAL)
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
			AND CORR_DETA=@CORR_DETA
		END ELSE
		IF @TIPO_ACTUALIZA=3 --Eliminar
		BEGIN
			DELETE FROM COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
			AND CORR_DETA=@CORR_DETA
		END

		DECLARE @TOTAL DECIMAL(18,2),@NOMBRE_BENEFICIARIO VARCHAR(255), @NOMBRE_PARTIDA VARCHAR(255), @CUANTAS_SIN_PROVISION INT,@PROVISIONAR_POR_DOC BIT,@DESCRIPCION_PAGO VARCHAR(1000)

		SELECT @PROVISIONAR_POR_DOC=PROVISIONAR_POR_DOC
		FROM COM_PARAMETRO A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA

		SELECT @DESCRIPCION_PAGO=A.NOMBRE_PARTIDA
		FROM COM_PAGO A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PAGO=@CORR_PAGO

		SELECT @NOMBRE_BENEFICIARIO=B.NOMBRE_BENEFICIARIO
		FROM COM_PAGO_DETA A
		LEFT OUTER JOIN V_COM_DOCUMENTO_PROVISION B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM=B.ANIO_PERIODO_COM AND A.MES_PERIODO_COM=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO_COM=B.CORR_DOCUMENTO_COM		
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PAGO=@CORR_PAGO
		AND A.CORR_DETA=@CORR_DETA

		SELECT @TOTAL=SUM(MONTO_PAGO*D.SUMA_RESTA),
		--@NOMBRE_PARTIDA =  dbo.StrConcat(DISTINCT CASE WHEN B.CORR_PROVISION IS NOT NULL THEN 'PAGO DE PROVISION '+CONVERT(VARCHAR,B.NUMERO_PROVISION) ELSE 'PAGO A '+E.NOMBRE_PROVEEDOR END),
		@PROVISIONES = dbo.StrConcat(DISTINCT CASE WHEN B.CORR_PROVISION IS NOT NULL THEN CONVERT(VARCHAR,B.NUMERO_PROVISION) ELSE '' END+' '),
		@PAGOS = dbo.StrConcat(DISTINCT CASE WHEN B.CORR_PROVISION IS NOT NULL THEN '' ELSE E.NOMBRE_PROVEEDOR END),
		@CUANTAS_SIN_PROVISION=SUM(DISTINCT CASE WHEN B.CORR_PROVISION IS NOT NULL THEN 0 ELSE 1 END)
		FROM COM_PAGO_DETA A
		LEFT OUTER JOIN V_COM_DOCUMENTO_PROVISION B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM=B.ANIO_PERIODO_COM AND A.MES_PERIODO_COM=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO_COM=B.CORR_DOCUMENTO_COM
		INNER JOIN COM_DOCUMENTO C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.ANIO_PERIODO_COM=C.ANIO_PERIODO AND A.MES_PERIODO_COM=C.MES_PERIODO AND A.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
		INNER JOIN GEN_TIPO_DOCUMENTO D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_TIPO_DOC=D.CORR_TIPO_DOC
		INNER JOIN GEN_PROVEEDOR E ON C.CORR_EMPRESA=E.CORR_EMPRESA AND C.CORR_PROVEEDOR=E.CORR_PROVEEDOR
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PAGO=@CORR_PAGO

		SET @NOMBRE_PARTIDA = TRIM(CASE WHEN TRIM(@PROVISIONES)<>'' THEN 'PAGO DE PROVISION ' + @PROVISIONES ELSE '' END +' ' + CASE WHEN TRIM(@PAGOS)<>'' THEN 'PAGO A ' + @PROVISIONES ELSE '' END)

		UPDATE COM_PAGO SET
		MONTO_PAGO=ISNULL(@TOTAL,0)
		,NOMBRE_BENEFICIARIO=CASE WHEN LTRIM(RTRIM(ISNULL(@NOMBRE_BENEFICIARIO,'')))='' THEN NOMBRE_BENEFICIARIO ELSE LTRIM(RTRIM(ISNULL(@NOMBRE_BENEFICIARIO,''))) END
		,NOMBRE_PARTIDA= CASE WHEN @PROVISIONAR_POR_DOC=1 THEN @DESCRIPCION_PAGO ELSE CASE WHEN @CUANTAS_SIN_PROVISION>0 OR ISNULL(@GENERA_CONCEPTO,0)=0 THEN NOMBRE_PARTIDA ELSE
							CASE WHEN LTRIM(RTRIM(ISNULL(@NOMBRE_BENEFICIARIO,'')))='' THEN NOMBRE_BENEFICIARIO ELSE LTRIM(RTRIM(ISNULL(@NOMBRE_BENEFICIARIO,''))) END+ ' '+@NOMBRE_PARTIDA
						END END						
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO

		--EL PROCESO NORMAL SERA QUE GENERE AUTOMATICAMENTE SU DETALLE CONTABLE AL INSERTAR UNA COMPRA
		--PERO EN UN PROCESO ESPECIAL COMO LA LIQUIDACION DE CAJA CHICA NO ES NECESARIO QUE SE EJECUTE ESTE PROCESO
		--O BIEN QUE SE GENERE POR SEPARADO 
		IF ISNULL(@GENERA_DETALLE_CONTABLE,1)=1
		BEGIN
			EXECUTE PRAL_GENE_COM_PAGO_CONTA @CORR_EMPRESA, @ANIO_PERIODO, @MES_PERIODO, @CORR_PAGO, @CORR_DETA, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @SYS_FILAS_AFECTADAS OUTPUT, @SYS_NUMERO_ERROR OUTPUT, @SYS_MENSAJE_ERROR OUTPUT
		END			

		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT

	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO



