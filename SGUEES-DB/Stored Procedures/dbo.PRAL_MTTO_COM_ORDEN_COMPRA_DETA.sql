CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_ORDEN_COMPRA_DETA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@CORR_ORDEN_COMPRA INT,
	@CORR_ORDEN_COMPRA_DETA INT OUTPUT,
	@CODIGO_ITEM VARCHAR(30),
	@CORR_UNIDAD_MEDIDA INT = NULL,
	@CANTIDAD_COMPRA DECIMAL(18, 2),
	@PRECIO_UNITARIO DECIMAL(18, 6),
	@MONTO_SUBTOTAL DECIMAL(18, 6),
	@ANIO_PERIODO_COTIZACION INT = NULL,
	@CORR_COTIZACION INT = NULL,
	@CORR_COTIZACION_DETA INT = NULL,
	@CORR_CENTRO_COSTO INT = NULL,
	@CANTIDAD_RECIBIDA DECIMAL(18, 2) = 0,
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30) = NULL,
	@FECHA_ACTU DATETIME = NULL,
	@ESTACION_ACTU VARCHAR(50) = NULL,
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0

	BEGIN TRY
		IF NOT EXISTS (
			SELECT 1 FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
				AND ESTADO_ORDEN = N'DI'
		)
		BEGIN
			RAISERROR(N'Solo se puede modificar el detalle de una orden digitada.', 16, 1)
		END

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_ORDEN_COMPRA_DETA = ISNULL(MAX(CORR_ORDEN_COMPRA_DETA), 0) + 1
			FROM dbo.COM_ORDEN_COMPRA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA

			INSERT INTO dbo.COM_ORDEN_COMPRA_DETA (
				CORR_EMPRESA, ANIO_PERIODO, CORR_ORDEN_COMPRA, CORR_ORDEN_COMPRA_DETA,
				CODIGO_ITEM, CORR_UNIDAD_MEDIDA, CANTIDAD_COMPRA, PRECIO_UNITARIO, MONTO_SUBTOTAL,
				ANIO_PERIODO_COTIZACION, CORR_COTIZACION, CORR_COTIZACION_DETA, CORR_CENTRO_COSTO, CANTIDAD_RECIBIDA,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA
			)
			VALUES (
				@CORR_EMPRESA, @ANIO_PERIODO, @CORR_ORDEN_COMPRA, @CORR_ORDEN_COMPRA_DETA,
				@CODIGO_ITEM, @CORR_UNIDAD_MEDIDA, @CANTIDAD_COMPRA, @PRECIO_UNITARIO, @MONTO_SUBTOTAL,
				@ANIO_PERIODO_COTIZACION, @CORR_COTIZACION, @CORR_COTIZACION_DETA, @CORR_CENTRO_COSTO, ISNULL(@CANTIDAD_RECIBIDA, 0),
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA
			)
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.COM_ORDEN_COMPRA_DETA SET
				CODIGO_ITEM = @CODIGO_ITEM,
				CORR_UNIDAD_MEDIDA = @CORR_UNIDAD_MEDIDA,
				CANTIDAD_COMPRA = @CANTIDAD_COMPRA,
				PRECIO_UNITARIO = @PRECIO_UNITARIO,
				MONTO_SUBTOTAL = @MONTO_SUBTOTAL,
				ANIO_PERIODO_COTIZACION = @ANIO_PERIODO_COTIZACION,
				CORR_COTIZACION = @CORR_COTIZACION,
				CORR_COTIZACION_DETA = @CORR_COTIZACION_DETA,
				CORR_CENTRO_COSTO = @CORR_CENTRO_COSTO,
				CANTIDAD_RECIBIDA = ISNULL(@CANTIDAD_RECIBIDA, 0),
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
				AND CORR_ORDEN_COMPRA_DETA = @CORR_ORDEN_COMPRA_DETA
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.COM_ORDEN_COMPRA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
				AND CORR_ORDEN_COMPRA_DETA = @CORR_ORDEN_COMPRA_DETA
		END

		UPDATE dbo.COM_ORDEN_COMPRA
		SET COMPRA_TOTAL = (
			SELECT ISNULL(SUM(MONTO_SUBTOTAL), 0)
			FROM dbo.COM_ORDEN_COMPRA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
		)
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE()
	END CATCH
END
GO
