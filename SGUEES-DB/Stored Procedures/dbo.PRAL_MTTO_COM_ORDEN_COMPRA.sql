CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_ORDEN_COMPRA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@CORR_ORDEN_COMPRA INT OUTPUT,
	@CORR_TIPO_DOC INT = NULL,
	@CORR_PROVEEDOR INT,
	@ATENCION_A VARCHAR(150) = NULL,
	@FECHA_ORDEN DATE,
	@ESTADO_ORDEN VARCHAR(2),
	@OBSERVACIONES VARCHAR(1000) = NULL,
	@COMPRA_TOTAL DECIMAL(18, 6) = NULL,
	@MONTO_EN_LETRAS VARCHAR(1000) = NULL,
	@NUMERO_ORDEN_COMPRA INT = NULL OUTPUT,
	@CORR_CONDICION_PAGO INT = NULL,
	@CORR_FORMA_PAGO INT = NULL,
	@DETALLE_FORMA_PAGO VARCHAR(250) = NULL,
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30) = NULL,
	@FECHA_ACTU DATETIME = NULL,
	@ESTACION_ACTU VARCHAR(50) = NULL,
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0

	BEGIN TRY
		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_ORDEN_COMPRA = ISNULL(MAX(CORR_ORDEN_COMPRA), 0) + 1
			FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO

			IF @NUMERO_ORDEN_COMPRA IS NULL OR @NUMERO_ORDEN_COMPRA = 0
			BEGIN
				SELECT @NUMERO_ORDEN_COMPRA = ISNULL(MAX(NUMERO_ORDEN_COMPRA), (@ANIO_PERIODO % 100) * 100000) + 1
				FROM dbo.COM_ORDEN_COMPRA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO
			END

			INSERT INTO dbo.COM_ORDEN_COMPRA (
				CORR_EMPRESA, ANIO_PERIODO, CORR_ORDEN_COMPRA, CORR_TIPO_DOC, CORR_PROVEEDOR,
				ATENCION_A, FECHA_ORDEN, ESTADO_ORDEN, OBSERVACIONES, COMPRA_TOTAL, MONTO_EN_LETRAS,
				NUMERO_ORDEN_COMPRA, CORR_CONDICION_PAGO, CORR_FORMA_PAGO, DETALLE_FORMA_PAGO,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA
			)
			VALUES (
				@CORR_EMPRESA, @ANIO_PERIODO, @CORR_ORDEN_COMPRA, @CORR_TIPO_DOC, @CORR_PROVEEDOR,
				@ATENCION_A, @FECHA_ORDEN, ISNULL(NULLIF(@ESTADO_ORDEN, N''), N'DI'), @OBSERVACIONES, @COMPRA_TOTAL, @MONTO_EN_LETRAS,
				@NUMERO_ORDEN_COMPRA, @CORR_CONDICION_PAGO, @CORR_FORMA_PAGO, @DETALLE_FORMA_PAGO,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA
			)
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.COM_ORDEN_COMPRA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
					AND ESTADO_ORDEN = N'DI'
			)
			BEGIN
				RAISERROR(N'Solo se puede modificar una orden digitada.', 16, 1)
			END

			UPDATE dbo.COM_ORDEN_COMPRA SET
				CORR_TIPO_DOC = @CORR_TIPO_DOC,
				CORR_PROVEEDOR = @CORR_PROVEEDOR,
				ATENCION_A = @ATENCION_A,
				FECHA_ORDEN = @FECHA_ORDEN,
				OBSERVACIONES = @OBSERVACIONES,
				COMPRA_TOTAL = @COMPRA_TOTAL,
				MONTO_EN_LETRAS = @MONTO_EN_LETRAS,
				CORR_CONDICION_PAGO = @CORR_CONDICION_PAGO,
				CORR_FORMA_PAGO = @CORR_FORMA_PAGO,
				DETALLE_FORMA_PAGO = @DETALLE_FORMA_PAGO,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA
				AND ANIO_PERIODO = @ANIO_PERIODO
				AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM dbo.COM_ORDEN_COMPRA
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
					AND ESTADO_ORDEN = N'DI'
			)
			BEGIN
				RAISERROR(N'Solo se puede eliminar una orden digitada.', 16, 1)
			END

			DELETE FROM dbo.COM_ORDEN_COMPRA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA

			DELETE FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
		END

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE()
	END CATCH
END
GO
