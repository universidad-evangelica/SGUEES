CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PROVISION_DESAPLICAR]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int OUTPUT,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)

AS

BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
	
		DECLARE	@ESTADO_PROVISION VARCHAR(2), @ANIO_PERIODO_PARTIDA INT, @MES_PERIODO_PARTIDA INT, @CORR_CLASE_PARTIDA INT, @CORR_PARTIDA INT, @HOY DATETIME
		
		SELECT @ESTADO_PROVISION=ESTADO_PROVISION
		FROM COM_PROVISION  A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION
		
		IF @ESTADO_PROVISION = 'AN'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='Esta provisión ya está anulada. No se puede desaplicar',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF NOT EXISTS(SELECT 1 FROM CON_PERIODO_CONTABLE
					  WHERE CORR_EMPRESA=@CORR_EMPRESA
					  AND ANIO_PERIODO=@ANIO_PERIODO
					  AND MES_PERIODO=@MES_PERIODO
					  AND ESTADO_PERIODO_COM='AB')
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='El periodo contable para compras NO esta Abierto. Esta provision no se puede aplicar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
					
		SELECT @CORR_PARTIDA=CORR_PARTIDA, @CORR_CLASE_PARTIDA=CORR_CLASE_PARTIDA, @ANIO_PERIODO_PARTIDA=ANIO_PERIODO_PARTIDA, @MES_PERIODO_PARTIDA=MES_PERIODO_PARTIDA   
		FROM COM_PROVISION 
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION 	
		
		
		--Se valida que el periodo CONTABLE este abierto
		IF NOT EXISTS(SELECT 1 FROM CON_PERIODO_CONTABLE
				  WHERE CORR_EMPRESA=@CORR_EMPRESA
				  AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
				  AND MES_PERIODO=@MES_PERIODO_PARTIDA
				  AND ESTADO_PERIODO_CON='AB')
		AND ISNULL(@ANIO_PERIODO_PARTIDA,0)<>0
		AND ISNULL(@MES_PERIODO_PARTIDA,0)<>0
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='El periodo contable NO esta Abierto. Esta provision no se puede contabilizar.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
BEGIN TRANSACTION
		SELECT @HOY=GETDATE()

		IF ISNULL(@ANIO_PERIODO_PARTIDA,0)<>0
		AND ISNULL(@MES_PERIODO_PARTIDA,0)<>0
		AND ISNULL(@CORR_CLASE_PARTIDA,0)<>0
		AND ISNULL(@CORR_PARTIDA,0)<>0
		EXECUTE PRAL_MTTO_CON_PARTIDA_DESAPLICAR
@CORR_EMPRESA
		  ,@ANIO_PERIODO_PARTIDA
		  ,@MES_PERIODO_PARTIDA
		  ,@CORR_CLASE_PARTIDA
		  ,@CORR_PARTIDA OUTPUT
		  ,@SYS_LOGIN_USUARIO
		  ,@HOY
		  ,@SYS_ESTACION 
		  ,@SYS_LOGIN_USUARIO
		  ,@SYS_ESTACION
		  ,@SYS_FILAS_AFECTADAS OUTPUT
		  ,@SYS_NUMERO_ERROR OUTPUT
		  ,@SYS_MENSAJE_ERROR OUTPUT
		  
		IF @SYS_NUMERO_ERROR<>0
		BEGIN
			IF @@TRANCOUNT>0
				ROLLBACK TRANSACTION
				
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='No se puede desaplicar esta provisión, ya que la partida contable no se pudo desaplicar.',@SYS_FILAS_AFECTADAS=0		
			GOTO FINA
		END 
		
		--Se mantiene la relación para poder sobre escribirla luego
		UPDATE COM_PROVISION SET
		ESTADO_PROVISION='DI'--,
		--ANIO_PERIODO_PARTIDA=NULL,MES_PERIODO_PARTIDA=NULL,
		--CORR_CLASE_PARTIDA=NULL,CORR_PARTIDA=NULL 
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION 
		
		UPDATE COM_DOCUMENTO SET
		ESTA_PROVISIONADO=0
		FROM COM_PROVISION A
		INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
		INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION
		
		--Se usan comentarios por que al aplicar se sobre escribe la partida
		--********************************************************************
		--DELETE FROM CON_PARTIDA_DETA
		--WHERE CORR_SUSCRIPCION=@CORR_SUSCRIPCION
	 --   AND CORR_CONFI_PAIS=@CORR_CONFI_PAIS
	 --   AND CORR_EMPRESA=@CORR_EMPRESA
		--AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
		--AND MES_PERIODO=@MES_PERIODO_PARTIDA
		--AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
		--AND CORR_PARTIDA=@CORR_PARTIDA
	
		--DELETE FROM CON_PARTIDA
		--WHERE CORR_SUSCRIPCION=@CORR_SUSCRIPCION
	 --   AND CORR_CONFI_PAIS=@CORR_CONFI_PAIS
	 --   AND CORR_EMPRESA=@CORR_EMPRESA
		--AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
		--AND MES_PERIODO=@MES_PERIODO_PARTIDA
		--AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
		--AND CORR_PARTIDA=@CORR_PARTIDA
			
		IF @@TRANCOUNT>0
			COMMIT TRANSACTION		
		
		GOTO FINA
		
		
		
	END TRY
	BEGIN CATCH
	IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO


