CREATE PROCEDURE [dbo].[PRAL_DATA_COM_PAGO_DETA]
(
	@TIPO_CONSULTA int,
	@CORR_EMPRESA int=NULL,
	@ANIO_PERIODO int=NULL,
	@MES_PERIODO int=NULL,
	@CORR_PAGO int=NULL,
	@CORR_DETA int=NULL,
	@OPCION_CONSULTA int=0
)
AS
	DECLARE @CORR_PROVEEDOR INT, @PAGA_SIN_PROVISION BIT
BEGIN
	SET NOCOUNT ON

	IF @TIPO_CONSULTA=1 --Todos los campos, todos los registrosl (Mtto)
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT * FROM V_COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
		END ELSE
		IF @OPCION_CONSULTA=1 --Pendientes de Pago
		BEGIN			
			SELECT @CORR_PROVEEDOR=CORR_PROVEEDOR
			FROM COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
			
			SELECT @PAGA_SIN_PROVISION=ISNULL(PAGA_SIN_PROVISION,0)
			FROM COM_PARAMETRO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			
			SELECT A.CORR_EMPRESA, A.ANIO_PERIODO, A.MES_PERIODO, A.CORR_DOCUMENTO, A.CORR_TIPO_DOC, A.NOMBRE_CORTO_TIPO_DOC, A.NUMERO_DOCUMENTO, A.FECHA_DOCUMENTO, A.FECHA_VENCIMIENTO, A.CORR_TIENDA, A.CORR_PROVEEDOR, A.NOMBRE_PROVEEDOR, A.DESCRIPCION_PARTIDA, A.CORR_CONDICION_PAGO, A.DIAS_CREDITO, A.ESTADO_DOCUMENTO, A.ESTA_CONTABILIZADO, A.TOTAL_DOCUMENTO, A.TOTAL_NETO, A.TOTAL_DOCUMENTO - ISNULL(SUM(B.MONTO_PAGO),0) SALDO_DOCUMENTO, A.USUARIO_CREA, A.FECHA_CREA, A.ESTACION_CREA, A.USUARIO_ACTU, A.FECHA_ACTU, A.ESTACION_ACTU, A.CORR_TIPO_GASTO, A.CORR_TIPO_PAGO, A.CANTIDAD, A.CORR_MOVIMIENTO, A.ESTA_PROVISIONADO, A.NUMERO_QUEDAN, A.ANIO_PERIODO_QUEDAN, A.MES_PERIODO_QUEDAN, A.CORR_QUEDAN, A.SELECCION, A.CORR_PROVISION, A.NUMERO_PROVISION, A.CORR_PAGO, A.CORR_DETA, A.MONTO_PAGO, A.SALDO_FINAL, A.NOMBRE_BENEFICIARIO, A.ESTADO_PAGO
			FROM V_COM_DOCUMENTO_A_PAGAR A
			LEFT OUTER JOIN V_COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO_COM AND A.MES_PERIODO=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO=B.CORR_DOCUMENTO_COM AND B.ESTADO_PAGO='AP'
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA			
			AND (ISNULL(@PAGA_SIN_PROVISION,0)=1 OR (ISNULL(@PAGA_SIN_PROVISION,0)=0 AND CORR_PROVISION IS NOT NULL))			
			--AND (CORR_PAGO IS NULL OR ESTADO_PAGO='AN')	
			--AND A.SALDO_DOCUMENTO<>0
			AND ESTADO_DOCUMENTO='AP'
			AND A.CORR_PROVEEDOR=@CORR_PROVEEDOR
			AND NOT EXISTS (
				SELECT 1 FROM COM_PAGO_DETA C
				WHERE A.CORR_EMPRESA=C.CORR_EMPRESA
				AND A.ANIO_PERIODO=C.ANIO_PERIODO_COM
				AND A.MES_PERIODO=C.MES_PERIODO_COM
				AND A.CORR_DOCUMENTO=C.CORR_DOCUMENTO_COM
				AND @ANIO_PERIODO=C.ANIO_PERIODO
				AND @MES_PERIODO=C.MES_PERIODO
				AND @CORR_PAGO=C.CORR_PAGO
			)
			GROUP BY 
				A.CORR_EMPRESA, A.ANIO_PERIODO, A.MES_PERIODO, A.CORR_DOCUMENTO, A.CORR_TIPO_DOC, A.NOMBRE_CORTO_TIPO_DOC, A.NUMERO_DOCUMENTO, A.FECHA_DOCUMENTO, A.FECHA_VENCIMIENTO, A.CORR_TIENDA, A.CORR_PROVEEDOR, A.NOMBRE_PROVEEDOR, A.DESCRIPCION_PARTIDA, A.CORR_CONDICION_PAGO, A.DIAS_CREDITO, A.ESTADO_DOCUMENTO, A.ESTA_CONTABILIZADO, A.TOTAL_DOCUMENTO, A.TOTAL_NETO, A.SALDO_DOCUMENTO, A.USUARIO_CREA, A.FECHA_CREA, A.ESTACION_CREA, A.USUARIO_ACTU, A.FECHA_ACTU, A.ESTACION_ACTU, A.CORR_TIPO_GASTO, A.CORR_TIPO_PAGO, A.CANTIDAD, A.CORR_MOVIMIENTO, A.ESTA_PROVISIONADO, A.NUMERO_QUEDAN, A.ANIO_PERIODO_QUEDAN, A.MES_PERIODO_QUEDAN, A.CORR_QUEDAN, A.SELECCION, A.CORR_PROVISION, A.NUMERO_PROVISION, A.CORR_PAGO, A.CORR_DETA, A.MONTO_PAGO, A.SALDO_FINAL, A.NOMBRE_BENEFICIARIO, A.ESTADO_PAGO
			HAVING ISNULL(SUM(B.MONTO_PAGO),0)<>A.TOTAL_DOCUMENTO

		END  ELSE
		IF @OPCION_CONSULTA=2
		BEGIN
			SELECT @PAGA_SIN_PROVISION=ISNULL(PAGA_SIN_PROVISION,0)
			FROM COM_PARAMETRO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
						
		    SELECT * FROM V_COM_DOCUMENTO_A_PAGAR
			WHERE CORR_EMPRESA=@CORR_EMPRESA			
			AND (ISNULL(@PAGA_SIN_PROVISION,0)=1 OR (ISNULL(@PAGA_SIN_PROVISION,0)=0 AND CORR_PROVISION IS NOT NULL))
			AND (CORR_PAGO IS NULL OR ESTADO_PAGO='AN')
			AND SALDO_DOCUMENTO<>0
			AND ESTADO_DOCUMENTO='AP'
		END
	END ELSE
	IF @TIPO_CONSULTA=2 --Algunos campos, todos los registrosl (Combos)
	BEGIN
		SELECT * FROM V_COM_PAGO_DETA
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO
	END ELSE
	IF @TIPO_CONSULTA=3 --Todos los campos, un solo registro
	BEGIN
		SELECT * FROM V_COM_PAGO_DETA
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO
		AND CORR_DETA=@CORR_DETA
	END ELSE
	IF @TIPO_CONSULTA=4 --Un campo, un solo registro
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT CORR_EMPRESA FROM V_COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
			AND CORR_DETA=@CORR_DETA
		END
	END

END
GO



