CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PAGO]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PAGO int OUTPUT,
	@CORR_TIPO_DOC int = NULL,
	@FECHA_SOLICITUD date = NULL,
	@FECHA_PAGO date = NULL,
	@CORR_PROVEEDOR int = 0,
	@CORR_TIPO_CHEQUE int = NULL,
	@CORR_CUENTA_BANCO int = NULL,
	@NOMBRE_PARTIDA varchar(1000) = '',
	@MONTO_PAGO decimal(18,2) = 0,
	@ANIO_PERIODO_CHEQUE int = NULL,
	@MES_PERIODO_CHEQUE int = NULL,
	@CORR_TIPO_MOVIMIENTO int = NULL,
	@CORR_DOCUMENTO_CHEQUE int = NULL,
	@ANIO_PERIODO_SOLI_CHEQUE int = NULL,
	@MES_PERIODO_SOLI_CHEQUE int = NULL,
	@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE int = NULL,
	@CORR_DOCUMENTO_SOLI_CHEQUE int = NULL,
	@ESTADO_PAGO varchar(2) = '',
	@PAGADO_CAJA_CHICA BIT = 0,
	@CORR_TIENDA INT = NULL,
	@CORR_CAJA INT = NULL,
	@NOMBRE_BENEFICIARIO VARCHAR(255)='',
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
BEGIN
	
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2) --VALIDACION PREVIA SI SE VA A ADICIONAR O ACTIALIZAR
		BEGIN
			IF NOT (@MES_PERIODO BETWEEN 1 AND 12)
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No ha seleccionado correctamente el mes.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
			IF NOT EXISTS ( SELECT 1 FROM GEN_PROVEEDOR
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND CORR_PROVEEDOR=@CORR_PROVEEDOR ) --SE VERIFICA QUE EXISTA EL PROVEEDOR SELECCIONADO
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No existe el Proveedor seleccionado.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
			SELECT @CORR_TIPO_DOC=CORR_TIPO_DOC_PAGO 
			FROM COM_PARAMETRO 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			
			IF NOT EXISTS ( SELECT 1 FROM GEN_TIPO_DOCUMENTO 
							WHERE CORR_EMPRESA=@CORR_EMPRESA 
							AND CORR_TIPO_DOC=@CORR_TIPO_DOC )
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No se ha configurado correctamente el tipo de documento.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
		END
		IF @TIPO_ACTUALIZA=1 --Adicionar
		BEGIN
			SELECT @CORR_PAGO=ISNULL(MAX(CORR_PAGO),0)+1, @ESTADO_PAGO='DI'
			FROM COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO

			INSERT INTO COM_PAGO
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PAGO,CORR_TIPO_DOC,FECHA_SOLICITUD,FECHA_PAGO,CORR_PROVEEDOR,CORR_TIPO_CHEQUE,CORR_CUENTA_BANCO,NOMBRE_PARTIDA,MONTO_PAGO,ANIO_PERIODO_CHEQUE,MES_PERIODO_CHEQUE,CORR_TIPO_MOVIMIENTO,CORR_DOCUMENTO_CHEQUE,ANIO_PERIODO_SOLI_CHEQUE,MES_PERIODO_SOLI_CHEQUE,CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE,CORR_DOCUMENTO_SOLI_CHEQUE,ESTADO_PAGO,PAGADO_CAJA_CHICA,CORR_TIENDA,CORR_CAJA,NOMBRE_BENEFICIARIO)
			VALUES
			(@CORR_EMPRESA,@ANIO_PERIODO,@MES_PERIODO,@CORR_PAGO,@CORR_TIPO_DOC,@FECHA_SOLICITUD,@FECHA_PAGO,@CORR_PROVEEDOR,@CORR_TIPO_CHEQUE,@CORR_CUENTA_BANCO,@NOMBRE_PARTIDA,@MONTO_PAGO,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE,@ANIO_PERIODO_SOLI_CHEQUE,@MES_PERIODO_SOLI_CHEQUE,@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE,@CORR_DOCUMENTO_SOLI_CHEQUE,@ESTADO_PAGO,@PAGADO_CAJA_CHICA,@CORR_TIENDA,@CORR_CAJA,@NOMBRE_BENEFICIARIO)
		END ELSE
		IF @TIPO_ACTUALIZA=2 --Actualizar
		BEGIN
			UPDATE COM_PAGO SET
			CORR_TIPO_DOC=@CORR_TIPO_DOC,
			FECHA_SOLICITUD=@FECHA_SOLICITUD,
			FECHA_PAGO=@FECHA_PAGO,
			CORR_PROVEEDOR=@CORR_PROVEEDOR,
			CORR_TIPO_CHEQUE=@CORR_TIPO_CHEQUE,
			CORR_CUENTA_BANCO=@CORR_CUENTA_BANCO,
			NOMBRE_PARTIDA=@NOMBRE_PARTIDA,
			MONTO_PAGO=@MONTO_PAGO,
			ANIO_PERIODO_CHEQUE=@ANIO_PERIODO_CHEQUE,
			MES_PERIODO_CHEQUE=@MES_PERIODO_CHEQUE,
			CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO,
			CORR_DOCUMENTO_CHEQUE=@CORR_DOCUMENTO_CHEQUE,
			ANIO_PERIODO_SOLI_CHEQUE=@ANIO_PERIODO_SOLI_CHEQUE,
			MES_PERIODO_SOLI_CHEQUE=@MES_PERIODO_SOLI_CHEQUE,
			CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE,
			CORR_DOCUMENTO_SOLI_CHEQUE=@CORR_DOCUMENTO_SOLI_CHEQUE,
			ESTADO_PAGO=@ESTADO_PAGO,
			PAGADO_CAJA_CHICA=@PAGADO_CAJA_CHICA,
			CORR_TIENDA=@CORR_TIENDA,
			CORR_CAJA=@CORR_CAJA,
			NOMBRE_BENEFICIARIO=@NOMBRE_BENEFICIARIO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
		END ELSE
		IF @TIPO_ACTUALIZA=3 --Eliminar
		BEGIN
			DELETE FROM COM_PAGO_CONTA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO 
			
			DELETE FROM COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO 
			
			DELETE FROM COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
		END ELSE
		IF @TIPO_ACTUALIZA=4 --BORRAR DETALLE
		BEGIN
			DELETE FROM COM_PAGO_CONTA 
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO 
			
			DELETE FROM COM_PAGO_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO 
		END
		
		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT
	
	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO



