CREATE PROCEDURE [dbo].[PRAL_DATA_COM_PAGO_ARCHIVO_BANCO]
(
	@TIPO_CONSULTA int,
	@CORR_EMPRESA int=NULL,	
	@CORR_ARCHIVO int=NULL,	
	@OPCION_CONSULTA int=0
)
AS
BEGIN
	SET NOCOUNT ON
		
	DECLARE @CLASE_BANCO VARCHAR(5)
	DECLARE @ARCHIVO TABLE (CORR_EMPRESA INT, CADENA VARCHAR(4000))
	
	IF @OPCION_CONSULTA=0 --ARCHIVOS PARA EL BANCO
	BEGIN
		SELECT @CLASE_BANCO=C.CLASE_BANCO
		FROM COM_PAGO_ARCHIVO A
		INNER JOIN BAN_CUENTA_BANCARIA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_CUENTA_BANCO=B.CORR_CUENTA_BANCO
		INNER JOIN BAN_BANCO C ON B.CORR_BANCO=C.CORR_BANCO
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.CORR_ARCHIVO=@CORR_ARCHIVO
	
		IF @CLASE_BANCO IN ('CREDO', 'BAC') --Formato Credomatic/BAC
		BEGIN
			INSERT INTO @ARCHIVO (CORR_EMPRESA,CADENA)
			SELECT TOP 1 A.CORR_EMPRESA,
			'B'
			+ SUBSTRING(ISNULL(REPLICATE('0',4-LEN(RTRIM(LTRIM(ISNULL(X.CODIGO_EMPRESARIAL,''))))),'') + RTRIM(LTRIM(ISNULL(X.CODIGO_EMPRESARIAL,''))),1,4)
			+ SUBSTRING(ISNULL(REPLICATE('0',5-LEN(RTRIM(LTRIM(ISNULL(X.CORRELATIVO,''))))),'') + RTRIM(LTRIM(ISNULL(X.CORRELATIVO,''))),1,5)
			+ SPACE(25)
			+ CONVERT(VARCHAR,YEAR(X.FECHA_PAGO))
			+ REPLICATE('0',2-LEN(CONVERT(VARCHAR,MONTH(X.FECHA_PAGO)))) + CONVERT(VARCHAR,MONTH(X.FECHA_PAGO))
			+ REPLICATE('0',2-LEN(CONVERT(VARCHAR,DAY(X.FECHA_PAGO)))) + CONVERT(VARCHAR,DAY(X.FECHA_PAGO))
			+ REPLICATE(SPACE(1),13-LEN(CONVERT(VARCHAR,CONVERT(INT,SUM(B.MONTO_PAGO)*100)))) + CONVERT(VARCHAR,CONVERT(INT,SUM(B.MONTO_PAGO)*100))
			+ REPLICATE(SPACE(1),5-LEN(CONVERT(VARCHAR,COUNT(D.CORR_PROVEEDOR)))) + CONVERT(VARCHAR,COUNT(D.CORR_PROVEEDOR))
			FROM COM_PAGO_ARCHIVO X
			INNER JOIN COM_PAGO A ON X.CORR_EMPRESA=A.CORR_EMPRESA AND X.CORR_ARCHIVO=A.CORR_ARCHIVO
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO				
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO 
			INNER JOIN GEN_PROVEEDOR D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_PROVEEDOR=D.CORR_PROVEEDOR				
			INNER JOIN BAN_TIPO_MOVI_BANCARIO E ON A.CORR_EMPRESA=E.CORR_EMPRESA AND A.CORR_TIPO_MOVIMIENTO=E.CORR_TIPO_MOVIMIENTO
			WHERE X.CORR_EMPRESA=@CORR_EMPRESA 			
			AND X.CORR_ARCHIVO=@CORR_ARCHIVO			
			GROUP BY A.CORR_EMPRESA,X.CODIGO_EMPRESARIAL,X.CORRELATIVO,X.FECHA_PAGO
			
			INSERT INTO @ARCHIVO (CORR_EMPRESA,CADENA)
			SELECT A.CORR_EMPRESA,
			'T'
			+ SUBSTRING(ISNULL(REPLICATE('0',4-LEN(RTRIM(LTRIM(ISNULL(X.CODIGO_EMPRESARIAL,''))))),'') + RTRIM(LTRIM(ISNULL(X.CODIGO_EMPRESARIAL,''))),1,4)
			+ SUBSTRING(ISNULL(REPLICATE('0',5-LEN(RTRIM(LTRIM(ISNULL(X.CORRELATIVO,''))))),'') + RTRIM(LTRIM(ISNULL(X.CORRELATIVO,''))),1,5)
			+ SUBSTRING(RTRIM(LTRIM(REPLACE(ISNULL(D.NUMERO_NIT,''),'-',''))) + ISNULL(REPLICATE(SPACE(1),20-LEN(RTRIM(LTRIM(REPLACE(ISNULL(D.NUMERO_NIT,''),'-',''))))),''),1,20)
			+ REPLICATE(SPACE(1),5-LEN(ROW_NUMBER() OVER(PARTITION BY A.CORR_EMPRESA ORDER BY C.CORR_PROVEEDOR))) + CONVERT(VARCHAR,ROW_NUMBER() OVER(PARTITION BY A.CORR_EMPRESA ORDER BY C.CORR_PROVEEDOR))
			+ CONVERT(VARCHAR,YEAR(X.FECHA_PAGO))
			+ REPLICATE('0',2-LEN(CONVERT(VARCHAR,MONTH(X.FECHA_PAGO)))) + CONVERT(VARCHAR,MONTH(X.FECHA_PAGO))
			+ REPLICATE('0',2-LEN(CONVERT(VARCHAR,DAY(X.FECHA_PAGO)))) + CONVERT(VARCHAR,DAY(X.FECHA_PAGO))
			+ REPLICATE(SPACE(1),13-LEN(CONVERT(VARCHAR,CONVERT(INT,SUM(B.MONTO_PAGO)*100)))) + CONVERT(VARCHAR,CONVERT(INT,SUM(B.MONTO_PAGO)*100))
			+ SPACE(5)
			+ SUBSTRING(RTRIM(LTRIM(C.DESCRIPCION_PARTIDA))+ISNULL(REPLICATE(SPACE(1),30-LEN(RTRIM(LTRIM(C.DESCRIPCION_PARTIDA)))),''),1,30)
			+ SPACE(1)
			+ REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(SUBSTRING(RTRIM(LTRIM(D.NOMBRE_PROVEEDOR)) + ISNULL(REPLICATE(SPACE(1),30-LEN(RTRIM(LTRIM(D.NOMBRE_PROVEEDOR)))),''),1,30)),'Ñ','N'),'Á','A'),'É','E'),'Í','I'),'Ó','O'),'Ú','U')
			+ SPACE(60)
			+ SUBSTRING(ISNULL(REPLICATE(SPACE(1),9-LEN(RTRIM(LTRIM(ISNULL(CP.CUENTA_BANCARIA,''))))),'') + RTRIM(LTRIM(ISNULL(CP.CUENTA_BANCARIA,''))),1,9)
			FROM COM_PAGO_ARCHIVO X
			INNER JOIN COM_PAGO A ON X.CORR_EMPRESA=A.CORR_EMPRESA AND X.CORR_ARCHIVO=A.CORR_ARCHIVO
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO				
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO 
			INNER JOIN GEN_PROVEEDOR D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_PROVEEDOR=D.CORR_PROVEEDOR
			LEFT OUTER JOIN COM_PROVEEDOR CP ON D.CORR_PROVEEDOR=CP.CORR_PROVEEDOR
			INNER JOIN BAN_TIPO_MOVI_BANCARIO E ON A.CORR_EMPRESA=E.CORR_EMPRESA AND A.CORR_TIPO_MOVIMIENTO=E.CORR_TIPO_MOVIMIENTO
			WHERE X.CORR_EMPRESA=@CORR_EMPRESA 			
			AND X.CORR_ARCHIVO=@CORR_ARCHIVO							
			GROUP BY A.CORR_EMPRESA,C.CORR_PROVEEDOR,X.CODIGO_EMPRESARIAL,X.CORRELATIVO,C.DESCRIPCION_PARTIDA,
					D.NUMERO_NIT,ISNULL(CP.CUENTA_BANCARIA,''),X.FECHA_PAGO,D.NOMBRE_PROVEEDOR
			HAVING SUM(B.MONTO_PAGO)>0
			
			SELECT  * FROM @ARCHIVO
		END			
	END
	
FINA:	
END


GO
