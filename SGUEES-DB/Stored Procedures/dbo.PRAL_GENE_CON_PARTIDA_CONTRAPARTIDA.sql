CREATE PROCEDURE [dbo].[PRAL_GENE_CON_PARTIDA_CONTRAPARTIDA]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO_ORIGEN INT,
	@MES_PERIODO_ORIGEN INT,
	@CORR_CLASE_PARTIDA_ORIGEN INT,
	@CORR_PARTIDA_ORIGEN INT,
	@ANIO_PERIODO_NUEVO INT,
	@MES_PERIODO_NUEVO INT,
	@CORR_CLASE_PARTIDA_NUEVO INT = NULL,
	@CORR_PARTIDA_NUEVO INT OUTPUT,
	@CORR_CONTRAPARTIDA INT OUTPUT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
	DECLARE @FECHA_PARTIDA DATE,
		@NOMBRE_PARTIDA VARCHAR(1000),
		@NUMERO_DOCUMENTO VARCHAR(25),
		@CORR_MONEDA INT,
		@FACTOR_CAMBIO DECIMAL(16, 6),
		@OPERADOR VARCHAR(2),
		@FECHA_CREA DATETIME,
		@CORR_PARTIDA_DETA INT,
		@CUENTA_CONTABLE VARCHAR(30),
		@CORR_AUXILIAR INT,
		@CORR_CENTRO_COSTO INT,
		@NOMBRE_TRAN VARCHAR(1255),
		@MONTO_CARGO DECIMAL(12, 2),
		@MONTO_ABONO DECIMAL(12, 2),
		@MONTO_CARGO_FORANEA DECIMAL(12, 2),
		@MONTO_ABONO_FORANEA DECIMAL(12, 2),
		@SYS_FILAS INT,
		@SYS_ERR NUMERIC(38, 0),
		@SYS_MSG NVARCHAR(4000)

BEGIN
	SET NOCOUNT ON
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0,
		@CORR_PARTIDA_NUEVO = 0, @CORR_CONTRAPARTIDA = 0, @FECHA_CREA = GETDATE()

	BEGIN TRY
		IF NOT EXISTS (
			SELECT 1 FROM CON_PARTIDA P
			INNER JOIN CON_PERIODO_CONTABLE PC ON P.CORR_EMPRESA = PC.CORR_EMPRESA
				AND P.ANIO_PERIODO = PC.ANIO_PERIODO AND P.MES_PERIODO = PC.MES_PERIODO
			WHERE P.CORR_EMPRESA = @CORR_EMPRESA
			  AND P.ANIO_PERIODO = @ANIO_PERIODO_ORIGEN
			  AND P.MES_PERIODO = @MES_PERIODO_ORIGEN
			  AND P.CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA_ORIGEN
			  AND P.CORR_PARTIDA = @CORR_PARTIDA_ORIGEN
			  AND P.ESTADO_PARTIDA = 'AP'
			  AND ISNULL(PC.ESTADO_PERIODO_CON, 'AB') = 'CE'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30100,
				@SYS_MENSAJE_ERROR = N'La partida origen no existe, no está aplicada o su período contable no está cerrado.',
				@SYS_FILAS_AFECTADAS = 0
			GOTO FINA
		END

		IF EXISTS (
			SELECT 1 FROM CON_PARTIDA_CONTRAPARTIDA
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND ANIO_PERIODO_ORIGEN = @ANIO_PERIODO_ORIGEN
			  AND MES_PERIODO_ORIGEN = @MES_PERIODO_ORIGEN
			  AND CORR_CLASE_PARTIDA_ORIGEN = @CORR_CLASE_PARTIDA_ORIGEN
			  AND CORR_PARTIDA_ORIGEN = @CORR_PARTIDA_ORIGEN
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30101,
				@SYS_MENSAJE_ERROR = N'Ya existe una contrapartida registrada para esta partida.',
				@SYS_FILAS_AFECTADAS = 0
			GOTO FINA
		END

		IF NOT EXISTS (
			SELECT 1 FROM CON_PERIODO_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND ANIO_PERIODO = @ANIO_PERIODO_NUEVO
			  AND MES_PERIODO = @MES_PERIODO_NUEVO
			  AND ISNULL(ESTADO_PERIODO_CON, 'AB') = 'AB'
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30102,
				@SYS_MENSAJE_ERROR = N'El período destino debe estar abierto en contabilidad.',
				@SYS_FILAS_AFECTADAS = 0
			GOTO FINA
		END

		SELECT @CORR_CLASE_PARTIDA_NUEVO = ISNULL(@CORR_CLASE_PARTIDA_NUEVO, @CORR_CLASE_PARTIDA_ORIGEN)

		IF NOT EXISTS (
			SELECT 1 FROM CON_CLASE_PARTIDA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA_NUEVO
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30103, @SYS_MENSAJE_ERROR = N'Clase de partida destino inválida.', @SYS_FILAS_AFECTADAS = 0
			GOTO FINA
		END

		SELECT @NOMBRE_PARTIDA = LEFT(
				N'Contrapartida aplicada a la partida número ' + CONVERT(VARCHAR(12), @CORR_PARTIDA_ORIGEN)
				+ N' del año ' + CONVERT(VARCHAR(4), @ANIO_PERIODO_ORIGEN)
				+ N' período ' + CONVERT(VARCHAR(2), @MES_PERIODO_ORIGEN),
				1000),
			@NUMERO_DOCUMENTO = NULLIF(LTRIM(RTRIM(P.NUMERO_DOCUMENTO)), ''),
			@CORR_MONEDA = P.CORR_MONEDA,
			@FACTOR_CAMBIO = ISNULL(P.FACTOR_CAMBIO, 1),
			@OPERADOR = ISNULL(P.OPERADOR, '*')
		FROM CON_PARTIDA P
		WHERE P.CORR_EMPRESA = @CORR_EMPRESA
		  AND P.ANIO_PERIODO = @ANIO_PERIODO_ORIGEN
		  AND P.MES_PERIODO = @MES_PERIODO_ORIGEN
		  AND P.CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA_ORIGEN
		  AND P.CORR_PARTIDA = @CORR_PARTIDA_ORIGEN

		SELECT @FECHA_PARTIDA = CONVERT(DATE,
			CONVERT(VARCHAR(4), @ANIO_PERIODO_NUEVO) + '-'
			+ RIGHT('0' + CONVERT(VARCHAR(2), @MES_PERIODO_NUEVO), 2) + '-01')

		SELECT @FECHA_PARTIDA = EOMONTH(@FECHA_PARTIDA)

		BEGIN TRAN

		EXEC PRAL_MTTO_CON_PARTIDA
			1,
			@CORR_EMPRESA,
			@ANIO_PERIODO_NUEVO,
			@MES_PERIODO_NUEVO,
			@CORR_CLASE_PARTIDA_NUEVO,
			@CORR_PARTIDA_NUEVO OUTPUT,
			@FECHA_PARTIDA,
			@NUMERO_DOCUMENTO,
			@NOMBRE_PARTIDA,
			'DI',
			'NOR',
			@CORR_MONEDA,
			@FACTOR_CAMBIO,
			@OPERADOR,
			@SYS_LOGIN_USUARIO,
			@FECHA_CREA,
			@SYS_ESTACION,
			NULL,
			NULL,
			NULL,
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS OUTPUT,
			@SYS_ERR OUTPUT,
			@SYS_MSG OUTPUT

		IF @SYS_ERR <> 0
		BEGIN
			SELECT @SYS_NUMERO_ERROR = @SYS_ERR, @SYS_MENSAJE_ERROR = @SYS_MSG, @SYS_FILAS_AFECTADAS = 0
			ROLLBACK TRAN
			GOTO FINA
		END

		DECLARE curDeta CURSOR LOCAL FAST_FORWARD FOR
		SELECT CORR_PARTIDA_DETA, CUENTA_CONTABLE, CORR_AUXILIAR, CORR_CENTRO_COSTO, NOMBRE_TRAN,
			MONTO_ABONO, MONTO_CARGO,
			ISNULL(MONTO_ABONO_FORANEA, 0), ISNULL(MONTO_CARGO_FORANEA, 0)
		FROM CON_PARTIDA_DETA
		WHERE CORR_EMPRESA = @CORR_EMPRESA
		  AND ANIO_PERIODO = @ANIO_PERIODO_ORIGEN
		  AND MES_PERIODO = @MES_PERIODO_ORIGEN
		  AND CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA_ORIGEN
		  AND CORR_PARTIDA = @CORR_PARTIDA_ORIGEN
		ORDER BY CORR_PARTIDA_DETA

		OPEN curDeta
		FETCH NEXT FROM curDeta INTO @CORR_PARTIDA_DETA, @CUENTA_CONTABLE, @CORR_AUXILIAR, @CORR_CENTRO_COSTO, @NOMBRE_TRAN,
			@MONTO_CARGO, @MONTO_ABONO, @MONTO_CARGO_FORANEA, @MONTO_ABONO_FORANEA

		WHILE @@FETCH_STATUS = 0
		BEGIN
			SET @CORR_PARTIDA_DETA = 0

			EXEC PRAL_MTTO_CON_PARTIDA_DETA
				1,
				@CORR_EMPRESA,
				@ANIO_PERIODO_NUEVO,
				@MES_PERIODO_NUEVO,
				@CORR_CLASE_PARTIDA_NUEVO,
				@CORR_PARTIDA_NUEVO,
				@CORR_PARTIDA_DETA OUTPUT,
				@CUENTA_CONTABLE,
				@CORR_CENTRO_COSTO,
				@MONTO_CARGO,
				@MONTO_ABONO,
				@NOMBRE_TRAN,
				@MONTO_CARGO_FORANEA,
				@MONTO_ABONO_FORANEA,
				NULL,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@SYS_FILAS OUTPUT,
				@SYS_ERR OUTPUT,
				@SYS_MSG OUTPUT,
				@CORR_AUXILIAR

			IF @SYS_ERR <> 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = @SYS_ERR, @SYS_MENSAJE_ERROR = @SYS_MSG, @SYS_FILAS_AFECTADAS = 0
				CLOSE curDeta
				DEALLOCATE curDeta
				ROLLBACK TRAN
				GOTO FINA
			END

			FETCH NEXT FROM curDeta INTO @CORR_PARTIDA_DETA, @CUENTA_CONTABLE, @CORR_AUXILIAR, @CORR_CENTRO_COSTO, @NOMBRE_TRAN,
				@MONTO_CARGO, @MONTO_ABONO, @MONTO_CARGO_FORANEA, @MONTO_ABONO_FORANEA
		END

		CLOSE curDeta
		DEALLOCATE curDeta

		SELECT @CORR_CONTRAPARTIDA = ISNULL(MAX(CORR_CONTRAPARTIDA), 0) + 1
		FROM CON_PARTIDA_CONTRAPARTIDA
		WHERE CORR_EMPRESA = @CORR_EMPRESA

		INSERT INTO CON_PARTIDA_CONTRAPARTIDA
		(
			CORR_EMPRESA, CORR_CONTRAPARTIDA,
			ANIO_PERIODO_ORIGEN, MES_PERIODO_ORIGEN, CORR_CLASE_PARTIDA_ORIGEN, CORR_PARTIDA_ORIGEN,
			ANIO_PERIODO_NUEVO, MES_PERIODO_NUEVO, CORR_CLASE_PARTIDA_NUEVO, CORR_PARTIDA_NUEVO,
			USUARIO_CREA, FECHA_CREA, ESTACION_CREA
		)
		VALUES
		(
			@CORR_EMPRESA, @CORR_CONTRAPARTIDA,
			@ANIO_PERIODO_ORIGEN, @MES_PERIODO_ORIGEN, @CORR_CLASE_PARTIDA_ORIGEN, @CORR_PARTIDA_ORIGEN,
			@ANIO_PERIODO_NUEVO, @MES_PERIODO_NUEVO, @CORR_CLASE_PARTIDA_NUEVO, @CORR_PARTIDA_NUEVO,
			@SYS_LOGIN_USUARIO, @FECHA_CREA, @SYS_ESTACION
		)

		COMMIT TRAN
		SELECT @SYS_FILAS_AFECTADAS = 1
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0 ROLLBACK TRAN
		DECLARE @CORR_BITACORA INT, @SEVERITY_ERROR INT, @ESTADO_ERROR INT,
			@ORIGEN_ERROR NVARCHAR(126), @LINEA_ERROR INT, @SYS_FECHA DATETIME
		SELECT @CORR_BITACORA = 0, @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SEVERITY_ERROR = ERROR_SEVERITY(),
			@ESTADO_ERROR = ERROR_STATE(), @ORIGEN_ERROR = ERROR_PROCEDURE(), @LINEA_ERROR = ERROR_LINE(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(), @SYS_FECHA = GETDATE()
		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1, @CORR_BITACORA OUTPUT, 'PM', @SYS_NUMERO_ERROR, @SEVERITY_ERROR, @ESTADO_ERROR, @ORIGEN_ERROR, @LINEA_ERROR, @SYS_MENSAJE_ERROR, @SYS_LOGIN_USUARIO, @SYS_FECHA, @SYS_ESTACION
	END CATCH
FINA:
END
GO
