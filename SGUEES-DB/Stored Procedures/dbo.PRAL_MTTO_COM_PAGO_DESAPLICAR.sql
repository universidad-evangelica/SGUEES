CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PAGO_DESAPLICAR]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PAGO int OUTPUT,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output,
	@GENERA_MOVIMIENTO_BANCARIO BIT = 1
)
AS
	DECLARE @CORR_MOVIMIENTO INT
BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
		
		IF NOT EXISTS(SELECT 1 FROM CON_PERIODO_CONTABLE
		              WHERE CORR_EMPRESA=@CORR_EMPRESA
		              AND ANIO_PERIODO=@ANIO_PERIODO
		              AND MES_PERIODO=@MES_PERIODO
		              AND ESTADO_PERIODO_COM='AB')
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='El periodo no esta abierto',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		DECLARE	@TEMP1 TABLE (
			  ANIO_PERIODO_COM INT
			, MES_PERIODO_COM INT
			, CORR_DOCUMENTO_COM INT
			, MONTO_PAGO DECIMAL(14,2)
			, ESTA_PROC INT
		)
		
		DECLARE  @USUARIO_ACTU varchar(30)
				,  @FECHA_ACTU datetime
				,  @ESTACION_ACTU varchar(50)
				,  @FECHA_EMISION DATE
		
		DECLARE @CONTADOR INT, @CANTIDAD_REGISTROS INT, @ESTADO_PAGO VARCHAR(2), @HOY DATETIME,
		@ANIO_PERIODO_COM INT, @MES_PERIODO_COM INT, @CORR_DOCUMENTO_COM INT, @MONTO_PAGO DECIMAL(18,2)
		
		SELECT @ESTADO_PAGO=ESTADO_PAGO,
		@CORR_MOVIMIENTO=CORR_MOVIMIENTO
		FROM COM_PAGO  A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PAGO=@CORR_PAGO

		IF @ESTADO_PAGO = 'DI'
		BEGIN
			GOTO FINA
		END
		
		IF @ESTADO_PAGO <> 'AP'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Este pago no se puede desaplicar',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END

		--Se elimina el movimiento bancario	y/o la solicitud de cheque	
		DECLARE @CORR_TIPO_MOVIMIENTO_CHEQUE INT, @ANIO_PERIODO_CHEQUE INT, @MES_PERIODO_CHEQUE INT, @CORR_DOCUMENTO_CHEQUE INT
		DECLARE @CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE INT, @ANIO_PERIODO_SOLI_CHEQUE INT, @MES_PERIODO_SOLI_CHEQUE INT, @CORR_DOCUMENTO_SOLI_CHEQUE INT
		
		SELECT @ANIO_PERIODO_CHEQUE=ANIO_PERIODO_CHEQUE, @MES_PERIODO_CHEQUE=MES_PERIODO_CHEQUE, @CORR_TIPO_MOVIMIENTO_CHEQUE=CORR_TIPO_MOVIMIENTO, @CORR_DOCUMENTO_CHEQUE=CORR_DOCUMENTO_CHEQUE
		, @ANIO_PERIODO_SOLI_CHEQUE=ANIO_PERIODO_SOLI_CHEQUE, @MES_PERIODO_SOLI_CHEQUE=MES_PERIODO_SOLI_CHEQUE, @CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE, @CORR_DOCUMENTO_SOLI_CHEQUE=CORR_DOCUMENTO_SOLI_CHEQUE
		FROM COM_PAGO 
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PAGO=@CORR_PAGO 

		IF EXISTS ( SELECT 1 FROM BAN_DOCUMENTO 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
					AND MES_PERIODO=@MES_PERIODO_CHEQUE 
					AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
					AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
					AND ESTADO_DOCUMENTO='AP' )
		BEGIN
			SELECT @FECHA_EMISION=FECHA_EMISION
			FROM BAN_DOCUMENTO 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
			AND MES_PERIODO=@MES_PERIODO_CHEQUE 
			AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
			AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
			
			--Validamos la fecha de planilla, antes de generar el/los movimiento/s bancario/s
			IF NOT dbo.BAN_ES_FECHA_VALIDA(@CORR_EMPRESA, @FECHA_EMISION) = 1
			BEGIN
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No se permiten movimientos bancarios después de la fecha de cierre.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA		
			END		
		END
		
		IF EXISTS ( SELECT 1 FROM BAN_DOCUMENTO 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
					AND MES_PERIODO=@MES_PERIODO_CHEQUE 
					AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
					AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE 
					AND ESTADO_DOCUMENTO='IM')
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Este pago no se puede desaplicar. El cheque generado ya está impreso.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END 

		
BEGIN TRANSACTION PAGO_DESAPLICAR
        SELECT @HOY=GETDATE()
        
        --Eliminando el movimiento del pago
		DELETE FROM COM_MOVIMIENTO
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_MOVIMIENTO=@CORR_MOVIMIENTO
				
		IF EXISTS ( SELECT 1 FROM BAN_DOCUMENTO 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
					AND MES_PERIODO=@MES_PERIODO_CHEQUE 
					AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
					AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
					AND ESTADO_DOCUMENTO='AP' )
		BEGIN
			
			EXECUTE PRAL_MTTO_BAN_DOCUMENTO_DESAPLICAR
		@CORR_EMPRESA,
			@ANIO_PERIODO_CHEQUE,
			@MES_PERIODO_CHEQUE,
			@CORR_TIPO_MOVIMIENTO_CHEQUE,
			@CORR_DOCUMENTO_CHEQUE OUTPUT,
			@USUARIO_ACTU,
			@HOY,
			@ESTACION_ACTU,
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS_AFECTADAS OUTPUT,
			@SYS_NUMERO_ERROR OUTPUT,
			@SYS_MENSAJE_ERROR OUTPUT
			
			IF @SYS_NUMERO_ERROR<>0
			BEGIN
				IF @@TRANCOUNT>0
					ROLLBACK TRANSACTION PAGO_DESAPLICAR
					
				SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Este pago no se puede desaplicar. El cheque generado no se puede desaplicar.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
			
			DELETE FROM BAN_DOCUMENTO_DETA 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
			AND MES_PERIODO=@MES_PERIODO_CHEQUE 
			AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
			AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
			
			DELETE FROM BAN_DOCUMENTO
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
			AND MES_PERIODO=@MES_PERIODO_CHEQUE 
			AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
			AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
		END
						
		IF EXISTS ( SELECT 1 FROM BAN_SOLI_CHEQUE 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_SOLI_CHEQUE 
					AND MES_PERIODO=@MES_PERIODO_SOLI_CHEQUE 
					AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE 
					AND CORR_DOCUMENTO=@CORR_DOCUMENTO_SOLI_CHEQUE )
		BEGIN
		
			SELECT @ANIO_PERIODO_CHEQUE=ANIO_PERIODO_CHEQUE, @MES_PERIODO_CHEQUE=MES_PERIODO_CHEQUE, @CORR_TIPO_MOVIMIENTO_CHEQUE=CORR_TIPO_MOVIMIENTO_CHEQUE, @CORR_DOCUMENTO_CHEQUE=CORR_DOCUMENTO_CHEQUE
			FROM BAN_SOLI_CHEQUE
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO_SOLI_CHEQUE 
			AND MES_PERIODO=@MES_PERIODO_SOLI_CHEQUE 
			AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE 
			AND CORR_DOCUMENTO=@CORR_DOCUMENTO_SOLI_CHEQUE
			
			IF EXISTS ( SELECT 1 FROM BAN_DOCUMENTO 
						WHERE CORR_EMPRESA=@CORR_EMPRESA 
						AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE 
						AND MES_PERIODO=@MES_PERIODO_CHEQUE 
						AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_CHEQUE 
						AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
						AND ESTADO_DOCUMENTO='AP' )
			BEGIN
				EXECUTE PRAL_MTTO_BAN_DOCUMENTO_DESAPLICAR
		@CORR_EMPRESA,
				@ANIO_PERIODO_CHEQUE,
				@MES_PERIODO_CHEQUE,
				@CORR_TIPO_MOVIMIENTO_CHEQUE,
				@CORR_DOCUMENTO_CHEQUE OUTPUT,
				@USUARIO_ACTU,
				@HOY,
				@ESTACION_ACTU,
				@SYS_LOGIN_USUARIO,
				@SYS_ESTACION,
				@SYS_FILAS_AFECTADAS OUTPUT,
				@SYS_NUMERO_ERROR OUTPUT,
				@SYS_MENSAJE_ERROR OUTPUT
				
				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					IF @@TRANCOUNT>0
						ROLLBACK TRANSACTION PAGO_DESAPLICAR
						
					SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Este pago no se puede desaplicar. El cheque generado no se puede desaplicar.',@SYS_FILAS_AFECTADAS=0
					GOTO FINA
				END
				
				DELETE FROM BAN_SOLI_CHEQUE_DETA 
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO_SOLI_CHEQUE 
				AND MES_PERIODO=@MES_PERIODO_SOLI_CHEQUE 
				AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE 
				AND CORR_DOCUMENTO=@CORR_DOCUMENTO_SOLI_CHEQUE
				
				DELETE FROM BAN_SOLI_CHEQUE 
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO_SOLI_CHEQUE 
				AND MES_PERIODO=@MES_PERIODO_SOLI_CHEQUE 
				AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE 
				AND CORR_DOCUMENTO=@CORR_DOCUMENTO_SOLI_CHEQUE	
			END 
		END	
		
		UPDATE COM_PAGO SET
		ANIO_PERIODO_CHEQUE=NULL,
		MES_PERIODO_CHEQUE=NULL,
		CORR_DOCUMENTO_CHEQUE=NULL,
		ANIO_PERIODO_SOLI_CHEQUE=NULL,
		MES_PERIODO_SOLI_CHEQUE=NULL,
		CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE=NULL,
		CORR_DOCUMENTO_SOLI_CHEQUE=NULL,
		ESTADO_PAGO='DI',
		CORR_MOVIMIENTO=NULL,
		CORR_ARCHIVO=NULL
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO 
		
		--Actualizando el saldo de los documentos
		;WITH CTE_PAGO_X_DOCUMENTO AS
		(
SELECT A.CORR_EMPRESA
			,A.ANIO_PERIODO_COM
			,A.MES_PERIODO_COM
			,A.CORR_DOCUMENTO_COM
			,SUM(B.MONTO_PAGO)MONTO_PAGO
			FROM COM_PAGO_DETA A
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM=B.ANIO_PERIODO_COM AND A.MES_PERIODO_COM=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO_COM=B.CORR_DOCUMENTO_COM
			INNER JOIN COM_PAGO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO=C.ANIO_PERIODO AND B.MES_PERIODO=C.MES_PERIODO AND B.CORR_PAGO=C.CORR_PAGO
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO 
			AND A.CORR_PAGO=@CORR_PAGO			
			AND C.ESTADO_PAGO='AP'
			GROUP BY A.CORR_EMPRESA
			,A.ANIO_PERIODO_COM
			,A.MES_PERIODO_COM
			,A.CORR_DOCUMENTO_COM
		)			
		UPDATE COM_DOCUMENTO SET
		SALDO_DOCUMENTO=A.TOTAL_DOCUMENTO-ISNULL(B.MONTO_PAGO,0)
		FROM COM_DOCUMENTO A
		LEFT OUTER JOIN CTE_PAGO_X_DOCUMENTO B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO_COM AND A.MES_PERIODO=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO=B.CORR_DOCUMENTO_COM		
	
		IF @@TRANCOUNT>0
			COMMIT TRANSACTION PAGO_DESAPLICAR
		
	END TRY
	BEGIN CATCH
	  IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION PAGO_DESAPLICAR
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
