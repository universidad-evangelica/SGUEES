CREATE OR ALTER PROCEDURE [dbo].[PRAL_MTTO_GEN_PROVEEDOR_PERSONA_JURIDICA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@CORR_PERSONA BIGINT = NULL OUTPUT,
	@CORR_PERSONA_JURIDICA BIGINT = NULL OUTPUT,
	@CODIGO_PERSONA VARCHAR(20) = NULL,
	@NOMBRE_EMPRESA VARCHAR(125) = NULL,
	@RAZON_SOCIAL VARCHAR(200) = NULL,
	@GIRO VARCHAR(150) = NULL,
	@ES_EXTRANJERO BIT = 0,
	@DOMICILIADO VARCHAR(2) = NULL,
	@CORR_TIPO_CONTRIBUYENTE INT = NULL,
	@CORR_ACTIVIDAD_ECONOMICA INT = NULL,
	@NUMERO_NIT VARCHAR(50) = NULL,
	@NUMERO_NRC VARCHAR(50) = NULL,
	@DIRECCION VARCHAR(255) = NULL,
	@CORR_PAIS INT = NULL,
	@CORR_DEPTO INT = NULL,
	@CORR_MUNICIPIO INT = NULL,
	@CORR_DISTRITO INT = NULL,
	@TELEFONO_FIJO VARCHAR(50) = NULL,
	@TELEFONO_MOVIL VARCHAR(50) = NULL,
	@CORREO_ELECTRONICO_1 VARCHAR(150) = NULL,
	@CORREO_ELECTRONICO_2 VARCHAR(150) = NULL,
	@SYS_LOGIN_USUARIO VARCHAR(50),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;

	SELECT
		@SYS_NUMERO_ERROR = 0,
		@SYS_MENSAJE_ERROR = N'',
		@SYS_FILAS_AFECTADAS = 0;

	DECLARE @FECHA_AUD DATETIME = GETDATE();

	BEGIN TRY
		IF @TIPO_ACTUALIZA NOT IN (1, 2)
		BEGIN
			SELECT
				@SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'TIPO_ACTUALIZA no válido. Use 1=Insert, 2=Update.',
				@SYS_FILAS_AFECTADAS = 0;
			RETURN;
		END;

		IF ISNULL(@CORR_EMPRESA, 0) <= 0
		BEGIN
			SELECT
				@SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'CORR_EMPRESA es requerido.',
				@SYS_FILAS_AFECTADAS = 0;
			RETURN;
		END;

		SET @NOMBRE_EMPRESA = NULLIF(LTRIM(RTRIM(@NOMBRE_EMPRESA)), N'');
		SET @RAZON_SOCIAL = NULLIF(LTRIM(RTRIM(@RAZON_SOCIAL)), N'');
		SET @GIRO = NULLIF(LTRIM(RTRIM(@GIRO)), N'');
		SET @DOMICILIADO = NULLIF(LTRIM(RTRIM(@DOMICILIADO)), N'');
		SET @NUMERO_NIT = NULLIF(LTRIM(RTRIM(@NUMERO_NIT)), N'');
		SET @NUMERO_NRC = NULLIF(LTRIM(RTRIM(@NUMERO_NRC)), N'');
		SET @DIRECCION = NULLIF(LTRIM(RTRIM(@DIRECCION)), N'');
		SET @TELEFONO_FIJO = NULLIF(LTRIM(RTRIM(@TELEFONO_FIJO)), N'');
		SET @TELEFONO_MOVIL = NULLIF(LTRIM(RTRIM(@TELEFONO_MOVIL)), N'');
		SET @CORREO_ELECTRONICO_1 = NULLIF(LTRIM(RTRIM(@CORREO_ELECTRONICO_1)), N'');
		SET @CORREO_ELECTRONICO_2 = NULLIF(LTRIM(RTRIM(@CORREO_ELECTRONICO_2)), N'');

		IF @RAZON_SOCIAL IS NULL AND @NOMBRE_EMPRESA IS NULL
		BEGIN
			SELECT
				@SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'Debe indicar Nombre empresa o Razón social.',
				@SYS_FILAS_AFECTADAS = 0;
			RETURN;
		END;

		IF @RAZON_SOCIAL IS NULL
			SET @RAZON_SOCIAL = @NOMBRE_EMPRESA;
		IF @NOMBRE_EMPRESA IS NULL
			SET @NOMBRE_EMPRESA = @RAZON_SOCIAL;

		IF @DOMICILIADO IS NOT NULL AND @DOMICILIADO NOT IN (N'SI', N'NO')
		BEGIN
			SELECT
				@SYS_NUMERO_ERROR = 30000,
				@SYS_MENSAJE_ERROR = N'DOMICILIADO inválido. Use SI o NO.',
				@SYS_FILAS_AFECTADAS = 0;
			RETURN;
		END;

		IF ISNULL(@DOMICILIADO, N'') <> N'SI'
		BEGIN
			SET @CORR_DEPTO = NULL;
			SET @CORR_MUNICIPIO = NULL;
			SET @CORR_DISTRITO = NULL;
			IF ISNULL(@DOMICILIADO, N'') <> N'NO'
				SET @CORR_PAIS = NULL;
		END;

		IF ISNULL(@CORR_TIPO_CONTRIBUYENTE, 0) <= 0 SET @CORR_TIPO_CONTRIBUYENTE = NULL;
		IF ISNULL(@CORR_ACTIVIDAD_ECONOMICA, 0) <= 0 SET @CORR_ACTIVIDAD_ECONOMICA = NULL;
		IF ISNULL(@CORR_PAIS, 0) <= 0 SET @CORR_PAIS = NULL;
		IF ISNULL(@CORR_DEPTO, 0) <= 0 SET @CORR_DEPTO = NULL;
		IF ISNULL(@CORR_MUNICIPIO, 0) <= 0 SET @CORR_MUNICIPIO = NULL;
		IF ISNULL(@CORR_DISTRITO, 0) <= 0 SET @CORR_DISTRITO = NULL;

		BEGIN TRANSACTION;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			SELECT @CORR_PERSONA = ISNULL(MAX(CORR_PERSONA), 0) + 1
			FROM dbo.GEN_PERSONA WITH (UPDLOCK, HOLDLOCK);

			IF NULLIF(LTRIM(RTRIM(@CODIGO_PERSONA)), N'') IS NULL
				SET @CODIGO_PERSONA = CONVERT(VARCHAR(20), @CORR_PERSONA);

			INSERT INTO dbo.GEN_PERSONA
			(
				CORR_PERSONA, CODIGO_PERSONA, ACTIVO_PERSONA,
				USUARIO_CREA, ESTACION_CREA, FECHA_CREA,
				USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
			)
			VALUES
			(
				@CORR_PERSONA, @CODIGO_PERSONA, 1,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
			);

			SELECT @CORR_PERSONA_JURIDICA = ISNULL(MAX(CORR_PERSONA_JURIDICA), 0) + 1
			FROM dbo.GEN_PERSONA_JURIDICA WITH (UPDLOCK, HOLDLOCK);

			INSERT INTO dbo.GEN_PERSONA_JURIDICA
			(
				CORR_PERSONA, CORR_PERSONA_JURIDICA,
				NOMBRE_EMPRESA, RAZON_SOCIAL, GIRO,
				ES_EXTRANJERO, DOMICILIADO,
				CORR_TIPO_CONTRIBUYENTE, CORR_ACTIVIDAD_ECONOMICA,
				USUARIO_CREA, ESTACION_CREA, FECHA_CREA,
				USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
			)
			VALUES
			(
				@CORR_PERSONA, @CORR_PERSONA_JURIDICA,
				@NOMBRE_EMPRESA, @RAZON_SOCIAL, @GIRO,
				ISNULL(@ES_EXTRANJERO, 0), @DOMICILIADO,
				@CORR_TIPO_CONTRIBUYENTE, @CORR_ACTIVIDAD_ECONOMICA,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD,
				@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
			);
		END
		ELSE
		BEGIN
			IF ISNULL(@CORR_PERSONA, 0) <= 0
			BEGIN
				SELECT
					@SYS_NUMERO_ERROR = 30000,
					@SYS_MENSAJE_ERROR = N'CORR_PERSONA es requerido para actualizar.',
					@SYS_FILAS_AFECTADAS = 0;
				ROLLBACK TRANSACTION;
				RETURN;
			END;

			IF NOT EXISTS (SELECT 1 FROM dbo.GEN_PERSONA_JURIDICA WHERE CORR_PERSONA = @CORR_PERSONA)
			BEGIN
				SELECT
					@SYS_NUMERO_ERROR = 30000,
					@SYS_MENSAJE_ERROR = N'La persona no es jurídica o no existe.',
					@SYS_FILAS_AFECTADAS = 0;
				ROLLBACK TRANSACTION;
				RETURN;
			END;

			UPDATE dbo.GEN_PERSONA_JURIDICA
			SET
				NOMBRE_EMPRESA = @NOMBRE_EMPRESA,
				RAZON_SOCIAL = @RAZON_SOCIAL,
				GIRO = @GIRO,
				ES_EXTRANJERO = ISNULL(@ES_EXTRANJERO, 0),
				DOMICILIADO = @DOMICILIADO,
				CORR_TIPO_CONTRIBUYENTE = @CORR_TIPO_CONTRIBUYENTE,
				CORR_ACTIVIDAD_ECONOMICA = @CORR_ACTIVIDAD_ECONOMICA,
				USUARIO_ACTU = @SYS_LOGIN_USUARIO,
				ESTACION_ACTU = @SYS_ESTACION,
				FECHA_ACTU = @FECHA_AUD
			WHERE CORR_PERSONA = @CORR_PERSONA;

			SELECT @CORR_PERSONA_JURIDICA = CORR_PERSONA_JURIDICA
			FROM dbo.GEN_PERSONA_JURIDICA
			WHERE CORR_PERSONA = @CORR_PERSONA;

			IF NULLIF(LTRIM(RTRIM(@CODIGO_PERSONA)), N'') IS NOT NULL
			BEGIN
				UPDATE dbo.GEN_PERSONA
				SET CODIGO_PERSONA = @CODIGO_PERSONA,
					USUARIO_ACTU = @SYS_LOGIN_USUARIO,
					ESTACION_ACTU = @SYS_ESTACION,
					FECHA_ACTU = @FECHA_AUD
				WHERE CORR_PERSONA = @CORR_PERSONA;
			END;
		END;

		;MERGE dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD AS T
		USING (
			SELECT @CORR_EMPRESA AS CORR_EMPRESA, @CORR_PERSONA AS CORR_PERSONA, 2 AS CORR_TIPO_DOCUMENTO_IDENTIDAD, @NUMERO_NIT AS VALOR_DOCUMENTO
			WHERE @NUMERO_NIT IS NOT NULL
			UNION ALL
			SELECT @CORR_EMPRESA, @CORR_PERSONA, 3, @NUMERO_NRC WHERE @NUMERO_NRC IS NOT NULL
		) AS S
		ON T.CORR_EMPRESA = S.CORR_EMPRESA
		 AND T.CORR_PERSONA = S.CORR_PERSONA
		 AND T.CORR_TIPO_DOCUMENTO_IDENTIDAD = S.CORR_TIPO_DOCUMENTO_IDENTIDAD
		WHEN MATCHED THEN
			UPDATE SET
				VALOR_DOCUMENTO = S.VALOR_DOCUMENTO,
				USUARIO_ACTU = @SYS_LOGIN_USUARIO,
				ESTACION_ACTU = @SYS_ESTACION,
				FECHA_ACTU = @FECHA_AUD
		WHEN NOT MATCHED THEN
			INSERT (CORR_EMPRESA, CORR_PERSONA, CORR_TIPO_DOCUMENTO_IDENTIDAD, VALOR_DOCUMENTO,
					USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU)
			VALUES (S.CORR_EMPRESA, S.CORR_PERSONA, S.CORR_TIPO_DOCUMENTO_IDENTIDAD, S.VALOR_DOCUMENTO,
					@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD);

		IF @TIPO_ACTUALIZA = 2
		BEGIN
			IF @NUMERO_NIT IS NULL
				DELETE FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 2;
			IF @NUMERO_NRC IS NULL
				DELETE FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_DOCUMENTO_IDENTIDAD = 3;
		END;

		IF @DIRECCION IS NOT NULL OR @CORR_PAIS IS NOT NULL
		BEGIN
			IF EXISTS (
				SELECT 1 FROM dbo.GEN_PERSONA_DOMICILIO
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_DOMICILIO = 1
			)
			BEGIN
				UPDATE dbo.GEN_PERSONA_DOMICILIO
				SET DIRECCION = @DIRECCION,
					CORR_PAIS = @CORR_PAIS,
					CORR_DEPTO = @CORR_DEPTO,
					CORR_MUNICIPIO = @CORR_MUNICIPIO,
					CORR_DISTRITO = @CORR_DISTRITO,
					ACTIVO_DOMICILIO = 1,
					USUARIO_ACTU = @SYS_LOGIN_USUARIO,
					ESTACION_ACTU = @SYS_ESTACION,
					FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_DOMICILIO = 1;
			END
			ELSE
			BEGIN
				INSERT INTO dbo.GEN_PERSONA_DOMICILIO
				(
					CORR_EMPRESA, CORR_PERSONA, CORR_DOMICILIO, DIRECCION,
					CORR_PAIS, CORR_DEPTO, CORR_MUNICIPIO, CORR_DISTRITO, ACTIVO_DOMICILIO,
					USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
				)
				VALUES
				(
					@CORR_EMPRESA, @CORR_PERSONA, 1, @DIRECCION,
					@CORR_PAIS, @CORR_DEPTO, @CORR_MUNICIPIO, @CORR_DISTRITO, 1,
					@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
				);
			END;
		END;

		DECLARE @Contactos TABLE (CORR_TIPO_CONTACTO INT, VALOR VARCHAR(150));
		INSERT INTO @Contactos (CORR_TIPO_CONTACTO, VALOR)
		SELECT 1, @TELEFONO_FIJO WHERE @TELEFONO_FIJO IS NOT NULL
		UNION ALL SELECT 2, @TELEFONO_MOVIL WHERE @TELEFONO_MOVIL IS NOT NULL
		UNION ALL SELECT 3, @CORREO_ELECTRONICO_1 WHERE @CORREO_ELECTRONICO_1 IS NOT NULL
		UNION ALL SELECT 4, @CORREO_ELECTRONICO_2 WHERE @CORREO_ELECTRONICO_2 IS NOT NULL;

		DECLARE @TIPO_C INT, @VALOR_C VARCHAR(150), @CORR_C INT;

		DECLARE curC CURSOR LOCAL FAST_FORWARD FOR
			SELECT CORR_TIPO_CONTACTO, VALOR FROM @Contactos;
		OPEN curC;
		FETCH NEXT FROM curC INTO @TIPO_C, @VALOR_C;
		WHILE @@FETCH_STATUS = 0
		BEGIN
			SELECT TOP (1) @CORR_C = CORR_CONTACTO
			FROM dbo.GEN_PERSONA_CONTACTO
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PERSONA = @CORR_PERSONA
			  AND CORR_TIPO_CONTACTO = @TIPO_C
			ORDER BY CORR_CONTACTO;

			IF @CORR_C IS NOT NULL
			BEGIN
				UPDATE dbo.GEN_PERSONA_CONTACTO
				SET VALOR_CONTACTO = @VALOR_C,
					ACTIVO_CONTACTO = 1,
					USUARIO_ACTU = @SYS_LOGIN_USUARIO,
					ESTACION_ACTU = @SYS_ESTACION,
					FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_CONTACTO = @CORR_C;
			END
			ELSE
			BEGIN
				SELECT @CORR_C = ISNULL(MAX(CORR_CONTACTO), 0) + 1
				FROM dbo.GEN_PERSONA_CONTACTO WITH (UPDLOCK, HOLDLOCK)
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA;

				INSERT INTO dbo.GEN_PERSONA_CONTACTO
				(
					CORR_EMPRESA, CORR_PERSONA, CORR_CONTACTO, VALOR_CONTACTO, ACTIVO_CONTACTO, CORR_TIPO_CONTACTO,
					USUARIO_CREA, ESTACION_CREA, FECHA_CREA, USUARIO_ACTU, ESTACION_ACTU, FECHA_ACTU
				)
				VALUES
				(
					@CORR_EMPRESA, @CORR_PERSONA, @CORR_C, @VALOR_C, 1, @TIPO_C,
					@SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD, @SYS_LOGIN_USUARIO, @SYS_ESTACION, @FECHA_AUD
				);
			END;

			SET @CORR_C = NULL;
			FETCH NEXT FROM curC INTO @TIPO_C, @VALOR_C;
		END;
		CLOSE curC;
		DEALLOCATE curC;

		IF @TIPO_ACTUALIZA = 2
		BEGIN
			IF @TELEFONO_FIJO IS NULL
				UPDATE dbo.GEN_PERSONA_CONTACTO SET ACTIVO_CONTACTO = 0, USUARIO_ACTU = @SYS_LOGIN_USUARIO, ESTACION_ACTU = @SYS_ESTACION, FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_CONTACTO = 1;
			IF @TELEFONO_MOVIL IS NULL
				UPDATE dbo.GEN_PERSONA_CONTACTO SET ACTIVO_CONTACTO = 0, USUARIO_ACTU = @SYS_LOGIN_USUARIO, ESTACION_ACTU = @SYS_ESTACION, FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_CONTACTO = 2;
			IF @CORREO_ELECTRONICO_1 IS NULL
				UPDATE dbo.GEN_PERSONA_CONTACTO SET ACTIVO_CONTACTO = 0, USUARIO_ACTU = @SYS_LOGIN_USUARIO, ESTACION_ACTU = @SYS_ESTACION, FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_CONTACTO = 3;
			IF @CORREO_ELECTRONICO_2 IS NULL
				UPDATE dbo.GEN_PERSONA_CONTACTO SET ACTIVO_CONTACTO = 0, USUARIO_ACTU = @SYS_LOGIN_USUARIO, ESTACION_ACTU = @SYS_ESTACION, FECHA_ACTU = @FECHA_AUD
				WHERE CORR_EMPRESA = @CORR_EMPRESA AND CORR_PERSONA = @CORR_PERSONA AND CORR_TIPO_CONTACTO = 4;
		END;

		COMMIT TRANSACTION;
		SET @SYS_FILAS_AFECTADAS = 1;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION;

		SELECT
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(),
			@SYS_FILAS_AFECTADAS = 0;
	END CATCH;
END
GO
