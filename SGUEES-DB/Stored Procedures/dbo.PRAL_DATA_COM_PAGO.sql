CREATE PROCEDURE [dbo].[PRAL_DATA_COM_PAGO]
(
	@TIPO_CONSULTA int,
	@CORR_EMPRESA int=NULL,
	@ANIO_PERIODO int=NULL,
	@MES_PERIODO int=NULL,
	@CORR_PAGO int=NULL,
	@FECHA_INICIAL DATE=NULL,
	@FECHA_FINAL DATE=NULL,
	@OPCION_CONSULTA int=0
)
AS
BEGIN
	SET NOCOUNT ON

	IF @TIPO_CONSULTA=1 --Todos los campos, todos los registrosl (Mtto)
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT * FROM V_COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND (FECHA_PAGO>=@FECHA_INICIAL OR @FECHA_INICIAL IS NULL)
			AND (FECHA_PAGO<=@FECHA_FINAL OR @FECHA_FINAL IS NULL)
			ORDER BY ANIO_PERIODO DESC, MES_PERIODO DESC, FECHA_PAGO DESC
		END
		IF @OPCION_CONSULTA=1
		BEGIN
			SELECT A.*, CONVERT(BIT,0) SELECCION  
			FROM V_COM_PAGO A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND A.ESTADO_PAGO='DI'
		END
		IF @OPCION_CONSULTA=2 --Pagos a desaplicar
		BEGIN
			SELECT A.* 
			FROM V_COM_PAGO_SELECCION A
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND FECHA_PAGO>=@FECHA_INICIAL
			AND FECHA_PAGO<=@FECHA_FINAL
			AND A.ESTADO_PAGO='AP'
		END
		
	END ELSE
	IF @TIPO_CONSULTA=2 --Algunos campos, todos los registrosl (Combos)
	BEGIN
		SELECT * FROM V_COM_PAGO
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
	END ELSE
	IF @TIPO_CONSULTA=3 --Todos los campos, un solo registro
	BEGIN
		SELECT * FROM V_COM_PAGO
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PAGO=@CORR_PAGO
	END ELSE
	IF @TIPO_CONSULTA=4 --Un campo, un solo registro
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT CORR_EMPRESA FROM V_COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
		END
		IF @OPCION_CONSULTA=1
		BEGIN
			SELECT MONTO_PAGO FROM V_COM_PAGO
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PAGO=@CORR_PAGO
		END ELSE 
		IF @OPCION_CONSULTA=2
		BEGIN	
			SELECT  TOP 1 E.NOMBRE_BENEFICIARIO FROM COM_PAGO A
			INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO
			INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
			INNER JOIN COM_PROVISION_DETA D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.ANIO_PERIODO=D.ANIO_PERIODO_COM AND C.MES_PERIODO=D.MES_PERIODO_COM AND C.CORR_DOCUMENTO=D.CORR_DOCUMENTO_COM
			INNER JOIN COM_PROVISION E ON D.CORR_EMPRESA=E.CORR_EMPRESA AND D.ANIO_PERIODO=E.ANIO_PERIODO AND D.MES_PERIODO=E.MES_PERIODO AND D.CORR_PROVISION=E.CORR_PROVISION
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND A.ANIO_PERIODO=@ANIO_PERIODO
			AND A.MES_PERIODO=@MES_PERIODO
			AND A.CORR_PAGO=@CORR_PAGO
		END
	END

END
GO



