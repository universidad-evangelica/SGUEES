CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PAGO_APLICAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@MES_PERIODO INT,	
	@CORR_PAGO INT,
	@CORR_MOVIMIENTO INT OUTPUT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38,0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT,
	@GENERA_MOVIMIENTO_BANCARIO BIT = 1
)
AS
BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
	
		DECLARE	@TEMP1 TABLE (
			  ANIO_PERIODO_COM INT
			, MES_PERIODO_COM INT
			, CORR_DOCUMENTO_COM INT
			, NOMBRE_CORTO_TIPO_DOC VARCHAR(30)
			, MONTO_PAGO DECIMAL(14,2)
			, ESTA_PROC INT
		)
		DECLARE @TEMP2 TABLE (
			CORR_DETA INT,
			CUENTA_CONTABLE VARCHAR(30),
			CORR_AUXILIAR INT,
			CORR_CENTRO_COSTO INT,
			MONTO_CARGO DECIMAL(18,2),
			MONTO_ABONO DECIMAL(18,2),
			NOMBRE_TRAN VARCHAR(1255),
			ESTA_PROC INT
		)
		
		DECLARE	   @ESTADO_DOCUMENTO VARCHAR(2)		
				,  @SUMA_RESTA INT
				,  @CORR_TIPO_DOC INT
				,  @NUMERO_DOCUMENTO INT
				,  @TIPO_ACTUALIZA int
				,  @CORR_PROVEEDOR int
				,  @FECHA_MOVIMIENTO date
				,  @REFERENCIA varchar(4000)
				,  @TOTAL DECIMAL(14,2)
				,  @MONTO_CARGO DECIMAL(14,2)
				,  @MONTO_ABONO DECIMAL(14,2)
				,  @USUARIO_CREA varchar(30)
				,  @FECHA_CREA datetime
				,  @ESTACION_CREA varchar(50)
				,  @USUARIO_ACTU varchar(30)
				,  @FECHA_ACTU datetime
				,  @ESTACION_ACTU varchar(50)
				,  @ESTADO_MOVIMIENTO varchar(2)
				
				
				
				, @USA_AUXILIARES BIT
		
		DECLARE @CONTADOR INT, @CANTIDAD_REGISTROS INT, @ESTADO_PAGO VARCHAR(2), @HOY DATETIME,
		@ANIO_PERIODO_COM INT, @MES_PERIODO_COM INT, @CORR_DOCUMENTO_COM INT, @MONTO_PAGO DECIMAL(18,2),
		@CORR_TIPO_MOVIMIENTO INT, @PAGO_COMPRAS_GENERA varchar(5), @CONTADOR_DETA INT, @CANTIDAD_REGISTROS_DETA INT,
		@CORR_DETA INT, @CUENTA_CONTABLE VARCHAR(30), @CORR_CENTRO_COSTO INT, @MONTO_CARGO_DETA DECIMAL(18,2), @MONTO_ABONO_DETA DECIMAL(18,2), @NOMBRE_TRAN VARCHAR(1255)
		
		SELECT @USA_AUXILIARES=ISNULL(A.USA_AUXILIARES,0)
		FROM CON_PARAMETRO A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 

		SELECT @ESTADO_PAGO=ESTADO_PAGO, @CORR_TIPO_MOVIMIENTO=CORR_TIPO_MOVIMIENTO 
		FROM COM_PAGO  A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PAGO=@CORR_PAGO
		
		IF @ESTADO_PAGO <> 'DI'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Este pago ya está aplicado o anulado',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		--Agregué esta validación porque me pasó que
		--al desaplicar el pago me permitió desaplicar la compra y modificarla
		--luego quise aplicar el pago y no verificaba que los documentos estaban digitados
		--Alternativamente se puede Aplicar todos los documentos en este mismo procedimiento antes de aplicar el pago
		--tal como se hace en la Aplicacion del Quedan
		IF EXISTS ( SELECT 1 FROM COM_PAGO_DETA A
					INNER JOIN COM_DOCUMENTO B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM=B.ANIO_PERIODO AND A.MES_PERIODO_COM=B.MES_PERIODO AND A.CORR_DOCUMENTO_COM=B.CORR_DOCUMENTO 
					WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
					AND A.ANIO_PERIODO=@ANIO_PERIODO 
					AND A.MES_PERIODO=@MES_PERIODO 
					AND A.CORR_PAGO=@CORR_PAGO 
					AND B.ESTADO_DOCUMENTO<>'AP' )
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Este pago no se puede aplicar. Todos los documentos de compras deben estar aplicados.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END

		IF EXISTS(SELECT 1 FROM COM_PAGO_DETA A
					INNER JOIN COM_DOCUMENTO B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM = B.ANIO_PERIODO AND A.MES_PERIODO_COM = B.MES_PERIODO AND A.CORR_DOCUMENTO_COM = B.CORR_DOCUMENTO
					WHERE A.CORR_EMPRESA=@CORR_EMPRESA
						  AND A.ANIO_PERIODO=@ANIO_PERIODO
						  AND A.MES_PERIODO=@MES_PERIODO
						  AND A.CORR_PAGO=@CORR_PAGO
						  AND B.SALDO_DOCUMENTO=0
		)
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Este pago no se puede aplicar. Uno de los documentos por compra no cuenta con saldo suficiente.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
BEGIN TRANSACTION

        SELECT @HOY=GETDATE(), @REFERENCIA='Pago de '
				
		--Se debe generar un COM_MOVIMIENTO por el pago realizado 		
		SELECT @NUMERO_DOCUMENTO=CORR_PAGO
		, @MONTO_CARGO=CASE WHEN MONTO_PAGO<0 THEN ABS(MONTO_PAGO) ELSE 0 END, @MONTO_ABONO=CASE WHEN MONTO_PAGO>0 THEN MONTO_PAGO ELSE 0 END
		, @CORR_MOVIMIENTO=ISNULL(A.CORR_MOVIMIENTO,0)
		, @CORR_PROVEEDOR=A.CORR_PROVEEDOR
		, @FECHA_MOVIMIENTO=A.FECHA_PAGO 
		, @ESTADO_MOVIMIENTO='AP'
		, @USUARIO_CREA=@SYS_LOGIN_USUARIO 
		, @FECHA_CREA=GETDATE()
		, @ESTACION_CREA=@SYS_ESTACION 
		, @USUARIO_ACTU=@SYS_LOGIN_USUARIO 
		, @FECHA_ACTU=GETDATE()
		, @ESTACION_ACTU=@SYS_ESTACION 			
		FROM COM_PAGO A		
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PAGO=@CORR_PAGO										
				
		SELECT @REFERENCIA='Pago a: '+dbo.StrConcat(LTRIM(RTRIM(D.NOMBRE_CORTO_TIPO_DOC))+' '+LTRIM(RTRIM(CONVERT(VARCHAR,C.NUMERO_DOCUMENTO)))+' US$'+LTRIM(RTRIM(CONVERT(VARCHAR,B.MONTO_PAGO)))+',')
		FROM COM_PAGO A
		INNER JOIN COM_PAGO_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PAGO=B.CORR_PAGO		
		INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
		INNER JOIN GEN_TIPO_DOCUMENTO D ON C.CORR_EMPRESA=D.CORR_EMPRESA AND C.CORR_TIPO_DOC=D.CORR_TIPO_DOC
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PAGO=@CORR_PAGO
				
		SELECT @REFERENCIA=SUBSTRING(LTRIM(RTRIM(@REFERENCIA)),1,LEN(LTRIM(RTRIM(@REFERENCIA)))-1)
		
		IF EXISTS ( SELECT 1 FROM COM_MOVIMIENTO A
					WHERE A.CORR_EMPRESA=@CORR_EMPRESA
					AND A.ANIO_PERIODO=@ANIO_PERIODO
					AND A.MES_PERIODO=@MES_PERIODO					
					AND A.CORR_MOVIMIENTO=@CORR_MOVIMIENTO )
		BEGIN
			SELECT @TIPO_ACTUALIZA=2 --Actualizar
		END ELSE
		BEGIN
			SELECT @TIPO_ACTUALIZA=1 --Adicionar 
		END
			
		EXECUTE PRAL_MTTO_COM_MOVIMIENTO
		   @TIPO_ACTUALIZA
		, @CORR_EMPRESA
		  ,@ANIO_PERIODO
		  ,@MES_PERIODO
		  ,@CORR_TIPO_DOC
		  ,@CORR_MOVIMIENTO OUTPUT
		  ,@CORR_PROVEEDOR
		  ,@FECHA_MOVIMIENTO
		  ,@REFERENCIA
		  ,@MONTO_CARGO
		  ,@MONTO_ABONO
		  ,@USUARIO_CREA
		  ,@FECHA_CREA
		  ,@ESTACION_CREA
		  ,@USUARIO_ACTU
		  ,@FECHA_ACTU
		  ,@ESTACION_ACTU
		  ,@CORR_PAGO 
		  ,@ESTADO_MOVIMIENTO
		  ,@SYS_LOGIN_USUARIO
		  ,@SYS_ESTACION
		  ,@SYS_FILAS_AFECTADAS OUTPUT
		  ,@SYS_NUMERO_ERROR OUTPUT
		  ,@SYS_MENSAJE_ERROR OUTPUT
		
		IF @SYS_NUMERO_ERROR <> 0
		BEGIN
			IF @@TRANCOUNT>0
			BEGIN
				ROLLBACK TRANSACTION
	        END
	        GOTO FINA
		END		
		
		UPDATE COM_PAGO SET				
		CORR_MOVIMIENTO=@CORR_MOVIMIENTO
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PAGO=@CORR_PAGO
		
		--Se genera un movimiento bancario
		IF @GENERA_MOVIMIENTO_BANCARIO=1
		AND EXISTS(SELECT 1 FROM COM_PAGO
				   WHERE CORR_EMPRESA=@CORR_EMPRESA 
				   AND ANIO_PERIODO=@ANIO_PERIODO 
				   AND MES_PERIODO=@MES_PERIODO 
				   AND CORR_PAGO=@CORR_PAGO
				   AND ISNULL(PAGADO_CAJA_CHICA,0)=0)
		BEGIN		
			IF NOT EXISTS ( SELECT 1 FROM BAN_TIPO_MOVI_BANCARIO 
							WHERE CORR_EMPRESA=@CORR_EMPRESA 
							AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO )
			BEGIN
				IF @@TRANCOUNT>0
					ROLLBACK TRANSACTION
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='Este pago no puede generar un movimiento bancario porque no existe el tipo de movimiento seleccionado.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA
			END
			
			DECLARE @CLASE_MOVIMIENTO VARCHAR(3), @ANIO_PERIODO_CHEQUE INT, @MES_PERIODO_CHEQUE INT, @CORR_DOCUMENTO_CHEQUE INT,
			@CORR_CUENTA_BANCO INT, @FECHA_EMISION DATE, @NOMBRE_PARTIDA VARCHAR(1000),@CORR_AUXILIAR INT,
			@FECHA_SOLICITADO DATE, @NOMBRE_BENEFICIARIO VARCHAR(255), @MONTO_DOCUMENTO DECIMAL(18,2), @CORR_TIPO_CHEQUE INT, @CORR_MOVIMIENTO_CHEQUE INT, @CORR_MOVIMIENTO_DESTINO_CHEQUE INT
					
			SELECT @CLASE_MOVIMIENTO=CLASE_MOVIMIENTO
			FROM BAN_TIPO_MOVI_BANCARIO 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO
			
			SELECT @ANIO_PERIODO_CHEQUE=YEAR(A.FECHA_PAGO), @MES_PERIODO_CHEQUE=MONTH(A.FECHA_PAGO), @CORR_DOCUMENTO_CHEQUE=0,
			@CORR_CUENTA_BANCO=A.CORR_CUENTA_BANCO, @NOMBRE_PARTIDA=A.NOMBRE_PARTIDA, @CORR_PROVEEDOR=A.CORR_PROVEEDOR,
			@MONTO_DOCUMENTO=A.MONTO_PAGO, @FECHA_EMISION=A.FECHA_PAGO, @CORR_TIPO_CHEQUE=A.CORR_TIPO_CHEQUE , @FECHA_SOLICITADO=A.FECHA_SOLICITUD,
			@CORR_MOVIMIENTO_CHEQUE=0, @CORR_MOVIMIENTO_DESTINO_CHEQUE=0,@NOMBRE_BENEFICIARIO=CASE WHEN LTRIM(RTRIM(ISNULL(A.NOMBRE_BENEFICIARIO,'')))='' THEN B.NOMBRE_PROVEEDOR ELSE LTRIM(RTRIM(ISNULL(A.NOMBRE_BENEFICIARIO,''))) END
			FROM COM_PAGO A
			INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
			AND A.ANIO_PERIODO=@ANIO_PERIODO 
			AND A.MES_PERIODO=@MES_PERIODO 
			AND A.CORR_PAGO=@CORR_PAGO			


			
			--SELECT @NOMBRE_BENEFICIARIO=NOMBRE_USUARIO 
			--FROM SEG_USUARIO 
			--WHERE CORR_SUSCRIPCION=@CORR_SUSCRIPCION 
			--AND CORR_CONFI_PAIS=@CORR_CONFI_PAIS 
			--AND LOGIN_SISTEMA=@SYS_LOGIN_USUARIO 
			
			--Validando la fecha de emision del cheque
			IF NOT dbo.BAN_ES_FECHA_VALIDA(@CORR_EMPRESA, @FECHA_EMISION) = 1
			BEGIN
				IF @@TRANCOUNT>0
					ROLLBACK TRANSACTION
				SELECT @SYS_NUMERO_ERROR=30000,@SYS_MENSAJE_ERROR='No se permiten movimientos bancarios después de la fecha de cierre.',@SYS_FILAS_AFECTADAS=0
				GOTO FINA		
			END
			
			IF @CLASE_MOVIMIENTO='CHQ'
			BEGIN				
				--Verificamos si genera cheque o solicitud de cheque
				SELECT @PAGO_COMPRAS_GENERA=PAGO_COMPRAS_GENERA
				FROM COM_PARAMETRO 
				WHERE CORR_EMPRESA=@CORR_EMPRESA 				
				
				IF ISNULL(@PAGO_COMPRAS_GENERA,'SOLI')='SOLI'
					--Insertar una solicitud de cheque
					EXEC PRAL_MTTO_BAN_SOLI_CHEQUE 1,@CORR_EMPRESA,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE OUTPUT,
					@CORR_CUENTA_BANCO,@NUMERO_DOCUMENTO,@FECHA_EMISION,@NOMBRE_PARTIDA,@CORR_PROVEEDOR,NULL,NULL,@NOMBRE_BENEFICIARIO,@MONTO_DOCUMENTO,'DI',@SYS_LOGIN_USUARIO,@FECHA_SOLICITADO,NULL,'',@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@CORR_TIPO_CHEQUE,NULL,NULL,NULL,NULL,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT,0
				ELSE
					--Insertar un cheque
					EXEC PRAL_MTTO_BAN_DOCUMENTO 1,@CORR_EMPRESA,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE OUTPUT,
					@CORR_CUENTA_BANCO,@NUMERO_DOCUMENTO,@FECHA_EMISION,@NOMBRE_PARTIDA,@CORR_PROVEEDOR,NULL,NULL,@NOMBRE_BENEFICIARIO,@MONTO_DOCUMENTO,'DI',0,@SYS_LOGIN_USUARIO,'','','','',@FECHA_SOLICITADO,NULL,NULL,'',@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@CORR_MOVIMIENTO_CHEQUE,@CORR_MOVIMIENTO_DESTINO_CHEQUE,@CORR_TIPO_CHEQUE,NULL,NULL,NULL,NULL,NULL,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT,0
					

			
				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					IF @@TRANCOUNT>0
						ROLLBACK TRANSACTION
					GOTO FINA
				END
				
				--Insertando el detalle				
				INSERT INTO @TEMP2 (CORR_DETA,CUENTA_CONTABLE,CORR_AUXILIAR,CORR_CENTRO_COSTO,MONTO_CARGO,MONTO_ABONO,NOMBRE_TRAN,ESTA_PROC)
				SELECT CORR_DETA,CUENTA_CONTABLE,CORR_AUXILIAR,CORR_CENTRO_COSTO,MONTO_CARGO,MONTO_ABONO,NOMBRE_TRAN,0
				FROM COM_PAGO_CONTA 
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO 
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_PAGO=@CORR_PAGO 
				
				SELECT @CANTIDAD_REGISTROS_DETA=COUNT(*), @CONTADOR_DETA=0
				FROM @TEMP2 
				
				WHILE (@CONTADOR_DETA<@CANTIDAD_REGISTROS_DETA)
				BEGIN
					SELECT TOP 1 @CORR_DETA=CORR_DETA,
					@CUENTA_CONTABLE=CUENTA_CONTABLE,
					@CORR_CENTRO_COSTO=CORR_CENTRO_COSTO,
					@MONTO_ABONO_DETA=MONTO_ABONO,
					@MONTO_CARGO_DETA=MONTO_CARGO,
					@NOMBRE_TRAN=NOMBRE_TRAN,
					@CORR_AUXILIAR=CORR_AUXILIAR
					FROM @TEMP2 WHERE ESTA_PROC=0

					--SELECT @CORR_AUXILIAR=NULL

					--SELECT @CORR_AUXILIAR=CASE WHEN @USA_AUXILIARES=1 THEN A.CORR_AUXILIAR ELSE NULL END
					--FROM CON_CATALOGO_CUENTA_AUXI A 
					--WHERE A.CORR_SUSCRIPCION=@CORR_SUSCRIPCION
					--AND A.CORR_CONFI_PAIS=@CORR_CONFI_PAIS
					--AND A.CORR_EMPRESA=@CORR_EMPRESA
					--AND A.CUENTA_CONTABLE=@CUENTA_CONTABLE
					--AND A.CORR_CUENTA_BANCO=@CORR_CUENTA_BANCO
					
					IF ISNULL(@PAGO_COMPRAS_GENERA,'SOLI')='SOLI'
						EXEC PRAL_MTTO_BAN_SOLI_CHEQUE_DETA 1,@CORR_EMPRESA,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE,0,
						@CUENTA_CONTABLE,@CORR_CENTRO_COSTO,@NOMBRE_TRAN,@MONTO_CARGO_DETA,@MONTO_ABONO_DETA,@CORR_AUXILIAR,NULL,NULL,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT
					ELSE
						EXEC PRAL_MTTO_BAN_DOCUMENTO_DETA 1,@CORR_EMPRESA,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE,0,
						@CUENTA_CONTABLE,@CORR_CENTRO_COSTO,@NOMBRE_TRAN,@MONTO_CARGO_DETA,@MONTO_ABONO_DETA,@CORR_AUXILIAR,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT
				
					
					IF @SYS_NUMERO_ERROR<>0
					BEGIN
						IF @@TRANCOUNT>0
							ROLLBACK TRANSACTION
						GOTO FINA
					END
				
					UPDATE @TEMP2 SET ESTA_PROC=1
					WHERE CORR_DETA=@CORR_DETA 
					SELECT @CONTADOR_DETA+=1
				END
				
				IF ISNULL(@PAGO_COMPRAS_GENERA,'SOLI')='SOLI'
					UPDATE BAN_SOLI_CHEQUE SET
					ESTADO_DOCUMENTO='SO', FECHA_SOLICITADO=GETDATE(), SOLICITADO_POR=@SYS_LOGIN_USUARIO  
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_CHEQUE
					AND MES_PERIODO=@MES_PERIODO_CHEQUE
					AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO
					AND CORR_DOCUMENTO=@CORR_DOCUMENTO_CHEQUE
				ELSE
					EXEC PRAL_MTTO_BAN_DOCUMENTO_APLICAR @CORR_EMPRESA,@ANIO_PERIODO_CHEQUE,@MES_PERIODO_CHEQUE,@CORR_TIPO_MOVIMIENTO,@CORR_DOCUMENTO_CHEQUE,
					@SYS_LOGIN_USUARIO,@HOY,@SYS_ESTACION,@SYS_LOGIN_USUARIO,@SYS_ESTACION,@SYS_FILAS_AFECTADAS OUTPUT,@SYS_NUMERO_ERROR OUTPUT,@SYS_MENSAJE_ERROR OUTPUT
				 
				
				--Si el error es por disponibilidad bancaria, 
				--se debe continuar aunque el cheque quede en la cola por autorizar
				IF @SYS_NUMERO_ERROR NOT IN (0, 30002) --Error 30002: disponibilidad bancaria, ver PRAL_MTTO_BAN_DOCUMENTO_APLICAR
				BEGIN
					IF @@TRANCOUNT>0
						ROLLBACK TRANSACTION
					GOTO FINA
				END
				
				IF ISNULL(@PAGO_COMPRAS_GENERA,'SOLI')='SOLI'
					UPDATE COM_PAGO SET
					ESTADO_PAGO='AP', 
					ANIO_PERIODO_SOLI_CHEQUE=@ANIO_PERIODO_CHEQUE, MES_PERIODO_SOLI_CHEQUE=@MES_PERIODO_CHEQUE,
					CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE=@CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO_SOLI_CHEQUE=@CORR_DOCUMENTO_CHEQUE 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO 
					AND MES_PERIODO=@MES_PERIODO 
					AND CORR_PAGO=@CORR_PAGO	
				ELSE
					UPDATE COM_PAGO SET
					ESTADO_PAGO='AP', 
					ANIO_PERIODO_CHEQUE=@ANIO_PERIODO_CHEQUE, MES_PERIODO_CHEQUE=@MES_PERIODO_CHEQUE,
					CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO, CORR_DOCUMENTO_CHEQUE=@CORR_DOCUMENTO_CHEQUE 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO 
					AND MES_PERIODO=@MES_PERIODO 
					AND CORR_PAGO=@CORR_PAGO
					
								
			END ELSE
			BEGIN
				EXEC PRAL_MTTO_BAN_DOCUMENTO 
				1,
		@CORR_EMPRESA,
