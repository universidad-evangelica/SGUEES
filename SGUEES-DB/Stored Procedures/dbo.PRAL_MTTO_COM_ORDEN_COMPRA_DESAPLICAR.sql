CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_ORDEN_COMPRA_DESAPLICAR]
(
	@CORR_EMPRESA INT,
	@ANIO_PERIODO INT,
	@CORR_ORDEN_COMPRA INT,
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38, 0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0
	BEGIN TRY
		IF NOT EXISTS (
			SELECT 1 FROM dbo.COM_ORDEN_COMPRA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
				AND ESTADO_ORDEN IN (N'AP', N'SO')
		)
		BEGIN
			RAISERROR(N'Solo se puede desaplicar una orden aplicada o solicitada.', 16, 1)
		END
		IF EXISTS (
			SELECT 1 FROM dbo.COM_ORDEN_COMPRA_DETA
			WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
				AND ISNULL(CANTIDAD_RECIBIDA, 0) > 0
		)
		BEGIN
			RAISERROR(N'No se puede desaplicar: ya hay cantidad recibida.', 16, 1)
		END

		UPDATE dbo.COM_ORDEN_COMPRA SET
			ESTADO_ORDEN = N'DI',
			USUARIO_AUTORIZA = NULL,
			FECHA_AUTORIZA = NULL,
			USUARIO_ACTU = @SYS_LOGIN_USUARIO,
			FECHA_ACTU = GETDATE(),
			ESTACION_ACTU = @SYS_ESTACION
		WHERE CORR_EMPRESA = @CORR_EMPRESA AND ANIO_PERIODO = @ANIO_PERIODO AND CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA

		SET @SYS_FILAS_AFECTADAS = @@ROWCOUNT
	END TRY
	BEGIN CATCH
		SELECT @SYS_NUMERO_ERROR = ERROR_NUMBER(), @SYS_MENSAJE_ERROR = ERROR_MESSAGE()
	END CATCH
END
GO
