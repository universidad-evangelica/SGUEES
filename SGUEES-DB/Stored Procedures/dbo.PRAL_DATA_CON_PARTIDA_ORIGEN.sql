-- Qué hace: devuelve, de forma informativa, el documento que originó una partida contable.
-- Cómo lo hace: cada componente que genera CORR_PARTIDA aporta un UNION ALL con las mismas tres columnas.
-- Si ninguna fuente apunta a la llave, no devuelve filas (partida manual).
CREATE OR ALTER PROCEDURE [dbo].[PRAL_DATA_CON_PARTIDA_ORIGEN]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_CLASE_PARTIDA int,
	@CORR_PARTIDA int
)
AS
BEGIN
	SET NOCOUNT ON

	SELECT
		O.NUMERO_DETALLE,
		O.TIPO_DOCUMENTO,
		O.DESCRIPCION
	FROM
	(
		-- Provisión: partida generada al aplicar.
		SELECT
			CONVERT(varchar(10), P.ANIO_PERIODO) + ' - ' + CONVERT(varchar(20), P.CORR_PROVISION) AS NUMERO_DETALLE,
			'PROVISION' AS TIPO_DOCUMENTO,
			ISNULL(P.NOMBRE_BENEFICIARIO, '') AS DESCRIPCION
		FROM COM_PROVISION P
		WHERE P.CORR_EMPRESA = @CORR_EMPRESA
		  AND P.ANIO_PERIODO_PARTIDA = @ANIO_PERIODO
		  AND P.MES_PERIODO_PARTIDA = @MES_PERIODO
		  AND P.CORR_CLASE_PARTIDA = @CORR_CLASE_PARTIDA
		  AND P.CORR_PARTIDA = @CORR_PARTIDA

		UNION ALL

		-- Provisión: partida generada al anular.
		SELECT
			CONVERT(varchar(10), P.ANIO_PERIODO) + ' - ' + CONVERT(varchar(20), P.CORR_PROVISION),
			'PROVISION',
			ISNULL(P.NOMBRE_BENEFICIARIO, '')
		FROM COM_PROVISION P
		WHERE P.CORR_EMPRESA = @CORR_EMPRESA
		  AND P.ANIO_PERIODO_PARTIDA_ANULACION = @ANIO_PERIODO
		  AND P.MES_PERIODO_PARTIDA_ANULACION = @MES_PERIODO
		  AND P.CORR_CLASE_PARTIDA_ANULACION = @CORR_CLASE_PARTIDA
		  AND P.CORR_PARTIDA_ANULACION = @CORR_PARTIDA

		-- Siguiente origen: otro UNION ALL con NUMERO_DETALLE, TIPO_DOCUMENTO y DESCRIPCION.
	) O
	ORDER BY O.TIPO_DOCUMENTO, O.NUMERO_DETALLE
END
GO
