CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PROVISION_DETA]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int,
	@CORR_DETA int OUTPUT,
	@ANIO_PERIODO_COM int,
	@MES_PERIODO_COM int,
	@CORR_DOCUMENTO_COM int,
	@MONTO_DOCUMENTO decimal(14,2),
	@MONTO_INICIAL decimal(14,2),
	@MONTO_PAGO decimal(14,2),
	@MONTO_FINAL decimal(14,2),
	@NO_CONTABILIZAR bit=0,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
BEGIN
	
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY
		IF @TIPO_ACTUALIZA=1 --Adicionar
		BEGIN
			SELECT @CORR_DETA=ISNULL(MAX(CORR_DETA),0)+1
			FROM COM_PROVISION_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION

			INSERT INTO COM_PROVISION_DETA
			(CORR_EMPRESA,ANIO_PERIODO,MES_PERIODO,CORR_PROVISION,CORR_DETA,ANIO_PERIODO_COM,MES_PERIODO_COM,CORR_DOCUMENTO_COM,MONTO_DOCUMENTO,MONTO_INICIAL,MONTO_PAGO,MONTO_FINAL)
			VALUES
			(@CORR_EMPRESA,@ANIO_PERIODO,@MES_PERIODO,@CORR_PROVISION,@CORR_DETA,@ANIO_PERIODO_COM,@MES_PERIODO_COM,@CORR_DOCUMENTO_COM,ABS(@MONTO_DOCUMENTO),ABS(@MONTO_INICIAL),ABS(@MONTO_PAGO),ABS(@MONTO_FINAL))									
		END ELSE
		IF @TIPO_ACTUALIZA=2 --Actualizar
		BEGIN
			UPDATE COM_PROVISION_DETA SET
			ANIO_PERIODO_COM=@ANIO_PERIODO_COM,
			MES_PERIODO_COM=@MES_PERIODO_COM,
			CORR_DOCUMENTO_COM=@CORR_DOCUMENTO_COM,
			MONTO_DOCUMENTO=ABS(@MONTO_DOCUMENTO),
			MONTO_INICIAL=ABS(@MONTO_INICIAL),
			MONTO_PAGO=ABS(@MONTO_PAGO),
			MONTO_FINAL=ABS(@MONTO_FINAL)
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			AND CORR_DETA=@CORR_DETA
		END ELSE
		IF @TIPO_ACTUALIZA=3 --Eliminar
		BEGIN
			DELETE FROM COM_PROVISION_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			AND CORR_DETA=@CORR_DETA
		END
				
		DECLARE @TOTAL DECIMAL(18,2)
		
		SELECT @TOTAL=SUM(MONTO_PAGO)
		FROM V_COM_PROVISION_DETA 
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
		
		UPDATE COM_PROVISION SET
		MONTO_PAGO=ISNULL(@TOTAL,0)
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
		
		IF ISNULL(@NO_CONTABILIZAR,0)=0
		BEGIN
			EXEC PRAL_GENE_COM_PROVISION_CONTA
		@CORR_EMPRESA,
			@ANIO_PERIODO,
			@MES_PERIODO,
			@CORR_PROVISION OUTPUT,	
			@SYS_LOGIN_USUARIO,
			@SYS_ESTACION,
			@SYS_FILAS_AFECTADAS output,
			@SYS_NUMERO_ERROR output,
			@SYS_MENSAJE_ERROR output
		END
		
		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT
	
	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO



