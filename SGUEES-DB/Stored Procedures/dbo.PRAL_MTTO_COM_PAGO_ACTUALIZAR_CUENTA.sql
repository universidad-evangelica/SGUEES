CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PAGO_ACTUALIZAR_CUENTA]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_TIPO_MOVIMIENTO int,
	@CORR_PAGO int OUTPUT,
	@CORR_CUENTA_BANCO int,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
BEGIN
	
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
    DECLARE @CORR_CUENTA_BANCO_ANTERIOR INT,@CUENTA_CONTABLE_ANTERIOR VARCHAR(30),@CUENTA_CONTABLE_NUEVA VARCHAR(30)
	BEGIN TRY
		
		IF EXISTS (SELECT 1 FROM COM_PAGO
					WHERE CORR_EMPRESA=@CORR_EMPRESA
					AND ANIO_PERIODO=@ANIO_PERIODO
					AND MES_PERIODO=@MES_PERIODO
					AND CORR_PAGO=@CORR_PAGO
					AND ESTADO_PAGO='DI')
		BEGIN

		---------OBTENIENDO LA NUEVA CUENTA CONTABLE QUE REMPLAZARA A LA ANTERIOR---- 
		   SELECT @CUENTA_CONTABLE_NUEVA=CUENTA_CONTABLE
		   FROM BAN_CUENTA_BANCARIA
		   WHERE CORR_EMPRESA=@CORR_EMPRESA
		   AND CORR_CUENTA_BANCO = @CORR_CUENTA_BANCO
		   
			UPDATE COM_PAGO SET
			CORR_CUENTA_BANCO=@CORR_CUENTA_BANCO			
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			--AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO
			AND CORR_PAGO=@CORR_PAGO
			
		   UPDATE A SET
		   CUENTA_CONTABLE=@CUENTA_CONTABLE_NUEVA
		   FROM COM_PAGO_CONTA A
		   INNER JOIN BAN_CUENTA_BANCARIA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CUENTA_CONTABLE=B.CUENTA_CONTABLE
		   WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		   AND A.ANIO_PERIODO=@ANIO_PERIODO
		   AND A.MES_PERIODO=@MES_PERIODO
		--   AND CORR_TIPO_MOVIMIENTO=@CORR_TIPO_MOVIMIENTO
		   AND A.CORR_PAGO=@CORR_PAGO
		   --AND CUENTA_CONTABLE = @CUENTA_CONTABLE_ANTERIOR
		    
		END

		SELECT @SYS_FILAS_AFECTADAS=@@ROWCOUNT

	END TRY

	BEGIN CATCH
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION
 
	END CATCH;
FINA:
END
GO


