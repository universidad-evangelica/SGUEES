-- Qué hace: alta, toque de auditoría y baja del vínculo GEN_PROVEEDOR_USUARIO.
-- Cómo: no crea ni borra SEG_USUARIO; eso lo hace el API antes o después de este SP.
CREATE OR ALTER PROCEDURE [dbo].[PRAL_MTTO_GEN_PROVEEDOR_USUARIO]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@CORR_PROVEEDOR INT,
	@LOGIN_SISTEMA VARCHAR(30),
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38,0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;

	BEGIN TRY
		IF @TIPO_ACTUALIZA = 1
		BEGIN
			IF NOT EXISTS (
				SELECT 1
				FROM dbo.GEN_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30011, @SYS_MENSAJE_ERROR = N'El proveedor no existe.';
				GOTO FINA;
			END

			IF EXISTS (
				SELECT 1
				FROM dbo.GEN_PROVEEDOR_USUARIO
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
				  AND LOGIN_SISTEMA = @LOGIN_SISTEMA
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30012, @SYS_MENSAJE_ERROR = N'Ese usuario ya está asignado a este proveedor.';
				GOTO FINA;
			END

			INSERT INTO dbo.GEN_PROVEEDOR_USUARIO
			(
				CORR_EMPRESA, CORR_PROVEEDOR, LOGIN_SISTEMA,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA,
				USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_PROVEEDOR, @LOGIN_SISTEMA,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA,
				@USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU
			);
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			UPDATE dbo.GEN_PROVEEDOR_USUARIO
			SET USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			  AND LOGIN_SISTEMA = @LOGIN_SISTEMA;

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30013, @SYS_MENSAJE_ERROR = N'El usuario no está asignado a este proveedor.';
				GOTO FINA;
			END
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.GEN_PROVEEDOR_USUARIO
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			  AND LOGIN_SISTEMA = @LOGIN_SISTEMA;

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30013, @SYS_MENSAJE_ERROR = N'El usuario no está asignado a este proveedor.';
				GOTO FINA;
			END
		END

		SELECT @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
	END TRY
	BEGIN CATCH
		DECLARE
			@CORR_BITACORA INT,
			@SEVERITY_ERROR INT,
			@ESTADO_ERROR INT,
			@ORIGEN_ERROR NVARCHAR(126),
			@LINEA_ERROR INT,
			@SYS_FECHA DATETIME;

		SELECT
			@CORR_BITACORA = 0,
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SEVERITY_ERROR = ERROR_SEVERITY(),
			@ESTADO_ERROR = ERROR_STATE(),
			@ORIGEN_ERROR = ERROR_PROCEDURE(),
			@LINEA_ERROR = ERROR_LINE(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(),
			@SYS_FECHA = GETDATE();

		EXEC dbo.PRAL_MTTO_ADMIN_BITACORA_SISTEMA
			1, @CORR_BITACORA OUTPUT, 'PM', @SYS_NUMERO_ERROR, @SEVERITY_ERROR, @ESTADO_ERROR,
			@ORIGEN_ERROR, @LINEA_ERROR, @SYS_MENSAJE_ERROR, @SYS_LOGIN_USUARIO, @SYS_FECHA, @SYS_ESTACION;
	END CATCH
FINA:
END
GO
