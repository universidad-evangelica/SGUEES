CREATE PROCEDURE [dbo].[PRAL_GENE_COM_ANULACION_PROVISION]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)

AS

BEGIN
	SET NOCOUNT ON
	
	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
	
	BEGIN TRY
		DECLARE	 @ESTADO_PROVISION VARCHAR(2)
		
		SELECT @ESTADO_PROVISION=ESTADO_PROVISION
		FROM COM_PROVISION A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION
		
		IF ISNULL(@ESTADO_PROVISION,'') = ''
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='Esta provisión no existe.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		IF @ESTADO_PROVISION = 'AN'
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Esta provisión ya está anulada.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END
		
		UPDATE COM_PROVISION SET
		ESTADO_PROVISION='AN'
		WHERE CORR_EMPRESA=@CORR_EMPRESA 
		AND ANIO_PERIODO=@ANIO_PERIODO 
		AND MES_PERIODO=@MES_PERIODO 
		AND CORR_PROVISION=@CORR_PROVISION
		SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0
		GOTO FINA
		
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT>0
	  BEGIN
		ROLLBACK TRANSACTION
      END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO


