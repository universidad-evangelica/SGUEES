CREATE PROCEDURE [dbo].[PRAL_MTTO_COM_PROVISION_ANULAR]
(
	@CORR_EMPRESA int,
	@ANIO_PERIODO int,
	@MES_PERIODO int,
	@CORR_PROVISION int OUTPUT,
	@FECHA_ANULACION date,
	@SYS_LOGIN_USUARIO Varchar(30),
	@SYS_ESTACION Varchar(50),
	@SYS_FILAS_AFECTADAS int output,
	@SYS_NUMERO_ERROR numeric(38,0) output,
	@SYS_MENSAJE_ERROR nvarchar(4000) output
)
AS
	DECLARE	@ESTADO_PROVISION VARCHAR(2), @ANIO_PERIODO_PARTIDA INT, @MES_PERIODO_PARTIDA INT, @CORR_CLASE_PARTIDA INT, @CORR_PARTIDA INT
	DECLARE @ANIO_PERIODO_PARTIDA_ANULACION INT, @MES_PERIODO_PARTIDA_ANULACION INT, @CORR_PARTIDA_ANULACION INT
	DECLARE @NUMERO_DOCUMENTO VARCHAR(25), @NOMBRE_PARTIDA VARCHAR(255), @HOY DATETIME, @CLASE_PARTIDA VARCHAR(3)
	DECLARE @CORR_PARTIDA_DETA INT, @CUENTA_CONTABLE VARCHAR(30), @CORR_CENTRO_COSTO INT, @NOMBRE_TRAN VARCHAR(255), @MONTO_CARGO DECIMAL(12,2), @MONTO_ABONO DECIMAL(12,2), @ESTA_CONCILIA BIT, @CORR_AUXILIAR INT
	DECLARE @DETA TABLE (CORR_PARTIDA_DETA INT, CUENTA_CONTABLE VARCHAR(30), CORR_CENTRO_COSTO INT NULL, NOMBRE_TRAN VARCHAR(255), MONTO_CARGO DECIMAL(12,2), MONTO_ABONO DECIMAL(12,2), ESTA_CONCILIA BIT NULL, CORR_AUXILIAR INT NULL)

BEGIN
	SET NOCOUNT ON

	SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

	BEGIN TRY		

		SELECT @ESTADO_PROVISION=ESTADO_PROVISION
		,@ANIO_PERIODO_PARTIDA=ANIO_PERIODO_PARTIDA
		,@MES_PERIODO_PARTIDA=MES_PERIODO_PARTIDA
		,@CORR_CLASE_PARTIDA=CORR_CLASE_PARTIDA
		,@CORR_PARTIDA=CORR_PARTIDA
		,@ANIO_PERIODO_PARTIDA_ANULACION=ISNULL(ANIO_PERIODO_PARTIDA_ANULACION, YEAR(@FECHA_ANULACION))
		,@MES_PERIODO_PARTIDA_ANULACION=ISNULL(MES_PERIODO_PARTIDA_ANULACION, MONTH(@FECHA_ANULACION))
		,@CORR_PARTIDA_ANULACION=ISNULL(CORR_PARTIDA_ANULACION,0)
		,@FECHA_ANULACION=CASE WHEN ESTADO_PROVISION='AN' THEN FECHA_ANULACION ELSE @FECHA_ANULACION END
		FROM COM_PROVISION A
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO
		AND A.CORR_PROVISION=@CORR_PROVISION

		IF ISNULL(@ESTADO_PROVISION,'') = ''
		BEGIN
			SELECT @SYS_NUMERO_ERROR=30001,@SYS_MENSAJE_ERROR='Esta provisión no existe.',@SYS_FILAS_AFECTADAS=0
			GOTO FINA
		END

		--IF @ESTADO_PROVISION = 'AN'
		--BEGIN
		--	SELECT @SYS_NUMERO_ERROR=30002,@SYS_MENSAJE_ERROR='Esta provisión ya está anulada.',@SYS_FILAS_AFECTADAS=0
		--	GOTO FINA
		--END

		BEGIN TRANSACTION COM_PROVI_ANULAR

		IF @ESTADO_PROVISION <> 'AN'
		BEGIN
			IF EXISTS ( SELECT 1 FROM CON_PARTIDA 
						WHERE CORR_EMPRESA=@CORR_EMPRESA 
						AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
						AND MES_PERIODO=@MES_PERIODO_PARTIDA
						AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA 
						AND CORR_PARTIDA=@CORR_PARTIDA
						AND ESTADO_PARTIDA='AP' )
			BEGIN				
				SELECT @ANIO_PERIODO_PARTIDA_ANULACION=YEAR(@FECHA_ANULACION)
				,@MES_PERIODO_PARTIDA_ANULACION=MONTH(@FECHA_ANULACION)
				,@CORR_PARTIDA_ANULACION=0
				,@NUMERO_DOCUMENTO=NUMERO_DOCUMENTO, @NOMBRE_PARTIDA='[Contrapartida] '+NOMBRE_PARTIDA, @HOY=GETDATE(), @CLASE_PARTIDA=CLASE_PARTIDA 
				FROM CON_PARTIDA
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA 
				AND CORR_PARTIDA=@CORR_PARTIDA

				IF NOT EXISTS ( SELECT 1 FROM CON_PERIODO_CONTABLE 
					WHERE CORR_EMPRESA=@CORR_EMPRESA 
					AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA_ANULACION
					AND MES_PERIODO=@MES_PERIODO_PARTIDA_ANULACION
					AND ISNULL(ESTADO_PERIODO_CON,'AB')='AB' )
				BEGIN	
					ROLLBACK TRANSACTION COM_PROVI_ANULAR

					SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='El periodo contable no está abierto, no se puede crear o modificar la contrapartida.'
					GOTO FINA
				END

				INSERT INTO @DETA (CORR_PARTIDA_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO, ESTA_CONCILIA, CORR_AUXILIAR )
				SELECT CORR_PARTIDA_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO, ESTA_CONCILIA, CORR_AUXILIAR 
				FROM CON_PARTIDA_DETA
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
				AND MES_PERIODO=@MES_PERIODO_PARTIDA
				AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
				AND CORR_PARTIDA=@CORR_PARTIDA 				

				EXECUTE PRAL_MTTO_CON_PARTIDA
					1, --Tipo actualiza
		@CORR_EMPRESA,
					@ANIO_PERIODO_PARTIDA_ANULACION,
					@MES_PERIODO_PARTIDA_ANULACION,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA_ANULACION OUTPUT,
					@FECHA_ANULACION,
					@NUMERO_DOCUMENTO,
					@NOMBRE_PARTIDA,
					'DI',
					@CLASE_PARTIDA,
					NULL, NULL, NULL
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT

				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					ROLLBACK TRANSACTION COM_PROVI_ANULAR

					SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede insertar la contrapartida.'
					GOTO FINA
				END

				WHILE EXISTS ( SELECT 1 FROM @DETA )
				BEGIN
					SELECT TOP 1 @CORR_PARTIDA_DETA=CORR_PARTIDA_DETA, @CUENTA_CONTABLE=CUENTA_CONTABLE, @CORR_CENTRO_COSTO=CORR_CENTRO_COSTO, @MONTO_CARGO=MONTO_CARGO, @MONTO_ABONO=MONTO_ABONO, @NOMBRE_TRAN=NOMBRE_TRAN, @ESTA_CONCILIA=ESTA_CONCILIA, @CORR_AUXILIAR=CORR_AUXILIAR 
					FROM @DETA ORDER BY CORR_PARTIDA_DETA


					EXECUTE PRAL_MTTO_CON_PARTIDA_DETA 
						1, --Tipo actualiza
		@CORR_EMPRESA, 
						@ANIO_PERIODO_PARTIDA_ANULACION, 
						@MES_PERIODO_PARTIDA_ANULACION, 
						@CORR_CLASE_PARTIDA, 
						@CORR_PARTIDA_ANULACION, 
						@CORR_PARTIDA_DETA OUTPUT, 
						@CUENTA_CONTABLE, 
						@CORR_CENTRO_COSTO, 
						@MONTO_ABONO, --Monto cargo invertido por el monto abono por ser contrapartida
						@MONTO_CARGO, 
						@NOMBRE_TRAN,
						NULL, NULL, NULL
						@SYS_LOGIN_USUARIO, 
						@SYS_ESTACION, 
						@SYS_FILAS_AFECTADAS OUTPUT, 
						@SYS_NUMERO_ERROR OUTPUT, 
						@SYS_MENSAJE_ERROR OUTPUT

					IF @SYS_NUMERO_ERROR<>0
					BEGIN
						ROLLBACK TRANSACTION COM_PROVI_ANULAR

						SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede insertar el detalle de la contrapartida.'
						GOTO FINA
					END

					DELETE FROM @DETA 
					WHERE CORR_PARTIDA_DETA=@CORR_PARTIDA_DETA
				END

				UPDATE COM_PROVISION SET
				ANIO_PERIODO_PARTIDA_ANULACION=@ANIO_PERIODO_PARTIDA_ANULACION,
				MES_PERIODO_PARTIDA_ANULACION=@MES_PERIODO_PARTIDA_ANULACION,
				CORR_CLASE_PARTIDA_ANULACION=@CORR_CLASE_PARTIDA,
				CORR_PARTIDA_ANULACION=@CORR_PARTIDA_ANULACION
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO 
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_PROVISION=@CORR_PROVISION

				EXECUTE PRAL_MTTO_CON_PARTIDA_APLICAR 
		@CORR_EMPRESA,
					@ANIO_PERIODO_PARTIDA_ANULACION,
					@MES_PERIODO_PARTIDA_ANULACION,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA_ANULACION OUTPUT,
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT

				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					ROLLBACK TRANSACTION COM_PROVI_ANULAR

					SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede aplicar la contrapartida.'
					GOTO FINA
				END
			END

			UPDATE COM_PROVISION SET
			ESTADO_PROVISION='AN',
			FECHA_ANULACION=@FECHA_ANULACION 
			WHERE CORR_EMPRESA=@CORR_EMPRESA 
			AND ANIO_PERIODO=@ANIO_PERIODO 
			AND MES_PERIODO=@MES_PERIODO 
			AND CORR_PROVISION=@CORR_PROVISION
		END ELSE
		BEGIN

			IF EXISTS ( SELECT 1 FROM CON_PARTIDA 
						WHERE CORR_EMPRESA=@CORR_EMPRESA 
						AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA_ANULACION
						AND MES_PERIODO=@MES_PERIODO_PARTIDA_ANULACION
						AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
						AND CORR_PARTIDA=@CORR_PARTIDA_ANULACION
						AND ESTADO_PARTIDA='AP' )
			BEGIN
				EXECUTE PRAL_MTTO_CON_PARTIDA_DESAPLICAR
		@CORR_EMPRESA,
					@ANIO_PERIODO_PARTIDA_ANULACION,
					@MES_PERIODO_PARTIDA_ANULACION,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA_ANULACION OUTPUT,
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT

				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					ROLLBACK TRANSACTION COM_PROVI_ANULAR

					SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede des-aplicar la contrapartida.'
					GOTO FINA
				END

				INSERT INTO @DETA (CORR_PARTIDA_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO, ESTA_CONCILIA, CORR_AUXILIAR )
				SELECT CORR_PARTIDA_DETA, CUENTA_CONTABLE, CORR_CENTRO_COSTO, NOMBRE_TRAN, MONTO_CARGO, MONTO_ABONO, ESTA_CONCILIA, CORR_AUXILIAR 
				FROM CON_PARTIDA_DETA
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA_ANULACION
				AND MES_PERIODO=@MES_PERIODO_PARTIDA_ANULACION
				AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA
				AND CORR_PARTIDA=@CORR_PARTIDA_ANULACION

				WHILE EXISTS ( SELECT 1 FROM @DETA )
				BEGIN
					SELECT TOP 1 @CORR_PARTIDA_DETA=CORR_PARTIDA_DETA, @CUENTA_CONTABLE=CUENTA_CONTABLE, @CORR_CENTRO_COSTO=CORR_CENTRO_COSTO, @MONTO_CARGO=MONTO_CARGO, @MONTO_ABONO=MONTO_ABONO, @NOMBRE_TRAN=NOMBRE_TRAN, @ESTA_CONCILIA=ESTA_CONCILIA, @CORR_AUXILIAR=CORR_AUXILIAR 
					FROM @DETA ORDER BY CORR_PARTIDA_DETA


					EXECUTE PRAL_MTTO_CON_PARTIDA_DETA 
						3, --Tipo Eliminar
		@CORR_EMPRESA, 
						@ANIO_PERIODO_PARTIDA_ANULACION, 
						@MES_PERIODO_PARTIDA_ANULACION, 
						@CORR_CLASE_PARTIDA, 
						@CORR_PARTIDA_ANULACION, 
						@CORR_PARTIDA_DETA OUTPUT, 
						@CUENTA_CONTABLE, 
						@CORR_CENTRO_COSTO, 
						@MONTO_ABONO, --Monto cargo invertido por el monto abono por ser contrapartida
						@MONTO_CARGO, 
						@NOMBRE_TRAN,
						NULL, NULL, NULL
						@SYS_LOGIN_USUARIO, 
						@SYS_ESTACION, 
						@SYS_FILAS_AFECTADAS OUTPUT, 
						@SYS_NUMERO_ERROR OUTPUT, 
						@SYS_MENSAJE_ERROR OUTPUT

					IF @SYS_NUMERO_ERROR<>0
					BEGIN
						ROLLBACK TRANSACTION COM_PROVI_ANULAR

						SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede insertar el detalle de la contrapartida.'
						GOTO FINA
					END

					DELETE FROM @DETA 
					WHERE CORR_PARTIDA_DETA=@CORR_PARTIDA_DETA
				END

				EXECUTE PRAL_MTTO_CON_PARTIDA
					3, --Tipo Eliminar
		@CORR_EMPRESA,
					@ANIO_PERIODO_PARTIDA_ANULACION,
					@MES_PERIODO_PARTIDA_ANULACION,
					@CORR_CLASE_PARTIDA,
					@CORR_PARTIDA_ANULACION OUTPUT,
					@FECHA_ANULACION,
					@NUMERO_DOCUMENTO,
					@NOMBRE_PARTIDA,
					'DI',
					@CLASE_PARTIDA,
					NULL, NULL, NULL
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@HOY,
					@SYS_ESTACION,
					@SYS_LOGIN_USUARIO,
					@SYS_ESTACION,
					@SYS_FILAS_AFECTADAS OUTPUT,
					@SYS_NUMERO_ERROR OUTPUT,
					@SYS_MENSAJE_ERROR OUTPUT

				IF @SYS_NUMERO_ERROR<>0
				BEGIN
					ROLLBACK TRANSACTION COM_PROVI_ANULAR

					SELECT @SYS_FILAS_AFECTADAS=0, @SYS_NUMERO_ERROR=30000, @SYS_MENSAJE_ERROR='No se puede eliminar la contrapartida.'
					GOTO FINA
				END

				UPDATE COM_PROVISION SET
				ANIO_PERIODO_PARTIDA_ANULACION=NULL,
				MES_PERIODO_PARTIDA_ANULACION=NULL,
				CORR_CLASE_PARTIDA_ANULACION=NULL,
				CORR_PARTIDA_ANULACION=NULL
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO 
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_PROVISION=@CORR_PROVISION

			END

			IF EXISTS ( SELECT 1 FROM CON_PARTIDA 
						WHERE CORR_EMPRESA=@CORR_EMPRESA 
						AND ANIO_PERIODO=@ANIO_PERIODO_PARTIDA
						AND MES_PERIODO=@MES_PERIODO_PARTIDA
						AND CORR_CLASE_PARTIDA=@CORR_CLASE_PARTIDA 
						AND CORR_PARTIDA=@CORR_PARTIDA
						AND ESTADO_PARTIDA='AP' )
			BEGIN				
				UPDATE COM_PROVISION SET
				ESTADO_PROVISION='AP',
				FECHA_ANULACION=NULL
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO 
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_PROVISION=@CORR_PROVISION
			END ELSE
			BEGIN
				UPDATE COM_PROVISION SET
				ESTADO_PROVISION='DI',
				FECHA_ANULACION=NULL 
				WHERE CORR_EMPRESA=@CORR_EMPRESA 
				AND ANIO_PERIODO=@ANIO_PERIODO 
				AND MES_PERIODO=@MES_PERIODO 
				AND CORR_PROVISION=@CORR_PROVISION
			END
		END

		UPDATE COM_DOCUMENTO SET
		ESTA_PROVISIONADO=0
		FROM COM_PROVISION A
		INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO AND A.MES_PERIODO=B.MES_PERIODO AND A.CORR_PROVISION=B.CORR_PROVISION
		INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
		WHERE A.CORR_EMPRESA=@CORR_EMPRESA 
		AND A.ANIO_PERIODO=@ANIO_PERIODO 
		AND A.MES_PERIODO=@MES_PERIODO 
		AND A.CORR_PROVISION=@CORR_PROVISION 

		SELECT @SYS_NUMERO_ERROR=0,@SYS_MENSAJE_ERROR='',@SYS_FILAS_AFECTADAS=0

		IF @@TRANCOUNT>0 AND @@ERROR=0
			COMMIT TRANSACTION COM_PROVI_ANULAR

	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT>0
		BEGIN
			ROLLBACK TRANSACTION COM_PROVI_ANULAR
		END
		DECLARE
		@CORR_BITACORA  int,
		@SEVERITY_ERROR  int,
		@ESTADO_ERROR     int,
		@ORIGEN_ERROR nvarchar(126),
		@LINEA_ERROR      int,
		@SYS_FECHA DateTime

		SELECT @CORR_BITACORA=0,
		@SYS_NUMERO_ERROR=ERROR_NUMBER(),
		@SEVERITY_ERROR=ERROR_SEVERITY(),
		@ESTADO_ERROR=ERROR_STATE(),
		@ORIGEN_ERROR=ERROR_PROCEDURE(),
		@LINEA_ERROR=ERROR_LINE(),
		@SYS_MENSAJE_ERROR=ERROR_MESSAGE(),
		@SYS_FECHA=GETDATE()

		EXEC PRAL_MTTO_ADMIN_BITACORA_SISTEMA 1,@CORR_BITACORA output,'PM',@SYS_NUMERO_ERROR,@SEVERITY_ERROR,@ESTADO_ERROR,@ORIGEN_ERROR,@LINEA_ERROR,@SYS_MENSAJE_ERROR,@SYS_LOGIN_USUARIO,@SYS_FECHA,@SYS_ESTACION

	END CATCH;
FINA:
END
GO


