CREATE PROCEDURE [dbo].[PRAL_DATA_COM_PROVISION_DETA]
(
	@TIPO_CONSULTA int,
	@CORR_EMPRESA int=NULL,
	@ANIO_PERIODO int=NULL,
	@MES_PERIODO int=NULL,
	@CORR_PROVISION int=NULL,
	@CORR_DETA int=NULL,
	@OPCION_CONSULTA int=0,
	@ANIO_PERIODO_COM int=NULL,
	@MES_PERIODO_COM int=NULL,
	@CORR_DOCUMENTO int=NULL,
	@CORR_PROVEEDOR int=NULL,
	@NUMERO_DOCUMENTO BIGINT=NULL
)
AS
BEGIN
	SET NOCOUNT ON

	IF @TIPO_CONSULTA=1 --Todos los campos, todos los registrosl (Mtto)
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT * FROM V_COM_PROVISION_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
		END ELSE
		IF @OPCION_CONSULTA=1 --Pendientes de Provisionar
		BEGIN
			SELECT @CORR_PROVEEDOR=CORR_PROVEEDOR
			FROM COM_PROVISION
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			
			SELECT * FROM V_COM_DOCUMENTO_A_PROVISIONAR
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ESTA_PROVISIONADO=0 
			AND CORR_PROVISION IS NULL
			AND SALDO_DOCUMENTO>0
			AND ESTADO_DOCUMENTO='AP'
			AND CORR_PROVEEDOR=@CORR_PROVEEDOR
		END ELSE
		IF @OPCION_CONSULTA=2
		BEGIN
		    SELECT * FROM V_COM_DOCUMENTO_A_PROVISIONAR
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ESTA_PROVISIONADO=0 
			AND CORR_PROVISION IS NULL
			AND SALDO_DOCUMENTO>0
			AND ESTADO_DOCUMENTO='AP'
		END
	END ELSE
	IF @TIPO_CONSULTA=2 --Algunos campos, todos los registrosl (Combos)
	BEGIN
		SELECT * FROM V_COM_PROVISION_DETA
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
	END ELSE
	IF @TIPO_CONSULTA=3 --Todos los campos, un solo registro
	BEGIN
		SELECT * FROM V_COM_PROVISION_DETA
		WHERE CORR_EMPRESA=@CORR_EMPRESA
		AND ANIO_PERIODO=@ANIO_PERIODO
		AND MES_PERIODO=@MES_PERIODO
		AND CORR_PROVISION=@CORR_PROVISION
		AND CORR_DETA=@CORR_DETA
	END ELSE
	IF @TIPO_CONSULTA=4 --Un campo, un solo registro
	BEGIN
		IF @OPCION_CONSULTA=0
		BEGIN
			SELECT CORR_EMPRESA FROM V_COM_PROVISION_DETA
			WHERE CORR_EMPRESA=@CORR_EMPRESA
			AND ANIO_PERIODO=@ANIO_PERIODO
			AND MES_PERIODO=@MES_PERIODO
			AND CORR_PROVISION=@CORR_PROVISION
			AND CORR_DETA=@CORR_DETA
		END ELSE
		IF @OPCION_CONSULTA=1
		BEGIN
			SELECT ISNULL(MAX(A.CORR_DOCUMENTO),0) CORR_DOCUMENTO 
		    FROM V_COM_DOCUMENTO A
			INNER JOIN COM_PROVISION_DETA B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO=B.ANIO_PERIODO_COM AND A.MES_PERIODO=B.MES_PERIODO_COM AND A.CORR_DOCUMENTO=B.CORR_DOCUMENTO_COM
			WHERE A.CORR_EMPRESA=@CORR_EMPRESA
			AND A.ANIO_PERIODO=@ANIO_PERIODO_COM
			AND A.MES_PERIODO=@MES_PERIODO_COM
			AND A.CORR_PROVEEDOR=@CORR_PROVEEDOR
			AND A.NUMERO_DOCUMENTO=@NUMERO_DOCUMENTO
			AND A.ESTADO_DOCUMENTO='DI'
			AND B.ANIO_PERIODO=@ANIO_PERIODO
			AND B.MES_PERIODO=@MES_PERIODO
			AND B.CORR_PROVISION=@CORR_PROVISION
		END
	END

END
GO



