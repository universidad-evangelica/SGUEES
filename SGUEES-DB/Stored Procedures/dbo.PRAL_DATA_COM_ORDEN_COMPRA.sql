CREATE PROCEDURE [dbo].[PRAL_DATA_COM_ORDEN_COMPRA]
(
	@TIPO_CONSULTA INT,
	@CORR_EMPRESA INT = NULL,
	@ANIO_PERIODO INT = NULL,
	@CORR_ORDEN_COMPRA INT = NULL,
	@CORR_CUADRO_COMPARATIVO INT = NULL,
	@LOGIN_SISTEMA VARCHAR(30) = NULL,
	@OPCION_CONSULTA INT = 0,
	@FECHA_INICIAL DATE = NULL,
	@FECHA_FINAL DATE = NULL
)
AS
BEGIN
	SET NOCOUNT ON

	IF @TIPO_CONSULTA = 1
	BEGIN
		SELECT A.*
		FROM dbo.V_COM_ORDEN_COMPRA A
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA
			AND CONVERT(DATE, A.FECHA_ORDEN_COMPRA) >= @FECHA_INICIAL
			AND CONVERT(DATE, A.FECHA_ORDEN_COMPRA) <= @FECHA_FINAL
			AND (
				@OPCION_CONSULTA = 1
				OR NOT EXISTS (
					SELECT 1 FROM dbo.COM_PROVEEDOR_USUARIO U
					WHERE U.LOGIN_SISTEMA = @LOGIN_SISTEMA
				)
				OR EXISTS (
					SELECT 1 FROM dbo.COM_PROVEEDOR_USUARIO U
					WHERE U.LOGIN_SISTEMA = @LOGIN_SISTEMA
						AND U.CORR_PROVEEDOR = A.CORR_PROVEEDOR
				)
			)
		ORDER BY A.NUMERO_ORDEN_COMPRA DESC
	END
	ELSE IF @TIPO_CONSULTA = 2
	BEGIN
		SELECT A.*
		FROM dbo.V_COM_ORDEN_COMPRA A
		WHERE A.CORR_EMPRESA = @CORR_EMPRESA
			AND A.ANIO_PERIODO = @ANIO_PERIODO
			AND A.CORR_ORDEN_COMPRA = @CORR_ORDEN_COMPRA
	END
END
GO
