CREATE OR ALTER PROCEDURE [dbo].[PRAL_DATA_GEN_PROVEEDOR_PERSONA]
(
	@CORR_EMPRESA INT,
	@CORR_PERSONA BIGINT
)
AS
BEGIN
	SET NOCOUNT ON;

	SELECT
		P.CORR_PERSONA,
		P.CODIGO_PERSONA,
		P.ACTIVO_PERSONA,
		CAST(
			CASE
				WHEN PN.CORR_PERSONA IS NOT NULL THEN N'N'
				WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'J'
				ELSE N''
			END AS VARCHAR(1)
		) AS TIPO_PERSONERIA,
		CASE
			WHEN PN.CORR_PERSONA IS NOT NULL THEN N'Natural'
			WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'Jurídico'
			ELSE N''
		END AS NOMBRE_TIPO_PERSONERIA,
		ISNULL(PN.NOMBRE_COMPLETO, ISNULL(PJ.RAZON_SOCIAL, PJ.NOMBRE_EMPRESA)) AS NOMBRE_PERSONA,
		PN.CORR_PERSONA_NATURAL,
		PN.PRIMER_NOMBRE,
		PN.SEGUNDO_NOMBRE,
		PN.PRIMER_APELLIDO,
		PN.SEGUNDO_APELLIDO,
		PJ.CORR_PERSONA_JURIDICA,
		PJ.NOMBRE_EMPRESA,
		PJ.RAZON_SOCIAL,
		PJ.GIRO,
		CAST(ISNULL(PN.ES_EXTRANJERO, PJ.ES_EXTRANJERO) AS BIT) AS ES_EXTRANJERO,
		ISNULL(PN.DOMICILIADO, PJ.DOMICILIADO) AS DOMICILIADO,
		ISNULL(PN.CORR_TIPO_CONTRIBUYENTE, PJ.CORR_TIPO_CONTRIBUYENTE) AS CORR_TIPO_CONTRIBUYENTE,
		TC.NOMBRE_TIPO_CONTRIBUYENTE,
		ISNULL(PN.CORR_ACTIVIDAD_ECONOMICA, PJ.CORR_ACTIVIDAD_ECONOMICA) AS CORR_ACTIVIDAD_ECONOMICA,
		AE.NOMBRE_ACTIVIDAD_ECONOMICA,
		DOC_DIP.VALOR_DOCUMENTO AS NUMERO_DIP,
		DOC_NIT.VALOR_DOCUMENTO AS NUMERO_NIT,
		DOC_NRC.VALOR_DOCUMENTO AS NUMERO_NRC,
		DOM.DIRECCION,
		DOM.CORR_PAIS,
		PA.NOMBRE_PAIS,
		DOM.CORR_DEPTO,
		DE.NOMBRE_DEPTO,
		DOM.CORR_MUNICIPIO,
		MU.NOMBRE_MUNICIPIO,
		DOM.CORR_DISTRITO,
		TEL.VALOR_CONTACTO AS TELEFONO_FIJO,
		CEL.VALOR_CONTACTO AS TELEFONO_MOVIL,
		MAIL1.VALOR_CONTACTO AS CORREO_ELECTRONICO_1,
		MAIL2.VALOR_CONTACTO AS CORREO_ELECTRONICO_2
	FROM dbo.GEN_PERSONA P
	LEFT JOIN dbo.GEN_PERSONA_NATURAL PN ON PN.CORR_PERSONA = P.CORR_PERSONA
	LEFT JOIN dbo.GEN_PERSONA_JURIDICA PJ ON PJ.CORR_PERSONA = P.CORR_PERSONA
	LEFT JOIN dbo.GEN_TIPO_CONTRIBUYENTE TC
		ON TC.CORR_TIPO_CONTRIBUYENTE = ISNULL(PN.CORR_TIPO_CONTRIBUYENTE, PJ.CORR_TIPO_CONTRIBUYENTE)
	LEFT JOIN dbo.GEN_ACTIVIDAD_ECONOMICA AE
		ON AE.CORR_ACTIVIDAD_ECONOMICA = ISNULL(PN.CORR_ACTIVIDAD_ECONOMICA, PJ.CORR_ACTIVIDAD_ECONOMICA)
	OUTER APPLY
	(
		SELECT TOP (1) D.DIRECCION, D.CORR_PAIS, D.CORR_DEPTO, D.CORR_MUNICIPIO, D.CORR_DISTRITO
		FROM dbo.GEN_PERSONA_DOMICILIO D
		WHERE D.CORR_EMPRESA = @CORR_EMPRESA
		  AND D.CORR_PERSONA = P.CORR_PERSONA
		  AND ISNULL(D.ACTIVO_DOMICILIO, 1) = 1
		ORDER BY D.CORR_DOMICILIO
	) DOM
	LEFT JOIN dbo.GEN_PAIS PA ON PA.CORR_PAIS = DOM.CORR_PAIS
	LEFT JOIN dbo.GEN_DEPTO DE ON DE.CORR_PAIS = DOM.CORR_PAIS AND DE.CORR_DEPTO = DOM.CORR_DEPTO
	LEFT JOIN dbo.GEN_MUNICIPIO MU
		ON MU.CORR_PAIS = DOM.CORR_PAIS AND MU.CORR_DEPTO = DOM.CORR_DEPTO AND MU.CORR_MUNICIPIO = DOM.CORR_MUNICIPIO
	OUTER APPLY
	(
		SELECT TOP (1) PD.VALOR_DOCUMENTO
		FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
		WHERE PD.CORR_EMPRESA = @CORR_EMPRESA AND PD.CORR_PERSONA = P.CORR_PERSONA AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 1
	) DOC_DIP
	OUTER APPLY
	(
		SELECT TOP (1) PD.VALOR_DOCUMENTO
		FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
		WHERE PD.CORR_EMPRESA = @CORR_EMPRESA AND PD.CORR_PERSONA = P.CORR_PERSONA AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 2
	) DOC_NIT
	OUTER APPLY
	(
		SELECT TOP (1) PD.VALOR_DOCUMENTO
		FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
		WHERE PD.CORR_EMPRESA = @CORR_EMPRESA AND PD.CORR_PERSONA = P.CORR_PERSONA AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 3
	) DOC_NRC
	OUTER APPLY
	(
		SELECT TOP (1) C.VALOR_CONTACTO
		FROM dbo.GEN_PERSONA_CONTACTO C
		WHERE C.CORR_EMPRESA = @CORR_EMPRESA AND C.CORR_PERSONA = P.CORR_PERSONA
		  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1 AND C.CORR_TIPO_CONTACTO = 1
		ORDER BY C.CORR_CONTACTO
	) TEL
	OUTER APPLY
	(
		SELECT TOP (1) C.VALOR_CONTACTO
		FROM dbo.GEN_PERSONA_CONTACTO C
		WHERE C.CORR_EMPRESA = @CORR_EMPRESA AND C.CORR_PERSONA = P.CORR_PERSONA
		  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1 AND C.CORR_TIPO_CONTACTO = 2
		ORDER BY C.CORR_CONTACTO
	) CEL
	OUTER APPLY
	(
		SELECT TOP (1) C.VALOR_CONTACTO
		FROM dbo.GEN_PERSONA_CONTACTO C
		WHERE C.CORR_EMPRESA = @CORR_EMPRESA AND C.CORR_PERSONA = P.CORR_PERSONA
		  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1 AND C.CORR_TIPO_CONTACTO = 3
		ORDER BY C.CORR_CONTACTO
	) MAIL1
	OUTER APPLY
	(
		SELECT TOP (1) C.VALOR_CONTACTO
		FROM dbo.GEN_PERSONA_CONTACTO C
		WHERE C.CORR_EMPRESA = @CORR_EMPRESA AND C.CORR_PERSONA = P.CORR_PERSONA
		  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1 AND C.CORR_TIPO_CONTACTO = 4
		ORDER BY C.CORR_CONTACTO
	) MAIL2
	WHERE P.CORR_PERSONA = @CORR_PERSONA;
END
GO
