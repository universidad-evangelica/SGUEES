-- Qué hace: alta, cambio y baja de GEN_PROVEEDOR_CUENTA_CONTABLE.
-- Cómo: si la fila queda activa, apaga la otra activa del mismo tipo en la misma transacción.
CREATE OR ALTER PROCEDURE [dbo].[PRAL_MTTO_GEN_PROVEEDOR_CUENTA_CONTABLE]
(
	@TIPO_ACTUALIZA INT,
	@CORR_EMPRESA INT,
	@CORR_PROVEEDOR INT,
	@CORR_CUENTA INT OUTPUT,
	@TIPO_CUENTA VARCHAR(3),
	@CUENTA_CONTABLE VARCHAR(30),
	@ACTIVO BIT,
	@USUARIO_CREA VARCHAR(30),
	@FECHA_CREA DATETIME,
	@ESTACION_CREA VARCHAR(50),
	@USUARIO_ACTU VARCHAR(30),
	@FECHA_ACTU DATETIME,
	@ESTACION_ACTU VARCHAR(50),
	@SYS_LOGIN_USUARIO VARCHAR(30),
	@SYS_ESTACION VARCHAR(50),
	@SYS_FILAS_AFECTADAS INT OUTPUT,
	@SYS_NUMERO_ERROR NUMERIC(38,0) OUTPUT,
	@SYS_MENSAJE_ERROR NVARCHAR(4000) OUTPUT
)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT @SYS_NUMERO_ERROR = 0, @SYS_MENSAJE_ERROR = N'', @SYS_FILAS_AFECTADAS = 0;
	SET @TIPO_CUENTA = UPPER(LTRIM(RTRIM(ISNULL(@TIPO_CUENTA, ''))));
	SET @CUENTA_CONTABLE = LTRIM(RTRIM(ISNULL(@CUENTA_CONTABLE, '')));

	BEGIN TRY
		IF @TIPO_ACTUALIZA IN (1, 2)
		BEGIN
			IF NOT EXISTS (
				SELECT 1
				FROM dbo.GEN_PROVEEDOR
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30021, @SYS_MENSAJE_ERROR = N'El proveedor no existe.';
				GOTO FINA;
			END

			IF @TIPO_CUENTA NOT IN (N'CXP', N'GAS', N'PRO', N'ANT', N'RET', N'IVA', N'DES', N'DEV')
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30022, @SYS_MENSAJE_ERROR = N'Debe seleccionar un tipo de cuenta.';
				GOTO FINA;
			END

			IF NOT EXISTS (
				SELECT 1
				FROM dbo.CON_CATALOGO_CUENTA
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CUENTA_CONTABLE = @CUENTA_CONTABLE
				  AND ES_DETALLE = 1
				  AND ISNULL(NO_HABILITADA, 0) = 0
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30023, @SYS_MENSAJE_ERROR = N'Debe seleccionar una cuenta de detalle habilitada.';
				GOTO FINA;
			END
		END

		BEGIN TRAN;

		IF @TIPO_ACTUALIZA = 1
		BEGIN
			IF @ACTIVO = 1
			BEGIN
				UPDATE dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
				SET ACTIVO = 0,
					USUARIO_ACTU = @USUARIO_ACTU,
					FECHA_ACTU = @FECHA_ACTU,
					ESTACION_ACTU = @ESTACION_ACTU
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
				  AND TIPO_CUENTA = @TIPO_CUENTA
				  AND ACTIVO = 1;
			END

			SELECT @CORR_CUENTA = ISNULL(MAX(CORR_CUENTA), 0) + 1
			FROM dbo.GEN_PROVEEDOR_CUENTA_CONTABLE WITH (UPDLOCK, HOLDLOCK)
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR;

			INSERT INTO dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
			(
				CORR_EMPRESA, CORR_PROVEEDOR, CORR_CUENTA,
				TIPO_CUENTA, CUENTA_CONTABLE, ACTIVO,
				USUARIO_CREA, FECHA_CREA, ESTACION_CREA,
				USUARIO_ACTU, FECHA_ACTU, ESTACION_ACTU
			)
			VALUES
			(
				@CORR_EMPRESA, @CORR_PROVEEDOR, @CORR_CUENTA,
				@TIPO_CUENTA, @CUENTA_CONTABLE, @ACTIVO,
				@USUARIO_CREA, @FECHA_CREA, @ESTACION_CREA,
				@USUARIO_ACTU, @FECHA_ACTU, @ESTACION_ACTU
			);
		END
		ELSE IF @TIPO_ACTUALIZA = 2
		BEGIN
			IF NOT EXISTS (
				SELECT 1
				FROM dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
				  AND CORR_CUENTA = @CORR_CUENTA
			)
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30024, @SYS_MENSAJE_ERROR = N'La cuenta no está asignada a este proveedor.';
				ROLLBACK TRAN;
				GOTO FINA;
			END

			IF @ACTIVO = 1
			BEGIN
				UPDATE dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
				SET ACTIVO = 0,
					USUARIO_ACTU = @USUARIO_ACTU,
					FECHA_ACTU = @FECHA_ACTU,
					ESTACION_ACTU = @ESTACION_ACTU
				WHERE CORR_EMPRESA = @CORR_EMPRESA
				  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
				  AND TIPO_CUENTA = @TIPO_CUENTA
				  AND ACTIVO = 1
				  AND CORR_CUENTA <> @CORR_CUENTA;
			END

			UPDATE dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
			SET TIPO_CUENTA = @TIPO_CUENTA,
				CUENTA_CONTABLE = @CUENTA_CONTABLE,
				ACTIVO = @ACTIVO,
				USUARIO_ACTU = @USUARIO_ACTU,
				FECHA_ACTU = @FECHA_ACTU,
				ESTACION_ACTU = @ESTACION_ACTU
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			  AND CORR_CUENTA = @CORR_CUENTA;
		END
		ELSE IF @TIPO_ACTUALIZA = 3
		BEGIN
			DELETE FROM dbo.GEN_PROVEEDOR_CUENTA_CONTABLE
			WHERE CORR_EMPRESA = @CORR_EMPRESA
			  AND CORR_PROVEEDOR = @CORR_PROVEEDOR
			  AND CORR_CUENTA = @CORR_CUENTA;

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT @SYS_NUMERO_ERROR = 30024, @SYS_MENSAJE_ERROR = N'La cuenta no está asignada a este proveedor.';
				ROLLBACK TRAN;
				GOTO FINA;
			END
		END
		ELSE
		BEGIN
			SELECT @SYS_NUMERO_ERROR = 30020, @SYS_MENSAJE_ERROR = N'Tipo de actualización no válido.';
			ROLLBACK TRAN;
			GOTO FINA;
		END

		SELECT @SYS_FILAS_AFECTADAS = @@ROWCOUNT;
		COMMIT TRAN;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRAN;

		DECLARE
			@CORR_BITACORA INT,
			@SEVERITY_ERROR INT,
			@ESTADO_ERROR INT,
			@ORIGEN_ERROR NVARCHAR(126),
			@LINEA_ERROR INT,
			@SYS_FECHA DATETIME;

		SELECT
			@CORR_BITACORA = 0,
			@SYS_NUMERO_ERROR = ERROR_NUMBER(),
			@SEVERITY_ERROR = ERROR_SEVERITY(),
			@ESTADO_ERROR = ERROR_STATE(),
			@ORIGEN_ERROR = ERROR_PROCEDURE(),
			@LINEA_ERROR = ERROR_LINE(),
			@SYS_MENSAJE_ERROR = ERROR_MESSAGE(),
			@SYS_FECHA = GETDATE();

		EXEC dbo.PRAL_MTTO_ADMIN_BITACORA_SISTEMA
			1, @CORR_BITACORA OUTPUT, 'PM', @SYS_NUMERO_ERROR, @SEVERITY_ERROR, @ESTADO_ERROR,
			@ORIGEN_ERROR, @LINEA_ERROR, @SYS_MENSAJE_ERROR, @SYS_LOGIN_USUARIO, @SYS_FECHA, @SYS_ESTACION;
	END CATCH
FINA:
END
GO
