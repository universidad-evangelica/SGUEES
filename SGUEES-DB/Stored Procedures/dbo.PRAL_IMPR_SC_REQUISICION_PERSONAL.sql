-- =============================================================================
-- Procedimiento: dbo.PRAL_IMPR_SC_REQUISICION_PERSONAL
-- Qué hace: datos para XtraReport rptRequisicionPersonal (1 fila).
-- Parámetros: @CORR_EMPRESA, @CORR_REQUISICION_PERSONAL
-- Consumo: SGUEES-RPT Layouts/SelectionHiring/SelectionHiring.aspx
--   ?fuente=sc-requisicion-personal&report=rptRequisicionPersonal&...
--
-- Vacante (CORR_TIPO_VACANTE):
--   1 = Promoción | 2 = Transferencia | 3 = Renuncia
--   4 = Nueva creación | 5 = Otro
--
-- Aprobaciones (flujo 101 — V_SEG_FLUJO_BITACORA_FIRMAS):
--   Última firma por ESTADO_DESTINO:
--     Aprobado JI → JEFE INMEDIATO
--     Aprobado JU → DECANO / GERENTE / DIRECTOR
--     Aprobado GG → VRA / VRITE / VRIV / GG / DIGGEI
--   Nombre firmante:
--     LOGIN_SISTEMA → GEN_PERSONA_USUARIO.CORR_PERSONA
--                  → GEN_EMPLEADO (CORR_PERSONA + CORR_EMPRESA)
--                  → GEN_PERSONA_NATURAL.NOMBRE_COMPLETO
--     Fallback: LOGIN_SISTEMA si no hay empleado/persona.
-- =============================================================================
CREATE OR ALTER PROCEDURE [dbo].[PRAL_IMPR_SC_REQUISICION_PERSONAL]
(
	@CORR_EMPRESA INT,
	@CORR_REQUISICION_PERSONAL INT
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @TipoDocumentoRequisicion INT = 101;

	SELECT
		R.CORR_EMPRESA,
		R.CORR_REQUISICION_PERSONAL,
		R.CANTIDAD_PLAZAS,
		ISNULL(P.NOMBRE_PUESTO, N'') AS NOMBRE_PUESTO,
		ISNULL(U.NOMBRE_UNIDAD, N'') AS NOMBRE_UNIDAD,
		R.SALARIO,
		ISNULL(R.HORARIO, N'') AS HORARIO,
		ISNULL(R.JUSTIFICACION, N'') AS JUSTIFICACION,
		R.CORR_TIPO_VACANTE,
		ISNULL(PN.NOMBRE_COMPLETO, N'') AS NOMBRE_EMPLEADO_SUSTITUTO,
		/* Texto por línea: solo la del tipo de vacante lleva el nombre */
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 1 THEN ISNULL(PN.NOMBRE_COMPLETO, N'') ELSE N'' END AS NVARCHAR(250)) AS TEXTO_PROMOCION,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 2 THEN ISNULL(PN.NOMBRE_COMPLETO, N'') ELSE N'' END AS NVARCHAR(250)) AS TEXTO_TRANSFERENCIA,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 3 THEN ISNULL(PN.NOMBRE_COMPLETO, N'') ELSE N'' END AS NVARCHAR(250)) AS TEXTO_RENUNCIA,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 4 THEN ISNULL(PN.NOMBRE_COMPLETO, N'') ELSE N'' END AS NVARCHAR(250)) AS TEXTO_NUEVA_CREACION,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 5 THEN ISNULL(PN.NOMBRE_COMPLETO, N'') ELSE N'' END AS NVARCHAR(250)) AS TEXTO_OTROS,
		CASE
			WHEN ISNULL(TC.ES_PERMANENTE, 1) = 0 AND ISNULL(R.TIEMPO_CONTRATO, 0) > 0
				THEN CAST(R.TIEMPO_CONTRATO AS NVARCHAR(20)) + N' mes(es)'
			ELSE N''
		END AS TIEMPO_CONTRATO_TXT,
		CAST(NULL AS DATE) AS FECHA_DESDE,
		CAST(NULL AS DATE) AS FECHA_HASTA,
		/* Modalidad */
		CAST(CASE WHEN ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Presencial%' THEN 1 ELSE 0 END AS BIT) AS CHK_PRESENCIAL,
		CAST(CASE
			WHEN ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Teletrabajo%Total%'
			  OR (ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Teletrabajo%' AND ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Total%')
			THEN 1 ELSE 0 END AS BIT) AS CHK_TELETRABAJO_TOTAL,
		CAST(CASE
			WHEN ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Teletrabajo%Parcial%'
			  OR (ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Teletrabajo%' AND ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Parcial%')
			  OR ISNULL(M.MODALIDAD_NOMBRE, N'') LIKE N'%Parcial%'
			THEN 1 ELSE 0 END AS BIT) AS CHK_TELETRABAJO_PARCIAL,
		/* Contratación */
		CAST(CASE WHEN ISNULL(TC.ES_PERMANENTE, 0) = 1 THEN 1 ELSE 0 END AS BIT) AS CHK_PERMANENTE,
		CAST(CASE WHEN ISNULL(TC.ES_PERMANENTE, 1) = 0 THEN 1 ELSE 0 END AS BIT) AS CHK_TEMPORAL,
		/* Vacante por CORR_TIPO_VACANTE (1..5) */
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 1 THEN 1 ELSE 0 END AS BIT) AS CHK_PROMOCION,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 2 THEN 1 ELSE 0 END AS BIT) AS CHK_TRANSFERENCIA,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 3 THEN 1 ELSE 0 END AS BIT) AS CHK_RENUNCIA,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 4 THEN 1 ELSE 0 END AS BIT) AS CHK_NUEVA_CREACION,
		CAST(CASE WHEN R.CORR_TIPO_VACANTE = 5 THEN 1 ELSE 0 END AS BIT) AS CHK_OTROS,
		/* Aprobaciones — última firma por estado (flujo 101) */
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(JI.NOMBRE_FIRMANTE)), N''), ISNULL(JI.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_JEFE_INMEDIATO,
		JI.FECHA_ACCION AS FECHA_JEFE_INMEDIATO,
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(JU.NOMBRE_FIRMANTE)), N''), ISNULL(JU.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_DECANO_GERENTE,
		JU.FECHA_ACCION AS FECHA_DECANO_GERENTE,
		CAST(ISNULL(NULLIF(LTRIM(RTRIM(GG.NOMBRE_FIRMANTE)), N''), ISNULL(GG.LOGIN_SISTEMA, N'')) AS NVARCHAR(150)) AS NOMBRE_VRA,
		GG.FECHA_ACCION AS FECHA_VRA,
		ISNULL(E.NOMBRE_EMPRESA, N'') AS NOMBRE_EMPRESA
	FROM dbo.SC_REQUISICION_PERSONAL AS R
	LEFT JOIN dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS U
		ON U.CORR_EMPRESA = R.CORR_EMPRESA
	   AND U.CORR_UNIDAD = R.CORR_UNIDAD
	LEFT JOIN dbo.PLA_PUESTO AS P
		ON P.CORR_EMPRESA = R.CORR_EMPRESA
	   AND P.CORR_PUESTO = R.CORR_PUESTO
	LEFT JOIN dbo.SC_TIPO_MODALIDAD AS M
		ON M.CORR_EMPRESA = R.CORR_EMPRESA
	   AND M.CORR_TIPO_MODALIDAD = R.CORR_TIPO_MODALIDAD
	LEFT JOIN dbo.SC_TIPO_CONTRATACION AS TC
		ON TC.CORR_EMPRESA = R.CORR_EMPRESA
	   AND TC.CORR_TIPO_CONTRATACION = R.CORR_TIPO_CONTRATACION
	LEFT JOIN dbo.GEN_EMPRESA AS E
		ON E.CORR_EMPRESA = R.CORR_EMPRESA
	/* Empleado sustituto: CORR → nombre (cuando aplique) */
	LEFT JOIN dbo.GEN_EMPLEADO AS EMP
		ON EMP.CORR_EMPRESA = R.CORR_EMPRESA
	   AND EMP.CORR_EMPLEADO = TRY_CAST(NULLIF(LTRIM(RTRIM(CAST(R.CORR_EMPLEADO_SUSTITUTO AS NVARCHAR(50)))), N'') AS INT)
	LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN
		ON PN.CORR_PERSONA = EMP.CORR_PERSONA
	/* Última aprobación JI */
	OUTER APPLY (
		SELECT TOP (1)
			B.LOGIN_SISTEMA,
			B.FECHA_ACCION,
			PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU
			ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F
			ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA
		   AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F
			ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = R.CORR_EMPRESA
		  AND B.CORR_TIPO_DOCUMENTO = @TipoDocumentoRequisicion
		  AND B.CORR_DOCUMENTO = R.CORR_REQUISICION_PERSONAL
		  AND B.ESTADO_DESTINO = N'Aprobado JI'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS JI
	/* Última aprobación JU */
	OUTER APPLY (
		SELECT TOP (1)
			B.LOGIN_SISTEMA,
			B.FECHA_ACCION,
			PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU
			ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F
			ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA
		   AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F
			ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = R.CORR_EMPRESA
		  AND B.CORR_TIPO_DOCUMENTO = @TipoDocumentoRequisicion
		  AND B.CORR_DOCUMENTO = R.CORR_REQUISICION_PERSONAL
		  AND B.ESTADO_DESTINO = N'Aprobado JU'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS JU
	/* Última aprobación GG */
	OUTER APPLY (
		SELECT TOP (1)
			B.LOGIN_SISTEMA,
			B.FECHA_ACCION,
			PN_F.NOMBRE_COMPLETO AS NOMBRE_FIRMANTE
		FROM dbo.V_SEG_FLUJO_BITACORA_FIRMAS AS B
		LEFT JOIN dbo.GEN_PERSONA_USUARIO AS PU
			ON LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = LTRIM(RTRIM(B.LOGIN_SISTEMA))
		LEFT JOIN dbo.GEN_EMPLEADO AS EMP_F
			ON EMP_F.CORR_PERSONA = PU.CORR_PERSONA
		   AND EMP_F.CORR_EMPRESA = B.CORR_EMPRESA
		LEFT JOIN dbo.GEN_PERSONA_NATURAL AS PN_F
			ON PN_F.CORR_PERSONA = EMP_F.CORR_PERSONA
		WHERE B.CORR_EMPRESA = R.CORR_EMPRESA
		  AND B.CORR_TIPO_DOCUMENTO = @TipoDocumentoRequisicion
		  AND B.CORR_DOCUMENTO = R.CORR_REQUISICION_PERSONAL
		  AND B.ESTADO_DESTINO = N'Aprobado GG'
		ORDER BY B.FECHA_ACCION DESC, B.CORR_BITACORA DESC
	) AS GG
	WHERE R.CORR_EMPRESA = @CORR_EMPRESA
	  AND R.CORR_REQUISICION_PERSONAL = @CORR_REQUISICION_PERSONAL;
END;
GO
