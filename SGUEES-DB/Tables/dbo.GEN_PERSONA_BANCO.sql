-- Qué hace: cuentas bancarias de una persona (N filas; una sola por defecto).
-- Cómo: PK (CORR_EMPRESA, CORR_PERSONA, CORR_PERSONA_BANCO); FK a GEN_BANCO.
--       POR_DEFECTO: índice único filtrado, una fila por persona y empresa.
SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO

IF OBJECT_ID(N'dbo.GEN_PERSONA_BANCO', N'U') IS NULL
BEGIN
	CREATE TABLE [dbo].[GEN_PERSONA_BANCO]
	(
		[CORR_EMPRESA] [int] NOT NULL,
		[CORR_PERSONA] [bigint] NOT NULL,
		[CORR_PERSONA_BANCO] [int] NOT NULL,
		[CORR_BANCO] [int] NOT NULL,
		[CUENTA_BANCARIA] [varchar](30) NOT NULL,
		[POR_DEFECTO] [bit] NOT NULL CONSTRAINT [DF_GEN_PERSONA_BANCO_POR_DEFECTO] DEFAULT (0),
		[USUARIO_CREA] [varchar](50) NULL,
		[FECHA_CREA] [datetime] NULL,
		[ESTACION_CREA] [varchar](50) NULL,
		[USUARIO_ACTU] [varchar](50) NULL,
		[FECHA_ACTU] [datetime] NULL,
		[ESTACION_ACTU] [varchar](50) NULL,
		CONSTRAINT [PK_GEN_PERSONA_BANCO] PRIMARY KEY CLUSTERED
		(
			[CORR_EMPRESA] ASC,
			[CORR_PERSONA] ASC,
			[CORR_PERSONA_BANCO] ASC
		)
	);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_EMPRESA'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_EMPRESA]
		FOREIGN KEY ([CORR_EMPRESA]) REFERENCES [dbo].[GEN_EMPRESA] ([CORR_EMPRESA]);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_PERSONA'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_PERSONA]
		FOREIGN KEY ([CORR_PERSONA]) REFERENCES [dbo].[GEN_PERSONA] ([CORR_PERSONA]);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_BANCO_GEN_BANCO'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_BANCO_GEN_BANCO]
		FOREIGN KEY ([CORR_EMPRESA], [CORR_BANCO])
		REFERENCES [dbo].[GEN_BANCO] ([CORR_EMPRESA], [CORR_BANCO]);
END
GO

IF COL_LENGTH(N'dbo.GEN_PERSONA_BANCO', N'POR_DEFECTO') IS NULL
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_BANCO]
	ADD [POR_DEFECTO] [bit] NOT NULL
		CONSTRAINT [DF_GEN_PERSONA_BANCO_POR_DEFECTO] DEFAULT (0);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.indexes
	WHERE name = N'UX_GEN_PERSONA_BANCO_DEFECTO'
	  AND object_id = OBJECT_ID(N'dbo.GEN_PERSONA_BANCO')
)
BEGIN
	CREATE UNIQUE INDEX [UX_GEN_PERSONA_BANCO_DEFECTO]
	ON [dbo].[GEN_PERSONA_BANCO] ([CORR_EMPRESA], [CORR_PERSONA])
	WHERE [POR_DEFECTO] = 1;
END
GO
