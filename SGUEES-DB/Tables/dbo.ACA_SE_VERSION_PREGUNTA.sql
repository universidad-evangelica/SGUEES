CREATE TABLE [dbo].[ACA_SE_VERSION_PREGUNTA]
(
	[CORR_VERSION_PREGUNTA] [int] IDENTITY(1,1) NOT NULL,
	[CORR_VERSION] [int] NOT NULL,
	[CORR_PREGUNTA] [int] NOT NULL,
	[CORR_SECCION_SE] [int] NULL,
	[ORDEN] [int] NOT NULL,
	[PUNTAJE] [decimal](10,2) NOT NULL,
	[ES_REQUERIDO] [bit] NOT NULL,
	[ROL_MONTO] [varchar](20) NULL,
	[CORR_PREGUNTA_BRUTO] [int] NULL,
	[CORR_PREGUNTA_DESCUENTO] [int] NULL,
	[ACTIVO] [bit] NOT NULL,
	[USUARIO_CREA] [varchar](100) NOT NULL,
	[ESTACION_CREA] [varchar](50) NOT NULL,
	[FECHA_CREA] [datetime] NOT NULL,
	[USUARIO_ACTU] [varchar](100) NULL,
	[ESTACION_ACTU] [varchar](50) NULL,
	[FECHA_ACTU] [datetime] NULL,
	CONSTRAINT [PK_ACA_SE_VERSION_PREGUNTA_V4] PRIMARY KEY CLUSTERED ([CORR_VERSION_PREGUNTA] ASC),
	CONSTRAINT [CK_ACA_SE_VP_ROL_MONTO] CHECK ([ROL_MONTO] IS NULL OR [ROL_MONTO] IN (N'BRUTO', N'DESCUENTO', N'LIQUIDO', N'MONTO')),
	CONSTRAINT [CK_ACA_SE_VP_LIQUIDO_ASOC] CHECK (
		(
			[ROL_MONTO] = N'LIQUIDO'
			AND (
				([CORR_PREGUNTA_BRUTO] IS NULL AND [CORR_PREGUNTA_DESCUENTO] IS NULL)
				OR (
					[CORR_PREGUNTA_BRUTO] IS NOT NULL
					AND [CORR_PREGUNTA_DESCUENTO] IS NOT NULL
					AND [CORR_PREGUNTA_BRUTO] <> [CORR_PREGUNTA_DESCUENTO]
					AND [CORR_PREGUNTA_BRUTO] <> [CORR_PREGUNTA]
					AND [CORR_PREGUNTA_DESCUENTO] <> [CORR_PREGUNTA]
				)
			)
		)
		OR
		(
			ISNULL([ROL_MONTO], N'') <> N'LIQUIDO'
			AND [CORR_PREGUNTA_BRUTO] IS NULL
			AND [CORR_PREGUNTA_DESCUENTO] IS NULL
		)
	)
);
GO

