SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO

IF OBJECT_ID(N'dbo.GEN_PERSONA_PROVEEDOR', N'U') IS NULL
BEGIN
	CREATE TABLE [dbo].[GEN_PERSONA_PROVEEDOR]
	(
		[CORR_EMPRESA] [int] NOT NULL,
		[CORR_PERSONA] [bigint] NOT NULL,
		[CORR_PROVEEDOR] [int] NOT NULL,
		[USUARIO_CREA] [varchar](50) NULL,
		[ESTACION_CREA] [varchar](50) NULL,
		[FECHA_CREA] [datetime] NULL,
		[USUARIO_ACTU] [varchar](50) NULL,
		[ESTACION_ACTU] [varchar](50) NULL,
		[FECHA_ACTU] [datetime] NULL,
		CONSTRAINT [PK_GEN_PERSONA_PROVEEDOR] PRIMARY KEY CLUSTERED
		(
			[CORR_EMPRESA] ASC,
			[CORR_PROVEEDOR] ASC
		)
	);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.indexes
	WHERE name = N'UQ_GEN_PERSONA_PROVEEDOR_PERSONA'
	  AND object_id = OBJECT_ID(N'dbo.GEN_PERSONA_PROVEEDOR')
)
BEGIN
	CREATE UNIQUE NONCLUSTERED INDEX [UQ_GEN_PERSONA_PROVEEDOR_PERSONA]
		ON [dbo].[GEN_PERSONA_PROVEEDOR] ([CORR_EMPRESA] ASC, [CORR_PERSONA] ASC);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_PROVEEDOR_GEN_PERSONA'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_PROVEEDOR] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_PROVEEDOR_GEN_PERSONA]
		FOREIGN KEY ([CORR_PERSONA]) REFERENCES [dbo].[GEN_PERSONA] ([CORR_PERSONA]);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_PROVEEDOR_GEN_PROVEEDOR'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_PROVEEDOR] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_PROVEEDOR_GEN_PROVEEDOR]
		FOREIGN KEY ([CORR_EMPRESA], [CORR_PROVEEDOR])
		REFERENCES [dbo].[GEN_PROVEEDOR] ([CORR_EMPRESA], [CORR_PROVEEDOR]);
END
GO

IF NOT EXISTS (
	SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_GEN_PERSONA_PROVEEDOR_GEN_EMPRESA'
)
BEGIN
	ALTER TABLE [dbo].[GEN_PERSONA_PROVEEDOR] WITH CHECK
	ADD CONSTRAINT [FK_GEN_PERSONA_PROVEEDOR_GEN_EMPRESA]
		FOREIGN KEY ([CORR_EMPRESA]) REFERENCES [dbo].[GEN_EMPRESA] ([CORR_EMPRESA]);
END
