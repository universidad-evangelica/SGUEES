-- Cuentas contables de detalle asignadas a un proveedor, por tipo.
-- Puede haber varias filas del mismo tipo; solo una con ACTIVO = 1.
SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO

IF OBJECT_ID(N'dbo.GEN_PROVEEDOR_CUENTA_CONTABLE', N'U') IS NULL
BEGIN
	CREATE TABLE [dbo].[GEN_PROVEEDOR_CUENTA_CONTABLE]
	(
		[CORR_EMPRESA] [int] NOT NULL,
		[CORR_PROVEEDOR] [int] NOT NULL,
		[CORR_CUENTA] [int] NOT NULL,
		[TIPO_CUENTA] [varchar](3) COLLATE Latin1_General_CS_AS NOT NULL,
		[CUENTA_CONTABLE] [varchar](30) COLLATE Latin1_General_CS_AS NOT NULL,
		[ACTIVO] [bit] NOT NULL CONSTRAINT [DF_GEN_PROVEEDOR_CUENTA_CONTABLE_ACTIVO] DEFAULT (1),
		[USUARIO_CREA] [varchar](30) COLLATE Latin1_General_CS_AS NOT NULL,
		[FECHA_CREA] [datetime] NOT NULL,
		[ESTACION_CREA] [varchar](50) COLLATE Latin1_General_CS_AS NOT NULL,
		[USUARIO_ACTU] [varchar](30) COLLATE Latin1_General_CS_AS NULL,
		[FECHA_ACTU] [datetime] NULL,
		[ESTACION_ACTU] [varchar](50) COLLATE Latin1_General_CS_AS NULL,
		CONSTRAINT [PK_GEN_PROVEEDOR_CUENTA_CONTABLE] PRIMARY KEY CLUSTERED ([CORR_EMPRESA], [CORR_PROVEEDOR], [CORR_CUENTA]),
		CONSTRAINT [FK_GEN_PROVEEDOR_CUENTA_CONTABLE_GEN_PROVEEDOR] FOREIGN KEY ([CORR_EMPRESA], [CORR_PROVEEDOR])
			REFERENCES [dbo].[GEN_PROVEEDOR] ([CORR_EMPRESA], [CORR_PROVEEDOR]),
		CONSTRAINT [FK_GEN_PROVEEDOR_CUENTA_CONTABLE_CON_CATALOGO_CUENTA] FOREIGN KEY ([CORR_EMPRESA], [CUENTA_CONTABLE])
			REFERENCES [dbo].[CON_CATALOGO_CUENTA] ([CORR_EMPRESA], [CUENTA_CONTABLE])
	) ON [PRIMARY];
END
GO

IF NOT EXISTS (
	SELECT 1
	FROM sys.indexes
	WHERE name = N'UX_GEN_PROVEEDOR_CUENTA_ACTIVA'
	  AND object_id = OBJECT_ID(N'dbo.GEN_PROVEEDOR_CUENTA_CONTABLE')
)
BEGIN
	CREATE UNIQUE INDEX [UX_GEN_PROVEEDOR_CUENTA_ACTIVA]
		ON [dbo].[GEN_PROVEEDOR_CUENTA_CONTABLE] ([CORR_EMPRESA], [CORR_PROVEEDOR], [TIPO_CUENTA])
		WHERE [ACTIVO] = 1;
END
GO
