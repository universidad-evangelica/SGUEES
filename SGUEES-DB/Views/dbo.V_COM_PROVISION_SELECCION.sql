CREATE VIEW [dbo].[V_COM_PROVISION_SELECCION]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_PROVISION
      ,A.FECHA_PROVISION
      ,B.NOMBRE_PROVEEDOR 
      ,A.NOMBRE_PARTIDA
      ,A.MONTO_PAGO
      ,A.ANIO_PERIODO_PARTIDA
      ,A.MES_PERIODO_PARTIDA
      ,A.CORR_CLASE_PARTIDA
      ,ISNULL(C.NOMBRE_CLASE_PARTIDA,'') NOMBRE_CLASE_PARTIDA
      ,A.CORR_PARTIDA
      ,A.ESTADO_PROVISION
      ,CASE A.ESTADO_PROVISION
		  WHEN 'DI' THEN 'Digitado'
		  WHEN 'AP' THEN 'Aplicado'
		  ELSE '' END NOMBRE_ESTADO_PROVISION
      ,CONVERT(BIT,0) SELECCION
  FROM COM_PROVISION A
  INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR 
  LEFT OUTER JOIN CON_CLASE_PARTIDA C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_CLASE_PARTIDA=C.CORR_CLASE_PARTIDA
GO



