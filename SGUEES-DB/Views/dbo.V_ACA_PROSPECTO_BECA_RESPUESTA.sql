/* ==========================================================================
   V_ACA_PROSPECTO_BECA_RESPUESTA
   Qué hace: cada respuesta guardada del cuestionario, con su puntaje.
   Cómo lo hace: una fila por ACA_PROSPECTO_BECA_RESPUESTA (en opción
             múltiple hay una fila por opción marcada). La API filtra por
             CORR_EMPRESA y CORR_PROSPECTO_BECA.
   ========================================================================== */
CREATE   VIEW dbo.V_ACA_PROSPECTO_BECA_RESPUESTA
AS
SELECT
    R.CORR_EMPRESA,
    R.CORR_PROSPECTO_BECA,
    R.CORR_RESPUESTA_BECA,
    S.ORDEN AS ORDEN_SECCION,
    S.NOMBRE_SECCION,
    P.ORDEN AS ORDEN_PREGUNTA,
    P.CORR_PREGUNTA_BECA,
    P.CODIGO_PREGUNTA,
    P.TEXTO_PREGUNTA,
    P.TIPO_RESPUESTA,
    ISNULL(R.CORR_OPCION_BECA, 0) AS CORR_OPCION_BECA,
    CASE
        WHEN P.TIPO_RESPUESTA = 'ACEPTACION'
            THEN COALESCE(NULLIF(LTRIM(RTRIM(R.RESPUESTA_TEXTO)), ''), R.TEXTO_OPCION_HISTORICO)
        WHEN P.TIPO_RESPUESTA IN ('OPCION_UNICA', 'OPCION_MULTIPLE', 'SI_NO')
            THEN R.TEXTO_OPCION_HISTORICO
        WHEN P.TIPO_RESPUESTA = 'DOCUMENTO'
            THEN R.ARCHIVO_NOMBRE
        WHEN P.TIPO_RESPUESTA IN ('NUMERO', 'DECIMAL') AND R.RESPUESTA_NUMERO IS NOT NULL
            THEN CASE
                    WHEN R.RESPUESTA_NUMERO = FLOOR(R.RESPUESTA_NUMERO)
                        THEN CONVERT(VARCHAR(40), CONVERT(BIGINT, R.RESPUESTA_NUMERO))
                    ELSE CONVERT(VARCHAR(40), CONVERT(DECIMAL(18, 2), R.RESPUESTA_NUMERO))
                 END
        WHEN P.TIPO_RESPUESTA IN ('TEXTO', 'TEXTO_LARGO')
            THEN R.RESPUESTA_TEXTO
        WHEN R.RESPUESTA_FECHA IS NOT NULL
            THEN CONVERT(VARCHAR(10), R.RESPUESTA_FECHA, 103)
        ELSE COALESCE(R.TEXTO_OPCION_HISTORICO, R.RESPUESTA_TEXTO)
    END AS RESPUESTA,
    CAST(CASE
        WHEN P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS' THEN ISNULL(DEP.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
             AND P.CORR_PREGUNTA_BECA = PR.CORR_PREGUNTA_DESTINO THEN ISNULL(ACA.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO') THEN 0
        ELSE R.PUNTAJE_OBTENIDO
    END AS decimal(10, 2)) AS PUNTAJE_OBTENIDO,
    CAST(CASE
        WHEN P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS' THEN ISNULL(DEP.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
             AND P.CORR_PREGUNTA_BECA = PR.CORR_PREGUNTA_DESTINO THEN ISNULL(ACA.PUNTAJE, 0)
        WHEN P.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO') THEN 0
        ELSE R.PORCENTAJE_APLICADO
    END AS decimal(10, 2)) AS PORCENTAJE_APLICADO
FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R
INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P
    ON P.CORR_PREGUNTA_BECA = R.CORR_PREGUNTA_BECA
INNER JOIN dbo.ACA_PROSPECTO_BECA_SECCION AS S
    ON S.CORR_SECCION_BECA = P.CORR_SECCION_BECA
INNER JOIN dbo.ACA_PROSPECTO_BECA AS PB
    ON PB.CORR_PROSPECTO_BECA = R.CORR_PROSPECTO_BECA
LEFT JOIN (
    SELECT
        G.CORR_PROSPECTO_BECA,
        G.PROMEDIO,
        D.CORR_PREGUNTA_BECA AS CORR_PREGUNTA_DESTINO
    FROM (
        SELECT
            R2.CORR_PROSPECTO_BECA,
            AVG(R2.RESPUESTA_NUMERO) AS PROMEDIO
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R2
        INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P2
            ON P2.CORR_PREGUNTA_BECA = R2.CORR_PREGUNTA_BECA
        WHERE P2.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
          AND R2.RESPUESTA_NUMERO IS NOT NULL
        GROUP BY R2.CORR_PROSPECTO_BECA
    ) AS G
    CROSS APPLY (
        SELECT TOP (1) R3.CORR_PREGUNTA_BECA
        FROM dbo.ACA_PROSPECTO_BECA_RESPUESTA AS R3
        INNER JOIN dbo.ACA_PROSPECTO_BECA_PREGUNTA AS P3
            ON P3.CORR_PREGUNTA_BECA = R3.CORR_PREGUNTA_BECA
        WHERE R3.CORR_PROSPECTO_BECA = G.CORR_PROSPECTO_BECA
          AND P3.CODIGO_PREGUNTA IN (N'ACA_PROMEDIO_PRIMERO', N'ACA_PROMEDIO_SEGUNDO', N'ACA_PROMEDIO_TERCERO')
          AND R3.RESPUESTA_NUMERO IS NOT NULL
        ORDER BY P3.ORDEN DESC, R3.CORR_RESPUESTA_BECA DESC
    ) AS D
) AS PR
    ON PR.CORR_PROSPECTO_BECA = R.CORR_PROSPECTO_BECA
OUTER APPLY (
    SELECT TOP (1) B.PUNTAJE
    FROM dbo.ACA_PROSPECTO_BECA_BANDA AS B
    WHERE B.ACTIVO = 1
      AND B.CODIGO_REGLA = N'DEPENDIENTES'
      AND P.CODIGO_PREGUNTA = N'SOC_DEPENDIENTES_ECONOMICOS'
      AND R.RESPUESTA_NUMERO >= B.VALOR_DESDE
      AND R.RESPUESTA_NUMERO < B.VALOR_HASTA
) AS DEP
OUTER APPLY (
    SELECT TOP (1) B.PUNTAJE
    FROM dbo.ACA_PROSPECTO_BECA_BANDA AS B
    WHERE B.ACTIVO = 1
      AND B.CODIGO_REGLA = N'PROMEDIO_BACHILLERATO'
      AND PR.PROMEDIO >= B.VALOR_DESDE
      AND PR.PROMEDIO < B.VALOR_HASTA
) AS ACA
WHERE PB.ESTADO_BECA IN ('BORRADOR', 'ENVIADA')
  AND P.TIPO_RESPUESTA <> 'DOCUMENTO';

GO
