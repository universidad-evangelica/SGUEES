CREATE OR ALTER VIEW [dbo].[V_GEN_PROVEEDOR_CUENTA_CONTABLE]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PROVEEDOR,
	A.CORR_CUENTA,
	A.TIPO_CUENTA,
	A.CUENTA_CONTABLE,
	B.NOMBRE_CUENTA,
	A.ACTIVO,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU
FROM dbo.GEN_PROVEEDOR_CUENTA_CONTABLE A
INNER JOIN dbo.CON_CATALOGO_CUENTA B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.CUENTA_CONTABLE = B.CUENTA_CONTABLE
GO
