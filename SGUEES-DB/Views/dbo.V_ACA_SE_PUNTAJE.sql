CREATE OR ALTER VIEW [dbo].[V_ACA_SE_PUNTAJE]
AS
SELECT
	PU.CORR_PUNTAJE,
	PU.CORR_PREGUNTA,
	P.CODIGO AS CODIGO_PREGUNTA,
	P.ENUNCIADO AS ENUNCIADO_PREGUNTA,
	PU.CORR_OPCION,
	O.CODIGO AS CODIGO_OPCION,
	O.TEXTO AS TEXTO_OPCION,
	PU.PUNTAJE,
	PU.PORCENTAJE,
	PU.FECHA_INICIO,
	PU.FECHA_FIN,
	PU.ACTIVO,
	PU.CORR_EMPRESA,
	PU.USUARIO_CREA,
	PU.ESTACION_CREA,
	PU.FECHA_CREA,
	PU.USUARIO_ACTU,
	PU.ESTACION_ACTU,
	PU.FECHA_ACTU
FROM dbo.ACA_SE_PUNTAJE AS PU
INNER JOIN dbo.ACA_SE_PREGUNTA AS P
	ON P.CORR_PREGUNTA = PU.CORR_PREGUNTA
LEFT JOIN dbo.ACA_SE_OPCION AS O
	ON O.CORR_OPCION = PU.CORR_OPCION;
GO
