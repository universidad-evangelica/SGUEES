-- Qué hace: browse de cuentas bancarias por persona.
-- Cómo: GEN_PERSONA_BANCO + GEN_BANCO (NOMBRE_BANCO).
CREATE OR ALTER VIEW [dbo].[V_GEN_PERSONA_BANCO]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PERSONA,
	A.CORR_PERSONA_BANCO,
	A.CORR_BANCO,
	ISNULL(B.NOMBRE_BANCO, N'') AS NOMBRE_BANCO,
	A.CUENTA_BANCARIA,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU
FROM dbo.GEN_PERSONA_BANCO A
LEFT JOIN dbo.GEN_BANCO B
	ON B.CORR_EMPRESA = A.CORR_EMPRESA
	AND B.CORR_BANCO = A.CORR_BANCO
GO
