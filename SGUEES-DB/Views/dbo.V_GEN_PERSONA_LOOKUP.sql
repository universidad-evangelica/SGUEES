-- Qué hace: lookup de personas (natural o jurídica) para etiquetar como proveedor.
-- Cómo: GEN_PERSONA + LEFT JOIN natural/jurídica; TIPO_PERSONERIA N/J.
CREATE OR ALTER VIEW [dbo].[V_GEN_PERSONA_LOOKUP]
AS
SELECT
	PE.CORR_PERSONA,
	ISNULL(PE.CODIGO_PERSONA, N'') AS CODIGO_PERSONA,
	CAST(
		CASE
			WHEN PN.CORR_PERSONA IS NOT NULL THEN N'N'
			WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'J'
			ELSE N''
		END AS VARCHAR(1)
	) AS TIPO_PERSONERIA,
	CASE
		WHEN PN.CORR_PERSONA IS NOT NULL THEN N'Natural'
		WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'Jurídico'
		ELSE N''
	END AS NOMBRE_TIPO_PERSONERIA,
	CAST(
		CASE
			WHEN PN.CORR_PERSONA IS NOT NULL THEN ISNULL(NULLIF(LTRIM(RTRIM(PN.NOMBRE_COMPLETO)), N''), N'')
			WHEN PJ.CORR_PERSONA IS NOT NULL THEN ISNULL(NULLIF(LTRIM(RTRIM(PJ.RAZON_SOCIAL)), N''), ISNULL(PJ.NOMBRE_EMPRESA, N''))
			ELSE N''
		END AS VARCHAR(200)
	) AS NOMBRE_PERSONA,
	CAST(ISNULL(PE.ACTIVO_PERSONA, 1) AS BIT) AS ACTIVO_PERSONA
FROM dbo.GEN_PERSONA PE
LEFT JOIN dbo.GEN_PERSONA_NATURAL PN
	ON PN.CORR_PERSONA = PE.CORR_PERSONA
LEFT JOIN dbo.GEN_PERSONA_JURIDICA PJ
	ON PJ.CORR_PERSONA = PE.CORR_PERSONA
WHERE PN.CORR_PERSONA IS NOT NULL
   OR PJ.CORR_PERSONA IS NOT NULL
GO
