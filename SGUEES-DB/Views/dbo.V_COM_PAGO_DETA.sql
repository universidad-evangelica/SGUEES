CREATE VIEW [dbo].[V_COM_PAGO_DETA]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_PAGO
      ,A.CORR_DETA
      ,A.ANIO_PERIODO_COM
      ,A.MES_PERIODO_COM
      ,A.CORR_DOCUMENTO_COM
      ,B.NUMERO_DOCUMENTO 
      ,B.NOMBRE_CORTO_TIPO_DOC NOMBRE_TIPO_DOC 
      ,B.CORR_PROVEEDOR 
      ,B.CORR_TIENDA CORR_TIENDA_COM
      ,B.FECHA_DOCUMENTO 
      ,B.TOTAL_DOCUMENTO
      ,B.SALDO_DOCUMENTO
      ,B.TOTAL_NETO
      ,(A.MONTO_DOCUMENTO*B.SUMA_RESTA) MONTO_DOCUMENTO
      ,(A.MONTO_INICIAL*B.SUMA_RESTA) MONTO_INICIAL
      ,(A.MONTO_PAGO*B.SUMA_RESTA) MONTO_PAGO
      ,(A.MONTO_FINAL*B.SUMA_RESTA) MONTO_FINAL
      ,C.ESTADO_PAGO
      ,C.FECHA_PAGO      
FROM COM_PAGO_DETA A
INNER JOIN V_COM_DOCUMENTO B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_COM=B.ANIO_PERIODO AND A.MES_PERIODO_COM=B.MES_PERIODO AND A.CORR_DOCUMENTO_COM=B.CORR_DOCUMENTO 
INNER JOIN COM_PAGO C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.ANIO_PERIODO=C.ANIO_PERIODO AND A.MES_PERIODO=C.MES_PERIODO AND A.CORR_PAGO=C.CORR_PAGO
GO



