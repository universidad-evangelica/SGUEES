CREATE OR ALTER VIEW [dbo].[V_ACA_SE_VERSION_PREGUNTA]
AS
SELECT
	VP.CORR_VERSION_PREGUNTA,
	VP.CORR_VERSION,
	V.CODIGO AS CODIGO_VERSION,
	V.NOMBRE AS NOMBRE_VERSION,
	VP.CORR_PREGUNTA,
	P.CODIGO AS CODIGO_PREGUNTA,
	P.ENUNCIADO AS ENUNCIADO_PREGUNTA,
	VP.CORR_SECCION_SE,
	S.NOMBRE_SECCION,
	S.ORDEN AS ORDEN_SECCION,
	VP.ORDEN,
	VP.ES_REQUERIDO,
	VP.ACTIVO,
	VP.USUARIO_CREA,
	VP.ESTACION_CREA,
	VP.FECHA_CREA,
	VP.USUARIO_ACTU,
	VP.ESTACION_ACTU,
	VP.FECHA_ACTU
FROM dbo.ACA_SE_VERSION_PREGUNTA AS VP
INNER JOIN dbo.ACA_SE_VERSION AS V
	ON V.CORR_VERSION = VP.CORR_VERSION
INNER JOIN dbo.ACA_SE_PREGUNTA AS P
	ON P.CORR_PREGUNTA = VP.CORR_PREGUNTA
LEFT JOIN dbo.ACA_SE_SECCION AS S
	ON S.CORR_SECCION_SE = VP.CORR_SECCION_SE;
GO
