CREATE OR ALTER VIEW [dbo].[V_ACA_SE_VERSION_PREGUNTA]
AS
SELECT
	VP.CORR_VERSION_PREGUNTA,
	VP.CORR_VERSION,
	V.CODIGO AS CODIGO_VERSION,
	V.NOMBRE AS NOMBRE_VERSION,
	VP.CORR_SECCION_SE,
	S.CODIGO AS CODIGO_SECCION,
	S.NOMBRE_SECCION,
	S.TIPO_EVALUACION,
	VP.CORR_PREGUNTA,
	P.CODIGO AS CODIGO_PREGUNTA,
	P.ENUNCIADO AS ENUNCIADO_PREGUNTA,
	P.CORR_TIPO_PREGUNTA,
	T.CODIGO AS CODIGO_TIPO_PREGUNTA,
	T.NOMBRE AS NOMBRE_TIPO_PREGUNTA,
	VP.ORDEN,
	VP.PUNTAJE,
	VP.ES_REQUERIDO,
	VP.ROL_MONTO,
	CASE VP.ROL_MONTO
		WHEN N'BRUTO' THEN N'Bruto'
		WHEN N'DESCUENTO' THEN N'Descuento'
		WHEN N'LIQUIDO' THEN N'Líquido'
		WHEN N'MONTO' THEN N'Monto'
		ELSE NULL
	END AS NOMBRE_ROL_MONTO,
	VP.CORR_PREGUNTA_BRUTO,
	PB.CODIGO AS CODIGO_PREGUNTA_BRUTO,
	PB.ENUNCIADO AS ENUNCIADO_PREGUNTA_BRUTO,
	VP.CORR_PREGUNTA_DESCUENTO,
	PD.CODIGO AS CODIGO_PREGUNTA_DESCUENTO,
	PD.ENUNCIADO AS ENUNCIADO_PREGUNTA_DESCUENTO,
	VP.ACTIVO,
	VP.USUARIO_CREA,
	VP.ESTACION_CREA,
	VP.FECHA_CREA,
	VP.USUARIO_ACTU,
	VP.ESTACION_ACTU,
	VP.FECHA_ACTU
FROM dbo.ACA_SE_VERSION_PREGUNTA AS VP
INNER JOIN dbo.ACA_SE_VERSION AS V
	ON V.CORR_VERSION = VP.CORR_VERSION
INNER JOIN dbo.ACA_SE_PREGUNTA AS P
	ON P.CORR_PREGUNTA = VP.CORR_PREGUNTA
INNER JOIN dbo.GEN_SE_TIPO_PREGUNTA AS T
	ON T.CORR_TIPO_PREGUNTA = P.CORR_TIPO_PREGUNTA
LEFT JOIN dbo.ACA_SE_SECCION AS S
	ON S.CORR_SECCION_SE = VP.CORR_SECCION_SE
LEFT JOIN dbo.ACA_SE_PREGUNTA AS PB
	ON PB.CORR_PREGUNTA = VP.CORR_PREGUNTA_BRUTO
LEFT JOIN dbo.ACA_SE_PREGUNTA AS PD
	ON PD.CORR_PREGUNTA = VP.CORR_PREGUNTA_DESCUENTO;
GO
