CREATE OR ALTER VIEW [dbo].[V_ACA_SE_OPCION]
AS
SELECT
	O.CORR_OPCION,
	O.CORR_PREGUNTA,
	P.CODIGO AS CODIGO_PREGUNTA,
	P.ENUNCIADO AS ENUNCIADO_PREGUNTA,
	P.CORR_TIPO_PREGUNTA,
	T.CODIGO AS CODIGO_TIPO_PREGUNTA,
	T.NOMBRE AS NOMBRE_TIPO_PREGUNTA,
	O.CODIGO,
	O.TEXTO,
	O.ORDEN,
	O.PUNTAJE,
	O.ACTIVO,
	O.USUARIO_CREA,
	O.ESTACION_CREA,
	O.FECHA_CREA,
	O.USUARIO_ACTU,
	O.ESTACION_ACTU,
	O.FECHA_ACTU
FROM dbo.ACA_SE_OPCION AS O
INNER JOIN dbo.ACA_SE_PREGUNTA AS P
	ON P.CORR_PREGUNTA = O.CORR_PREGUNTA
INNER JOIN dbo.GEN_SE_TIPO_PREGUNTA AS T
	ON T.CORR_TIPO_PREGUNTA = P.CORR_TIPO_PREGUNTA;
GO
