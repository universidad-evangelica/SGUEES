CREATE VIEW [dbo].[V_COM_DOCUMENTO_A_PROVISIONAR]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_DOCUMENTO
      ,A.CORR_TIPO_DOC
      ,B.NOMBRE_CORTO_TIPO_DOC
      ,B.NOMBRE_TIPO_DOC
      ,A.NUMERO_DOCUMENTO
      ,A.FECHA_DOCUMENTO
      ,A.FECHA_VENCIMIENTO
      ,A.CORR_TIENDA
      ,A.CORR_PROVEEDOR
      ,F.NOMBRE_PROVEEDOR
      ,A.DESCRIPCION_PARTIDA
      ,A.CORR_CONDICION_PAGO
      ,A.DIAS_CREDITO
      ,A.ESTADO_DOCUMENTO
      ,A.ESTA_CONTABILIZADO
      ,A.TOTAL_DOCUMENTO * B.SUMA_RESTA AS TOTAL_DOCUMENTO
      ,A.TOTAL_NETO
      ,A.SALDO_DOCUMENTO
      ,A.USUARIO_CREA
      ,A.FECHA_CREA
      ,A.ESTACION_CREA
      ,A.USUARIO_ACTU
      ,A.FECHA_ACTU
      ,A.ESTACION_ACTU
      ,A.CORR_TIPO_GASTO
      ,A.CANTIDAD
      ,A.CORR_MOVIMIENTO
      ,A.ESTA_PROVISIONADO
      ,CONVERT(BIT, 0) AS SELECCION
      ,D.CORR_PROVISION
FROM COM_DOCUMENTO A
INNER JOIN GEN_TIPO_DOCUMENTO B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.CORR_TIPO_DOC = B.CORR_TIPO_DOC
INNER JOIN V_COM_PROVEEDOR F
	ON A.CORR_PROVEEDOR = F.CORR_PROVEEDOR
LEFT OUTER JOIN COM_PROVISION_DETA D
	ON A.CORR_EMPRESA = D.CORR_EMPRESA
	AND A.ANIO_PERIODO = D.ANIO_PERIODO_COM
	AND A.MES_PERIODO = D.MES_PERIODO_COM
	AND A.CORR_DOCUMENTO = D.CORR_DOCUMENTO_COM
GO
