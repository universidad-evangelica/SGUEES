SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO

CREATE OR ALTER VIEW [dbo].[V_ACA_SE_SECCION]
AS
SELECT
	S.CORR_SECCION_SE,
	S.CORR_VERSION,
	V.CODIGO AS CODIGO_VERSION,
	V.NOMBRE AS NOMBRE_VERSION,
	S.CODIGO,
	S.NOMBRE_SECCION,
	S.DESCRIPCION,
	S.ORDEN,
	S.PORCENTAJE_MAXIMO,
	S.ACTIVO,
	S.CORR_EMPRESA,
	S.USUARIO_CREA,
	S.ESTACION_CREA,
	S.FECHA_CREA,
	S.USUARIO_ACTU,
	S.ESTACION_ACTU,
	S.FECHA_ACTU
FROM dbo.ACA_SE_SECCION AS S
INNER JOIN dbo.ACA_SE_VERSION AS V
	ON V.CORR_VERSION = S.CORR_VERSION;
GO
