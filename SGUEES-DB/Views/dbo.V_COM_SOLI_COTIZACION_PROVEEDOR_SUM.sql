CREATE OR ALTER VIEW [dbo].[V_COM_SOLI_COTIZACION_PROVEEDOR_SUM]
AS
SELECT A.CORR_EMPRESA
	  ,A.ANIO_PERIODO
	  ,A.CORR_SOLI_COTIZACION
	  ,dbo.StrConcat(B.NOMBRE_PROVEEDOR+', ') NOMBRE_PROVEEDOR
FROM COM_SOLI_COTIZACION_PROVEEDOR A
INNER JOIN dbo.GEN_PROVEEDOR B ON A.CORR_EMPRESA = B.CORR_EMPRESA AND A.CORR_PROVEEDOR = B.CORR_PROVEEDOR
GROUP BY A.CORR_EMPRESA
	  ,A.ANIO_PERIODO
	  ,A.CORR_SOLI_COTIZACION
GO
