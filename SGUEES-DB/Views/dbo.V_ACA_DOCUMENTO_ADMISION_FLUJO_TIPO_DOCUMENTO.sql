CREATE OR ALTER VIEW [dbo].[V_ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO]
AS
SELECT
  A.[CORR_EMPRESA],
  A.[CORR_TIPO_DOCUMENTO],
  T.[NOMBRE_TIPO],
  A.[CORR_DOCUMENTO_ADMISION],
  D.[CODIGO],
  D.[NOMBRE_DOCUMENTO],
  D.[ORDEN],
  D.[OBLIGATORIO],
  D.[ACTIVO],
  A.[USUARIO_CREA],
  A.[ESTACION_CREA],
  A.[FECHA_CREA],
  A.[USUARIO_ACTU],
  A.[ESTACION_ACTU],
  A.[FECHA_ACTU]
FROM [dbo].[ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO] A
INNER JOIN [dbo].[SEG_FLUJO_TIPO_DOCUMENTO] T
  ON T.[CORR_EMPRESA] = A.[CORR_EMPRESA]
 AND T.[CORR_TIPO_DOCUMENTO] = A.[CORR_TIPO_DOCUMENTO]
INNER JOIN [dbo].[ACA_DOCUMENTO_ADMISION] D
  ON D.[CORR_DOCUMENTO_ADMISION] = A.[CORR_DOCUMENTO_ADMISION]
GO
