/*
  Proveedores disponibles — origen SGUEES (COM_PROVEEDOR). Sin CLASS.

  HISTÓRICO CLASS (NO ELIMINAR — solo desconectado):
  FROM [CLASS_UEES].[CLASS_UEES].[CLASS_UEES].dbo.CLIENTES A
  LEFT JOIN COM_PROVEEDOR B ON A.CLIIDU = B.CORR_PROVEEDOR
  WHERE A.CLITIP = 'V' AND A.CLISTS = 'A'
    AND A.CLICAT IN ('PN-','PE-','PG-','PP-','PM-','PR-')
*/
CREATE OR ALTER VIEW [dbo].[V_COM_PROVEEDOR_DISPONIBLE]
AS
SELECT
	CONVERT(BIT, 0) AS SELECCION,
	A.CORR_PROVEEDOR,
	A.CODIGO_PROVEEDOR,
	A.NOMBRE_PROVEEDOR,
	ISNULL(A.CORR_FORMA_PAGO, 4) AS CORR_FORMA_PAGO,
	ISNULL(A.CORR_CONDICION_PAGO, 0) AS CORR_CONDICION_PAGO,
	CAST(N'' AS VARCHAR(100)) AS DETALLE_FORMA_PAGO
FROM dbo.COM_PROVEEDOR A
WHERE A.ESTADO_PROVEEDOR = N'A'
GO
