CREATE VIEW [dbo].[V_GEN_PARAMETRO_PLANTILLA_VERSION]
AS
SELECT 
    v.CORR_EMPRESA,
    v.CORR_PARAMETRO_PLANTILLA,
    p.CODIGO_PLANTILLA,
    p.NOMBRE_PLANTILLA,
    v.NUMERO_VERSION,
    v.ASUNTO_PLANTILLA,
    v.CUERPO_PLANTILLA,
    v.CORREO_CC,
    v.CORREO_CCO,
    v.ES_VERSION_ACTIVA,
    v.MOTIVO_VERSION,
    v.USUARIO_CREA,
    v.ESTACION_CREA,
    v.FECHA_CREA,
    v.USUARIO_ACTU,
    v.ESTACION_ACTU,
    v.FECHA_ACTU
FROM dbo.GEN_PARAMETRO_PLANTILLA_VERSION v
INNER JOIN dbo.GEN_PARAMETRO_PLANTILLA p 
    ON v.CORR_EMPRESA = p.CORR_EMPRESA 
    AND v.CORR_PARAMETRO_PLANTILLA = p.CORR_PARAMETRO_PLANTILLA;
GO
