CREATE VIEW [dbo].[V_GEN_PARAMETRO_PLANTILLA]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PARAMETRO_PLANTILLA,
	A.CODIGO_PLANTILLA,
	A.NOMBRE_PLANTILLA,
	A.ASUNTO_PLANTILLA,
	A.CUERPO_PLANTILLA,
	A.CORR_PARAMETRO_SMTP,
	B.CORREO_REMITENTE,
	B.SERVIDOR_CORREO,
	A.CORREO_CC,
	A.CORREO_CCO,
	A.ACTIVO_PLANTILLA,
	A.USUARIO_CREA,
	A.ESTACION_CREA,
	A.FECHA_CREA,
	A.USUARIO_ACTU,
	A.ESTACION_ACTU,
	A.FECHA_ACTU
FROM dbo.GEN_PARAMETRO_PLANTILLA A
LEFT JOIN dbo.GEN_PARAMETRO_SMTP B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.CORR_PARAMETRO_SMTP = B.CORR_PARAMETRO_SMTP
GO
