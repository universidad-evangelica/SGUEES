CREATE VIEW [dbo].[V_GEN_PARAMETRO_PLANTILLA]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PARAMETRO_PLANTILLA,
	A.CODIGO_PLANTILLA,
	A.NOMBRE_PLANTILLA,
	A.ASUNTO_PLANTILLA,
	A.CUERPO_PLANTILLA,
	A.CORR_PARAMETRO_SMTP,
	B.CORREO_REMITENTE,
	B.SERVIDOR_CORREO,
	A.CORREO_CC,
	A.CORREO_CCO,
	A.CODIGO_SISTEMA,
	S.NOMBRE_SISTEMA,
	A.CODIGO_OPCION,
	O.NOMBRE_OPCION,
	A.ACTIVO_PLANTILLA,
	ISNULL(ver.CANT_VERSIONES, 0) AS CANT_VERSIONES,
	ver.NUMERO_VERSION_ACTIVA,
	CASE
		WHEN ISNULL(ver.CANT_VERSIONES, 0) = 0 THEN N'Borrador'
		WHEN A.ACTIVO_PLANTILLA = 1 THEN N'Activa'
		ELSE N'Inactiva'
	END AS ESTADO_PLANTILLA,
	A.USUARIO_CREA,
	A.ESTACION_CREA,
	A.FECHA_CREA,
	A.USUARIO_ACTU,
	A.ESTACION_ACTU,
	A.FECHA_ACTU
FROM dbo.GEN_PARAMETRO_PLANTILLA A
LEFT JOIN dbo.GEN_PARAMETRO_SMTP B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.CORR_PARAMETRO_SMTP = B.CORR_PARAMETRO_SMTP
LEFT JOIN dbo.SEG_SISTEMA S
	ON A.CODIGO_SISTEMA = S.CODIGO_SISTEMA
LEFT JOIN dbo.SEG_OPCION_SISTEMA O
	ON A.CODIGO_OPCION = O.CODIGO_OPCION
OUTER APPLY (
	SELECT
		CASE
			WHEN COUNT(*) = 0 THEN 0
			WHEN COUNT(*) = 1 AND SUM(
				CASE
					WHEN LEN(LTRIM(RTRIM(
						REPLACE(REPLACE(REPLACE(ISNULL(v.CUERPO_PLANTILLA, N''), N'<p><br></p>', N''), N'<p></p>', N''), N'&nbsp;', N'')
					))) > 0 THEN 1
					ELSE 0
				END
			) = 0 THEN 0
			ELSE COUNT(*)
		END AS CANT_VERSIONES,
		CASE
			WHEN COUNT(*) = 1 AND SUM(
				CASE
					WHEN LEN(LTRIM(RTRIM(
						REPLACE(REPLACE(REPLACE(ISNULL(v.CUERPO_PLANTILLA, N''), N'<p><br></p>', N''), N'<p></p>', N''), N'&nbsp;', N'')
					))) > 0 THEN 1
					ELSE 0
				END
			) = 0 THEN NULL
			ELSE MAX(CASE WHEN v.ES_VERSION_ACTIVA = 1 THEN v.NUMERO_VERSION END)
		END AS NUMERO_VERSION_ACTIVA
	FROM dbo.GEN_PARAMETRO_PLANTILLA_VERSION v
	WHERE v.CORR_EMPRESA = A.CORR_EMPRESA
	  AND v.CORR_PARAMETRO_PLANTILLA = A.CORR_PARAMETRO_PLANTILLA
) ver
GO
