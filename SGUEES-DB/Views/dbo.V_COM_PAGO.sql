CREATE VIEW [dbo].[V_COM_PAGO]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_PAGO
      ,A.CORR_TIPO_DOC 
      ,C.NOMBRE_TIPO_DOC 
      ,C.NOMBRE_CORTO_TIPO_DOC 
      ,C.CLASE_DOCUMENTO 
      ,C.SUMA_RESTA 
      ,A.FECHA_SOLICITUD
      ,A.FECHA_PAGO
      ,A.CORR_PROVEEDOR
      ,B.NOMBRE_PROVEEDOR 
      ,A.CORR_TIPO_CHEQUE
      ,A.CORR_CUENTA_BANCO
      ,A.NOMBRE_PARTIDA
      ,A.MONTO_PAGO
      ,ISNULL(A.ANIO_PERIODO_CHEQUE,0) ANIO_PERIODO_CHEQUE
      ,ISNULL(A.MES_PERIODO_CHEQUE,0) MES_PERIODO_CHEQUE
      ,ISNULL(A.CORR_TIPO_MOVIMIENTO,0) CORR_TIPO_MOVIMIENTO
	  ,CASE WHEN A.PAGADO_CAJA_CHICA=1 THEN 'Caja Chica' ELSE ISNULL(F.NOMBRE_TIPO_MOVIMIENTO,'') END NOMBRE_TIPO_MOVIMIENTO
      ,ISNULL(A.CORR_DOCUMENTO_CHEQUE,0) CORR_DOCUMENTO_CHEQUE
      ,A.ESTADO_PAGO
      ,CASE A.ESTADO_PAGO
      WHEN 'DI' THEN 'Digitado'
      WHEN 'AP' THEN 'Aplicado'
      ELSE '' END NOMBRE_ESTADO_PAGO
      ,ISNULL(A.ANIO_PERIODO_SOLI_CHEQUE,0) ANIO_PERIODO_SOLI_CHEQUE
      ,ISNULL(A.MES_PERIODO_SOLI_CHEQUE,0) MES_PERIODO_SOLI_CHEQUE
      ,ISNULL(A.CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE,0) CORR_TIPO_MOVIMIENTO_SOLI_CHEQUE
      ,ISNULL(A.CORR_DOCUMENTO_SOLI_CHEQUE,0) CORR_DOCUMENTO_SOLI_CHEQUE
      ,A.CORR_MOVIMIENTO
      ,ISNULL(A.PAGADO_CAJA_CHICA,0) PAGADO_CAJA_CHICA
      ,ISNULL(A.CORR_TIENDA,0) CORR_TIENDA
      ,ISNULL(A.CORR_CAJA,0) CORR_CAJA
      ,CONVERT(VARCHAR(100),'') NOMBRE_CAJA
      ,ISNULL(A.NOMBRE_BENEFICIARIO,'') NOMBRE_BENEFICIARIO
      ,G.CORR_ARCHIVO
      ,G.FECHA_PAGO FECHA_PAGO_ARCHIVO
      ,G.CORRELATIVO
FROM COM_PAGO A
INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR 
INNER JOIN GEN_TIPO_DOCUMENTO C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_TIPO_DOC=C.CORR_TIPO_DOC 
LEFT OUTER JOIN BAN_TIPO_MOVI_BANCARIO F ON A.CORR_EMPRESA=F.CORR_EMPRESA AND A.CORR_TIPO_MOVIMIENTO=F.CORR_TIPO_MOVIMIENTO
LEFT OUTER JOIN COM_PAGO_ARCHIVO G ON A.CORR_EMPRESA=G.CORR_EMPRESA AND A.CORR_ARCHIVO=G.CORR_ARCHIVO
GO




