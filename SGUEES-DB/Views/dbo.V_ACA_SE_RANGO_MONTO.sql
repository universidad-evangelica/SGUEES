CREATE OR ALTER VIEW [dbo].[V_ACA_SE_RANGO_MONTO]
AS
SELECT
	R.CORR_RANGO_MONTO,
	R.CORR_VERSION,
	V.CODIGO AS CODIGO_VERSION,
	V.NOMBRE AS NOMBRE_VERSION,
	R.CORR_SECCION_SE,
	S.CODIGO AS CODIGO_SECCION,
	S.NOMBRE_SECCION,
	S.TIPO_EVALUACION,
	R.DESCRIPCION,
	R.PUNTAJE,
	R.RANGO_INICIAL,
	R.RANGO_FINAL,
	R.ORDEN,
	R.ACTIVO,
	R.CORR_EMPRESA,
	R.USUARIO_CREA,
	R.ESTACION_CREA,
	R.FECHA_CREA,
	R.USUARIO_ACTU,
	R.ESTACION_ACTU,
	R.FECHA_ACTU
FROM dbo.ACA_SE_RANGO_MONTO AS R
INNER JOIN dbo.ACA_SE_VERSION AS V
	ON V.CORR_VERSION = R.CORR_VERSION
INNER JOIN dbo.ACA_SE_SECCION AS S
	ON S.CORR_SECCION_SE = R.CORR_SECCION_SE;
GO
