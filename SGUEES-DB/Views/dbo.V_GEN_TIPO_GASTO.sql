CREATE OR ALTER VIEW [dbo].[V_GEN_TIPO_GASTO]
AS
SELECT A.CORR_EMPRESA
      ,A.CORR_TIPO_GASTO
      ,A.NOMBRE_TIPO_GASTO
      ,A.ES_SERVICIO
      ,A.ES_INTANGIBLE
      ,A.CUENTA_CONTABLE
      ,ISNULL(B.NOMBRE_CUENTA,'') NOMBRE_CUENTA
FROM GEN_TIPO_GASTO A
LEFT OUTER JOIN CON_CATALOGO_CUENTA B
	ON A.CORR_EMPRESA=B.CORR_EMPRESA
	AND A.CUENTA_CONTABLE=B.CUENTA_CONTABLE
GO
