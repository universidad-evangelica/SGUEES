CREATE VIEW [dbo].[V_GEN_PLANTILLA_CONTRATO_VERSION]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PLANTILLA_CONTRATO_VERSION,
	A.CORR_PLANTILLA_CONTRATO,
	A.NUMERO_VERSION,
	A.NOMBRE_VERSION,
	A.CORR_VERSION_PADRE,
	P.NOMBRE_VERSION AS NOMBRE_VERSION_PADRE,
	A.CUERPO_PLANTILLA,
	A.ES_VERSION_ACTIVA,
	A.OBSERVACION,
	A.USUARIO_CREA,
	A.ESTACION_CREA,
	A.FECHA_CREA,
	A.USUARIO_ACTU,
	A.ESTACION_ACTU,
	A.FECHA_ACTU
FROM [dbo].[GEN_PLANTILLA_CONTRATO_VERSION] A
LEFT JOIN [dbo].[GEN_PLANTILLA_CONTRATO_VERSION] P
	ON A.CORR_EMPRESA = P.CORR_EMPRESA
	AND A.CORR_PLANTILLA_CONTRATO = P.CORR_PLANTILLA_CONTRATO
	AND A.CORR_VERSION_PADRE = P.CORR_PLANTILLA_CONTRATO_VERSION
GO

