CREATE VIEW [dbo].[V_COM_ORDEN_COMPRA_AUTORIZAR]
AS
SELECT
	 A.CORR_EMPRESA
	,A.ANIO_PERIODO
	,A.CORR_ORDEN_COMPRA
	,A.NUMERO_ORDEN_COMPRA
	,A.CORR_PROVEEDOR
	,ISNULL(P.NOMBRE_PROVEEDOR, N'') NOMBRE_PROVEEDOR
	,A.FECHA_ORDEN FECHA_ORDEN_COMPRA
	,A.ESTADO_ORDEN ESTADO_ORDEN_COMPRA
	,CASE A.ESTADO_ORDEN
		WHEN N'DI' THEN N'Digitada'
		WHEN N'SO' THEN N'Solicitada'
		WHEN N'AP' THEN N'Aplicada'
		WHEN N'AN' THEN N'Anulada'
		WHEN N'FI' THEN N'Recibido'
		ELSE N'' END NOMBRE_ESTADO_ORDEN_COMPRA
	,A.OBSERVACIONES
	,A.COMPRA_TOTAL
	,ISNULL(SUM(D.MONTO_SUBTOTAL), 0) MONTO_SUBTOTAL
	,CONVERT(BIT, 0) SELECCION
	,A.USUARIO_CREA
	,A.FECHA_CREA
	,A.USUARIO_ACTU
	,A.FECHA_ACTU
FROM dbo.COM_ORDEN_COMPRA A
INNER JOIN dbo.V_COM_PROVEEDOR P ON A.CORR_PROVEEDOR = P.CORR_PROVEEDOR
LEFT JOIN dbo.COM_ORDEN_COMPRA_DETA D
	ON A.CORR_EMPRESA = D.CORR_EMPRESA
	AND A.ANIO_PERIODO = D.ANIO_PERIODO
	AND A.CORR_ORDEN_COMPRA = D.CORR_ORDEN_COMPRA
WHERE A.ESTADO_ORDEN = N'SO'
GROUP BY
	 A.CORR_EMPRESA, A.ANIO_PERIODO, A.CORR_ORDEN_COMPRA, A.NUMERO_ORDEN_COMPRA, A.CORR_PROVEEDOR,
	 P.NOMBRE_PROVEEDOR, A.FECHA_ORDEN, A.ESTADO_ORDEN, A.OBSERVACIONES, A.COMPRA_TOTAL,
	 A.USUARIO_CREA, A.FECHA_CREA, A.USUARIO_ACTU, A.FECHA_ACTU
GO
