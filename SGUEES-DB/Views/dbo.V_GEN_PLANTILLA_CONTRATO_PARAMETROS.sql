-- =========================================================================
-- Vista: dbo.V_GEN_PLANTILLA_CONTRATO_PARAMETROS
-- Qué hace: cataloga los parámetros dinámicos disponibles para redactar plantillas de contratos laborales.
-- Cómo lo hace: define mediante UNION ALL las categorías funcionales, tokens {{key}}, etiquetas y descripciones ordenadas.
-- =========================================================================
CREATE OR ALTER VIEW [dbo].[V_GEN_PLANTILLA_CONTRATO_PARAMETROS]
AS
SELECT
	CATEGORIA,
	ORDEN_CATEGORIA,
	KEY_PARAMETRO,
	LABEL_PARAMETRO,
	DESCRIPCION,
	ORDEN_PARAMETRO
FROM (
	-- 1. PATRONO Y RECTORÍA
	SELECT 1 AS ORDEN_CATEGORIA, '1. PATRONO Y RECTORÍA' AS CATEGORIA, 1 AS ORDEN_PARAMETRO, 'EMPRESA_NOMBRE_LARGO' AS KEY_PARAMETRO, 'Nombre Empresa' AS LABEL_PARAMETRO, 'GEN_EMPRESA.NOMBRE_EMPRESA_LARGO' AS DESCRIPCION
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 2, 'EMPRESA_NIT', 'NIT Patrono', 'GEN_EMPRESA.NUMERO_NIT'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 3, 'EMPRESA_DIRECCION', 'Dirección Patrono', 'GEN_EMPRESA.DIRECCION_EMPRESA_LARGO'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 4, 'SUCURSAL_NOMBRE', 'Sede / Sucursal', 'V_GEN_SUCURSALES.NOMBRE_SUCURSAL'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 5, 'RECTOR_NOMBRE', 'Nombre Rector(a)', 'Jefe activo unidad Rectoría (Organigrama)'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 6, 'RECTOR_PUESTO', 'Cargo Rector(a)', 'V_SC_ORGANIGRAMA_ESTRUCTURAL_JEFES_UNIDADES.NOMBRE_PUESTO'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 7, 'RECTOR_DUI', 'DUI Rector(a)', 'Documento identidad del titular de Rectoría'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 8, 'RECTOR_EDAD', 'Edad Rector(a)', 'V_GEN_PERSONA_NATURAL.EDAD'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 9, 'RECTOR_PROFESION', 'Profesión Rector(a)', 'V_GEN_PERSONA_FORMACION_ACADEMICA.TITULO'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 10, 'RECTOR_ESTADO_CIVIL', 'Estado Civil Rector(a)', 'V_GEN_PERSONA_NATURAL.ESTADO_CIVIL'
	UNION ALL SELECT 1, '1. PATRONO Y RECTORÍA', 11, 'RECTOR_DOMICILIO', 'Domicilio Rector(a)', 'V_GEN_PERSONA_DOMICILIO'

	-- 2. DATOS DEL EMPLEADO
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 1, 'CODIGO_EMPLEADO', 'Código Empleado', 'V_GEN_EMPLEADO.CODIGO_EMPLEADO'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 2, 'EMPLEADO_NOMBRE_COMPLETO', 'Nombre Completo', 'V_GEN_EMPLEADO.NOMBRE_EMPLEADO'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 3, 'EMPLEADO_DUI', 'DUI Empleado', 'V_GEN_EMPLEADO.DUI'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 4, 'EMPLEADO_NIT', 'NIT Empleado', 'V_GEN_EMPLEADO.NIT'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 5, 'EMPLEADO_EDAD', 'Edad', 'V_GEN_PERSONA_NATURAL.EDAD'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 6, 'EMPLEADO_ESTADO_CIVIL', 'Estado Civil', 'V_GEN_PERSONA_NATURAL.ESTADO_CIVIL'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 7, 'EMPLEADO_NACIONALIDAD', 'Nacionalidad', 'V_GEN_PERSONA_NATURAL.NACIONALIDAD'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 8, 'EMPLEADO_PROFESION', 'Profesión / Título', 'V_GEN_PERSONA_FORMACION_ACADEMICA.TITULO'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 9, 'EMPLEADO_DIRECCION', 'Dirección Residencia', 'V_GEN_PERSONA_DOMICILIO.DIRECCION'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 10, 'EMPLEADO_MUNICIPIO', 'Municipio', 'V_GEN_PERSONA_DOMICILIO.NOMBRE_MUNICIPIO'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 11, 'EMPLEADO_DEPTO', 'Departamento', 'V_GEN_PERSONA_DOMICILIO.NOMBRE_DEPTO'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 12, 'EMPLEADO_CORREO', 'Correo Institucional', 'V_GEN_EMPLEADO.CORREO_INSTITUCIONAL'
	UNION ALL SELECT 2, '2. DATOS DEL EMPLEADO', 13, 'EMPLEADO_TELEFONO', 'Teléfono', 'V_GEN_EMPLEADO.TELEFONO_1'

	-- 3. CARGO, MOVIMIENTO Y SALARIO
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 1, 'NOMBRE_PUESTO', 'Puesto Laboral', 'PLA_PUESTO.NOMBRE_PUESTO'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 2, 'MISION_PUESTO', 'Misión del Puesto', 'PLA_PUESTO.MISION_PUESTO'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 3, 'NOMBRE_UNIDAD', 'Unidad / Área', 'V_SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES.NOMBRE_UNIDAD'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 4, 'NOMBRE_UNIDAD_PADRE', 'Unidad Superior', 'V_SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES.NOMBRE_UNIDAD_PADRE'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 5, 'TIPO_CONTRATACION', 'Tipo de Contratación', 'SC_TIPO_CONTRATACION.NOMBRE_TIPO_CONTRATACION'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 6, 'MODALIDAD_TRABAJO', 'Modalidad', 'SC_TIPO_MODALIDAD.MODALIDAD_NOMBRE'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 7, 'SALARIO_MENSUAL', 'Salario Mensual', 'GEN_EMPLEADO_PUESTO.SUELDO'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 8, 'SALARIO_EN_LETRAS', 'Salario en Letras', 'Monto mensual expresado en texto'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 9, 'HORARIO_LABORAL', 'Horario Laboral', 'GEN_EMPLEADO_PUESTO.HORARIO_LABORAL'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 10, 'FECHA_INGRESO', 'Fecha de Ingreso', 'GEN_EMPLEADO_PUESTO.FECHA_INGRESO'
	UNION ALL SELECT 3, '3. CARGO, MOVIMIENTO Y SALARIO', 11, 'FECHA_FINALIZACION', 'Fecha Finalización', 'SC_MOVIMIENTO_PERSONAL.FECHA_FINALIZACION'

	-- 4. DOCUMENTO Y FECHAS
	UNION ALL SELECT 4, '4. DOCUMENTO Y FECHAS', 1, 'CIUDAD_FIRMA', 'Ciudad de Firma', 'Municipio de sede o patrono'
	UNION ALL SELECT 4, '4. DOCUMENTO Y FECHAS', 2, 'FECHA_FIRMA', 'Fecha de Firma', 'Fecha de emisión del contrato'
	UNION ALL SELECT 4, '4. DOCUMENTO Y FECHAS', 3, 'FECHA_ACTUAL_LETRAS', 'Fecha Actual en Letras', 'Fecha redactada para comparecencia'
	UNION ALL SELECT 4, '4. DOCUMENTO Y FECHAS', 4, 'ANIO_ACTUAL', 'Año Actual', 'Año calendario vigente'
) P
