/*
  V_COM_PROVEEDOR — origen SGUEES (COM_PROVEEDOR). Sin linked server CLASS.

  HISTÓRICO CLASS (NO ELIMINAR — solo desconectado):
  ----------------------------------------------------------------
  Master anterior: [CLASS_UEES].[CLASS_UEES].[CLASS_UEES].dbo.CLIENTES AA
  JOIN COM_PROVEEDOR A ON AA.CLIIDU = A.CORR_PROVEEDOR
  WHERE AA.CLITIP IN ('V','P')  + UNION ALL
  Catálogos CLASS: CODIGOS / PAISES / PROVINCIAS
  Catálogos e-AdminFE (también desconectados aquí por prefijos linked server):
    [EADMINFE].[EADMINFE].[e-AdminFE].dbo.GEN_TIPO_DIP
    [EADMINFE].[EADMINFE].[e-AdminFE].dbo.GEN_FORMA_PAGO
    [EADMINFE].[EADMINFE].[e-AdminFE].dbo.GEN_SECTOR
  Script de referencia: Scripts/UPDATE_V_COM_PROVEEDOR.sql
  ----------------------------------------------------------------
  Nombres de catálogo externo quedan vacíos; el form SPA sigue usando lookups API.
*/
CREATE OR ALTER VIEW [dbo].[V_COM_PROVEEDOR]
AS
SELECT
	A.CORR_PROVEEDOR,
	A.CODIGO_PROVEEDOR,
	A.TIPO_PERSONERIA,
	CASE A.TIPO_PERSONERIA
		WHEN N'N' THEN N'Natural'
		WHEN N'J' THEN N'Jurídico'
		ELSE N''
	END AS NOMBRE_TIPO_PERSONERIA,
	A.NOMBRE_PROVEEDOR,
	ISNULL(A.PRIMER_NOMBRE, N'') AS PRIMER_NOMBRE,
	ISNULL(A.SEGUNDO_NOMBRE, N'') AS SEGUNDO_NOMBRE,
	ISNULL(A.PRIMER_APELLIDO, N'') AS PRIMER_APELLIDO,
	ISNULL(A.SEGUNDO_APELLIDO, N'') AS SEGUNDO_APELLIDO,
	ISNULL(A.NOMBRE_COMERCIAL, N'') AS NOMBRE_COMERCIAL,
	A.CORR_TIPO_DIP,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_TIPO_DIP,
	ISNULL(A.NUMERO_DIP, N'') AS NUMERO_DIP,
	ISNULL(A.NUMERO_NRC, N'') AS NUMERO_NRC,
	ISNULL(A.NUMERO_NIT, N'') AS NUMERO_NIT,
	ISNULL(LTRIM(RTRIM(A.CORR_ACTIVIDAD_ECONOMICA)), N'') AS CORR_ACTIVIDAD_ECONOMICA,
	CAST(N'' AS VARCHAR(150)) AS NOMBRE_ACTIVIDAD_ECONOMICA,
	ISNULL(A.DIRECCION_PROVEEDOR, N'') AS DIRECCION_PROVEEDOR,
	RTRIM(LTRIM(ISNULL(A.CODIGO_PAIS, N'SLV'))) AS CODIGO_PAIS,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_PAIS,
	ISNULL(RTRIM(LTRIM(A.CODIGO_DEPTO)), N'') AS CODIGO_DEPTO,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_DEPTO,
	ISNULL(RTRIM(LTRIM(A.CODIGO_MUNICIPIO)), N'') AS CODIGO_MUNICIPIO,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_MUNICIPIO,
	ISNULL(A.NOMBRE_CONTACTO, N'') AS NOMBRE_CONTACTO,
	ISNULL(A.TELEFONO_FIJO, N'') AS TELEFONO_FIJO,
	ISNULL(A.TELEFONO_MOVIL, N'') AS TELEFONO_MOVIL,
	ISNULL(A.CORREO_ELECTRONICO_1, N'') AS CORREO_ELECTRONICO_1,
	ISNULL(A.CORREO_ELECTRONICO_2, N'') AS CORREO_ELECTRONICO_2,
	ISNULL(A.CORR_FORMA_PAGO, 0) AS CORR_FORMA_PAGO,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_FORMA_PAGO,
	ISNULL(A.CUENTA_BANCARIA, N'') AS CUENTA_BANCARIA,
	ISNULL(A.CORR_BANCO, 0) AS CORR_BANCO,
	ISNULL(H.NOMBRE_BANCO, N'') AS NOMBRE_BANCO,
	ISNULL(A.ESTADO_PROVEEDOR, N'I') AS ESTADO_PROVEEDOR,
	CASE ISNULL(A.ESTADO_PROVEEDOR, N'I')
		WHEN N'A' THEN N'Activo'
		WHEN N'I' THEN N'Inactivo'
		ELSE N''
	END AS NOMBRE_ESTADO_PROVEEDOR,
	ISNULL(A.ESTADO_PROVEEDOR_WEB, N'D') AS ESTADO_PROVEEDOR_WEB,
	CASE ISNULL(A.ESTADO_PROVEEDOR_WEB, N'D')
		WHEN N'D' THEN N'Digitado'
		WHEN N'A' THEN N'Activo'
		WHEN N'I' THEN N'Inactivo'
		ELSE N''
	END AS NOMBRE_ESTADO_PROVEEDOR_WEB,
	ISNULL(A.CORR_CONDICION_PAGO, 0) AS CORR_CONDICION_PAGO,
	ISNULL(I.NOMBRE_CONDICION_PAGO, N'') AS NOMBRE_CONDICION_PAGO,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU,
	CAST(N'' AS VARCHAR(10)) AS CLASE_TAMANIO,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_CLASE_TAMANIO,
	ISNULL(N.CORR_SECTOR, 0) AS CORR_SECTOR,
	CAST(N'' AS VARCHAR(100)) AS NOMBRE_SECTOR
FROM dbo.COM_PROVEEDOR A
LEFT JOIN dbo.COM_BANCO H
	ON A.CORR_BANCO = H.CORR_BANCO
LEFT JOIN dbo.COM_CONDICION_PAGO I
	ON A.CORR_CONDICION_PAGO = I.CORR_CONDICION_PAGO
LEFT JOIN dbo.CLA_COM_PROVEEDOR_SECTOR N
	ON A.CORR_PROVEEDOR = N.CORR_PROVEEDOR
GO
