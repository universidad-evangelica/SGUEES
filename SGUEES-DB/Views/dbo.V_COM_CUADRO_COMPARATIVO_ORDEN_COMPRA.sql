CREATE VIEW [dbo].[V_COM_CUADRO_COMPARATIVO_ORDEN_COMPRA]
AS
SELECT
	 A.CORR_EMPRESA
	,A.ANIO_PERIODO
	,A.CORR_CUADRO_COMPARATIVO
	,A.NUMERO_ORDEN
	,A.CORR_ORDEN_COMPRA
	,A.CORR_PROVEEDOR
	,ISNULL(P.NOMBRE_PROVEEDOR, '') NOMBRE_PROVEEDOR
	,A.MONTO_TOTAL_ORDEN
	,LTRIM(RTRIM(ISNULL(P.NOMBRE_CONTACTO, ''))) NOMBRE_CONTACTO
	,A.CORR_CONDICION_PAGO
	,C.NOMBRE_CONDICION_PAGO
	,A.CORR_FORMA_PAGO
	,D.NOMBRE_FORMA_PAGO
	,A.DETALLE_FORMA_PAGO
	,O.ESTADO_ORDEN ESTADO_ORDEN_COMPRA
	,CASE O.ESTADO_ORDEN
		WHEN 'DI' THEN 'Digitada'
		WHEN 'SO' THEN 'Solicitada'
		WHEN 'AP' THEN 'Aplicada'
		WHEN 'AN' THEN 'Anulada'
		WHEN 'FI' THEN 'Recibido'
		ELSE '' END NOMBRE_ESTADO_ORDEN_COMPRA
	,O.FECHA_ORDEN FECHA_ORDEN_COMPRA
	,O.NUMERO_ORDEN_COMPRA
FROM dbo.COM_CUADRO_COMPARATIVO_ORDEN_COMPRA A
LEFT JOIN dbo.COM_ORDEN_COMPRA O
	ON A.CORR_EMPRESA = O.CORR_EMPRESA
	AND A.ANIO_PERIODO = O.ANIO_PERIODO
	AND A.CORR_ORDEN_COMPRA = O.CORR_ORDEN_COMPRA
LEFT JOIN dbo.V_COM_PROVEEDOR P
	ON A.CORR_PROVEEDOR = P.CORR_PROVEEDOR
LEFT JOIN dbo.COM_CONDICION_PAGO C
	ON A.CORR_EMPRESA = C.CORR_EMPRESA
	AND A.CORR_CONDICION_PAGO = C.CORR_CONDICION_PAGO
LEFT JOIN dbo.V_GEN_FORMA_PAGO D
	ON A.CORR_FORMA_PAGO = D.CORR_FORMA_PAGO
GO
