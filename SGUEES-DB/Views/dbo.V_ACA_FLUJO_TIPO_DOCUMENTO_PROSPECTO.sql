CREATE OR ALTER VIEW [dbo].[V_ACA_FLUJO_TIPO_DOCUMENTO_PROSPECTO]
AS
SELECT
	T.[CORR_EMPRESA],
	T.[CORR_TIPO_DOCUMENTO],
	T.[NOMBRE_TIPO],
	T.[DESCRIPCION],
	T.[CODIGO_OPCION],
	T.[ACTIVO],
	ISNULL(C.[CANT_DOCUMENTOS], 0) AS [CANT_DOCUMENTOS]
FROM [dbo].[SEG_FLUJO_TIPO_DOCUMENTO] AS T
LEFT JOIN (
	SELECT
		A.[CORR_EMPRESA],
		A.[CORR_TIPO_DOCUMENTO],
		COUNT(*) AS [CANT_DOCUMENTOS]
	FROM [dbo].[ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO] AS A
	GROUP BY A.[CORR_EMPRESA], A.[CORR_TIPO_DOCUMENTO]
) AS C
	ON C.[CORR_EMPRESA] = T.[CORR_EMPRESA]
   AND C.[CORR_TIPO_DOCUMENTO] = T.[CORR_TIPO_DOCUMENTO]
WHERE T.[ACTIVO] = 1
  AND T.[CODIGO_OPCION] IN (
		N'ACA_PROSPECTO',
		N'ACA_PROSPECTO_SOCIOECONOMICO',
		N'ACA_PROSPECTO_BECA'
  );
GO
