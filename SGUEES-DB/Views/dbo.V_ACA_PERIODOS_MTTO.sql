-- Qué hace: períodos académicos con sede, alcance y si ya están en uso.
-- Cómo lo hace: nombra cada columna de ACA_PERIODOS_ACADEMICOS. No usa SELECT *
--               porque, al agregar CORR_CICLO_ACADEMICO y ES_GESTIONADO_CICLO,
--               la vista corrida leía el ciclo como si fuera la empresa.
-- El usuario lo ejecuta en SGUEES. No cambia la tabla.
CREATE OR ALTER VIEW [dbo].[V_ACA_PERIODOS_MTTO]
AS
SELECT
	P.CORR_PERIODO_ACADEMICO,
	P.CORR_SEDE,
	P.CORR_AREA_ACADEMICA,
	P.CORR_FACULTAD,
	P.CORR_CARRERA,
	P.ANIO,
	P.NUMERO_PERIODO,
	P.FECHA_INICIO,
	P.FECHA_FIN,
	P.FECHA_INICIO_INSCRIPCION,
	P.FECHA_FIN_INSCRIPCION,
	P.USUARIO_CREA,
	P.ESTACION_CREA,
	P.FECHA_CREA,
	P.USUARIO_ACTU,
	P.ESTACION_ACTU,
	P.FECHA_ACTU,
	P.ACTIVO,
	P.CORR_CICLO_ACADEMICO,
	P.ES_GESTIONADO_CICLO,
	S.CORR_EMPRESA,
	S.NOMBRE_SEDE,
	A.NOMBRE_AREA,
	F.NOMBRE_FACULTAD,
	C.NOMBRE_CARRERA,
	CAST(CASE
		WHEN P.CORR_CARRERA IS NOT NULL THEN 'Carrera'
		WHEN P.CORR_FACULTAD IS NOT NULL THEN 'Facultad'
		ELSE 'Área'
	END AS varchar(12)) AS ALCANCE,
	CAST(CASE
		WHEN EXISTS (SELECT 1 FROM dbo.ACA_PROSPECTO R WHERE R.CORR_PERIODO_ACADEMICO = P.CORR_PERIODO_ACADEMICO)
		  OR EXISTS (SELECT 1 FROM dbo.ACA_PROSPECTO_BECA R WHERE R.CORR_PERIODO_ACADEMICO = P.CORR_PERIODO_ACADEMICO)
		  OR EXISTS (SELECT 1 FROM dbo.ACA_PROSPECTO_DOCUMENTO R WHERE R.CORR_PERIODO_ACADEMICO = P.CORR_PERIODO_ACADEMICO)
		THEN 1 ELSE 0
	END AS bit) AS EN_USO
FROM dbo.ACA_PERIODOS_ACADEMICOS P
INNER JOIN dbo.GEN_SEDES S
	ON S.CORR_SEDE = P.CORR_SEDE
INNER JOIN dbo.ACA_AREAS_ACADEMICAS A
	ON A.CORR_AREA_ACADEMICA = P.CORR_AREA_ACADEMICA
	AND A.CORR_EMPRESA = S.CORR_EMPRESA
LEFT JOIN dbo.ACA_FACULTADES F
	ON F.CORR_FACULTAD = P.CORR_FACULTAD
	AND F.CORR_EMPRESA = S.CORR_EMPRESA
LEFT JOIN dbo.ACA_CARRERAS C
	ON C.CORR_CARRERA = P.CORR_CARRERA
	AND C.CORR_EMPRESA = S.CORR_EMPRESA;
GO
