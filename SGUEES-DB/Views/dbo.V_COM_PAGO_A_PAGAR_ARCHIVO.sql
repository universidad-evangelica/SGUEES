CREATE VIEW [dbo].[V_COM_PAGO_A_PAGAR_ARCHIVO]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_PAGO     
      ,(((CONVERT(INT,SUBSTRING(LTRIM(RTRIM(CONVERT(VARCHAR,A.ANIO_PERIODO))),3,2))*100)+A.MES_PERIODO)*1000)+A.CORR_PAGO NUMERO_PAGO
      ,A.FECHA_PAGO
      ,A.CORR_PROVEEDOR
      ,B.NOMBRE_PROVEEDOR 
      ,A.CORR_CUENTA_BANCO
      ,C.DESCRIPCION_PARTIDA NOMBRE_PARTIDA
	  ,D.MONTO_PAGO 
      --,A.MONTO_PAGO      
      ,ISNULL(A.NOMBRE_BENEFICIARIO,'') NOMBRE_BENEFICIARIO
      ,A.CORR_ARCHIVO
      ,CONVERT(BIT,0) SELECCION      
      ,CONVERT(DECIMAL(14,2),0) MONTO_ARCHIVO
FROM COM_PAGO A
INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR 
INNER JOIN COM_PAGO_DETA D ON A.CORR_EMPRESA=D.CORR_EMPRESA AND A.ANIO_PERIODO=D.ANIO_PERIODO AND A.MES_PERIODO=D.MES_PERIODO AND A.CORR_PAGO=D.CORR_PAGO				
INNER JOIN COM_DOCUMENTO C ON D.CORR_EMPRESA=C.CORR_EMPRESA AND D.ANIO_PERIODO_COM=C.ANIO_PERIODO AND D.MES_PERIODO_COM=C.MES_PERIODO AND D.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO 
WHERE A.ESTADO_PAGO = 'DI'
AND ISNULL(A.CORR_ARCHIVO,0)=0


GO




