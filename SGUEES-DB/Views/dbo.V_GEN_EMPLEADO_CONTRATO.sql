-- Qué hace: proyecta los contratos asignados por empleado con datos de plantilla, versión, unidad, puesto y estado legible.
-- Cómo lo hace: une GEN_EMPLEADO_CONTRATO con V_GEN_EMPLEADO, GEN_PLANTILLA_CONTRATO_VERSION, GEN_PLANTILLA_CONTRATO, SC_TIPO_CONTRATACION, SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES y PLA_PUESTO.
CREATE VIEW [dbo].[V_GEN_EMPLEADO_CONTRATO]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_EMPLEADO_CONTRATO,
	A.CORR_EMPLEADO,
	E.CODIGO_EMPLEADO,
	E.NOMBRE_EMPLEADO,
	E.DUI,
	A.CORR_UNIDAD,
	U.NOMBRE_UNIDAD,
	A.CORR_PUESTO,
	P.NOMBRE_PUESTO,
	A.CORR_PLANTILLA_CONTRATO_VERSION,
	PV.CORR_PLANTILLA_CONTRATO,
	PC.NOMBRE_PLANTILLA,
	PC.CORR_TIPO_CONTRATACION,
	TC.NOMBRE_TIPO_CONTRATACION,
	PV.NUMERO_VERSION,
	PV.NOMBRE_VERSION,
	A.CUERPO_CONTRATO,
	A.FECHA_INICIO,
	A.FECHA_FIN,
	A.FECHA_FIRMA,
	A.ESTADO_CONTRATO,
	CASE A.ESTADO_CONTRATO
		WHEN 1 THEN 'Borrador'
		WHEN 2 THEN 'Vigente'
		WHEN 3 THEN 'Finalizado'
		WHEN 4 THEN 'Anulado'
		ELSE CAST(A.ESTADO_CONTRATO AS VARCHAR(20))
	END AS NOMBRE_ESTADO_CONTRATO,
	A.NOMBRE_ARCHIVO,
	A.RUTA_ARCHIVO,
	CAST(CASE WHEN NULLIF(LTRIM(RTRIM(ISNULL(A.RUTA_ARCHIVO, ''))), '') IS NOT NULL THEN 1 ELSE 0 END AS BIT) AS TIENE_ARCHIVO_FIRMADO,
	A.FECHA_CARGA,
	A.MOTIVO_ANULACION,
	A.USUARIO_CREA,
	A.ESTACION_CREA,
	A.FECHA_CREA,
	A.USUARIO_ACTU,
	A.ESTACION_ACTU,
	A.FECHA_ACTU
FROM [dbo].[GEN_EMPLEADO_CONTRATO] A
LEFT JOIN [dbo].[V_GEN_EMPLEADO] E
	ON E.CORR_EMPRESA = A.CORR_EMPRESA
	AND E.CORR_EMPLEADO = A.CORR_EMPLEADO
LEFT JOIN [dbo].[GEN_PLANTILLA_CONTRATO_VERSION] PV
	ON PV.CORR_EMPRESA = A.CORR_EMPRESA
	AND PV.CORR_PLANTILLA_CONTRATO_VERSION = A.CORR_PLANTILLA_CONTRATO_VERSION
LEFT JOIN [dbo].[GEN_PLANTILLA_CONTRATO] PC
	ON PC.CORR_EMPRESA = PV.CORR_EMPRESA
	AND PC.CORR_PLANTILLA_CONTRATO = PV.CORR_PLANTILLA_CONTRATO
LEFT JOIN [dbo].[SC_TIPO_CONTRATACION] TC
	ON TC.CORR_EMPRESA = PC.CORR_EMPRESA
	AND TC.CORR_TIPO_CONTRATACION = PC.CORR_TIPO_CONTRATACION
LEFT JOIN [dbo].[SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES] U
	ON U.CORR_EMPRESA = A.CORR_EMPRESA
	AND U.CORR_UNIDAD = A.CORR_UNIDAD
LEFT JOIN [dbo].[PLA_PUESTO] P
	ON P.CORR_EMPRESA = A.CORR_EMPRESA
	AND P.CORR_PUESTO = A.CORR_PUESTO
GO

