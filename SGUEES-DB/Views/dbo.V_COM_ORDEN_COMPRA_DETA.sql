CREATE VIEW [dbo].[V_COM_ORDEN_COMPRA_DETA]
AS
SELECT
	 D.CORR_EMPRESA
	,D.ANIO_PERIODO
	,D.CORR_ORDEN_COMPRA
	,D.CORR_ORDEN_COMPRA_DETA
	,O.NUMERO_ORDEN_COMPRA
	,O.FECHA_ORDEN FECHA_ORDEN_COMPRA
	,D.CODIGO_ITEM
	,ISNULL(CD.OBSERVACIONES, D.CODIGO_ITEM) NOMBRE_ITEM
	,D.CORR_UNIDAD_MEDIDA
	,ISNULL(U.NOMBRE_UNIDAD_MEDIDA, '') NOMBRE_UNIDAD_MEDIDA
	,D.CANTIDAD_COMPRA CANTIDAD
	,D.PRECIO_UNITARIO
	,D.MONTO_SUBTOTAL
	,D.ANIO_PERIODO_COTIZACION
	,D.CORR_COTIZACION
	,D.CORR_COTIZACION_DETA
	,D.CORR_CENTRO_COSTO
	,D.CANTIDAD_RECIBIDA
	,D.USUARIO_CREA
	,D.FECHA_CREA
	,D.ESTACION_CREA
	,D.USUARIO_ACTU
	,D.FECHA_ACTU
	,D.ESTACION_ACTU
FROM dbo.COM_ORDEN_COMPRA_DETA D
INNER JOIN dbo.COM_ORDEN_COMPRA O
	ON D.CORR_EMPRESA = O.CORR_EMPRESA
	AND D.ANIO_PERIODO = O.ANIO_PERIODO
	AND D.CORR_ORDEN_COMPRA = O.CORR_ORDEN_COMPRA
LEFT JOIN dbo.COM_UNIDAD_MEDIDA U
	ON D.CORR_EMPRESA = U.CORR_EMPRESA
	AND D.CORR_UNIDAD_MEDIDA = U.CORR_UNIDAD_MEDIDA
LEFT JOIN dbo.COM_COTIZACION_DETA CD
	ON D.CORR_EMPRESA = CD.CORR_EMPRESA
	AND D.ANIO_PERIODO_COTIZACION = CD.ANIO_PERIODO
	AND D.CORR_COTIZACION = CD.CORR_COTIZACION
	AND D.CORR_COTIZACION_DETA = CD.CORR_COTIZACION_DETA
GO
