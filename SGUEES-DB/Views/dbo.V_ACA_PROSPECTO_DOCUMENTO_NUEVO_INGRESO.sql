CREATE OR ALTER VIEW [dbo].[V_ACA_PROSPECTO_DOCUMENTO_NUEVO_INGRESO]
AS
SELECT
    AA.CORR_EMPRESA,
    P.CORR_PROSPECTO,
    D.CORR_DOCUMENTO_ADMISION,
    D.NOMBRE_DOCUMENTO,
    D.CODIGO,
    D.OBLIGATORIO,
    D.ORDEN,
    D.FORMATOS_PERMITIDOS,
    D.TAMANO_MAXIMO_MB,
    DOC.CORR_PROSPECTO_DOCUMENTO,
    DOC.NOMBRE_ARCHIVO,
    DOC.FECHA_CARGA,
    DOC.ESTADO_REVISION
FROM dbo.ACA_PROSPECTO AS P
INNER JOIN dbo.ACA_PERIODOS_ACADEMICOS AS PA
    ON PA.CORR_PERIODO_ACADEMICO = P.CORR_PERIODO_ACADEMICO
INNER JOIN dbo.ACA_AREAS_ACADEMICAS AS AA
    ON AA.CORR_AREA_ACADEMICA = PA.CORR_AREA_ACADEMICA
INNER JOIN dbo.ACA_DOCUMENTO_ADMISION_FLUJO_TIPO_DOCUMENTO AS F
    ON F.CORR_EMPRESA = AA.CORR_EMPRESA
   AND F.CORR_TIPO_DOCUMENTO = 104
INNER JOIN dbo.ACA_DOCUMENTO_ADMISION AS D
    ON D.CORR_DOCUMENTO_ADMISION = F.CORR_DOCUMENTO_ADMISION
   AND D.ACTIVO = 1
INNER JOIN dbo.ACA_DOCUMENTO_ADMISION_REGLA AS R
    ON R.CORR_DOCUMENTO_ADMISION = D.CORR_DOCUMENTO_ADMISION
   AND R.ES_EQUIVALENCIA = CASE WHEN UPPER(LTRIM(RTRIM(ISNULL(P.FORMA_INGRESO, '')))) = 'EQ' THEN CAST(1 AS bit) ELSE CAST(0 AS bit) END
   AND R.CON_CUOTA_MAXIMA = CAST(ISNULL((
        SELECT TOP 1 CASE WHEN S.APLICA_CUOTA_MAXIMA = 1 THEN 1 ELSE 0 END
        FROM dbo.ACA_PROSPECTO_PERSONA AS PE
        INNER JOIN dbo.ACA_PROSPECTO_SOCIOECONOMICO AS S
            ON S.CORR_PROSPECTO_PERSONA = PE.CORR_PROSPECTO_PERSONA
        WHERE PE.CORR_PROSPECTO = P.CORR_PROSPECTO
        ORDER BY S.CORR_PROSPECTO_SOCIOECONOMICO DESC
   ), 0) AS bit)
OUTER APPLY (
    SELECT TOP 1
        C.CORR_PROSPECTO_DOCUMENTO,
        C.NOMBRE_ARCHIVO,
        C.FECHA_CARGA,
        C.ESTADO_REVISION
    FROM dbo.ACA_PROSPECTO_DOCUMENTO AS C
    WHERE C.CORR_PROSPECTO = P.CORR_PROSPECTO
      AND C.CORR_DOCUMENTO_ADMISION = D.CORR_DOCUMENTO_ADMISION
      AND C.ACTIVO = 1
    ORDER BY C.FECHA_CARGA DESC, C.CORR_PROSPECTO_DOCUMENTO DESC
) AS DOC;
GO
