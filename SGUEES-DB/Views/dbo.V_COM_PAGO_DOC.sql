CREATE VIEW [dbo].[V_COM_PAGO_DOC]
AS
SELECT A.CORR_EMPRESA
		, A.ANIO_PERIODO
		, A.MES_PERIODO
		, A.CORR_PAGO
		, A.ANIO_PERIODO_CHEQUE
		, A.MES_PERIODO_CHEQUE
		, A.CORR_TIPO_MOVIMIENTO CORR_TIPO_MOVIMIENTO_CHEQUE
		, A.CORR_DOCUMENTO_CHEQUE
		, ISNULL(C.NOMBRE_TIPO_CORTO, C.NOMBRE_TIPO_MOVIMIENTO) TIPO_DOCUMENTO
		, B.FECHA_EMISION FECHA_DOCUMENTO
		, B.NUMERO_DOCUMENTO
		, CASE ISNULL(C.CLASE_MOVIMIENTO,'')
		  WHEN 'CHQ' THEN 'BAN_DOCUMENTO'
		  ELSE 'BAN_DOCUMENTO_OTRO' END FORMA
		, LTRIM(RTRIM(CONVERT(VARCHAR,B.CORR_TIPO_MOVIMIENTO)))+'-'+LTRIM(RTRIM(CONVERT(VARCHAR,B.CORR_DOCUMENTO))) ID_DOCUMENTO
FROM COM_PAGO A
INNER JOIN BAN_DOCUMENTO B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.ANIO_PERIODO_CHEQUE=B.ANIO_PERIODO AND A.MES_PERIODO_CHEQUE=B.MES_PERIODO AND A.CORR_TIPO_MOVIMIENTO=B.CORR_TIPO_MOVIMIENTO AND A.CORR_DOCUMENTO_CHEQUE=B.CORR_DOCUMENTO
INNER JOIN BAN_TIPO_MOVI_BANCARIO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.CORR_TIPO_MOVIMIENTO=C.CORR_TIPO_MOVIMIENTO
GO



