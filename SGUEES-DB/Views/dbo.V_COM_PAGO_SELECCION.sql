CREATE VIEW [dbo].[V_COM_PAGO_SELECCION]
AS
SELECT A.CORR_EMPRESA
      ,A.ANIO_PERIODO
      ,A.MES_PERIODO
      ,A.CORR_PAGO
      ,C.NOMBRE_TIPO_DOC 
      ,C.NOMBRE_CORTO_TIPO_DOC 
      ,C.CLASE_DOCUMENTO 
      ,A.FECHA_SOLICITUD
      ,A.FECHA_PAGO
      ,B.NOMBRE_PROVEEDOR 
      ,A.NOMBRE_PARTIDA
      ,A.MONTO_PAGO
      ,A.ESTADO_PAGO
      ,CASE A.ESTADO_PAGO
		  WHEN 'DI' THEN 'Digitado'
		  WHEN 'AP' THEN 'Aplicado'
		  ELSE '' END NOMBRE_ESTADO_PAGO
      ,CONVERT(BIT,0) SELECCION
  FROM COM_PAGO A
  INNER JOIN GEN_PROVEEDOR B ON A.CORR_EMPRESA=B.CORR_EMPRESA AND A.CORR_PROVEEDOR=B.CORR_PROVEEDOR 
  INNER JOIN GEN_TIPO_DOCUMENTO C ON A.CORR_EMPRESA=C.CORR_EMPRESA AND A.CORR_TIPO_DOC=C.CORR_TIPO_DOC
GO



