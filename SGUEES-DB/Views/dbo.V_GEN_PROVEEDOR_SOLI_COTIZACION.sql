-- Qué hace: lookup de proveedores activos para la solicitud de cotización.
-- Cómo: solo GEN_PROVEEDOR. La empresa la filtra GetAllPROVEEDOR_DISPONIBLE.
--       SELECCION y DETALLE_FORMA_PAGO los arma la vista; no existen en la tabla.
-- Permiso: el GET sigue en COM_SOLI_COTIZACION con /com-soli-cotizacion|R.
CREATE OR ALTER VIEW [dbo].[V_GEN_PROVEEDOR_SOLI_COTIZACION]
AS
SELECT
	A.CORR_EMPRESA,
	CONVERT(BIT, 0) AS SELECCION,
	A.CORR_PROVEEDOR,
	A.CODIGO_PROVEEDOR,
	A.NOMBRE_PROVEEDOR,
	ISNULL(A.CORR_FORMA_PAGO, 4) AS CORR_FORMA_PAGO,
	ISNULL(A.CORR_CONDICION_PAGO, 0) AS CORR_CONDICION_PAGO,
	CAST(N'' AS VARCHAR(100)) AS DETALLE_FORMA_PAGO
FROM dbo.GEN_PROVEEDOR A
WHERE A.ESTADO_PROVEEDOR = N'A'
GO
