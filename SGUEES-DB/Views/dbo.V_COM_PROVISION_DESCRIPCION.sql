CREATE VIEW [dbo].[V_COM_PROVISION_DESCRIPCION]
AS
SELECT B.CORR_EMPRESA
,B.ANIO_PERIODO
,B.MES_PERIODO
,B.CORR_PROVISION
,RTRIM(LTRIM(dbo.StrConcat(DISTINCT C.DESCRIPCION_PARTIDA+' '))) DESCRIPCION_PARTIDA
FROM COM_PROVISION_DETA B
INNER JOIN COM_DOCUMENTO C ON B.CORR_EMPRESA=C.CORR_EMPRESA AND B.ANIO_PERIODO_COM=C.ANIO_PERIODO AND B.MES_PERIODO_COM=C.MES_PERIODO AND B.CORR_DOCUMENTO_COM=C.CORR_DOCUMENTO
GROUP BY B.CORR_EMPRESA
,B.ANIO_PERIODO
,B.MES_PERIODO
,B.CORR_PROVISION
GO



