CREATE VIEW [dbo].[V_COM_ORDEN_COMPRA]
AS
SELECT
	 A.CORR_EMPRESA
	,A.ANIO_PERIODO
	,A.CORR_ORDEN_COMPRA
	,A.CORR_TIPO_DOC
	,ISNULL(T.NOMBRE_TIPO_DOC, '') NOMBRE_TIPO_DOC
	,A.CORR_PROVEEDOR
	,P.CODIGO_PROVEEDOR
	,P.NOMBRE_PROVEEDOR
	,P.DIRECCION_PROVEEDOR
	,P.NOMBRE_COMERCIAL
	,P.NOMBRE_ACTIVIDAD_ECONOMICA ACTIVIDAD_ECONOMICA
	,P.NOMBRE_CONTACTO
	,P.CORREO_ELECTRONICO_1 CORREO_ELECTRONICO_PROVEEDOR
	,P.TELEFONO_FIJO TELEFONO_PROVEEDOR
	,A.ATENCION_A
	,A.FECHA_ORDEN FECHA_ORDEN_COMPRA
	,A.ESTADO_ORDEN ESTADO_ORDEN_COMPRA
	,CASE A.ESTADO_ORDEN
		WHEN 'DI' THEN 'Digitada'
		WHEN 'SO' THEN 'Solicitada'
		WHEN 'AP' THEN 'Aplicada'
		WHEN 'AN' THEN 'Anulada'
		WHEN 'FI' THEN 'Recibido'
		ELSE '' END NOMBRE_ESTADO_ORDEN_COMPRA
	,A.USUARIO_AUTORIZA
	,A.FECHA_AUTORIZA
	,A.OBSERVACIONES
	,A.COMPRA_TOTAL TOTAL_ORDEN
	,A.COMPRA_TOTAL SUB_TOTAL
	,CONVERT(DECIMAL(18, 6), 0) TOTAL_IMPUESTO
	,A.MONTO_EN_LETRAS TOTAL_EN_LETRAS
	,A.NUMERO_ORDEN_COMPRA
	,A.CORR_CONDICION_PAGO
	,CP.NOMBRE_CONDICION_PAGO
	,A.CORR_FORMA_PAGO
	,FP.NOMBRE_FORMA_PAGO
	,A.DETALLE_FORMA_PAGO
	,B.CORR_CUADRO_COMPARATIVO
	,B.NUMERO_ORDEN
	,H.AUTORIZACIONES_REALIZADAS
	,F.NUMERO_COTIZACION NUMERO_SOLI_COTIZACION
	,F.NOMBRE_DEPTO NOMBRE_DEPARTAMENTO
	,F.USUARIO_CREA USUARIO_CREA_SOLI
	,A.USUARIO_CREA
	,A.FECHA_CREA
	,A.ESTACION_CREA
	,A.USUARIO_ACTU
	,A.FECHA_ACTU
	,A.ESTACION_ACTU
FROM dbo.COM_ORDEN_COMPRA A
INNER JOIN dbo.V_COM_PROVEEDOR P
	ON A.CORR_PROVEEDOR = P.CORR_PROVEEDOR
LEFT JOIN dbo.GEN_TIPO_DOCUMENTO T
	ON A.CORR_EMPRESA = T.CORR_EMPRESA
	AND A.CORR_TIPO_DOC = T.CORR_TIPO_DOC
LEFT JOIN dbo.COM_CONDICION_PAGO CP
	ON A.CORR_EMPRESA = CP.CORR_EMPRESA
	AND A.CORR_CONDICION_PAGO = CP.CORR_CONDICION_PAGO
LEFT JOIN dbo.V_GEN_FORMA_PAGO FP
	ON A.CORR_FORMA_PAGO = FP.CORR_FORMA_PAGO
LEFT JOIN dbo.COM_CUADRO_COMPARATIVO_ORDEN_COMPRA B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.ANIO_PERIODO = B.ANIO_PERIODO
	AND A.CORR_ORDEN_COMPRA = B.CORR_ORDEN_COMPRA
	AND A.CORR_PROVEEDOR = B.CORR_PROVEEDOR
LEFT JOIN dbo.V_COM_CUADRO_COMPARATIVO_AUTORIZACIONES_CONSOLIDADAS H
	ON B.CORR_EMPRESA = H.CORR_EMPRESA
	AND B.ANIO_PERIODO = H.ANIO_PERIODO
	AND B.CORR_CUADRO_COMPARATIVO = H.CORR_CUADRO_COMPARATIVO
LEFT JOIN dbo.V_COM_CUADRO_COMPARATIVO_COTIZACION_SUM F
	ON B.CORR_EMPRESA = F.CORR_EMPRESA
	AND B.ANIO_PERIODO = F.ANIO_PERIODO
	AND B.CORR_CUADRO_COMPARATIVO = F.CORR_CUADRO_COMPARATIVO
GO

