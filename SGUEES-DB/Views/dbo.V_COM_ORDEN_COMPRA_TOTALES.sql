CREATE VIEW [dbo].[V_COM_ORDEN_COMPRA_TOTALES]
AS
SELECT
	 A.CORR_EMPRESA
	,A.ANIO_PERIODO
	,A.CORR_ORDEN_COMPRA
	,A.NUMERO_ORDEN_COMPRA NUMERO_ORDEN
	,A.OBSERVACIONES
	,A.MONTO_EN_LETRAS TOTAL_EN_LETRAS
	,ISNULL(SUM(D.MONTO_SUBTOTAL), 0) SUB_TOTAL
	,CONVERT(DECIMAL(18, 6), 0) TOTAL_IMPUESTO
	,ISNULL(A.COMPRA_TOTAL, ISNULL(SUM(D.MONTO_SUBTOTAL), 0)) TOTAL_ORDEN
FROM dbo.COM_ORDEN_COMPRA A
LEFT JOIN dbo.COM_ORDEN_COMPRA_DETA D
	ON A.CORR_EMPRESA = D.CORR_EMPRESA
	AND A.ANIO_PERIODO = D.ANIO_PERIODO
	AND A.CORR_ORDEN_COMPRA = D.CORR_ORDEN_COMPRA
GROUP BY
	 A.CORR_EMPRESA
	,A.ANIO_PERIODO
	,A.CORR_ORDEN_COMPRA
	,A.NUMERO_ORDEN_COMPRA
	,A.OBSERVACIONES
	,A.MONTO_EN_LETRAS
	,A.COMPRA_TOTAL
GO
