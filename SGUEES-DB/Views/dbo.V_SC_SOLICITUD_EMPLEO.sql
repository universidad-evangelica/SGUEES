CREATE OR ALTER VIEW dbo.V_SC_SOLICITUD_EMPLEO
AS
SELECT
    S.CORR_EMPRESA,
    S.CORR_SOLICITUD_EMPLEO,
    S.FECHA_GENERACION,
    S.CORREO_INVITACION,
    S.DUI,
    S.NOMBRE,
    S.CORR_TIPO_CONTRATACION,
    T.NOMBRE_TIPO_CONTRATACION,
    CAST(ISNULL(T.ES_PERMANENTE, 0) AS bit) AS ES_PERMANENTE,
    S.CORR_PERSONA_DATOS,
    CAST(CASE WHEN EXISTS (
        SELECT 1
        FROM dbo.SC_EXPEDIENTE_SOLICITUD AS ES
        WHERE ES.CORR_EMPRESA = S.CORR_EMPRESA
          AND ES.CORR_SOLICITUD_EMPLEO = S.CORR_SOLICITUD_EMPLEO
    ) THEN 1 ELSE 0 END AS bit) AS TIENE_EXPEDIENTE,
    (
        SELECT TOP (1) ES.CORR_EXPEDIENTE_CANDIDATO
        FROM dbo.SC_EXPEDIENTE_SOLICITUD AS ES
        WHERE ES.CORR_EMPRESA = S.CORR_EMPRESA
          AND ES.CORR_SOLICITUD_EMPLEO = S.CORR_SOLICITUD_EMPLEO
    ) AS CORR_EXPEDIENTE_CANDIDATO,
    CAST(CASE WHEN S.FECHA_GENERACION IS NOT NULL OR EXISTS (
        SELECT 1
        FROM dbo.SC_SOLICITUD_EMPLEO_TOKEN AS T
        WHERE T.CORR_EMPRESA = S.CORR_EMPRESA
          AND T.CORR_SOLICITUD_EMPLEO = S.CORR_SOLICITUD_EMPLEO
    ) THEN 1 ELSE 0 END AS bit) AS TIENE_TOKEN,
    S.ACTIVO,
    S.USUARIO_CREA,
    S.ESTACION_CREA,
    S.FECHA_CREA,
    S.USUARIO_ACTU,
    S.ESTACION_ACTU,
    S.FECHA_ACTU
FROM dbo.SC_SOLICITUD_EMPLEO AS S
LEFT JOIN dbo.SC_TIPO_CONTRATACION AS T
    ON T.CORR_EMPRESA = S.CORR_EMPRESA
   AND T.CORR_TIPO_CONTRATACION = S.CORR_TIPO_CONTRATACION;
GO
