-- Qué hace: catálogo/browse de proveedores (persona + rol).
-- Cómo: GEN_PROVEEDOR + GEN_PERSONA_PROVEEDOR + NATURAL/JURIDICA (LEFT JOIN).
--       TIPO_PERSONERIA: N si natural, J si jurídica; fallback a columna legacy.
--       NOMBRE_PROVEEDOR = nombre persona (concat / razón social de persona).
--       NOMBRE_COMERCIAL = Nombre/Razón social del proveedor (editable en mtto).
--       ESTADO_PROVEEDOR en GEN_PROVEEDOR = activo/inactivo ('A'/'I').
CREATE OR ALTER VIEW [dbo].[V_GEN_PROVEEDOR]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PROVEEDOR,
	VP.CORR_PERSONA,
	A.CODIGO_PROVEEDOR,
	CAST(
		CASE
			WHEN PN.CORR_PERSONA IS NOT NULL THEN N'N'
			WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'J'
			ELSE ISNULL(A.TIPO_PERSONERIA, N'')
		END AS VARCHAR(1)
	) AS TIPO_PERSONERIA,
	CASE
		WHEN PN.CORR_PERSONA IS NOT NULL THEN N'Natural'
		WHEN PJ.CORR_PERSONA IS NOT NULL THEN N'Jurídico'
		WHEN A.TIPO_PERSONERIA = N'N' THEN N'Natural'
		WHEN A.TIPO_PERSONERIA = N'J' THEN N'Jurídico'
		ELSE N''
	END AS NOMBRE_TIPO_PERSONERIA,
	A.NOMBRE_PROVEEDOR,
	ISNULL(PN.PRIMER_NOMBRE, ISNULL(A.PRIMER_NOMBRE, N'')) AS PRIMER_NOMBRE,
	ISNULL(PN.SEGUNDO_NOMBRE, ISNULL(A.SEGUNDO_NOMBRE, N'')) AS SEGUNDO_NOMBRE,
	ISNULL(PN.PRIMER_APELLIDO, ISNULL(A.PRIMER_APELLIDO, N'')) AS PRIMER_APELLIDO,
	ISNULL(PN.SEGUNDO_APELLIDO, ISNULL(A.SEGUNDO_APELLIDO, N'')) AS SEGUNDO_APELLIDO,
	A.NOMBRE_COMERCIAL,
	A.CORR_TIPO_DIP,
	ISNULL(DOC_DIP.VALOR_DOCUMENTO, A.NUMERO_DIP) AS NUMERO_DIP,
	ISNULL(DOC_NRC.VALOR_DOCUMENTO, A.NUMERO_NRC) AS NUMERO_NRC,
	ISNULL(DOC_NIT.VALOR_DOCUMENTO, A.NUMERO_NIT) AS NUMERO_NIT,
	CASE
		WHEN PN.CORR_ACTIVIDAD_ECONOMICA IS NOT NULL THEN CONVERT(VARCHAR(10), PN.CORR_ACTIVIDAD_ECONOMICA)
		WHEN PJ.CORR_ACTIVIDAD_ECONOMICA IS NOT NULL THEN CONVERT(VARCHAR(10), PJ.CORR_ACTIVIDAD_ECONOMICA)
		ELSE ISNULL(A.CORR_ACTIVIDAD_ECONOMICA, N'')
	END AS CORR_ACTIVIDAD_ECONOMICA,
	ISNULL(DOM.DIRECCION, A.DIRECCION_PROVEEDOR) AS DIRECCION_PROVEEDOR,
	ISNULL(DOM.CORR_PAIS, A.CORR_PAIS) AS CORR_PAIS,
	ISNULL(DOM.CORR_DEPTO, A.CORR_DEPTO) AS CORR_DEPTO,
	ISNULL(DOM.CORR_MUNICIPIO, A.CORR_MUNICIPIO) AS CORR_MUNICIPIO,
	A.NOMBRE_CONTACTO,
	ISNULL(TEL.VALOR_CONTACTO, A.TELEFONO_FIJO) AS TELEFONO_FIJO,
	ISNULL(CEL.VALOR_CONTACTO, A.TELEFONO_MOVIL) AS TELEFONO_MOVIL,
	ISNULL(MAIL1.VALOR_CONTACTO, A.CORREO_ELECTRONICO_1) AS CORREO_ELECTRONICO_1,
	ISNULL(MAIL2.VALOR_CONTACTO, A.CORREO_ELECTRONICO_2) AS CORREO_ELECTRONICO_2,
	A.CORR_FORMA_PAGO,
	A.CUENTA_BANCARIA,
	A.CORR_BANCO,
	A.ESTADO_PROVEEDOR,
	CAST(CASE WHEN A.ESTADO_PROVEEDOR = N'A' THEN 1 ELSE 0 END AS BIT) AS ACTIVO_PROVEEDOR,
	CASE A.ESTADO_PROVEEDOR
		WHEN N'A' THEN N'Activo'
		WHEN N'I' THEN N'Inactivo'
		WHEN N'D' THEN N'Digitado'
		WHEN N'S' THEN N'Solicitado'
		ELSE N''
	END AS NOMBRE_ESTADO_PROVEEDOR,
	A.ESTADO_PROVEEDOR_WEB,
	A.CORR_CONDICION_PAGO,
	A.USUARIO_CREA,
	A.FECHA_CREA,
	A.ESTACION_CREA,
	A.USUARIO_ACTU,
	A.FECHA_ACTU,
	A.ESTACION_ACTU
FROM dbo.GEN_PROVEEDOR A
LEFT JOIN dbo.GEN_PERSONA_PROVEEDOR VP
	ON VP.CORR_EMPRESA = A.CORR_EMPRESA
	AND VP.CORR_PROVEEDOR = A.CORR_PROVEEDOR
LEFT JOIN dbo.GEN_PERSONA_NATURAL PN
	ON PN.CORR_PERSONA = VP.CORR_PERSONA
LEFT JOIN dbo.GEN_PERSONA_JURIDICA PJ
	ON PJ.CORR_PERSONA = VP.CORR_PERSONA
OUTER APPLY
(
	SELECT TOP (1) D.DIRECCION, D.CORR_PAIS, D.CORR_DEPTO, D.CORR_MUNICIPIO
	FROM dbo.GEN_PERSONA_DOMICILIO D
	WHERE D.CORR_EMPRESA = A.CORR_EMPRESA
	  AND D.CORR_PERSONA = VP.CORR_PERSONA
	  AND ISNULL(D.ACTIVO_DOMICILIO, 1) = 1
	ORDER BY D.CORR_DOMICILIO
) DOM
OUTER APPLY
(
	SELECT TOP (1) C.VALOR_CONTACTO
	FROM dbo.GEN_PERSONA_CONTACTO C
	WHERE C.CORR_EMPRESA = A.CORR_EMPRESA
	  AND C.CORR_PERSONA = VP.CORR_PERSONA
	  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1
	  AND C.CORR_TIPO_CONTACTO = 1 /* teléfono fijo — ajustar si catálogo difiere */
	ORDER BY C.CORR_CONTACTO
) TEL
OUTER APPLY
(
	SELECT TOP (1) C.VALOR_CONTACTO
	FROM dbo.GEN_PERSONA_CONTACTO C
	WHERE C.CORR_EMPRESA = A.CORR_EMPRESA
	  AND C.CORR_PERSONA = VP.CORR_PERSONA
	  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1
	  AND C.CORR_TIPO_CONTACTO = 2 /* móvil */
	ORDER BY C.CORR_CONTACTO
) CEL
OUTER APPLY
(
	SELECT TOP (1) C.VALOR_CONTACTO
	FROM dbo.GEN_PERSONA_CONTACTO C
	WHERE C.CORR_EMPRESA = A.CORR_EMPRESA
	  AND C.CORR_PERSONA = VP.CORR_PERSONA
	  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1
	  AND C.CORR_TIPO_CONTACTO = 3 /* correo */
	ORDER BY C.CORR_CONTACTO
) MAIL1
OUTER APPLY
(
	SELECT TOP (1) C.VALOR_CONTACTO
	FROM dbo.GEN_PERSONA_CONTACTO C
	WHERE C.CORR_EMPRESA = A.CORR_EMPRESA
	  AND C.CORR_PERSONA = VP.CORR_PERSONA
	  AND ISNULL(C.ACTIVO_CONTACTO, 1) = 1
	  AND C.CORR_TIPO_CONTACTO = 4 /* correo 2 */
	ORDER BY C.CORR_CONTACTO
) MAIL2
OUTER APPLY
(
	SELECT TOP (1) PD.VALOR_DOCUMENTO
	FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
	WHERE PD.CORR_EMPRESA = A.CORR_EMPRESA
	  AND PD.CORR_PERSONA = VP.CORR_PERSONA
	  AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 1 /* DUI */
) DOC_DIP
OUTER APPLY
(
	SELECT TOP (1) PD.VALOR_DOCUMENTO
	FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
	WHERE PD.CORR_EMPRESA = A.CORR_EMPRESA
	  AND PD.CORR_PERSONA = VP.CORR_PERSONA
	  AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 2 /* NIT */
) DOC_NIT
OUTER APPLY
(
	SELECT TOP (1) PD.VALOR_DOCUMENTO
	FROM dbo.GEN_PERSONA_TIPO_DOCUMENTO_IDENTIDAD PD
	WHERE PD.CORR_EMPRESA = A.CORR_EMPRESA
	  AND PD.CORR_PERSONA = VP.CORR_PERSONA
	  AND PD.CORR_TIPO_DOCUMENTO_IDENTIDAD = 3 /* NRC */
) DOC_NRC
GO
