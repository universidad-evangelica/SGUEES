-- Qué hace: lectura de los documentos marcados por período académico.
-- Cómo lo hace: une la relación con el documento y los nombres del período (sede, área, facultad y carrera).
-- El usuario lo ejecuta en SGUEES antes de usar la pantalla.
CREATE OR ALTER VIEW [dbo].[V_ACA_DOCUMENTO_ADMISION_PERIODOS_ACADEMICOS]
AS
SELECT
	R.CORR_EMPRESA,
	R.CORR_DOCUMENTO_ADMISION,
	R.CORR_PERIODO_ACADEMICO,
	D.CODIGO,
	D.NOMBRE_DOCUMENTO,
	D.ORDEN,
	D.OBLIGATORIO,
	D.ACTIVO AS ACTIVO_DOCUMENTO,
	P.ANIO,
	P.NUMERO_PERIODO,
	P.FECHA_INICIO,
	P.FECHA_FIN,
	P.ACTIVO AS ACTIVO_PERIODO,
	S.NOMBRE_SEDE,
	A.NOMBRE_AREA,
	F.NOMBRE_FACULTAD,
	C.NOMBRE_CARRERA,
	CAST(CASE
		WHEN P.CORR_CARRERA IS NOT NULL THEN 'Carrera'
		WHEN P.CORR_FACULTAD IS NOT NULL THEN 'Facultad'
		ELSE N'Área'
	END AS varchar(12)) AS ALCANCE,
	R.USUARIO_CREA,
	R.ESTACION_CREA,
	R.FECHA_CREA,
	R.USUARIO_ACTU,
	R.ESTACION_ACTU,
	R.FECHA_ACTU
FROM dbo.ACA_DOCUMENTO_ADMISION_PERIODOS_ACADEMICOS R
INNER JOIN dbo.ACA_DOCUMENTO_ADMISION D
	ON D.CORR_DOCUMENTO_ADMISION = R.CORR_DOCUMENTO_ADMISION
INNER JOIN dbo.ACA_PERIODOS_ACADEMICOS P
	ON P.CORR_PERIODO_ACADEMICO = R.CORR_PERIODO_ACADEMICO
INNER JOIN dbo.GEN_SEDES S
	ON S.CORR_SEDE = P.CORR_SEDE
INNER JOIN dbo.ACA_AREAS_ACADEMICAS A
	ON A.CORR_AREA_ACADEMICA = P.CORR_AREA_ACADEMICA
	AND A.CORR_EMPRESA = S.CORR_EMPRESA
LEFT JOIN dbo.ACA_FACULTADES F
	ON F.CORR_FACULTAD = P.CORR_FACULTAD
	AND F.CORR_EMPRESA = S.CORR_EMPRESA
LEFT JOIN dbo.ACA_CARRERAS C
	ON C.CORR_CARRERA = P.CORR_CARRERA
	AND C.CORR_EMPRESA = S.CORR_EMPRESA;
GO
