CREATE VIEW [dbo].[V_GEN_PLANTILLA_CONTRATO]
AS
SELECT
	A.CORR_EMPRESA,
	A.CORR_PLANTILLA_CONTRATO,
	A.NOMBRE_PLANTILLA,
	A.CORR_TIPO_CONTRATACION,
	B.NOMBRE_TIPO_CONTRATACION,
	V.CORR_PLANTILLA_CONTRATO_VERSION AS CORR_VERSION_ACTIVA,
	V.NUMERO_VERSION AS NUMERO_VERSION_ACTIVA,
	V.NOMBRE_VERSION AS NOMBRE_VERSION_ACTIVA,
	V.CUERPO_PLANTILLA,
	A.USUARIO_CREA,
	A.ESTACION_CREA,
	A.FECHA_CREA,
	A.USUARIO_ACTU,
	A.ESTACION_ACTU,
	A.FECHA_ACTU
FROM [dbo].[GEN_PLANTILLA_CONTRATO] A
LEFT JOIN [dbo].[SC_TIPO_CONTRATACION] B
	ON A.CORR_EMPRESA = B.CORR_EMPRESA
	AND A.CORR_TIPO_CONTRATACION = B.CORR_TIPO_CONTRATACION
LEFT JOIN [dbo].[GEN_PLANTILLA_CONTRATO_VERSION] V
	ON A.CORR_EMPRESA = V.CORR_EMPRESA
	AND A.CORR_PLANTILLA_CONTRATO = V.CORR_PLANTILLA_CONTRATO
	AND V.ES_VERSION_ACTIVA = 1
GO
