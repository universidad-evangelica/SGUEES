CREATE OR ALTER VIEW [dbo].[V_ACA_SE_PREGUNTA]
AS
SELECT
	P.CORR_PREGUNTA,
	P.CORR_TIPO_PREGUNTA,
	T.CODIGO AS CODIGO_TIPO_PREGUNTA,
	T.NOMBRE AS NOMBRE_TIPO_PREGUNTA,
	P.CODIGO,
	P.ENUNCIADO,
	P.AYUDA,
	P.ACTIVO,
	P.USUARIO_CREA,
	P.ESTACION_CREA,
	P.FECHA_CREA,
	P.USUARIO_ACTU,
	P.ESTACION_ACTU,
	P.FECHA_ACTU
FROM dbo.ACA_SE_PREGUNTA AS P
INNER JOIN dbo.GEN_SE_TIPO_PREGUNTA AS T
	ON T.CORR_TIPO_PREGUNTA = P.CORR_TIPO_PREGUNTA;
GO
