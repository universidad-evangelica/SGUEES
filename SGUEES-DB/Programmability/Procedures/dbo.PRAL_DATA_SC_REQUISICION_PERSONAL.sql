-- =============================================================================
-- Qué hace: Listado visible de SC_REQUISICION_PERSONAL para el login de sesión.
-- Cómo: Visibilidad =
--   1) Observador DEFECTO → todas
--   2) Observador REQUISICION → esa req
--   3) USUARIO_CREA = login → lo que registró (colaborador / no jefe)
--   4) CORR_UNIDAD ∈ jefe activo + hijas → jefe padre ve todo su ámbito
-- Nota: No modifica PRAL_DATA_SC_UNIDADES_USUARIO.
-- =============================================================================
CREATE OR ALTER PROCEDURE [dbo].[PRAL_DATA_SC_REQUISICION_PERSONAL]
(
	@CORR_EMPRESA INT,
	@LOGIN_SISTEMA VARCHAR(30)
)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @LOGIN VARCHAR(30) = LTRIM(RTRIM(ISNULL(@LOGIN_SISTEMA, '')));

	IF @CORR_EMPRESA IS NULL OR @CORR_EMPRESA <= 0 OR @LOGIN = ''
	BEGIN
		SELECT TOP (0) *
		FROM dbo.V_SC_REQUISICION_PERSONAL;
		RETURN;
	END;

	IF EXISTS (
		SELECT 1
		FROM dbo.SC_REQUISICION_OBSERVADORES AS O
		WHERE O.CORR_EMPRESA = @CORR_EMPRESA
		  AND O.ACTIVO = CONVERT(BIT, 1)
		  AND UPPER(LTRIM(RTRIM(O.TIPO_OBSERVADOR))) = N'DEFECTO'
		  AND ISNULL(O.CORR_REQUISICION_PERSONAL, 0) = 0
		  AND LTRIM(RTRIM(O.LOGIN_SISTEMA)) = @LOGIN
	)
	BEGIN
		SELECT V.*
		FROM dbo.V_SC_REQUISICION_PERSONAL AS V
		WHERE V.CORR_EMPRESA = @CORR_EMPRESA
		ORDER BY V.FECHA_REQUISICION DESC, V.CORR_REQUISICION_PERSONAL DESC;
		RETURN;
	END;

	;WITH EmpleadoLogin AS
	(
		SELECT
			E.CORR_EMPRESA,
			E.CORR_EMPLEADO
		FROM dbo.GEN_EMPLEADO AS E
		INNER JOIN dbo.GEN_PERSONA_USUARIO AS PU
			ON PU.CORR_PERSONA = E.CORR_PERSONA
		WHERE E.CORR_EMPRESA = @CORR_EMPRESA
		  AND LTRIM(RTRIM(PU.LOGIN_SISTEMA)) = @LOGIN
	),
	UnidadesComoJefe AS
	(
		SELECT DISTINCT
			JU.CORR_EMPRESA,
			JU.CORR_UNIDAD
		FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_JEFES_UNIDADES AS JU
		INNER JOIN EmpleadoLogin AS EL
			ON EL.CORR_EMPRESA = JU.CORR_EMPRESA
		   AND EL.CORR_EMPLEADO = JU.CORR_EMPLEADO
		WHERE JU.CORR_EMPRESA = @CORR_EMPRESA
		  AND JU.ACTIVO = CONVERT(BIT, 1)
	),
	UnidadesHijasACargo AS
	(
		SELECT
			H.CORR_EMPRESA,
			H.CORR_UNIDAD,
			0 AS NIVEL
		FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS H
		INNER JOIN UnidadesComoJefe AS J
			ON J.CORR_EMPRESA = H.CORR_EMPRESA
		   AND J.CORR_UNIDAD = H.CORR_UNIDAD_PADRE
		WHERE H.CORR_EMPRESA = @CORR_EMPRESA

		UNION ALL

		SELECT
			H.CORR_EMPRESA,
			H.CORR_UNIDAD,
			P.NIVEL + 1
		FROM dbo.SC_ORGANIGRAMA_ESTRUCTURAL_UNIDADES AS H
		INNER JOIN UnidadesHijasACargo AS P
			ON P.CORR_EMPRESA = H.CORR_EMPRESA
		   AND P.CORR_UNIDAD = H.CORR_UNIDAD_PADRE
		WHERE H.CORR_EMPRESA = @CORR_EMPRESA
		  AND P.NIVEL < 20
	),
	UnidadesAmbitoJefe AS
	(
		SELECT CORR_EMPRESA, CORR_UNIDAD FROM UnidadesComoJefe
		UNION
		SELECT CORR_EMPRESA, CORR_UNIDAD FROM UnidadesHijasACargo
	)
	SELECT V.*
	FROM dbo.V_SC_REQUISICION_PERSONAL AS V
	WHERE V.CORR_EMPRESA = @CORR_EMPRESA
	  AND (
			LTRIM(RTRIM(V.USUARIO_CREA)) = @LOGIN
			OR EXISTS (
				SELECT 1
				FROM UnidadesAmbitoJefe AS U
				WHERE U.CORR_EMPRESA = V.CORR_EMPRESA
				  AND U.CORR_UNIDAD = V.CORR_UNIDAD
			)
			OR EXISTS (
				SELECT 1
				FROM dbo.SC_REQUISICION_OBSERVADORES AS O
				WHERE O.CORR_EMPRESA = V.CORR_EMPRESA
				  AND O.CORR_REQUISICION_PERSONAL = V.CORR_REQUISICION_PERSONAL
				  AND O.ACTIVO = CONVERT(BIT, 1)
				  AND UPPER(LTRIM(RTRIM(O.TIPO_OBSERVADOR))) = N'REQUISICION'
				  AND LTRIM(RTRIM(O.LOGIN_SISTEMA)) = @LOGIN
			)
	  )
	ORDER BY V.FECHA_REQUISICION DESC, V.CORR_REQUISICION_PERSONAL DESC
	OPTION (MAXRECURSION 20);
END
GO
